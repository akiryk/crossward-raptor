import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 20-S3 — The Preview tooltip stays over a group.
//
// Once a Preview tooltip shows over a red or gold cell, it stays where it
// is, with its text, while the mouse moves over cells of the same mark
// that touch it, side by side or one above the other, through cells of
// that mark. Crossing the line between two cells never hides it. Moving
// onto a touching cell of the other mark moves it there with that
// mark's text, without hiding it in between. Over an unmarked cell or off
// the grid it goes at once, as before (20-S2); a group reached that way
// gets a new tooltip. When the cell it stays over is no longer of the
// hovered cell's group, it moves to the hovered cell.
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 900 };
const GOLD = 'Consider avoiding two-letter words.';
const RED = 'Filling in these cells will result in a symmetrical puzzle.';

const tooltip = (page: Page) => page.getByTestId('preview-tooltip');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const editorGrid = (page: Page) => page.getByTestId('grid-region');
const previewToggle = (page: Page) => page.getByTestId('preview-toggle');

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((line, row) => {
    [...line].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/**
 * In Preview (col,row), as in 20-S2:
 *   L L L L #
 *   L # # # #
 *   g g # G G     g, G: two gold groups, apart
 *   # # # # R
 *   # R R R R     R: one red group, turning a corner, touching G at 4,2
 */
const marked = () => gridOf(['CATS.', 'O....', 'AD...', '.....', '.....']);

let titleCounter = 0;
async function openBuilder(page: Page, grid: Grid) {
  titleCounter += 1;
  const title = `20-S3 ${Date.now()}-${titleCounter}`;
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, title);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function previewOn(page: Page) {
  await previewToggle(page).click();
  await expect(previewToggle(page).locator('input')).toBeChecked();
}

async function expectState(page: Page, coord: string, state: string) {
  await expect(cell(page, coord), `${coord} is ${state}`).toHaveAttribute('data-cell-state', state);
}

async function centerOf(page: Page, coord: string) {
  const b = await box(cell(page, coord));
  return { x: b.left + b.width / 2, y: b.top + b.height / 2 };
}

/** From off the grid straight onto a cell's center. */
async function enter(page: Page, coord: string) {
  await page.getByTestId('puzzle-grid').scrollIntoViewIfNeeded();
  await page.mouse.move(2, 2);
  await expect(tooltip(page)).toHaveCount(0);
  const { x, y } = await centerOf(page, coord);
  await page.mouse.move(x, y);
}

/** The mouse moves in small steps to a cell's center, over the lines between. */
async function glide(page: Page, coord: string) {
  const { x, y } = await centerOf(page, coord);
  await page.mouse.move(x, y, { steps: 40 });
}

/** The mouse rests on the line between two cells side by side or one above the other. */
async function onLineBetween(page: Page, a: string, b: string) {
  const first = await box(cell(page, a));
  const second = await box(cell(page, b));
  const sideBySide = Math.abs(first.top - second.top) < 1;
  // The first point between the two cells' boxes, in the layout's 1/64px
  // steps, that hits neither cell: the line itself, which hit testing may
  // narrow to a fraction of a pixel.
  const point = await page.evaluate(
    ([from, to, fixed, horizontal]) => {
      for (let p = from; p <= to; p += 1 / 64) {
        const [x, y] = horizontal ? [p, fixed] : [fixed, p];
        if (!document.elementFromPoint(x, y)?.closest('[data-coord]')) return { x, y };
      }
      return null;
    },
    sideBySide
      ? ([first.right - 1, second.left + 1, first.top + first.height / 2, true] as const)
      : ([first.bottom - 1, second.top + 1, first.left + first.width / 2, false] as const)
  );
  expect(point, `a point on the line between ${a} and ${b}`).not.toBeNull();
  await page.mouse.move(point!.x, point!.y);
  const hovered = await page.evaluate(() => document.querySelector('[data-coord]:hover')?.getAttribute('data-coord') ?? null);
  expect(hovered, `the mouse is on the line between ${a} and ${b}, over neither cell`).toBeNull();
}

/** Counts each moment the tooltip is absent from the page, from now on. */
async function watchForGaps(page: Page) {
  await page.evaluate(() => {
    const w = window as unknown as { __gaps: number; __watch?: MutationObserver };
    w.__watch?.disconnect();
    w.__gaps = 0;
    w.__watch = new MutationObserver(() => {
      if (!document.querySelector('[data-testid="preview-tooltip"]')) w.__gaps += 1;
    });
    w.__watch.observe(document.body, { childList: true, subtree: true });
  });
}

async function expectNoGaps(page: Page) {
  const gaps = await page.evaluate(() => (window as unknown as { __gaps: number }).__gaps);
  expect(gaps, 'the tooltip never went away').toBe(0);
}

/** One tooltip, with this text, its bottom 4px above this cell and centered on it. */
async function expectOver(page: Page, coord: string, text: string) {
  await expect(tooltip(page)).toHaveCount(1);
  await expect(tooltip(page)).toHaveText(text);
  const target = await box(cell(page, coord));
  const tip = await box(tooltip(page));
  expectNear(tip.bottom, target.top - 4, 1, `4px above ${coord}`);
  expectNear(tip.left + tip.width / 2, target.left + target.width / 2, 1, `centered on ${coord}`);
}

test.describe('20-S3 the Preview tooltip stays over a group', () => {
  test.use({ viewport: WIDE });

  test('20-S3-1 across a gold group, it stays over the first cell, also on the line between', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);
    await expectState(page, '3,2', 'recommended');
    await expectState(page, '4,2', 'recommended');

    await enter(page, '3,2');
    await expectOver(page, '3,2', GOLD);
    await watchForGaps(page);

    await onLineBetween(page, '3,2', '4,2');
    await expectOver(page, '3,2', GOLD);
    await glide(page, '4,2');
    await expectOver(page, '3,2', GOLD);
    await glide(page, '3,2');
    await expectOver(page, '3,2', GOLD);
    await expectNoGaps(page);
  });

  test('20-S3-2 along a red group and round its corner, it stays over the first cell', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);
    for (const coord of ['1,4', '2,4', '3,4', '4,4', '4,3']) await expectState(page, coord, 'required');

    await enter(page, '1,4');
    await expectOver(page, '1,4', RED);
    await watchForGaps(page);

    for (const coord of ['2,4', '3,4', '4,4']) {
      await glide(page, coord);
      await expectOver(page, '1,4', RED);
    }
    await onLineBetween(page, '4,3', '4,4');
    await expectOver(page, '1,4', RED);
    await glide(page, '4,3');
    await expectOver(page, '1,4', RED);
    await expectNoGaps(page);
  });

  test('20-S3-3 onto a touching cell of the other mark, it moves there with its text, never gone', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);
    await expectState(page, '4,2', 'recommended');
    await expectState(page, '4,3', 'required');

    await enter(page, '4,2');
    await expectOver(page, '4,2', GOLD);
    await watchForGaps(page);

    await onLineBetween(page, '4,2', '4,3');
    await expectOver(page, '4,2', GOLD);
    await glide(page, '4,3');
    await expectOver(page, '4,3', RED);
    await glide(page, '4,2');
    await expectOver(page, '4,2', GOLD);
    await expectNoGaps(page);
  });

  test('20-S3-4 over an unmarked cell it goes; a group reached that way gets its own (pass today)', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);
    await expectState(page, '2,2', 'black');
    await expectState(page, '1,1', 'black');

    await enter(page, '1,2');
    await expectOver(page, '1,2', GOLD);
    await glide(page, '2,2');
    await expect(tooltip(page)).toHaveCount(0);
    await glide(page, '3,2');
    await expectOver(page, '3,2', GOLD);

    await enter(page, '1,2');
    await expectOver(page, '1,2', GOLD);
    await glide(page, '1,1');
    await expect(tooltip(page)).toHaveCount(0);
  });

  test('20-S3-5 when the cell it stays over leaves the group, it moves to the hovered cell', async ({ page }) => {
    // C A in a two-letter word; 3,4 and 4,4 their gold, empty mirrors.
    await openBuilder(page, gridOf(['CA...', '.....', '.....', '.....', '.....']));
    await previewOn(page);
    await expectState(page, '3,4', 'recommended');
    await expectState(page, '4,4', 'recommended');

    await enter(page, '3,4');
    await glide(page, '4,4');
    await expectOver(page, '3,4', GOLD);

    // Deleting A from the keyboard: 3,4 turns black, 4,4 red.
    await editorGrid(page).focus();
    await page.keyboard.press('ArrowRight');
    await expect(cell(page, '1,0')).toHaveAttribute('data-selected', 'true');
    await page.keyboard.press('Backspace');
    await expectState(page, '3,4', 'black');
    await expectState(page, '4,4', 'required');
    await expectOver(page, '4,4', RED);
  });
});
