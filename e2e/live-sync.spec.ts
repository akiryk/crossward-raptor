import { test, expect } from '@playwright/test';
import type { Page, Route } from '@playwright/test';
import { createGrid, withLetter, type Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { commitFromElsewhere, isAction, journalEntries, readSaved, savedRow } from './helpers/operations';
import { blockCatchUp, isCatchUp, pruneLogBelow, secondContext, setVisibility } from './helpers/live-sync';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 24-S4 — live sync by polling.
//
// Each visible editor asks for the operations committed since its confirmed
// version about once a second, and at once on becoming visible or coming
// back online. Remote operations of every kind are applied to the confirmed
// state, the builder's own pending edits shown over them, without moving
// the cursor, focus or Preview. A tab behind the log's retention reloads the
// puzzle as stored. Two browser contexts of one account stand in for two
// builders (no membership needed).
//
// Do not edit this file to match an implementation.

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
const name = (label: string) => `24-S4 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const status = (page: Page) => page.getByTestId('save-status');
const step = (page: Page, id: string) => page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);

async function seedCat(size = 5) {
  const grid = letters(createGrid({ cols: size, rows: size }), [[0, 0, 'C'], [1, 0, 'A'], [2, 0, 'T']]);
  return seedPuzzle({ grid, hints: {}, phase: 'grid' }, name('cat'));
}
async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}
async function typeAt(page: Page, coord: string, text: string) {
  await cell(page, coord).click();
  await page.keyboard.type(text);
}
/** A row as the page shows it: letters, '.' for empty, '#' for black. */
async function shownRow(page: Page, row: number, cols = 5): Promise<string> {
  let text = '';
  for (let col = 0; col < cols; col++) {
    const target = cell(page, `${col},${row}`);
    if ((await target.getAttribute('data-kind')) === 'black') {
      text += '#';
      continue;
    }
    const letter = (await target.innerText()).replace(/[^A-Z]/g, '');
    text += letter.length > 0 ? letter : '.';
  }
  return text;
}
const selected = (page: Page) => page.locator('[data-selected="true"]').getAttribute('data-coord');
const gridFocused = (page: Page) => page.evaluate(() => document.activeElement?.getAttribute('data-testid') === 'grid-region');

test.describe('24-S4-E1 two contexts of one account converge', () => {
  test('each sees the other’s words; overlapping edits end as the later commit; compatible ones both survive; nothing local moves', async ({ page, browser }) => {
    const { id } = await seedCat();
    const other = await secondContext(browser);
    try {
      const b = other.page;
      await open(page, id);
      await open(b, id);

      await typeAt(page, '0,2', 'DOG');
      await expect.poll(() => shownRow(b, 2), { timeout: 5000 }).toBe('DOG..');
      await typeAt(b, '0,4', 'EEL');
      await expect.poll(() => shownRow(page, 4), { timeout: 5000 }).toBe('EEL..');

      // Overlapping: page writes MASK across row 3; then b writes MAG over its first cells.
      await typeAt(page, '0,3', 'MASK');
      await expect(status(page)).toHaveText('Saved');
      const cursorBefore = await selected(page);
      await expect.poll(() => shownRow(b, 3), { timeout: 5000 }).toBe('MASK.');
      await typeAt(b, '0,3', 'MAG');
      await expect(status(b)).toHaveText('Saved');
      await expect.poll(() => shownRow(page, 3), { timeout: 5000 }).toBe('MAGK.');
      expect(await selected(page)).toBe(cursorBefore);
      expect(await gridFocused(page)).toBe(true);

      // Compatible, at the same time: each writes its own cells.
      await cell(page, '3,1').click();
      await cell(b, '3,4').click();
      await Promise.all([page.keyboard.type('XY'), b.keyboard.type('ZW')]);
      for (const p of [page, b]) {
        await expect.poll(async () => [await shownRow(p, 1), await shownRow(p, 4)], { timeout: 8000 }).toEqual(['...XY', 'EELZW']);
      }
      await expect(status(page)).toHaveText('Saved');
      await expect(status(b)).toHaveText('Saved');
      const saved = await readSaved(id);
      expect(saved.grid.cells.map((_, row) => savedRow(saved.grid, row))).toEqual(['CAT..', '...XY', 'DOG..', 'MAGK.', 'EELZW']);
      expect(saved.version).toBe(saved.log.filter((record) => record.status === 'accepted').length);
    } finally {
      await other.context.close();
    }
  });

  test('remote changes keep the builder’s unsaved edits shown, its cursor and its focus', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    let blocked = true;
    await page.route(`**/puzzles/${id}`, (route: Route) =>
      blocked && isAction(route.request()) ? route.abort('failed') : route.continue());
    await cell(page, '0,2').click();
    await page.keyboard.type('BI');
    await expect(status(page)).toHaveText('Not saved — retrying');
    await commitFromElsewhere(id, { kind: 'cells', writes: [{ col: 0, row: 4, value: 'R' }, { col: 0, row: 2, value: 'Q' }] });
    await expect.poll(() => shownRow(page, 4), { timeout: 5000 }).toBe('R....');
    // The unsaved edit over the remote write: B stays where the builder typed it.
    expect(await shownRow(page, 2)).toBe('BI...');
    expect(await selected(page)).toBe('2,2');
    expect(await gridFocused(page)).toBe(true);
    blocked = false;
    await page.keyboard.type('N');
    await expect(status(page)).toHaveText('Saved', { timeout: 20_000 });
    expect(savedRow((await readSaved(id)).grid, 2)).toBe('BIN..');
    expect(await shownRow(page, 2)).toBe('BIN..');
  });
});

test.describe('24-S4-E2 a Start Over or Enter Hints from another context', () => {
  test('Start Over elsewhere clears this editor; its edit made before it heard is refused, its input kept', async ({ page, browser }) => {
    const { id } = await seedCat();
    const other = await secondContext(browser);
    try {
      const b = other.page;
      await open(page, id);
      await open(b, id);
      let blocked = true;
      await b.route(`**/puzzles/${id}`, (route: Route) =>
        blocked && isAction(route.request()) ? route.abort('failed') : route.continue());
      await typeAt(b, '0,1', 'DOG');
      await expect(status(b)).toHaveText('Not saved — retrying');

      await page.getByTestId('start-over').click();
      await page.getByTestId('start-over-confirm').click();
      await expect.poll(async () => (await readSaved(id)).resetEpoch).toBe(1);
      await expect.poll(() => shownRow(b, 0), { timeout: 5000 }).toBe('.....');
      expect(await shownRow(b, 1)).toBe('.....');

      blocked = false;
      const notice = b.getByTestId('save-notice');
      await expect(notice).toBeVisible({ timeout: 20_000 });
      await expect(notice.getByTestId('save-notice-message')).toHaveText(/^Your DOG in \d+-Across wasn't saved: the puzzle was started over\.$/);
      await expect(notice.getByTestId('save-notice-input')).toHaveValue('DOG');
      const saved = await readSaved(id);
      expect(saved.log.at(-1)).toMatchObject({ kind: 'cells', status: 'refused', code: 'epoch' });
      expect(savedRow(saved.grid, 1)).toBe('.....');

      // b carries on in the new epoch.
      await typeAt(b, '0,2', 'NEW');
      await expect(status(b)).toHaveText('Saved');
      await expect.poll(() => shownRow(page, 2), { timeout: 5000 }).toBe('NEW..');
      expect((await readSaved(id)).log.at(-1)).toMatchObject({ kind: 'cells', status: 'accepted' });
    } finally {
      await other.context.close();
    }
  });

  test('Enter Hints elsewhere moves this editor to Create Hints, Preview off; its hints then save', async ({ page, browser }) => {
    const { id } = await seedCat();
    const other = await secondContext(browser);
    try {
      const b = other.page;
      await open(page, id);
      await open(b, id);
      await b.getByTestId('preview-toggle').click();
      await expect(b.getByTestId('puzzle-grid')).toHaveAttribute('data-grid-mode', 'preview');

      await typeAt(page, '0,1', 'ABCDE');
      await expect(status(page)).toHaveText('Saved');
      await step(page, 'hints').click();
      await page.getByTestId('modal-confirm').click();
      await expect(page.getByTestId('hints-region')).toBeVisible();

      await expect(b.getByTestId('hints-region')).toBeVisible({ timeout: 5000 });
      await expect(b.getByTestId('puzzle-grid')).toHaveAttribute('data-grid-mode', 'hints');
      await expect(b.getByTestId('preview-toggle')).toHaveCount(0);
      expect(await shownRow(b, 4)).toBe('#####');
      expect(await shownRow(b, 1)).toBe('ABCDE');

      const saved = await readSaved(id);
      const key = Object.keys(saved.hints)[0];
      const input = b.locator(`[data-hint-key="${key}"] [data-testid="hint-input"]`);
      await input.fill('From the other context');
      await b.getByTestId('puzzle-title').click();
      await expect.poll(async () => (await readSaved(id)).hints[key]).toBe('From the other context');
      await expect(page.locator(`[data-hint-key="${key}"] [data-testid="hint-input"]`)).toHaveValue('From the other context', { timeout: 5000 });
    } finally {
      await other.context.close();
    }
  });
});

test.describe('24-S4-E3 reconnecting', () => {
  test('a context taken offline edits, the other edits meanwhile; back online, both converge', async ({ page, browser }) => {
    const { id } = await seedCat();
    const other = await secondContext(browser);
    try {
      const b = other.page;
      await open(page, id);
      await open(b, id);
      await other.context.setOffline(true);
      await typeAt(b, '0,3', 'XYZ');
      await expect(status(b)).toHaveText('Not saved — retrying');

      await typeAt(page, '0,4', 'ABC');
      await typeAt(page, '0,3', 'Q');
      await expect(status(page)).toHaveText('Saved');
      expect(await shownRow(b, 4)).toBe('.....');

      await other.context.setOffline(false);
      for (const p of [page, b]) {
        await expect.poll(async () => [await shownRow(p, 3), await shownRow(p, 4)], { timeout: 20_000 }).toEqual(['XYZ..', 'ABC..']);
      }
      await expect(status(b)).toHaveText('Saved');
      const saved = await readSaved(id);
      expect([savedRow(saved.grid, 3), savedRow(saved.grid, 4)]).toEqual(['XYZ..', 'ABC..']);
    } finally {
      await other.context.close();
    }
  });

  test('behind the log’s retention, the editor reloads the puzzle as stored and carries on', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    const unblock = await blockCatchUp(page, id);
    await commitFromElsewhere(id, { kind: 'cells', writes: [{ col: 0, row: 1, value: 'P' }] });
    await commitFromElsewhere(id, { kind: 'title', title: 'Stored title' });
    await commitFromElsewhere(id, { kind: 'cells', writes: [{ col: 0, row: 2, value: 'R' }] });
    await pruneLogBelow(id, 3);
    await unblock();
    await expect.poll(() => shownRow(page, 2), { timeout: 20_000 }).toBe('R....');
    expect(await shownRow(page, 1)).toBe('P....');
    await expect(page.getByTestId('puzzle-title')).toHaveValue('Stored title');
    await typeAt(page, '0,4', 'Z');
    await expect(status(page)).toHaveText('Saved');
    const saved = await readSaved(id);
    expect(saved.version).toBe(4);
    expect(saved.log.at(-1)).toMatchObject({ kind: 'cells', status: 'accepted', version: 4 });
  });

  test('a tab that adopts a live tab’s journal: the edit is committed once, both tabs show it, both journals empty', async ({ page, context }) => {
    const { id } = await seedCat();
    await open(page, id);
    let blocked = true;
    await page.route(`**/puzzles/${id}`, (route: Route) =>
      blocked && isAction(route.request()) ? route.abort('failed') : route.continue());
    await typeAt(page, '0,3', 'EEL');
    await expect(status(page)).toHaveText('Not saved — retrying');
    expect(await journalEntries(page, id)).toHaveLength(1);

    const second = await context.newPage();
    await open(second, id);
    await expect(status(second)).toHaveText('Saved', { timeout: 10_000 });
    expect(await shownRow(second, 3)).toBe('EEL..');
    blocked = false;
    await expect(status(page)).toHaveText('Saved', { timeout: 20_000 });
    expect(await shownRow(page, 3)).toBe('EEL..');
    const saved = await readSaved(id);
    expect(saved.version).toBe(1);
    expect(saved.log).toHaveLength(1);
    expect(await journalEntries(page, id)).toHaveLength(0);

    // Both carry on in step.
    await typeAt(page, '0,1', 'ON');
    await expect.poll(() => shownRow(second, 1), { timeout: 5000 }).toBe('ON...');
    await second.close();
  });
});

test.describe('24-S4-E4 latency and request cost (measured for the push decision)', () => {
  test('a commit elsewhere shows within about a second; about one small request a second while visible, none while hidden', async ({ page }) => {
    const { id } = await seedCat(9);
    await open(page, id);
    const polls: number[] = [];
    const sizes: number[] = [];
    page.on('request', (request) => { if (isCatchUp(request, id)) polls.push(Date.now()); });
    page.on('response', async (response) => {
      if (isCatchUp(response.request(), id)) sizes.push((await response.body()).length);
    });

    const latencies: number[] = [];
    for (let i = 0; i < 8; i++) {
      const row = i;
      const started = Date.now();
      await commitFromElsewhere(id, { kind: 'cells', writes: [{ col: 8, row, value: 'L' }] });
      const committed = Date.now();
      await expect(cell(page, `8,${row}`)).toContainText('L', { timeout: 5000 });
      latencies.push(Date.now() - committed);
      expect(committed - started).toBeLessThan(5000);
    }
    latencies.sort((a, b) => a - b);
    const median = latencies[Math.floor(latencies.length / 2)];
    test.info().annotations.push({ type: 'latency-ms', description: latencies.join(',') });
    expect(median).toBeLessThanOrEqual(2000);
    expect(latencies.at(-1)).toBeLessThanOrEqual(4000);

    // Idle and visible: about one request a second, each answer tiny.
    polls.length = 0;
    sizes.length = 0;
    await page.waitForTimeout(10_000);
    test.info().annotations.push({ type: 'idle-polls-10s', description: String(polls.length) });
    expect(polls.length).toBeGreaterThanOrEqual(5);
    expect(polls.length).toBeLessThanOrEqual(12);
    expect(Math.max(...sizes)).toBeLessThan(100);

    // Hidden: none. Visible again: at once.
    await setVisibility(page, 'hidden');
    await page.waitForTimeout(1500);
    polls.length = 0;
    await page.waitForTimeout(5000);
    expect(polls).toHaveLength(0);
    const shown = Date.now();
    await setVisibility(page, 'visible');
    await expect.poll(() => polls.length, { timeout: 2000 }).toBeGreaterThan(0);
    expect(polls[0] - shown).toBeLessThan(500);
  });
});
