import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 14-S11 — Keyboard focus ring.
//
// Keyboard focus on a button, a link, the Preview toggle or a Radio option
// shows `outline: 2px solid` in the `focus-ring` color style (#00F0FF, the
// `cyan` palette variable), with no offset. Mouse focus shows no ring. The
// toggle and a Radio option are ringed as a whole (their label); a puzzle
// row is ringed as a whole when its link has keyboard focus, and the link
// itself is not. Text inputs and the grid keep their own focus look, with no
// ring. Hover's look on keyboard focus is unchanged.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

test.use({ viewport: { width: 1280, height: 800 } });

const FOCUS_RING = 'solid 2px rgb(0, 240, 255) offset 0px';

/** The element's settled outline: "none", or style, width, color and offset. */
function ringOf(locator: Locator) {
  return locator.evaluate(async (el) => {
    await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
    const s = getComputedStyle(el);
    const transparent = /rgba\(.*,\s*0\)$|transparent/.test(s.outlineColor);
    if (s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0 || transparent) return 'none';
    return `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor} offset ${s.outlineOffset}`;
  });
}

/** Gives `target` keyboard focus: focus whatever precedes it, then press Tab. */
async function tabTo(page: Page, target: Locator) {
  await target.evaluate((el) => el.setAttribute('data-tab-target', ''));
  await page.evaluate(() => {
    const all = Array.from(
      document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled]), [tabindex]')
    ).filter((el) => el.tabIndex >= 0 && !(el instanceof HTMLInputElement && el.type === 'radio' && !el.checked));
    const index = all.findIndex((el) => el.hasAttribute('data-tab-target'));
    all[index - 1].focus();
    all[index].removeAttribute('data-tab-target');
  });
  await page.keyboard.press('Tab');
  await expect(target).toBeFocused();
}

/** Mouse focus without activating: press on `target`, move off, release. */
async function pressWithMouse(page: Page, target: Locator) {
  await target.hover();
  await page.mouse.down();
  await expect(target).toBeFocused();
}

async function releaseMouse(page: Page) {
  await page.mouse.move(1, 1);
  await page.mouse.up();
}

async function blur(page: Page) {
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
}

async function styleGuide(page: Page) {
  await page.goto('/style-guide');
  await expect(page.getByTestId('sg-buttons')).toBeVisible();
}

const sgButtons = (page: Page) => page.getByTestId('sg-hover').getByTestId('sg-button');
const radioOptions = (page: Page, group: string) => page.getByTestId(group).getByTestId(`${group}-option`);
const sgRows = (page: Page) => page.getByTestId('sg-puzzle-row').getByTestId('puzzle-list-item');

/** CAT across the top row of a 3x3. */
function catGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'C');
  grid = withLetter(grid, { col: 1, row: 0 }, 'A');
  grid = withLetter(grid, { col: 2, row: 0 }, 'T');
  return grid;
}

// --- 14-S11-1: the color ---
test.describe('14-S11-1 the color', () => {
  test('focus-ring resolves to #00F0FF', async ({ page }) => {
    await styleGuide(page);
    const color = await page.evaluate(() => {
      const probe = document.createElement('div');
      probe.style.backgroundColor = 'var(--color-focus-ring)';
      document.body.appendChild(probe);
      const resolved = getComputedStyle(probe).backgroundColor;
      probe.remove();
      return resolved;
    });
    expect(color).toBe('rgb(0, 240, 255)');
  });
});

// --- 14-S11-2: keyboard focus shows the ring ---
test.describe('14-S11-2 keyboard focus shows the ring', () => {
  test('every Button type, selected or not, and it goes when focus leaves', async ({ page }) => {
    await styleGuide(page);
    const buttons = sgButtons(page);
    const count = await buttons.count();
    expect(count).toBe(8);
    for (let i = 0; i < count; i++) {
      const button = buttons.nth(i);
      expect(await ringOf(button), `button ${i} idle`).toBe('none');
      await tabTo(page, button);
      expect(await ringOf(button), `button ${i} on keyboard focus`).toBe(FOCUS_RING);
      await blur(page);
      expect(await ringOf(button), `button ${i} blurred`).toBe('none');
    }
  });

  test('the Preview toggle, off and on, is ringed as a whole; its pill and knob are not', async ({ page }) => {
    await styleGuide(page);
    for (const id of ['sg-toggle-off', 'sg-toggle-on']) {
      const toggle = page.getByTestId(id);
      expect(await ringOf(toggle), `${id} idle`).toBe('none');
      await tabTo(page, toggle.locator('input'));
      expect(await ringOf(toggle), `${id} on keyboard focus`).toBe(FOCUS_RING);
      expect(await ringOf(toggle.locator('[data-toggle-pill]')), `${id} pill`).toBe('none');
      expect(await ringOf(toggle.locator('[data-toggle-knob]')), `${id} knob`).toBe('none');
      await blur(page);
      expect(await ringOf(toggle), `${id} blurred`).toBe('none');
    }
  });

  test('a form and a nav Radio option are ringed as a whole, also after an arrow key; the circle is not', async ({ page }) => {
    await styleGuide(page);
    for (const group of ['sg-radio-form', 'sg-radio-nav']) {
      const options = radioOptions(page, group);
      const selected = options.filter({ has: page.locator('input:checked') });
      await tabTo(page, selected.locator('input'));
      expect(await ringOf(selected), `${group} selected on keyboard focus`).toBe(FOCUS_RING);
      expect(await ringOf(selected.locator('input')), `${group} circle`).toBe('none');

      await page.keyboard.press('ArrowRight');
      const now = options.filter({ has: page.locator('input:checked') });
      await expect(now.locator('input')).toBeFocused();
      expect(await ringOf(now), `${group} arrowed to`).toBe(FOCUS_RING);
      const count = await options.count();
      for (let i = 0; i < count; i++) {
        if (await options.nth(i).locator('input').evaluate((el) => el === document.activeElement)) continue;
        expect(await ringOf(options.nth(i)), `${group} option ${i} unfocused`).toBe('none');
      }
      await blur(page);
    }
  });

  test('links: the sample link, the masthead logo and Sign out', async ({ page }) => {
    await styleGuide(page);
    const targets: [string, Locator][] = [
      ['sample link', page.getByTestId('sg-links').locator('a')],
      ['logo link', page.getByTestId('sg-masthead-signed-in').locator('a').first()],
      ['sign out', page.getByTestId('sg-masthead-sign-out')],
    ];
    for (const [label, target] of targets) {
      expect(await ringOf(target), `${label} idle`).toBe('none');
      await tabTo(page, target);
      expect(await ringOf(target), `${label} on keyboard focus`).toBe(FOCUS_RING);
      await blur(page);
    }
  });

  test("the dialog's × and its buttons", async ({ page }) => {
    await styleGuide(page);
    await tabTo(page, page.getByTestId('sg-modal-open'));
    await page.keyboard.press('Enter');
    const modal = page.getByTestId('sg-modal-dialog');
    await expect(modal).toBeVisible();
    for (const id of ['modal-close', 'sg-modal-confirm', 'sg-modal-cancel']) {
      const target = modal.getByTestId(id);
      for (let i = 0; i < 6; i++) {
        if (await target.evaluate((el) => el === document.activeElement)) break;
        await page.keyboard.press('Tab');
      }
      await expect(target).toBeFocused();
      expect(await ringOf(target), `${id} on keyboard focus`).toBe(FOCUS_RING);
    }
  });

  test("a puzzle row is ringed as a whole when its link has keyboard focus; the link itself and the row's control separately", async ({ page }) => {
    await styleGuide(page);
    const row = sgRows(page).first();
    const link = row.getByTestId('puzzle-edit-link');
    expect(await ringOf(row), 'row idle').toBe('none');
    await tabTo(page, link);
    expect(await ringOf(row), 'row on keyboard focus').toBe(FOCUS_RING);
    expect(await ringOf(link), 'link itself').toBe('none');

    const control = row.locator('button').first();
    await page.keyboard.press('Tab');
    await expect(control).toBeFocused();
    expect(await ringOf(control), 'row control on keyboard focus').toBe(FOCUS_RING);
    expect(await ringOf(row), 'row once its link loses focus').toBe('none');
  });
});

// --- 14-S11-3: mouse focus shows no ring ---
test.describe('14-S11-3 mouse focus shows no ring', () => {
  test('clicking a Button, the toggle or a Radio option shows no ring', async ({ page }) => {
    await styleGuide(page);
    const buttons = sgButtons(page);
    for (let i = 0; i < (await buttons.count()); i++) {
      const button = buttons.nth(i);
      await button.click();
      await expect(button).toBeFocused();
      expect(await ringOf(button), `button ${i} clicked`).toBe('none');
    }

    const toggle = page.getByTestId('sg-toggle-off');
    await toggle.click();
    await expect(toggle.locator('input')).toBeFocused();
    expect(await ringOf(toggle), 'toggle clicked').toBe('none');

    for (const group of ['sg-radio-form', 'sg-radio-nav']) {
      const option = radioOptions(page, group).last();
      await option.click();
      await expect(option.locator('input')).toBeFocused();
      expect(await ringOf(option), `${group} option clicked`).toBe('none');
    }
  });

  test('pressing a link, the masthead logo, Sign out or a puzzle row shows no ring', async ({ page }) => {
    await styleGuide(page);
    const row = sgRows(page).first();
    const targets: [string, Locator, Locator][] = [
      ['sample link', page.getByTestId('sg-links').locator('a'), page.getByTestId('sg-links').locator('a')],
      ['logo link', page.getByTestId('sg-masthead-signed-in').locator('a').first(), page.getByTestId('sg-masthead-signed-in').locator('a').first()],
      ['sign out', page.getByTestId('sg-masthead-sign-out'), page.getByTestId('sg-masthead-sign-out')],
      ['puzzle row', row.getByTestId('puzzle-edit-link'), row],
    ];
    for (const [label, target, ringed] of targets) {
      await pressWithMouse(page, target);
      expect(await ringOf(ringed), `${label} pressed`).toBe('none');
      await releaseMouse(page);
      await blur(page);
    }
  });

  test("clicking the dialog's open button, then its ×, shows no ring", async ({ page }) => {
    await styleGuide(page);
    await page.getByTestId('sg-modal-open').click();
    const modal = page.getByTestId('sg-modal-dialog');
    await expect(modal).toBeVisible();
    for (const id of ['modal-close', 'sg-modal-confirm', 'sg-modal-cancel']) {
      expect(await ringOf(modal.getByTestId(id)), `${id} after a mouse open`).toBe('none');
    }
    const close = modal.getByTestId('modal-close');
    await pressWithMouse(page, close);
    expect(await ringOf(close), '× pressed').toBe('none');
    await releaseMouse(page);
  });

  test('Tab after a click shows the ring on the next control', async ({ page }) => {
    await styleGuide(page);
    const buttons = sgButtons(page);
    await buttons.first().click();
    expect(await ringOf(buttons.first()), 'clicked').toBe('none');
    await page.keyboard.press('Tab');
    await expect(buttons.nth(1)).toBeFocused();
    expect(await ringOf(buttons.nth(1)), 'tabbed to').toBe(FOCUS_RING);
  });
});

// --- 14-S11-4: on the real screens ---
test.describe('14-S11-4 on the real screens', () => {
  test('the editor: steps and the toggle ring on Tab, not on click; the title input and the grid never', async ({ page }) => {
    const { id } = await seedPuzzle({ grid: catGrid(), hints: {}, phase: 'grid' });
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);

    const step = page.locator('[data-testid="builder-steps"] [data-step-id="build"]');
    await tabTo(page, step);
    expect(await ringOf(step), 'step on keyboard focus').toBe(FOCUS_RING);

    const toggle = page.getByTestId('preview-toggle');
    await tabTo(page, toggle.locator('input'));
    expect(await ringOf(toggle), 'toggle on keyboard focus').toBe(FOCUS_RING);
    await toggle.click();
    expect(await ringOf(toggle), 'toggle clicked').toBe('none');

    const title = page.getByTestId('puzzle-title');
    await tabTo(page, title);
    expect(await ringOf(title), 'title input on keyboard focus').toBe('none');

    const grid = page.getByTestId('grid-region');
    await tabTo(page, grid);
    expect(await ringOf(grid), 'grid on keyboard focus').toBe('none');
  });

  test('the library: a row and Build/Play ring on Tab, not on click', async ({ page }) => {
    const title = `Focus ring ${Date.now()}`;
    await seedPuzzle({ grid: catGrid(), hints: {}, phase: 'grid' }, title);
    await page.goto('/puzzles');
    const row = page.getByTestId('puzzle-list-item').filter({ hasText: title });
    await expect(row).toBeVisible();

    await tabTo(page, row.getByTestId('puzzle-edit-link'));
    expect(await ringOf(row), 'row on keyboard focus').toBe(FOCUS_RING);
    await blur(page);
    expect(await ringOf(row), 'row blurred').toBe('none');

    const radios = page.locator('[role="radiogroup"]').first();
    const selected = radios.locator('label').filter({ has: page.locator('input:checked') });
    await tabTo(page, selected.locator('input'));
    expect(await ringOf(selected), 'Build/Play on keyboard focus').toBe(FOCUS_RING);
    await blur(page);
    await selected.click();
    await expect(selected.locator('input')).toBeFocused();
    expect(await ringOf(selected), 'Build/Play clicked').toBe('none');
  });
});
