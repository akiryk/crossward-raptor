import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { readPuzzleRow } from './helpers/read-puzzle-row';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S6 — Reset Grid with locked words.
//
// With no locked word, Reset Grid's dialog is 20-S1's, unchanged. With one
// or more, the title is still "Reset Grid", the body reads "Do you want
// locked words to remain or would you rather clear every cell?", and the
// buttons are Clear Every Cell (`start-over-clear-all`, primary), Keep
// Locked Words (`start-over-keep-locked`, alternate) and Cancel
// (`start-over-cancel`, alternate), in that order. On one line when they
// fit; otherwise stacked, one per line, left-aligned, Clear Every Cell on
// top.
//
// Clear Every Cell makes every cell white and empty and removes every lock.
// Keep Locked Words makes every cell outside a locked word white and empty,
// and those words stay locked (gray letters, outline, ticks). Either way the
// cursor is on the first cell, Across, the grid focused, and it's saved.
// Cancel or Escape changes nothing.
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const PHONE = { width: 375, height: 800 };

const OLD_BODY = 'Are you sure? This will remove every letter from the grid.';
const LOCKED_BODY = 'Do you want locked words to remain or would you rather clear every cell?';
const BUTTONS = ['Clear Every Cell', 'Keep Locked Words', 'Cancel'];

const GRAY_500 = 'rgb(139, 144, 154)'; // locked letters
const BLACK = 'rgb(0, 0, 0)';
const SIZE = 15;

const run = (from: number, word: string) => [...word].map((_, i) => from + i);
const across = (row: number, cols: number[]) => cols.map((col) => `${col},${row}`);
const down = (col: number, rows: number[]) => rows.map((row) => `${col},${row}`);

/** A daily: TANGENT across row 3 (3–9); ONE down column 5 (2–4), through
 *  TANGENT's N; RAT across row 8 (3–5); black cells at the corners. */
const TANGENT = across(3, run(3, 'TANGENT'));
const TANGENT_ENDS = ['2,3', '10,3'];
const ONE = down(5, run(2, 'ONE'));
const RAT = across(8, run(3, 'RAT'));
const BLACKS = ['0,0', '14,14'];
const EMPTY = '7,6';

function lockGrid(): Grid {
  let grid = createGrid({ cols: SIZE, rows: SIZE, black: [{ col: 0, row: 0 }, { col: 14, row: 14 }] });
  const put = (cells: string[], letters: string) =>
    cells.forEach((coord, i) => {
      const [col, row] = coord.split(',').map(Number);
      grid = withLetter(grid, { col, row }, letters[i]);
    });
  put(TANGENT, 'TANGENT');
  put(ONE, 'ONE');
  put(RAT, 'RAT');
  return grid;
}

async function open(page: Page, viewport = WIDE) {
  await page.setViewportSize(viewport);
  const { id } = await seedPuzzle({ grid: lockGrid(), hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const outlines = (page: Page) => page.getByTestId('word-outline');
const ticks = (page: Page) => page.getByTestId('lock-tick');
const startOver = (page: Page) => page.getByTestId('start-over');
const dialog = (page: Page) => page.getByTestId('start-over-dialog');
const confirm = (page: Page) => page.getByTestId('start-over-confirm');
const clearAll = (page: Page) => page.getByTestId('start-over-clear-all');
const keepLocked = (page: Page) => page.getByTestId('start-over-keep-locked');
const cancel = (page: Page) => page.getByTestId('start-over-cancel');
const gridRegion = (page: Page) => page.getByTestId('grid-region');

const css = (locator: Locator, property: string) =>
  locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);

type Box = { x: number; y: number; width: number; height: number };

async function boxOf(locator: Locator): Promise<Box> {
  const box = await locator.boundingBox();
  if (!box) throw new Error('no bounding box');
  return box;
}

function near(a: number, b: number, tolerance = 2) {
  return Math.abs(a - b) <= tolerance;
}

async function select(page: Page, coord: string) {
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
}

/** Locks the cursor's word with S2's button (at the full width). */
async function lockAt(page: Page, coord: string) {
  await select(page, coord);
  await expect(lockButton(page)).toHaveAccessibleName('Lock word', { timeout: 2000 });
  await lockButton(page).click();
  await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
}

async function lockTangent(page: Page, id: string) {
  await lockAt(page, '6,3');
  await select(page, EMPTY);
  await expect.poll(async () => (await readPuzzleRow(id)).grid.lockedWords, { timeout: 10_000 }).toEqual([
    { col: 3, row: 3, orientation: 'across', length: 7 },
  ]);
}

async function openDialog(page: Page) {
  await startOver(page).click();
  await expect(dialog(page)).toBeVisible();
}

/** Every rendered cell, row by row, as `kind:letters`. */
function renderedCells(page: Page) {
  return page.getByTestId('grid-cell').evaluateAll((cells) =>
    cells.map((element) => {
      const clone = element.cloneNode(true) as HTMLElement;
      clone.querySelectorAll('[data-testid="cell-number"]').forEach((number) => number.remove());
      return `${element.getAttribute('data-kind')}:${clone.textContent?.trim() ?? ''}`;
    })
  );
}

/** The grid as `kind:letters` per cell, row by row, with only these
 *  words' letters (by coordinate) and every other cell white and empty. */
function onlyLetters(words: { cells: string[]; letters: string }[]) {
  const expected = Array<string>(SIZE * SIZE).fill('active:');
  for (const { cells, letters } of words) {
    cells.forEach((coord, i) => {
      const [col, row] = coord.split(',').map(Number);
      expected[row * SIZE + col] = `active:${letters[i]}`;
    });
  }
  return expected;
}

async function savedCells(id: string) {
  const { grid } = await readPuzzleRow(id);
  return grid.cells.flat().map((saved) => (saved.kind === 'active' ? `active:${saved.letter ?? ''}` : 'black'));
}

/** The color of the cell's letter itself (not its number). */
async function letterColor(page: Page, coord: string) {
  return cell(page, coord).evaluate((root) => {
    const elements = [root, ...root.querySelectorAll('*')];
    const holder = elements.find((el) =>
      [...el.childNodes].some((n) => n.nodeType === Node.TEXT_NODE && /^[A-Z]+$/i.test(n.textContent!.trim()))
    );
    return holder ? getComputedStyle(holder).color : 'no letter';
  });
}

async function expectLetters(page: Page, coords: string[], color: string) {
  for (const coord of coords) expect(await letterColor(page, coord), `${coord}'s letter`).toBe(color);
}

/** An outline goes around exactly these cells. */
async function expectOutline(page: Page, coords: string[]) {
  const boxes = await Promise.all(coords.map((coord) => boxOf(cell(page, coord))));
  const want = {
    left: Math.min(...boxes.map((b) => b.x)),
    top: Math.min(...boxes.map((b) => b.y)),
    right: Math.max(...boxes.map((b) => b.x + b.width)),
    bottom: Math.max(...boxes.map((b) => b.y + b.height)),
  };
  await expect
    .poll(async () => {
      for (const outline of await outlines(page).all()) {
        const b = await boxOf(outline);
        if (near(b.x, want.left) && near(b.y, want.top) && near(b.x + b.width, want.right) && near(b.y + b.height, want.bottom)) {
          return true;
        }
      }
      return false;
    }, { message: `an outline around ${coords.join(' ')}` })
    .toBe(true);
}

async function expectAcrossAtOrigin(page: Page) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(1);
  await expect(cell(page, '0,0')).toHaveAttribute('data-highlight', 'selected');
  await expect(cell(page, '1,0')).toHaveAttribute('data-highlight', 'slot');
  await expect(gridRegion(page)).toBeFocused();
}

test.describe('21-S6-2 no locked words: the dialog is unchanged', () => {
  test('never locked: 20-S1\'s body and two buttons', async ({ page }) => {
    await open(page);
    await openDialog(page);
    await expect(dialog(page)).toContainText(OLD_BODY);
    await expect(confirm(page)).toHaveText('Reset Grid');
    await expect(cancel(page)).toHaveText('Cancel');
    await expect(clearAll(page)).toHaveCount(0);
    await expect(keepLocked(page)).toHaveCount(0);
    await expect(page.getByTestId('modal-footer').getByRole('button')).toHaveCount(2);
  });

  test('locked, then unlocked: the same', async ({ page }) => {
    await open(page);
    await lockAt(page, '6,3');
    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Lock word');

    await openDialog(page);
    await expect(dialog(page)).toContainText(OLD_BODY);
    await expect(confirm(page)).toHaveText('Reset Grid');
    await expect(clearAll(page)).toHaveCount(0);
    await expect(keepLocked(page)).toHaveCount(0);
  });
});

test.describe('21-S6-3 the three-button dialog', () => {
  test('a locked word: the title, the new body and three buttons in order on one line', async ({ page }) => {
    const id = await open(page);
    await lockTangent(page, id);
    await openDialog(page);

    await expect(dialog(page).getByRole('heading', { name: 'Reset Grid', exact: true })).toBeVisible();
    await expect(dialog(page)).toContainText(LOCKED_BODY);
    await expect(dialog(page)).not.toContainText(OLD_BODY);
    await expect(confirm(page)).toHaveCount(0);

    const footer = page.getByTestId('modal-footer').getByRole('button');
    await expect(footer).toHaveText(BUTTONS);
    await expect(clearAll(page)).toHaveText('Clear Every Cell');
    await expect(keepLocked(page)).toHaveText('Keep Locked Words');
    await expect(cancel(page)).toHaveText('Cancel');

    const [c, k, x] = await Promise.all([clearAll(page), keepLocked(page), cancel(page)].map(boxOf));
    expect(near(c.y, k.y) && near(k.y, x.y), 'one line').toBe(true);
    expect(c.x + c.width, 'Clear Every Cell first').toBeLessThan(k.x);
    expect(k.x + k.width, 'Keep Locked Words second').toBeLessThan(x.x);

    // Clear Every Cell primary, the other two alternate (20-S1's two looks).
    await expect(clearAll(page)).toHaveAttribute('data-button-type', 'normal');
    await expect(keepLocked(page)).toHaveAttribute('data-button-type', 'alternate');
    await expect(cancel(page)).toHaveAttribute('data-button-type', 'alternate');
  });
});

test.describe('21-S6-4 Clear Every Cell', () => {
  test('every cell white and empty, no lock left, saved, and after a reload', async ({ page }) => {
    const id = await open(page);
    await lockTangent(page, id);
    await page.keyboard.press('ArrowDown');

    await openDialog(page);
    await clearAll(page).click();
    await expect(dialog(page)).toHaveCount(0);

    const blank = onlyLetters([]);
    await expect.poll(() => renderedCells(page)).toEqual(blank);
    await expect(outlines(page)).toHaveCount(0);
    await expect(ticks(page)).toHaveCount(0);
    await expectAcrossAtOrigin(page);
    await expect.poll(() => savedCells(id)).toEqual(blank);
    await expect.poll(async () => (await readPuzzleRow(id)).grid.lockedWords ?? []).toEqual([]);

    await page.reload();
    await waitForEditorReady(page);
    await expect.poll(() => renderedCells(page)).toEqual(blank);
    await expect(outlines(page)).toHaveCount(0);
    await expect(ticks(page)).toHaveCount(0);

    // The old word's cells take letters again.
    await select(page, '4,3');
    await page.keyboard.type('x');
    await expect(cell(page, '4,3')).toContainText('X');
  });
});

test.describe('21-S6-5 Keep Locked Words', () => {
  test('only the locked words\' letters remain, still locked; saved, and after a reload', async ({ page }) => {
    const id = await open(page);
    await lockTangent(page, id);

    await openDialog(page);
    await keepLocked(page).click();
    await expect(dialog(page)).toHaveCount(0);

    // ONE's O and E and RAT go, and the black corners turn white; TANGENT
    // (with ONE's N, its own letter) stays.
    const kept = onlyLetters([{ cells: TANGENT, letters: 'TANGENT' }]);
    await expect.poll(() => renderedCells(page)).toEqual(kept);
    for (const coord of BLACKS) await expect(cell(page, coord)).toHaveAttribute('data-kind', 'active');
    await expectAcrossAtOrigin(page);
    await expectLetters(page, TANGENT, GRAY_500);
    await expectOutline(page, [...TANGENT_ENDS, ...TANGENT]);
    await expect(ticks(page)).toHaveCount(2);
    await expect.poll(() => savedCells(id)).toEqual(kept);
    expect((await readPuzzleRow(id)).grid.lockedWords).toEqual([{ col: 3, row: 3, orientation: 'across', length: 7 }]);

    await page.reload();
    await waitForEditorReady(page);
    await expect.poll(() => renderedCells(page)).toEqual(kept);
    await expectLetters(page, TANGENT, GRAY_500);
    await expectOutline(page, [...TANGENT_ENDS, ...TANGENT]);
    await expect(ticks(page)).toHaveCount(2);
  });

  test('two locked words crossing: both stay, letters shared', async ({ page }) => {
    const id = await open(page);
    await lockTangent(page, id);
    await select(page, '5,2');
    await page.keyboard.press('ArrowDown'); // the first press turns the cursor Down
    await expect(cell(page, '5,4')).toHaveAttribute('data-highlight', 'slot');
    await expect(lockButton(page)).toHaveAccessibleName('Lock word', { timeout: 2000 });
    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');

    await openDialog(page);
    await keepLocked(page).click();
    const kept = onlyLetters([
      { cells: TANGENT, letters: 'TANGENT' },
      { cells: ONE, letters: 'ONE' },
    ]);
    await expect.poll(() => renderedCells(page)).toEqual(kept);
    await expectLetters(page, [...TANGENT, ...ONE], GRAY_500);
    await expect.poll(() => savedCells(id)).toEqual(kept);
  });
});

test.describe('21-S6-6 Cancel', () => {
  test('Cancel or Escape changes nothing; the lock stays', async ({ page }) => {
    const id = await open(page);
    await lockTangent(page, id);
    const before = await renderedCells(page);
    const savedBefore = await savedCells(id);

    await openDialog(page);
    await cancel(page).click();
    await expect(dialog(page)).toHaveCount(0);
    await expect(gridRegion(page)).toBeFocused();
    expect(await renderedCells(page)).toEqual(before);

    await openDialog(page);
    await page.keyboard.press('Escape');
    await expect(dialog(page)).toHaveCount(0);
    expect(await renderedCells(page)).toEqual(before);
    await expectLetters(page, TANGENT, GRAY_500);
    await expectLetters(page, RAT, BLACK);

    await page.waitForTimeout(1500);
    expect(await savedCells(id), 'nothing saved').toEqual(savedBefore);
    expect((await readPuzzleRow(id)).grid.lockedWords).toEqual([{ col: 3, row: 3, orientation: 'across', length: 7 }]);
  });
});

test.describe('21-S6-7 narrow (375px)', () => {
  test('the three buttons stack, one per line, in order, without overflow', async ({ page }) => {
    const id = await open(page);
    await lockTangent(page, id);
    await page.setViewportSize(PHONE);
    await openDialog(page);

    const [c, k, x] = await Promise.all([clearAll(page), keepLocked(page), cancel(page)].map(boxOf));
    expect(k.y, 'Keep Locked Words under Clear Every Cell').toBeGreaterThanOrEqual(c.y + c.height);
    expect(x.y, 'Cancel under Keep Locked Words').toBeGreaterThanOrEqual(k.y + k.height);
    expect(near(c.x, k.x, 1) && near(k.x, x.x, 1), 'left-aligned').toBe(true);

    const panel = await boxOf(page.getByTestId('modal-footer'));
    for (const b of [c, k, x]) expect(b.x + b.width, 'inside the dialog').toBeLessThanOrEqual(panel.x + panel.width);
    expect(
      await page.getByTestId('modal-footer').evaluate((el) => el.scrollWidth <= el.clientWidth),
      'the footer does not overflow'
    ).toBe(true);
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth),
      'the page does not overflow'
    ).toBe(true);
  });
});
