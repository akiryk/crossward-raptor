import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 20-S4 — Reset Grid under the grid.
//
// In the build phase Reset Grid (`start-over`, 20-S1's link) is no longer
// in the toggle row: it sits under the grid with its right edge at the
// grid's right edge, on the color key's first line, its text baseline the
// key's text baseline. It's there with Preview off, and in Preview with or
// without a key, in the same spot. The key is unchanged: 16px below the
// grid from its left edge. Narrow, the key's items wrap in the room left,
// at least 20px from the link. Its look, dialog and behavior are 20-S1's
// (e2e/start-over.spec.ts).
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const PHONE = { width: 375, height: 900 };

const link = (page: Page) => page.getByTestId('start-over');
const puzzleGrid = (page: Page) => page.getByTestId('puzzle-grid');
const legendItems = (page: Page) => page.getByTestId('preview-legend').getByTestId('preview-legend-item');

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

/** The window y of an element's first-line text baseline. */
function baseline(locator: Locator) {
  return locator.evaluate((el) => {
    const probe = document.createElement('span');
    probe.style.cssText = 'display:inline-block;width:0;height:0;margin:0;padding:0;border:0;';
    el.insertBefore(probe, el.firstChild);
    const y = probe.getBoundingClientRect().bottom;
    probe.remove();
    return y;
  });
}

/** AB at the top left, DC at the bottom right (two two-letter words, gold)
 *  and Q at 5,5 with its counterpart 9,9 empty (red): both key items. */
function bothMarks(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'A');
  grid = withLetter(grid, { col: 1, row: 0 }, 'B');
  grid = withLetter(grid, { col: 13, row: 14 }, 'C');
  grid = withLetter(grid, { col: 14, row: 14 }, 'D');
  return withLetter(grid, { col: 5, row: 5 }, 'Q');
}

let titleCounter = 0;
async function openBuilder(page: Page, grid: Grid) {
  titleCounter += 1;
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, `20-S4 ${Date.now()}-${titleCounter}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  await puzzleGrid(page).scrollIntoViewIfNeeded();
}

async function previewOn(page: Page) {
  await page.getByTestId('preview-toggle').locator('input').click({ force: true });
  await expect(puzzleGrid(page)).toHaveAttribute('data-grid-mode', 'preview');
}

/** The link's box, relative to the grid's bottom right corner. */
async function placeOf(page: Page) {
  const g = await box(puzzleGrid(page));
  const at = await box(link(page));
  return { right: g.right - at.right, top: at.top - g.bottom, bottom: at.bottom - g.bottom };
}

test.describe('20-S4 Reset Grid under the grid', () => {
  test('20-S4-1 under the grid at its right edge, on the color key\'s line, in one spot', async ({ page }) => {
    await page.setViewportSize(WIDE);
    await openBuilder(page, bothMarks());
    await expect(link(page)).toHaveCount(1);
    await expect(link(page)).toHaveText('Reset Grid');
    await expect(page.getByTestId('toggle-row').getByTestId('start-over')).toHaveCount(0);

    const off = await placeOf(page);
    expectNear(off.right, 0, 1, 'Preview off: right edge at the grid\'s');
    expect(off.top, 'Preview off: under the grid').toBeGreaterThan(0);

    await previewOn(page);
    await expect(legendItems(page)).toHaveCount(2);
    const on = await placeOf(page);
    expectNear(on.right, 0, 1, 'with the key: right edge at the grid\'s');
    expectNear(on.top, off.top, 0.5, 'with the key: the same spot');
    const text = legendItems(page).first().getByTestId('preview-legend-text');
    expectNear(await baseline(link(page)), await baseline(text), 1, 'the key\'s text baseline');
    const g = await box(puzzleGrid(page));
    const dot = await box(legendItems(page).first().getByTestId('preview-legend-dot'));
    expectNear(dot.top - g.bottom, 16, 1, 'the key 16px below the grid');
    expectNear(dot.left, g.left, 1, 'the key at the grid\'s left edge');

    await openBuilder(page, createGrid({ cols: 15, rows: 15 }));
    await previewOn(page);
    await expect(page.getByTestId('preview-legend')).toHaveCount(0);
    const none = await placeOf(page);
    expectNear(none.right, 0, 1, 'no key: right edge at the grid\'s');
    expectNear(none.top, off.top, 0.5, 'no key: the same spot');
  });

  test('20-S4-2 narrow: on the key\'s first line, clear of its items, no overflow', async ({ page }) => {
    await page.setViewportSize(PHONE);
    await openBuilder(page, bothMarks());
    const off = await placeOf(page);
    expectNear(off.right, 0, 1, 'Preview off: right edge at the grid\'s');

    await previewOn(page);
    await expect(legendItems(page)).toHaveCount(2);
    const on = await placeOf(page);
    expectNear(on.right, 0, 1, 'right edge at the grid\'s');
    expectNear(on.top, off.top, 0.5, 'the same spot');
    const first = legendItems(page).first().getByTestId('preview-legend-text');
    expectNear(await baseline(link(page)), await baseline(first), 1, 'the first key item\'s baseline');

    const at = await box(link(page));
    for (let i = 0; i < 2; i++) {
      const item = await box(legendItems(page).nth(i));
      const sameLine = item.top < at.bottom && item.bottom > at.top;
      if (sameLine) expect(at.left - item.right, `key item ${i + 1} at least 20px from it`).toBeGreaterThanOrEqual(19.5);
    }
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    expect(overflow, 'no horizontal overflow').toBeLessThanOrEqual(0);
  });
});
