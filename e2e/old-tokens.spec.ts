import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 14-S8 — Old-token cleanup.
//
// The pre-redesign tokens no longer resolve anywhere: the 23 old colors,
// --font-display and --font-data, the old radii, and the old type and
// weight tokens. Tailwind emits its own default --radius-sm/-md/-lg when
// any scanned file (the docs included) mentions their utilities, so those
// three are checked in the source (src/app/old-tokens-source.test.ts).
// --font-body and --grid-line-width stay. The page's text is `primary` in
// Inter on white. The style guide's old-token samples (sg-text,
// sg-confirmation, sg-error, sg-tooltip) are gone; each section's first
// heading uses title-2, and the color catalog's subsection headings
// title-3, in primary. A black cell in a build-phase grid (only in data
// saved before 14-S5 removed '.') is an off cell, build-cell-off.
//
// Do not edit this file to match an implementation.

test.use({ viewport: { width: 1280, height: 800 } });

const OLD_TOKENS = [
  ...[
    'background',
    'foreground',
    'ink-2',
    'ink-3',
    'rule',
    'rule-strong',
    'hover-tint',
    'panel-tint',
    'accent',
    'accent-hover',
    'ok-tint',
    'grid-empty',
    'grid-line-build',
    'grid-line-play',
    'cell-fill',
    'selected',
    'slot',
    'slot-content',
    'required',
    'recommended',
    'locked-letter',
    'editable-letter',
    'incomplete',
  ].map((n) => `--color-${n}`),
  '--font-display',
  '--font-data',
  '--radius-btn',
  '--radius-grid',
  ...['headline', 'body', 'help', 'title'].map((n) => `--text-${n}`),
  '--weight-normal',
  '--weight-bold',
];

const KEPT_TOKENS = ['--font-body', '--grid-line-width', '--radius-pill', '--radius-modal'];

const PRIMARY = 'rgb(0, 0, 0)'; // black
const BUILD_OFF = 'rgb(221, 224, 230)'; // gray-200
const CLEAR = ['rgba(0, 0, 0, 0)', 'rgb(255, 255, 255)'];

function tokens(page: Page, names: string[]) {
  return page.evaluate((list) => {
    const style = getComputedStyle(document.documentElement);
    return Object.fromEntries(list.map((n) => [n, style.getPropertyValue(n).trim()]));
  }, names);
}

const firstFamily = (family: string) => family.split(',')[0].trim().replace(/^["']|["']$/g, '');

// --- 14-S8-1: the old tokens are gone ---
test.describe('14-S8-1 old tokens', () => {
  for (const path of ['/', '/puzzles', '/style-guide']) {
    test(`none resolves on ${path}; the kept ones do`, async ({ page }) => {
      await page.goto(path);
      await expect(page.getByTestId('app-header')).toBeVisible();

      const old = await tokens(page, OLD_TOKENS);
      expect(Object.entries(old).filter(([, value]) => value !== '')).toEqual([]);

      const kept = await tokens(page, KEPT_TOKENS);
      for (const name of KEPT_TOKENS) expect(kept[name], name).not.toBe('');
    });
  }
});

// --- 14-S8-2: the page's text and background ---
test.describe('14-S8-2 page', () => {
  test('text is primary in Inter, on white', async ({ page }) => {
    await page.goto('/puzzles');
    await expect(page.getByTestId('app-header')).toBeVisible();

    const look = await page.evaluate(() => {
      const body = getComputedStyle(document.body);
      const html = getComputedStyle(document.documentElement);
      return {
        color: body.color,
        font: body.fontFamily,
        bodyBackground: body.backgroundColor,
        htmlBackground: html.backgroundColor,
      };
    });
    expect(look.color).toBe(PRIMARY);
    expect(firstFamily(look.font)).toBe('Inter');
    expect(CLEAR).toContain(look.bodyBackground);
    expect(CLEAR).toContain(look.htmlBackground);
  });
});

// --- 14-S8-3: the style guide ---
test.describe('14-S8-3 style guide', () => {
  test('the old-token samples are gone', async ({ page }) => {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-colors')).toBeVisible();

    for (const id of ['sg-text', 'sg-confirmation', 'sg-error', 'sg-tooltip']) {
      await expect(page.getByTestId(id), id).toHaveCount(0);
    }
  });

  test('section headings are title-2 and subsection headings title-3, in primary', async ({ page }) => {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-colors')).toBeVisible();

    const headings = await page.evaluate(() => {
      const read = (el: Element) => {
        const s = getComputedStyle(el);
        const section = el.closest('section')?.getAttribute('data-testid') ?? '?';
        return `${section} "${el.textContent?.trim()}": ${s.fontSize} ${s.fontWeight} ${s.color}`;
      };
      return {
        h2: Array.from(document.querySelectorAll('section[data-testid^="sg-"] > h2:first-of-type')).map(read),
        h3: Array.from(document.querySelectorAll('[data-testid="sg-colors"] h3')).map(read),
      };
    });

    expect(headings.h2.length).toBeGreaterThan(20);
    expect(headings.h2.filter((h) => !h.endsWith(`: 32px 600 ${PRIMARY}`))).toEqual([]);
    expect(headings.h3.length).toBe(2);
    expect(headings.h3.filter((h) => !h.endsWith(`: 18px 600 ${PRIMARY}`))).toEqual([]);
  });
});

// --- 14-S8-4: a black cell in a build-phase grid ---
test.describe('14-S8-4 build-phase black cell', () => {
  test('is an off cell, colored like an empty one', async ({ page }) => {
    // A 5×5 saved before 14-S5 with a symmetric pair of black cells and a
    // letter in the corner.
    let grid: Grid = createGrid({ cols: 5, rows: 5, black: [{ col: 2, row: 1 }, { col: 2, row: 3 }] });
    grid = withLetter(grid, { col: 0, row: 0 }, 'A');
    const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' });
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);

    const bg = (coord: string) =>
      page.locator(`[data-coord="${coord}"]`).evaluate((el) => getComputedStyle(el).backgroundColor);

    await expect(page.locator('[data-coord="2,1"]')).toHaveAttribute('data-kind', 'black');
    expect(await bg('2,1')).toBe(BUILD_OFF);
    expect(await bg('2,3')).toBe(BUILD_OFF);
    expect(await bg('1,4')).toBe(BUILD_OFF);
  });
});
