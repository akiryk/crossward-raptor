const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);

type Box = { x: number; y: number; width: number; height: number };

async function boxOf(locator: Locator): Promise<Box> {
  const box = await locator.boundingBox({ timeout: 5000 });
  if (!box) throw new Error('no bounding box');
  return box;
}

/** The box of an element's text itself, not its element. */
function textBox(locator: Locator): Promise<Box> {
  return locator.evaluate((element) => {
    const range = document.createRange();
    range.selectNodeContents(element);
    const r = range.getBoundingClientRect();
    return { x: r.left, y: r.top, width: r.width, height: r.height };
  });
}

/** Whether an element takes any room: absent, or no box. */
async function takesRoom(locator: Locator) {
  if ((await locator.count()) === 0) return false;
  return locator.first().evaluate((element) => {
    const r = element.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  });
}

const css = (locator: Locator, property: string) =>
  locator.evaluate((element, p) => getComputedStyle(element).getPropertyValue(p), property);

/** A CSS color as this browser reports it, for comparison. */
function resolved(page: Page, value: string) {
  return page.evaluate((v) => {
    const probe = document.createElement('div');
    probe.style.color = v;
    document.body.appendChild(probe);
    const color = getComputedStyle(probe).color;
    probe.remove();
    return color;
  }, value);
}

function near(actual: number, expected: number, tolerance = 1) {
  return Math.abs(actual - expected) <= tolerance;
}

function expectNear(actual: number, expected: number, label: string, tolerance = 1) {
  expect(near(actual, expected, tolerance), `${label}: ${actual} ≈ ${expected}`).toBe(true);
}

/** The row's content box: inside its padding. */
async function content(page: Page) {
  const box = await boxOf(row(page));
  const left = parseFloat(await css(row(page), 'padding-left'));
  const right = parseFloat(await css(row(page), 'padding-right'));
  return { left: box.x + left, right: box.x + box.width - right, top: box.y, bottom: box.y + box.height, height: box.height };
}

/** The bar's inside (its content box): where the fill and zone are drawn. */
async function inside(page: Page) {
  const box = await boxOf(bar(page));
  const border = parseFloat(await css(bar(page), 'border-left-width'));
  return { x: box.x + border, width: box.width - 2 * border };
}

/** Shown: the message, "N% complete" and the bar's value. */
async function expectProgress(page: Page, value: number) {
  const ready = value >= 80;
  await expect(progressbar(page)).toBeVisible();
  await expect(message(page)).toHaveText(ready ? 'Ready to create hints!' : 'Keep building.');
  await expect(percent(page)).toHaveText(`${value}% complete`);
  await expect(progressbar(page)).toHaveAttribute('aria-valuenow', String(value));
}

async function expectNoProgress(page: Page) {
  await expect(progressbar(page)).toHaveCount(0);
  await expect(progress(page)).toHaveCount(0);
  await expect(row(page).getByText(/% complete$/)).toHaveCount(0);
}

/** The saved grid's lettered cells, polled past the autosave. */
async function expectSavedLettered(id: string, lettered: number) {
  await expect
    .poll(async () => {
      const grid = deserializeGrid((await readPuzzleRow(id)).grid);
      return completionCount(grid).lettered;
    }, 'saved lettered cells')
    .toBe(lettered);
}

/** Every shown element inside the row's content box, nothing overflowing. */
async function expectInsideRow(page: Page) {
  const c = await content(page);
  for (const [label, locator] of [
    ['Preview', previewToggle(page)],
    ['message', message(page)],
    ['bar', bar(page)],
    ['percentage', percent(page)],
  ] as const) {
    const box = await boxOf(locator);
    expect(box.x, `${label} left`).toBeGreaterThanOrEqual(c.left - 0.5);
    expect(box.x + box.width, `${label} right`).toBeLessThanOrEqual(c.right + 0.5);
    expect(box.y, `${label} top`).toBeGreaterThanOrEqual(c.top - 0.5);
    expect(box.y + box.height, `${label} bottom`).toBeLessThanOrEqual(c.bottom + 0.5);
  }
  const text = await textBox(message(page));
  const box = await boxOf(message(page));
  expect(text.x, 'message text inside its box').toBeGreaterThanOrEqual(box.x - 0.5);
  const overflow = await row(page).evaluate((element) => element.scrollWidth - element.clientWidth);
  expect(overflow, 'row overflow').toBeLessThanOrEqual(0);
}

const center = (box: Box) => box.y + box.height / 2;

/** One line: centered on the row, message box, 12px, bar, 8px, percentage box at the right edge. */
async function expectOneLine(page: Page, barWidth: number) {
  const c = await content(page);
  const rowCenter = c.top + c.height / 2;
  const [p, m, b, pc] = await Promise.all([
    boxOf(previewToggle(page)),
    boxOf(message(page)),
    boxOf(bar(page)),
    boxOf(percent(page)),
  ]);
  for (const [label, box] of [['Preview', p], ['message', m], ['bar', b], ['percentage', pc]] as const) {
    expectNear(center(box), rowCenter, `${label} centered on the row`);
  }
  expectNear(b.height, BAR_HEIGHT, 'bar height', 0.5);
  expectNear(b.width, barWidth, 'bar width');
  expectNear(m.width, MESSAGE_BOX, 'message box');
  expectNear(pc.width, PERCENT_BOX, 'percentage box');
  expectNear(b.x - (m.x + m.width), MESSAGE_TO_BAR, 'message to bar');
  expectNear(pc.x - (b.x + b.width), BAR_TO_PERCENT, 'bar to percentage');
  expectNear(pc.x + pc.width, c.right, 'percentage at the right edge');
  expect(m.x - (p.x + p.width), 'room between Preview and the message').toBeGreaterThanOrEqual(PREVIEW_TO_MESSAGE_MIN - 0.5);
  // The message's text ends at its box's right edge, 12px before the bar.
  const t = await textBox(message(page));
  expectNear(t.x + t.width, m.x + m.width, 'message text right-aligned');
  const pt = await textBox(percent(page));
  expectNear(pt.x, pc.x, 'percentage text left-aligned');
  await expectInsideRow(page);
}

/** Two lines: Preview and the message, then the bar and the percentage, 64px. */
async function expectTwoLines(page: Page, barWidth: number, messageBox = MESSAGE_BOX) {
  const c = await content(page);
  expectNear(c.height, TWO_LINE_ROW, 'row height');
  const [p, m, b, pc] = await Promise.all([
    boxOf(previewToggle(page)),
    boxOf(message(page)),
    boxOf(bar(page)),
    boxOf(percent(page)),
  ]);
  // Line 1, 8px down and 24px tall: Preview stays where a 40px row has it.
  expectNear(center(p), c.top + 20, 'Preview on line 1');
  expectNear(center(m), c.top + 20, 'message on line 1');
  expectNear(m.width, messageBox, 'message box');
  expectNear(m.x + m.width, c.right, 'message at the right edge');
  // Line 2, 8px below line 1, 16px tall.
  expectNear(center(b), c.top + 48, 'bar on line 2');
  expectNear(center(pc), c.top + 48, 'percentage on line 2');
  expectNear(b.height, BAR_HEIGHT, 'bar height', 0.5);
  expectNear(b.width, barWidth, 'bar width');
  expectNear(pc.width, PERCENT_BOX, 'percentage box');
  expectNear(pc.x - (b.x + b.width), BAR_TO_PERCENT, 'bar to percentage');
  expectNear(pc.x + pc.width, c.right, 'percentage at the right edge');
  expect(b.y, 'the bar below the message').toBeGreaterThanOrEqual(m.y + m.height - 0.5);
  expect(m.x, 'the message clear of Preview').toBeGreaterThanOrEqual(p.x + p.width + PREVIEW_TO_MESSAGE_MIN - 0.5);
  const t = await textBox(message(page));
  expectNear(t.x + t.width, m.x + m.width, 'message text right-aligned');
  await expectInsideRow(page);
}

/** The bar on one line: what's left after the fixed parts, 80–180px. */
async function oneLineBar(page: Page) {
  const c = await content(page);
  const p = await boxOf(previewToggle(page));
  const left =
    c.right - c.left - p.width - PREVIEW_TO_MESSAGE_MIN - MESSAGE_BOX - MESSAGE_TO_BAR - BAR_TO_PERCENT - PERCENT_BOX;
  return Math.min(BAR_MAX, left);
}

async function twoLineBar(page: Page) {
  const c = await content(page);
  return Math.min(BAR_MAX, c.right - c.left - BAR_TO_PERCENT - PERCENT_BOX);
}

