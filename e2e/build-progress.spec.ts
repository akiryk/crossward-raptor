// Story 22-S2 — The progress bar.
//
// In the build phase of a daily (15×15) or Sunday (21×21) puzzle, with
// Preview on, the toggle row shows, at the right, on one line: a message
// ("Keep building." below 80%, "Ready to create hints!" at 80% and above),
// a 12px bar and "N% complete" (lettered cells over all cells, rounded
// down). Rebus and Lock Word leave the row while it shows. With Preview
// off, in a mini or midi, in the hints phase and after publishing, the row
// is as before.
//
// Hooks and sizes (the story's delegated decisions):
// - `build-progress` holds `build-progress-message`, `build-progress-bar`
//   (role progressbar, named "Grid completion", aria-valuenow the shown
//   percentage, min 0, max 100) and `build-progress-percent`, in that order.
//   The bar holds `build-progress-fill` and `build-progress-zone`.
// - The bar is 12px tall, border included: a white track (`progress-track`)
//   with a 1px gray-200 border (`line-muted`), square corners. Inside the
//   border, the fill (`progress-fill` gray-200, `progress-fill-ready`
//   interactive-dark from 80%) runs from 0 to the exact share of lettered
//   cells, and the zone (`progress-zone` orange) covers 80–85%, drawn over
//   the fill. No transition.
// - The message is `body-normal`, `primary`, in a 144px box, text right-
//   aligned; the percentage `body-small`, `muted`, in an 88px box, text
//   left-aligned, at the content's right edge. 12px from the message box to
//   the bar, 8px from the bar to the percentage box, at least 16px between
//   Preview and the message box. These boxes hold the widest texts
//   ("Ready to create hints!" 143.7px, "100% complete" 87.8px, measured),
//   so the bar never moves when the text changes. Neither wraps
//   (white-space: nowrap).
// - The percentage, aria-valuenow, the message and the fill's color come
//   from S1's completionPercent / isReadyForHints; the fill's width from
//   completionCount's lettered / total.
// - One line, from a 474px row (a 490px window): every element centered on
//   the row's line; the bar is 180px, or what's left down to 80px.
// - Two lines, below that: the row is 64px tall (8px padding, a 24px line,
//   8px, a 16px line). Line 1: Preview at the left, the message box at the
//   right edge, centered with Preview. Line 2: the bar and the percentage
//   box at the right edge, the bar 180px or what's left.
// - Smaller message font, below a 288px row (a 304px window): the message
//   is `body-small` in a 124px box.
//
// Below 748px the page has 8px of padding a side and the row 12px inside,
// so below 636px (daily) or 716px (Sunday) the row is the window less 16px.
//
// Colors and sizes are written out here. Do not edit this file to match an
// implementation.

const WIDE = { width: 1440, height: 1000 };
const PHONE = { width: 375, height: 900 };

const GRAY_200 = '#dde0e6';
const INTERACTIVE_DARK = '#005b8c';
const ORANGE = '#ef9d05';
const WHITE = '#ffffff';

const BAR_MAX = 180;
const BAR_MIN = 80;
const BAR_HEIGHT = 12;
const MESSAGE_BOX = 144;
const MESSAGE_BOX_SMALL = 124;
const PERCENT_BOX = 88;
const MESSAGE_TO_BAR = 12;
const BAR_TO_PERCENT = 8;
const PREVIEW_TO_MESSAGE_MIN = 16;
const TWO_LINE_ROW = 64;

type Size = 'mini' | 'midi' | 'daily' | 'sunday';
const SIDE: Record<Size, number> = { mini: 5, midi: 9, daily: 15, sunday: 21 };

/** A grid of the size whose first `lettered` cells, in reading order, hold "A". */
function gridWith(size: Size, lettered: number): Grid {
  const side = SIDE[size];
  let grid = createGrid({ cols: side, rows: side });
  for (let i = 0; i < lettered; i++) {
    grid = withLetter(grid, { col: i % side, row: Math.floor(i / side) }, 'A');
  }
  return grid;
}

function hintsFor(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  return Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
}

let titleCounter = 0;
async function seed(size: Size, lettered: number, phase: Phase = 'grid', options: { published?: boolean } = {}) {
  titleCounter += 1;
  const grid = gridWith(size, lettered);
  const { id } = await seedPuzzle(
    { grid, hints: phase === 'hints' ? hintsFor(grid) : {}, phase },
    `22-S2 ${size} ${lettered} ${Date.now()}-${titleCounter}`,
  );
  if (options.published) {
    const client = ownershipTestClient();
    try {
      await client.puzzle.update({
        where: { id },
        data: { publishedAt: new Date('2026-10-01T00:00:00Z'), visibility: 'public' },
      });
    } finally {
      await client.$disconnect();
    }
  }
  return id;
}

async function open(page: Page, id: string, viewport = WIDE) {
  await page.setViewportSize(viewport);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  // Text widths are measured: wait for Inter, not its fallback.
  await page.evaluate(() => document.fonts.ready.then(() => undefined));
}

async function openWithPreview(page: Page, size: Size, lettered: number, viewport = WIDE) {
  const id = await seed(size, lettered);
  await open(page, id, viewport);
  await previewToggle(page).click();
  await expect(previewToggle(page).locator('input')).toBeChecked();
  return id;
}

