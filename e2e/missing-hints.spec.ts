import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { hintKey, requiredHints } from '../src/engine/hints';
import { seedPuzzle } from './helpers/seed-puzzle';
import { builderEditSnapshot } from './helpers/builder-edits';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 17-S1 — Missing hints.
//
// In the hints phase, clicking 3 Publish while any required hint is blank
// (empty or only spaces) still opens "Not quite!", and marks every blank
// hint's row (`data-missing="true"`): the row's background is the new
// `hint-missing` style (the `pink` palette variable, #FFE4E2), and the
// hint number (`hint-label`), the answer word (`hint-answer`) and the
// input's 1px bottom line are the `error` color, focused or not. The input
// is `aria-invalid="true"`. Marking moves nothing.
//
// The marks show with the dialog and stay after it closes. A row's mark
// clears at the first change to its text, from its row or the Hint Box;
// the others stay. A hint emptied again isn't marked until the next
// Publish click, which marks exactly the blank hints. Marks aren't saved.
//
// Below 1000px the Hint Box shows its word's mark: `data-missing="true"`,
// the input filled `hint-missing` with an `error` bottom line and
// `aria-invalid`, and the word in `error`.
//
// Colors are the tokens' resolved hex values (pinned by color-tokens).
// Do not edit this file to match an implementation.

const PINK = 'rgb(255, 228, 226)'; // #FFE4E2
const ERROR = 'rgb(226, 101, 95)'; // text-error
const BLACK = 'rgb(0, 0, 0)'; // primary
const MUTED = 'rgb(139, 144, 154)'; // gray-500
const LINE_MUTED = 'rgb(221, 224, 230)'; // gray-200
const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // hint-box-input
const TRANSPARENT = 'rgba(0, 0, 0, 0)';

const NOT_QUITE = "Some of the puzzle's words still need hints.";

/** A 3×3 word square, CAT / ARE / TEA: 1, 4 and 5 Across; 1, 2 and 3 Down. */
function wordSquare(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  ['CAT', 'ARE', 'TEA'].forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/** Every hint written except 4 Across (absent), 1 Down (empty) and
 *  2 Down (only spaces). */
const BLANK = ['4-across', '1-down', '2-down'];
function someHints(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  const hints: Record<string, string> = Object.fromEntries(
    [...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`])
  );
  delete hints['4-across'];
  hints['1-down'] = '';
  hints['2-down'] = '   ';
  return hints;
}
const FILLED = ['1-across', '5-across', '3-down'];

let titleCounter = 0;
async function open(page: Page, width = 1280) {
  await page.setViewportSize({ width, height: 900 });
  titleCounter += 1;
  const grid = wordSquare();
  const { id } = await seedPuzzle(
    { grid, hints: someHints(grid), phase: 'hints' },
    `S1 missing ${Date.now()}-${titleCounter}`
  );
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

const publish = (page: Page) => page.locator('[data-testid="builder-steps"] [data-step-id="publish"]');
const tooEarly = (page: Page) => page.getByTestId('too-early-dialog');
const row = (page: Page, key: string) => page.locator(`[data-testid="hint-row"][data-hint-key="${key}"]`);
const rowInput = (page: Page, key: string) => row(page, key).getByTestId('hint-input');
const hintBox = (page: Page) => page.getByTestId('hint-box');
const boxInput = (page: Page) => hintBox(page).getByTestId('hint-box-input');
const next = (page: Page) => hintBox(page).getByRole('button', { name: 'Next word' });

async function clickPublish(page: Page) {
  await publish(page).click();
  await expect(tooEarly(page)).toBeVisible();
  await expect(tooEarly(page).getByTestId('modal-title')).toHaveText('Not quite!');
  await expect(tooEarly(page).getByTestId('modal-content')).toHaveText(NOT_QUITE);
}

async function closeDialog(page: Page) {
  await tooEarly(page).getByTestId('modal-ok').click();
  await expect(tooEarly(page)).toHaveCount(0);
}

/** A marked row: the attribute, pink, and error on the number, word and line. */
async function expectMarked(page: Page, key: string) {
  const r = row(page, key);
  await expect(r, key).toHaveAttribute('data-missing', 'true');
  await expect(r, `${key} background`).toHaveCSS('background-color', PINK);
  await expect(r.getByTestId('hint-label'), `${key} number`).toHaveCSS('color', ERROR);
  await expect(r.getByTestId('hint-answer'), `${key} word`).toHaveCSS('color', ERROR);
  await expect(rowInput(page, key), `${key} line`).toHaveCSS('border-bottom-color', ERROR);
  await expect(rowInput(page, key), `${key} invalid`).toHaveAttribute('aria-invalid', 'true');
}

/** An unmarked row at rest, as before this story. */
async function expectUnmarked(page: Page, key: string) {
  const r = row(page, key);
  await expect(r, key).not.toHaveAttribute('data-missing', /.*/);
  await expect(r, `${key} background`).toHaveCSS('background-color', TRANSPARENT);
  await expect(r.getByTestId('hint-label'), `${key} number`).toHaveCSS('color', BLACK);
  await expect(rowInput(page, key), `${key} invalid`).not.toHaveAttribute('aria-invalid', 'true');
}

/** An unmarked row away from focus: the word muted and the line line-muted. */
async function expectUnmarkedAtRest(page: Page, key: string) {
  await expectUnmarked(page, key);
  await expect(row(page, key).getByTestId('hint-answer'), `${key} word`).toHaveCSS('color', MUTED);
  await expect(rowInput(page, key), `${key} line`).toHaveCSS('border-bottom-color', LINE_MUTED);
}

async function markedKeys(page: Page) {
  return page
    .locator('[data-testid="hint-row"][data-missing="true"]')
    .evaluateAll((rows) => rows.map((r) => r.getAttribute('data-hint-key')));
}

test.describe('17-S1-1 Publish marks the blank hints', () => {
  test('no marks before Publish; after it, exactly the blank rows, with the dialog and after it', async ({ page }) => {
    const id = await open(page);
    for (const key of [...BLANK, ...FILLED]) await expectUnmarkedAtRest(page, key);

    await clickPublish(page);
    expect((await markedKeys(page)).sort(), 'with the dialog open').toEqual([...BLANK].sort());

    await closeDialog(page);
    for (const key of BLANK) await expectMarked(page, key);
    for (const key of FILLED) await expectUnmarkedAtRest(page, key);
    expect((await builderEditSnapshot(id)).publishedAt).toBeNull();
  });

  test('marking moves no row, number, input or word', async ({ page }) => {
    await open(page);
    const boxes = () =>
      page
        .locator('[data-testid="hint-row"], [data-testid="hint-label"], [data-testid="hint-input"], [data-testid="hint-answer"]')
        .evaluateAll((els) =>
          els.map((el) => {
            const r = el.getBoundingClientRect();
            return [r.x, r.y, r.width, r.height].map((n) => Math.round(n * 10) / 10);
          })
        );
    const before = await boxes();
    await clickPublish(page);
    await closeDialog(page);
    await expectMarked(page, '1-down');
    expect(await boxes()).toEqual(before);
  });

  test('focusing a marked input keeps its marks', async ({ page }) => {
    await open(page);
    await clickPublish(page);
    await closeDialog(page);
    await rowInput(page, '1-down').click();
    await expect(rowInput(page, '1-down')).toBeFocused();
    await expectMarked(page, '1-down');
  });
});

test.describe('17-S1-2 a row clears at its first change', () => {
  test('typing one letter clears its row only', async ({ page }) => {
    await open(page);
    await clickPublish(page);
    await closeDialog(page);

    await rowInput(page, '1-down').click();
    await page.keyboard.type('F');
    await expectUnmarked(page, '1-down');
    await expect(row(page, '1-down').getByTestId('hint-answer'), 'focused word').toHaveCSS('color', BLACK);
    for (const key of ['4-across', '2-down']) await expectMarked(page, key);
  });

  test('deleting a space from a hint of spaces clears it', async ({ page }) => {
    await open(page);
    await clickPublish(page);
    await closeDialog(page);

    await rowInput(page, '2-down').click();
    await expectMarked(page, '2-down');
    await page.keyboard.press('End');
    await page.keyboard.press('Backspace');
    await expectUnmarked(page, '2-down');
  });

  test('a hint emptied again stays unmarked until the next Publish, which marks exactly the blank ones', async ({ page }) => {
    await open(page);
    await clickPublish(page);
    await closeDialog(page);

    await rowInput(page, '1-down').click();
    await page.keyboard.type('F');
    await page.keyboard.press('Backspace');
    await expect(rowInput(page, '1-down')).toHaveValue('');
    await expectUnmarked(page, '1-down');

    await rowInput(page, '4-across').click();
    await page.keyboard.type('Region');

    await clickPublish(page);
    await closeDialog(page);
    expect((await markedKeys(page)).sort()).toEqual(['1-down', '2-down']);
    await expectMarked(page, '1-down');
    await expectUnmarkedAtRest(page, '4-across');
  });

  test('with every hint written, Publish opens the Publish dialog and nothing is marked', async ({ page }) => {
    await open(page);
    await clickPublish(page);
    await closeDialog(page);
    for (const key of BLANK) {
      await rowInput(page, key).fill(`Hint ${key}`);
    }
    await publish(page).click();
    await expect(page.getByTestId('publish-dialog')).toBeVisible();
    await expect(tooEarly(page)).toHaveCount(0);
    expect(await markedKeys(page)).toEqual([]);
  });

  test('marks are not saved: a reload shows none', async ({ page }) => {
    await open(page);
    await clickPublish(page);
    await closeDialog(page);
    await expectMarked(page, '1-down');

    await page.reload();
    await waitForEditorReady(page);
    expect(await markedKeys(page)).toEqual([]);
    for (const key of BLANK) await expectUnmarkedAtRest(page, key);
  });
});

test.describe('17-S1-3 the Hint Box', () => {
  test('at 768px the box shows its word’s mark, and typing there clears it', async ({ page }) => {
    await open(page, 768);
    await expect(hintBox(page)).toBeVisible();
    await expect(boxInput(page)).toHaveAccessibleName('1 Across hint');
    await expect(hintBox(page)).not.toHaveAttribute('data-missing', /.*/);

    await clickPublish(page);
    await closeDialog(page);

    // 1 Across has a hint: unmarked.
    await expect(hintBox(page)).not.toHaveAttribute('data-missing', /.*/);
    await expect(boxInput(page)).toHaveCSS('background-color', BLUE_MEDIUM);
    await expect(boxInput(page)).not.toHaveAttribute('aria-invalid', 'true');
    await expect(hintBox(page).getByTestId('hint-box-word')).toHaveCSS('color', MUTED);

    // 4 Across is blank: marked, and still marked with the input focused.
    await next(page).click();
    await expect(boxInput(page)).toHaveAccessibleName('4 Across hint');
    await expect(boxInput(page)).toBeFocused();
    await expect(hintBox(page)).toHaveAttribute('data-missing', 'true');
    await expect(boxInput(page)).toHaveCSS('background-color', PINK);
    await expect(boxInput(page)).toHaveCSS('border-bottom-color', ERROR);
    await expect(boxInput(page)).toHaveCSS('border-bottom-width', '1px');
    await expect(boxInput(page)).toHaveAttribute('aria-invalid', 'true');
    await expect(hintBox(page).getByTestId('hint-box-word')).toHaveCSS('color', ERROR);

    await page.keyboard.type('R');
    await expect(hintBox(page)).not.toHaveAttribute('data-missing', /.*/);
    await expect(boxInput(page)).toHaveCSS('background-color', BLUE_MEDIUM);
    await expect(boxInput(page)).not.toHaveAttribute('aria-invalid', 'true');
    await expect(hintBox(page).getByTestId('hint-box-word')).toHaveCSS('color', MUTED);

    // The list (hidden here) shares the marks.
    expect((await markedKeys(page)).sort()).toEqual(['1-down', '2-down']);
  });

  test('a mark cleared in the list is cleared in the box', async ({ page }) => {
    await open(page, 1280);
    await clickPublish(page);
    await closeDialog(page);
    await rowInput(page, '4-across').click();
    await page.keyboard.type('R');

    await page.setViewportSize({ width: 768, height: 900 });
    await expect(hintBox(page)).toBeVisible();
    await expect(boxInput(page)).toHaveAccessibleName('4 Across hint');
    await expect(hintBox(page)).not.toHaveAttribute('data-missing', /.*/);
    await next(page).click(); // 5 Across, filled
    await next(page).click(); // 1 Down, blank
    await expect(boxInput(page)).toHaveAccessibleName('1 Down hint');
    await expect(hintBox(page)).toHaveAttribute('data-missing', 'true');
  });
});

test.describe('17-S1-4 style guide', () => {
  test('sg-hint-row-missing shows a marked row beside an unmarked one', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.goto('/style-guide');
    const section = page.getByTestId('sg-hint-row-missing');
    await expect(section).toBeVisible();

    const marked = section.locator('[data-testid="hint-row"][data-missing="true"]');
    await expect(marked).toHaveCount(1);
    await expect(marked).toHaveCSS('background-color', PINK);
    await expect(marked.getByTestId('hint-label')).toHaveCSS('color', ERROR);
    await expect(marked.getByTestId('hint-answer')).toHaveCSS('color', ERROR);
    await expect(marked.getByTestId('hint-input')).toHaveCSS('border-bottom-color', ERROR);

    const unmarked = section.locator('[data-testid="hint-row"]:not([data-missing])');
    await expect(unmarked.first()).toBeVisible();
    await expect(unmarked.first()).toHaveCSS('background-color', TRANSPARENT);
  });
});
