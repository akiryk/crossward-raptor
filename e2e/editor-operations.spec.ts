import { test, expect } from '@playwright/test';
import type { Page, Route } from '@playwright/test';
import { createGrid, withLetter, type Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { seedBuilderEditPuzzle } from './helpers/builder-edits';
import { currentBuilderId } from './helpers/ownership';
import { commitFromElsewhere, isAction, journalEntries, readSaved, savedRow } from './helpers/operations';
import { waitForEditorReady } from './helpers/wait-for-ready';
import { blockCatchUp } from './helpers/live-sync';

// Story 24-S3 — the editor saves by operations.
//
// Edits go up in bursts (500 ms idle, a 2 s maximum wait, the cursor
// leaving the word, blur, a step button, Start Over, Publish, the page
// hidden or closed), one operation in flight at a time, retried with the
// same opId. The status line at the end of the step row reads "Saving…",
// "Saved" or "Not saved — retrying". Unacknowledged operations are journaled
// in localStorage and re-sent on the next open; leaving with any warns. A
// refused edit is explained above the grid with its input kept. Enter
// Hints, Start Over, locks and Publish are operations (Publish pinned to a
// version). The snapshot actions are gone; an editor tab of another build
// reloads at its next server action.
//
// Do not edit this file to match an implementation.

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
const name = (label: string) => `24-S3 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const status = (page: Page) => page.getByTestId('save-status');
const step = (page: Page, id: string) => page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);

async function seedCat(size = 5) {
  const grid = letters(createGrid({ cols: size, rows: size }), [[0, 0, 'C'], [1, 0, 'A'], [2, 0, 'T']]);
  return seedPuzzle({ grid, hints: {}, phase: 'grid' }, name('cat'));
}
async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}
async function typeAt(page: Page, coord: string, text: string) {
  await cell(page, coord).click();
  await page.keyboard.type(text);
}
const cellsOps = async (id: string) => (await readSaved(id)).log.filter((record) => record.kind === 'cells');

test.describe('24-S3-E1 saving status and bursts', () => {
  test('a word typed is one operation; the status goes Saving… then Saved; the same letter again is no change', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    await expect(status(page)).toHaveText('');
    await typeAt(page, '0,2', 'DOG');
    await expect(status(page)).toHaveText('Saving…');
    await expect(status(page)).toHaveText('Saved');
    const saved = await readSaved(id);
    expect(saved.version).toBe(1);
    expect(savedRow(saved.grid, 2)).toBe('DOG..');
    expect(saved.log).toHaveLength(1);
    expect(saved.log[0]).toMatchObject({ kind: 'cells', status: 'accepted', version: 1 });

    await typeAt(page, '0,2', 'D');
    await page.waitForTimeout(1200);
    expect((await readSaved(id)).log).toHaveLength(1);
    await expect(status(page)).toHaveText('Saved');
  });

  test('moving to another word finalizes the burst; a long run of typing is cut at the maximum wait', async ({ page }) => {
    const { id } = await seedCat(9);
    await open(page, id);
    await typeAt(page, '0,2', 'AB');
    await typeAt(page, '0,6', 'X');
    await expect(status(page)).toHaveText('Saved');
    expect((await cellsOps(id)).map((record) => (record.operation as { writes: unknown[] }).writes.length)).toEqual([2, 1]);

    await cell(page, '0,4').click();
    for (const letter of 'LONGWORDS') {
      await page.keyboard.press(letter);
      await page.waitForTimeout(320);
    }
    await expect(status(page)).toHaveText('Saved');
    const run = (await cellsOps(id)).slice(2);
    expect(run.length).toBeGreaterThanOrEqual(2);
    expect(savedRow((await readSaved(id)).grid, 4)).toBe('LONGWORDS');
  });

  test('a title and a hint are their own bursts, finalized on blur', async ({ page }) => {
    const builder = await currentBuilderId(page);
    const { id } = await seedBuilderEditPuzzle(name('hints'), builder, 'hints');
    await open(page, id);
    const input = page.locator('[data-hint-key="1-across"] [data-testid="hint-input"]');
    await input.click();
    await input.fill('First clue');
    await page.getByTestId('puzzle-title').click();
    await expect.poll(async () => (await readSaved(id)).hints['1-across']).toBe('First clue');
    await page.getByTestId('puzzle-title').fill('Renamed here');
    await expect.poll(async () => (await readSaved(id)).title).toBe('Renamed here');
    const kinds = (await readSaved(id)).log.map((record) => record.kind);
    expect(kinds).toEqual(['hint', 'title']);
    await expect(status(page)).toHaveText('Saved');
  });
});

test.describe('24-S3-E2 failures, the journal and leaving', () => {
  test('a failing send shows Not saved — retrying, then saves once it can', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    let blocked = true;
    await page.route(`**/puzzles/${id}`, (route: Route) =>
      blocked && isAction(route.request()) ? route.abort('failed') : route.continue());
    await typeAt(page, '0,3', 'EEL');
    await expect(status(page)).toHaveText('Not saved — retrying');
    expect((await readSaved(id)).version).toBe(0);
    blocked = false;
    await expect(status(page)).toHaveText('Saved', { timeout: 20_000 });
    expect(savedRow((await readSaved(id)).grid, 3)).toBe('EEL..');
  });

  test('reloading with journaled operations warns, then restores and saves them', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    let blocked = true;
    await page.route(`**/api/puzzles/${id}/operations`, (route: Route) => route.abort('failed'));
    await page.route(`**/puzzles/${id}`, (route: Route) =>
      blocked && isAction(route.request()) ? route.abort('failed') : route.continue());
    const dialogs: string[] = [];
    page.on('dialog', (dialog) => {
      dialogs.push(dialog.type());
      void dialog.accept();
    });
    await typeAt(page, '0,3', 'EEL');
    await expect(status(page)).toHaveText('Not saved — retrying');
    expect(await journalEntries(page, id)).toHaveLength(1);

    await page.reload({ waitUntil: 'commit' });
    blocked = false;
    expect(dialogs).toContain('beforeunload');
    expect((await readSaved(id)).version).toBe(0);
    await waitForEditorReady(page);
    await expect(cell(page, '2,3')).toContainText('L');
    await expect(status(page)).toHaveText('Saved', { timeout: 20_000 });
    const saved = await readSaved(id);
    expect(saved.version).toBe(1);
    expect(savedRow(saved.grid, 3)).toBe('EEL..');
    expect(await journalEntries(page, id)).toHaveLength(0);
  });

  test('an operation that landed without its answer is re-sent after a reload and applied once', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    let lose = true;
    await page.route(`**/api/puzzles/${id}/operations`, (route: Route) => route.abort('failed'));
    await page.route(`**/puzzles/${id}`, async (route: Route) => {
      if (!lose || !isAction(route.request())) return route.continue();
      await route.fetch();
      await route.abort('failed');
    });
    await typeAt(page, '0,4', 'Z');
    await expect.poll(async () => (await readSaved(id)).version).toBe(1);
    await expect(status(page)).toHaveText('Not saved — retrying');

    await page.reload({ waitUntil: 'commit' });
    lose = false;
    await waitForEditorReady(page);
    await expect(status(page)).toHaveText('Saved', { timeout: 20_000 });
    const saved = await readSaved(id);
    expect(saved.version).toBe(1);
    expect(saved.log).toHaveLength(1);
    await expect(cell(page, '0,4')).toContainText('Z');
  });
});

test.describe('24-S3-E3 refusals', () => {
  test('a burst into a word locked elsewhere is explained, its input kept; the grid shows the saved letters', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    // Amended by 24-S4: the editor now catches up about once a second, and a
    // lock it has seen protects the word before any burst is made. Catching
    // up is held off, so the lock is committed while this editor hasn't yet
    // seen it, the case this test is about.
    await blockCatchUp(page, id);
    expect(await commitFromElsewhere(id, { kind: 'lock', word: { col: 0, row: 0, orientation: 'across', length: 3 } }))
      .toMatchObject({ status: 'accepted', version: 1 });
    await typeAt(page, '1,0', 'O');
    const notice = page.getByTestId('save-notice');
    await expect(notice).toBeVisible();
    await expect(notice.getByTestId('save-notice-message')).toHaveText("Your COT in 1-Across wasn't saved: the word was locked.");
    await expect(notice.getByTestId('save-notice-input')).toHaveValue('COT');
    await expect(notice.getByTestId('save-notice-input')).toHaveAttribute('readonly', '');
    await expect(cell(page, '1,0')).toContainText('A');
    const saved = await readSaved(id);
    expect(saved.version).toBe(1);
    expect(saved.log.at(-1)).toMatchObject({ kind: 'cells', status: 'refused', code: 'locked' });
    await expect(page.getByTestId('grid-region')).toBeVisible();
    await notice.getByTestId('save-notice-dismiss').click();
    await expect(notice).toHaveCount(0);
  });

  test('Publish refused at a stale version says so in the Publish dialog and publishes nothing', async ({ page }) => {
    const builder = await currentBuilderId(page);
    const { id } = await seedBuilderEditPuzzle(name('stale'), builder, 'hints');
    await open(page, id);
    await step(page, 'publish').click();
    const dialog = page.getByTestId('publish-dialog');
    await expect(dialog).toBeVisible();
    await commitFromElsewhere(id, { kind: 'hint', key: '1-across', text: 'Changed elsewhere' });
    await dialog.getByTestId('modal-confirm').click();
    await expect(dialog.getByTestId('publish-refusal')).toHaveText(
      "This puzzle changed after you checked it, so it wasn't published. Reload the page to see the changes, then publish again.",
    );
    await expect(dialog).toBeVisible();
    await expect(page.getByTestId('publish-state')).toHaveCount(0);
    expect((await readSaved(id)).publishedAt).toBeNull();
  });
});

test.describe('24-S3-E4 structural operations', () => {
  test('locking, Reset Grid, Enter Hints and Publish go through operations', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    await cell(page, '1,0').click();
    const lock = page.getByRole('button', { name: 'Lock word' });
    await expect(lock).toBeVisible({ timeout: 5000 });
    await lock.click();
    await expect.poll(async () => (await readSaved(id)).log.map((record) => record.kind)).toEqual(['lock']);
    expect((await readSaved(id)).grid.lockedWords).toEqual([{ col: 0, row: 0, orientation: 'across', length: 3 }]);

    await page.getByTestId('start-over').click();
    await page.getByTestId('start-over-clear-all').click();
    await expect.poll(async () => (await readSaved(id)).resetEpoch).toBe(1);
    expect(savedRow((await readSaved(id)).grid, 0)).toBe('.....');

    await typeAt(page, '0,0', 'ABCDE');
    await step(page, 'hints').click();
    await page.getByTestId('modal-confirm').click();
    await expect(page.getByTestId('hints-region')).toBeVisible();
    const saved = await readSaved(id);
    expect(saved.phase).toBe('hints');
    expect(saved.log.map((record) => record.kind)).toEqual(['lock', 'startOver', 'cells', 'enterHints']);
    expect(saved.log.every((record) => record.status === 'accepted')).toBe(true);

    for (const key of Object.keys(saved.hints)) {
      const input = page.locator(`[data-hint-key="${key}"] [data-testid="hint-input"]`);
      await input.fill(`Clue ${key}`);
    }
    await step(page, 'publish').click();
    await page.getByTestId('publish-dialog').getByTestId('modal-confirm').click();
    await expect(page.getByTestId('publish-state')).toHaveText('Published');
    const published = await readSaved(id);
    expect(published.publishedAt).toBeInstanceOf(Date);
    expect(Object.values(published.hints).every((text) => text.startsWith('Clue '))).toBe(true);
    expect(published.version).toBe(published.log.filter((record) => record.status === 'accepted').length);
  });
});

test.describe('24-S3-E5 old tabs and removed snapshot actions', () => {
  test('a version-0 puzzle edited by the editor refuses snapshot writes: an old tab’s save changes nothing', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    const ids: string[] = [];
    page.on('request', (request) => {
      const header = request.headers()['x-deployment-id'];
      if (isAction(request) && header) ids.push(header);
    });
    await typeAt(page, '0,2', 'DOG');
    await expect(status(page)).toHaveText('Saved');
    expect(ids.length).toBeGreaterThan(0);
    const before = await readSaved(id);
    expect(before.version).toBe(1);

    const body = JSON.stringify([id, { cols: 5, rows: 5, cells: [] }]);
    const action = { 'next-action': `7f${'ab'.repeat(20)}`, accept: 'text/x-component', 'content-type': 'text/plain;charset=UTF-8' };
    const current = await page.request.post(`/puzzles/${id}`, { headers: { ...action, 'x-deployment-id': ids[0] }, data: body, maxRedirects: 0 });
    expect(current.status()).toBe(404);
    const old = await page.request.post(`/puzzles/${id}`, { headers: action, data: body, maxRedirects: 0 });
    expect(old.headers()['x-action-redirect']).toBe(`/puzzles/${id};replace`);
    expect(await readSaved(id)).toEqual(before);
  });

  test('an editor tab of another build reloads into this one at its next save, keeping the burst', async ({ page }) => {
    const { id } = await seedCat();
    await open(page, id);
    await page.evaluate(() => { (window as unknown as { oldTab: boolean }).oldTab = true; });
    let stale = true;
    await page.route(`**/puzzles/${id}`, (route: Route) => {
      if (!stale || !isAction(route.request())) return route.continue();
      stale = false;
      const headers = { ...route.request().headers() };
      delete headers['x-deployment-id'];
      return route.continue({ headers });
    });
    await typeAt(page, '0,3', 'OLD');
    await expect.poll(() => page.evaluate(() => (window as unknown as { oldTab?: boolean }).oldTab ?? false), { timeout: 15_000 }).toBe(false);
    await waitForEditorReady(page);
    await expect(cell(page, '2,3')).toContainText('D');
    await expect.poll(async () => savedRow((await readSaved(id)).grid, 3)).toBe('OLD..');
    expect((await readSaved(id)).version).toBe(1);
  });
});
