import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter, type Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { readSaved, savedRow } from './helpers/operations';
import { blockCatchUp, isCatchUp } from './helpers/live-sync';
import { addJay, collaboratorContext, deletePuzzleRow, removeJay } from './helpers/collaborators';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 24-S5 — collaborator membership and authorization.
//
// Adam (the suite's builder) owns the puzzle; Jay (the second seeded
// account) is made a collaborator directly in the database. Jay edits the
// shared puzzle as Adam does, without Reset Grid or Publish. When Jay loses
// access while his editor is open (removed, the puzzle deleted or
// published), the editor stops polling and saving, explains why, becomes
// read-only and keeps his unsaved input to copy. A lost session goes to `/`.
//
// Do not edit this file to match an implementation.

const REMOVED = 'This puzzle is no longer available to you: it was deleted, or you were removed from it. Nothing more can be saved here.';
const PUBLISHED = "This puzzle was published, so it can't be edited any more.";

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
const name = (label: string) => `24-S5 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const status = (page: Page) => page.getByTestId('save-status');
const step = (page: Page, id: string) => page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);
const hintInput = (page: Page, key: string) => page.locator(`[data-hint-key="${key}"] [data-testid="hint-input"]`);
const messages = (page: Page) => page.getByTestId('save-notice-message');

async function seedCat() {
  const grid = letters(createGrid({ cols: 5, rows: 5 }), [[0, 0, 'C'], [1, 0, 'A'], [2, 0, 'T']]);
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, name('cat'));
  await addJay(id);
  return id;
}
/** A 3×3 in Create Hints with every hint written: ready to publish. */
async function seedReady() {
  let grid = createGrid({ cols: 3, rows: 3 });
  for (let row = 0; row < 3; row++) for (let col = 0; col < 3; col++) grid = withLetter(grid, { col, row }, 'A');
  const hints = { '1-across': 'a', '4-across': 'b', '5-across': 'c', '1-down': 'd', '2-down': 'e', '3-down': 'f' };
  const { id } = await seedPuzzle({ grid, hints, phase: 'hints' }, name('ready'));
  await addJay(id);
  return id;
}
async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}
async function typeAt(page: Page, coord: string, text: string) {
  await cell(page, coord).click();
  await page.keyboard.type(text);
}
/** A row as the page shows it: letters, '.' for empty, '#' for black. */
async function shownRow(page: Page, row: number, cols = 5): Promise<string> {
  let text = '';
  for (let col = 0; col < cols; col++) {
    const target = cell(page, `${col},${row}`);
    if ((await target.getAttribute('data-kind')) === 'black') {
      text += '#';
      continue;
    }
    const letter = (await target.innerText()).replace(/[^A-Z]/g, '');
    text += letter.length > 0 ? letter : '.';
  }
  return text;
}
/** Counts the page's catch-up requests from now on. */
function countCatchUps(page: Page, id: string): () => number {
  let count = 0;
  page.on('request', (request) => {
    if (isCatchUp(request, id)) count++;
  });
  return () => count;
}
/** The editor is read-only: the grid takes no focus or keys. */
async function expectReadOnly(page: Page, coord: string) {
  await expect(page.getByTestId('grid-region')).not.toHaveAttribute('tabindex');
  const before = await cell(page, coord).innerText();
  await cell(page, coord).click();
  await page.keyboard.type('Z');
  await expect(cell(page, coord)).toHaveText(before);
}

test.describe('24-S5-E1 a collaborator edits the shared puzzle', () => {
  test('Jay and Adam each see the other’s words; only Adam has Reset Grid', async ({ page, browser }) => {
    const id = await seedCat();
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(page, id);
      await open(j, id);

      await typeAt(j, '0,2', 'DOG');
      await expect(status(j)).toHaveText('Saved');
      await expect.poll(() => shownRow(page, 2), { timeout: 5000 }).toBe('DOG..');
      await typeAt(page, '0,4', 'EEL');
      await expect.poll(() => shownRow(j, 4), { timeout: 5000 }).toBe('EEL..');
      expect(savedRow((await readSaved(id)).grid, 2)).toBe('DOG..');

      await expect(page.getByTestId('start-over')).toBeVisible();
      await expect(j.getByTestId('start-over')).toHaveCount(0);
      await expect(step(j, 'hints')).toBeVisible();
    } finally {
      await jay.context.close();
    }
  });

  test('in Create Hints Jay’s hints save and he has no 3 Publish; Adam has it', async ({ page, browser }) => {
    const id = await seedReady();
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(page, id);
      await open(j, id);
      await expect(step(page, 'publish')).toBeVisible();
      await expect(step(j, 'publish')).toHaveCount(0);

      await hintInput(j, '1-across').fill('From Jay');
      await hintInput(j, '1-across').press('Tab');
      await expect(status(j)).toHaveText('Saved');
      expect((await readSaved(id)).hints['1-across']).toBe('From Jay');
      await expect(hintInput(page, '1-across')).toHaveValue('From Jay', { timeout: 5000 });
    } finally {
      await jay.context.close();
    }
  });

  test('someone who isn’t a collaborator gets the not-found page', async ({ browser }) => {
    const { id } = await seedPuzzle({ grid: createGrid({ cols: 3, rows: 3 }), hints: {}, phase: 'grid' }, name('private'));
    const jay = await collaboratorContext(browser);
    try {
      await jay.page.goto(`/puzzles/${id}`);
      await expect(jay.page.getByTestId('puzzle-not-found')).toBeVisible();
      await expect(jay.page.getByTestId('puzzle-editor')).toHaveCount(0);
    } finally {
      await jay.context.close();
    }
  });
});

test.describe('24-S5-E2 removal while Jay’s editor is open', () => {
  test('with nothing pending: the note and read-only within seconds, and no more polling', async ({ browser }) => {
    const id = await seedCat();
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(j, id);
      await removeJay(id);

      await expect(j.getByTestId('access-lost-state')).toHaveText('No longer available', { timeout: 6000 });
      await expect(messages(j)).toHaveText([REMOVED]);
      const polls = countCatchUps(j, id);
      await j.waitForTimeout(3000);
      expect(polls()).toBe(0);
      await expectReadOnly(j, '3,3');
      await expect(j.getByTestId('start-over')).toHaveCount(0);
    } finally {
      await jay.context.close();
    }
  });

  test('an edit made before he heard is refused and kept to copy; the editor is read-only', async ({ browser }) => {
    const id = await seedCat();
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(j, id);
      await blockCatchUp(j, id);
      await removeJay(id);

      await typeAt(j, '0,2', 'DOGMA');
      await expect(j.getByTestId('access-lost-state')).toBeVisible({ timeout: 6000 });
      await expect(messages(j)).toHaveText([
        REMOVED,
        /^Your DOGMA in \d+-Across wasn't saved: this puzzle is no longer available\.$/,
      ]);
      await expect(j.getByTestId('save-notice-input')).toHaveValue('DOGMA');
      await expect(j.getByTestId('save-notice-copy')).toBeVisible();
      expect(savedRow((await readSaved(id)).grid, 2)).toBe('.....');
      await expectReadOnly(j, '3,3');
    } finally {
      await jay.context.close();
    }
  });
});

test.describe('24-S5-E3 deletion and publication while open', () => {
  test('the puzzle deleted: the same note, read-only, no more polling', async ({ browser }) => {
    const id = await seedCat();
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(j, id);
      await deletePuzzleRow(id);

      await expect(j.getByTestId('access-lost-state')).toBeVisible({ timeout: 6000 });
      await expect(messages(j)).toHaveText([REMOVED]);
      const polls = countCatchUps(j, id);
      await j.waitForTimeout(3000);
      expect(polls()).toBe(0);
      await expectReadOnly(j, '3,3');
    } finally {
      await jay.context.close();
    }
  });

  test('Adam publishes: Jay sees the published state, his unsent hint kept to copy, and stops polling; Adam sees no note', async ({ page, browser }) => {
    const id = await seedReady();
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(page, id);
      await open(j, id);
      const unblock = await blockCatchUp(j, id);

      await step(page, 'publish').click();
      await page.getByTestId('publish-dialog').getByTestId('modal-confirm').click();
      await expect(page.getByTestId('publish-state')).toHaveText('Published');

      await hintInput(j, '1-across').fill('Unsent');
      await hintInput(j, '1-across').press('Tab');
      await expect(messages(j).first()).toHaveText(
        "Your hint for 1-Across wasn't saved: the puzzle was published.", { timeout: 6000 });
      await unblock();

      await expect(j.getByTestId('publish-state')).toHaveText('Published', { timeout: 20_000 });
      await expect(messages(j)).toHaveText(["Your hint for 1-Across wasn't saved: the puzzle was published.", PUBLISHED]);
      await expect(j.getByTestId('save-notice-input')).toHaveValue('Unsent');
      await expect(hintInput(j, '1-across')).toBeDisabled();
      const polls = countCatchUps(j, id);
      await j.waitForTimeout(3000);
      expect(polls()).toBe(0);

      expect((await readSaved(id)).hints['1-across']).toBe('a');
      await expect(page.getByTestId('save-notice')).toHaveCount(0);
    } finally {
      await jay.context.close();
    }
  });
});

test.describe('24-S5-E4 a lost session', () => {
  test('with the session’s cookies gone, the editor lands on / within seconds', async ({ page }) => {
    const id = await seedCat();
    await open(page, id);
    await page.context().clearCookies();
    await expect(page).toHaveURL(/^http:\/\/localhost:3100\/$/, { timeout: 8000 });
  });
});
