// 16-S4 acceptance: duplicating a puzzle.
//
// Every Build row's menu offers Duplicate first. It creates, on the server
// from the stored puzzle, a new unpublished puzzle owned by the caller, titled
// "{title} (copy)", with the source's grid, letters, hints, phase and
// gridBeforeHints, and opens it in the editor. The source and its play
// sessions don't change, and the copy has none.
//
// The suite shares one database, so rows are found by exact titles, never by
// position or count. Do not edit this file to match an implementation.

type Rgb = { r: number; g: number; b: number };

function rgbOf(value: string): Rgb {
  const m = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (!m) throw new Error(`unparseable colour: "${value}"`);
  return { r: Number(m[1]), g: Number(m[2]), b: Number(m[3]) };
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string): Promise<Rgb> {
  return rgbOf(await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style));
}

async function colorOf(locator: Locator) {
  return rgbOf(await locator.evaluate((el) => getComputedStyle(el).color));
}

/** Gives `target` keyboard focus: focus whatever precedes it, then press Tab. */
async function tabTo(page: Page, target: Locator) {
  await target.evaluate((el) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled])'))
      .filter((candidate) => candidate.tabIndex >= 0);
    all[all.indexOf(el as HTMLElement) - 1].focus();
  });
  await page.keyboard.press('Tab');
  await expect(target).toBeFocused();
}

function gate() {
  let release!: () => void;
  const promise = new Promise<void>((resolve) => { release = resolve; });
  return { promise, release };
}

function uniqueTitle(label: string) {
  return `16-S4 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

/** The grid before hints were entered: the fixture's shape without its black square. */
const BEFORE_HINTS = serializeGrid(createGrid({ cols: 3, rows: 3 }));

/** play-route's 3×3 fixture (black centre, CAT/A#A/TEN, four hints) in the given state. */
async function seedSource(builderId: string, state: BuilderEditState) {
  const title = uniqueTitle(state);
  const fixture = playPuzzleFixture();
  const unpublishedGrid = state === 'grid';
  const { id } = await seedPuzzle(
    { ...fixture, phase: unpublishedGrid ? 'grid' : 'hints', hints: unpublishedGrid ? {} : fixture.hints },
    title,
    builderId,
  );
  const client = ownershipTestClient();
  try {
    await client.puzzle.update({
      where: { id },
      data: {
        gridBeforeHints: unpublishedGrid ? Prisma.DbNull : (BEFORE_HINTS as unknown as Prisma.InputJsonValue),
        publishedAt: state.includes('published') ? new Date('2026-10-01T00:00:00Z') : null,
        visibility: state === 'public published' ? 'public' : 'private',
      },
    });
  } finally {
    await client.$disconnect();
  }
  return { id, title };
}

async function library(page: Page) {
  await page.goto('/puzzles');
  await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
}

async function showView(page: Page, view: 'Build' | 'Play') {
  const option = page.getByTestId('library-view').getByRole('radio', { name: view, exact: true });
  await option.check();
  await expect(option).toBeChecked();
}

/** The row whose title is exactly `title`: a copy's title contains its source's. */
function row(page: Page, title: string) {
  return page.getByTestId('puzzle-list-item')
    .filter({ has: page.getByTestId('puzzle-list-title').getByText(title, { exact: true }) });
}

const trigger = (item: Locator) => item.getByTestId('puzzle-menu-button');
const menu = (page: Page) => page.getByTestId('puzzle-menu');
const items = (page: Page) => menu(page).getByRole('menuitem');
const duplicate = (page: Page) => menu(page).getByTestId('puzzle-menu-duplicate');
const hintInput = (page: Page, key: string) => page.locator(`[data-hint-key="${key}"]`).getByTestId('hint-input');

async function openMenu(page: Page, item: Locator) {
  await trigger(item).click();
  await expect(menu(page)).toBeVisible();
}

/** Waits for the copy's editor and returns its ID from the URL. */
async function openedCopy(page: Page, sourceId: string) {
  await expect(page).toHaveURL(/\/puzzles\/[^/]+$/);
  await expect(page).not.toHaveURL(new RegExp(`/puzzles/${sourceId}$`));
  await waitForEditorReady(page);
  const id = new URL(page.url()).pathname.split('/').pop()!;
  expect(id).not.toBe(sourceId);
  return id;
}

/** The source's row and its sessions, for "nothing changed". */
async function snapshot(id: string) {
  return { puzzle: await readPlayPuzzle(id), sessions: await readPlaySessions(id) };
}

/** What a copy must hold, against its source's stored row. */
async function expectCopyOf(copyId: string, source: Awaited<ReturnType<typeof readPlayPuzzle>>, builderId: string) {
  const copy = await readPlayPuzzle(copyId);
  expect(copy.builderId, 'owned by the caller').toBe(builderId);
  expect(copy.title, 'title').toBe(`${source.title} (copy)`);
  expect(copy.grid, 'grid and letters').toEqual(source.grid);
  expect(copy.hints, 'hints').toEqual(source.hints);
  expect(copy.phase, 'phase').toBe(source.phase);
  expect(copy.gridBeforeHints, 'gridBeforeHints').toEqual(source.gridBeforeHints);
  expect(copy.publishedAt, 'unpublished').toBeNull();
  expect(copy.visibility, 'the default visibility').toBe('private');
  expect(copy.createdAt.getTime(), 'created now').toBeGreaterThan(source.updatedAt.getTime());
  expect(copy.updatedAt.getTime(), 'updated now').toBeGreaterThan(source.updatedAt.getTime());
  expect(await readPlaySessions(copyId), 'no play sessions').toEqual([]);
  return copy;
}

test.describe('16-S4-1 what the menu offers', () => {
  test('Duplicate first on every Build row, then the visibility item on published rows, then Delete', async ({ page }) => {
    const me = await currentBuilderId(page);
    for (const [state, expected] of [
      ['grid', ['Duplicate', 'Delete']],
      ['hints', ['Duplicate', 'Delete']],
      ['private published', ['Duplicate', 'Make public', 'Delete']],
      ['public published', ['Duplicate', 'Make unlisted', 'Delete']],
    ] as const) {
      const source = await seedSource(me, state);
      await library(page);
      await openMenu(page, row(page, source.title));
      expect((await items(page).allTextContents()).map((text) => text.trim()), state).toEqual(expected);
      await expect(items(page).first(), state).toHaveAttribute('data-testid', 'puzzle-menu-duplicate');
      await expect(items(page).first()).toHaveAccessibleName('Duplicate');
      expect(await colorOf(items(page).first()), `${state}: Duplicate is primary`).toEqual(await token(page, 'primary'));
      await page.keyboard.press('Escape');
    }
  });
});

test.describe('16-S4-2 duplicating a published puzzle', () => {
  test('opens an unpublished copy in the hints phase, with the same grid, letters and hints, and leaves the source and its sessions alone', async ({ page }) => {
    const me = await currentBuilderId(page);
    const source = await seedSource(me, 'public published');
    const played = playPuzzleFixture().grid;
    await seedPlaySession(me, source.id, played);
    await seedPlaySession(await seedOtherBuilder(), source.id, played);
    const before = await snapshot(source.id);
    expect(before.sessions).toHaveLength(2);

    await library(page);
    await openMenu(page, row(page, source.title));
    await duplicate(page).click();
    const copyId = await openedCopy(page, source.id);
    await expectCopyOf(copyId, before.puzzle, me);
    expect(await snapshot(source.id), 'the source and its sessions are unchanged').toEqual(before);

    // The editor shows an editable puzzle in the hints phase: shape locked, not published.
    await expect(page.getByTestId('puzzle-title')).toHaveValue(`${source.title} (copy)`);
    await expect(page.getByTestId('puzzle-title')).toBeEnabled();
    await expect(page.getByTestId('publish-state')).toHaveCount(0);
    await expect(page.getByTestId('builder-steps')).toBeVisible();
    await expect(page.locator('[data-testid="builder-steps"] [data-step-id="build"]'), 'the shape stays locked').toBeDisabled();
    await expect(page.getByTestId('lock-letters-toggle')).toBeVisible();
    await expect(hintInput(page, '1-across')).toHaveValue('Feline');

    // Editing the copy changes only the copy.
    await hintInput(page, '1-across').fill('Big cat');
    await expect.poll(async () => ((await readPlayPuzzle(copyId)).hints as Record<string, string>)['1-across']).toBe('Big cat');
    expect(await snapshot(source.id), 'the source is still unchanged').toEqual(before);

    // The library lists the copy as a hints-phase draft and keeps the source as it was.
    await library(page);
    await expect(row(page, `${source.title} (copy)`).getByTestId('puzzle-status-badge')).toHaveText('[hint]');
    await expect(row(page, `${source.title} (copy)`)).toHaveAttribute('data-published', 'false');
    await expect(row(page, source.title).getByTestId('puzzle-status-badge')).toHaveText('[published]');
    await expect(row(page, source.title)).toHaveAttribute('data-visibility', 'public');
    await showView(page, 'Play');
    await expect(row(page, source.title)).toHaveCount(1);
    await expect(row(page, `${source.title} (copy)`), 'an unpublished copy is not in Play').toHaveCount(0);
  });
});

test.describe('16-S4-3 duplicating an unpublished puzzle', () => {
  test('a grid-phase copy, chosen by keyboard, opens in grid building; a hints-phase copy keeps its gridBeforeHints', async ({ page }) => {
    const me = await currentBuilderId(page);

    const grid = await seedSource(me, 'grid');
    const gridBefore = await snapshot(grid.id);
    await library(page);
    await tabTo(page, trigger(row(page, grid.title)));
    await page.keyboard.press('Enter');
    await expect(items(page).first(), 'the menu opens on Duplicate').toBeFocused();
    await expect(items(page).first()).toHaveAttribute('data-testid', 'puzzle-menu-duplicate');
    await page.keyboard.press('Enter');
    const gridCopyId = await openedCopy(page, grid.id);
    const gridCopy = await expectCopyOf(gridCopyId, gridBefore.puzzle, me);
    expect(gridCopy.phase).toBe('grid');
    expect(gridCopy.gridBeforeHints).toBeNull();
    await expect(page.getByTestId('puzzle-title')).toHaveValue(`${grid.title} (copy)`);
    await expect(page.locator('[data-testid="builder-steps"] [data-step-id="build"]'), 'grid building').toBeEnabled();
    await expect(page.getByTestId('preview-toggle')).toBeVisible();
    expect(await snapshot(grid.id)).toEqual(gridBefore);

    const hints = await seedSource(me, 'hints');
    const hintsBefore = await snapshot(hints.id);
    await library(page);
    await openMenu(page, row(page, hints.title));
    await duplicate(page).click();
    const hintsCopyId = await openedCopy(page, hints.id);
    const hintsCopy = await expectCopyOf(hintsCopyId, hintsBefore.puzzle, me);
    expect(hintsCopy.gridBeforeHints).toEqual(BEFORE_HINTS);
    await expect(page.locator('[data-testid="builder-steps"] [data-step-id="build"]')).toBeDisabled();
    expect(await snapshot(hints.id)).toEqual(hintsBefore);
  });

  test('a copy of a copy is "{title} (copy) (copy)"', async ({ page }) => {
    const me = await currentBuilderId(page);
    const source = await seedSource(me, 'hints');
    await library(page);
    await openMenu(page, row(page, source.title));
    await duplicate(page).click();
    const first = await openedCopy(page, source.id);

    await library(page);
    await openMenu(page, row(page, `${source.title} (copy)`));
    await duplicate(page).click();
    const second = await openedCopy(page, first);
    expect((await readPlayPuzzle(second)).title).toBe(`${source.title} (copy) (copy)`);
    expect(await countPuzzlesNamed(`${source.title} (copy)`), 'the first copy is unchanged').toBe(1);
  });
});

test.describe('16-S4-4 pending and failure', () => {
  test('a pending duplicate disables the item and keeps the menu open, and creates one copy; a failed one says so, creates none and can be retried', async ({ page }) => {
    const source = await seedSource(await currentBuilderId(page), 'private published');
    const copyTitle = `${source.title} (copy)`;
    await library(page);
    const held = gate();
    let requests = 0;
    let failNext = false;
    await page.route('**/puzzles', async (route) => {
      if (!route.request().headers()['next-action']) return route.continue();
      requests++;
      if (failNext) { failNext = false; return route.abort('failed'); }
      await held.promise;
      return route.continue();
    });

    failNext = true;
    await openMenu(page, row(page, source.title));
    await duplicate(page).click();
    const alert = page.getByTestId('puzzle-menu-error');
    await expect(alert).toHaveText('Could not duplicate the puzzle. Please try again.');
    await expect(alert).toHaveAttribute('role', 'alert');
    await expect(menu(page)).toBeVisible();
    await expect(duplicate(page)).not.toHaveAttribute('aria-disabled', 'true');
    await expect(page).toHaveURL(/\/puzzles$/);
    expect(await countPuzzlesNamed(copyTitle), 'a failed duplicate creates nothing').toBe(0);

    requests = 0;
    try {
      await duplicate(page).click();
      await expect.poll(() => requests).toBe(1);
      await expect(duplicate(page)).toHaveAttribute('aria-disabled', 'true');
      await page.keyboard.press('Escape');
      await page.getByTestId('page-heading').click();
      await expect(menu(page), 'stays open while pending').toBeVisible();
      await duplicate(page).click({ force: true });
      expect(requests, 'no second request while pending').toBe(1);
    } finally {
      held.release();
    }
    await openedCopy(page, source.id);
    expect(await countPuzzlesNamed(copyTitle), 'exactly one copy').toBe(1);
  });
});
