import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 14-S10 — Enter-hints dialog copy and Preview.
//
// 2 Create Hints opens a dialog titled "You sure?", whose whole body is
// "Creating hints will lock the black and white cells as they are now.",
// with "Yes, create hints" (confirm) and "Keep building" (cancel). Preview
// turns on as the dialog opens, if it's off; it stays on after the dialog
// closes without confirming, whichever way it closes. Confirming enters the
// hints phase with the hints-phase grid, as before. Preview is still not
// persisted.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

test.use({ viewport: { width: 1280, height: 800 } });

/** CAT across the top row of a 3x3; every other cell active but empty. */
function catGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'C');
  grid = withLetter(grid, { col: 1, row: 0 }, 'A');
  grid = withLetter(grid, { col: 2, row: 0 }, 'T');
  return grid;
}

async function openPuzzle(page: Page) {
  const { id } = await seedPuzzle({ grid: catGrid(), hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

const step = (page: Page, id: string) =>
  page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);
const dialog = (page: Page) => page.getByTestId('enter-hints-dialog');
const gridMode = (page: Page) => page.getByTestId('puzzle-grid');
const toggleInput = (page: Page) => page.getByTestId('preview-toggle').locator('input');
// (1,1) is empty and mirrors no letter: "empty" in build, "black" in preview.
const centre = (page: Page) => page.locator('[data-coord="1,1"]');

async function expectPreviewOn(page: Page, label: string) {
  await expect(gridMode(page), label).toHaveAttribute('data-grid-mode', 'preview');
  await expect(toggleInput(page), label).toBeChecked();
  await expect(centre(page), label).toHaveAttribute('data-cell-state', 'black');
}

async function expectPreviewOff(page: Page, label: string) {
  await expect(gridMode(page), label).toHaveAttribute('data-grid-mode', 'build');
  await expect(toggleInput(page), label).not.toBeChecked();
  await expect(centre(page), label).toHaveAttribute('data-cell-state', 'empty');
}

async function expectStillGridPhase(page: Page, label: string) {
  await expect(dialog(page), label).toHaveCount(0);
  await expect(step(page, 'build'), label).toHaveAttribute('aria-current', 'true');
  await expect(page.getByTestId('hints-region'), label).toHaveCount(0);
}

/**
 * Clicks 2 Create Hints and returns the grid mode and the toggle's state as
 * they were the moment the dialog entered the page.
 */
async function openDialogWatchingPreview(page: Page) {
  await page.evaluate(() => {
    const w = window as unknown as { __atOpen: unknown };
    w.__atOpen = null;
    const observer = new MutationObserver(() => {
      if (w.__atOpen || !document.querySelector('[data-testid="enter-hints-dialog"]')) return;
      const input = document.querySelector<HTMLInputElement>('[data-testid="preview-toggle"] input');
      w.__atOpen = {
        gridMode: document.querySelector('[data-testid="puzzle-grid"]')?.getAttribute('data-grid-mode'),
        checked: input ? input.checked : null,
      };
      observer.disconnect();
    });
    observer.observe(document.body, { childList: true, subtree: true, attributes: true });
  });
  await step(page, 'hints').click();
  await expect(dialog(page)).toBeVisible();
  return page.evaluate(() => (window as unknown as { __atOpen: unknown }).__atOpen);
}

const CLOSE_WAYS: { name: string; close: (page: Page) => Promise<void> }[] = [
  { name: 'Keep building', close: (page) => dialog(page).getByTestId('modal-cancel').click() },
  { name: 'the ×', close: (page) => dialog(page).getByTestId('modal-close').click() },
  { name: 'Escape', close: (page) => page.keyboard.press('Escape') },
  {
    name: 'the backdrop',
    close: (page) => page.getByTestId('modal-backdrop').click({ position: { x: 5, y: 5 } }),
  },
];

test.describe('14-S10-1 the copy', () => {
  test('"You sure?", its one-sentence body and its two buttons', async ({ page }) => {
    await openPuzzle(page);
    await step(page, 'hints').click();
    await expect(dialog(page)).toBeVisible();

    await expect(dialog(page).getByTestId('modal-title')).toHaveText('You sure?');
    const body = (await dialog(page).getByTestId('modal-content').innerText()).trim();
    expect(body).toBe('Creating hints will lock the black and white cells as they are now.');
    await expect(dialog(page).getByTestId('modal-confirm')).toHaveText('Yes, create hints');
    await expect(dialog(page).getByTestId('modal-cancel')).toHaveText('Keep building');
    expect(await dialog(page).innerText()).not.toMatch(/clue/i);
  });
});

test.describe('14-S10-2 Preview turns on as the dialog opens', () => {
  test('from off, Preview is on the moment the dialog appears', async ({ page }) => {
    await openPuzzle(page);
    await expectPreviewOff(page, 'before');

    const atOpen = await openDialogWatchingPreview(page);

    expect(atOpen).toEqual({ gridMode: 'preview', checked: true });
    await expectPreviewOn(page, 'while open');
  });

  test('already on, Preview stays on', async ({ page }) => {
    await openPuzzle(page);
    await page.getByTestId('preview-toggle').click();
    await expectPreviewOn(page, 'before');

    const atOpen = await openDialogWatchingPreview(page);

    expect(atOpen).toEqual({ gridMode: 'preview', checked: true });
    await expectPreviewOn(page, 'while open');
    await dialog(page).getByTestId('modal-cancel').click();
    await expectPreviewOn(page, 'after Keep building');
  });
});

test.describe('14-S10-3 Preview stays on after the dialog closes', () => {
  for (const way of CLOSE_WAYS) {
    test(`closed by ${way.name}`, async ({ page }) => {
      await openPuzzle(page);
      await step(page, 'hints').click();
      await expect(dialog(page)).toBeVisible();

      await way.close(page);

      await expectStillGridPhase(page, way.name);
      await expectPreviewOn(page, way.name);
      // The toggle still turns it off.
      await page.getByTestId('preview-toggle').click();
      await expectPreviewOff(page, `${way.name}, then the toggle`);
    });
  }

  test('reopening after a close leaves it on, and a reload turns it off', async ({ page }) => {
    await openPuzzle(page);
    await step(page, 'hints').click();
    await dialog(page).getByTestId('modal-cancel').click();
    await expectPreviewOn(page, 'after the first close');

    const atOpen = await openDialogWatchingPreview(page);
    expect(atOpen).toEqual({ gridMode: 'preview', checked: true });
    await page.keyboard.press('Escape');
    await expectPreviewOn(page, 'after the second close');

    await page.reload();
    await waitForEditorReady(page);
    await expectPreviewOff(page, 'after a reload');
  });
});

test.describe('14-S10-4 confirming', () => {
  test('from off: the hints phase starts with the hints-phase grid', async ({ page }) => {
    await openPuzzle(page);
    await step(page, 'hints').click();
    await dialog(page).getByTestId('modal-confirm').click();

    await expect(dialog(page)).toHaveCount(0);
    await expect(page.getByTestId('hints-region')).toBeVisible();
    await expect(gridMode(page)).toHaveAttribute('data-grid-mode', 'hints');
    await expect(page.getByTestId('preview-toggle')).toHaveCount(0);
  });

  test('with Preview already on: the same', async ({ page }) => {
    await openPuzzle(page);
    await page.getByTestId('preview-toggle').click();
    await expectPreviewOn(page, 'before');
    await step(page, 'hints').click();
    await dialog(page).getByTestId('modal-confirm').click();

    await expect(dialog(page)).toHaveCount(0);
    await expect(page.getByTestId('hints-region')).toBeVisible();
    await expect(gridMode(page)).toHaveAttribute('data-grid-mode', 'hints');
    await expect(page.getByTestId('preview-toggle')).toHaveCount(0);
    // EDIT GRID shows the hints-phase grid too, not Preview.
    await step(page, 'build').click();
    await expect(gridMode(page)).toHaveAttribute('data-grid-mode', 'hints-editing');
  });
});
