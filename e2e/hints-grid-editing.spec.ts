// Story 14-S12 — Letters and hints together.
//
// The hints phase has no EDIT GRID mode. Its shape stays locked, but the
// grid takes focus like the build grid: a Tab stop, focused by a click on
// a cell (not on load), and typing a letter overtypes the cursor's cell
// and advances. Backspace still does nothing. The hint inputs stay enabled
// throughout, so the builder moves between letters and hints with a click.
//
// 1 is done: disabled, not selected, gray (button-done, gray-400) and 70px
// wide, its number gray in the white circle, a 16px white check centred in
// the 40px beside the circle, and its label "Build the Grid" faded out but
// still its name. 2 Create Hints is selected. When the hints phase begins,
// the label fades out over 150ms, then the check fades in over 150ms,
// while the fill, width and number change over 300ms; under reduced
// motion, and on a page that loads in the hints phase, it changes at once.
//
// Lock Grid Letters takes the Preview toggle's place in the hints phase,
// off on every load. While on, the on cells are hint-cell-locked-on
// (gray-200) and the grid takes no focus, clicks or keys; a focused hint's
// word is still hint-cell-selected (blue).
//
// The grid keeps the hints phase's colors (on cells hint-cell-on white,
// off cells hint-cell-off gray-700, lines hint-cell-border gray-500).
// While the grid has focus, the cursor cell is hint-cell-cursor
// (yellow-bright), the rest of its word hint-cell-cursor-word
// (yellow-medium), and that word's hint input is filled hint-cell-cursor.
// While a hint input has focus its word is hint-cell-selected (blue), as
// in 14-S6. Nothing fades.
//
// A published puzzle's grid takes no focus and shows no toggle.
//
// Colors are the tokens' resolved hex values (pinned by color-tokens).
// Do not edit this file to match an implementation.

