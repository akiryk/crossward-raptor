// Story 14-S12 — Letters and hints together.
//
// The hints phase has no EDIT GRID mode. Its shape stays locked, but the
// grid takes focus like the build grid: a Tab stop, focused by a click on
// a cell (not on load), and typing a letter overtypes the cursor's cell
// and advances. Backspace still does nothing. The hint inputs stay enabled
// throughout, so the builder moves between letters and hints with a click.
//
// 17-S8 retired 1's "done" look (gray, 70px, a check): the hints phase's
// current step is a label, "2 Create Hints", with no step back.
//
// Lock Grid Letters takes the Preview toggle's place in the hints phase,
// off on every load. While on, the on cells are hint-cell-locked-on
// (gray-200) and the grid takes no focus, clicks or keys; a focused hint's
// word is still hint-cell-selected (blue).
//
// The grid keeps the hints phase's colors (on cells hint-cell-on white,
// off cells hint-cell-off gray-700, lines hint-cell-border gray-500).
// While the grid has focus, the cursor cell is hint-cell-cursor
// (yellow-bright), the rest of its word hint-cell-cursor-word
// (blue-medium since 17-S5, was yellow-medium), and that word's hint
// input is filled hint-cell-cursor.
// While a hint input has focus its word is hint-cell-selected (blue), as
// in 14-S6. Nothing fades.
//
// A published puzzle's grid takes no focus and shows no toggle.
//
// Colors are the tokens' resolved hex values (pinned by color-tokens).
// Do not edit this file to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const WHITE = 'rgb(255, 255, 255)';
const OFF = 'rgb(20, 21, 27)'; // gray-700
const BORDER = 'rgb(139, 144, 154)'; // gray-500
const BLUE = 'rgb(207, 238, 255)'; // blue-medium
const CURSOR = 'rgb(252, 255, 77)'; // yellow-bright
const CURSOR_WORD = 'rgb(207, 238, 255)'; // blue-medium (17-S5, was yellow-medium)
const GRAY_200 = 'rgb(221, 224, 230)'; // hint-cell-locked-on; also build's off
const TRANSPARENT = 'rgba(0, 0, 0, 0)';
const MUTED = 'rgb(139, 144, 154)'; // gray-500

/**
 * A 5×5 with off corners at (4,0) and (0,4), every other cell lettered.
 * 1-across is CATS, (0,0)–(3,0); 1-down is CART, (0,0)–(0,3).
 */
function cornersGrid(): Grid {
  const rows = ['CATS.', 'AREAS', 'RENTS', 'TANKS', '.SEES'];
  let grid = createGrid({ cols: 5, rows: 5, black: [{ col: 4, row: 0 }, { col: 0, row: 4 }] });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

async function open(page: Page, phase: 'grid' | 'hints' = 'hints') {
  const { id } = await seedPuzzle({ grid: cornersGrid(), hints: {}, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

async function openPublished(page: Page) {
  const { id } = await seedPuzzle({ grid: cornersGrid(), hints: {}, phase: 'hints' });
  const client = ownershipTestClient();
  try {
    await client.puzzle.update({ where: { id }, data: { publishedAt: new Date('2026-10-01T00:00:00Z') } });
  } finally {
    await client.$disconnect();
  }
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const grid = (page: Page) => page.getByTestId('puzzle-grid');
const region = (page: Page) => page.getByTestId('grid-region');
const row = (page: Page, key: string) => page.locator(`[data-hint-key="${key}"]`);
const input = (page: Page, key: string) => row(page, key).getByTestId('hint-input');
const answer = (page: Page, key: string) => row(page, key).getByTestId('hint-answer');
const number = (page: Page, key: string) => row(page, key).getByTestId('hint-label');
const heading = (page: Page, orientation: 'across' | 'down') =>
  page
    .locator(`[data-testid="hint-column"][data-orientation="${orientation}"]`)
    .getByTestId('hint-column-heading');
const step = (page: Page, id: string) =>
  page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);
const lockToggle = (page: Page) => page.getByTestId('lock-letters-toggle');
const lockInput = (page: Page) => lockToggle(page).locator('input');

const bg = (locator: Locator) =>
  locator.evaluate((el) => getComputedStyle(el).backgroundColor);

/** The opacity an element is drawn at: its own times every ancestor's. */
const drawnOpacity = (locator: Locator) =>
  locator.evaluate((el) => {
    let opacity = 1;
    for (let node: Element | null = el; node; node = node.parentElement) {
      opacity *= Number(getComputedStyle(node).opacity);
    }
    return Math.round(opacity * 1000) / 1000;
  });

const ACROSS_1 = ['0,0', '1,0', '2,0', '3,0'];
const DOWN_1 = ['0,0', '0,1', '0,2', '0,3'];
/** Every on cell of the corners grid. */
const ON_CELLS = Array.from({ length: 25 }, (_, i) => `${i % 5},${Math.floor(i / 5)}`).filter(
  (coord) => coord !== '4,0' && coord !== '0,4'
);

/** Confirms 2 Create Hints' dialog on a build-phase puzzle. */
async function createHints(page: Page) {
  await step(page, 'hints').click();
  await page.getByTestId('enter-hints-dialog').getByTestId('modal-confirm').click();
}

// 17-S8 retired 14-S12-1 "the numbered buttons" (4 cases) and 14-S12-2
// "1 turns done when the hints phase begins": the hints phase has no 1,
// its current step is the "2 Create Hints" label (17-S8-1,
// e2e/step-controls.spec.ts), so the "done" look is gone.

test.describe('14-S12-3 Lock Grid Letters', () => {
  test("it replaces Preview in the toggle row when the hints phase begins, off; a published puzzle shows neither", async ({ page }) => {
    await open(page, 'grid');
    const preview = (await page.getByTestId('preview-toggle').boundingBox())!;
    await createHints(page);

    await expect(page.getByTestId('preview-toggle')).toHaveCount(0);
    await expect(lockToggle(page)).toBeVisible();
    await expect(lockToggle(page)).toContainText('Lock Grid Letters');
    await expect(lockInput(page)).not.toBeChecked();
    const lock = (await lockToggle(page).boundingBox())!;
    expect(lock.x, 'Preview’s left').toBeCloseTo(preview.x, 0);
    expect(lock.y, 'Preview’s top').toBeCloseTo(preview.y, 0);

    await openPublished(page);
    await expect(lockToggle(page)).toHaveCount(0);
    await expect(page.getByTestId('preview-toggle')).toHaveCount(0);
  });

  test('on, the on cells are gray-200 and the grid takes no focus, clicks or letters', async ({ page }) => {
    await open(page);
    await lockToggle(page).click();
    await expect(lockInput(page)).toBeChecked();
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'hints-locked');

    for (const coord of ON_CELLS) {
      await expect.poll(() => bg(cell(page, coord)), coord).toBe(GRAY_200);
    }
    expect(await bg(cell(page, '4,0')), 'an off cell').toBe(OFF);
    expect(await bg(grid(page)), 'the lines').toBe(BORDER);

    expect(await region(page).getAttribute('tabindex'), 'no Tab stop').toBeNull();
    await cell(page, '1,0').click();
    await expect(region(page), 'a click doesn’t focus it').not.toBeFocused();
    await expect(cell(page, '1,0')).not.toHaveAttribute('data-selected', 'true');
    await page.keyboard.press('u');
    await expect(cell(page, '1,0')).toContainText('A');
    for (const coord of ACROSS_1) expect(await bg(cell(page, coord)), coord).toBe(GRAY_200);
    await expect(input(page, '1-across'), 'the hints stay enabled').toBeEnabled();
  });

  test("on, a focused hint's word is still blue", async ({ page }) => {
    await open(page);
    await lockToggle(page).click();
    await input(page, '1-down').click();

    for (const coord of DOWN_1) {
      await expect.poll(() => bg(cell(page, coord)), coord).toBe(BLUE);
    }
    expect(await bg(cell(page, '1,0')), 'outside the word').toBe(GRAY_200);
    expect(await bg(input(page, '1-down')), 'no fill on the hint').toBe(TRANSPARENT);
  });

  test('off again, the grid is white and takes letters; a reload turns it off', async ({ page }) => {
    const id = await open(page);
    await lockToggle(page).click();
    await expect.poll(() => bg(cell(page, '1,1'))).toBe(GRAY_200);
    await lockToggle(page).click();
    await expect(lockInput(page)).not.toBeChecked();
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'hints');
    await expect.poll(() => bg(cell(page, '1,1'))).toBe(WHITE);

    await cell(page, '1,0').click();
    await expect(region(page)).toBeFocused();
    await page.keyboard.press('u');
    await expect(cell(page, '1,0')).toContainText('U');

    await lockToggle(page).click();
    await expect(lockInput(page)).toBeChecked();
    await expect
      .poll(async () => JSON.stringify((await builderEditSnapshot(id)).grid), { timeout: 5000 })
      .toContain('"U"');
    await page.reload();
    await waitForEditorReady(page);
    await expect(lockInput(page), 'not saved').not.toBeChecked();
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'hints');
  });
});

test.describe('14-S12-4 the grid takes focus and letters', () => {
  test('a Tab stop, not focused on load, focused by a click that selects the cell', async ({ page }) => {
    await open(page);
    await expect(region(page), 'on load').not.toBeFocused();
    expect(await region(page).getAttribute('tabindex'), 'a Tab stop').toBe('0');

    await cell(page, '2,2').click();
    await expect(region(page), 'after a click').toBeFocused();
    await expect(cell(page, '2,2')).toHaveAttribute('data-selected', 'true');
    await expect(row(page, '7-across'), "the cell's word is the active hint").toHaveAttribute('data-active', 'true');
  });

  test('typing overtypes and advances, and the answer follows; Backspace does nothing', async ({ page }) => {
    const id = await open(page);
    await cell(page, '1,0').click();
    await page.keyboard.press('u');

    await expect(cell(page, '1,0')).toContainText('U');
    await expect(cell(page, '2,0')).toHaveAttribute('data-selected', 'true');
    await expect(answer(page, '1-across')).toHaveText('CUTS');

    await page.keyboard.press('Backspace');
    await expect(cell(page, '2,0')).toContainText('T');
    await expect(cell(page, '1,0')).toContainText('U');

    await expect
      .poll(async () => JSON.stringify((await builderEditSnapshot(id)).grid), { timeout: 5000 })
      .toContain('"U"');
    await page.reload();
    await waitForEditorReady(page);
    await expect(cell(page, '1,0')).toContainText('U');
  });

  test('the arrow keys move the cursor and the active hint', async ({ page }) => {
    await open(page);
    await cell(page, '1,0').click();
    await page.keyboard.press('ArrowDown'); // turns to the down word at (1,0)
    await expect(row(page, '2-down')).toHaveAttribute('data-active', 'true');
    await page.keyboard.press('ArrowDown');
    await expect(cell(page, '1,1')).toHaveAttribute('data-selected', 'true');
    await expect(row(page, '2-down')).toHaveAttribute('data-active', 'true');
  });

  test('from a hint to a letter and back, with no mode to switch', async ({ page }) => {
    const id = await open(page);
    await input(page, '1-across').click();
    await page.keyboard.type('Felines');

    await cell(page, '1,0').click();
    await page.keyboard.press('u');
    await expect(cell(page, '1,0')).toContainText('U');
    await expect(input(page, '1-across')).toBeEnabled();

    await input(page, '1-across').click();
    await input(page, '1-across').fill('Gets a haircut, say');
    await expect(input(page, '1-across')).toHaveValue('Gets a haircut, say');

    await expect
      .poll(async () => {
        const stored = await builderEditSnapshot(id);
        const hints = stored.hints as Record<string, string>;
        return [JSON.stringify(stored.grid).includes('"U"'), hints['1-across']];
      }, { timeout: 5000 })
      .toEqual([true, 'Gets a haircut, say']);
  });

  test("a published puzzle's grid takes no focus", async ({ page }) => {
    await openPublished(page);

    expect(await region(page).getAttribute('tabindex'), 'no Tab stop').toBeNull();
    await cell(page, '1,0').click();
    await expect(region(page)).not.toBeFocused();
    for (const coord of ACROSS_1) expect(await bg(cell(page, coord)), coord).toBe(WHITE);
  });
});

test.describe('14-S12-5 the grid colors', () => {
  test("with the grid focused: the cursor yellow-bright, its word blue-medium, the hints phase's colors otherwise", async ({ page }) => {
    await open(page);
    await cell(page, '1,0').click();
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'hints');

    await expect.poll(() => bg(cell(page, '1,0')), 'the cursor cell').toBe(CURSOR);
    for (const coord of ['0,0', '2,0', '3,0']) {
      expect(await bg(cell(page, coord)), `its word, ${coord}`).toBe(CURSOR_WORD);
    }
    expect(await bg(cell(page, '1,1')), 'an on cell outside it').toBe(WHITE);
    expect(await bg(cell(page, '4,0')), 'an off cell').toBe(OFF);
    expect(await bg(grid(page)), 'the lines').toBe(BORDER);
  });

  test("from the grid to a hint, the yellow gives way to the hint's word in blue", async ({ page }) => {
    await open(page);
    await cell(page, '2,2').click();
    await expect.poll(() => bg(cell(page, '2,2'))).toBe(CURSOR);

    await input(page, '1-down').click();
    for (const coord of DOWN_1) {
      await expect.poll(() => bg(cell(page, coord)), coord).toBe(BLUE);
    }
    expect(await bg(cell(page, '2,2')), 'the old cursor cell').toBe(WHITE);
    expect(await bg(cell(page, '1,2')), 'its old word').toBe(WHITE);
  });

  test('no selection once the grid loses focus', async ({ page }) => {
    await open(page);
    await cell(page, '1,0').click();
    await expect.poll(() => bg(cell(page, '1,0'))).toBe(CURSOR);

    await page.getByTestId('puzzle-title').click();
    for (const coord of ACROSS_1) {
      await expect.poll(() => bg(cell(page, coord)), coord).toBe(WHITE);
    }
  });
});

test.describe("14-S12-6 the selected word's hint", () => {
  test('while the grid has focus, its word\'s hint input is filled yellow-bright and nothing fades', async ({ page }) => {
    await open(page);
    await cell(page, '1,0').click();

    await expect.poll(() => bg(input(page, '1-across')), 'its input').toBe(CURSOR);
    await expect(input(page, '1-across')).toBeEnabled();
    expect(await answer(page, '1-across').evaluate((el) => getComputedStyle(el).color), 'its answer').toBe(MUTED);
    expect(await bg(input(page, '1-down')), 'another hint').toBe(TRANSPARENT);

    for (const orientation of ['across', 'down'] as const) {
      expect(await drawnOpacity(heading(page, orientation)), `${orientation} label`).toBe(1);
    }
    const keys = await page
      .locator('[data-hint-key]')
      .evaluateAll((rows) => rows.map((r) => r.getAttribute('data-hint-key') ?? ''));
    expect(keys.length, 'every hint').toBeGreaterThan(2);
    for (const key of keys) {
      expect(await drawnOpacity(number(page, key)), `${key} number`).toBe(1);
      expect(await drawnOpacity(input(page, key)), `${key} input`).toBe(1);
      expect(await drawnOpacity(answer(page, key)), `${key} answer`).toBe(1);
    }
  });

  test('the fill follows the selected word', async ({ page }) => {
    await open(page);
    await cell(page, '1,0').click();
    await cell(page, '0,0').click();
    await expect.poll(() => bg(input(page, '1-across'))).toBe(CURSOR);

    // A second click on the cursor cell turns it to the down word.
    await cell(page, '0,0').click();
    await expect.poll(() => bg(input(page, '1-down')), '1 Down').toBe(CURSOR);
    expect(await bg(input(page, '1-across')), '1 Across').toBe(TRANSPARENT);
  });

  test('the fill goes when the grid loses focus, to the title or to a hint', async ({ page }) => {
    await open(page);
    await cell(page, '1,0').click();
    await expect.poll(() => bg(input(page, '1-across'))).toBe(CURSOR);
    await page.getByTestId('puzzle-title').click();
    await expect.poll(() => bg(input(page, '1-across')), 'the title').toBe(TRANSPARENT);

    // Not the cursor cell again, which would turn the cursor to 2 Down.
    await cell(page, '2,0').click();
    await expect.poll(() => bg(input(page, '1-across'))).toBe(CURSOR);
    await input(page, '1-across').click();
    await expect.poll(() => bg(input(page, '1-across')), 'its own input').toBe(TRANSPARENT);
  });
});

test.describe('14-S12-7 style guide', () => {
  test.use({ viewport: { width: 1280, height: 800 } });

  // 17-S8: was "…, the done 1, and …": the hints phase's sample has no 1.
  test('the focused-grid and locked-letters samples, and no EDIT GRID sample', async ({ page }) => {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-grid-hints-editing')).toHaveCount(0);

    const colorsOf = (sample: Locator) =>
      sample.getByTestId('grid-cell').evaluateAll((cells) => cells.map((c) => getComputedStyle(c).backgroundColor));

    const selected = page.getByTestId('sg-grid-hints-selected').getByTestId('puzzle-grid');
    await expect(selected).toHaveAttribute('data-grid-mode', 'hints');
    const selectedColors = await colorsOf(selected);
    expect(selectedColors).toContain(CURSOR);
    expect(selectedColors).toContain(CURSOR_WORD);
    expect(selectedColors).toContain(WHITE);
    expect(selectedColors).toContain(OFF);
    expect(selectedColors, 'no gray-200 cell').not.toContain(GRAY_200);
    expect(await bg(selected), 'the lines').toBe(BORDER);

    const locked = page.getByTestId('sg-grid-hints-locked').getByTestId('puzzle-grid');
    await expect(locked).toHaveAttribute('data-grid-mode', 'hints-locked');
    const lockedColors = await colorsOf(locked);
    expect(lockedColors).toContain(GRAY_200);
    expect(lockedColors).toContain(BLUE);
    expect(lockedColors).toContain(OFF);
    expect(lockedColors, 'no white cell').not.toContain(WHITE);
    expect(await bg(locked), 'the lines').toBe(BORDER);

    const hintsSteps = page.getByTestId('sg-builder-steps').getByTestId('builder-steps').nth(1);
    await expect(hintsSteps.locator('[data-step-id="build"]')).toHaveCount(0);
  });
});
