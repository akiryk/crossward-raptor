type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) {
    return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  }
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: string, expected: Rgba, label: string) {
  const parsed = parseColor(actual);
  expect({ r: parsed.r, g: parsed.g, b: parsed.b }, label).toEqual({
    r: expected.r,
    g: expected.g,
    b: expected.b,
  });
  expect(parsed.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

/** A text style's size, weight and line height as computed on this page. */
async function textStyleToken(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.fontWeight = `var(--text-${s}--font-weight)`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const c = getComputedStyle(probe);
    const resolved = { fontSize: c.fontSize, fontWeight: c.fontWeight, lineHeight: c.lineHeight };
    probe.remove();
    return resolved;
  }, style);
}

async function expectTextStyle(page: Page, locator: Locator, style: string, label: string) {
  const actual = await locator.evaluate((el) => {
    const c = getComputedStyle(el);
    return {
      fontFamily: c.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      fontSize: c.fontSize,
      fontWeight: c.fontWeight,
      lineHeight: c.lineHeight,
    };
  });
  expect(actual.fontFamily, `${label} family`).toBe('Inter');
  const { fontSize, fontWeight, lineHeight } = actual;
  expect({ fontSize, fontWeight, lineHeight }, `${label} ${style}`).toEqual(await textStyleToken(page, style));
}

async function expectTextColor(page: Page, locator: Locator, style: string, label: string) {
  expectColor(await locator.evaluate((el) => getComputedStyle(el).color), await token(page, style), label);
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

/** The lines an element renders, as the browser lays its text out. */
async function lines(locator: Locator) {
  const text = await locator.evaluate((el) => (el as HTMLElement).innerText);
  return text.split('\n').map((line) => line.trim()).filter(Boolean);
}

/**
 * Where a phrase is drawn inside `root`: its text color, its left edge, its
 * top, and how many lines it occupies. The phrase must sit in one text node.
 */
async function phrase(root: Locator, text: string) {
  return root.evaluate((el, wanted) => {
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const start = (node.textContent ?? '').indexOf(wanted);
      if (start < 0) continue;
      const range = document.createRange();
      range.setStart(node, start);
      range.setEnd(node, start + wanted.length);
      const rects = Array.from(range.getClientRects()).filter((r) => r.width > 0);
      return {
        color: getComputedStyle(node.parentElement!).color,
        left: Math.min(...rects.map((r) => r.left)),
        top: Math.min(...rects.map((r) => r.top)),
        lineCount: new Set(rects.map((r) => Math.round(r.top))).size,
      };
    }
    throw new Error(`"${wanted}" is not drawn in one text node`);
  }, text);
}

function uniqueEmail(label: string) {
  return `s1-${label}-${randomUUID()}@example.test`;
}

async function desktop(page: Page) {
  await page.setViewportSize({ width: 1280, height: 800 });
  await openSignedOutFrontDoor(page);
}

/** Every magic-link request the page sends, as parsed JSON bodies. */
function recordLinkRequests(page: Page) {
  const bodies: Array<Record<string, unknown>> = [];
  page.on('request', (request) => {
    if (new URL(request.url()).pathname === MAGIC_LINK_PATH && request.method() === 'POST') {
      bodies.push(JSON.parse(request.postData() ?? '{}'));
    }
  });
  return bodies;
}

/** The container's geometry: its box and the content edge 20px right of its 1px hairline. */
async function frame(page: Page) {
  const container = await box(page.getByTestId('front-door'));
  return { container, contentLeft: container.x + 1 + 20 };
}

function fields(page: Page) {
  return {
    email: page.getByTestId('sign-in-email'),
    submit: page.getByTestId('sign-in-submit'),
    emailError: page.getByTestId('sign-in-email-error'),
    heading: page.getByTestId('front-door').getByRole('heading', { level: 1 }),
    help: page.getByTestId('sign-in-privacy'),
  };
}

async function submitThroughForm(page: Page, email: string) {
  const f = fields(page);
  await f.email.fill(email);
  await f.submit.click();
  await expect(page.getByTestId('sign-in-sent')).toBeVisible();
}

/** Sign in from a fresh front door with this email, save the suggested username, landing on /puzzles. */
async function signInThroughForm(page: Page, email: string) {
  await openSignedOutFrontDoor(page);
  await submitThroughForm(page, email);
  await page.goto(await readMagicLinkUrl(email));
  await page.waitForSelector('[data-testid="username-step"][data-ready="true"]');
  await page.getByTestId('username-submit').click();
  await expect(page).toHaveURL(/\/puzzles$/);
}

async function expectNewPuzzleOpensDirectly(page: Page) {
  await waitForNewPuzzleReady(page);
  await page.getByTestId('new-puzzle-button').click();
  await expect(page.getByTestId('new-puzzle-dialog')).toBeVisible();
  await expect(page.getByTestId('new-puzzle-name')).toBeFocused();
  await expect(page.getByTestId('display-name-step')).toHaveCount(0);
}

test.describe('14-S1-1 layout', () => {
  test('one centered container 90px below the masthead, 700px wide, at least 630px tall, with a 1px line-muted left hairline', async ({ page }) => {
    await desktop(page);
    const container = page.getByTestId('front-door');
    const header = await box(page.getByTestId('app-header'));
    const c = await box(container);
    const viewport = await page.evaluate(() => document.documentElement.clientWidth);

    expect(c.y - (header.y + header.height), 'gap below the masthead').toBeCloseTo(90, 0);
    expect(c.width, 'width').toBeCloseTo(700, 0);
    expect(c.x + c.width / 2, 'centered').toBeCloseTo(viewport / 2, 0);
    expect(c.height, 'height').toBeGreaterThanOrEqual(630);

    const border = await container.evaluate((el) => {
      const s = getComputedStyle(el);
      return {
        widths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
        leftStyle: s.borderLeftStyle,
        leftColor: s.borderLeftColor,
      };
    });
    expect(border.widths, 'only a left border').toEqual(['0px', '0px', '0px', '1px']);
    expect(border.leftStyle).toBe('solid');
    expectColor(border.leftColor, await token(page, 'line-muted'), 'hairline');
  });

  test('heading, fields, button and help line share the left edge 20px right of the hairline', async ({ page }) => {
    await desktop(page);
    const { contentLeft } = await frame(page);
    const f = fields(page);
    for (const [label, locator] of [
      ['heading', f.heading],
      ['email', f.email],
      ['button', f.submit],
      ['help line', f.help],
    ] as const) {
      expect((await box(locator)).x, label).toBeCloseTo(contentLeft, 0);
    }
    for (const text of HEADING) {
      expect((await phrase(f.heading, text)).left, text).toBeCloseTo(contentLeft, 0);
    }
    expect((await phrase(f.help, 'We’ll only')).left, 'help text').toBeCloseTo(contentLeft, 0);
  });

  test('40px heading to email, 40px email to button; the field 400px', async ({ page }) => {
    await desktop(page);
    const f = fields(page);
    const heading = await box(f.heading);
    const email = await box(f.email);
    const button = await box(f.submit);
    expect(email.y - (heading.y + heading.height), 'heading to email').toBeCloseTo(40, 0);
    expect(button.y - (email.y + email.height), 'email to button').toBeCloseTo(40, 0);
    expect(email.width, 'email width').toBeCloseTo(400, 0);
  });

  test('the help line sits at the container bottom on one line', async ({ page }) => {
    await desktop(page);
    const { container } = await frame(page);
    const help = fields(page).help;
    const h = await box(help);
    expect(h.y + h.height, 'help line bottom').toBeCloseTo(container.y + container.height, 0);
    expect((await phrase(help, HELP)).lineCount, 'one line').toBe(1);
  });
});

