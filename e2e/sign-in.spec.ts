test.describe('14-S1-3 validation', () => {
  test('an empty submit shows the error in the field’s error state, focuses Email, and sends nothing', async ({ page }) => {
    await desktop(page);
    const requests = recordLinkRequests(page);
    const f = fields(page);
    await f.submit.click();

    await expect(f.emailError).toHaveText(BLANK_EMAIL);
    await expect(f.email).toBeFocused();
    for (const [label, input, message] of [
      ['email', f.email, f.emailError],
    ] as const) {
      await expect(input).toHaveAttribute('aria-invalid', 'true');
      expectColor(
        await input.evaluate((el) => getComputedStyle(el).borderBottomColor),
        await token(page, 'error'),
        `${label} line`,
      );
      await expectTextStyle(page, message, 'body-normal', `${label} message`);
      await expectTextColor(page, message, 'error', `${label} message`);
      const i = await box(input);
      const m = await box(message);
      expect(m.y - (i.y + i.height), `${label} message gap`).toBeCloseTo(8, 0);
    }
    const emailMessage = await box(f.emailError);
    const button = await box(f.submit);
    expect(button.y - (emailMessage.y + emailMessage.height), 'email error to button').toBeCloseTo(40, 0);

    await page.waitForLoadState('networkidle');
    expect(requests).toEqual([]);
    await expect(page.getByTestId('sign-in-sent')).toHaveCount(0);
  });

  test('editing the field clears its error', async ({ page }) => {
    await desktop(page);
    const f = fields(page);
    await f.submit.click();
    await expect(f.emailError).toHaveText(BLANK_EMAIL);
    await f.email.fill('a');
    await expect(f.emailError).toHaveCount(0);
    await expect(f.email).not.toHaveAttribute('aria-invalid', 'true');
  });

  test('a malformed email shows its error, focuses Email and sends nothing; fixing it sends the trimmed email', async ({ page }) => {
    await desktop(page);
    const requests = recordLinkRequests(page);
    const f = fields(page);
    for (const bad of ['ada@example', 'ada lovelace@example.com', 'ada@@example.com', '@example.com']) {
      await f.email.fill(bad);
      await f.submit.click();
      await expect(f.emailError, bad).toHaveText(BAD_EMAIL);
      await expect(f.email).toBeFocused();
    }
    await page.waitForLoadState('networkidle');
    expect(requests).toEqual([]);

    const email = uniqueEmail('trimmed');
    await f.email.fill(`  ${email}  `);
    await f.submit.click();
    await expect(page.getByTestId('sign-in-sent')).toBeVisible();
    await page.waitForLoadState('networkidle');
    expect(requests).toHaveLength(1);
    expect(requests[0]).toEqual({ email, callbackURL: '/puzzles' });
  });
});

test.describe('14-S1-4 sent', () => {
  test('two body-large lines replace the fields 40px below the heading; the help line stays put', async ({ page }) => {
    await desktop(page);
    const f = fields(page);
    const helpBefore = await box(f.help);
    await submitThroughForm(page, uniqueEmail('sent'));

    const sent = page.getByTestId('sign-in-sent');
    const tip = page.getByTestId('front-door').getByText(PRO_TIP, { exact: true });
    await expect(sent).toHaveText(SENT);
    await expect(tip).toBeVisible();
    await expectTextStyle(page, sent, 'body-large', 'sent line');
    await expectTextColor(page, sent, 'primary', 'sent line');
    await expectTextStyle(page, tip, 'body-large', 'pro-tip');
    await expectTextColor(page, tip, 'muted', 'pro-tip');

    const { contentLeft } = await frame(page);
    const heading = await box(f.heading);
    const s = await box(sent);
    const t = await box(tip);
    expect(s.y - (heading.y + heading.height), 'heading to sent').toBeCloseTo(40, 0);
    expect(t.y, 'pro-tip below sent').toBeGreaterThanOrEqual(s.y + s.height - 1);
    expect(s.x, 'sent left').toBeCloseTo(contentLeft, 0);
    expect(t.x, 'pro-tip left').toBeCloseTo(contentLeft, 0);

    await expect(f.email).toHaveCount(0);
    await expect(f.submit).toHaveCount(0);
    const helpAfter = await box(f.help);
    expect(helpAfter.x, 'help line x').toBeCloseTo(helpBefore.x, 0);
    expect(helpAfter.y, 'help line y').toBeCloseTo(helpBefore.y, 0);
  });
});

test.describe('14-S1-5 failure', () => {
  test('a failed send keeps the form and value, shows a two-line alert 20px below the button, and a retry sends', async ({ page }) => {
    await desktop(page);
    let attempts = 0;
    await page.route(`**${MAGIC_LINK_PATH}`, async (route) => {
      attempts += 1;
      if (attempts === 1) {
        await route.fulfill({
          status: 503,
          contentType: 'application/json',
          body: JSON.stringify({ code: 'DELIVERY_UNAVAILABLE', message: 'Could not send the sign-in link.' }),
        });
        return;
      }
      await route.continue();
    });
    const f = fields(page);
    const email = uniqueEmail('retry');
    await f.email.fill(email);
    await f.submit.click();

    const alert = page.getByTestId('sign-in-form').getByRole('alert');
    await expect(alert).toBeVisible();
    expect(await lines(alert)).toEqual(FAILURE);
    await expectTextStyle(page, alert, 'body-large', 'alert');
    const first = await phrase(alert, FAILURE[0]);
    const second = await phrase(alert, FAILURE[1]);
    expectColor(first.color, await token(page, 'primary'), 'alert first line');
    expectColor(second.color, await token(page, 'muted'), 'alert second line');
    expect(second.top, 'second line below first').toBeGreaterThan(first.top);

    const { contentLeft } = await frame(page);
    const button = await box(f.submit);
    const a = await box(alert);
    expect(a.y - (button.y + button.height), 'button to alert').toBeCloseTo(20, 0);
    expect(a.x, 'alert left').toBeCloseTo(contentLeft, 0);

    await expect(page.getByTestId('sign-in-sent')).toHaveCount(0);
    await expect(f.email).toHaveValue(email);
    await expect(f.submit).toBeEnabled();

    await f.submit.click();
    await expect(page.getByTestId('sign-in-sent')).toBeVisible();
    await expect(alert).toHaveCount(0);
    expect(attempts).toBe(2);
    expect(await readMagicLinkUrl(email)).toBeTruthy();
  });
});

