// Story F5 — Input.
//
// `TextInput` is one underlined field in two sizes: regular (`body-normal`)
// and large (`body-large`), with entered text in `primary` and any
// placeholder in `muted`. Its only stroke is a 1px bottom line in
// `line-muted` that turns `line-highlight` on focus, never with a focus
// ring, and does not change on hover. An optional label sits above in
// `title-4` `primary`; an optional error turns the line `error`, even when
// focused, and shows a `body-normal` `error` message below it. The sign-in
// email is large; the new-puzzle and builder-name fields carry their names
// as labels; the hint inputs are regular. Asserted by color style;
// paddings are not pinned. `/style-guide` catalogs the variations.
// Do not edit this file to match an implementation.

const SENTINEL = '#123456';

type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) {
    return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  }
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: string, expected: Rgba, label: string) {
  const parsed = parseColor(actual);
  expect({ r: parsed.r, g: parsed.g, b: parsed.b }, label).toEqual({
    r: expected.r,
    g: expected.g,
    b: expected.b,
  });
  expect(parsed.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

function styleOf(locator: Locator) {
  return locator.evaluate((el) => {
    const s = getComputedStyle(el);
    const placeholder = getComputedStyle(el, '::placeholder');
    return {
      background: s.backgroundColor,
      color: s.color,
      placeholderColor: placeholder.color,
      borderColors: [s.borderTopColor, s.borderRightColor, s.borderBottomColor, s.borderLeftColor],
      borderWidths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
      bottomStyle: s.borderBottomStyle,
      radii: [s.borderTopLeftRadius, s.borderTopRightRadius, s.borderBottomRightRadius, s.borderBottomLeftRadius],
      paddingLeft: parseFloat(s.paddingLeft),
      fontSize: parseFloat(s.fontSize),
      fontWeight: Number(s.fontWeight),
      fontFamily: s.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      lineHeight: s.lineHeight,
      boxShadow: s.boxShadow,
      outline:
        s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0
          ? 'none'
          : `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor}`,
    };
  });
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

async function tokenLineHeight(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const lh = getComputedStyle(probe).lineHeight;
    probe.remove();
    return lh;
  }, style);
}

async function expectTextStyle(page: Page, locator: Locator, style: string, size: number, weight: number, label: string) {
  const s = await styleOf(locator);
  expect(s.fontFamily, `${label} family`).toBe('Inter');
  expect(s.fontSize, `${label} size`).toBe(size);
  expect(s.fontWeight, `${label} weight`).toBe(weight);
  expect(s.lineHeight, `${label} line height`).toBe(await tokenLineHeight(page, style));
}

/** A field's resting line: only the bottom edge, 1px solid, in `style`; no box, fill or ring. */
async function expectUnderline(page: Page, input: Locator, style: string, label: string) {
  const s = await styleOf(input);
  expect(s.borderWidths, `${label} border widths`).toEqual(['0px', '0px', '1px', '0px']);
  expect(s.bottomStyle, `${label} bottom style`).toBe('solid');
  expectColor(s.borderColors[2], await token(page, style), `${label} underline`);
  expect(s.radii, `${label} radii`).toEqual(['0px', '0px', '0px', '0px']);
  expect(parseColor(s.background).a, `${label} background`).toBe(0);
  expect(s.outline, `${label} outline`).toBe('none');
  expect(s.boxShadow, `${label} box shadow`).toBe('none');
}

async function catalog(page: Page) {
  await page.goto('/style-guide');
  await expect(page.getByTestId('sg-inputs')).toBeVisible();
  await page.mouse.move(1, 1);
  return {
    regular: page.getByTestId('sg-input-regular'),
    label: page.getByTestId('sg-input-label'),
    large: page.getByTestId('sg-input-large'),
    error: page.getByTestId('sg-input-error'),
  };
}

/** A 3x3 with CAT across the top, every other cell lettered. */
function letteredGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  for (let row = 0; row < 3; row += 1) {
    for (let col = 0; col < 3; col += 1) {
      grid = withLetter(grid, { col, row }, 'CATAAAAAA'[row * 3 + col]);
    }
  }
  return grid;
}

// --- F5-1: the catalog ---
test.describe('F5-1 catalog', () => {
  test('the sg-inputs section shows regular, labelled, large and error text inputs', async ({ page }) => {
    const c = await catalog(page);
    for (const [name, input] of Object.entries(c)) {
      await expect(input, name).toBeVisible();
      await expect(input, name).toHaveAttribute('type', 'text');
      await expect(page.getByTestId('sg-inputs').locator(`[data-testid="sg-input-${name}"]`), name).toHaveCount(1);
    }
    await expect(c.regular).toHaveAttribute('placeholder', /\S/);
    await expect(c.large).toHaveAttribute('placeholder', /\S/);
    await expect(page.getByTestId('sg-input-label-label')).toHaveText(/\S/);
    await expect(page.getByTestId('sg-input-error-error')).toHaveText(/\S/);
  });

  test('no horizontal overflow at 1280px or 375px', async ({ page }) => {
    for (const width of [1280, 375]) {
      await page.setViewportSize({ width, height: 800 });
      await catalog(page);
      const overflow = await page.evaluate(
        () => document.documentElement.scrollWidth - document.documentElement.clientWidth
      );
      expect(overflow, `overflow at ${width}px`).toBeLessThanOrEqual(0);
    }
  });
});

// --- F5-2: the underline ---
test.describe('F5-2 underline', () => {
  test('every field rests with a 1px line-muted underline and nothing else', async ({ page }) => {
    const c = await catalog(page);
    await expectUnderline(page, c.regular, 'line-muted', 'regular');
    await expectUnderline(page, c.label, 'line-muted', 'labelled');
    await expectUnderline(page, c.large, 'line-muted', 'large');
  });

  test('hover leaves it unchanged; focus by click or Tab turns it line-highlight with no ring; blur restores', async ({ page }) => {
    const c = await catalog(page);
    const rest = await styleOf(c.regular);

    await c.regular.hover();
    expect(await styleOf(c.regular), 'hover').toEqual(rest);
    await page.mouse.move(1, 1);

    await c.regular.click();
    await expect(c.regular).toBeFocused();
    await expectUnderline(page, c.regular, 'line-highlight', 'clicked');

    await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
    expect(await styleOf(c.regular), 'blurred').toEqual(rest);

    await c.large.focus();
    await page.keyboard.press('Shift+Tab');
    await page.keyboard.press('Tab');
    await expect(c.large).toBeFocused();
    await expectUnderline(page, c.large, 'line-highlight', 'tabbed');
  });

  test('a disabled field is dimmed and not-allowed', async ({ page }) => {
    const c = await catalog(page);
    await c.regular.evaluate((el) => ((el as HTMLInputElement).disabled = true));
    const s = await c.regular.evaluate((el) => {
      const cs = getComputedStyle(el);
      return { opacity: Number(cs.opacity), cursor: cs.cursor };
    });
    expect(s.opacity).toBeLessThan(1);
    expect(s.cursor).toBe('not-allowed');
  });
});

// --- F5-3: sizes and text ---
test.describe('F5-3 sizes and text', () => {
  test('regular is body-normal and large is body-large, both Inter in primary, large taller', async ({ page }) => {
    const c = await catalog(page);
    await expectTextStyle(page, c.regular, 'body-normal', 14, 400, 'regular');
    await expectTextStyle(page, c.large, 'body-large', 18, 400, 'large');
    expectColor((await styleOf(c.regular)).color, await token(page, 'primary'), 'regular text');
    expectColor((await styleOf(c.large)).color, await token(page, 'primary'), 'large text');
    expect((await box(c.large)).height).toBeGreaterThan((await box(c.regular)).height);
  });

  test('placeholders are muted', async ({ page }) => {
    const c = await catalog(page);
    expectColor((await styleOf(c.regular)).placeholderColor, await token(page, 'muted'), 'regular placeholder');
    expectColor((await styleOf(c.large)).placeholderColor, await token(page, 'muted'), 'large placeholder');
  });

  test('text starts a little inside the line, never at or far from its edge', async ({ page }) => {
    const c = await catalog(page);
    for (const [name, input] of [['regular', c.regular], ['large', c.large]] as const) {
      const { paddingLeft } = await styleOf(input);
      expect(paddingLeft, `${name} inset`).toBeGreaterThanOrEqual(2);
      expect(paddingLeft, `${name} inset`).toBeLessThanOrEqual(8);
    }
  });
});

// --- F5-4: the label ---
test.describe('F5-4 label', () => {
  test('the label sits above the field, left-aligned with the line, in title-4 primary', async ({ page }) => {
    const c = await catalog(page);
    const label = page.getByTestId('sg-input-label-label');
    await expectTextStyle(page, label, 'title-4', 14, 600, 'label');
    expectColor((await styleOf(label)).color, await token(page, 'primary'), 'label');

    const labelBox = await box(label);
    const inputBox = await box(c.label);
    expect(labelBox.y + labelBox.height, 'label above').toBeLessThanOrEqual(inputBox.y + 0.5);
    expect(Math.abs(labelBox.x - inputBox.x), 'label left-aligned').toBeLessThanOrEqual(1);
  });

  test('the label names the field and focuses it on click, and does not change on focus', async ({ page }) => {
    const c = await catalog(page);
    const label = page.getByTestId('sg-input-label-label');
    const text = (await label.innerText()).trim();
    await expect(page.getByRole('textbox', { name: text, exact: true })).toHaveAttribute(
      'data-testid',
      'sg-input-label'
    );

    const before = await styleOf(label);
    await label.click();
    await expect(c.label).toBeFocused();
    expect(await styleOf(label), 'label on focus').toEqual(before);
  });
});

// --- F5-5: the error ---
test.describe('F5-5 error', () => {
  test('the error field has an error underline, also when focused, and a body-normal error message below', async ({ page }) => {
    const c = await catalog(page);
    await expectUnderline(page, c.error, 'error', 'error rest');
    await c.error.click();
    await expectUnderline(page, c.error, 'error', 'error focused');

    const message = page.getByTestId('sg-input-error-error');
    await expectTextStyle(page, message, 'body-normal', 14, 400, 'message');
    expectColor((await styleOf(message)).color, await token(page, 'error'), 'message');
    const inputBox = await box(c.error);
    const messageBox = await box(message);
    expect(messageBox.y, 'message below the line').toBeGreaterThanOrEqual(inputBox.y + inputBox.height - 0.5);
    expect(Math.abs(messageBox.x - inputBox.x), 'message left-aligned').toBeLessThanOrEqual(1);
  });

  test('the error is wired for assistive tech, and fields without one carry none', async ({ page }) => {
    const c = await catalog(page);
    await expect(c.error).toHaveAttribute('aria-invalid', 'true');
    const describedBy = await c.error.getAttribute('aria-describedby');
    expect(describedBy).toBeTruthy();
    await expect(page.getByTestId('sg-input-error-error')).toHaveAttribute('id', describedBy!);

    for (const [name, input] of [['regular', c.regular], ['label', c.label], ['large', c.large]] as const) {
      await expect(input, name).not.toHaveAttribute('aria-invalid', 'true');
      await expect(page.getByTestId(`sg-input-${name}-error`), name).toHaveCount(0);
    }
  });
});

// --- F5-6: call sites ---
test.describe('F5-6 call sites', () => {
  test.describe('signed out', () => {
    test.use({ storageState: { cookies: [], origins: [] } });

    test('the sign-in email is a large field with a placeholder', async ({ page }) => {
      await openSignedOutFrontDoor(page);
      const email = page.getByTestId('sign-in-email');
      await expectTextStyle(page, email, 'body-large', 18, 400, 'sign-in email');
      await expectUnderline(page, email, 'line-muted', 'sign-in email');
      await expect(email).toHaveAttribute('placeholder', /\S/);
    });

    test('the builder-name field carries its name as a title-4 label above it', async ({ page }) => {
      await signInDisplayNameUser(page);
      await page.goto('/puzzles');
      await waitForNewPuzzleReady(page);
      await page.getByTestId('new-puzzle-button').click();
      const input = page.getByTestId('display-name-input');
      const label = page.getByTestId('display-name-input-label');
      await expect(label).toHaveText('Builder name');
      await expectTextStyle(page, label, 'title-4', 14, 600, 'builder-name label');
      expect((await box(label)).y).toBeLessThan((await box(input)).y);
      await expect(page.getByRole('textbox', { name: 'Builder name', exact: true })).toBeFocused();
      await expectTextStyle(page, input, 'body-normal', 14, 400, 'builder-name field');
      await expectUnderline(page, input, 'line-highlight', 'builder-name focused');
    });
  });

  test('the new-puzzle name carries its name as a title-4 label above a regular field', async ({ page }) => {
    await page.goto('/puzzles');
    await waitForNewPuzzleReady(page);
    await page.getByTestId('new-puzzle-button').click();
    const input = page.getByTestId('new-puzzle-name');
    const label = page.getByTestId('new-puzzle-name-label');
    await expect(label).toHaveText('Puzzle name');
    await expectTextStyle(page, label, 'title-4', 14, 600, 'new-puzzle label');
    expect((await box(label)).y).toBeLessThan((await box(input)).y);
    await expect(page.getByRole('textbox', { name: 'Puzzle name', exact: true })).toBeFocused();
    await expectTextStyle(page, input, 'body-normal', 14, 400, 'new-puzzle field');
    await expectUnderline(page, input, 'line-highlight', 'new-puzzle focused');
  });

  test('hint inputs are regular underlined fields that turn line-highlight on focus', async ({ page }) => {
    const { id } = await seedPuzzle({ grid: letteredGrid(), hints: {}, phase: 'hints' });
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await page.mouse.move(1, 1);
    const input = page.getByTestId('hint-input').first();
    await expectTextStyle(page, input, 'body-normal', 14, 400, 'hint');
    await expectUnderline(page, input, 'line-muted', 'hint rest');
    await input.click();
    await expectUnderline(page, input, 'line-highlight', 'hint focused');
  });
});

// --- F5-7: token-driven ---
test.describe('F5-7 token-driven', () => {
  test('live edits of the palette repaint the underline, and restore', async ({ page }) => {
    const c = await catalog(page);
    const sentinel = parseColor('rgb(18, 52, 86)');
    const set = (name: string, value: string | null) =>
      page.evaluate(
        ([n, v]) =>
          v === null
            ? document.documentElement.style.removeProperty(n!)
            : document.documentElement.style.setProperty(n!, v),
        [name, value] as const
      );

    await set('--palette-gray-200', SENTINEL);
    expectColor((await styleOf(c.regular)).borderColors[2], sentinel, 'rest edited');
    await set('--palette-gray-200', null);
    await expectUnderline(page, c.regular, 'line-muted', 'rest restored');

    await c.regular.click();
    await set('--palette-blue-bright', SENTINEL);
    expectColor((await styleOf(c.regular)).borderColors[2], sentinel, 'focus edited');
    await set('--palette-blue-bright', null);
    await expectUnderline(page, c.regular, 'line-highlight', 'focus restored');
  });
});
