import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { clearLetters, createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { currentBuilderId } from './helpers/ownership';
import { playPuzzleFixture, seedPlayPuzzle, seedPlaySession } from './helpers/play-route';

// Story 17-S2 — Play opens on the first empty cell.
//
// Once a play session is ready and the puzzle isn't complete, the cursor
// is on the first empty cell of the player's entries in reading order
// (left to right, top to bottom), Across, or Down where that cell has no
// Across word. A full but unsolved grid opens on its first white cell.
// The grid has focus, so the word is highlighted, the Prominent Hint (wide)
// or the hint bar (narrow) shows its hint, and typing works at once.
// Opening doesn't scroll the page. The opening cursor is an ordinary
// cursor: clicking its cell toggles the direction. A completed puzzle
// opens with nothing selected, as before.
//
// The Prominent Hint's text is title-3 primary (was body-large), on the
// label's baseline, in a bar still 52px tall.
//
// Do not edit this file to match an implementation.

// The fixture (helpers/play-route): a 3×3, CAT / A#A / TEN, off cell (1,1).
// 1-across (0,0)–(2,0) "Feline", 3-across (0,2)–(2,2) "Twice five",
// 1-down (0,0)–(0,2) "A pet that purrs", 2-down (2,0)–(2,2) "A shade of brown".
// (0,1) and (2,1) are in no Across word.

const WIDE = { width: 1440, height: 1000 };
const PRIMARY = 'rgb(0, 0, 0)';

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const region = (page: Page) => page.getByTestId('play-grid-region');
const bar = (page: Page) => page.getByTestId('prominent-hint');
const hintBarText = (page: Page) => page.getByTestId('play-hint-bar-text');

async function seed(page: Page, entries?: Grid) {
  const builderId = await currentBuilderId(page);
  const puzzle = playPuzzleFixture();
  const fixture = await seedPlayPuzzle({ builderId, puzzle });
  if (entries) await seedPlaySession(builderId, fixture.id, entries);
  return fixture;
}

async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

/** Exactly `cursor` is selected and exactly `word` (with it) highlighted. */
async function expectWord(page: Page, cursor: string, word: string[]) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(1);
  await expect(cell(page, cursor)).toHaveAttribute('data-selected', 'true');
  const others = word.filter((coord) => coord !== cursor);
  await expect(page.locator('[data-highlight="slot"]')).toHaveCount(others.length);
  for (const coord of others) await expect(cell(page, coord)).toHaveAttribute('data-highlight', 'slot');
}

function letters(rows: string[]): Grid {
  let grid = clearLetters(playPuzzleFixture().grid);
  for (const [row, line] of rows.entries()) {
    for (const [col, letter] of [...line].entries()) {
      if (letter !== '#' && letter !== '.') grid = withLetter(grid, { col, row }, letter);
    }
  }
  return grid;
}

const style = (locator: Locator, property: string) =>
  locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);

function tokenPx(page: Page, name: string) {
  return page.evaluate((token) => {
    const probe = document.createElement('div');
    // Out of the body's flow, which a taller page would shrink it in (17-S7).
    probe.style.position = 'absolute';
    probe.style.height = `var(${token})`;
    document.body.append(probe);
    const px = getComputedStyle(probe).height;
    probe.remove();
    return px;
  }, name);
}

/** The y of an element's first text baseline, read with a zero-size probe. */
function baseline(locator: Locator) {
  return locator.evaluate((el) => {
    const probe = document.createElement('span');
    probe.style.cssText = 'display:inline-block;width:0;height:0;vertical-align:baseline';
    el.prepend(probe);
    const y = probe.getBoundingClientRect().top;
    probe.remove();
    return y;
  });
}

test.describe('17-S2-1 play opens on the first empty cell', () => {
  test.use({ viewport: WIDE });

  test('a new session: (0,0) Across, the grid focused, the Prominent Hint showing, typing at once', async ({ page }) => {
    const fixture = await seed(page);
    await open(page, fixture.id);
    await expectWord(page, '0,0', ['0,0', '1,0', '2,0']);
    await expect(region(page)).toBeFocused();
    await expect(bar(page)).toHaveText(/^1A\s*Feline$/);
    await page.keyboard.type('c');
    await expect(cell(page, '0,0')).toContainText('C');
    await expectWord(page, '1,0', ['0,0', '1,0', '2,0']);
  });

  test('a saved session opens on its first empty cell in reading order, and so does a reload', async ({ page }) => {
    const fixture = await seed(page, letters(['C..', '.#.', '...']));
    await open(page, fixture.id);
    await expectWord(page, '1,0', ['0,0', '1,0', '2,0']);
    await expect(bar(page)).toHaveText(/^1A\s*Feline$/);
    await page.keyboard.type('at');
    await expect(cell(page, '2,0')).toContainText('T');
    await expect(page.getByTestId('play-save-status')).toHaveAttribute('data-save-state', 'saved');
    await page.reload();
    await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
    // Row 0 is full; (0,1) is the first empty cell, and it has no Across word.
    await expectWord(page, '0,1', ['0,0', '0,1', '0,2']);
    await expect(region(page)).toBeFocused();
    await expect(bar(page)).toHaveText(/^1D\s*A pet that purrs$/);
  });

  test('a cell with no Across word opens Down', async ({ page }) => {
    const fixture = await seed(page, letters(['CAT', 'A#.', 'TEN']));
    await open(page, fixture.id);
    await expectWord(page, '2,1', ['2,0', '2,1', '2,2']);
    await expect(bar(page)).toHaveText(/^2D\s*A shade of brown$/);
  });

  test('a full but unsolved grid opens on its first white cell', async ({ page }) => {
    const fixture = await seed(page, letters(['XXX', 'X#X', 'XXX']));
    await open(page, fixture.id);
    await expectWord(page, '0,0', ['0,0', '1,0', '2,0']);
    await expect(region(page)).toBeFocused();
    await expect(bar(page)).toHaveText(/^1A\s*Feline$/);
  });

  test('clicking the opening cell toggles to Down, as any cursor cell', async ({ page }) => {
    const fixture = await seed(page);
    await open(page, fixture.id);
    await expectWord(page, '0,0', ['0,0', '1,0', '2,0']);
    await cell(page, '0,0').click();
    await expectWord(page, '0,0', ['0,0', '0,1', '0,2']);
    await expect(bar(page)).toHaveText(/^1D\s*A pet that purrs$/);
  });

  test('a completed puzzle opens with nothing selected (guard)', async ({ page }) => {
    const fixture = await seed(page, playPuzzleFixture().grid);
    await open(page, fixture.id);
    await expect(page.getByTestId('play-lock-message')).toBeVisible();
    await expect(page.locator('[data-selected="true"], [data-highlight="slot"]')).toHaveCount(0);
    await expect(region(page)).not.toBeFocused();
    await expect(bar(page)).toHaveText('');
  });

  test.describe('on a short window', () => {
    test.use({ viewport: { width: 1440, height: 600 } });

    test('opening leaves the page at the top', async ({ page }) => {
      const builderId = await currentBuilderId(page);
      const fixture = await seedPlayPuzzle({
        builderId,
        puzzle: { grid: createGrid({ cols: 15, rows: 15 }), phase: 'hints', hints: { '1-across': 'A hint' } },
      });
      await open(page, fixture.id);
      await expect(cell(page, '0,0')).toHaveAttribute('data-selected', 'true');
      await expect(region(page)).toBeFocused();
      expect(await page.evaluate(() => document.documentElement.scrollHeight > window.innerHeight), 'the page scrolls')
        .toBe(true);
      expect(await page.evaluate(() => window.scrollY), 'after opening').toBe(0);
    });
  });

  test.describe('narrow', () => {
    test.use({ viewport: { width: 768, height: 900 } });

    test('the hint bar shows the opening word’s hint, and typing works at once', async ({ page }) => {
      const fixture = await seed(page);
      await open(page, fixture.id);
      await expect(hintBarText(page)).toHaveText('Feline');
      await expect(region(page)).toBeFocused();
      await page.keyboard.type('c');
      await expect(cell(page, '0,0')).toContainText('C');
    });
  });
});

test.describe('17-S2-2 the Prominent Hint’s text', () => {
  test.use({ viewport: WIDE });

  test('title-3 primary, on the label’s baseline, in a 52px bar', async ({ page }) => {
    const fixture = await seed(page);
    await open(page, fixture.id);
    const text = bar(page).getByTestId('prominent-hint-text');
    const label = bar(page).getByTestId('prominent-hint-label');
    await expect(text).toHaveText('Feline');
    expect(await style(text, 'font-size'), 'title-3 size').toBe(await tokenPx(page, '--text-title-3'));
    expect(await style(text, 'line-height'), 'title-3 line height')
      .toBe(await tokenPx(page, '--text-title-3--line-height'));
    expect(await style(text, 'font-weight'), 'title-3 weight').toBe('600');
    expect(await style(text, 'color'), 'primary').toBe(PRIMARY);
    expect(await baseline(text), 'one baseline').toBeCloseTo(await baseline(label), 0);
    expect((await bar(page).boundingBox())!.height, 'height').toBeCloseTo(52, 0);
  });
});
