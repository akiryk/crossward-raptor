// Story 18-S3 — Status icons and green play rows.
//
// A library row's icon follows the puzzle's status: Play for a published
// puzzle (public or unlisted, whoever built it), Build for an unpublished
// grid-phase puzzle, Hint for an unpublished hints-phase one. Each icon is
// the human's 46×34 export, cleaned and centered: a 34px outlined 3×3 grid
// (its 34px square at x 6) under a 42×12 label band (at x 2, y 11) with the
// label in white. Build draws in gray-500 (#8B909A); Hint's grid in gray-700
// (#14151B) under a black band; Play in the new `green` (#84C600) through
// the `status-play` style. The icon is aria-hidden, its grid where the old
// 34px icon was (10px in) and the title where it was (56px in).
//
// The row's link carries visually hidden text naming the status ("Ready to
// play", "Build phase", "Hint phase") after the title, so the link reads
// "<title> <status>", then any play marker. The `[grid]`, `[hint]` and
// `[published]` markers are gone; play rows keep `[in-play]` (and kept
// `[complete]` until 18-S5, below).
//
// A row with the Play icon is `puzzle-row-play` (#F0F5E5), turning
// `puzzle-row-play-hover` (#EAF0DB) on hover and while its link has keyboard
// focus; other rows keep `puzzle-row` (#F5F7FA) and `puzzle-row-hover`
// (#EBEFF7). 18-S3 was written within the Build | Play views. 18-S4
// replaced the views with one list (e2e/library-filters.spec.ts), so these
// cases no longer choose a view.
//
// 18-S5 gave a published puzzle the caller has completed a fourth icon,
// DONE, named "Complete" in the hidden text, and removed `[complete]`
// (e2e/done-icon.spec.ts); its row stays green. So the Play cases here use
// published puzzles still to finish.
//
// Colors are the human's values written out, not read from the styles.
// Measured at 1280×800. Do not edit this file to match an implementation.

