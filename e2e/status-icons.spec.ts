/** The icon's pixels as RGB, decoded in the page from Playwright's screenshot of its 46×34 box. */
async function iconPixels(page: Page, icon: Locator) {
  const png = (await icon.screenshot()).toString('base64');
  const data = await page.evaluate(async (base64) => {
    const image = new Image();
    image.src = `data:image/png;base64,${base64}`;
    await image.decode();
    const canvas = document.createElement('canvas');
    canvas.width = image.width;
    canvas.height = image.height;
    const context = canvas.getContext('2d')!;
    context.drawImage(image, 0, 0);
    const { data: rgba, width, height } = context.getImageData(0, 0, image.width, image.height);
    return { rgba: Array.from(rgba), width, height };
  }, png);
  const at = (x: number, y: number): Rgb => {
    const i = (y * data.width + x) * 4;
    return { r: data.rgba[i], g: data.rgba[i + 1], b: data.rgba[i + 2] };
  };
  return { at, width: data.width, height: data.height };
}

function expectPixel(actual: Rgb, expected: string, label: string) {
  const want = hex(expected);
  for (const channel of ['r', 'g', 'b'] as const) {
    expect(Math.abs(actual[channel] - want[channel]), `${label}: ${JSON.stringify(actual)} is ${expected}`).toBeLessThanOrEqual(2);
  }
}

/** Draws are checked at pixel centres well inside each region; (x, y) are relative to the 46×34 box. */
async function expectIcon(page: Page, item: Locator, status: Status, background: string) {
  const icon = item.getByTestId('puzzle-icon');
  await expect(icon).toHaveAttribute('aria-hidden', 'true');
  const { at, width, height } = await iconPixels(page, icon);
  expect({ width, height }, `${status} icon size`).toEqual({ width: 46, height: 34 });
  const { grid, band } = STATUS[status];

  // The grid: its 34px square at x 6, three 10px cells per row 1px apart inside a 1px outline.
  expectPixel(at(12, 6), WHITE, `${status} cell 0,0`);
  expectPixel(at(23, 6), grid, `${status} cell 1,0 dark`);
  expectPixel(at(34, 6), WHITE, `${status} cell 2,0`);
  expectPixel(at(12, 28), WHITE, `${status} cell 0,2`);
  expectPixel(at(23, 28), WHITE, `${status} cell 1,2`);
  expectPixel(at(34, 28), grid, `${status} cell 2,2 dark`);
  expectPixel(at(17, 28), grid, `${status} line between white cells`);
  expectPixel(at(23, 33), grid, `${status} bottom outline`);
  expectPixel(at(39, 9), grid, `${status} right outline`);
  expectPixel(at(6, 0), background, `${status} rounded corner`);
  expectPixel(at(7, 1), background, `${status} rounded corner`);
  expectPixel(at(39, 33), background, `${status} rounded corner`);

  // The band: 42×12 at x 2, y 11, across the grid's middle row, its label in white.
  expectPixel(at(3, 17), band, `${status} band's left end`);
  expectPixel(at(42, 17), band, `${status} band's right end`);
  expectPixel(at(1, 17), background, `${status} left of the band`);
  expectPixel(at(44, 17), background, `${status} right of the band`);
  expectPixel(at(3, 9), background, `${status} above the band, left of the grid`);
  expectPixel(at(3, 24), background, `${status} below the band, left of the grid`);
  let white = 0;
  let left = Infinity;
  let right = -Infinity;
  for (let y = 12; y <= 21; y++) {
    for (let x = 3; x <= 42; x++) {
      const p = at(x, y);
      if (p.r > 200 && p.g > 200 && p.b > 200) {
        white += 1;
        left = Math.min(left, x);
        right = Math.max(right, x);
      }
    }
  }
  expect(white, `${status} label drawn in white`).toBeGreaterThan(40);
  return { labelLeft: left, labelRight: right };
}

