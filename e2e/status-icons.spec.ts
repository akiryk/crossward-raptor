test.describe('18-S3-2 the icon follows the status', () => {
  // 18-S5: a completed puzzle draws DONE (e2e/done-icon.spec.ts), so only published rows still to finish draw Play.
  test('own rows draw Build, Hint and Play icons by phase and publication; every published row still to finish draws Play', async ({ page }) => {
    const me = await freshBuilder(page);
    const other = await seedOtherBuilder();
    const own = {
      grid: await seedOwn(me, 'grid'),
      hints: await seedOwn(me, 'hints'),
      unlisted: await seedOwn(me, 'private published', 'unlisted'),
      public: await seedOwn(me, 'public published', 'public'),
    };
    const foreignPublic = await seedPublished(other, me, 'none');
    const foreignUnlisted = await seedPublished(other, me, 'in-play', { visibility: 'private' });
    await openLibrary(page);

    const labels: Partial<Record<Status, number>> = {};
    for (const [fixture, status, background] of [
      [own.grid, 'build', ROW],
      [own.hints, 'hint', ROW],
      [own.unlisted, 'play', PLAY_ROW],
      [own.public, 'play', PLAY_ROW],
    ] as const) {
      const item = row(page, fixture.title);
      await page.mouse.move(0, 0);
      const { labelLeft, labelRight } = await expectIcon(page, item, status, background);
      labels[status] = labelRight - labelLeft;
    }
    // The three labels differ: BUILD is the widest, HINT the narrowest.
    expect(labels.build!, 'BUILD wider than PLAY').toBeGreaterThan(labels.play! + 1);
    expect(labels.play!, 'PLAY wider than HINT').toBeGreaterThan(labels.hint! + 1);

    for (const fixture of [own.unlisted, own.public, foreignPublic, foreignUnlisted]) {
      await page.mouse.move(0, 0);
      await expectIcon(page, row(page, fixture.title), 'play', PLAY_ROW);
    }
    await expect(page.getByTestId('puzzle-thumbnail')).toHaveCount(0);
  });

  test('the icon is 46×34, 4px in so its grid is 10px in, centered, and the title stays 56px in', async ({ page }) => {
    const me = await freshBuilder(page);
    const draft = await seedOwn(me, 'grid');
    const published = await seedOwn(me, 'public published');
    await openLibrary(page);

    for (const fixture of [draft, published]) {
      const item = row(page, fixture.title);
      const r = await box(item);
      const i = await box(item.getByTestId('puzzle-icon'));
      const t = await box(item.getByTestId('puzzle-list-title'));
      expect(i.width, 'icon width').toBeCloseTo(46, 0);
      expect(i.height, 'icon height').toBeCloseTo(34, 0);
      expect(i.x - r.x, 'icon inset').toBeCloseTo(4, 0);
      expect(i.y + i.height / 2, 'icon centered').toBeCloseTo(r.y + r.height / 2, 0);
      expect(t.x - r.x, 'title inset, 12px after the grid').toBeCloseTo(56, 0);
    }
  });

  test('each icon clips with its own id', async ({ page }) => {
    const me = await freshBuilder(page);
    await seedOwn(me, 'grid');
    await seedOwn(me, 'hints');
    await seedOwn(me, 'public published');
    await openLibrary(page);

    const clips = await page.getByTestId('puzzle-icon').evaluateAll((icons) =>
      icons.map((icon) => {
        const used = Array.from(icon.querySelectorAll('[clip-path]'), (el) =>
          (el.getAttribute('clip-path') ?? '').replace(/^url\(#(.*)\)$/, '$1'));
        const own = Array.from(icon.querySelectorAll('clipPath'), (el) => el.id);
        return { used, own };
      })
    );
    expect(clips.length).toBeGreaterThanOrEqual(3);
    const all = clips.flatMap(({ own }) => own);
    expect(new Set(all).size, 'clip ids are unique on the page').toBe(all.length);
    for (const { used, own } of clips) {
      expect(used.length, 'the icon clips its grid').toBeGreaterThan(0);
      for (const id of used) expect(own, `clip ${id} is the icon's own`).toContain(id);
    }
  });
});

