async function expectRowColors(page: Page, item: Locator, rest: string, hover: string, label: string) {
  const link = linkOf(item);
  const isColor = async (expected: string) => JSON.stringify(rgbOf(await bgOf(item))) === JSON.stringify(hex(expected));

  await item.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await expect.poll(() => isColor(rest), { message: `${label} at rest` }).toBe(true);
  const transition = await item.evaluate((el) => {
    const s = getComputedStyle(el);
    return { property: s.transitionProperty, duration: s.transitionDuration };
  });
  expect(transition.duration.split(',').map((d) => d.trim()), `${label} transition`).toContain('0.15s');
  expect(transition.property).toMatch(/\b(all|background-color)\b/);

  const date = await item.getByTestId('puzzle-list-updated').boundingBox();
  if (!date) throw new Error('no date box');
  await page.mouse.move(date.x + date.width / 2, date.y + date.height / 2);
  await expect.poll(() => isColor(hover), { message: `${label} on hover` }).toBe(true);
  await page.mouse.move(0, 0);
  await expect.poll(() => isColor(rest), { message: `${label} after hover` }).toBe(true);

  await link.evaluate((el) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled])'));
    all[all.indexOf(el as HTMLElement) - 1].focus();
  });
  await page.keyboard.press('Tab');
  await expect(link).toBeFocused();
  await expect.poll(() => isColor(hover), { message: `${label} on keyboard focus` }).toBe(true);
  await link.blur();
  await expect.poll(() => isColor(rest), { message: `${label} after keyboard focus` }).toBe(true);

  // Press on the title without releasing, then leave: the link has mouse focus only.
  const title = await item.getByTestId('puzzle-list-title').boundingBox();
  if (!title) throw new Error('no title box');
  await page.mouse.move(title.x + 4, title.y + title.height / 2);
  await page.mouse.down();
  await page.mouse.move(0, 0);
  expect(await link.evaluate((el) => el === document.activeElement), `${label}: link focused by the mouse`).toBe(true);
  await page.waitForTimeout(300);
  expect(await isColor(rest), `${label} on mouse focus`).toBe(true);
  await page.mouse.up();
}
