type Rgb = { r: number; g: number; b: number };
type Rgba = Rgb & { a: number };

const GREEN = '#84C600';
const GRAY_500 = '#8B909A';
const GRAY_700 = '#14151B';
const BLACK = '#000000';
const WHITE = '#FFFFFF';
const ROW = '#F5F7FA';
const ROW_HOVER = '#EBEFF7';
const PLAY_ROW = '#F0F5E5';
const PLAY_ROW_HOVER = '#EAF0DB';

type Status = 'build' | 'hint' | 'play';
// status -> the grid's color, the band's color, the hidden text
const STATUS: Record<Status, { grid: string; band: string; text: string }> = {
  build: { grid: GRAY_500, band: GRAY_500, text: 'Build phase' },
  hint: { grid: GRAY_700, band: BLACK, text: 'Hint phase' },
  play: { grid: GREEN, band: GREEN, text: 'Ready to play' },
};

function hex(value: string): Rgb {
  const n = parseInt(value.replace('#', ''), 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

/** The forms getComputedStyle reports for a colour: rgb(), rgba() and color(srgb ...). */
function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function rgbOf(color: Rgba): Rgb {
  return { r: color.r, g: color.g, b: color.b };
}

/** The colour a CSS value paints as a background on this page. */
async function resolve(page: Page, cssValue: string) {
  return parseColor(
    await page.evaluate((value) => {
      const probe = document.createElement('div');
      probe.style.backgroundColor = value;
      document.body.appendChild(probe);
      const resolved = getComputedStyle(probe).backgroundColor;
      probe.remove();
      return resolved;
    }, cssValue)
  );
}

async function bgOf(locator: Locator) {
  return parseColor(await locator.evaluate((el) => getComputedStyle(el).backgroundColor));
}

async function box(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { x: r.left + window.scrollX, y: r.top + window.scrollY, width: r.width, height: r.height };
  });
}

/** The page top of the first drawn text inside an element. */
async function textTop(locator: Locator) {
  return locator.evaluate((el) => {
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if (!(node.textContent ?? '').trim()) continue;
      const range = document.createRange();
      range.selectNodeContents(node);
      const rect = Array.from(range.getClientRects()).find((r) => r.width > 0);
      if (rect) return rect.top + window.scrollY;
    }
    throw new Error('no drawn text');
  });
}

