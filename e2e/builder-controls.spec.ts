/** The three buttons' visible labels, numbers and selected flags, in order. */
async function readSteps(page: Page) {
  return steps(page).locator('[data-step-id]').evaluateAll((buttons) =>
    buttons.map((button) => ({
      id: button.getAttribute('data-step-id'),
      tag: button.tagName,
      type: button.getAttribute('data-button-type'),
      number: button.querySelector('[data-button-number]')?.textContent?.trim() ?? null,
      label: (button.textContent ?? '').replace(button.querySelector('[data-button-number]')?.textContent ?? '', '').trim(),
      selected: button.getAttribute('aria-current') === 'true',
    }))
  );
}

function expected(first: 'Build the Grid', selected: 'build' | 'hints') {
  return [
    { id: 'build', tag: 'BUTTON', type: 'numbered', number: '1', label: first, selected: selected === 'build' },
    { id: 'hints', tag: 'BUTTON', type: 'numbered', number: '2', label: 'Create Hints', selected: selected === 'hints' },
    { id: 'publish', tag: 'BUTTON', type: 'numbered', number: '3', label: 'Publish', selected: false },
  ];
}

/** Closes the open dialog `dialog` in one of the four shared ways. */
async function dismiss(page: Page, dialog: Locator, how: 'footer' | 'close' | 'Escape' | 'backdrop', footerTestId: string) {
  if (how === 'footer') await dialog.getByTestId(footerTestId).click();
  else if (how === 'close') await dialog.getByTestId('modal-close').click();
  else if (how === 'Escape') await page.keyboard.press('Escape');
  else await page.getByTestId('modal-backdrop').click({ position: { x: 2, y: 2 } });
  await expect(dialog).toHaveCount(0);
}

/** Gives `target` keyboard focus: focus whatever precedes it, then press Tab. */
async function tabTo(page: Page, target: Locator) {
  await target.evaluate((el) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled])'));
    all[all.indexOf(el as HTMLElement) - 1].focus();
  });
  await page.keyboard.press('Tab');
  await expect(target).toBeFocused();
}

