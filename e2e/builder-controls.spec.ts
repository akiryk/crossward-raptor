// Story 14-S4 — Builder controls.
//
// Three F3 numbered buttons in `builder-steps` replace the stepper:
// "1 Build the Grid", "2 Create Hints" and "3 Publish", each with
// `data-step-id` build, hints or publish. One is selected
// (`aria-current="true"`): 1 in the build phase, 2 in the hints phase,
// never 3. Clicking the selected button does nothing. In the build phase 2
// opens the enter-hints dialog; in the hints phase 1 is disabled (14-S12:
// there is no EDIT GRID mode). 3 opens "Lol."
// then "Nope." for every later build-phase click until a reload, "Not
// quite!" while any required hint is blank, and otherwise the Publish
// dialog. Publishing is final: a published puzzle shows "Published" and a
// "Play it!" link instead of the buttons, with no Unpublish.
//
// The title sits at the top in `title-1`, 32px above the buttons. The
// buttons are 10px apart; the build phase's Preview toggle sits about 27px
// below them and the grid about 12px below it; in the hints phase the
// toggle's row holds Lock Grid Letters (14-S12), so the grid doesn't move.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

