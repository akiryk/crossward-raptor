import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S7 — the lock button's second starts over when the grid gets
// focus back.
//
// The button beside an unlocked word shows once the cursor has stayed in
// it for 1 second while the grid has focus (21-S2). Time spent without
// focus doesn't count: when the grid gets focus back, however long it was
// away, the button and its outline wait a full second again. A locked
// word's button and outline still show at once.
//
// Amended by 21-S16: the wait is 3 seconds (was 1); every wait timed
// against it is 2000ms longer. Where this file says "a second", read three.
//
// Amended by 22-S6: the wait is 2 seconds (was 3). 21-S7-1's "still
// waiting" checks are at 1500ms after focus returns (were 2500ms); the
// other waits are unchanged. Where this file says "a second", read two.
//
// Amended by 21-S17: 21-S7-2 moves the mouse off the grid after the click
// that locks TANGENT, which left it on TANGENT's ticked end cell.
//
// Do not edit this file to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

/** TANGENT across row 3 (3–9) on a daily. */
function lockGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  [...'TANGENT'].forEach((letter, i) => {
    grid = withLetter(grid, { col: 3 + i, row: 3 }, letter);
  });
  return grid;
}

async function open(page: Page) {
  const { id } = await seedPuzzle({ grid: lockGrid(), hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const outlines = (page: Page) => page.getByTestId('word-outline');
const gridRegion = (page: Page) => page.getByTestId('grid-region');

/** The cursor in TANGENT, its button shown after the second. */
async function inTangent(page: Page) {
  await cell(page, '6,3').click();
  await expect(cell(page, '6,3')).toHaveAttribute('data-selected', 'true');
  await expect(lockButton(page)).toBeVisible({ timeout: 4000 });
}

async function blurFor(page: Page, ms: number) {
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
  await expect(lockButton(page)).toBeHidden({ timeout: 300 });
  await page.waitForTimeout(ms);
}

test.describe('21-S7-1 back in an unlocked word', () => {
  test('after more than a second away, the button and outline wait a second again', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await blurFor(page, 3500);

    await gridRegion(page).focus();
    await expect(gridRegion(page)).toBeFocused();
    await expect(cell(page, '6,3')).toHaveAttribute('data-selected', 'true');
    await page.waitForTimeout(1500); // 22-S6: was 2500
    await expect(lockButton(page), 'still waiting 1.5 seconds after focus returns').toBeHidden();
    await expect(outlines(page)).toHaveCount(0);

    await expect(lockButton(page)).toBeVisible({ timeout: 1500 });
    await expect(lockButton(page)).toHaveAccessibleName('Lock word');
    await expect(outlines(page)).toHaveCount(1);
  });

  test('after a short time away, the same', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await blurFor(page, 200);

    await gridRegion(page).focus();
    await expect(gridRegion(page)).toBeFocused();
    await page.waitForTimeout(1500); // 22-S6: was 2500
    await expect(lockButton(page)).toBeHidden();
    await expect(lockButton(page)).toBeVisible({ timeout: 1500 });
  });
});

test.describe('21-S7-2 back in a locked word', () => {
  test('the button and outline show at once', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
    // 21-S17: off the grid, so the mouse isn't left on TANGENT's new tick,
    // whose hover would show the button at once.
    await page.mouse.move(0, 0);
    await blurFor(page, 3500);
    await expect(outlines(page), 'a locked word keeps its outline').toHaveCount(1);

    await gridRegion(page).focus();
    await expect(lockButton(page)).toBeVisible({ timeout: 300 });
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
  });
});
