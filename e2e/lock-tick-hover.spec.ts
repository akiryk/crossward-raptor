// Story 21-S11 — hovering a tick mark darkens its locked words.
//
// In the build phase with Preview off, a locked word's end cells carry a
// tick in their top-right corner (21-S2). Resting the mouse on a tick
// darkens every cell of each locked word ending at that cell by 15%, all
// of them where words share it, at once, and only while the mouse is on
// its end cell (amended by 21-S13: was on the tick). The tick's hover
// area is its whole end cell (amended by 21-S13: was its square, a
// quarter of the cell each way in the cell's top-right corner). "15%
// darker" is the cell's
// whole paint at 85% in each sRGB channel, as a 15%-black layer over it
// gives, whatever color it had (white, the cursor's yellow, blue-medium).
// The end cells (the hovered one included), the outline, the ticks and any
// lock button keep their colors. It changes no state: the cursor, the
// highlight and the saved puzzle are as they were, and a click on the
// tick is a click on its cell. 21-S13 adds a lock button after a second
// on a ticked end cell, for one of its words, which stays on that word's
// cells (amended by 21-S13: for 21-S10 the tick was part of its end cell,
// and moving onto it left a hovered word). Where a lock button covers
// part of the cell, the button wins (amended by 21-S12: was a down
// word's button covering part of the square). The darkening
// follows the tick: unlocking the word under the resting mouse ends it.
// It works whether or not the grid has focus, and below the grid's full
// width (21-S5) too. Mouse only; nothing with Preview on. Only the cell
// boxes darken; the grid lines keep their color (not measured here).
//
// Hooks: 21-S2's "Lock word" / "Unlock word" button, its outline
// [data-testid="word-outline"] and tick [data-testid="lock-tick"]; the
// toggle row's Lock Word [data-testid="lock-word-control"] (21-S5). The
// darkening is measured in the grid's own pixels, from a screenshot, at a
// spot in each cell's lower left away from its letter, number, the tick and
// the lock button.
//
// Amended by 21-S15: a tick hover no longer darkens its words; it outlines
// each in black, around its letters (not its end cells), and every cell
// keeps its paint. Where this file says "darker" or "the darkening", read
// "outlined" or "the outline"; expectPaint and expectPaintNow check it.
// Amended by 21-S14: with the cursor in no word its line's lettered cells
// are white, and outside the cursor's word an off cell is gray-200 (were
// dull blue). Amended by 21-S16: the button's wait is 3 seconds (was 1);
// LONG_MS is 3500ms and the cursor's button is awaited 4000ms.
//
// Timing: "at once" is within 500ms (a screenshot is taken each try).
//
// Amended by 21-S17: the tick hover's black outline is 2px (was 1px),
// its outer edge where the 1px line was. 21-S13's button now shows at
// once on the tick.
//
// Do not edit this file to match an implementation.

