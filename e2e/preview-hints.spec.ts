// Story 17-S9 — Preview Hints (as corrected 2026-11-01).
//
// In the hints phase a "Preview Hints" toggle (`preview-hints-toggle`,
// F6's toggle) shows the builder what the hints look like to a player.
// It's wide only (a 1140px window and up), on its own `toggle-row` panel
// (`preview-hints-row`) over the hints list: the toggle row's line and
// height, from the hints list's left edge (the Across column's) to its
// right edge, 10px corners, the toggle 16px in. Narrow, there is none.
//
// On, only the hints list changes: it is play's Player Hints with every
// hint in full, read-only, with no hint marked in play's blue, and a
// Player Hint click changes nothing. The grid is the editor's, letters
// and all, fully editable, and Lock Grid Letters works as always. There
// is no Prominent Hint. "Not quite!" turns Preview Hints off, so its
// marks show. Off, the hints list is the editor's again. It isn't saved,
// and a published puzzle and the build phase have none.
//
// Do not edit this file to match an implementation.

type Rgb = { r: number; g: number; b: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

async function background(locator: Locator) {
  return parseColor(await locator.evaluate((el) => getComputedStyle(el).backgroundColor));
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

/** A 3×3 word square, CAT / ARE / TEA. */
function wordSquare(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  ['CAT', 'ARE', 'TEA'].forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

// Long enough to wrap several times in a Player Hint, so a cut-off or
// one-line hint fails.
const LONG_HINT =
  'A small domesticated carnivorous mammal with soft fur, a short snout and retractable claws, '
  + 'widely kept as a pet or for catching mice, and the subject of a great many internet videos';

function hintsFor(grid: Grid, options: { missing?: string } = {}): Record<string, string> {
  const { across, down } = requiredHints(grid);
  const hints = Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
  hints['1-across'] = LONG_HINT;
  if (options.missing) delete hints[options.missing];
  return hints;
}

let titleCounter = 0;
async function seed(phase: Phase, options: { missing?: string; published?: boolean } = {}) {
  const grid = wordSquare();
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid, hints: phase === 'hints' ? hintsFor(grid, options) : {}, phase },
    `S9 ${phase} ${Date.now()}-${titleCounter}`
  );
  if (options.published) {
    const client = ownershipTestClient();
    try {
      await client.puzzle.update({
        where: { id },
        data: { publishedAt: new Date('2026-10-01T00:00:00Z'), visibility: 'public' },
      });
    } finally {
      await client.$disconnect();
    }
  }
  return id;
}

async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const visible = (locator: Locator) => locator.filter({ visible: true });
const previewToggle = (page: Page) => visible(page.getByTestId('preview-hints-toggle'));
const previewRow = (page: Page) => page.getByTestId('preview-hints-row');
const toggleRow = (page: Page) => page.getByTestId('toggle-row');
const lockToggle = (page: Page) => page.getByTestId('lock-letters-toggle');
const grid = (page: Page) => page.getByTestId('puzzle-grid');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);

async function turnOn(page: Page) {
  await previewToggle(page).click();
  await expect(previewToggle(page).locator('input')).toBeChecked();
}

/** Each cell's letters, without its number, in reading order. */
async function letters(page: Page) {
  return grid(page).getByTestId('grid-cell').evaluateAll((cells) =>
    cells.map((c) => {
      const clone = c.cloneNode(true) as HTMLElement;
      clone.querySelectorAll('[data-testid="cell-number"]').forEach((n) => n.remove());
      return (clone.textContent ?? '').trim();
    })
  );
}

const SQUARE = ['C', 'A', 'T', 'A', 'R', 'E', 'T', 'E', 'A'];

test.describe('17-S9-1 the toggle', () => {
  test.use({ viewport: { width: 1280, height: 900 } });

  test('wide: its own toggle-row panel over the hints list, on the toggle row’s line', async ({ page }) => {
    await open(page, await seed('hints'));
    await expect(previewToggle(page)).toHaveCount(1);
    await expect(previewToggle(page)).toContainText('Preview Hints');
    await expect(previewToggle(page).locator('input')).not.toBeChecked();
    await expect(previewRow(page).getByTestId('preview-hints-toggle')).toBeVisible();

    const row = await box(previewRow(page));
    const gridRow = await box(toggleRow(page));
    const list = await box(page.getByTestId('hints-region'));
    const across = await box(page.locator('[data-testid="hint-column"][data-orientation="across"]'));
    const pill = await box(previewToggle(page).locator('[data-toggle-pill]'));

    expectNear(row.top, gridRow.top, 0.5, 'same line as the toggle row');
    expectNear(row.height, 48, 0.5, 'panel height');
    expectNear(row.left, across.left, 1, 'panel left = the Across column’s left');
    expectNear(row.left, list.left, 1, 'panel left = the hints list’s left');
    expectNear(row.right, list.right, 1, 'panel right = the hints list’s right');
    expectNear(pill.left - row.left, 16, 1, 'toggle inset');
    expectNear((pill.top + pill.bottom) / 2, (row.top + row.bottom) / 2, 1, 'toggle centred');

    expect(await background(previewRow(page)), 'toggle-row fill').toEqual(await token(page, 'toggle-row'));
    const radii = await previewRow(page).evaluate((el) => {
      const c = getComputedStyle(el);
      return [c.borderTopLeftRadius, c.borderTopRightRadius, c.borderBottomRightRadius, c.borderBottomLeftRadius];
    });
    expect(radii, '10px corners').toEqual(['10px', '10px', '10px', '10px']);
  });

  test('the build phase and a published puzzle have none', async ({ page }) => {
    await open(page, await seed('grid'));
    await expect(previewToggle(page)).toHaveCount(0);
    await expect(page.getByText('Preview Hints')).toHaveCount(0);

    await open(page, await seed('hints', { published: true }));
    await expect(previewToggle(page)).toHaveCount(0);
    await expect(page.getByText('Preview Hints')).toHaveCount(0);
  });

  test('it isn’t saved: a reload is back to editing', async ({ page }) => {
    await open(page, await seed('hints'));
    await turnOn(page);
    await page.reload();
    await waitForEditorReady(page);
    await expect(previewToggle(page).locator('input')).not.toBeChecked();
    await expect(page.getByTestId('hint-input')).toHaveCount(6);
  });
});

test.describe('17-S9-2 only the hints list changes', () => {
  test.use({ viewport: { width: 1280, height: 900 } });

  test('on: Player Hints in full; the grid as when editing, no Prominent Hint; off: editing as before', async ({ page }) => {
    await open(page, await seed('hints'));
    const before = await box(grid(page));
    await turnOn(page);

    // The grid: the editor's, its letters kept, not moved; no Prominent Hint.
    await expect(grid(page)).not.toHaveAttribute('data-grid-mode', 'play');
    expect(await letters(page)).toEqual(SQUARE);
    await expect(grid(page).getByTestId('cell-number')).toHaveText(['1', '2', '3', '4', '5']);
    await expect(page.getByTestId('prominent-hint')).toHaveCount(0);
    const after = await box(grid(page));
    expectNear(after.top, before.top, 0.5, 'the grid doesn’t move');
    expectNear(after.left, before.left, 0.5, 'the grid doesn’t move');

    // The hints: play's Player Hints, read-only, nothing of the editor's.
    await expect(page.getByTestId('hint-input')).toHaveCount(0);
    await expect(page.getByTestId('hint-answer')).toHaveCount(0);
    const hints = page.getByTestId('hints-region');
    await expect(hints.locator('textarea, input')).toHaveCount(0);
    await expect(hints.getByTestId('play-clue-column')).toHaveCount(2);
    await expect(hints.getByTestId('play-clue')).toHaveCount(6);
    await expect(hints.locator('[data-clue-key="2-down"] [data-testid="play-clue-text"]')).toHaveText('Hint 2-down');

    // The long hint in full: every word there, wrapped, nothing clipped.
    const long = hints.locator('[data-clue-key="1-across"] [data-testid="play-clue-text"]');
    await expect(long).toHaveText(LONG_HINT);
    const fit = await long.evaluate((el) => {
      const c = getComputedStyle(el);
      return {
        clipped: el.scrollWidth > el.clientWidth + 0.5 || el.scrollHeight > el.clientHeight + 0.5,
        ellipsis: c.textOverflow,
        clamp: c.webkitLineClamp,
        lines: el.getBoundingClientRect().height / parseFloat(c.lineHeight),
      };
    });
    expect(fit.clipped, 'not clipped').toBe(false);
    expect(fit.ellipsis).not.toBe('ellipsis');
    expect(['none', '', 'auto']).toContain(fit.clamp);
    expect(fit.lines, 'wrapped').toBeGreaterThan(1.5);

    // Off: editing, letters and inputs as before.
    await previewToggle(page).click();
    expect(await letters(page)).toEqual(SQUARE);
    await expect(page.getByTestId('hint-input')).toHaveCount(6);
    await expect(page.getByTestId('play-clue')).toHaveCount(0);
    await expect(page.locator('[data-hint-key="1-across"] [data-testid="hint-input"]')).toHaveValue(LONG_HINT);
  });
});

test.describe('17-S9-3 the grid stays editable; the Player Hints show no selection', () => {
  test.use({ viewport: { width: 1280, height: 900 } });

  test('a letter typed while it’s on shows and is saved', async ({ page }) => {
    const id = await seed('hints');
    await open(page, id);
    await turnOn(page);
    await cell(page, '1,1').click();
    await page.keyboard.type('X');
    expect((await letters(page))[4]).toBe('X');
    // Past the 500ms autosave, a reload has it.
    await page.waitForTimeout(1200);
    await open(page, id);
    expect((await letters(page))[4]).toBe('X');
  });

  test('a cell click selects in the editor’s colors, and no Player Hint is marked', async ({ page }) => {
    await open(page, await seed('hints'));
    await turnOn(page);
    await cell(page, '1,0').click();
    // The hints phase's own colors (14-S12, 17-S5), on the editor's grid.
    await expect(grid(page)).not.toHaveAttribute('data-grid-mode', 'play');
    expect(await background(cell(page, '1,0')), 'cursor').toEqual(await token(page, 'hint-cell-cursor'));
    for (const word of ['0,0', '2,0']) {
      expect(await background(cell(page, word)), `word ${word}`).toEqual(await token(page, 'hint-cell-cursor-word'));
    }
    expect(await background(cell(page, '1,1')), 'outside the word').toEqual(await token(page, 'hint-cell-on'));

    const blue = await token(page, 'play-cell-selected-row');
    await expect(page.locator('[data-testid="play-clue"][data-active="true"]')).toHaveCount(0);
    for (const clue of await page.getByTestId('play-clue').all()) {
      expect(await background(clue), 'no blue').not.toEqual(blue);
    }
  });

  test('a Player Hint click changes nothing', async ({ page }) => {
    await open(page, await seed('hints'));
    await turnOn(page);
    await cell(page, '1,1').click();
    // 3 Down's cells, outside the selected 4 Across except where they cross.
    const down = async () => Promise.all(['2,0', '2,2'].map((c) => background(cell(page, c))));
    const shown = await down();
    await page.locator('[data-testid="play-clue"][data-clue-key="3-down"]').click();
    await expect(page.locator('[data-testid="play-clue"][data-active="true"]')).toHaveCount(0);
    expect(await background(page.locator('[data-testid="play-clue"][data-clue-key="3-down"]'))).not.toEqual(
      await token(page, 'play-cell-selected-row')
    );
    expect(await down(), '3 Down isn’t selected').toEqual(shown);
  });
});

test.describe('17-S9-4 editing goes on while it’s on', () => {
  test.use({ viewport: { width: 1280, height: 900 } });

  test('Lock Grid Letters works as always', async ({ page }) => {
    await open(page, await seed('hints'));
    await turnOn(page);
    await expect(lockToggle(page).locator('input')).toBeEnabled();
    const opacity = await lockToggle(page).evaluate((el) => Number(getComputedStyle(el).opacity));
    expect(opacity, 'no inactive look').toBe(1);
    await lockToggle(page).click();
    await expect(lockToggle(page).locator('input')).toBeChecked();
    // Locked, typing changes no letter, as when Preview Hints is off.
    await cell(page, '1,1').click();
    await page.keyboard.type('X');
    expect((await letters(page))[4]).toBe('R');
    await lockToggle(page).click();
    await expect(lockToggle(page).locator('input')).not.toBeChecked();
  });

  test('3 Publish with a hint missing turns it off, so "Not quite!"’s marks show', async ({ page }) => {
    await open(page, await seed('hints', { missing: '2-down' }));
    await turnOn(page);
    await page.locator('[data-testid="builder-steps"] [data-step-id="publish"]').click();
    await expect(page.getByTestId('too-early-dialog')).toBeVisible();
    await expect(previewToggle(page).locator('input')).not.toBeChecked();
    await page.getByTestId('too-early-dialog').getByRole('button', { name: 'OK' }).click();
    await expect(page.locator('[data-hint-key="2-down"]')).toHaveAttribute('data-missing', 'true');
  });
});

