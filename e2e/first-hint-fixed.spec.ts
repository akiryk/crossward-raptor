import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 18-S9 — First hint numbers fixed.
//
// In the hints phase, toggling Preview Hints (17-S9) moves neither
// column's first hint number: not its left, not its top, not its size or
// color (the human, 2026-11-02). The rows after it may move; that is the
// hints' own vertical layout. In one column (below a 1430px window) the
// Down label may move (18-S7), so Down's first number keeps its place
// relative to the Down label.
//
// Positions are those of the number's text (a DOM Range over it), compared
// relative to the grid's box, with the list unscrolled.
//
// Do not edit this file to match an implementation.

const TOLERANCE = 0.5;
const TWO_COLUMNS_FROM_PX = 1430;

function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

function everyHint(size: number): Record<string, string> {
  const hints: Record<string, string> = {};
  const text = (key: string) => `Hint ${key}, long enough to wrap onto a second line somewhere`;
  for (let n = 1; n <= size; n++) hints[`${n}-down`] = text(`${n}-down`);
  hints['1-across'] = text('1-across');
  for (let row = 1; row < size; row++) hints[`${size + row}-across`] = text(`${size + row}-across`);
  return hints;
}

let titleCounter = 0;
async function open(page: Page, width: number, size: number) {
  await page.setViewportSize({ width, height: 900 });
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid: filled(size), hints: everyHint(size), phase: 'hints' },
    `S9 ${size} ${Date.now()}-${titleCounter}`
  );
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  await expect(page.getByTestId('hints-region')).toBeVisible();
}

const region = (page: Page) => page.getByTestId('hints-region');
const previewToggle = (page: Page) => page.getByTestId('preview-hints-toggle').filter({ visible: true });

async function setPreview(page: Page, on: boolean) {
  const input = previewToggle(page).locator('input');
  if ((await input.isChecked()) !== on) await previewToggle(page).click();
  if (on) {
    await expect(input).toBeChecked();
    await expect(region(page).getByTestId('play-clue').first()).toBeVisible();
  } else {
    await expect(input).not.toBeChecked();
    await expect(region(page).getByTestId('hint-input').first()).toBeVisible();
  }
}

type Look = { left: number; top: number; fontSize: string; fontWeight: string; color: string };

/** The text's left and top, and its size, weight and color. */
async function look(locator: Locator): Promise<Look> {
  return locator.evaluate((el) => {
    const range = document.createRange();
    range.selectNodeContents(el);
    const r = range.getBoundingClientRect();
    const style = getComputedStyle(el);
    return { left: r.left, top: r.top, fontSize: style.fontSize, fontWeight: style.fontWeight, color: style.color };
  });
}

/** Each column's first number, relative to the grid's box and to its label's text. */
async function firstNumbers(page: Page, preview: boolean) {
  const g = await page.getByTestId('puzzle-grid').boundingBox();
  if (!g) throw new Error('no grid box');
  const column = preview ? 'play-clue-column' : 'hint-column';
  const numberId = preview ? 'play-clue-number' : 'hint-label';
  const out: Record<string, Look & { labelTop: number }> = {};
  for (const orientation of ['across', 'down']) {
    const col = region(page).locator(`[data-testid="${column}"][data-orientation="${orientation}"]`);
    const number = await look(col.getByTestId(numberId).first());
    const heading = await look(col.getByRole('heading'));
    out[orientation] = {
      ...number,
      left: number.left - g.x,
      top: number.top - g.y,
      labelTop: number.top - heading.top,
    };
  }
  return out;
}

function expectSame(
  actual: Awaited<ReturnType<typeof firstNumbers>>,
  expected: Awaited<ReturnType<typeof firstNumbers>>,
  twoColumns: boolean,
  when: string
) {
  for (const orientation of ['across', 'down']) {
    const a = actual[orientation];
    const e = expected[orientation];
    const what = `${orientation}'s first number, ${when}`;
    expect(Math.abs(a.left - e.left), `${what}: left`).toBeLessThanOrEqual(TOLERANCE);
    if (orientation === 'across' || twoColumns) {
      expect(Math.abs(a.top - e.top), `${what}: top`).toBeLessThanOrEqual(TOLERANCE);
    } else {
      expect(Math.abs(a.labelTop - e.labelTop), `${what}: top below the Down label`).toBeLessThanOrEqual(TOLERANCE);
    }
    expect(a.fontSize, `${what}: size`).toBe(e.fontSize);
    expect(a.fontWeight, `${what}: weight`).toBe(e.fontWeight);
    expect(a.color, `${what}: color`).toBe(e.color);
  }
}

test.describe('18-S9-1 Preview Hints moves neither column\'s first hint number', () => {
  for (const width of [1440, 2400, 1430, 1429, 1280, 1140]) {
    for (const size of [5, 15]) {
      test(`${width}px, ${size}×${size}: off, on and off again`, async ({ page }) => {
        const twoColumns = width >= TWO_COLUMNS_FROM_PX;
        await open(page, width, size);
        const off = await firstNumbers(page, false);
        await setPreview(page, true);
        expectSame(await firstNumbers(page, true), off, twoColumns, 'Preview Hints on');
        await setPreview(page, false);
        expectSame(await firstNumbers(page, false), off, twoColumns, 'Preview Hints off again');
      });
    }
  }
});
