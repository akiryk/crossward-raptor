import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { currentBuilderId } from './helpers/ownership';
import { seedPlayPuzzle, seedPlaySession } from './helpers/play-route';

// Story 15-S5 — Play, narrow.
//
// Below a 1290px window (1242px of room in play), play shows no title,
// controls row, Prominent Hint or Player Hints. The masthead is the only
// thing above the grid, which is 24px under it, 560px and centered in
// play's width. Messages that need attention (a failed save and its
// Retry, the completed mark and message) show above the grid, 16px from
// it; the routine "Saved" status doesn't show.
//
// Directly under the grid, at its width, the play hint bar: a 4px
// hint-rule (gray-700) along its top, filled play-hint-bar (blue-medium),
// 48px tall with the rule, growing when a hint wraps. Inside, the
// Previous and Next arrows (24px buttons) 12px from its sides and
// vertically centered, and between them, 12px from each, the hint of the
// word at the cursor in body-large primary, centered, with no number or
// direction. With no word selected (the grid unfocused, a complete
// puzzle) the bar is empty and keeps its height. Play opens on 1 Across
// with the grid focused (17-S2), so the bar shows its hint on load and a
// test starts there without clicking (0,0), which would toggle to Down.
//
// The arrows step from the cursor's word in the Hint Box's order (every
// Across word by number, then every Down word, wrapping both ways); with
// no cursor, Next goes to the first Across word and Previous to the last
// Down word. An arrow selects its word as a click on a Player Hint does:
// the cursor goes to its first empty cell (its first cell when full) in
// its direction, and the grid takes focus. The arrows are disabled once
// the puzzle is complete.
//
// From 1290px up, play is as in S2. Colors are the tokens' resolved hex
// values (pinned by color-tokens).
//
// Do not edit this file to match an implementation.

const GRAY_700 = 'rgb(20, 21, 27)';
const BLUE_MEDIUM = 'rgb(207, 238, 255)';
const BLACK = 'rgb(0, 0, 0)'; // primary

const GRID_PX = 560;
const PAGE_PADDING_PX = 24;
const MESSAGE_GAP_PX = 16;
const BAR_PX = 48;
const RULE_PX = 4;
const INSET_PX = 12;
const ARROW_PX = 24;
const ARROW_TO_HINT_PX = 12;

/** Every cell lettered, so every word survives into play. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

/** A hint for every word of a filled 5×5: 1 and 6–9 Across, 1–5 Down. */
function everyHint(): Record<string, string> {
  const hints: Record<string, string> = { '1-across': 'Across hint 1' };
  for (let n = 6; n <= 9; n++) hints[`${n}-across`] = `Across hint ${n}`;
  for (let n = 1; n <= 5; n++) hints[`${n}-down`] = `Down hint ${n}`;
  return hints;
}

async function open(page: Page, width: number, options: { hints?: Record<string, string>; complete?: boolean } = {}) {
  await page.setViewportSize({ width, height: 900 });
  const builderId = await currentBuilderId(page);
  const puzzle = { grid: filled(5), phase: 'hints' as const, hints: options.hints ?? everyHint() };
  const fixture = await seedPlayPuzzle({ builderId, puzzle });
  if (options.complete) await seedPlaySession(builderId, fixture.id, puzzle.grid);
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
  return fixture;
}

async function rect(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

function css(locator: Locator, property: string) {
  return locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);
}

/** A design token's value in px, resolved the way the page resolves it. */
function tokenPx(page: Page, name: string) {
  return page.evaluate((n) => {
    const probe = document.createElement('div');
    probe.style.width = `var(${n})`;
    document.body.appendChild(probe);
    const width = getComputedStyle(probe).width;
    probe.remove();
    return width;
  }, name);
}

/** The horizontal center of an element's text, not its box. */
function textCenter(locator: Locator) {
  return locator.evaluate((el) => {
    const range = document.createRange();
    range.selectNodeContents(el);
    const r = range.getBoundingClientRect();
    return r.left + r.width / 2;
  });
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const region = (page: Page) => page.getByTestId('play-grid-region');
const hintBar = (page: Page) => page.getByTestId('play-hint-bar');
const hintText = (page: Page) => hintBar(page).getByTestId('play-hint-bar-text');
const previous = (page: Page) => hintBar(page).getByRole('button', { name: 'Previous word' });
const next = (page: Page) => hintBar(page).getByRole('button', { name: 'Next word' });
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const visible = (locator: Locator) => locator.filter({ visible: true });

/** The wide arrangement's parts, all hidden narrow. */
const WIDE_PARTS = ['play-title', 'play-options', 'play-reset-button', 'prominent-hint', 'play-clues'];

function noHorizontalOverflow(page: Page) {
  return page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth);
}

// --- 15-S5-1: the threshold ---
test.describe('15-S5-1 the threshold', () => {
  for (const width of [1289, 1024]) {
    test(`at ${width}px: no title, controls or hint lists, and the bar under the grid`, async ({ page }) => {
      await open(page, width);
      for (const id of WIDE_PARTS) await expect(page.getByTestId(id), id).toBeHidden();
      await expect(hintBar(page)).toBeVisible();
      const g = await rect(grid(page));
      expect((await rect(hintBar(page))).y, 'under the grid').toBeCloseTo(g.bottom, 0);
    });
  }

  test('at 1290px: the title, controls, Prominent Hint and Player Hints, and no bar', async ({ page }) => {
    await open(page, 1290);
    for (const id of WIDE_PARTS) await expect(page.getByTestId(id), id).toBeVisible();
    await expect(hintBar(page)).toBeHidden();
  });
});

// --- 15-S5-2: above the grid ---
test.describe('15-S5-2 above the grid', () => {
  for (const width of [1024, 768]) {
    test(`at ${width}px: only the masthead, the grid 24px under it, 560px and centered`, async ({ page }) => {
      await open(page, width);
      const header = page.getByTestId('app-header');
      await expect(header.getByTestId('home-link')).toBeVisible();
      await expect(header.getByTestId('sign-out')).toBeVisible();

      const h = await rect(header);
      const g = await rect(grid(page));
      const play = await rect(page.getByTestId('play-puzzle'));
      expect(g.y - h.bottom, '24px under the masthead').toBeCloseTo(PAGE_PADDING_PX, 0);
      expect(g.width, '560px').toBeCloseTo(GRID_PX, 0);
      expect(g.x - play.x, 'centered in play’s width').toBeCloseTo(play.right - g.right, 0);
      await expect(visible(page.getByText(/^(Saved|Saving…|Waiting to save…)$/)), 'no routine save status').toHaveCount(0);
    });
  }
});

// --- 15-S5-3: messages ---
test.describe('15-S5-3 messages', () => {
  test('at 768px: a failed save shows its message and Retry 16px above the grid, and Retry saves', async ({ page }) => {
    const fixture = await open(page, 768);
    const action = `**/puzzles/${fixture.id}/play`;
    await page.route(action, async (route) => {
      if (route.request().headers()['next-action']) await route.abort('failed');
      else await route.continue();
    });
    await cell(page, '0,0').click();
    await page.keyboard.type('a');

    const alert = visible(page.getByRole('alert').filter({ hasText: 'We couldn’t save your entries.' }));
    await expect(alert).toHaveCount(1);
    const a = await rect(alert);
    const g = await rect(grid(page));
    expect(g.y - a.bottom, '16px above the grid').toBeCloseTo(MESSAGE_GAP_PX, 0);
    expect(a.x, 'from the grid’s left').toBeGreaterThanOrEqual(g.x - 0.5);
    expect(a.right, 'within the grid’s width').toBeLessThanOrEqual(g.right + 0.5);

    await page.unroute(action);
    const saved = page.waitForResponse(
      (response) => response.url().includes(`/puzzles/${fixture.id}/play`)
        && response.request().headers()['next-action'] !== undefined
    );
    await alert.getByRole('button', { name: 'Retry' }).click();
    await saved;
    await expect(alert).toHaveCount(0);
  });

  test('at 768px: a complete puzzle shows the completed mark and message 16px above the grid', async ({ page }) => {
    await open(page, 768, { complete: true });
    const message = page.getByTestId('play-lock-message');
    const mark = page.getByTestId('play-completed-mark');
    await expect(message).toBeVisible();
    await expect(mark).toBeVisible();
    const bottom = Math.max((await rect(message)).bottom, (await rect(mark)).bottom);
    expect((await rect(grid(page))).y - bottom, '16px above the grid').toBeCloseTo(MESSAGE_GAP_PX, 0);
  });
});

// --- 15-S5-4: the bar ---
test.describe('15-S5-4 the bar', () => {
  test('at 768px: under the grid at its width, the rule, the fill, 48px tall, the arrows 12px in', async ({ page }) => {
    await open(page, 768);
    const bar = hintBar(page);
    const g = await rect(grid(page));
    const b = await rect(bar);
    expect(b.y, 'directly under the grid').toBeCloseTo(g.bottom, 0);
    expect(b.x, 'from the grid’s left').toBeCloseTo(g.x, 0);
    expect(b.width, 'the grid’s width').toBeCloseTo(g.width, 0);
    expect(b.height, '48px with the rule').toBeCloseTo(BAR_PX, 0);

    expect(await css(bar, 'border-top-width'), 'the rule').toBe(`${RULE_PX}px`);
    expect(await css(bar, 'border-top-color'), 'the rule is hint-rule').toBe(GRAY_700);
    for (const side of ['left', 'right', 'bottom']) {
      expect(parseFloat(await css(bar, `border-${side}-width`)), `no ${side} outline`).toBe(0);
    }
    expect(await css(bar, 'background-color'), 'play-hint-bar').toBe(BLUE_MEDIUM);

    const prev = await rect(previous(page));
    const nxt = await rect(next(page));
    for (const [name, r] of [['Previous', prev], ['Next', nxt]] as const) {
      expect(r.width, `${name} is 24px`).toBeCloseTo(ARROW_PX, 0);
      expect(r.height, `${name} is 24px`).toBeCloseTo(ARROW_PX, 0);
      expect(r.y + r.height / 2, `${name} vertically centered`).toBeCloseTo((b.y + RULE_PX + b.bottom) / 2, 0);
    }
    expect(prev.x - b.x, 'Previous 12px from the left').toBeCloseTo(INSET_PX, 0);
    expect(b.right - nxt.right, 'Next 12px from the right').toBeCloseTo(INSET_PX, 0);
  });

  test('a long hint wraps, the bar grows and the arrows stay centered', async ({ page }) => {
    const long = Array(3).fill('A very long hint that cannot possibly fit on one line of the bar').join(', ');
    await open(page, 768, { hints: { ...everyHint(), '1-across': long } });
    await expect(hintText(page)).toHaveText(long);
    const b = await rect(hintBar(page));
    expect(b.height, 'taller than one line').toBeGreaterThan(BAR_PX + 1);
    const prev = await rect(previous(page));
    expect(prev.y + prev.height / 2, 'Previous vertically centered').toBeCloseTo((b.y + RULE_PX + b.bottom) / 2, 0);
    const t = await rect(hintText(page));
    expect(t.bottom, 'the hint within the bar').toBeLessThanOrEqual(b.bottom + 0.5);
  });
});

// --- 15-S5-5: the hint ---
test.describe('15-S5-5 the hint', () => {
  test('at 768px: the cursor word’s hint in body-large primary, centered between the arrows, no number', async ({ page }) => {
    await open(page, 768);
    const text = hintText(page);
    await expect(text).toHaveText('Across hint 1');
    await expect(hintBar(page)).toHaveText('Across hint 1');

    expect(await css(text, 'font-size'), 'body-large size').toBe(await tokenPx(page, '--text-body-large'));
    expect(await css(text, 'line-height'), 'body-large line height').toBe(await tokenPx(page, '--text-body-large--line-height'));
    expect(await css(text, 'color'), 'primary').toBe(BLACK);

    const prev = await rect(previous(page));
    const nxt = await rect(next(page));
    const t = await rect(text);
    expect(t.x - prev.right, '12px after Previous').toBeCloseTo(ARROW_TO_HINT_PX, 0);
    expect(nxt.x - t.right, '12px before Next').toBeCloseTo(ARROW_TO_HINT_PX, 0);
    expect(await textCenter(text), 'centered between the arrows').toBeCloseTo((prev.right + nxt.x) / 2, 0);
  });

  test('on load: 1 Across’s hint, 48px tall', async ({ page }) => {
    await open(page, 768);
    await expect(hintBar(page)).toHaveText('Across hint 1');
    expect((await rect(hintBar(page))).height, '48px').toBeCloseTo(BAR_PX, 0);
  });
});

// --- 15-S5-6: it follows the cursor ---
test.describe('15-S5-6 it follows the cursor', () => {
  test('at 768px: clicks, the toggle and the arrow keys move it; it empties when the grid loses focus', async ({ page }) => {
    await open(page, 768);
    await expect(hintText(page)).toHaveText('Across hint 1');
    await cell(page, '0,0').click();
    await expect(hintText(page)).toHaveText('Down hint 1');
    await cell(page, '2,3').click();
    await expect(hintText(page)).toHaveText('Down hint 3');
    await page.keyboard.press(' ');
    await expect(hintText(page)).toHaveText('Across hint 8');
    await page.keyboard.press('ArrowUp');
    await expect(hintText(page)).toHaveText('Down hint 3');
    await page.keyboard.press('ArrowLeft');
    await page.keyboard.press('ArrowUp');
    await expect(hintText(page)).toHaveText('Down hint 3');
    await page.keyboard.press('ArrowLeft');
    await expect(hintText(page)).toHaveText('Across hint 8');

    await region(page).blur();
    await expect(hintBar(page)).toHaveText('');
    expect((await rect(hintBar(page))).height, 'keeps its height').toBeCloseTo(BAR_PX, 0);
  });
});

// --- 15-S5-7: the order ---
test.describe('15-S5-7 the order', () => {
  test('at 768px: from 1 Across, Next visits 6–9 Across, 1–5 Down and wraps; Previous wraps back', async ({ page }) => {
    await open(page, 768);
    await expect(hintText(page)).toHaveText('Across hint 1');
    const expected = [6, 7, 8, 9].map((n) => `Across hint ${n}`)
      .concat([1, 2, 3, 4, 5].map((n) => `Down hint ${n}`), ['Across hint 1']);
    for (const hint of expected) {
      await next(page).click();
      await expect(hintText(page)).toHaveText(hint);
    }
    await previous(page).click();
    await expect(hintText(page)).toHaveText('Down hint 5');
  });

  test('on open, at 1 Across, Next shows 6 Across and Previous 5 Down', async ({ page }) => {
    await open(page, 768);
    await next(page).click();
    await expect(hintText(page)).toHaveText('Across hint 6');
    await page.reload();
    await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
    await previous(page).click();
    await expect(hintText(page)).toHaveText('Down hint 5');
  });

  test('after the grid loses focus, Next steps from the cursor’s word', async ({ page }) => {
    await open(page, 768);
    await cell(page, '0,1').click();
    await expect(hintText(page)).toHaveText('Across hint 6');
    await region(page).blur();
    await expect(hintBar(page)).toHaveText('');
    await next(page).click();
    await expect(hintText(page)).toHaveText('Across hint 7');
  });
});

// --- 15-S5-8: an arrow selects its word ---
test.describe('15-S5-8 an arrow selects its word', () => {
  test('at 768px: the grid takes focus, the cursor at the word’s first empty cell, and typing fills it', async ({ page }) => {
    await open(page, 768);
    await cell(page, '0,1').click();
    await page.keyboard.type('ab');
    await cell(page, '0,0').click();
    await expect(hintText(page)).toHaveText('Across hint 1');

    await next(page).click();
    await expect(hintText(page)).toHaveText('Across hint 6');
    await expect(region(page)).toBeFocused();
    await expect(cell(page, '2,1'), 'the first empty cell').toHaveAttribute('data-selected', 'true');
    for (const coord of ['0,1', '1,1', '3,1', '4,1']) {
      await expect(cell(page, coord), `${coord} in the word`).toHaveAttribute('data-highlight', 'slot');
    }
    await page.keyboard.type('c');
    await expect(cell(page, '2,1')).toContainText('C');
    await expect(cell(page, '3,1')).toHaveAttribute('data-selected', 'true');
  });

  test('a full word: the cursor at its first cell, in the word’s direction', async ({ page }) => {
    await open(page, 768);
    await cell(page, '0,2').click();
    await page.keyboard.type('aaaaa');
    await cell(page, '0,1').click();
    await next(page).click();
    await expect(hintText(page)).toHaveText('Across hint 7');
    await expect(cell(page, '0,2')).toHaveAttribute('data-selected', 'true');

    // From 9 Across, Next goes to 1 Down: down the first column.
    await cell(page, '0,4').click();
    await next(page).click();
    await expect(hintText(page)).toHaveText('Down hint 1');
    await expect(cell(page, '0,0')).toHaveAttribute('data-selected', 'true');
    for (const coord of ['0,1', '0,2', '0,3', '0,4']) {
      await expect(cell(page, coord), `${coord} in 1 Down`).toHaveAttribute('data-highlight', 'slot');
    }
  });
});

