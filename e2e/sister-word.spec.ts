import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 25-S1 — the sister word.
//
// In the build phase with Preview off, while the cursor is in a word (the
// blue-medium word of 21-S1 and 22-S5), the cells of that word's 180°
// image, its sister word, are interactive-faint-hover (#E8F7FF), whatever
// they were: an off cell (gray), a symmetric hint (white, no letter) or a
// letter (white). They are pale blue in the cursor's own line too (the
// center row or column), where the rest of the line looks as outside the
// word. The cursor and its word keep their colors. Only the background
// changes: `data-cell-state` and the letters stay as they were. With no
// cursor word, or in Preview, no cell is pale blue.
//
// Colors are the human's values, written out here. Do not edit this file
// to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const SISTER = 'rgb(232, 247, 255)'; // interactive-faint-hover, #E8F7FF
const CURSOR = 'rgb(252, 255, 77)'; // yellow-bright
const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // #CFEEFF
const OFF = 'rgb(221, 224, 230)'; // gray-200, build-cell-off
const WHITE = 'rgb(255, 255, 255)'; // build-cell-on
const RED = 'rgb(255, 37, 26)'; // cell-error, Preview's symmetric hint

function gridWith(letters: Record<string, string>): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  for (const [coord, letter] of Object.entries(letters)) {
    const [col, row] = coord.split(',').map(Number);
    grid = withLetter(grid, { col, row }, letter);
  }
  return grid;
}

const spell = (coords: string[], word: string) => Object.fromEntries(coords.map((coord, i) => [coord, word[i]]));

// A daily (the counterpart of (c,r) is (14−c, 14−r)).
// CAT across row 0, columns 0–2; its sister cells (12–14,14) are
// symmetric hints. The cell after it, (3,0), has the off cell (11,14) as
// its counterpart.
const CAT = ['0,0', '1,0', '2,0'];
const CAT_SISTER = ['14,14', '13,14', '12,14', '11,14'];
// DOGS across row 14, columns 11–14: the sister of CAT's four-cell word.
const DOGS = ['11,14', '12,14', '13,14', '14,14'];

let titleCounter = 0;
async function open(page: Page, grid: Grid) {
  titleCounter += 1;
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, `25-S1 ${Date.now()}-${titleCounter}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const bg = (page: Page, coord: string) =>
  cell(page, coord).evaluate((el) => getComputedStyle(el).backgroundColor);

/** The coords of every grid cell whose background is the sister's color. */
const paleCells = (page: Page) =>
  page.locator('[data-testid="grid-cell"]').evaluateAll(
    (cells, color) =>
      cells.filter((el) => getComputedStyle(el).backgroundColor === color).map((el) => el.getAttribute('data-coord')),
    SISTER
  );

const sorted = (coords: (string | null)[]) => [...coords].sort();

/** The cursor on `coord`, in `orientation` (as in e2e/would-be-word.spec.ts). */
async function cursorOn(page: Page, coord: string, orientation: 'across' | 'down') {
  const [col, row] = coord.split(',').map(Number);
  const other = orientation === 'across' ? `${col === 0 ? 1 : 0},${row}` : `${col},${row === 0 ? 1 : 0}`;
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  if ((await cell(page, other).getAttribute('data-highlight')) !== 'slot') await cell(page, coord).click();
  await expect(cell(page, other)).toHaveAttribute('data-highlight', 'slot');
}

test.describe('25-S1-4 typing a word: gray and white sister cells turn pale blue', () => {
  test('typed CAT: its four-cell word\'s sister, three symmetric hints and an off cell, is pale blue', async ({ page }) => {
    await open(page, createGrid({ cols: 15, rows: 15 }));
    await cursorOn(page, '0,0', 'across');
    await page.keyboard.type('CAT');
    await expect(cell(page, '3,0')).toHaveAttribute('data-selected', 'true');

    expect(sorted(await paleCells(page))).toEqual(sorted(CAT_SISTER));
    // Only the background changes: the cells keep their states.
    for (const coord of ['14,14', '13,14', '12,14']) {
      await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', 'symmetric-hint');
    }
    await expect(cell(page, '11,14')).toHaveAttribute('data-cell-state', 'empty');
    // The rest of row 14 is as before.
    expect(await bg(page, '10,14')).toBe(OFF);
    // The cursor and its word keep their colors.
    expect(await bg(page, '3,0')).toBe(CURSOR);
    for (const coord of CAT) expect(await bg(page, coord), coord).toBe(BLUE_MEDIUM);
  });

  test('mid-word: after C alone, the sister is the image of the cursor\'s word so far', async ({ page }) => {
    await open(page, createGrid({ cols: 15, rows: 15 }));
    await cursorOn(page, '0,0', 'across');
    await page.keyboard.type('C');
    await expect(cell(page, '1,0')).toHaveAttribute('data-selected', 'true');
    // The cursor's word is (0–1,0), the cell it would join included (22-S5).
    expect(sorted(await paleCells(page))).toEqual(sorted(['14,14', '13,14']));
  });
});

test.describe('25-S1-5 a sister that is already a word turns pale blue', () => {
  test('the cursor in CAT\'s word: DOGS\'s white letters are pale blue, letters and states unchanged', async ({ page }) => {
    await open(page, gridWith({ ...spell(CAT, 'CAT'), ...spell(DOGS, 'DOGS') }));
    await cursorOn(page, '1,0', 'across');

    expect(sorted(await paleCells(page))).toEqual(sorted(DOGS));
    for (const [i, coord] of DOGS.entries()) {
      await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', 'letter');
      await expect(cell(page, coord), coord).toContainText('DOGS'[i]);
    }
  });

  test('it follows the cursor: in DOGS, CAT and its symmetric hint are pale blue; DOGS is the word', async ({ page }) => {
    await open(page, gridWith({ ...spell(CAT, 'CAT'), ...spell(DOGS, 'DOGS') }));
    await cursorOn(page, '12,14', 'across');

    expect(sorted(await paleCells(page))).toEqual(sorted([...CAT, '3,0']));
    for (const coord of ['11,14', '13,14', '14,14']) expect(await bg(page, coord), coord).toBe(BLUE_MEDIUM);
  });

  test('a down word\'s sister is pale blue too', async ({ page }) => {
    // SIR down column 9, rows 3–5; its sister (5,9–11) is symmetric hints.
    await open(page, gridWith(spell(['9,3', '9,4', '9,5'], 'SIR')));
    await cursorOn(page, '9,4', 'down');
    expect(sorted(await paleCells(page))).toEqual(sorted(['5,11', '5,10', '5,9']));
  });
});

test.describe('25-S1-6 in the cursor\'s own line', () => {
  test('the center row: AT\'s sister, in the same row, is pale blue; the row\'s off cells stay gray', async ({ page }) => {
    // A, T at (2,7), (3,7); their counterparts (12,7), (11,7) are symmetric hints.
    await open(page, gridWith(spell(['2,7', '3,7'], 'AT')));
    await cursorOn(page, '2,7', 'across');

    expect(sorted(await paleCells(page))).toEqual(sorted(['12,7', '11,7']));
    for (const coord of ['12,7', '11,7']) {
      await expect(cell(page, coord), coord).toHaveAttribute('data-highlight', 'slot');
      await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', 'symmetric-hint');
    }
    for (const coord of ['0,7', '7,7', '10,7', '13,7']) expect(await bg(page, coord), coord).toBe(OFF);
  });
});

test.describe('25-S1-7 where there is no sister', () => {
  test('a word symmetric about the center is its own sister: no pale blue', async ({ page }) => {
    // A, T at (6,7), (7,7): (8,7) is a symmetric hint, so the word is (6–8,7).
    await open(page, gridWith(spell(['6,7', '7,7'], 'AT')));
    await cursorOn(page, '6,7', 'across');
    await expect(cell(page, '8,7')).toHaveAttribute('data-cell-state', 'slot-required');
    expect(await paleCells(page)).toEqual([]);
  });

  test('the cursor in no word: no pale blue; leaving the word clears it', async ({ page }) => {
    await open(page, gridWith({ ...spell(CAT, 'CAT'), ...spell(DOGS, 'DOGS') }));
    await cursorOn(page, '1,0', 'across');
    expect(sorted(await paleCells(page))).toEqual(sorted(DOGS));

    // (7,10) across touches no white cell (21-S14's look).
    await cursorOn(page, '7,10', 'across');
    expect(await paleCells(page)).toEqual([]);
    for (const coord of DOGS) expect(await bg(page, coord), coord).toBe(WHITE);
  });

  test('Preview: no pale blue; the sister cells take Preview\'s colors', async ({ page }) => {
    await open(page, gridWith(spell(CAT, 'CAT')));
    await cursorOn(page, '1,0', 'across');
    expect(sorted(await paleCells(page))).toEqual(sorted(['14,14', '13,14', '12,14']));

    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(page.getByTestId('puzzle-grid')).toHaveAttribute('data-grid-mode', 'preview');
    await expect.poll(() => paleCells(page)).toEqual([]);
    expect(await bg(page, '14,14')).toBe(RED);
  });
});
