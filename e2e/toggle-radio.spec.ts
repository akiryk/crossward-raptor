// --- F6-6: token-driven ---
test.describe('F6-6 token-driven', () => {
  test('live edits of the palette repaint the toggle and the rings, and restore', async ({ page }) => {
    await catalog(page);
    const sentinel = parseColor('rgb(18, 52, 86)');
    const set = (name: string, value: string | null) =>
      page.evaluate(
        ([n, v]) =>
          v === null
            ? document.documentElement.style.removeProperty(n!)
            : document.documentElement.style.setProperty(n!, v),
        [name, value] as const
      );
    const on = toggleParts(page, 'sg-toggle-on');
    const options = radioOptions(page, 'sg-radio-form');
    const selected = optionParts(options.filter({ has: page.locator('input:checked') }));
    const unselected = optionParts(options.filter({ hasNot: page.locator('input:checked') }).first());

    await set('--palette-interactive-dark', SENTINEL);
    expectColor((await styleOf(on.pill)).background, sentinel, 'on pill edited');
    expectColor((await styleOf(selected.input)).borderColors[0], sentinel, 'selected ring edited');
    expectColor((await styleOf(selected.dot)).background, sentinel, 'dot edited');
    await set('--palette-interactive-dark', null);
    await expectToggleColor(page, on, 'button-active', 'on restored');
    await expectRing(page, selected, 'button-active', 'selected restored');

    await set('--palette-gray-600', SENTINEL);
    expectColor((await styleOf(unselected.input)).borderColors[0], sentinel, 'unselected ring edited');
    await set('--palette-gray-600', null);
    await expectRing(page, unselected, 'line-dark', 'unselected restored');
  });
});

// --- F6-7: color transitions ---
test.describe('F6-7 color transitions', () => {
  test('buttons, the toggle, Radio and links change color, and the knob slides, over 150ms ease-out', async ({ page }) => {
    await catalog(page);
    const form = optionParts(radioOptions(page, 'sg-radio-form').filter({ has: page.locator('input:checked') }));
    const navUnselected = optionParts(
      radioOptions(page, 'sg-radio-nav').filter({ hasNot: page.locator('input:checked') })
    );
    const off = toggleParts(page, 'sg-toggle-off');
    const parts: [string, Locator, string[]][] = [
      ['button', page.getByTestId('sg-button').first(), ['background-color', 'border-color', 'color']],
      ['toggle pill', off.pill, ['background-color']],
      ['toggle knob', off.knob, ['border-color', 'translate']],
      ['toggle label', off.label, ['color']],
      ['radio ring', form.input, ['border-color']],
      ['radio dot', form.dot, ['background-color']],
      ['nav radio label', navUnselected.label, ['color']],
      ['link', page.getByTestId('sg-links').locator('a').first(), ['color']],
    ];
    for (const [name, locator, properties] of parts) {
      const t = await locator.evaluate((el) => {
        const s = getComputedStyle(el);
        return {
          properties: s.transitionProperty.split(',').map((p) => p.trim()),
          durations: s.transitionDuration.split(',').map((d) => d.trim()),
          timings: s.transitionTimingFunction.split(/,(?![^(]*\))/).map((f) => f.trim()),
        };
      });
      for (const property of properties) {
        let index = t.properties.indexOf(property);
        if (index < 0) index = t.properties.indexOf('all');
        expect(index, `${name} transitions ${property}`).toBeGreaterThanOrEqual(0);
        expect(t.durations[index % t.durations.length], `${name} ${property} duration`).toBe('0.15s');
        // Tailwind's `ease-out`.
        expect(t.timings[index % t.timings.length], `${name} ${property} timing`).toBe('cubic-bezier(0, 0, 0.2, 1)');
      }
    }
  });
});
