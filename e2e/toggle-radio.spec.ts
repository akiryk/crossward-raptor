type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) {
    return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  }
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: string, expected: Rgba, label: string) {
  const parsed = parseColor(actual);
  expect({ r: parsed.r, g: parsed.g, b: parsed.b }, label).toEqual({
    r: expected.r,
    g: expected.g,
    b: expected.b,
  });
  expect(parsed.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

function styleOf(locator: Locator) {
  return locator.evaluate(async (el) => {
    for (let i = 0; i < 10 && el.getAnimations().length > 0; i++) {
      await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
    }
    const s = getComputedStyle(el);
    const r = el.getBoundingClientRect();
    return {
      background: s.backgroundColor,
      color: s.color,
      borderColors: [s.borderTopColor, s.borderRightColor, s.borderBottomColor, s.borderLeftColor],
      borderWidths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
      borderStyles: [s.borderTopStyle, s.borderRightStyle, s.borderBottomStyle, s.borderLeftStyle],
      radius: parseFloat(s.borderTopLeftRadius),
      width: r.width,
      height: r.height,
      fontSize: parseFloat(s.fontSize),
      fontWeight: Number(s.fontWeight),
      fontFamily: s.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      lineHeight: s.lineHeight,
      boxShadow: s.boxShadow,
      outline:
        s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0
          ? 'none'
          : `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor}`,
    };
  });
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

async function tokenLineHeight(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const lh = getComputedStyle(probe).lineHeight;
    probe.remove();
    return lh;
  }, style);
}

async function expectTextStyle(page: Page, locator: Locator, style: string, size: number, weight: number, label: string) {
  const s = await styleOf(locator);
  expect(s.fontFamily, `${label} family`).toBe('Inter');
  expect(s.fontSize, `${label} size`).toBe(size);
  expect(s.fontWeight, `${label} weight`).toBe(weight);
  expect(s.lineHeight, `${label} line height`).toBe(await tokenLineHeight(page, style));
}

async function parkMouse(page: Page) {
  await page.mouse.move(1, 1);
}

/** Focuses an element the way a keyboard user does, so :focus-visible applies. */
async function focusByKeyboard(page: Page, target: Locator) {
  await target.evaluate((el) => el.setAttribute('data-tab-target', ''));
  await page.evaluate(() => {
    const all = Array.from(
      document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input, select, textarea, [tabindex]')
    ).filter((el) => el.tabIndex >= 0);
    const index = all.findIndex((el) => el.hasAttribute('data-tab-target'));
    if (index > 0) {
      all[index - 1].focus();
    } else {
      (document.activeElement as HTMLElement | null)?.blur();
    }
  });
  for (let i = 0; i < 5; i++) {
    await page.keyboard.press('Tab');
    if (await target.evaluate((el) => el === document.activeElement)) break;
  }
  await expect(target).toBeFocused();
  await target.evaluate((el) => el.removeAttribute('data-tab-target'));
}

async function blur(page: Page) {
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
}

async function catalog(page: Page) {
  await page.goto('/style-guide');
  await expect(page.getByTestId('sg-toggles')).toBeVisible();
  await expect(page.getByTestId('sg-radios')).toBeVisible();
  await parkMouse(page);
}

function toggleParts(page: Page, testId: string) {
  const root = page.getByTestId(testId);
  return {
    root,
    input: root.locator('input[type="checkbox"]'),
    pill: root.locator('[data-toggle-pill]'),
    knob: root.locator('[data-toggle-knob]'),
    label: root.locator('[data-toggle-label]'),
  };
}

type Toggle = ReturnType<typeof toggleParts>;

/** The pill and its knob outline are both `style`; the knob is white; nothing has a ring. */
async function expectToggleColor(page: Page, t: Toggle, style: string, label: string) {
  const color = await token(page, style);
  const pill = await styleOf(t.pill);
  const knob = await styleOf(t.knob);
  expectColor(pill.background, color, `${label} pill`);
  expectColor(knob.background, await token(page, 'inverse'), `${label} knob fill`);
  expect(knob.borderWidths, `${label} knob outline width`).toEqual(['1px', '1px', '1px', '1px']);
  expect(knob.borderStyles, `${label} knob outline style`).toEqual(['solid', 'solid', 'solid', 'solid']);
  for (const c of knob.borderColors) expectColor(c, color, `${label} knob outline`);
  for (const [part, s] of [['pill', pill], ['knob', knob]] as const) {
    expect(s.outline, `${label} ${part} outline`).toBe('none');
    expect(s.boxShadow, `${label} ${part} box shadow`).toBe('none');
  }
}

function radioOptions(page: Page, groupTestId: string) {
  return page.getByTestId(groupTestId).getByTestId(`${groupTestId}-option`);
}

function optionParts(option: Locator) {
  return {
    option,
    input: option.locator('input[type="radio"]'),
    dot: option.locator('[data-radio-dot]'),
    label: option.locator('[data-radio-label]'),
  };
}

type Option = ReturnType<typeof optionParts>;

/** A round 2px solid ring in `ringStyle`, transparent inside, with no focus ring. */
async function expectRing(page: Page, o: Option, ringStyle: string, label: string) {
  const s = await styleOf(o.input);
  expect(s.borderWidths, `${label} ring width`).toEqual(['2px', '2px', '2px', '2px']);
  expect(s.borderStyles, `${label} ring style`).toEqual(['solid', 'solid', 'solid', 'solid']);
  const color = await token(page, ringStyle);
  for (const c of s.borderColors) expectColor(c, color, `${label} ring`);
  expect(Math.abs(s.width - s.height), `${label} ring is square`).toBeLessThanOrEqual(0.5);
  expect(s.width, `${label} ring size`).toBeCloseTo(16, 0);
  expect(s.radius, `${label} ring is round`).toBeGreaterThanOrEqual(s.width / 2 - 0.5);
  expect(parseColor(s.background).a, `${label} ring fill`).toBe(0);
  expect(s.outline, `${label} outline`).toBe('none');
  expect(s.boxShadow, `${label} box shadow`).toBe('none');
}

/** The selected dot: visible, round, `dotStyle`, centred inside the ring and clear of it. */
async function expectDot(page: Page, o: Option, dotStyle: string, label: string) {
  await expect(o.dot, `${label} dot`).toBeVisible();
  const s = await styleOf(o.dot);
  expectColor(s.background, await token(page, dotStyle), `${label} dot`);
  expect(s.radius, `${label} dot is round`).toBeGreaterThanOrEqual(s.width / 2 - 0.5);
  const ring = await box(o.input);
  const dot = await box(o.dot);
  expect(dot.width, `${label} dot size`).toBeCloseTo(8, 0);
  expect(dot.height, `${label} dot size`).toBeCloseTo(8, 0);
  expect(Math.abs(dot.x + dot.width / 2 - (ring.x + ring.width / 2)), `${label} dot centred x`).toBeLessThanOrEqual(1);
  expect(Math.abs(dot.y + dot.height / 2 - (ring.y + ring.height / 2)), `${label} dot centred y`).toBeLessThanOrEqual(1);
}

/** The label sits 8px right of the ring and is centred on it. */
async function expectLabelBeside(o: Option, label: string) {
  const ring = await box(o.input);
  const text = await box(o.label);
  expect(text.x - (ring.x + ring.width), `${label} label 8px right of the ring`).toBeCloseTo(8, 0);
  expect(Math.abs(text.y + text.height / 2 - (ring.y + ring.height / 2)), `${label} label centred on the ring`).toBeLessThanOrEqual(2);
}

async function expectLabelColor(page: Page, o: Option, style: string, label: string) {
  expectColor((await styleOf(o.label)).color, await token(page, style), `${label} label`);
}

