/** AB at the top left and DC at the bottom right: two two-letter words,
 *  each the other's symmetric counterpart, so warnings and no errors. */
function warningsGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'A');
  grid = withLetter(grid, { col: 1, row: 0 }, 'B');
  grid = withLetter(grid, { col: 13, row: 14 }, 'C');
  grid = withLetter(grid, { col: 14, row: 14 }, 'D');
  return grid;
}

/** warningsGrid plus Q at (5,5): its counterpart (9,9) is a lone missing
 *  symmetric letter, so an error as well. */
function bothGrid(): Grid {
  return withLetter(warningsGrid(), { col: 5, row: 5 }, 'Q');
}

const ERROR_TEXT = 'Avoid breaking radial symmetry';
const WARNING_TEXT = 'Avoid two-letter words';
const legend = (page: Page) => page.getByTestId('preview-legend');
const items = (page: Page) => legend(page).getByTestId('preview-legend-item');

async function preview(page: Page) {
  await page.getByTestId('preview-toggle').locator('input').click({ force: true });
  await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');
}

test.describe('14-S5-8 Preview legend', () => {
  test.use({ viewport: { width: 1440, height: 1000 } });

  test('none with Preview off, or in Preview with no error or warning cells', async ({ page }) => {
    await open(page, bothGrid());
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'build');
    await expect(legend(page)).toHaveCount(0);

    await open(page, createGrid({ cols: 15, rows: 15 }));
    await preview(page);
    await expect(legend(page)).toHaveCount(0);
  });

  test('warning cells only: the warning item alone', async ({ page }) => {
    await open(page, warningsGrid());
    await preview(page);
    await expect(items(page)).toHaveText([WARNING_TEXT]);
    expect(await bg(cell(page, '0,0')), 'the warning cell').toBe(PREVIEW_WARNING);
    expect(await bg(items(page).getByTestId('preview-legend-dot'))).toBe(PREVIEW_WARNING);
  });

  test('error cells only: the error item alone', async ({ page }) => {
    await open(page, dailyGrid());
    await preview(page);
    await expect(items(page)).toHaveText([ERROR_TEXT]);
    expect(await bg(items(page).getByTestId('preview-legend-dot'))).toBe(PREVIEW_ERROR);
  });

  test('both: error first, then warning', async ({ page }) => {
    await open(page, bothGrid());
    await preview(page);
    expect(await bg(cell(page, '9,9')), 'the error cell').toBe(PREVIEW_ERROR);
    await expect(items(page)).toHaveText([ERROR_TEXT, WARNING_TEXT]);
    const dots = items(page).getByTestId('preview-legend-dot');
    expect(await bg(dots.nth(0))).toBe(PREVIEW_ERROR);
    expect(await bg(dots.nth(1))).toBe(PREVIEW_WARNING);
  });

  test('24px round dots, 6px to the text, 20px between items, 16px below the grid', async ({ page }) => {
    await open(page, bothGrid());
    await preview(page);
    const g = await box(grid(page));
    const [first, second] = [items(page).nth(0), items(page).nth(1)];
    const dot1 = await box(first.getByTestId('preview-legend-dot'));
    const dot2 = await box(second.getByTestId('preview-legend-dot'));
    const text1 = await box(first.getByTestId('preview-legend-text'));
    const text2 = await box(second.getByTestId('preview-legend-text'));

    for (const dot of [dot1, dot2]) {
      expect(dot.width).toBeCloseTo(24, 0);
      expect(dot.height).toBeCloseTo(24, 0);
    }
    expect(await style(first.getByTestId('preview-legend-dot'), 'border-radius')).not.toBe('0px');
    expect(text1.x - (dot1.x + dot1.width), 'dot to text').toBeCloseTo(6, 0);
    expect(text2.x - (dot2.x + dot2.width), 'dot to text').toBeCloseTo(6, 0);
    expect(dot2.x - (text1.x + text1.width), 'between items').toBeCloseTo(20, 0);
    expect(dot1.x, 'level with the grid').toBeCloseTo(g.x, 0);
    expect(dot1.y - (g.y + g.height), 'below the grid').toBeCloseTo(16, 0);
    expect(dot2.y, 'one row').toBeCloseTo(dot1.y, 0);
  });

  test('the text is body-normal in primary', async ({ page }) => {
    await open(page, bothGrid());
    await preview(page);
    const text = items(page).first().getByTestId('preview-legend-text');
    expect(await style(text, 'font-size')).toBe('14px');
    expect(await style(text, 'font-weight')).toBe('400');
    expect(await style(text, 'line-height')).toBe('20px');
    expect(await style(text, 'color')).toBe(PRIMARY);
  });

  test('it goes when Preview is turned off', async ({ page }) => {
    await open(page, bothGrid());
    await preview(page);
    await expect(legend(page)).toBeVisible();
    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'build');
    await expect(legend(page)).toHaveCount(0);
  });

  test("the style guide's Preview sample shows its legend", async ({ page }) => {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-grid-preview').getByTestId('preview-legend-item')).toHaveText([ERROR_TEXT]);
  });
});
