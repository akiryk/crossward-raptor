// 16-S3 acceptance: deleting published puzzles.
//
// The Build row's menu offers Delete on published rows too, after the
// visibility item. For a published puzzle the existing "Delete puzzle?"
// dialog also says other players lose their progress. A link to a puzzle
// that isn't there, in play or the editor, shows a "no longer available"
// page with a way back to /puzzles. A player whose save fails because the
// puzzle was deleted is told so in place of the generic save error.
//
// The suite shares one database, so rows are found by unique titles, never by
// position or count. Do not edit this file to match an implementation.

const FOCUS_RING = 'solid 2px rgb(0, 240, 255) offset 0px';
const PUBLISHED_WARNING = 'Everyone who has played it, including other players, loses their progress.';
const GONE = 'This puzzle is no longer available.';
const GONE_DETAIL = 'It may have been deleted, or the link may be wrong.';

type Rgb = { r: number; g: number; b: number };

function rgbOf(value: string): Rgb {
  const m = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (!m) throw new Error(`unparseable colour: "${value}"`);
  return { r: Number(m[1]), g: Number(m[2]), b: Number(m[3]) };
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string): Promise<Rgb> {
  return rgbOf(await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style));
}

async function colorOf(locator: Locator) {
  return rgbOf(await locator.evaluate((el) => getComputedStyle(el).color));
}

async function expectTextStyle(page: Page, locator: Locator, style: string, label: string) {
  const expected = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.fontWeight = `var(--text-${s}--font-weight)`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const c = getComputedStyle(probe);
    const resolved = { fontSize: c.fontSize, fontWeight: c.fontWeight, lineHeight: c.lineHeight };
    probe.remove();
    return resolved;
  }, style);
  const actual = await locator.evaluate((el) => {
    const c = getComputedStyle(el);
    return { fontSize: c.fontSize, fontWeight: c.fontWeight, lineHeight: c.lineHeight };
  });
  expect(actual, `${label} ${style}`).toEqual(expected);
}

/** The element's settled outline: "none", or style, width, color and offset. */
function ringOf(locator: Locator) {
  return locator.evaluate(async (el) => {
    await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
    const s = getComputedStyle(el);
    const transparent = /rgba\(.*,\s*0\)$|transparent/.test(s.outlineColor);
    if (s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0 || transparent) return 'none';
    return `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor} offset ${s.outlineOffset}`;
  });
}

/** Page-relative box. */
async function box(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { x: r.left + window.scrollX, y: r.top + window.scrollY, width: r.width, height: r.height };
  });
}

/** Gives `target` keyboard focus: focus whatever precedes it, then press Tab. */
async function tabTo(page: Page, target: Locator) {
  await target.evaluate((el) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled])'))
      .filter((candidate) => candidate.tabIndex >= 0);
    const index = all.indexOf(el as HTMLElement);
    if (index > 0) all[index - 1].focus();
    else (document.activeElement as HTMLElement | null)?.blur();
  });
  await page.keyboard.press('Tab');
  await expect(target).toBeFocused();
}

function uniqueTitle(label: string) {
  return `16-S3 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

async function seedOwn(builderId: string, state: BuilderEditState, label: string = state) {
  const title = uniqueTitle(label);
  const { id } = await seedBuilderEditPuzzle(title, builderId, state);
  return { id, title };
}

async function puzzleExists(id: string) {
  const client = ownershipTestClient();
  try {
    return (await client.puzzle.findUnique({ where: { id }, select: { id: true } })) !== null;
  } finally {
    await client.$disconnect();
  }
}

function row(page: Page, title: string) {
  return page.getByTestId('puzzle-list-item').filter({ hasText: title });
}

async function library(page: Page) {
  await page.goto('/puzzles');
  await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
}

async function showView(page: Page, view: 'Build' | 'Play') {
  const option = page.getByTestId('library-view').getByRole('radio', { name: view, exact: true });
  await option.check();
  await expect(option).toBeChecked();
}

const trigger = (item: Locator) => item.getByTestId('puzzle-menu-button');
const menu = (page: Page) => page.getByTestId('puzzle-menu');
const dialog = (page: Page) => page.getByTestId('puzzle-delete-dialog');

async function openMenu(page: Page, item: Locator) {
  await trigger(item).click();
  await expect(menu(page)).toBeVisible();
}

async function chooseDelete(page: Page, item: Locator) {
  await openMenu(page, item);
  await menu(page).getByTestId('puzzle-menu-delete').click();
  await expect(dialog(page)).toBeVisible();
}

async function openPlay(page: Page, id: string) {
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
  await expect(page.getByTestId('play-grid-region')).toHaveAttribute('data-ready', 'true');
}

async function cellLetter(page: Page, coord: string) {
  return page.locator(`[data-coord="${coord}"]`).evaluate((element) => {
    const clone = element.cloneNode(true) as HTMLElement;
    clone.querySelectorAll('[data-testid="cell-number"]').forEach((number) => number.remove());
    return clone.textContent?.trim() ?? '';
  });
}

/** One letter typed in seedPlayPuzzle's 3×3 fixture. */
const partial: SerializedGrid = {
  cols: 3, rows: 3,
  cells: [
    [{ kind: 'active', letter: 'C' }, { kind: 'active', letter: null }, { kind: 'active', letter: null }],
    [{ kind: 'active', letter: null }, { kind: 'black' }, { kind: 'active', letter: null }],
    [{ kind: 'active', letter: null }, { kind: 'active', letter: null }, { kind: 'active', letter: null }],
  ],
};

/** A signed-in second player in their own browser context. */
async function withPlayer<T>(page: Page, run: (player: Page, playerId: string) => Promise<T>) {
  const context = await page.context().browser()!.newContext({ storageState: { cookies: [], origins: [] } });
  try {
    const player = await context.newPage();
    await signInSeededUser(player);
    return await run(player, await currentBuilderId(player));
  } finally {
    await context.close();
  }
}

/** The "no longer available" page, in place at `path`. */
async function expectGonePage(page: Page, path: string) {
  const response = await page.goto(path);
  expect(response?.status(), `${path} is a 404`).toBe(404);
  expect(new URL(page.url()).pathname, `${path} stays put`).toBe(path);
  const gone = page.getByTestId('puzzle-not-found');
  await expect(gone).toBeVisible();
  await expect(gone.getByRole('heading', { level: 1 })).toHaveText(GONE);
  await expect(gone).toContainText(GONE_DETAIL);
  await expect(gone).not.toContainText('Puzzle not found');
  const back = gone.getByRole('link', { name: 'Back to puzzles', exact: true });
  await expect(back).toHaveAttribute('href', '/puzzles');
  await expect(page.getByTestId('play-puzzle')).toHaveCount(0);
  await expect(page.getByTestId('puzzle-editor')).toHaveCount(0);
  await expect(page.getByTestId('grid-cell')).toHaveCount(0);
  return { gone, back };
}

test.describe('16-S3-1 Delete on published rows', () => {
  test('the menu offers Delete after the visibility item on published rows, and Delete alone on unpublished ones', async ({ page }) => {
    const me = await currentBuilderId(page);
    for (const [state, expected] of [
      ['grid', ['Delete']],
      ['hints', ['Delete']],
      ['private published', ['Make public', 'Delete']],
      ['public published', ['Make unlisted', 'Delete']],
    ] as const) {
      const fixture = await seedOwn(me, state);
      await library(page);
      await openMenu(page, row(page, fixture.title));
      const entries = menu(page).getByRole('menuitem');
      expect((await entries.allTextContents()).map((text) => text.trim()), state).toEqual(expected);
      await expect(entries.last(), state).toHaveAttribute('data-testid', 'puzzle-menu-delete');
      await expect(entries.last()).toHaveAccessibleName('Delete');
      expect(await colorOf(entries.last()), `${state}: Delete is error`).toEqual(await token(page, 'error'));
      await page.keyboard.press('Escape');
    }
  });
});

test.describe('16-S3-2 the confirmation', () => {
  test('for a published puzzle, the dialog also says other players lose their progress; for an unpublished one it does not', async ({ page }) => {
    const me = await currentBuilderId(page);
    for (const state of ['private published', 'public published'] as const) {
      const fixture = await seedOwn(me, state);
      await library(page);
      await chooseDelete(page, row(page, fixture.title));
      await expect(dialog(page)).toHaveAccessibleName('Delete puzzle?');
      await expect(dialog(page)).toContainText(`This deletes ${fixture.title}.`);
      await expect(dialog(page), state).toContainText(PUBLISHED_WARNING);
      await expect(dialog(page)).toContainText('This cannot be undone.');
      await expect(page.getByTestId('puzzle-delete-confirm')).toHaveAccessibleName('Delete puzzle');
      await expect(page.getByTestId('puzzle-delete-cancel')).toHaveAccessibleName('Cancel');
      await page.getByTestId('puzzle-delete-cancel').click();
    }
    for (const state of ['grid', 'hints'] as const) {
      const fixture = await seedOwn(me, state);
      await library(page);
      await chooseDelete(page, row(page, fixture.title));
      await expect(dialog(page)).toContainText(`This deletes ${fixture.title}. This cannot be undone.`);
      await expect(dialog(page), state).not.toContainText(/other players|progress/i);
      await page.getByTestId('puzzle-delete-cancel').click();
    }
  });
});

test.describe('16-S3-3 declining', () => {
  for (const dismissal of ['Cancel', 'Escape', 'backdrop', 'Close'] as const) {
    test(`${dismissal} deletes nothing: the published puzzle and every session stay, and focus returns to the menu button`, async ({ page }) => {
      const me = await currentBuilderId(page);
      const fixture = await seedPlayPuzzle({ builderId: me, visibility: 'public' });
      await seedPlaySession(await seedOtherBuilder(), fixture.id, deserializeGrid(partial));
      const before = { puzzle: await readPlayPuzzle(fixture.id), sessions: await readPlaySessions(fixture.id) };
      await library(page);
      const item = row(page, fixture.title);
      await chooseDelete(page, item);

      if (dismissal === 'Cancel') await page.getByTestId('puzzle-delete-cancel').click();
      else if (dismissal === 'Escape') await page.keyboard.press('Escape');
      else if (dismissal === 'backdrop') await page.getByTestId('modal-backdrop').click({ position: { x: 2, y: 2 } });
      else await dialog(page).getByTestId('modal-close').click();

      await expect(dialog(page)).toHaveCount(0);
      await expect(item).toHaveCount(1);
      await expect(trigger(item)).toBeFocused();
      expect(await readPlayPuzzle(fixture.id)).toEqual(before.puzzle);
      expect(await readPlaySessions(fixture.id)).toEqual(before.sessions);
    });
  }
});

test.describe('16-S3-4 confirming', () => {
  test('deletes the published puzzle and every session for it, in place, and it leaves both views', async ({ page }) => {
    const me = await currentBuilderId(page);
    const doomed = await seedPlayPuzzle({ builderId: me, visibility: 'public' });
    const kept = await seedPlayPuzzle({ builderId: me, visibility: 'public' });
    const other = await seedOtherBuilder();
    await seedPlaySession(me, doomed.id, deserializeGrid(partial));
    await seedPlaySession(other, doomed.id, deserializeGrid(partial));
    await seedPlaySession(other, kept.id, deserializeGrid(partial));
    expect(await readPlaySessions(doomed.id)).toHaveLength(2);
    const keptBefore = { puzzle: await readPlayPuzzle(kept.id), sessions: await readPlaySessions(kept.id) };

    await library(page);
    await page.evaluate(() => { (window as unknown as { s3Marker: boolean }).s3Marker = true; });
    await chooseDelete(page, row(page, doomed.title));
    await page.getByTestId('puzzle-delete-confirm').click();

    await expect(dialog(page)).toHaveCount(0);
    await expect(row(page, doomed.title)).toHaveCount(0);
    await expect(row(page, kept.title)).toHaveCount(1);
    await expect(page.getByTestId('page-heading')).toBeFocused();
    await expect.poll(() => puzzleExists(doomed.id)).toBe(false);
    expect(await readPlaySessions(doomed.id)).toEqual([]);
    expect(await readPlayPuzzle(kept.id)).toEqual(keptBefore.puzzle);
    expect(await readPlaySessions(kept.id)).toEqual(keptBefore.sessions);

    await showView(page, 'Play');
    await expect(row(page, kept.title)).toHaveCount(1);
    await expect(row(page, doomed.title)).toHaveCount(0);
    expect(await page.evaluate(() => (window as unknown as { s3Marker?: boolean }).s3Marker), 'no reload').toBe(true);
    await expect(page).toHaveURL(/\/puzzles$/);
  });
});

test.describe('16-S3-5 the "no longer available" page', () => {
  test('a deleted puzzle’s play and editor links, and an unknown ID, show it with a way back to /puzzles', async ({ page }) => {
    const me = await currentBuilderId(page);
    const deleted = await seedPlayPuzzle({ builderId: me });
    await deletePlayFixture(deleted.id);
    expect(await puzzleExists(deleted.id)).toBe(false);

    for (const path of [
      `/puzzles/${deleted.id}/play`,
      `/puzzles/${deleted.id}`,
      '/puzzles/16-s3-never-existed',
      '/puzzles/16-s3-never-existed/play',
    ]) {
      await expectGonePage(page, path);
    }

    const { back } = await expectGonePage(page, `/puzzles/${deleted.id}/play`);
    await back.click();
    await expect(page).toHaveURL(/\/puzzles$/);
    await expect(page.getByTestId('puzzle-library')).toBeVisible();
  });

  test('its design: a title-2 heading, a muted line 8px below, and a link 16px below that', async ({ page }) => {
    const { gone, back } = await expectGonePage(page, '/puzzles/16-s3-never-existed-design');
    const heading = gone.getByRole('heading', { level: 1 });
    const detail = gone.getByText(GONE_DETAIL, { exact: true });

    await expectTextStyle(page, heading, 'title-2', 'heading');
    expect(await colorOf(heading), 'heading is primary').toEqual(await token(page, 'primary'));
    await expectTextStyle(page, detail, 'body-normal', 'detail');
    expect(await colorOf(detail), 'detail is muted').toEqual(await token(page, 'muted'));
    await expectTextStyle(page, back, 'body-normal', 'link');
    expect(await colorOf(back), 'link is button-fill').toEqual(await token(page, 'button-fill'));
    expect(await back.evaluate((el) => getComputedStyle(el).textDecorationLine)).toBe('underline');

    const h = await box(heading);
    const d = await box(detail);
    const b = await box(back);
    // The link may be inline: its line box is centred on its text box.
    const lineHeight = parseFloat(await back.evaluate((el) => getComputedStyle(el).lineHeight));
    const linkLineTop = b.y + b.height / 2 - lineHeight / 2;
    expect(d.y - (h.y + h.height), 'detail is 8px below the heading').toBeCloseTo(8, 0);
    // Within 1px: an inline text box's centre carries font-metric rounding.
    expect(Math.abs(linkLineTop - (d.y + d.height) - 16), 'link is 16px below the detail').toBeLessThanOrEqual(1);

    await back.hover();
    await expect.poll(async () => colorOf(back), { message: 'link is button-hover on hover' })
      .toEqual(await token(page, 'button-hover'));
    await page.mouse.move(0, 0);
    await tabTo(page, back);
    expect(await ringOf(back), 'keyboard focus shows the ring').toBe(FOCUS_RING);
  });
});

test.describe('16-S3-6 a player mid-solve', () => {
  test('after the builder deletes the puzzle, the player’s next save says it is no longer available, editing stops, and it is gone on reload and from Play', async ({ page }) => {
    const me = await currentBuilderId(page);
    const fixture = await seedPlayPuzzle({ builderId: me, visibility: 'public' });

    await withPlayer(page, async (player, playerId) => {
      await seedPlaySession(playerId, fixture.id, deserializeGrid(partial));
      await openPlay(player, fixture.id);

      await library(page);
      await chooseDelete(page, row(page, fixture.title));
      await page.getByTestId('puzzle-delete-confirm').click();
      await expect(row(page, fixture.title)).toHaveCount(0);
      await expect.poll(() => puzzleExists(fixture.id)).toBe(false);

      let actions = 0;
      player.on('request', (request) => {
        if (request.method() === 'POST' && request.headers()['next-action']) actions++;
      });
      await player.locator('[data-coord="2,0"]').click();
      await player.keyboard.type('t');

      const unavailable = player.getByTestId('play-unavailable');
      await expect(unavailable).toBeVisible();
      await expect(unavailable).toHaveAttribute('role', 'alert');
      await expect(unavailable).toContainText(GONE);
      const back = unavailable.getByRole('link', { name: 'Back to puzzles', exact: true });
      await expect(back).toHaveAttribute('href', '/puzzles');
      await expectTextStyle(player, unavailable, 'body-small', 'message');
      expect(await colorOf(unavailable), 'message is error').toEqual(await token(player, 'error'));
      expect(await colorOf(back), 'link is button-fill').toEqual(await token(player, 'button-fill'));
      await expect(player.getByTestId('play-puzzle')).not.toContainText('We couldn’t save your entries.');
      await expect(player.getByTestId('play-puzzle')).not.toContainText('We couldn’t verify your entries.');
      await expect(player.getByTestId('play-puzzle').getByRole('button', { name: 'Retry', exact: true })).toHaveCount(0);
      expect(actions, 'only the failed save: the check is not a server action').toBe(1);

      // Editing stops; the letters already shown stay.
      await expect.poll(() => cellLetter(player, '2,0')).toBe('T');
      await player.locator('[data-coord="0,2"]').click();
      await player.keyboard.type('x');
      await player.waitForTimeout(800);
      expect(await cellLetter(player, '0,2')).toBe('');
      expect(actions, 'no further save after the puzzle is gone').toBe(1);

      await player.reload();
      await expect(player.getByTestId('puzzle-not-found')).toBeVisible();
      await expect(player.getByTestId('puzzle-not-found').getByRole('heading', { level: 1 })).toHaveText(GONE);

      await library(player);
      await showView(player, 'Play');
      await expect(row(player, fixture.title)).toHaveCount(0);
    });
  });

  test('a save that fails while the puzzle still exists, or whose availability check fails, keeps the generic save error', async ({ page }) => {
    const fixture = await seedPlayPuzzle({ builderId: await seedOtherBuilder(), visibility: 'public' });
    await openPlay(page, fixture.id);

    // The puzzle exists: the save fails for another reason.
    let failSave = true;
    await page.route(`**/puzzles/${fixture.id}/play`, async (route) => {
      if (failSave && route.request().headers()['next-action']) {
        failSave = false;
        return route.abort('failed');
      }
      return route.continue();
    });
    await page.locator('[data-coord="1,0"]').click();
    await page.keyboard.type('a');
    const status = page.getByTestId('play-save-status');
    await expect(status).toHaveAttribute('data-save-state', 'error');
    await expect(status).toContainText('We couldn’t save your entries.');
    await page.waitForTimeout(800);
    await expect(page.getByTestId('play-unavailable')).toHaveCount(0);
    await status.getByRole('button', { name: 'Retry', exact: true }).click();
    await expect(status).toHaveAttribute('data-save-state', 'saved');
    await page.unroute(`**/puzzles/${fixture.id}/play`);

    // The puzzle is gone, but the check itself fails: nothing proves it's gone.
    await deletePlayFixture(fixture.id);
    await page.route(`**/puzzles/${fixture.id}/play`, async (route) => {
      if (route.request().headers()['next-action']) return route.continue();
      return route.abort('failed');
    });
    await page.locator('[data-coord="2,0"]').click();
    await page.keyboard.type('b');
    await expect(status).toHaveAttribute('data-save-state', 'error');
    await expect(status).toContainText('We couldn’t save your entries.');
    await page.waitForTimeout(800);
    await expect(page.getByTestId('play-unavailable')).toHaveCount(0);
  });
});
