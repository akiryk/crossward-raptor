import { test, expect, type Locator, type Page } from '@playwright/test';
import { seedBuilderEditPuzzle } from './helpers/builder-edits';
import { currentBuilderId } from './helpers/ownership';
import { signInSeededUser } from './helpers/seed-session';

// Story 19-S2 — room below the puzzles.
//
// On /puzzles, the list of rows (`puzzle-list`) has a 32px bottom margin,
// so the last row ends 32px above the bottom of the hairline
// (`puzzle-library`'s left border), and `puzzle-library` has a 32px bottom
// margin, so the page ends 32px below the hairline. Wide (1280px) and
// narrow (400px), with a list taller than the container's 630px minimum
// and with a short one. The row colors and Sign out are checked in
// done-icon, status-icons, color-tokens and masthead.
//
// Do not edit this file to match an implementation.

async function freshBuilder(page: Page, width: number) {
  await page.setViewportSize({ width, height: 800 });
  await signInSeededUser(page);
  return currentBuilderId(page);
}

async function openLibrary(page: Page) {
  await page.goto('/puzzles');
  await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
}

/** A box in page coordinates. */
async function pageBox(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { top: r.top + window.scrollY, bottom: r.bottom + window.scrollY };
  });
}

async function expectBottomSpace(page: Page) {
  const library = page.getByTestId('puzzle-library');
  const list = page.getByTestId('puzzle-list');
  expect(await list.evaluate((el) => getComputedStyle(el).marginBottom), 'the list').toBe('32px');
  expect(await library.evaluate((el) => getComputedStyle(el).marginBottom), 'puzzle-library').toBe('32px');
  expect(await library.evaluate((el) => getComputedStyle(el).borderLeftWidth), 'the hairline').toBe('1px');

  const l = await pageBox(library);
  const height = await page.evaluate(() => document.documentElement.scrollHeight);
  expect(height - l.bottom, 'the page ends 32px below the hairline').toBeCloseTo(32, 0);
  return l;
}

for (const width of [1280, 400]) {
  test.describe(`19-S2-1 at ${width}px`, () => {
    test('a long list: the last row 32px above the hairline\'s end, the page 32px below it', async ({ page }) => {
      const me = await freshBuilder(page, width);
      for (let i = 0; i < 12; i++) {
        await seedBuilderEditPuzzle(`S2 bottom ${i} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`, me, 'grid');
      }
      await openLibrary(page);
      const rows = page.getByTestId('puzzle-list-item');
      expect(await rows.count()).toBeGreaterThanOrEqual(12);
      const l = await expectBottomSpace(page);
      const last = await pageBox(rows.last());
      const list = await pageBox(page.getByTestId('puzzle-list'));
      expect(list.bottom - last.bottom, 'the last row ends the list').toBeCloseTo(0, 0);
      expect(l.bottom - last.bottom, 'the last row to the hairline\'s end').toBeCloseTo(32, 0);
    });

    test('a short list: the page still ends 32px below the hairline', async ({ page }) => {
      await freshBuilder(page, width);
      await openLibrary(page);
      await expectBottomSpace(page);
    });
  });
}
