// Story F7 — Title, Logo and Masthead.
//
// Title is a heading: `size` 1 to 4 gives the `title-1` to `title-4` style
// and, unless `as` overrides it, the `h1` to `h4` element; `color` is one
// of the seven text color styles, `primary` by default.
//
// Logo is the human's SVG inline, 172×20: nine cells in a row (`logo-cell`
// fill, 1px `logo` stroke) holding the letters C R O S S W O R D (`logo`).
// The SVG is hidden from assistive technology; hidden text names it
// "Crossward".
//
// Masthead is the app header: a full-width `masthead` bar with a 1px
// `line-muted` hairline along its bottom. The logo, a link home, has 20px
// to the top, the left and the hairline, so the bar is 61px tall. When
// signed in, a "Sign out" link-looking button sits 20px from the right,
// centred on the logo, in `body-large` `link-muted`. Hovering or keyboard
// focus turns the logo's strokes and letters, or Sign out, `button-hover`
// over 150ms `ease-out`, never with a ring.
//
// Style reads wait for the element's running transitions to finish.
// Do not edit this file to match an implementation.

const SENTINEL = '#123456';

type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) {
    return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  }
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: string, expected: Rgba, label: string) {
  const parsed = parseColor(actual);
  expect({ r: parsed.r, g: parsed.g, b: parsed.b }, label).toEqual({
    r: expected.r,
    g: expected.g,
    b: expected.b,
  });
  expect(parsed.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

function styleOf(locator: Locator) {
  return locator.evaluate(async (el) => {
    for (let i = 0; i < 10 && el.getAnimations().length > 0; i++) {
      await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
    }
    const s = getComputedStyle(el);
    return {
      tag: el.tagName.toLowerCase(),
      background: s.backgroundColor,
      color: s.color,
      fill: s.fill,
      stroke: s.stroke,
      strokeWidth: s.strokeWidth,
      borderBottom: `${s.borderBottomStyle} ${s.borderBottomWidth}`,
      borderBottomColor: s.borderBottomColor,
      borderWidths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
      fontSize: parseFloat(s.fontSize),
      fontWeight: Number(s.fontWeight),
      fontFamily: s.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      lineHeight: s.lineHeight,
      textDecoration: s.textDecorationLine,
      boxShadow: s.boxShadow,
      outline:
        s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0
          ? 'none'
          : `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor}`,
    };
  });
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

/** SVG geometry, from the element's own rect (Playwright's box model widens SVG paths). */
function rect(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { x: r.x, y: r.y, width: r.width, height: r.height };
  });
}

async function tokenLineHeight(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const lh = getComputedStyle(probe).lineHeight;
    probe.remove();
    return lh;
  }, style);
}

async function expectTextStyle(page: Page, locator: Locator, style: string, size: number, weight: number, label: string) {
  const s = await styleOf(locator);
  expect(s.fontFamily, `${label} family`).toBe('Inter');
  expect(s.fontSize, `${label} size`).toBe(size);
  expect(s.fontWeight, `${label} weight`).toBe(weight);
  expect(s.lineHeight, `${label} line height`).toBe(await tokenLineHeight(page, style));
}

async function parkMouse(page: Page) {
  await page.mouse.move(1, 400);
}

/** Focuses an element the way a keyboard user does, so :focus-visible applies. */
async function focusByKeyboard(page: Page, target: Locator) {
  await target.evaluate((el) => el.setAttribute('data-tab-target', ''));
  await page.evaluate(() => {
    const all = Array.from(
      document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input, select, textarea, [tabindex]')
    ).filter((el) => el.tabIndex >= 0);
    const index = all.findIndex((el) => el.hasAttribute('data-tab-target'));
    if (index > 0) {
      all[index - 1].focus();
    } else {
      (document.activeElement as HTMLElement | null)?.blur();
    }
  });
  for (let i = 0; i < 5; i++) {
    await page.keyboard.press('Tab');
    if (await target.evaluate((el) => el === document.activeElement)) break;
  }
  await expect(target).toBeFocused();
  await target.evaluate((el) => el.removeAttribute('data-tab-target'));
}

async function blur(page: Page) {
  await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
}

async function catalog(page: Page) {
  await page.goto('/style-guide');
  for (const id of ['sg-titles', 'sg-logo', 'sg-masthead']) {
    await expect(page.getByTestId(id)).toBeVisible();
  }
  await parkMouse(page);
}

async function puzzles(page: Page) {
  await page.goto('/puzzles');
  await waitForNewPuzzleReady(page);
  await parkMouse(page);
}

function logoParts(scope: Locator) {
  const svg = scope.locator('svg');
  return { svg, cells: svg.locator('[data-logo-cell]'), letters: svg.locator('[data-logo-letter]') };
}

/** Cells are `cellStyle` with a 1px `strokeStyle` stroke; letters are `letterStyle`. */
async function expectLogoColors(page: Page, scope: Locator, strokeStyle: string, cellStyle: string, label: string) {
  const { cells, letters } = logoParts(scope);
  const stroke = await token(page, strokeStyle);
  const cell = await token(page, cellStyle);
  for (let i = 0; i < 9; i++) {
    const c = await styleOf(cells.nth(i));
    expectColor(c.fill, cell, `${label} cell ${i} fill`);
    expectColor(c.stroke, stroke, `${label} cell ${i} stroke`);
    expect(parseFloat(c.strokeWidth), `${label} cell ${i} stroke width`).toBe(1);
    expectColor((await styleOf(letters.nth(i))).fill, stroke, `${label} letter ${i}`);
  }
}

async function expectNoRing(locator: Locator, label: string) {
  const s = await styleOf(locator);
  expect(s.outline, `${label} outline`).toBe('none');
  expect(s.boxShadow, `${label} box shadow`).toBe('none');
}

const TEXT_COLORS = ['primary', 'muted', 'link-muted', 'highlight', 'error', 'subtle', 'inverse'];

// --- F7-1: Title ---
test.describe('F7-1 Title', () => {
  test('each size is its heading element and title style in primary; each color sample is its style; as changes only the element', async ({ page }) => {
    await catalog(page);
    const sizes: [number, number][] = [
      [1, 44],
      [2, 32],
      [3, 18],
      [4, 14],
    ];
    for (const [n, px] of sizes) {
      const sample = page.getByTestId('sg-titles').getByTestId(`sg-title-${n}`);
      expect((await styleOf(sample)).tag, `size ${n} element`).toBe(`h${n}`);
      await expectTextStyle(page, sample, `title-${n}`, px, 600, `size ${n}`);
      expectColor((await styleOf(sample)).color, await token(page, 'primary'), `size ${n} color`);
    }
    for (const color of TEXT_COLORS) {
      const sample = page.getByTestId('sg-titles').getByTestId(`sg-title-${color}`);
      expect((await styleOf(sample)).tag, `${color} element`).toBe('h3');
      await expectTextStyle(page, sample, 'title-3', 18, 600, `${color} sample`);
      expectColor((await styleOf(sample)).color, await token(page, color), `${color} sample color`);
    }
    const as = page.getByTestId('sg-titles').getByTestId('sg-title-as');
    expect((await styleOf(as)).tag, 'as element').toBe('h5');
    await expectTextStyle(page, as, 'title-3', 18, 600, 'as sample');
  });
});

// --- F7-2: Logo ---
test.describe('F7-2 Logo', () => {
  test('a 172×20 SVG of nine logo-cell cells with 1px logo strokes, each holding one logo letter', async ({ page }) => {
    await catalog(page);
    const scope = page.getByTestId('sg-logo');
    const { svg, cells, letters } = logoParts(scope);
    await expect(svg).toHaveCount(1);
    const s = await rect(svg);
    expect(s.width, 'logo width').toBeCloseTo(172, 0);
    expect(s.height, 'logo height').toBeCloseTo(20, 0);
    await expect(cells).toHaveCount(9);
    await expect(letters).toHaveCount(9);

    let previousX = -Infinity;
    for (let i = 0; i < 9; i++) {
      const c = await rect(cells.nth(i));
      expect(c.width, `cell ${i} width`).toBeGreaterThanOrEqual(18.5);
      expect(c.width, `cell ${i} width`).toBeLessThanOrEqual(20.5);
      expect(c.height, `cell ${i} height`).toBeGreaterThanOrEqual(18.5);
      expect(c.height, `cell ${i} height`).toBeLessThanOrEqual(20.5);
      expect(Math.abs(c.y + c.height / 2 - (s.y + s.height / 2)), `cell ${i} in the row`).toBeLessThanOrEqual(1);
      expect(c.x, `cell ${i} right of cell ${i - 1}`).toBeGreaterThan(previousX);
      previousX = c.x;
    }
    // Each cell holds exactly one letter.
    for (let i = 0; i < 9; i++) {
      const l = await rect(letters.nth(i));
      const cx = l.x + l.width / 2;
      const cy = l.y + l.height / 2;
      let holders = 0;
      for (let j = 0; j < 9; j++) {
        const c = await rect(cells.nth(j));
        if (cx > c.x && cx < c.x + c.width && cy > c.y && cy < c.y + c.height) holders++;
      }
      expect(holders, `letter ${i} sits in one cell`).toBe(1);
    }
    await expectLogoColors(page, scope, 'logo', 'logo-cell', 'catalog');
  });

  test('the SVG is hidden from assistive technology and the logo reads "Crossward"', async ({ page }) => {
    await catalog(page);
    const scope = page.getByTestId('sg-logo');
    await expect(logoParts(scope).svg).toHaveAttribute('aria-hidden', 'true');
    await expect(scope.getByText('Crossward', { exact: true })).toHaveCount(1);
  });
});

// --- F7-3: Masthead signed out ---
test.describe('F7-3 Masthead signed out', () => {
  test.use({ storageState: { cookies: [], origins: [] } });

  test('a full-width white bar with a 1px line-muted hairline, 61px tall, with the logo home link 20px from the top, left and hairline', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 800 });
    await page.goto('/');
    await expect(page.getByTestId('front-door')).toBeVisible();
    const header = page.getByTestId('app-header');
    await expect(page.getByRole('banner')).toHaveAttribute('data-testid', 'app-header');

    const h = await styleOf(header);
    expectColor(h.background, await token(page, 'masthead'), 'bar');
    expect(h.borderBottom, 'hairline').toBe('solid 1px');
    expectColor(h.borderBottomColor, await token(page, 'line-muted'), 'hairline');
    expect(h.borderWidths.slice(0, 2).concat(h.borderWidths[3]), 'no other borders').toEqual(['0px', '0px', '0px']);
    const hb = await box(header);
    const viewport = await page.evaluate(() => document.documentElement.clientWidth);
    expect(hb.x, 'bar starts at the left edge').toBeCloseTo(0, 0);
    expect(hb.width, 'bar spans the window').toBeCloseTo(viewport, 0);
    expect(hb.height, 'bar height').toBeCloseTo(61, 0);

    const link = page.getByTestId('home-link');
    await expect(link).toHaveAttribute('href', '/');
    await expect(link).toHaveAccessibleName('Crossward');
    const logo = await rect(logoParts(link).svg);
    expect(logo.y - hb.y, 'logo to top').toBeCloseTo(20, 0);
    expect(logo.x - hb.x, 'logo to left').toBeCloseTo(20, 0);
    expect(hb.y + hb.height - 1 - (logo.y + logo.height), 'logo to hairline').toBeCloseTo(20, 0);
    await expectLogoColors(page, link, 'logo', 'logo-cell', 'masthead');
    await expect(page.getByTestId('sign-out')).toHaveCount(0);
  });
});

// --- F7-4: Masthead signed in ---
test.describe('F7-4 Masthead signed in', () => {
  test('Sign out is a body-large link-muted text button, centred on the logo and 20px from the right', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 800 });
    await puzzles(page);
    const header = page.getByTestId('app-header');
    const signOut = header.getByTestId('sign-out');
    await expect(signOut).toBeVisible();
    await expect(signOut).toHaveText('Sign out');
    expect((await styleOf(signOut)).tag, 'element').toBe('button');

    await expectTextStyle(page, signOut, 'body-large', 18, 400, 'sign out');
    const s = await styleOf(signOut);
    expectColor(s.color, await token(page, 'link-muted'), 'sign out color');
    expect(parseColor(s.background).a, 'no fill').toBe(0);
    expect(s.borderWidths, 'no border').toEqual(['0px', '0px', '0px', '0px']);
    expect(s.textDecoration, 'no underline').toBe('none');
    await expectNoRing(signOut, 'sign out');

    const hb = await box(header);
    expect(hb.height, 'bar height').toBeCloseTo(61, 0);
    const logo = await rect(logoParts(page.getByTestId('home-link')).svg);
    const so = await box(signOut);
    expect(Math.abs(so.y + so.height / 2 - (logo.y + logo.height / 2)), 'centred on the logo').toBeLessThanOrEqual(1.5);
    expect(hb.x + hb.width - (so.x + so.width), 'right inset').toBeCloseTo(20, 0);
  });
});

// --- F7-5: hover and keyboard focus ---
test.describe('F7-5 hover and focus', () => {
  test('hover and keyboard focus turn the logo strokes and letters button-hover, cells unchanged, with no ring', async ({ page }) => {
    await puzzles(page);
    const link = page.getByTestId('home-link');
    await link.hover();
    await expectLogoColors(page, link, 'button-hover', 'logo-cell', 'hovered');
    await parkMouse(page);
    await expectLogoColors(page, link, 'logo', 'logo-cell', 'unhovered');

    await focusByKeyboard(page, link);
    await expectLogoColors(page, link, 'button-hover', 'logo-cell', 'focused');
    await expectNoRing(link, 'focused link');
    await blur(page);
    await expectLogoColors(page, link, 'logo', 'logo-cell', 'blurred');
  });

  test('hover and keyboard focus turn Sign out button-hover, with no ring', async ({ page }) => {
    await puzzles(page);
    const signOut = page.getByTestId('sign-out');
    await signOut.hover();
    expectColor((await styleOf(signOut)).color, await token(page, 'button-hover'), 'hovered');
    await parkMouse(page);
    expectColor((await styleOf(signOut)).color, await token(page, 'link-muted'), 'unhovered');

    await focusByKeyboard(page, signOut);
    expectColor((await styleOf(signOut)).color, await token(page, 'button-hover'), 'focused');
    await expectNoRing(signOut, 'focused sign out');
    await blur(page);
    expectColor((await styleOf(signOut)).color, await token(page, 'link-muted'), 'blurred');
  });

  test('the logo and Sign out change color over 150ms ease-out', async ({ page }) => {
    await puzzles(page);
    const { cells, letters } = logoParts(page.getByTestId('home-link'));
    const parts: [string, Locator, string[]][] = [
      ['logo cell', cells.first(), ['stroke']],
      ['logo letter', letters.first(), ['fill']],
      ['sign out', page.getByTestId('sign-out'), ['color']],
    ];
    for (const [name, locator, properties] of parts) {
      const t = await locator.evaluate((el) => {
        const s = getComputedStyle(el);
        return {
          properties: s.transitionProperty.split(',').map((p) => p.trim()),
          durations: s.transitionDuration.split(',').map((d) => d.trim()),
          timings: s.transitionTimingFunction.split(/,(?![^(]*\))/).map((f) => f.trim()),
        };
      });
      for (const property of properties) {
        let index = t.properties.indexOf(property);
        if (index < 0) index = t.properties.indexOf('all');
        expect(index, `${name} transitions ${property}`).toBeGreaterThanOrEqual(0);
        expect(t.durations[index % t.durations.length], `${name} ${property} duration`).toBe('0.15s');
        // Tailwind's `ease-out`.
        expect(t.timings[index % t.timings.length], `${name} ${property} timing`).toBe('cubic-bezier(0, 0, 0.2, 1)');
      }
    }
  });
});

// --- F7-6: token-driven ---
test.describe('F7-6 token-driven', () => {
  test('live palette edits repaint the logo and the bar, and restore', async ({ page }) => {
    await puzzles(page);
    const sentinel = parseColor('rgb(18, 52, 86)');
    const set = (name: string, value: string | null) =>
      page.evaluate(
        ([n, v]) =>
          v === null
            ? document.documentElement.style.removeProperty(n!)
            : document.documentElement.style.setProperty(n!, v),
        [name, value] as const
      );
    const link = page.getByTestId('home-link');
    const { cells, letters } = logoParts(link);

    await set('--palette-gray-400', SENTINEL);
    expectColor((await styleOf(cells.first())).stroke, sentinel, 'stroke edited');
    expectColor((await styleOf(letters.first())).fill, sentinel, 'letter edited');
    await set('--palette-gray-400', null);
    await expectLogoColors(page, link, 'logo', 'logo-cell', 'gray-400 restored');

    await set('--palette-white', SENTINEL);
    expectColor((await styleOf(cells.first())).fill, sentinel, 'cell edited');
    expectColor((await styleOf(page.getByTestId('app-header'))).background, sentinel, 'bar edited');
    await set('--palette-white', null);
    await expectLogoColors(page, link, 'logo', 'logo-cell', 'white restored');
    expectColor((await styleOf(page.getByTestId('app-header'))).background, await token(page, 'masthead'), 'bar restored');
  });
});

// --- F7-7: catalog and overflow ---
test.describe('F7-7 catalog and overflow', () => {
  test('sg-titles, sg-logo and sg-masthead hold their samples', async ({ page }) => {
    await catalog(page);
    const titles = page.getByTestId('sg-titles');
    for (const id of ['1', '2', '3', '4', ...TEXT_COLORS, 'as']) {
      await expect(titles.getByTestId(`sg-title-${id}`), `sg-title-${id}`).toHaveCount(1);
    }
    await expect(logoParts(page.getByTestId('sg-logo')).svg).toHaveCount(1);
    const masthead = page.getByTestId('sg-masthead');
    const signedOut = masthead.getByTestId('sg-masthead-signed-out');
    const signedIn = masthead.getByTestId('sg-masthead-signed-in');
    await expect(signedOut).toHaveCount(1);
    await expect(signedIn).toHaveCount(1);
    await expect(logoParts(signedOut).svg).toHaveCount(1);
    await expect(logoParts(signedIn).svg).toHaveCount(1);
    await expect(signedOut.getByTestId('sg-masthead-sign-out')).toHaveCount(0);
    await expect(signedIn.getByTestId('sg-masthead-sign-out')).toHaveText('Sign out');
    await expect(masthead.getByTestId('sign-out')).toHaveCount(0);
  });

  test('no horizontal overflow on /style-guide, and the signed-in masthead fits, at 1280px and 375px', async ({ page }) => {
    for (const width of [1280, 375]) {
      await page.setViewportSize({ width, height: 800 });
      await catalog(page);
      const overflow = await page.evaluate(
        () => document.documentElement.scrollWidth - document.documentElement.clientWidth
      );
      expect(overflow, `catalog overflow at ${width}px`).toBeLessThanOrEqual(0);

      // The puzzle list's own overflow isn't F7's; the masthead's is.
      await puzzles(page);
      const header = page.getByTestId('app-header');
      const fit = await header.evaluate((el) => el.scrollWidth - el.clientWidth);
      expect(fit, `masthead overflow at ${width}px`).toBeLessThanOrEqual(0);
      const viewport = await page.evaluate(() => document.documentElement.clientWidth);
      const so = await box(header.getByTestId('sign-out'));
      expect(so.x + so.width, `sign out inside the window at ${width}px`).toBeLessThanOrEqual(viewport);
    }
  });
});
