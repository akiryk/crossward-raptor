import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 17-S4 — Selection in Preview.
//
// In Preview (build phase), the cursor and its word show over Preview's
// own words: the runs of cells Preview doesn't show black (the slots of
// `intendedGeometry`). With the grid focused, the cursor cell is
// `build-cell-selected-cell` and the rest of its word, in the cursor's
// direction, `build-cell-selected-row-on`, whether a cell is an error, a
// warning or lettered. Nothing takes `build-cell-selected-row-off`. Every
// other cell keeps Preview's color, and each cell's `data-cell-state`
// stays Preview's own (`required`, `recommended`, `letter`, `black`).
//
// Preview-black cells can't be selected: a click there changes nothing,
// typing advances only within the Preview word and stops at its end,
// arrows don't move onto them, and Backspace doesn't step back onto them.
// A cell emptied so that Preview shows it black stays selected until the
// cursor leaves it. Turning Preview on while the cursor is on a
// Preview-black cell selects nothing, and keys do nothing, until a cell is
// clicked. Clicking the cursor cell again toggles the direction, and the
// highlight shows only while the grid has focus, as in the build phase.
//
// Colors are read from the styles themselves (`--color-<style>`), so this
// file holds whatever values S5 gives them. Do not edit this file to match
// an implementation.

/**
 * A 5×5 with no black cells: B and C at (1,0) and (2,0), D at (2,1),
 * E at (4,4). Preview shows (col,row):
 *
 *   row 0: (0,0) error, (1,0) letter, (2,0) warning, (3,0) (4,0) black
 *   row 1: (2,1) warning, the rest black
 *   row 2: black
 *   row 3: (2,3) warning, the rest black
 *   row 4: (0,4) (1,4) black, (2,4) warning, (3,4) error, (4,4) letter
 *
 * So 1 Across is (0,0)-(2,0), mixing an error, a letter and a warning
 * (the human's A, B, C); (2,0)-(2,1) is a two-letter Down word; the bottom
 * row's word is (2,4)-(4,4). Every cell is active in the build phase.
 */
function mixedGrid(): Grid {
  let grid = createGrid({ cols: 5, rows: 5 });
  grid = withLetter(grid, { col: 1, row: 0 }, 'B');
  grid = withLetter(grid, { col: 2, row: 0 }, 'C');
  grid = withLetter(grid, { col: 2, row: 1 }, 'D');
  grid = withLetter(grid, { col: 4, row: 4 }, 'E');
  return grid;
}

const ALL = Array.from({ length: 25 }, (_, i) => `${i % 5},${Math.floor(i / 5)}`);

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const grid = (page: Page) => page.getByTestId('puzzle-grid');

function bg(locator: Locator) {
  return locator.evaluate((el) => getComputedStyle(el).backgroundColor);
}

/** A color style's resolved background color. */
function styleColor(page: Page, style: string) {
  return page.evaluate((name) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${name})`;
    document.body.appendChild(probe);
    const color = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return color;
  }, style);
}

async function colors(page: Page) {
  return {
    cursor: await styleColor(page, 'build-cell-selected-cell'),
    word: await styleColor(page, 'build-cell-selected-row-on'),
    rowOff: await styleColor(page, 'build-cell-selected-row-off'),
    on: await styleColor(page, 'preview-cell-on'),
    off: await styleColor(page, 'preview-cell-off'),
    error: await styleColor(page, 'preview-cell-error'),
    warning: await styleColor(page, 'preview-cell-warning'),
  };
}
type Colors = Awaited<ReturnType<typeof colors>>;

async function open(page: Page) {
  const { id } = await seedPuzzle({ grid: mixedGrid(), hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function previewOn(page: Page) {
  await page.getByTestId('preview-toggle').locator('input').click({ force: true });
  await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');
}

/** Exactly `cursor` is selected and exactly `word` (the other cells of its
 *  word) is highlighted, in their colors; every other cell has neither. */
async function expectSelection(page: Page, c: Colors, cursor: string, word: string[]) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(1);
  await expect(cell(page, cursor)).toHaveAttribute('data-selected', 'true');
  await expect(page.locator('[data-highlight="slot"]')).toHaveCount(word.length);
  for (const coord of word) {
    await expect(cell(page, coord)).toHaveAttribute('data-highlight', 'slot');
  }
  expect(await bg(cell(page, cursor)), `the cursor ${cursor}`).toBe(c.cursor);
  for (const coord of word) {
    expect(await bg(cell(page, coord)), `the word's ${coord}`).toBe(c.word);
  }
}

async function expectNoSelection(page: Page) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(0);
  await expect(page.locator('[data-highlight]')).toHaveCount(0);
}

/** Unselected cells in Preview's own colors. */
async function expectPreviewColors(page: Page, c: Colors, expected: Record<string, keyof Colors>) {
  for (const [coord, color] of Object.entries(expected)) {
    expect(await bg(cell(page, coord)), `${coord} is ${color}`).toBe(c[color]);
  }
}

test.describe('17-S4-1 a click selects its Preview word: error, warning and lettered cells together', () => {
  test('clicking any of 1 Across’s three cells highlights all three, the clicked one as the cursor', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    // The cursor starts on (0,0), Across; clicking (0,0) first would toggle.
    for (const clicked of ['1,0', '2,0', '0,0']) {
      await cell(page, clicked).click();
      const word = ['0,0', '1,0', '2,0'].filter((coord) => coord !== clicked);
      await expectSelection(page, c, clicked, word);
    }

    // Each cell keeps Preview's own state.
    await expect(cell(page, '0,0')).toHaveAttribute('data-cell-state', 'required');
    await expect(cell(page, '1,0')).toHaveAttribute('data-cell-state', 'letter');
    await expect(cell(page, '2,0')).toHaveAttribute('data-cell-state', 'recommended');

    // The rest keep Preview's colors, and nothing is row-off.
    await expectPreviewColors(page, c, {
      '3,0': 'off',
      '4,0': 'off',
      '2,1': 'warning',
      '2,2': 'off',
      '3,4': 'error',
      '4,4': 'on',
    });
    for (const coord of ALL) {
      expect(await bg(cell(page, coord)), `${coord} is never row-off`).not.toBe(c.rowOff);
    }
  });
});

test.describe('17-S4-2 direction, as in the build phase', () => {
  test('clicking the cursor cell again selects its Down word, and again Across', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '2,0').click();
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);

    await cell(page, '2,0').click();
    await expectSelection(page, c, '2,0', ['2,1']);
    await expectPreviewColors(page, c, { '0,0': 'error', '1,0': 'on' });

    await cell(page, '2,0').click();
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);
    await expectPreviewColors(page, c, { '2,1': 'warning' });
  });

  test('where no Preview word runs that way, only the cursor cell is selected', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '3,4').click();
    await expectSelection(page, c, '3,4', ['2,4', '4,4']);

    await cell(page, '3,4').click();
    await expectSelection(page, c, '3,4', []);
    await expectPreviewColors(page, c, { '2,4': 'warning', '4,4': 'on', '3,3': 'off' });
  });
});

test.describe('17-S4-3 Preview-black cells can’t be selected', () => {
  test('clicking one changes nothing', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '1,0').click();
    for (const black of ['3,0', '2,2', '0,4']) {
      await cell(page, black).click();
      await expectSelection(page, c, '1,0', ['0,0', '2,0']);
      expect(await bg(cell(page, black)), `${black} stays black`).toBe(c.off);
    }

    // Typing still goes to the cursor.
    await page.keyboard.type('x');
    await expect(cell(page, '1,0')).toContainText('X');
    for (const black of ['3,0', '2,2', '0,4']) {
      await expect(cell(page, black)).not.toContainText(/[A-Z]/);
    }
  });
});

test.describe('17-S4-4 typing advances only within the Preview word', () => {
  test('Across, it stops at the word’s last cell', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '1,0').click();
    await page.keyboard.type('x');
    await expect(cell(page, '1,0')).toContainText('X');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);

    await page.keyboard.type('y');
    await expect(cell(page, '2,0')).toContainText('Y');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);

    await page.keyboard.type('z');
    await expect(cell(page, '2,0')).toContainText('Z');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);
    await expect(cell(page, '3,0')).not.toContainText(/[A-Z]/);
    expect(await bg(cell(page, '3,0'))).toBe(c.off);
  });

  test('Down, likewise', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '2,0').click();
    await cell(page, '2,0').click();
    await page.keyboard.type('q');
    await expect(cell(page, '2,0')).toContainText('Q');
    await expectSelection(page, c, '2,1', ['2,0']);

    await page.keyboard.type('r');
    await expect(cell(page, '2,1')).toContainText('R');
    await expectSelection(page, c, '2,1', ['2,0']);
    await expect(cell(page, '2,2')).not.toContainText(/[A-Z]/);
  });

  test('with Preview off, typing advances over the same cells as before (guard)', async ({ page }) => {
    await open(page);
    await cell(page, '2,0').click();
    await page.keyboard.type('y');
    await expect(cell(page, '3,0')).toHaveAttribute('data-selected', 'true');
  });
});

test.describe('17-S4-5 arrows don’t move onto Preview-black cells', () => {
  test('the cursor stays at a word’s end; a cross-axis arrow turns it', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '1,0').click();
    await page.keyboard.press('ArrowRight');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);
    await page.keyboard.press('ArrowRight');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);

    await page.keyboard.press('ArrowDown');
    await expectSelection(page, c, '2,0', ['2,1']);
    await page.keyboard.press('ArrowDown');
    await expectSelection(page, c, '2,1', ['2,0']);
    await page.keyboard.press('ArrowDown');
    await expectSelection(page, c, '2,1', ['2,0']);
    await page.keyboard.press('ArrowUp');
    await expectSelection(page, c, '2,0', ['2,1']);

    await page.keyboard.press('ArrowLeft');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);
    await page.keyboard.press('ArrowLeft');
    await page.keyboard.press('ArrowLeft');
    await expectSelection(page, c, '0,0', ['1,0', '2,0']);
    await page.keyboard.press('ArrowLeft');
    await expectSelection(page, c, '0,0', ['1,0', '2,0']);
  });
});

test.describe('17-S4-6 Backspace', () => {
  test('on an empty cell at a word’s start, it doesn’t step back onto a Preview-black cell', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '2,4').click();
    await expectSelection(page, c, '2,4', ['3,4', '4,4']);
    await page.keyboard.press('Backspace');
    await expectSelection(page, c, '2,4', ['3,4', '4,4']);
    expect(await bg(cell(page, '1,4'))).toBe(c.off);
  });

  test('a cell emptied so that Preview shows it black stays selected until the cursor leaves it', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    // Emptying B leaves (1,0) and its counterpart (3,4) black in Preview,
    // and (0,0) in no Across word.
    await cell(page, '1,0').click();
    await page.keyboard.press('Backspace');
    await expect(cell(page, '1,0')).not.toContainText(/[A-Z]/);
    await expect(cell(page, '1,0')).toHaveAttribute('data-cell-state', 'black');
    await expectSelection(page, c, '1,0', []);
    await expectPreviewColors(page, c, { '0,0': 'error', '2,0': 'warning', '3,4': 'off' });

    // Typing there brings the word back and advances.
    await page.keyboard.type('b');
    await expect(cell(page, '1,0')).toContainText('B');
    await expectSelection(page, c, '2,0', ['0,0', '1,0']);

    // Emptying C: (2,0) stays selected; once the cursor leaves, it's black
    // and a click can't select it.
    await page.keyboard.press('Backspace');
    await expect(cell(page, '2,0')).not.toContainText(/[A-Z]/);
    await expectSelection(page, c, '2,0', []);
    await page.keyboard.press('ArrowLeft');
    await expectSelection(page, c, '1,0', ['0,0']);
    expect(await bg(cell(page, '2,0'))).toBe(c.off);
    await cell(page, '2,0').click();
    await expectSelection(page, c, '1,0', ['0,0']);
  });
});

test.describe('17-S4-7 Preview turned on with the cursor on a Preview-black cell', () => {
  test('selects nothing, and keys do nothing, until a cell is clicked', async ({ page }) => {
    await open(page);
    const c = await colors(page);

    await cell(page, '3,0').click();
    await expect(cell(page, '3,0')).toHaveAttribute('data-selected', 'true');
    await previewOn(page);

    await page.getByTestId('grid-region').focus();
    await expect(page.getByTestId('grid-region')).toBeFocused();
    await expectNoSelection(page);

    for (const key of ['z', 'ArrowLeft', 'ArrowDown', ' ', 'Backspace']) {
      await page.keyboard.press(key);
    }
    await expectNoSelection(page);
    await expect(cell(page, '3,0')).not.toContainText(/[A-Z]/);
    await expect(cell(page, '2,0')).toContainText('C');
    await expect(cell(page, '1,0')).toContainText('B');

    await cell(page, '1,0').click();
    await expectSelection(page, c, '1,0', ['0,0', '2,0']);
  });

  test('turning Preview off shows the build cursor where it was (guard)', async ({ page }) => {
    await open(page);

    await cell(page, '3,0').click();
    await previewOn(page);
    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'build');

    await page.getByTestId('grid-region').focus();
    await expect(cell(page, '3,0')).toHaveAttribute('data-selected', 'true');
  });
});

test.describe('17-S4-8 the highlight shows only while the grid has focus', () => {
  test('focus elsewhere shows Preview’s colors; focus back shows the word again', async ({ page }) => {
    await open(page);
    await previewOn(page);
    const c = await colors(page);

    await cell(page, '1,0').click();
    await expectSelection(page, c, '1,0', ['0,0', '2,0']);

    await page.getByTestId('puzzle-title').click();
    await expectNoSelection(page);
    await expectPreviewColors(page, c, { '0,0': 'error', '1,0': 'on', '2,0': 'warning' });

    await page.getByTestId('grid-region').focus();
    await expectSelection(page, c, '1,0', ['0,0', '2,0']);
  });
});

test.describe('17-S4-9 the style guide’s selected Preview word', () => {
  test('sg-grid-preview-selected: a cursor and its word mixing error, warning and lettered cells', async ({ page }) => {
    await page.goto('/style-guide');
    const c = await colors(page);
    const sample = page.getByTestId('sg-grid-preview-selected');
    await expect(sample.getByTestId('puzzle-grid')).toHaveAttribute('data-grid-mode', 'preview');

    const selected = sample.locator('[data-selected="true"]');
    await expect(selected).toHaveCount(1);
    expect(await bg(selected)).toBe(c.cursor);

    const highlighted = sample.locator('[data-highlight]');
    const states = new Set<string | null>();
    for (const el of await highlighted.all()) {
      states.add(await el.getAttribute('data-cell-state'));
    }
    expect([...states].sort()).toEqual(['letter', 'recommended', 'required']);
    for (const el of await sample.locator('[data-highlight="slot"]').all()) {
      expect(await bg(el)).toBe(c.word);
    }

    // Unselected cells keep Preview's colors.
    for (const [state, color] of [
      ['black', c.off],
      ['recommended', c.warning],
      ['required', c.error],
    ] as const) {
      const unselected = sample.locator(`[data-cell-state="${state}"]:not([data-highlight])`).first();
      await expect(unselected, `an unselected ${state} cell`).toBeVisible();
      expect(await bg(unselected)).toBe(color);
    }
  });
});
