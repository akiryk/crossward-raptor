import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S4 — the lock button's tooltip.
//
// After about 1 second of mouse hover over the lock button beside a word
// (21-S2), the app's Tooltip shows "Lock this word so you don't
// accidentally change it" for an unlocked word and "Enable changing this
// word" for a locked one. The delay is 1000ms from the mouse entering the
// button; it hides at once when the mouse leaves or the button goes. A
// click while it shows switches it to the new state's text in place. It
// is placed as Tooltip places it (above the button here, 4px off,
// centered) and never covers the button. Mouse only: keyboard focus and a
// touch tap show none.
//
// Hooks: the tooltip is Tooltip with data-testid "lock-tooltip" (role
// "tooltip"); the button is 21-S2's "Lock word" / "Unlock word".
//
// Timing: "not yet" is checked at once after 500ms of hover (a timer can
// fire late under load, never early); "shown" allows up to 1500ms more.
//
// Do not edit this file to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const UNLOCKED_TEXT = "Lock this word so you don't accidentally change it";
const LOCKED_TEXT = 'Enable changing this word';

/** Hover this long and the tooltip is not shown yet. */
const NOT_YET_MS = 500;
/** After NOT_YET_MS, the tooltip shows within this. */
const SHOWN_WITHIN_MS = 1500;
/** Hiding is "at once". */
const AT_ONCE_MS = 300;

/** A daily: TANGENT across row 3 (cols 3–9). */
function tooltipGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  [...'TANGENT'].forEach((letter, i) => (grid = withLetter(grid, { col: 3 + i, row: 3 }, letter)));
  return grid;
}

const EMPTY = '7,8';

async function open(page: Page) {
  const { id } = await seedPuzzle({ grid: tooltipGrid(), hints: {}, phase: 'grid' }, `21-S4 ${Date.now()}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const tooltip = (page: Page) => page.getByTestId('lock-tooltip');

async function boxOf(locator: Locator) {
  const box = await locator.boundingBox();
  if (!box) throw new Error('no bounding box');
  return { left: box.x, top: box.y, right: box.x + box.width, bottom: box.y + box.height, width: box.width };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

/** The cursor in TANGENT, across, its button shown, the mouse off it. */
async function inTangent(page: Page, coord = '6,3') {
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  await expect(lockButton(page)).toBeVisible();
}

/** No tooltip right now (no waiting for one to go). */
async function expectNone(page: Page, label: string) {
  expect(await tooltip(page).count(), label).toBe(0);
  expect(await page.getByRole('tooltip').count(), `${label} (any tooltip)`).toBe(0);
}

/** Hover the button: nothing at 500ms, then the text by ~1.5s. */
async function hoverUntilShown(page: Page, text: string) {
  await lockButton(page).hover();
  await page.waitForTimeout(NOT_YET_MS);
  await expectNone(page, `no tooltip after ${NOT_YET_MS}ms of hover`);
  await expect(tooltip(page)).toBeVisible({ timeout: SHOWN_WITHIN_MS });
  await expect(tooltip(page)).toHaveCount(1);
  await expect(tooltip(page)).toHaveText(text);
  await expect(page.getByRole('tooltip')).toHaveText(text);
}

/** The mouse to a spot away from the button and the grid's cells. */
async function mouseAway(page: Page) {
  await page.mouse.move(5, 5);
}

test.describe('21-S4 the lock button tooltip', () => {
  test('21-S4-1 unlocked: nothing before ~1s, then the unlocked text above the button', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await expect(lockButton(page)).toHaveAccessibleName('Lock word');
    await expectNone(page, 'no tooltip before hovering');

    await hoverUntilShown(page, UNLOCKED_TEXT);

    // Tooltip's own placement: above, 4px off, centered; never over the button.
    const button = await boxOf(lockButton(page));
    const bubble = await boxOf(tooltip(page));
    expectNear(bubble.bottom, button.top - 4, 1.5, 'bottom 4px above the button');
    expectNear(bubble.left + bubble.width / 2, button.left + button.width / 2, 1.5, 'centered on the button');
    const overlaps =
      bubble.left < button.right && bubble.right > button.left && bubble.top < button.bottom && bubble.bottom > button.top;
    expect(overlaps, 'the tooltip does not cover the button').toBe(false);
  });

  test('21-S4-2 locked: the locked text on a locked word\'s button', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');

    // Away and back: the button shows at once in a locked word.
    await cell(page, EMPTY).click();
    await expect(lockButton(page)).toBeHidden();
    await mouseAway(page);
    await expectNone(page, 'none once the button is gone');
    await inTangent(page, '4,3');
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
    await expectNone(page, 'none before hovering');

    await hoverUntilShown(page, LOCKED_TEXT);
  });

  test('21-S4-3 leaving: hidden at once; a hover under a second never shows it', async ({ page }) => {
    await open(page);
    await inTangent(page);

    // Shown, then the mouse leaves: gone at once.
    await hoverUntilShown(page, UNLOCKED_TEXT);
    await mouseAway(page);
    await expect(tooltip(page)).toHaveCount(0, { timeout: AT_ONCE_MS });
    await expect(lockButton(page)).toBeVisible();

    // A short hover never shows it, and a second short hover starts over.
    await lockButton(page).hover();
    await page.waitForTimeout(NOT_YET_MS);
    await mouseAway(page);
    await page.waitForTimeout(1200);
    await expectNone(page, 'a 500ms hover shows nothing, even later');

    await lockButton(page).hover();
    await page.waitForTimeout(600);
    await mouseAway(page);
    await lockButton(page).hover();
    await page.waitForTimeout(600);
    await expectNone(page, 'the delay restarts on each hover');
    await expect(tooltip(page)).toBeVisible({ timeout: SHOWN_WITHIN_MS });
    await expect(tooltip(page)).toHaveText(UNLOCKED_TEXT);

    // Shown, then the button goes (the grid loses focus): gone at once.
    await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
    await expect(lockButton(page)).toBeHidden({ timeout: AT_ONCE_MS });
    await expect(tooltip(page)).toHaveCount(0, { timeout: AT_ONCE_MS });
    await page.waitForTimeout(1200);
    await expectNone(page, 'nothing comes back without the button');
  });

  test('21-S4-4 click: the shown tooltip switches to the other text in place', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await hoverUntilShown(page, UNLOCKED_TEXT);

    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
    await expect(tooltip(page)).toHaveText(LOCKED_TEXT, { timeout: AT_ONCE_MS });
    await expect(tooltip(page)).toHaveCount(1);
    await expect(tooltip(page)).toBeVisible();

    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Lock word');
    await expect(tooltip(page)).toHaveText(UNLOCKED_TEXT, { timeout: AT_ONCE_MS });
    await expect(tooltip(page)).toHaveCount(1);
  });

  test('21-S4-5a keyboard: focusing the button shows none (pass today)', async ({ page }) => {
    await open(page);
    await inTangent(page);
    await mouseAway(page);
    await page.keyboard.press('Tab');
    await expect(lockButton(page)).toBeFocused();
    await page.waitForTimeout(1500);
    await expectNone(page, 'no tooltip for keyboard focus');
  });
});

test.describe('21-S4 on a touch screen', () => {
  test.use({ hasTouch: true });

  test('21-S4-5b touch: a tap on the button shows none (pass today)', async ({ page }) => {
    await open(page);
    await cell(page, '6,3').tap();
    await expect(lockButton(page)).toBeVisible();
    await lockButton(page).tap();
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
    await page.waitForTimeout(1500);
    await expectNone(page, 'no tooltip for a tap');
  });
});
