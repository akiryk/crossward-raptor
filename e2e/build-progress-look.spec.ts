// Story 22-S3 — The bar's look (the human's visual check of S2, 2026-11-08).
//
// The progress bar (22-S2, `e2e/build-progress.spec.ts`) becomes 16px tall,
// border included, with 20px corners (a pill at that height); the fill and
// the zone are clipped to the rounded inside. The fill below 80% is gray-500
// (`progress-fill`); from 80% it stays interactive-dark (`progress-fill-ready`).
//
// The fill animates: each time the progress appears (Preview turned on in a
// daily or Sunday build phase) it starts at 0 width and grows to its exact
// value, and every later change of the value moves it the same way. It is
// gray-500 while its drawn width is below 80% of the inside and switches to
// interactive-dark once it reaches 80% (in either direction). The message,
// "N% complete" and aria-valuenow change at once, not animated. With reduced
// motion (this suite's default) the fill shows its final width and color at
// once.
//
// Motion is sampled in the page, once per animation frame, reading what that
// frame draws: `build-progress-fill`'s box and background color, the bar's
// inside and the texts. Thresholds keep margins around the 80% switch so a
// color mid-transition never decides a case.
//
// Colors and sizes are written out here. Do not edit this file to match an
// implementation.

const WIDE = { width: 1440, height: 1000 };

const GRAY_200 = '#dde0e6';
const GRAY_500 = '#8b909a';
const INTERACTIVE_DARK = '#005b8c';
const ORANGE = '#ef9d05';
const WHITE = '#ffffff';
const INTERACTIVE_FAINT = '#f5f7fa'; // the toggle row's background

const BAR_HEIGHT = 16;
const RADIUS = '20px';

/** A recording runs this long after the first frame that differs from its first frame
 *  (the progress appearing, or its value or width changing): the animation (about
 *  700ms) and its settling. */
const RECORD_AFTER_CHANGE_MS = 1500;
/** And never longer than this from its start. */
const RECORD_CAP_MS = 5000;
/** The animation reaches its final width no sooner and no later than these, from its first frame. */
const SETTLE_MIN_MS = 300;
const SETTLE_MAX_MS = 1200;

/** A daily grid whose first `lettered` cells, in reading order, hold "A". */
function dailyWith(lettered: number): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  for (let i = 0; i < lettered; i++) {
    grid = withLetter(grid, { col: i % 15, row: Math.floor(i / 15) }, 'A');
  }
  return grid;
}

let titleCounter = 0;
async function seed(lettered: number) {
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid: dailyWith(lettered), hints: {}, phase: 'grid' },
    `22-S3 daily ${lettered} ${Date.now()}-${titleCounter}`,
  );
  return id;
}

async function open(page: Page, lettered: number) {
  const id = await seed(lettered);
  await page.setViewportSize(WIDE);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  await page.evaluate(() => document.fonts.ready.then(() => undefined));
}

async function turnPreviewOn(page: Page) {
  await previewToggle(page).click();
  await expect(previewToggle(page).locator('input')).toBeChecked();
  await expect(progressbar(page)).toBeVisible();
}

