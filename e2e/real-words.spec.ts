import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Coord, Grid } from '../src/engine/grid';
import type { Puzzle } from '../src/engine/puzzle';
import { currentBuilderId } from './helpers/ownership';
import { seedPlayPuzzle } from './helpers/play-route';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 17-S6 — Only real words.
//
// In the hints phase and play, the cursor's direction is one with a word
// through its cell. A click on a cell with a word one way only takes that
// way. Clicking the cursor cell again, Space or a cross-axis arrow turns
// the direction only where a word runs the new way; elsewhere they do
// nothing, and a cross-axis arrow never moves the cursor. Where words run
// both ways, all of them turn it as before. A cell with no word either way
// can still be selected, alone, and its direction doesn't change. The
// hints phase's cursor starts (on load, or on entering the phase) on the
// first white cell, Across, or Down where it has no Across word. The build
// phase is unchanged.
//
// Do not edit this file to match an implementation.

// The fixture, a 5×5 (# black):
//
//   A # # # #     1-Down  ABED (0,0)–(0,3)
//   B L U E #     2-Across BLUE (0,1)–(3,1)
//   E # # R #     3-Down  ERA  (3,1)–(3,3)
//   D # # A #
//   # # I # #     (2,4) has no word either way
//
// (0,0), (0,2), (0,3), (3,2) and (3,3) are Down only; (1,1) and (2,1)
// Across only; (0,1) and (3,1) both.

const ROWS = ['A####', 'BLUE#', 'E##R#', 'D##A#', '##I##'];
const ABED = ['0,0', '0,1', '0,2', '0,3'];
const BLUE = ['0,1', '1,1', '2,1', '3,1'];
const ERA = ['3,1', '3,2', '3,3'];
const HINTS = { '1-down': 'Retiring', '2-across': 'Sky color', '3-down': 'Age' };

/** The fixture's letters; its black cells black, or (build) left empty. */
function fixtureGrid(withBlack: boolean): Grid {
  const black: Coord[] = [];
  for (const [row, line] of ROWS.entries()) {
    for (const [col, letter] of [...line].entries()) if (letter === '#') black.push({ col, row });
  }
  let grid = createGrid({ cols: 5, rows: 5, black: withBlack ? black : [] });
  for (const [row, line] of ROWS.entries()) {
    for (const [col, letter] of [...line].entries()) {
      if (letter !== '#') grid = withLetter(grid, { col, row }, letter);
    }
  }
  return grid;
}

const hintsPuzzle = (): Puzzle => ({ grid: fixtureGrid(true), phase: 'hints', hints: HINTS });

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const editorGrid = (page: Page) => page.getByTestId('grid-region');
const bar = (page: Page) => page.getByTestId('prominent-hint');
const step = (page: Page, id: string) =>
  page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);

/** Exactly `cursor` is selected and exactly `word` (with it) highlighted. */
async function expectWord(page: Page, cursor: string, word: string[]) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(1);
  await expect(cell(page, cursor)).toHaveAttribute('data-selected', 'true');
  const others = word.filter((coord) => coord !== cursor);
  await expect(page.locator('[data-highlight="slot"]')).toHaveCount(others.length);
  for (const coord of others) await expect(cell(page, coord)).toHaveAttribute('data-highlight', 'slot');
}

/** Each key (or a click on the cursor cell) leaves `cursor` and `word` as they are. */
async function expectIgnored(page: Page, cursor: string, word: string[], keys: string[]) {
  await cell(page, cursor).click();
  await expectWord(page, cursor, word);
  for (const key of keys) {
    await page.keyboard.press(key);
    await expectWord(page, cursor, word);
  }
}

async function openEditor(page: Page, puzzle: Puzzle) {
  const { id } = await seedPuzzle(puzzle);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function openPlay(page: Page) {
  const builderId = await currentBuilderId(page);
  const { id } = await seedPlayPuzzle({ builderId, puzzle: hintsPuzzle() });
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

test.describe('17-S6 the hints phase selects only real words', () => {
  test('17-S6-1 the cursor starts Down where its cell has no Across word', async ({ page }) => {
    await openEditor(page, hintsPuzzle());
    await editorGrid(page).focus();
    await expectWord(page, '0,0', ABED);
  });

  test('17-S6-2 a click on a cell with a word one way only takes that way', async ({ page }) => {
    await openEditor(page, hintsPuzzle());
    await cell(page, '0,2').click();
    await expectWord(page, '0,2', ABED);
    await cell(page, '1,1').click();
    await expectWord(page, '1,1', BLUE);
    await cell(page, '3,2').click();
    await expectWord(page, '3,2', ERA);
  });

  test('17-S6-3 a second click, Space and cross-axis arrows do nothing where no word runs that way', async ({ page }) => {
    await openEditor(page, hintsPuzzle());
    await cell(page, '2,1').click();
    await expectWord(page, '2,1', BLUE);
    await expectIgnored(page, '2,1', BLUE, ['Space', 'ArrowUp', 'ArrowDown']);
    await cell(page, '3,3').click();
    await expectWord(page, '3,3', ERA);
    await expectIgnored(page, '3,3', ERA, ['Space', 'ArrowLeft', 'ArrowRight']);
  });

  test('17-S6-4 where words run both ways, a second click, Space and arrows turn it (guard)', async ({ page }) => {
    await openEditor(page, hintsPuzzle());
    await cell(page, '1,1').click();
    await cell(page, '3,1').click();
    await expectWord(page, '3,1', BLUE);
    await cell(page, '3,1').click();
    await expectWord(page, '3,1', ERA);
    await page.keyboard.press('ArrowLeft');
    await expectWord(page, '3,1', BLUE);
    await page.keyboard.press('Space');
    await expectWord(page, '3,1', ERA);
  });

  test('17-S6-5 a cell with no word either way is selected alone and keeps its direction', async ({ page }) => {
    await openEditor(page, hintsPuzzle());
    await cell(page, '1,1').click();
    await cell(page, '2,4').click();
    await expectWord(page, '2,4', ['2,4']);
    await expectIgnored(page, '2,4', ['2,4'], ['Space', 'ArrowUp', 'ArrowLeft']);
    await page.keyboard.type('o');
    await expect(cell(page, '2,4')).toContainText('O');
    await expectWord(page, '2,4', ['2,4']);
    await cell(page, '2,1').click();
    await expectWord(page, '2,1', BLUE);
  });

  test('17-S6-12 narrow, on a cell with no word either way the Hint Box keeps its word', async ({ page }) => {
    await page.setViewportSize({ width: 768, height: 1000 });
    await openEditor(page, hintsPuzzle());
    const input = page.getByTestId('hint-box').getByTestId('hint-box-input');
    await cell(page, '1,1').click();
    await expect(input).toHaveAccessibleName('2 Across hint');
    await cell(page, '2,4').click();
    await expectWord(page, '2,4', ['2,4']);
    await expect(input).toHaveAccessibleName('2 Across hint');
  });

  test('17-S6-6 entering the hints phase starts the cursor as a load does', async ({ page }) => {
    await openEditor(page, { grid: fixtureGrid(false), phase: 'grid', hints: {} });
    // (4,4) is empty, so it turns black on entering the hints phase.
    await cell(page, '4,4').click();
    await step(page, 'hints').click();
    await expect(page.getByTestId('enter-hints-dialog')).toBeVisible();
    await page.getByTestId('modal-confirm').click();
    await expect(page.getByTestId('hints-region')).toBeVisible();
    await expect(cell(page, '4,4')).toHaveAttribute('data-cell-state', 'black');
    await editorGrid(page).focus();
    await expectWord(page, '0,0', ABED);
  });
});

test.describe('17-S6 play selects only real words', () => {
  test('17-S6-7 the opening cell, Down only, ignores a second click, Space and cross-axis arrows', async ({ page }) => {
    await openPlay(page);
    await expectWord(page, '0,0', ABED);
    await expectIgnored(page, '0,0', ABED, ['Space', 'ArrowLeft', 'ArrowRight']);
    await expect(bar(page)).toHaveText(/^1D\s*Retiring$/);
  });

  test('17-S6-8 a click on an Across-only cell while Down takes Across, and stays there', async ({ page }) => {
    await openPlay(page);
    await cell(page, '2,1').click();
    await expectWord(page, '2,1', BLUE);
    await expect(bar(page)).toHaveText(/^2A\s*Sky color$/);
    await expectIgnored(page, '2,1', BLUE, ['Space', 'ArrowUp', 'ArrowDown']);
    await cell(page, '0,3').click();
    await expectWord(page, '0,3', ABED);
  });

  test('17-S6-9 where words run both ways, a second click, Space and arrows turn it (guard)', async ({ page }) => {
    await openPlay(page);
    await cell(page, '0,1').click();
    await expectWord(page, '0,1', ABED);
    await cell(page, '0,1').click();
    await expectWord(page, '0,1', BLUE);
    await page.keyboard.press('ArrowDown');
    await expectWord(page, '0,1', ABED);
    await page.keyboard.press('Space');
    await expectWord(page, '0,1', BLUE);
  });

  test('17-S6-10 a cell with no word either way is selected alone and can be filled', async ({ page }) => {
    await openPlay(page);
    await cell(page, '2,4').click();
    await expectWord(page, '2,4', ['2,4']);
    await expectIgnored(page, '2,4', ['2,4'], ['Space', 'ArrowUp', 'ArrowLeft']);
    await page.keyboard.type('i');
    await expect(cell(page, '2,4')).toContainText('I');
    await expectWord(page, '2,4', ['2,4']);
  });
});

test.describe('17-S6 the build phase is unchanged', () => {
  test('17-S6-11 a second click, Space and cross-axis arrows still turn onto a lone cell (guard)', async ({ page }) => {
    await openEditor(page, { grid: fixtureGrid(true), phase: 'grid', hints: {} });
    await cell(page, '1,1').click();
    await expectWord(page, '1,1', BLUE);
    await cell(page, '1,1').click();
    await expectWord(page, '1,1', ['1,1']);
    await page.keyboard.press('Space');
    await expectWord(page, '1,1', BLUE);
    await page.keyboard.press('ArrowDown');
    await expectWord(page, '1,1', ['1,1']);
  });
});
