// Story 23-S4 — Account in the masthead.
//
// Signed in with a username, the masthead's right side reads "Account | Sign
// out": Account, a link-looking button in `button-normal` and
// `masthead-account` (gray-500); a divider, a filled `line-muted` element
// 1px wide and 18px high, hidden
// from assistive technology, 10px from each word; Sign out as before, 20px
// from the right. Account hovers and focuses like Sign out (`button-hover`,
// the focus ring on keyboard focus). The username step's masthead and the
// signed-out one show neither Account nor the divider.
//
// Account opens the Account details modal: the Modal with its gray header
// option (`modal-title-background-gray`, gray-200; the title `title-3`
// `primary`), titled "Account details". Two regular fields, 360px wide, each
// with its caption under the line: the username, named "Username", holding
// the saved username and focused on open; under its caption, 20px down, the
// email, named "Email", holding the account's email, read-only until S5.
// The footer: Update (the primary Button) then Cancel (the alternate one).
// Update is disabled until the username differs from the value the modal
// opened with, exactly as typed. Cancel, ✕ and Escape close without saving.
// Update or Enter saves at once through a server action and closes the
// modal; the page stays where it is (no full reload: a window marker and an
// editor's typed letter survive) and shows the new name. Enter does nothing
// while Update is disabled. Closing or saving returns focus to Account; a
// failed save focuses the username field. The client
// checks the username rules first (TextInput's error line, the field
// focused, nothing sent); a failed save shows "Could not save your username.
// Please try again." on that line and keeps the value. While saving, the
// field and both buttons are disabled and Escape does nothing.
//
// Each test signs in its own account by database token. Measured at
// 1280×800. Do not edit this file to match an implementation.

