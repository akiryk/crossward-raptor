async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

/** The colour a color style resolves to on this page, as a computed `color`. */
async function token(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
}

/** A palette variable, as a computed `color`. */
async function palette(page: Page, name: string) {
  return page.evaluate((n) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--palette-${n})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, name);
}

/** A text style's size and line height, as computed. */
async function textStyle(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const c = getComputedStyle(probe);
    const result = { fontSize: c.fontSize, lineHeight: c.lineHeight };
    probe.remove();
    return result;
  }, style);
}

/** Computed style, once the element's running transitions have finished. */
function styleOf(locator: Locator) {
  return locator.evaluate(async (el) => {
    for (let i = 0; i < 10 && el.getAnimations().length > 0; i++) {
      await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
    }
    const s = getComputedStyle(el);
    return {
      tag: el.tagName.toLowerCase(),
      color: s.color,
      background: s.backgroundColor,
      borderWidths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
      fontSize: s.fontSize,
      fontWeight: Number(s.fontWeight),
      lineHeight: s.lineHeight,
      textDecoration: s.textDecorationLine,
      outline:
        s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0
          ? 'none'
          : `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor}`,
    };
  });
}

/** Focuses an element the way a keyboard user does, so :focus-visible applies. */
async function focusByKeyboard(page: Page, target: Locator) {
  await target.evaluate((el) => el.setAttribute('data-tab-target', ''));
  await page.evaluate(() => {
    const all = Array.from(
      document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input, select, textarea, [tabindex]')
    ).filter((el) => el.tabIndex >= 0);
    const index = all.findIndex((el) => el.hasAttribute('data-tab-target'));
    if (index > 0) all[index - 1].focus();
    else (document.activeElement as HTMLElement | null)?.blur();
  });
  for (let i = 0; i < 5; i++) {
    await page.keyboard.press('Tab');
    if (await target.evaluate((el) => el === document.activeElement)) break;
  }
  await expect(target).toBeFocused();
  await target.evaluate((el) => el.removeAttribute('data-tab-target'));
}

function masthead(page: Page) {
  const header = page.getByTestId('app-header');
  return {
    header,
    account: header.getByTestId('account'),
    divider: header.getByTestId('masthead-divider'),
    signOut: header.getByTestId('sign-out'),
    logo: page.getByTestId('home-link').locator('svg'),
  };
}

function details(page: Page) {
  const dialog = page.getByRole('dialog', { name: 'Account details' });
  return {
    dialog,
    header: dialog.getByTestId('modal-header'),
    title: dialog.getByTestId('modal-title'),
    close: dialog.getByTestId('modal-close'),
    username: dialog.getByTestId('account-username'),
    usernameCaption: dialog.getByTestId('account-username-caption'),
    usernameError: dialog.getByTestId('account-username-error'),
    email: dialog.getByTestId('account-email'),
    emailCaption: dialog.getByTestId('account-email-caption'),
    update: dialog.getByTestId('account-update'),
    cancel: dialog.getByTestId('account-cancel'),
  };
}

/** A new account with `username`, signed in on `page`, at /puzzles. */
async function namedAccount(page: Page, label: string, username = 'Lil Orange Fox') {
  await page.setViewportSize({ width: 1280, height: 800 });
  const email = uniqueEmail(`s4-${label}`);
  const userId = await createAccount(email, { displayName: username });
  await signInByLink(page, email);
  await expect(page).toHaveURL((url) => url.pathname === '/puzzles');
  await waitForNewPuzzleReady(page);
  return { email, userId };
}

async function openDetails(page: Page) {
  await page.mouse.move(1, 400);
  await masthead(page).account.click();
  const d = details(page);
  await expect(d.dialog).toBeVisible();
  return d;
}

/** Every server-action request the page sends. */
function recordActionPosts(page: Page) {
  const posts: string[] = [];
  page.on('request', (request) => {
    if (request.method() === 'POST' && request.headers()['next-action']) posts.push(request.url());
  });
  return posts;
}

