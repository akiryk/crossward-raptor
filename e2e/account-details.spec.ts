test.describe('23-S4-6 errors', () => {
  test('blank, whitespace-only and 81-code-point names show their message on the field’s error line and send nothing', async ({ page }) => {
    const { email } = await namedAccount(page, 'rules', 'Lil Orange Fox');
    const posts = recordActionPosts(page);
    const d = await openDetails(page);
    for (const [value, message] of [['', BLANK_USERNAME], ['   ', BLANK_USERNAME], ['🦖'.repeat(81), LONG_USERNAME]] as const) {
      await d.username.fill(value);
      await d.update.click();
      await expect(d.usernameError, JSON.stringify(value)).toHaveText(message);
      await expect(d.username).toBeFocused();
      await expect(d.username).toHaveAttribute('aria-invalid', 'true');
      await expect(d.username).toHaveValue(value);
      await expect(d.dialog).toBeVisible();
      const c = await box(d.usernameCaption);
      const e = await box(d.usernameError);
      expect(e.y, 'error under the caption').toBeGreaterThanOrEqual(c.y + c.height - 0.5);
      expect((await styleOf(d.usernameCaption)).color, 'caption stays muted').toBe(await token(page, 'muted'));
      expect((await styleOf(d.usernameError)).color, 'error color').toBe(await token(page, 'error'));
    }
    expect(posts, 'no save sent for a refused name').toEqual([]);
    expect((await readAccount(email))?.displayName).toBe('Lil Orange Fox');

    await d.username.fill('Fixed Name');
    await expect(d.usernameError, 'editing clears the error').toHaveCount(0);
    await expect(d.username).not.toHaveAttribute('aria-invalid', 'true');
  });

  test('a failed save shows its message on the field’s error line and keeps the value; a retry saves', async ({ page }) => {
    const { email } = await namedAccount(page, 'failure', 'Lil Orange Fox');
    let attempts = 0;
    await page.route('**/*', async (route) => {
      const request = route.request();
      if (request.method() === 'POST' && request.headers()['next-action'] && attempts++ === 0) {
        await route.fulfill({ status: 500, contentType: 'text/plain', body: 'Internal Server Error' });
        return;
      }
      await route.fallback();
    });
    const d = await openDetails(page);
    await d.username.fill('Grace Hopper');
    await d.update.click();
    await expect(d.usernameError).toHaveText(SAVE_FAILED);
    await expect(d.dialog).toBeVisible();
    await expect(d.username).toHaveValue('Grace Hopper');
    await expect(d.username).toBeEnabled();
    await expect(d.username, 'focus on the field after a failed save').toBeFocused();
    await expect(d.update).toBeEnabled();
    await expect(d.cancel).toBeEnabled();
    expect((await readAccount(email))?.displayName).toBe('Lil Orange Fox');

    await d.update.click();
    await expect(d.dialog).toHaveCount(0);
    await expect.poll(async () => (await readAccount(email))?.displayName).toBe('Grace Hopper');
  });
});

