// Story 18-S7 — Hint preview alignment.
//
// In the hints phase, toggling Preview Hints (17-S9) changes only the
// hints' own vertical layout. Labels and numbers start where Preview
// Hints put them before 18-S7: 6px into their column, the Across column
// 32px right of the grid, so 38px right of it, the numbers under their
// label. The Across label keeps its place; the Down label keeps its left
// edge, and every number keeps its left edge.
//
// Preview Hints follows the Hint Inputs' columns (the human, 2026-11-02):
// two side by side, 32px apart, from a 1430px window (650px of room beside
// a 700px grid, 730px beside a 620px one, 21-S9), the labels level at the
// list's top; below that one column, Down 32px below
// all of Across, in both states. There the Down label's height follows
// the Across hints', which is the hints' own vertical layout.
//
// The build phase's skeleton takes the same 6px inset, so its labels and
// dots also start 38px right of the grid, and Create Hints still moves no
// label's left edge and puts each number where its dot was (14-S6).
//
// Positions are those of the text itself (a DOM Range over the element's
// contents), not the element's box, since the lists pad differently.
// Measured with the list unscrolled; before and after are compared
// relative to the grid's box, so a window scroll doesn't count.
//
// Amended by 21-S9: a 15×15's grid is 620px (was 700px), so 18-S7-2's
// grid width is 620px; the windows are unchanged.
//
// Do not edit this file to match an implementation.

const GRID_PX = 620;
const GAP_PX = 32;
const INSET_PX = 6;
const LABEL_TOP_PX = 8;
const TOLERANCE = 0.5;

const ORIENTATIONS = ['across', 'down'] as const;
type Orientation = (typeof ORIENTATIONS)[number];

/** Every cell lettered, so every word survives into the hints phase. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

/** A hint for every word of an all-on square, long enough to wrap in a narrow column. */
function everyHint(size: number): Record<string, string> {
  const hints: Record<string, string> = {};
  const text = (key: string) => `Hint ${key}, long enough to wrap onto a second line somewhere`;
  for (let n = 1; n <= size; n++) hints[`${n}-down`] = text(`${n}-down`);
  hints['1-across'] = text('1-across');
  for (let row = 1; row < size; row++) hints[`${size + row}-across`] = text(`${size + row}-across`);
  return hints;
}

let titleCounter = 0;
async function open(
  page: Page,
  width: number,
  size: number,
  options: { phase?: 'grid' | 'hints'; wide?: boolean } = {}
) {
  const { phase = 'hints', wide = true } = options;
  await page.setViewportSize({ width, height: 900 });
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid: filled(size), hints: phase === 'hints' ? everyHint(size) : {}, phase },
    `S7 ${phase} ${size} ${Date.now()}-${titleCounter}`
  );
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  if (wide) {
    await expect(page.getByTestId(phase === 'hints' ? 'hints-region' : 'hint-skeleton')).toBeVisible();
  }
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const region = (page: Page) => page.getByTestId('hints-region');
const previewToggle = (page: Page) => page.getByTestId('preview-hints-toggle').filter({ visible: true });

async function setPreview(page: Page, on: boolean) {
  const input = previewToggle(page).locator('input');
  if ((await input.isChecked()) !== on) await previewToggle(page).click();
  if (on) {
    await expect(input).toBeChecked();
    await expect(region(page).getByTestId('play-clue').first()).toBeVisible();
  } else {
    await expect(input).not.toBeChecked();
    await expect(region(page).getByTestId('hint-input').first()).toBeVisible();
  }
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

/** The left and top of an element's text, from a Range over its contents. */
async function textBox(locator: Locator) {
  return locator.evaluate((el) => {
    const range = document.createRange();
    range.selectNodeContents(el);
    const r = range.getBoundingClientRect();
    return { left: r.left, top: r.top };
  });
}

/** An element's content top: its box's top plus its top padding. */
async function contentTop(locator: Locator) {
  return locator.evaluate((el) => el.getBoundingClientRect().top + parseFloat(getComputedStyle(el).paddingTop));
}

const label = (page: Page, orientation: Orientation) =>
  region(page).getByRole('heading', { name: orientation === 'across' ? 'Across' : 'Down', exact: true });

/** The shown list's column, whichever list it is. */
const listColumn = (page: Page, orientation: Orientation, preview: boolean) =>
  region(page).locator(
    `[data-testid="${preview ? 'play-clue-column' : 'hint-column'}"][data-orientation="${orientation}"]`
  );

/** Every hint number in the shown list, by key, whichever list it is. */
async function numbers(page: Page, preview: boolean) {
  const rows = preview ? region(page).getByTestId('play-clue') : region(page).getByTestId('hint-row');
  const keyAttribute = preview ? 'data-clue-key' : 'data-hint-key';
  const numberId = preview ? 'play-clue-number' : 'hint-label';
  const out: Record<string, number> = {};
  for (const row of await rows.all()) {
    const key = await row.getAttribute(keyAttribute);
    if (!key) throw new Error('row without a key');
    out[key] = (await textBox(row.getByTestId(numberId))).left;
  }
  return out;
}

type Layout = {
  labels: Record<Orientation, { left: number; top: number; contentTop: number }>;
  /** The Across column's bottom, for a stacked Down. */
  acrossBottom: number;
  /** The Down column's top. */
  downTop: number;
  numbers: Record<string, number>;
};

async function measure(page: Page, preview: boolean): Promise<Layout> {
  await region(page).evaluate((el) => el.scrollTo(0, 0));
  const labels = {} as Layout['labels'];
  for (const o of ORIENTATIONS) {
    const t = await textBox(label(page, o));
    labels[o] = { ...t, contentTop: await contentTop(label(page, o)) };
  }
  return {
    labels,
    acrossBottom: (await box(listColumn(page, 'across', preview))).bottom,
    downTop: (await box(listColumn(page, 'down', preview))).y,
    numbers: await numbers(page, preview),
  };
}

/** A layout relative to the grid's box, so a window scroll between two
 *  measurements doesn't count as a move. */
async function measureFromGrid(page: Page, preview: boolean): Promise<Layout> {
  const layout = await measure(page, preview);
  const g = await box(grid(page));
  const labels = {} as Layout['labels'];
  for (const o of ORIENTATIONS) {
    const l = layout.labels[o];
    labels[o] = { left: l.left - g.x, top: l.top - g.y, contentTop: l.contentTop - g.y };
  }
  return {
    labels,
    acrossBottom: layout.acrossBottom - g.y,
    downTop: layout.downTop - g.y,
    numbers: Object.fromEntries(Object.entries(layout.numbers).map(([key, left]) => [key, left - g.x])),
  };
}

function expectNear(actual: number, expected: number, what: string) {
  expect(Math.abs(actual - expected), `${what}: ${actual} vs ${expected}`).toBeLessThanOrEqual(TOLERANCE);
}

function expectSameLayout(a: Layout, b: Layout, stacked: boolean, what: string) {
  expectNear(b.labels.across.left, a.labels.across.left, `${what}: Across label left`);
  expectNear(b.labels.across.top, a.labels.across.top, `${what}: Across label top`);
  expectNear(b.labels.down.left, a.labels.down.left, `${what}: Down label left`);
  // Stacked, Down's height follows the Across hints' (the hints' own layout).
  if (!stacked) expectNear(b.labels.down.top, a.labels.down.top, `${what}: Down label top`);
  expect(Object.keys(b.numbers).sort(), `${what}: the same hints`).toEqual(Object.keys(a.numbers).sort());
  for (const [key, left] of Object.entries(a.numbers)) {
    expectNear(b.numbers[key], left, `${what}: number ${key} left`);
  }
}

/**
 * Where the labels and numbers belong, Preview Hints on or off: the Across
 * label and numbers 38px right of the grid, the Across label's content 8px
 * below the list's top. Two columns: Down's 6px into a column starting at
 * the list's left plus half its content width plus 16px, the labels level.
 * Stacked: Down's at Across's left, its column 32px below Across's, its
 * label's content 8px below that.
 */
async function expectPositions(page: Page, layout: Layout, stacked: boolean) {
  const g = await box(grid(page));
  const r = await box(region(page));
  expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
  // The list's content width: its box less any scrollbar room it keeps.
  const contentWidth = await region(page).evaluate((el) => el.clientWidth);
  const acrossLeft = g.right + GAP_PX + INSET_PX;
  const downLeft = stacked ? acrossLeft : r.x + (contentWidth + GAP_PX) / 2 + INSET_PX;

  expectNear(layout.labels.across.left, acrossLeft, 'Across label 38px right of the grid');
  expectNear(layout.labels.across.contentTop, r.y + LABEL_TOP_PX, 'Across label 8px below the list’s top');
  if (stacked) {
    expectNear(layout.labels.down.left, acrossLeft, 'Down label under Across');
    expectNear(layout.downTop - layout.acrossBottom, GAP_PX, 'Down 32px below all of Across');
    expectNear(layout.labels.down.contentTop, layout.downTop + LABEL_TOP_PX, 'Down label 8px into its column');
  } else {
    expectNear(layout.labels.down.left, downLeft, 'Down label 6px into the second column');
    expectNear(layout.labels.down.top, layout.labels.across.top, 'the labels level');
    expectNear(layout.labels.down.contentTop, r.y + LABEL_TOP_PX, 'Down label 8px below the list’s top');
  }
  for (const [key, left] of Object.entries(layout.numbers)) {
    expectNear(left, key.endsWith('-across') ? acrossLeft : downLeft, `number ${key} under its label`);
  }
}

// Two columns from 1430px; one column from 1140px to 1429px (beside a
// 620px grid, 730px of room and 440px to 729px, 21-S9).
const WIDTHS = [
  { name: 'wide', width: 1440, stacked: false },
  { name: 'widest, the 1800px main area', width: 2400, stacked: false },
  { name: 'at 1430px', width: 1430, stacked: false },
  { name: 'at 1429px', width: 1429, stacked: true },
  { name: 'laptop', width: 1280, stacked: true },
  { name: 'narrowest wide', width: 1140, stacked: true },
];

test.describe('18-S7-1 Preview Hints moves no label or number', () => {
  for (const w of WIDTHS) {
    for (const size of [5, 15]) {
      test(`${w.name} (${w.width}px), a ${size}×${size}: off, on and off again, the labels and numbers stay put`, async ({ page }) => {
        await open(page, w.width, size);
        const off = await measureFromGrid(page, false);
        await setPreview(page, true);
        const on = await measureFromGrid(page, true);
        await setPreview(page, false);
        const offAgain = await measureFromGrid(page, false);

        expectSameLayout(on, off, w.stacked, 'off vs on');
        expectSameLayout(on, offAgain, w.stacked, 'off again vs on');
      });
    }
  }
});

test.describe('18-S7-2 38px from the grid, in the Hint Inputs’ columns', () => {
  for (const w of WIDTHS) {
    for (const preview of [false, true]) {
      const shape = w.stacked ? 'one column, Down below Across' : 'two columns, the labels level';
      test(`${w.name} (${w.width}px), Preview Hints ${preview ? 'on' : 'off'}: ${shape}`, async ({ page }) => {
        await open(page, w.width, 15);
        await setPreview(page, preview);
        await expectPositions(page, await measure(page, preview), w.stacked);
      });
    }
  }
});

test.describe('18-S7-3 only the hints’ own layout differs', () => {
  test('off: Hint Inputs; on: Player Hints; the list doesn’t move', async ({ page }) => {
    await open(page, 1440, 5);
    const before = await box(region(page));
    await expect(region(page).getByTestId('hint-input')).toHaveCount(10);
    await setPreview(page, true);
    await expect(region(page).getByTestId('hint-input')).toHaveCount(0);
    await expect(region(page).getByTestId('play-clue')).toHaveCount(10);
    const after = await box(region(page));
    expectNear(after.x, before.x, 'list left');
    expectNear(after.y, before.y, 'list top');
    expectNear(after.width, before.width, 'list width');
  });
});

test.describe('18-S7-4 narrow: no Preview Hints, nothing to align', () => {
  test('at 1139px the Hint Box shows and there is no toggle', async ({ page }) => {
    await open(page, 1139, 5, { wide: false });
    await expect(page.getByTestId('hint-box')).toBeVisible();
    await expect(previewToggle(page)).toHaveCount(0);
  });
});

const skeletonColumn = (page: Page, orientation: Orientation) =>
  page.locator(`[data-testid="hint-skeleton-column"][data-orientation="${orientation}"]`);
const skeletonLabel = (page: Page, orientation: Orientation) =>
  skeletonColumn(page, orientation).getByText(orientation === 'across' ? 'Across' : 'Down', { exact: true });

test.describe('18-S7-5 the build phase’s skeleton takes the same inset', () => {
  for (const w of [WIDTHS[0], WIDTHS[4]]) {
    test(`${w.name} (${w.width}px): its labels and dots 6px into their column, the Across label 38px right of the grid`, async ({ page }) => {
      await open(page, w.width, 5, { phase: 'grid' });
      const g = await box(grid(page));
      for (const o of ORIENTATIONS) {
        const column = await box(skeletonColumn(page, o));
        const labelLeft = (await textBox(skeletonLabel(page, o))).left;
        expectNear(labelLeft, column.x + INSET_PX, `${o} label 6px in`);
        const dots = skeletonColumn(page, o).getByTestId('hint-skeleton-dot');
        expect(await dots.count(), `${o} dots`).toBeGreaterThan(0);
        for (const dot of await dots.all()) expectNear((await box(dot)).x, column.x + INSET_PX, `${o} dot 6px in`);
      }
      expectNear((await textBox(skeletonLabel(page, 'across'))).left, g.right + GAP_PX + INSET_PX, 'Across 38px right of the grid');
    });

    test(`${w.name} (${w.width}px): at Create Hints the labels keep their left (and, side by side, their top), each number in its dot’s place`, async ({ page }) => {
      await open(page, w.width, 5, { phase: 'grid' });
      const before = {
        labels: await Promise.all(ORIENTATIONS.map(async (o) => textBox(skeletonLabel(page, o)))),
        dots: await Promise.all(
          ORIENTATIONS.map(async (o) =>
            Promise.all((await skeletonColumn(page, o).getByTestId('hint-skeleton-dot').all()).map((d) => box(d)))
          )
        ),
      };

      await page.locator('[data-testid="builder-steps"] [data-step-id="hints"]').click();
      await page.getByRole('button', { name: 'Yes, create hints' }).click();
      await expect(region(page)).toBeVisible();

      const after = await measure(page, false);
      ORIENTATIONS.forEach((o, i) => {
        expectNear(after.labels[o].left, before.labels[i].left, `${o} label left`);
        // Stacked, Down's height follows Across's rows, which differ (14-S6).
        if (o === 'across' || !w.stacked) expectNear(after.labels[o].top, before.labels[i].top, `${o} label top`);
      });
      for (const [i, o] of ORIENTATIONS.entries()) {
        const keys = Object.keys(after.numbers).filter((k) => k.endsWith(`-${o}`));
        expect(keys.length, `${o} numbers`).toBe(before.dots[i].length);
        for (const key of keys) expectNear(after.numbers[key], before.dots[i][0].x, `number ${key} where the dot was`);
      }
    });
  }
});
