// Story 19-S3 — Reset in the row menu, Delete set apart.
//
// The caller's own completed row has no standalone Reset: its menu reads
// Duplicate, Open in builder, Make public/unlisted, Reset, Delete. Reset
// is an error-colored menu item that opens the existing reset dialog;
// dismissing the dialog returns focus to the menu button, and confirming
// resets the row in place onto Play. Rows that aren't completed have no
// Reset in the menu. Another builder's completed row (no menu) keeps its
// Reset button where it was.
//
// Every own menu sets Delete apart with a role="separator" hairline: 1px
// of line-muted, the menu's full inner width, 16px below the previous
// item, Delete directly under it. Arrow keys skip it. The style guide's
// sample shows it too.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

test.use({ storageState: { cookies: [], origins: [] }, viewport: { width: 1280, height: 800 } });

type Rgb = { r: number; g: number; b: number; a: number };

function rgbOf(value: string): Rgb {
  const m = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+))?\s*\)$/);
  if (m) return { r: Number(m[1]), g: Number(m[2]), b: Number(m[3]), a: m[4] === undefined ? 1 : Number(m[4]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\s*\)$/);
  if (!srgb) throw new Error(`unparseable colour: "${value}"`);
  return {
    r: Math.round(Number(srgb[1]) * 255),
    g: Math.round(Number(srgb[2]) * 255),
    b: Math.round(Number(srgb[3]) * 255),
    a: srgb[4] === undefined ? 1 : Number(srgb[4]),
  };
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string): Promise<Rgb> {
  return rgbOf(await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style));
}

async function colorOf(locator: Locator, property: string) {
  return rgbOf(await locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property));
}

/** Page-relative box. */
async function box(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { x: r.left + window.scrollX, y: r.top + window.scrollY, width: r.width, height: r.height };
  });
}

function uniqueTitle(label: string) {
  return `19-S3 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

async function freshBuilder(page: Page) {
  await signInSeededUser(page);
  return currentBuilderId(page);
}

async function seedOwn(builderId: string, state: BuilderEditState) {
  const title = uniqueTitle(state);
  const { id } = await seedBuilderEditPuzzle(title, builderId, state);
  return { id, title };
}

const solved: SerializedGrid = {
  cols: 3, rows: 3,
  cells: [
    [{ kind: 'active', letter: 'C' }, { kind: 'active', letter: 'A' }, { kind: 'active', letter: 'T' }],
    [{ kind: 'active', letter: 'A' }, { kind: 'black' }, { kind: 'active', letter: 'A' }],
    [{ kind: 'active', letter: 'T' }, { kind: 'active', letter: 'E' }, { kind: 'active', letter: 'N' }],
  ],
};

/** A published puzzle by `builderId` that `playerId` has not started, is playing, or completed. */
async function seedPublished(
  builderId: string,
  playerId: string,
  attempt: 'none' | 'in-play' | 'complete',
  visibility: 'public' | 'private' = 'public',
) {
  const fixture = await seedPlayPuzzle({ builderId, visibility });
  const title = uniqueTitle(`${visibility} ${attempt}`);
  const client = ownershipTestClient();
  try {
    await client.puzzle.update({ where: { id: fixture.id }, data: { title } });
    if (attempt !== 'none') {
      const entries = structuredClone(solved);
      if (attempt === 'in-play') entries.cells[0][0] = { kind: 'active', letter: null };
      const sessionId = await seedPlaySession(playerId, fixture.id, deserializeGrid(entries));
      if (attempt === 'complete') {
        await client.playSession.update({ where: { id: sessionId }, data: { completedAt: new Date('2026-01-04T04:05:06Z') } });
      }
    }
  } finally {
    await client.$disconnect();
  }
  return { id: fixture.id, title };
}

async function openLibrary(page: Page) {
  await page.goto('/puzzles');
  await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
}

function row(page: Page, title: string) {
  return page.getByTestId('puzzle-list-item').filter({ hasText: title });
}

const menu = (scope: Page | Locator) => scope.getByTestId('puzzle-menu');
const trigger = (scope: Page | Locator) => scope.getByTestId('puzzle-menu-button');

async function itemTexts(scope: Page | Locator) {
  return (await menu(scope).getByRole('menuitem').allTextContents()).map((text) => text.trim());
}

async function openMenu(item: Locator) {
  await trigger(item).click();
  await expect(menu(item.page())).toBeVisible();
}

test.describe('19-S3-1 the own completed row resets from its menu', () => {
  test('no standalone Reset; the menu reads Duplicate, Open in builder, the visibility item, Reset, Delete', async ({ page }) => {
    const me = await freshBuilder(page);
    const unlisted = await seedPublished(me, me, 'complete', 'private');
    const listed = await seedPublished(me, me, 'complete', 'public');
    await openLibrary(page);

    for (const [fixture, visibility] of [[unlisted, 'Make public'], [listed, 'Make unlisted']] as const) {
      const item = row(page, fixture.title);
      await expect(item).toHaveAttribute('data-play-state', 'completed');
      await expect(item.getByTestId('puzzle-reset-button'), `${visibility}: no standalone Reset`).toHaveCount(0);
      await openMenu(item);
      expect(await itemTexts(page), fixture.title).toEqual(['Duplicate', 'Open in builder', visibility, 'Reset', 'Delete']);
      const reset = menu(page).getByTestId('puzzle-menu-reset');
      await expect(reset).toHaveAttribute('role', 'menuitem');
      await expect(reset).toHaveAccessibleName('Reset');
      expect(await colorOf(reset, 'color'), 'Reset is error').toEqual(await token(page, 'error'));
      await page.keyboard.press('Escape');
      await expect(menu(page)).toHaveCount(0);
    }
  });

  test('own rows that are not completed have no Reset in the menu', async ({ page }) => {
    const me = await freshBuilder(page);
    const untouched = await seedPublished(me, me, 'none');
    const inPlay = await seedPublished(me, me, 'in-play');
    const draft = await seedOwn(me, 'grid');
    await openLibrary(page);

    for (const [fixture, expected] of [
      [untouched, ['Duplicate', 'Open in builder', 'Make unlisted', 'Delete']],
      [inPlay, ['Duplicate', 'Open in builder', 'Make unlisted', 'Delete']],
      [draft, ['Duplicate', 'Delete']],
    ] as const) {
      const item = row(page, fixture.title);
      await expect(item.getByTestId('puzzle-reset-button')).toHaveCount(0);
      await openMenu(item);
      expect(await itemTexts(page), fixture.title).toEqual(expected);
      await expect(menu(page).getByTestId('puzzle-menu-reset')).toHaveCount(0);
      await page.keyboard.press('Escape');
    }
  });
});

/** The hairline: one separator, right before Delete, 1px of line-muted across the menu, 16px below the item above. */
async function expectHairline(page: Page, list: Locator, label: string) {
  const separator = list.getByRole('separator');
  await expect(separator, `${label}: one hairline`).toHaveCount(1);
  const delete_ = list.getByRole('menuitem').last();
  await expect(delete_).toHaveText('Delete');
  const order = await list.evaluate((el) => Array.from(el.children).map((child) => child.getAttribute('role')));
  expect(order.at(-2), `${label}: the hairline comes right before Delete`).toBe('separator');
  expect(order.at(-1)).toBe('menuitem');

  const items = list.getByRole('menuitem');
  const above = await box(items.nth((await items.count()) - 2));
  const s = await box(separator);
  const d = await box(delete_);
  const l = await box(list);
  expect(s.height, `${label}: 1px tall`).toBeCloseTo(1, 1);
  expect(s.y - (above.y + above.height), `${label}: 16px below the item above`).toBeCloseTo(16, 0);
  expect(d.y - (s.y + s.height), `${label}: Delete directly under it`).toBeCloseTo(0, 0);
  expect(d.height, `${label}: Delete keeps its 32px`).toBeCloseTo(32, 0);
  expect(s.x, `${label}: from the menu's inner left`).toBeCloseTo(l.x + 1, 0);
  expect(s.width, `${label}: the menu's inner width`).toBeCloseTo(l.width - 2, 0);
  const lineMuted = await token(page, 'line-muted');
  const color = await separator.evaluate((el) => {
    const c = getComputedStyle(el);
    // A 1px line drawn either as its background or as a top/bottom border.
    if (parseFloat(c.borderTopWidth) > 0) return c.borderTopColor;
    if (parseFloat(c.borderBottomWidth) > 0) return c.borderBottomColor;
    return c.backgroundColor;
  });
  expect(rgbOf(color), `${label}: line-muted`).toEqual(lineMuted);
}

test.describe('19-S3-2 a hairline sets Delete apart', () => {
  test('in every own menu: completed, published and unpublished', async ({ page }) => {
    const me = await freshBuilder(page);
    const completed = await seedPublished(me, me, 'complete');
    const published = await seedPublished(me, me, 'none', 'private');
    const draft = await seedOwn(me, 'hints');
    await openLibrary(page);

    for (const fixture of [completed, published, draft]) {
      await openMenu(row(page, fixture.title));
      await expectHairline(page, menu(page), fixture.title);
      await page.keyboard.press('Escape');
      await expect(menu(page)).toHaveCount(0);
    }
  });

  test('arrow keys skip it: Reset, then Delete, then around to Duplicate', async ({ page }) => {
    const me = await freshBuilder(page);
    const completed = await seedPublished(me, me, 'complete');
    await openLibrary(page);
    const item = row(page, completed.title);
    await trigger(item).focus();
    await page.keyboard.press('ArrowUp');
    const items = menu(page).getByRole('menuitem');
    await expect(items.last(), 'ArrowUp opens on Delete').toBeFocused();
    await page.keyboard.press('ArrowUp');
    await expect(menu(page).getByTestId('puzzle-menu-reset')).toBeFocused();
    await page.keyboard.press('ArrowDown');
    await expect(items.last()).toBeFocused();
    await page.keyboard.press('ArrowDown');
    await expect(items.first()).toHaveText('Duplicate');
    await expect(items.first()).toBeFocused();
  });

  test('the style guide sample shows it before Delete', async ({ page }) => {
    await signInSeededUser(page);
    await page.goto('/style-guide');
    const sample = page.getByTestId('sg-row-menu');
    await trigger(sample).click();
    await expect(sample.getByRole('menuitem')).toHaveText(['Make public', 'Delete']);
    await expectHairline(page, menu(sample), 'style guide');
  });
});

test.describe('19-S3-3 the menu Reset uses the existing dialog', () => {
  test('dismissing returns focus to the menu button; confirming resets the row in place onto Play', async ({ page }) => {
    const me = await freshBuilder(page);
    const fixture = await seedPublished(me, me, 'complete');
    const before = await readPlaySessions(fixture.id);
    await openLibrary(page);
    const item = row(page, fixture.title);

    await openMenu(item);
    await menu(page).getByTestId('puzzle-menu-reset').click();
    const dialog = page.getByTestId('play-reset-dialog');
    await expect(dialog).toBeVisible();
    await expect(dialog).toHaveAccessibleName('Reset puzzle?');
    await expect(dialog).toContainText(fixture.title);
    await expect(menu(page), 'the menu closed').toHaveCount(0);
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    await expect(trigger(item)).toBeFocused();
    await expect(item).toHaveAttribute('data-play-state', 'completed');
    expect(await readPlaySessions(fixture.id)).toEqual(before);

    // The keyboard reaches it too: Enter on the focused button, then up past Delete.
    await page.keyboard.press('Enter');
    await expect(menu(page)).toBeVisible();
    await page.keyboard.press('End');
    await page.keyboard.press('ArrowUp');
    await expect(menu(page).getByTestId('puzzle-menu-reset')).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(dialog).toBeVisible();
    await page.getByTestId('play-reset-confirm').click();
    await expect(dialog).toHaveCount(0);
    await expect(item).toHaveAttribute('data-play-state', 'untouched');
    await expect(item.getByTestId('puzzle-status')).toHaveText('Ready to play');
    await expect(item.getByTestId('puzzle-play-link')).toBeFocused();

    await openMenu(item);
    expect(await itemTexts(page), 'no Reset once reset').toEqual(['Duplicate', 'Open in builder', 'Make unlisted', 'Delete']);
  });
});

test.describe('19-S3-4 another builder’s completed row keeps its Reset button', () => {
  test('no menu, the Reset button 12px from the right, opening the dialog', async ({ page }) => {
    const me = await freshBuilder(page);
    const fixture = await seedPublished(await seedOtherBuilder(), me, 'complete');
    await openLibrary(page);
    const item = row(page, fixture.title);

    await expect(trigger(item)).toHaveCount(0);
    const reset = item.getByTestId('puzzle-reset-button');
    await expect(reset).toHaveText('Reset');
    const r = await box(item);
    const k = await box(reset);
    expect(r.x + r.width - (k.x + k.width), 'right inset').toBeCloseTo(12, 0);
    await reset.click();
    await expect(page.getByTestId('play-reset-dialog')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(reset).toBeFocused();
  });
});
