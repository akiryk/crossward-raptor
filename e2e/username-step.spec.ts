const SIGN_IN_HEADING = ['Build a puzzle.', 'Or play a puzzle.', 'Log in to start.'];
const STEP_HEADING = ['Build a puzzle.', 'Or play a puzzle.', 'Create a username.'];
const BLANK_USERNAME = 'Oops! You need to add a username.';
const LONG_USERNAME = 'Oops! Use 80 characters or fewer.';
const MAGIC_LINK_PATH = '/api/auth/sign-in/magic-link';
const STORAGE_KEY = 'crossward:username';

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

async function lines(locator: Locator) {
  const text = await locator.evaluate((el) => (el as HTMLElement).innerText);
  return text.split('\n').map((line) => line.trim()).filter(Boolean);
}

/** The colour a color style resolves to on this page, as computed. */
async function token(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
}

/** The colour of the text node holding `text` inside `root`. */
async function phraseColor(root: Locator, text: string) {
  return root.evaluate((el, wanted) => {
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if ((node.textContent ?? '').includes(wanted)) return getComputedStyle(node.parentElement!).color;
    }
    throw new Error(`"${wanted}" is not drawn`);
  }, text);
}

function expectGeneratedName(value: string) {
  const words = value.split(' ');
  expect(words, `"${value}" is three words`).toHaveLength(3);
  expect(USERNAME_FIRST_ADJECTIVES as readonly string[], value).toContain(words[0]);
  expect(USERNAME_SECOND_ADJECTIVES as readonly string[], value).toContain(words[1]);
  expect(USERNAME_NOUNS as readonly string[], value).toContain(words[2]);
}

function step(page: Page) {
  return {
    form: page.getByTestId('username-step'),
    field: page.getByTestId('username-input'),
    caption: page.getByTestId('username-input-caption'),
    error: page.getByTestId('username-input-error'),
    submit: page.getByTestId('username-submit'),
    heading: page.getByTestId('front-door').getByRole('heading', { level: 1 }),
  };
}

/** The step is shown, ready, at `/`, and nothing privileged is. */
async function expectStep(page: Page) {
  await expect(page).toHaveURL((url) => url.pathname === '/');
  await expect(page.locator('[data-testid="username-step"][data-ready="true"]')).toBeVisible();
  await expect(page.getByTestId('sign-in-form')).toHaveCount(0);
  for (const testId of ['puzzle-library', 'new-puzzle', 'puzzle-editor', 'play-puzzle', 'sg-buttons']) {
    await expect(page.getByTestId(testId), testId).toHaveCount(0);
  }
}

/** Every magic-link request the page sends, as parsed JSON bodies. */
function recordLinkRequests(page: Page) {
  const bodies: Array<Record<string, unknown>> = [];
  page.on('request', (request) => {
    if (new URL(request.url()).pathname === MAGIC_LINK_PATH && request.method() === 'POST') {
      bodies.push(JSON.parse(request.postData() ?? '{}'));
    }
  });
  return bodies;
}

/** Sign in through the email-only form and follow the link. */
async function signInThroughForm(page: Page, email: string) {
  await openSignedOutFrontDoor(page);
  await page.getByTestId('sign-in-email').fill(email);
  await page.getByTestId('sign-in-submit').click();
  await expect(page.getByTestId('sign-in-sent')).toBeVisible();
  await page.goto(await readMagicLinkUrl(email));
}

/** A brand-new account, signed in by its first link: it lands on the step. */
async function newAccountOnStep(page: Page, label: string) {
  await page.setViewportSize({ width: 1280, height: 800 });
  const email = uniqueEmail(label);
  await signInByLink(page, email);
  await expectStep(page);
  return email;
}

