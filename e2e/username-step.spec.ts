test.describe('23-S3-9 signing out from the step', () => {
  test('Sign out returns to the sign-in form and ends the session', async ({ page }) => {
    await newAccountOnStep(page, 'sign-out');
    await page.getByTestId('sign-out').click();
    await expect(page.locator('[data-testid="sign-in-form"][data-ready="true"]')).toBeVisible();
    await expect(page.getByTestId('username-step')).toHaveCount(0);
    expect(await getSession(page)).toBeNull();
  });
});
