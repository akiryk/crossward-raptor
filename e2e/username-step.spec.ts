test.describe('23-S3-3 saving the username', () => {
  test('Get Started keeps the suggestion, goes on to /puzzles, and the account is in', async ({ page }) => {
    const email = await newAccountOnStep(page, 'keep');
    const suggestion = await step(page).field.inputValue();
    await step(page).submit.click();

    await expect(page).toHaveURL(/\/puzzles$/);
    await expect(page.getByTestId('puzzle-library')).toBeVisible();
    expect((await readAccount(email))?.displayName).toBe(suggestion);

    await waitForNewPuzzleReady(page);
    await page.getByTestId('new-puzzle-button').click();
    await expect(page.getByTestId('new-puzzle-dialog')).toBeVisible();
    await page.keyboard.press('Escape');

    await page.goto('/');
    await expect(page).toHaveURL(/\/puzzles$/);
  });

  test('a username of their own is saved trimmed, with Enter', async ({ page }) => {
    const email = await newAccountOnStep(page, 'own');
    await step(page).field.fill('  Ada Lovelace  ');
    await step(page).field.press('Enter');
    await expect(page).toHaveURL(/\/puzzles$/);
    expect((await readAccount(email))?.displayName).toBe('Ada Lovelace');
  });

  test('blank, whitespace-only and 81-code-point names are refused in the field’s error state; 80 is saved', async ({ page }) => {
    const email = await newAccountOnStep(page, 'rules');
    const s = step(page);
    // The client checks first: a refused name sends nothing.
    const actionPosts: string[] = [];
    page.on('request', (request) => {
      if (request.method() === 'POST' && request.headers()['next-action']) actionPosts.push(request.url());
    });
    for (const [value, message] of [['', BLANK_USERNAME], ['   ', BLANK_USERNAME], ['🦖'.repeat(81), LONG_USERNAME]] as const) {
      await s.field.fill(value);
      await s.submit.click();
      await expect(s.error, JSON.stringify(value)).toHaveText(message);
      await expect(s.field).toBeFocused();
      await expect(s.field).toHaveAttribute('aria-invalid', 'true');
      await expect(s.field).toHaveValue(value);
      await expect(page).toHaveURL((url) => url.pathname === '/');
      expect((await readAccount(email))?.displayName).toBeNull();
      // The step is the first to show a caption with an error: the error
      // under the caption, the caption still muted, the button 40px under the error.
      const c = await box(s.caption);
      const m = await box(s.error);
      expect(m.y, 'error under the caption').toBeGreaterThanOrEqual(c.y + c.height - 0.5);
      expect(await s.caption.evaluate((el) => getComputedStyle(el).color)).toBe(await token(page, 'muted'));
      const b = await box(s.submit);
      expect(b.y - (m.y + m.height), 'error to button').toBeCloseTo(40, 0);
    }
    expect(actionPosts, 'no save sent for a refused name').toEqual([]);
    await s.field.fill('🦖'.repeat(80));
    await expect(s.error).toHaveCount(0);
    await s.submit.click();
    await expect(page).toHaveURL(/\/puzzles$/);
    expect((await readAccount(email))?.displayName).toBe('🦖'.repeat(80));
  });

  test('a failed save keeps the step and the value, shows a two-line alert 20px under the button, and a retry saves', async ({ page }) => {
    const email = await newAccountOnStep(page, 'failure');
    let attempts = 0;
    await page.route('**/*', async (route) => {
      const request = route.request();
      if (request.method() === 'POST' && request.headers()['next-action'] && attempts++ === 0) {
        await route.fulfill({ status: 500, contentType: 'text/plain', body: 'Internal Server Error' });
        return;
      }
      await route.fallback();
    });
    const s = step(page);
    await s.field.fill('Grace Hopper');
    await s.submit.click();

    const alert = s.form.getByRole('alert');
    await expect(alert).toBeVisible();
    expect(await lines(alert)).toEqual(['Could not save your username.', 'Please try again.']);
    const a = await box(alert);
    const b = await box(s.submit);
    expect(a.y - (b.y + b.height), 'button to alert').toBeCloseTo(20, 0);
    await expect(page).toHaveURL((url) => url.pathname === '/');
    await expect(s.field).toHaveValue('Grace Hopper');
    await expect(s.field).toBeEnabled();
    await expect(s.submit).toBeEnabled();
    expect((await readAccount(email))?.displayName).toBeNull();

    await s.submit.click();
    await expect(page).toHaveURL(/\/puzzles$/);
    expect(attempts).toBe(2);
    expect((await readAccount(email))?.displayName).toBe('Grace Hopper');
  });

  test('two tabs on the step: each save goes on to /puzzles and the later one is kept', async ({ page, context }) => {
    const email = await newAccountOnStep(page, 'tabs');
    const other = await context.newPage();
    await other.setViewportSize({ width: 1280, height: 800 });
    await other.goto('/');
    await expectStep(other);

    await step(page).field.fill('First Tab');
    await step(page).submit.click();
    await expect(page).toHaveURL(/\/puzzles$/);
    expect((await readAccount(email))?.displayName).toBe('First Tab');

    await step(other).field.fill('Second Tab');
    await step(other).submit.click();
    await expect(other).toHaveURL(/\/puzzles$/);
    expect((await readAccount(email))?.displayName).toBe('Second Tab');
  });
});

