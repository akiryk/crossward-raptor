// Story 23-S3 — Email-only sign-in and the username step.
//
// The front door's form asks for the email only and the magic link carries
// no username. After the link, an account whose username (displayName) is
// blank, new or old, sees the username step at `/`: the front door's title
// ending "Create a username.", one large 400px field named "Username",
// pre-filled with a fresh generated "Adjective Adjective Noun" each time the
// step loads, its "USERNAME" caption under the line, and "Get Started".
// Saving goes on to /puzzles. Until a username is saved, the account reaches
// no page but the step and its server actions refuse, as for no session. An
// account with a username goes straight to /puzzles and keeps its username.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

