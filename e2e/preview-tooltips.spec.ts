// Story 20-S2 — Preview cell tooltips.
//
// In Preview (build phase only), hovering a red or gold cell with the
// mouse shows a tooltip (`preview-tooltip`, role `tooltip`): a gold cell
// (`data-cell-state="recommended"`) "Consider avoiding two-letter words.",
// a red one (`required`) "Filling in these cells will result in a
// symmetrical puzzle." A cell that's both is gold and shows the gold text.
// It follows the cell's mark, also under the cursor's colors, and changes
// or goes with it. One at most; none over other cells or off the grid.
//
// It is `preview-cell-off` with `inverse` `text-label` text, 4px/8px
// padding, 4px corners, no shadow, no arrow, at most 280px wide with the
// text centered; its bottom 4px above the cell, centered on it, at once,
// with no transition. It stays 8px inside the window's sides, and goes
// 4px below the cell when there's no room above. It takes no pointer
// events. A touch tap, the keyboard cursor, Preview off and the hints
// phase show none.
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 900 };
const PHONE = { width: 375, height: 600 };
const GOLD = 'Consider avoiding two-letter words.';
const RED = 'Filling in these cells will result in a symmetrical puzzle.';

type Rgb = { r: number; g: number; b: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

const css = (locator: Locator, property: string, pseudo?: string) =>
  locator.evaluate((el, [p, ps]) => getComputedStyle(el, ps ?? null).getPropertyValue(p as string), [
    property,
    pseudo,
  ] as const);

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

const tooltip = (page: Page) => page.getByTestId('preview-tooltip');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const editorGrid = (page: Page) => page.getByTestId('grid-region');
const previewToggle = (page: Page) => page.getByTestId('preview-toggle');

function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((line, row) => {
    [...line].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/**
 * In Preview (col,row):
 *   L L L L #
 *   L # # # #
 *   g g # G G     g: gold, lettered; G: gold, empty and missing its
 *   # # # # R        symmetric letter (gold wins)
 *   # R R R R     R: red
 */
const marked = () => gridOf(['CATS.', 'O....', 'AD...', '.....', '.....']);

/** The top row's corners are red. */
const corners = () => gridOf(['.....', '.....', '.....', '.....', 'S...T']);

function hintsFor(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  return Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
}

let titleCounter = 0;
async function openBuilder(page: Page, grid: Grid, phase: Phase = 'grid') {
  titleCounter += 1;
  const title = `20-S2 ${phase} ${Date.now()}-${titleCounter}`;
  const { id } = await seedPuzzle({ grid, hints: phase === 'hints' ? hintsFor(grid) : {}, phase }, title);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function previewOn(page: Page) {
  await previewToggle(page).click();
  await expect(previewToggle(page).locator('input')).toBeChecked();
}

async function expectState(page: Page, coord: string, state: string) {
  await expect(cell(page, coord), `${coord} is ${state}`).toHaveAttribute('data-cell-state', state);
}

/** The width of the window's content, without a scrollbar. */
const windowWidth = (page: Page) => page.evaluate(() => document.documentElement.clientWidth);

test.describe('20-S2 Preview cell tooltips', () => {
  test.use({ viewport: WIDE });

  test('20-S2-1 a red cell shows the red text; other cells and off the grid show none', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);
    await expectState(page, '4,4', 'required');
    await expectState(page, '0,0', 'letter');
    await expectState(page, '2,2', 'black');

    await cell(page, '4,4').hover();
    await expect(tooltip(page)).toHaveCount(1);
    await expect(tooltip(page)).toBeVisible();
    await expect(tooltip(page)).toHaveText(RED);
    await expect(page.getByRole('tooltip')).toHaveText(RED);

    await cell(page, '0,0').hover();
    await expect(tooltip(page)).toHaveCount(0);
    await cell(page, '2,2').hover();
    await expect(tooltip(page)).toHaveCount(0);

    await cell(page, '1,4').hover();
    await expect(tooltip(page)).toHaveText(RED);
    await page.mouse.move(2, 2);
    await expect(tooltip(page)).toHaveCount(0);
  });

  test('20-S2-2 a gold cell shows the gold text, also when it misses its symmetric letter', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);
    await expectState(page, '0,2', 'recommended');
    await expectState(page, '3,2', 'recommended');

    // Lettered.
    await cell(page, '0,2').hover();
    await expect(tooltip(page)).toHaveText(GOLD);
    // Empty, and the mirror of the lettered D at 1,2: gold wins.
    await cell(page, '3,2').hover();
    await expect(tooltip(page)).toHaveCount(1);
    await expect(tooltip(page)).toHaveText(GOLD);
  });

  test('20-S2-3 the look: dark, the label style, above the cell and centered, at once', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);

    await cell(page, '3,2').hover();
    // No delay: shown at once, at full opacity, with nothing animating.
    await expect(tooltip(page)).toBeVisible({ timeout: 250 });
    const tip = tooltip(page);
    expect(await css(tip, 'opacity')).toBe('1');
    for (const duration of (await css(tip, 'transition-duration')).split(',')) {
      expect(duration.trim(), 'no transition').toBe('0s');
    }
    expect(await css(tip, 'animation-name')).toBe('none');

    expect(parseColor(await css(tip, 'background-color'))).toEqual(await token(page, 'preview-cell-off'));
    expect(parseColor(await css(tip, 'color'))).toEqual(await token(page, 'inverse'));
    expect(await css(tip, 'font-size')).toBe('14px');
    expect(await css(tip, 'line-height')).toBe('20px');
    expect(await css(tip, 'font-weight')).toBe('400');
    expect(await css(tip, 'text-align')).toBe('center');
    expect(await css(tip, 'padding-top')).toBe('4px');
    expect(await css(tip, 'padding-bottom')).toBe('4px');
    expect(await css(tip, 'padding-left')).toBe('8px');
    expect(await css(tip, 'padding-right')).toBe('8px');
    expect(await css(tip, 'border-top-left-radius')).toBe('4px');
    expect(await css(tip, 'border-bottom-right-radius')).toBe('4px');
    expect(await css(tip, 'box-shadow')).toBe('none');
    expect(await css(tip, 'border-top-width')).toBe('0px');
    // No arrow.
    for (const pseudo of ['::before', '::after']) {
      expect(['none', 'normal'], `${pseudo} content`).toContain(await css(tip, 'content', pseudo));
    }
    await expect(tip.locator('svg')).toHaveCount(0);

    // The gold text on one line, 4px above the cell, centered on it.
    const goldCell = await box(cell(page, '3,2'));
    const gold = await box(tip);
    expectNear(gold.bottom, goldCell.top - 4, 1, 'gold tooltip 4px above the cell');
    expectNear(gold.left + gold.width / 2, goldCell.left + goldCell.width / 2, 1, 'gold tooltip centered');
    expectNear(gold.height, 28, 1, 'gold text on one line');
    expect(gold.width).toBeLessThanOrEqual(280.5);

    // The red text on two lines, at most 280px wide.
    await cell(page, '4,4').hover();
    await expect(tip).toHaveText(RED);
    const redCell = await box(cell(page, '4,4'));
    const red = await box(tip);
    expectNear(red.bottom, redCell.top - 4, 1, 'red tooltip 4px above the cell');
    expectNear(red.left + red.width / 2, redCell.left + redCell.width / 2, 1, 'red tooltip centered');
    expectNear(red.height, 48, 1, 'red text on two lines');
    expect(red.width).toBeLessThanOrEqual(280.5);
  });

  test('20-S2-4 moving between cells, clicking through it, and under the cursor', async ({ page }) => {
    await openBuilder(page, marked());
    await previewOn(page);

    await cell(page, '4,4').hover();
    await expect(tooltip(page)).toHaveText(RED);
    await cell(page, '0,2').hover();
    await expect(tooltip(page)).toHaveCount(1);
    await expect(tooltip(page)).toHaveText(GOLD);
    const goldCell = await box(cell(page, '0,2'));
    const gold = await box(tooltip(page));
    expectNear(gold.bottom, goldCell.top - 4, 1, 'moved above the gold cell');

    // The tooltip covers the bottom of O (0,1); a click there reaches it.
    const above = await box(cell(page, '0,1'));
    const x = gold.left + gold.width / 2;
    const y = gold.top + gold.height / 2;
    expect(x > above.left && x < above.right && y > above.top && y < above.bottom, 'the tooltip covers 0,1').toBe(true);
    await page.mouse.click(x, y);
    await expect(cell(page, '0,1')).toHaveAttribute('data-selected', 'true');
    await expect(tooltip(page)).toHaveCount(0);

    // The cursor's cell and its word keep theirs under the yellow and blue.
    await cell(page, '3,2').click();
    await expect(cell(page, '3,2')).toHaveAttribute('data-selected', 'true');
    await expect(tooltip(page)).toHaveText(GOLD);
    await expect(cell(page, '4,2')).toHaveAttribute('data-highlight', 'slot');
    await cell(page, '4,2').hover();
    await expect(tooltip(page)).toHaveCount(1);
    await expect(tooltip(page)).toHaveText(GOLD);
  });

  test('20-S2-5 the hovered cell\'s mark changes, and goes', async ({ page }) => {
    // C A in a two-letter word; 3,4 and 4,4 their gold, empty mirrors.
    await openBuilder(page, gridOf(['CA...', '.....', '.....', '.....', '.....']));
    await previewOn(page);
    await expectState(page, '4,4', 'recommended');

    await cell(page, '4,4').hover();
    await expect(tooltip(page)).toHaveText(GOLD);

    // Deleting A from the keyboard leaves C alone: 4,4 turns red.
    await editorGrid(page).focus();
    await page.keyboard.press('ArrowRight');
    await expect(cell(page, '1,0')).toHaveAttribute('data-selected', 'true');
    await page.keyboard.press('Backspace');
    await expectState(page, '4,4', 'required');
    await expect(tooltip(page)).toHaveText(RED);

    // A letter typed into it: no longer marked, no tooltip.
    await cell(page, '4,4').click();
    await expect(cell(page, '4,4')).toHaveAttribute('data-selected', 'true');
    await expect(tooltip(page)).toHaveText(RED);
    await page.keyboard.press('X');
    await expectState(page, '4,4', 'letter');
    await expect(tooltip(page)).toHaveCount(0);
  });
});

test.describe('20-S2 on a narrow window', () => {
  test.use({ viewport: PHONE });

  test('20-S2-6 kept 8px inside the window, and below the cell with no room above', async ({ page }) => {
    await openBuilder(page, corners());
    await previewOn(page);
    await expectState(page, '0,0', 'required');
    await expectState(page, '4,0', 'required');
    const width = await windowWidth(page);

    await cell(page, '0,0').hover();
    await expect(tooltip(page)).toHaveText(RED);
    let tip = await box(tooltip(page));
    expect(tip.left, 'left edge 8px in').toBeGreaterThanOrEqual(7.5);
    expect(tip.right).toBeLessThanOrEqual(width - 7.5);
    expectNear(tip.bottom, (await box(cell(page, '0,0'))).top - 4, 1, 'above the left corner');

    await cell(page, '4,0').hover();
    await expect(tooltip(page)).toHaveText(RED);
    tip = await box(tooltip(page));
    expect(tip.right, 'right edge 8px in').toBeLessThanOrEqual(width - 7.5);
    expect(tip.left).toBeGreaterThanOrEqual(7.5);

    // The top row at the window's top: no room above, so below. A short
    // window, so the page scrolls that far.
    await page.mouse.move(2, 2);
    await page.setViewportSize({ width: PHONE.width, height: 300 });
    await page.evaluate(() => {
      const top = document.querySelector('[data-coord="0,0"]')!.getBoundingClientRect().top;
      window.scrollBy(0, top);
    });
    const corner = await box(cell(page, '0,0'));
    expect(corner.top, 'the top row is at the window\'s top').toBeLessThan(8 + 48 + 4);
    await cell(page, '0,0').hover();
    await expect(tooltip(page)).toHaveText(RED);
    tip = await box(tooltip(page));
    const below = await box(cell(page, '0,0'));
    expectNear(tip.top, below.bottom + 4, 1, '4px below the cell');
    expect(tip.left).toBeGreaterThanOrEqual(7.5);
  });
});

