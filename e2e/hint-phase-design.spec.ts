test.describe("14-S6-5 the skeleton's frame", () => {
  test.use({ viewport: { width: 1440, height: 1000 } });

  test('labels are title-4 primary', async ({ page }) => {
    await open(page, cornersGrid());
    for (const orientation of ['across', 'down'] as const) {
      const label = heading(page, orientation);
      await expect(label).toHaveText(orientation === 'across' ? 'Across' : 'Down');
      expect(await style(label, 'font-size')).toBe('14px');
      expect(await style(label, 'font-weight')).toBe('600');
      expect(await style(label, 'color')).toBe(PRIMARY);
    }
  });

  test('the line starts 30px into the column and is 320px; lines 58px apart, the first 45px below the label', async ({ page }) => {
    await open(page, cornersGrid());
    const across = await box(column(page, 'across'));
    const label = await box(heading(page, 'across'));
    const inputs = column(page, 'across').getByTestId('hint-input');
    const first = await lineOf(inputs.nth(0));
    const second = await lineOf(inputs.nth(1));

    expect(first.x - across.x, 'the dot\'s 18px and the 12px gap').toBeCloseTo(30, 0);
    expect(first.width, 'line at full size').toBeCloseTo(320, 0);
    expect(first.y - (label.y + label.height), 'below the label').toBeCloseTo(45, 0);
    expect(second.y - first.y, 'line to line').toBeCloseTo(58, 0);
    expect(second.x, 'every line starts at the same x').toBeCloseTo(first.x, 0);
  });

  test('columns 32px apart, 72px right of the grid; labels level with the first row', async ({ page }) => {
    await open(page, cornersGrid());
    const g = await box(grid(page));
    const across = await box(column(page, 'across'));
    const down = await box(column(page, 'down'));
    const acrossLine = await lineOf(column(page, 'across').getByTestId('hint-input').first());

    expect(across.x - (g.x + g.width), 'from the grid').toBeCloseTo(72, 0);
    expect(down.x - acrossLine.right, 'between columns').toBeCloseTo(32, 0);

    const firstCell = await box(cell(page, '0,0'));
    for (const orientation of ['across', 'down'] as const) {
      const label = await box(heading(page, orientation));
      const centre = label.y + label.height / 2;
      expect(centre, `${orientation} within the first row`).toBeGreaterThanOrEqual(g.y);
      expect(centre, `${orientation} within the first row`).toBeLessThanOrEqual(firstCell.y + firstCell.height);
    }
  });

  test('nothing moves at Create Hints', async ({ page }) => {
    await open(page, dailyGrid(), 'grid');
    const skeleton = page.getByTestId('hint-skeleton');
    const before = {
      across: await box(skeleton.getByText('Across')),
      down: await box(skeleton.getByText('Down')),
      lines: await Promise.all(
        (['across', 'down'] as const).flatMap((o) =>
          [0, 1].map((i) =>
            box(
              page
                .locator(`[data-testid="hint-skeleton-column"][data-orientation="${o}"]`)
                .getByTestId('hint-skeleton-line')
                .nth(i)
            )
          )
        )
      ),
    };

    await step(page, 'hints').click();
    await page.getByRole('button', { name: 'Yes, create hints' }).click();
    await expect(page.getByTestId('hints-region')).toBeVisible();

    expect((await box(heading(page, 'across'))).y, 'Across').toBeCloseTo(before.across.y, 0);
    expect((await box(heading(page, 'across'))).x, 'Across').toBeCloseTo(before.across.x, 0);
    expect((await box(heading(page, 'down'))).x, 'Down').toBeCloseTo(before.down.x, 0);
    const after = [];
    for (const o of ['across', 'down'] as const) {
      for (const i of [0, 1]) after.push(await lineOf(column(page, o).getByTestId('hint-input').nth(i)));
    }
    after.forEach((line, i) => {
      expect(line.x, `line ${i} x`).toBeCloseTo(before.lines[i].x, 0);
      expect(line.y, `line ${i} y`).toBeCloseTo(before.lines[i].y, 0);
      expect(line.width, `line ${i} width`).toBeCloseTo(before.lines[i].width, 0);
    });
  });

  test('the hints scroll in their own box, its top level with the grid', async ({ page }) => {
    await open(page, cornersGrid());
    const region = page.getByTestId('hints-region');
    expect(await style(region, 'overflow-y')).toBe('auto');
    expect((await box(region)).y).toBeCloseTo((await box(grid(page))).y, 0);
  });
});

