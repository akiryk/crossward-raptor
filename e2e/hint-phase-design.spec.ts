/**
 * A 5×5 with off corners at (4,0) and (0,4), every other cell lettered.
 * 1-across is CATS, (0,0)–(3,0); 1-down is CART, (0,0)–(0,3).
 */
function cornersGrid(): Grid {
  const rows = ['CATS.', 'AREAS', 'RENTS', 'TANKS', '.SEES'];
  let grid = createGrid({ cols: 5, rows: 5, black: [{ col: 4, row: 0 }, { col: 0, row: 4 }] });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/** S5's 15×15: ABC across the top, ADE down the left, DF across and BF
 *  down through (1,1), Z at (5,14). Build phase, two words per column. */
function dailyGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  const letters: [number, number, string][] = [
    [0, 0, 'A'], [1, 0, 'B'], [2, 0, 'C'], [0, 1, 'D'], [0, 2, 'E'], [1, 1, 'F'], [5, 14, 'Z'],
  ];
  for (const [col, row, letter] of letters) grid = withLetter(grid, { col, row }, letter);
  return grid;
}

async function open(page: Page, grid: Grid, phase: 'grid' | 'hints' = 'hints') {
  const { id } = await seedPuzzle({ grid, hints: {}, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const grid = (page: Page) => page.getByTestId('puzzle-grid');
const row = (page: Page, key: string) => page.locator(`[data-hint-key="${key}"]`);
const input = (page: Page, key: string) => row(page, key).getByTestId('hint-input');
const answer = (page: Page, key: string) => row(page, key).getByTestId('hint-answer');
const number = (page: Page, key: string) => row(page, key).getByTestId('hint-label');
const column = (page: Page, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="hint-column"][data-orientation="${orientation}"]`);
const heading = (page: Page, orientation: 'across' | 'down') =>
  column(page, orientation).getByTestId('hint-column-heading');
const step = (page: Page, id: string) =>
  page.locator(`[data-testid="builder-steps"] [data-step-id="${id}"]`);

const bg = (locator: Locator) =>
  locator.evaluate((el) => getComputedStyle(el).backgroundColor);
const style = (locator: Locator, property: string) =>
  locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);

/** The opacity an element is drawn at: its own times every ancestor's. */
const drawnOpacity = (locator: Locator) =>
  locator.evaluate((el) => {
    let opacity = 1;
    for (let node: Element | null = el; node; node = node.parentElement) {
      opacity *= Number(getComputedStyle(node).opacity);
    }
    return Math.round(opacity * 1000) / 1000;
  });

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return b;
}

/** An input's line is its 1px bottom border. */
async function lineOf(locator: Locator) {
  const b = await box(locator);
  return { x: b.x, y: b.y + b.height - 1, width: b.width, right: b.x + b.width };
}

const ACROSS_1 = ['0,0', '1,0', '2,0', '3,0'];

test.describe('14-S6-1 the locked grid', () => {
  test.use({ viewport: { width: 1440, height: 1000 } });

  test('on cells white, off cells gray-700, lines gray-500, letters and numbers primary', async ({ page }) => {
    await open(page, cornersGrid());
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'hints');

    expect(await bg(cell(page, '0,0')), 'a lettered cell').toBe(WHITE);
    expect(await bg(cell(page, '2,2')), 'another lettered cell').toBe(WHITE);
    expect(await bg(cell(page, '4,0')), 'an off cell').toBe(OFF);
    expect(await bg(grid(page)), 'the lines').toBe(BORDER);
    const letter = cell(page, '2,2').locator('div').first();
    expect(await style(letter, 'color'), 'a letter').toBe(PRIMARY);
    const cellNumber = cell(page, '0,0').getByTestId('cell-number');
    expect(await style(cellNumber, 'color'), 'a number').toBe(PRIMARY);
  });

  test('the locked grid takes no focus: not on load, not on a click, no Tab stop, no keys', async ({ page }) => {
    await open(page, cornersGrid());
    const region = page.getByTestId('grid-region');
    await expect(region, 'on load').not.toBeFocused();
    expect(await region.getAttribute('tabindex'), 'no Tab stop').toBeNull();
    await expect(row(page, '1-across')).toHaveAttribute('data-active', 'true');

    await cell(page, '1,1').click();
    await expect(region, 'after a click').not.toBeFocused();
    await page.keyboard.press('ArrowDown');

    await expect(row(page, '1-across'), 'the arrow moved nothing').toHaveAttribute('data-active', 'true');
    for (const coord of ['0,0', '1,0', '1,1', '0,1']) {
      expect(await bg(cell(page, coord)), coord).toBe(WHITE);
    }
  });
});

test.describe('14-S6-2 the focused hint\'s word', () => {
  test.use({ viewport: { width: 1440, height: 1000 } });

  test("a focused hint input turns its word's cells blue-medium, and only those", async ({ page }) => {
    await open(page, cornersGrid());
    await input(page, '1-across').click();

    for (const coord of ACROSS_1) {
      await expect.poll(() => bg(cell(page, coord)), coord).toBe(BLUE);
    }
    expect(await bg(cell(page, '0,1')), 'outside the word').toBe(WHITE);
    expect(await bg(cell(page, '4,0')), 'an off cell').toBe(OFF);
    expect(await bg(grid(page)), 'the lines').toBe(BORDER);
  });

  test('the blue follows focus to another hint', async ({ page }) => {
    await open(page, cornersGrid());
    await input(page, '1-across').click();
    await input(page, '1-down').click();

    for (const coord of ['0,0', '0,1', '0,2', '0,3']) {
      await expect.poll(() => bg(cell(page, coord)), coord).toBe(BLUE);
    }
    expect(await bg(cell(page, '1,0')), "1-across's other cells").toBe(WHITE);
  });

  test('the blue goes when focus leaves the hint inputs', async ({ page }) => {
    await open(page, cornersGrid());
    await input(page, '1-across').click();
    await expect.poll(() => bg(cell(page, '1,0'))).toBe(BLUE);

    // A click on the locked grid, which takes focus from the hint.
    await cell(page, '2,2').click();
    for (const coord of ACROSS_1) {
      await expect.poll(() => bg(cell(page, coord)), `grid click, ${coord}`).toBe(WHITE);
    }

    // And to something else entirely.
    await input(page, '1-across').click();
    await expect.poll(() => bg(cell(page, '1,0'))).toBe(BLUE);
    await page.getByTestId('puzzle-title').click();
    for (const coord of ACROSS_1) {
      await expect.poll(() => bg(cell(page, coord)), `title focus, ${coord}`).toBe(WHITE);
    }
  });
});

