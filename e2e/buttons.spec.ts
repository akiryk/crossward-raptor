// Story F3 — Button.
//
// One Button in four types (normal, numbered, large, alternate), each with a
// normal, hover and selected state. Hover's look also shows on keyboard
// focus, never as a focus ring; pressing shows the selected look. Every
// button is a pill with a 1px stroke and is painted only through tokens,
// asserted by color style. A numbered button's number sits in an inverse
// circle drawn in the button's own current color. Alternate has one active
// look, shared by hover, keyboard focus, selected and pressed. Exact sizes
// are not pinned. `/style-guide` catalogs the types, and every existing
// Button use takes the new look. Colors change over a short transition
// (the F6 correction, 2026-10-24), so style reads wait for the element's
// running transitions to finish and assert the settled look.
// Do not edit this file to match an implementation.

const TYPES = ['normal', 'numbered', 'large', 'alternate'] as const;
type ButtonType = (typeof TYPES)[number];
const FILLED: ButtonType[] = ['normal', 'numbered', 'large'];

const SENTINEL = '#123456';

type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) {
    return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  }
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: string, expected: Rgba, label: string) {
  const parsed = parseColor(actual);
  expect({ r: parsed.r, g: parsed.g, b: parsed.b }, label).toEqual({
    r: expected.r,
    g: expected.g,
    b: expected.b,
  });
  expect(parsed.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

/** Everything that makes up a button's visible state. */
function look(locator: Locator) {
  return locator.evaluate(async (el) => {
    for (let i = 0; i < 10 && el.getAnimations().length > 0; i++) {
      await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
    }
    const s = getComputedStyle(el);
    return {
      background: s.backgroundColor,
      border: [s.borderTopColor, s.borderRightColor, s.borderBottomColor, s.borderLeftColor].join(' '),
      borderTop: s.borderTopColor,
      color: s.color,
      outline:
        s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0
          ? 'none'
          : parseColor(s.outlineColor).a === 0
            ? 'none'
            : `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor}`,
      boxShadow: s.boxShadow,
    };
  });
}

function catalogButton(page: Page, type: ButtonType, selected = false) {
  const base = page.locator(`[data-testid="sg-button"][data-button-type="${type}"]`);
  return selected ? base.and(page.locator('[aria-current="true"]')) : base.and(page.locator(':not([aria-current])'));
}

/** Moves the mouse well away from every catalog button. */
async function parkMouse(page: Page) {
  await page.mouse.move(1, 1);
}

/** Focuses a button the way a keyboard user does, so :focus-visible applies. */
async function focusByKeyboard(page: Page, target: Locator) {
  await target.evaluate((el) => el.setAttribute('data-tab-target', ''));
  // Start from the element just before the target in tab order.
  await page.evaluate(() => {
    const all = Array.from(
      document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input, select, textarea, [tabindex]')
    ).filter((el) => el.tabIndex >= 0);
    const index = all.findIndex((el) => el.hasAttribute('data-tab-target'));
    if (index > 0) {
      all[index - 1].focus();
    } else {
      (document.activeElement as HTMLElement | null)?.blur();
    }
  });
  for (let i = 0; i < 5; i++) {
    await page.keyboard.press('Tab');
    if (await target.evaluate((el) => el === document.activeElement)) break;
  }
  await expect(target).toBeFocused();
  await target.evaluate((el) => el.removeAttribute('data-tab-target'));
}

async function catalog(page: Page) {
  await page.goto('/style-guide');
  await expect(page.getByTestId('sg-buttons')).toBeVisible();
  await parkMouse(page);
}

/**
 *   C A T
 *   A . .
 *   T . .
 */
function letteredGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'C');
  grid = withLetter(grid, { col: 1, row: 0 }, 'A');
  grid = withLetter(grid, { col: 2, row: 0 }, 'T');
  grid = withLetter(grid, { col: 0, row: 1 }, 'A');
  grid = withLetter(grid, { col: 0, row: 2 }, 'T');
  return grid;
}

function uniqueTitle(label: string) {
  return `F3 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

async function expectFilled(page: Page, button: Locator, label: string) {
  const l = await look(button);
  expectColor(l.background, await token(page, 'button-fill'), `${label} fill`);
  expectColor(l.color, await token(page, 'inverse'), `${label} text`);
}

async function expectAlternate(page: Page, button: Locator, label: string) {
  const l = await look(button);
  expectColor(l.background, await token(page, 'fill-muted'), `${label} fill`);
  expectColor(l.borderTop, await token(page, 'button-alternate-border'), `${label} border`);
  expectColor(l.color, await token(page, 'subtle'), `${label} text`);
}

/** Alternate's one active look: hover, keyboard focus, selected and pressed. */
async function expectAlternateActive(page: Page, l: Awaited<ReturnType<typeof look>>, label: string) {
  expectColor(l.background, await token(page, 'button-alternate-hover'), `${label} fill`);
  for (const side of l.border.split(/ (?=rgb|color)/)) {
    expectColor(side, await token(page, 'line-dark'), `${label} border`);
  }
  expectColor(l.color, await token(page, 'inverse'), `${label} text`);
}

/** A numbered button's number circle and the colors it shows. */
function numberCircle(button: Locator) {
  return button.locator('[data-button-number]');
}

async function expectShape(button: Locator, label: string) {
  const shape = await button.evaluate((el) => {
    const s = getComputedStyle(el);
    return {
      height: el.getBoundingClientRect().height,
      radii: [s.borderTopLeftRadius, s.borderTopRightRadius, s.borderBottomRightRadius, s.borderBottomLeftRadius],
      widths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
      styles: [s.borderTopStyle, s.borderRightStyle, s.borderBottomStyle, s.borderLeftStyle],
    };
  });
  for (const radius of shape.radii) {
    expect(parseFloat(radius), `${label} is a pill`).toBeGreaterThanOrEqual(shape.height / 2);
  }
  expect(shape.widths, `${label} stroke`).toEqual(['1px', '1px', '1px', '1px']);
  expect(shape.styles, `${label} stroke style`).toEqual(['solid', 'solid', 'solid', 'solid']);
}

// --- F3-1: the catalog ---
test.describe('F3-1 button catalog', () => {
  test('shows each type unselected and selected, plus a disabled button', async ({ page }) => {
    await catalog(page);
    const section = page.getByTestId('sg-buttons');

    for (const type of TYPES) {
      await expect(section.locator(`[data-testid="sg-button"][data-button-type="${type}"]`)).toHaveCount(2);
      await expect(catalogButton(page, type)).toHaveCount(1);
      await expect(catalogButton(page, type, true)).toHaveCount(1);
      for (const button of [catalogButton(page, type), catalogButton(page, type, true)]) {
        await expect(button).toBeVisible();
        expect(await button.evaluate((el) => el.tagName.toLowerCase())).toBe('button');
        expect(await button.getAttribute('type')).toBe('button');
      }
    }
    await expect(section.getByTestId('sg-button-disabled')).toBeDisabled();
  });

  test('a numbered button shows its number before its label', async ({ page }) => {
    await catalog(page);

    for (const button of [catalogButton(page, 'numbered'), catalogButton(page, 'numbered', true)]) {
      const text = (await button.innerText()).replace(/\s+/g, ' ').trim();
      expect(text, 'numbered text').toMatch(/^\d+ \S/);
      const name = await button.evaluate((el) => el.textContent ?? '');
      expect(name.trim(), 'numbered accessible text').toMatch(/^\d+\s*\S/);
    }
    for (const type of ['normal', 'large', 'alternate'] as const) {
      const text = (await catalogButton(page, type).innerText()).trim();
      expect(text, `${type} has no leading number`).not.toMatch(/^\d/);
    }
  });

  test('no horizontal overflow at 1280px or 375px', async ({ page }) => {
    for (const width of [1280, 375]) {
      await page.setViewportSize({ width, height: 800 });
      await page.goto('/style-guide');
      const overflow = await page.evaluate(
        () => document.documentElement.scrollWidth - document.documentElement.clientWidth
      );
      expect(overflow, `overflow at ${width}px`).toBeLessThanOrEqual(0);
    }
  });
});

// --- F3-2: shape and type ---
test.describe('F3-2 shape and type', () => {
  test('every type is a pill with a 1px stroke and its button text style in Inter', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      for (const selected of [false, true]) {
        const button = catalogButton(page, type, selected);
        const label = `${type}${selected ? ' selected' : ''}`;
        await expectShape(button, label);

        const style = type === 'large' ? 'button-large' : 'button-normal';
        const [size, weight] = type === 'large' ? [18, 600] : [14, 600];
        const font = await button.evaluate((el) => {
          const s = getComputedStyle(el);
          return { size: parseFloat(s.fontSize), weight: Number(s.fontWeight), family: s.fontFamily, lh: s.lineHeight };
        });
        expect(font.size, `${label} size (${style})`).toBe(size);
        expect(font.weight, `${label} weight (${style})`).toBe(weight);
        expect(font.family.split(',')[0].replace(/["']/g, '').trim(), `${label} family`).toBe('Inter');
        const tokenLineHeight = await page.evaluate(
          (s) => {
            const probe = document.createElement('div');
            probe.style.fontSize = `var(--text-${s})`;
            probe.style.lineHeight = `var(--text-${s}--line-height)`;
            document.body.appendChild(probe);
            const lh = getComputedStyle(probe).lineHeight;
            probe.remove();
            return lh;
          },
          style
        );
        expect(font.lh, `${label} line height`).toBe(tokenLineHeight);
      }
    }
  });

  test('large is taller than normal; normal, numbered and alternate share a height', async ({ page }) => {
    await catalog(page);
    const height = async (type: ButtonType) => (await catalogButton(page, type).boundingBox())!.height;

    const normal = await height('normal');
    expect(await height('large')).toBeGreaterThan(normal);
    expect(await height('numbered')).toBeCloseTo(normal, 0);
    expect(await height('alternate')).toBeCloseTo(normal, 0);
  });

  test("a numbered button's number sits in an inverse circle in the button's current color", async ({ page }) => {
    await catalog(page);

    const check = async (button: Locator, label: string) => {
      const circle = numberCircle(button);
      await expect(circle, `${label} circle`).toHaveCount(1);
      expect((await circle.innerText()).trim(), `${label} circle holds the number`).toMatch(/^\d+$/);
      const c = await circle.evaluate(async (el) => {
        for (let i = 0; i < 10 && el.getAnimations().length > 0; i++) {
          await Promise.all(el.getAnimations().map((a) => a.finished.catch(() => undefined)));
        }
        const s = getComputedStyle(el);
        const box = el.getBoundingClientRect();
        return {
          width: box.width,
          height: box.height,
          radius: parseFloat(s.borderTopLeftRadius),
          background: s.backgroundColor,
          color: s.color,
        };
      });
      const outer = (await button.boundingBox())!;
      expect(c.width, `${label} circle is round`).toBeCloseTo(c.height, 0);
      expect(c.radius, `${label} circle radius`).toBeGreaterThanOrEqual(c.height / 2);
      expect(c.height, `${label} circle fits inside the button`).toBeLessThan(outer.height);
      expectColor(c.background, await token(page, 'inverse'), `${label} circle fill`);
      expectColor(c.color, parseColor((await look(button)).background), `${label} number follows the button`);
    };

    const button = catalogButton(page, 'numbered');
    await check(button, 'numbered');
    await button.hover();
    await check(button, 'numbered hover');
    await parkMouse(page);
    await focusByKeyboard(page, button);
    await check(button, 'numbered keyboard focus');
    await check(catalogButton(page, 'numbered', true), 'numbered selected');
    for (const type of ['normal', 'large', 'alternate'] as const) {
      await expect(numberCircle(catalogButton(page, type)), `${type} has no number circle`).toHaveCount(0);
    }
  });
});

// --- F3-3: normal state ---
test.describe('F3-3 normal state', () => {
  test('filled types use button-fill with inverse text; alternate uses fill-muted, its border and subtle text', async ({
    page,
  }) => {
    await catalog(page);

    for (const type of FILLED) {
      await expectFilled(page, catalogButton(page, type), type);
    }
    await expectAlternate(page, catalogButton(page, 'alternate'), 'alternate');
  });

  test('interactive buttons report a pointer cursor and show no outline', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const button = catalogButton(page, type);
      expect(await button.evaluate((el) => getComputedStyle(el).cursor), `${type} cursor`).toBe('pointer');
      expect((await look(button)).outline, `${type} outline`).toBe('none');
    }
  });
});

// --- F3-4: hover ---
test.describe('F3-4 hover', () => {
  test('hover changes every type: filled types turn button-hover, alternate takes its active look', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const button = catalogButton(page, type);
      const before = await look(button);
      await button.hover();
      const after = await look(button);
      expect(after, `${type} hover differs`).not.toEqual(before);
      if (FILLED.includes(type)) {
        expectColor(after.background, await token(page, 'button-hover'), `${type} hover fill`);
      } else {
        await expectAlternateActive(page, after, 'alternate hover');
      }
      await parkMouse(page);
      expect(await look(button), `${type} restores after hover`).toEqual(before);
    }
  });
});

// --- F3-5: keyboard focus ---
test.describe('F3-5 keyboard focus', () => {
  test('keyboard focus shows exactly the hover look, with no focus ring', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const button = catalogButton(page, type);
      await button.hover();
      const hovered = await look(button);
      await parkMouse(page);

      await focusByKeyboard(page, button);
      const focused = await look(button);
      expect(focused, `${type} keyboard focus looks like hover`).toEqual(hovered);
      expect(focused.outline, `${type} focus outline`).toBe('none');
    }
  });

  test('mouse focus shows no hover look once the pointer leaves', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const button = catalogButton(page, type);
      const before = await look(button);
      await button.click();
      await parkMouse(page);
      await expect(button).toBeFocused();
      expect(await look(button), `${type} after mouse click`).toEqual(before);
    }
  });
});

// --- F3-6: selected ---
test.describe('F3-6 selected', () => {
  test('the selected look: button-active for filled types, the active look for alternate', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const normal = await look(catalogButton(page, type));
      const selectedButton = catalogButton(page, type, true);
      const selected = await look(selectedButton);
      expect(selected, `${type} selected differs from normal`).not.toEqual(normal);

      await catalogButton(page, type).hover();
      const hovered = await look(catalogButton(page, type));
      await parkMouse(page);

      if (FILLED.includes(type)) {
        expect(selected, `${type} selected differs from hover`).not.toEqual(hovered);
        expectColor(selected.background, await token(page, 'button-active'), `${type} selected fill`);
        expectColor(selected.color, await token(page, 'inverse'), `${type} selected text`);
      } else {
        expect(selected, 'alternate selected looks like its hover').toEqual(hovered);
        await expectAlternateActive(page, selected, 'alternate selected');
      }
    }
  });

  test('a selected button keeps its look under hover and keyboard focus', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const button = catalogButton(page, type, true);
      const selected = await look(button);
      await button.hover();
      expect(await look(button), `${type} selected under hover`).toEqual(selected);
      await parkMouse(page);
      await focusByKeyboard(page, button);
      expect(await look(button), `${type} selected under keyboard focus`).toEqual(selected);
    }
  });

  test('pressing a button shows the selected look until release', async ({ page }) => {
    await catalog(page);

    for (const type of TYPES) {
      const button = catalogButton(page, type);
      const selected = await look(catalogButton(page, type, true));
      const before = await look(button);

      await button.hover();
      await page.mouse.down();
      expect(await look(button), `${type} while pressed`).toEqual(selected);
      await page.mouse.up();
      await parkMouse(page);
      expect(await look(button), `${type} after release`).toEqual(before);
    }
  });
});

// --- F3-7: disabled ---
test.describe('F3-7 disabled', () => {
  test('a disabled button is dimmed, not-allowed and unchanged by hover or press', async ({ page }) => {
    await catalog(page);
    const button = page.getByTestId('sg-button-disabled');

    const s = await button.evaluate((el) => {
      const cs = getComputedStyle(el);
      return { opacity: Number(cs.opacity), cursor: cs.cursor };
    });
    expect(s.opacity).toBeLessThan(1);
    expect(s.cursor).toBe('not-allowed');
    await expectShape(button, 'disabled');

    const before = await look(button);
    await button.hover({ force: true });
    expect(await look(button), 'disabled under hover').toEqual(before);
    await page.mouse.down();
    expect(await look(button), 'disabled while pressed').toEqual(before);
    await page.mouse.up();
  });
});

// --- F3-8: tokens drive the look ---
test.describe('F3-8 token-driven', () => {
  test('buttons follow live edits of their color variables and the pill radius', async ({ page }) => {
    await catalog(page);
    const normal = catalogButton(page, 'normal');
    const alternate = catalogButton(page, 'alternate');
    const sentinel = parseColor('rgb(18, 52, 86)');

    await page.evaluate((v) => document.documentElement.style.setProperty('--palette-interactive-light', v), SENTINEL);
    expectColor((await look(normal)).background, sentinel, 'normal fill follows interactive-light');
    await page.evaluate(() => document.documentElement.style.removeProperty('--palette-interactive-light'));

    await page.evaluate((v) => document.documentElement.style.setProperty('--palette-gray-200', v), SENTINEL);
    expectColor((await look(alternate)).background, sentinel, 'alternate fill follows gray-200');
    await page.evaluate(() => document.documentElement.style.removeProperty('--palette-gray-200'));

    await page.evaluate((v) => document.documentElement.style.setProperty('--palette-white', v), SENTINEL);
    expectColor((await look(normal)).color, sentinel, 'normal text follows white');
    await page.evaluate(() => document.documentElement.style.removeProperty('--palette-white'));

    await page.evaluate((v) => document.documentElement.style.setProperty('--palette-gray-600', v), SENTINEL);
    expectColor((await look(alternate)).color, sentinel, 'alternate text follows gray-600');
    await page.evaluate(() => document.documentElement.style.removeProperty('--palette-gray-600'));

    await page.evaluate((v) => document.documentElement.style.setProperty('--palette-gray-500', v), SENTINEL);
    await alternate.hover();
    expectColor((await look(alternate)).background, sentinel, 'alternate hover fill follows gray-500');
    await parkMouse(page);
    await page.evaluate(() => document.documentElement.style.removeProperty('--palette-gray-500'));

    const pill = await normal.evaluate((el) => getComputedStyle(el).borderTopLeftRadius);
    await page.evaluate(() => document.documentElement.style.setProperty('--radius-pill', '3px'));
    expect(await normal.evaluate((el) => getComputedStyle(el).borderTopLeftRadius)).toBe('3px');
    await page.evaluate(() => document.documentElement.style.removeProperty('--radius-pill'));
    expect(await normal.evaluate((el) => getComputedStyle(el).borderTopLeftRadius)).toBe(pill);
  });
});

// --- F3-9: every existing use takes the new look ---
test.describe('F3-9 adoption', () => {
  test('the new-puzzle button is a normal button', async ({ page }) => {
    await page.goto('/puzzles');
    await parkMouse(page);
    const button = page.getByTestId('new-puzzle-button');
    await expectFilled(page, button, 'new-puzzle');
    await expectShape(button, 'new-puzzle');
    expect(await button.evaluate((el) => parseFloat(getComputedStyle(el).fontSize))).toBe(14);
  });

  test('builder actions: delete and confirm are normal, clear-letters and cancel are alternate', async ({ page }) => {
    const { id } = await seedPuzzle({ grid: letteredGrid(), hints: {}, phase: 'grid' }, uniqueTitle('adoption'));
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await parkMouse(page);

    await expectFilled(page, page.getByTestId('delete-puzzle-button'), 'delete');
    await expectAlternate(page, page.getByTestId('clear-letters-button'), 'clear-letters');

    await page.getByTestId('delete-puzzle-button').click();
    await parkMouse(page);
    await expectFilled(page, page.getByTestId('delete-confirm-button'), 'delete confirm');
    await expectAlternate(page, page.getByTestId('delete-cancel-button'), 'delete cancel');
    await page.getByTestId('delete-cancel-button').click();

    await page.getByTestId('clear-letters-button').click();
    await parkMouse(page);
    await expectFilled(page, page.getByTestId('clear-letters-confirm-button'), 'clear confirm');
    await expectAlternate(page, page.getByTestId('clear-letters-cancel-button'), 'clear cancel');
  });

  test('the new-puzzle dialog: confirm is normal, cancel is alternate', async ({ page }) => {
    await page.goto('/puzzles');
    await page.getByTestId('new-puzzle-button').click();
    await parkMouse(page);
    const dialog = page.getByRole('dialog');
    await expect(dialog).toBeVisible();

    const confirm = dialog.getByTestId('new-puzzle-create');
    const cancel = dialog.getByTestId('new-puzzle-cancel');
    // The confirm may start disabled until the form is valid; its colors
    // are still the normal type's.
    expectColor((await look(confirm)).background, await token(page, 'button-fill'), 'modal confirm fill');
    await expectAlternate(page, cancel, 'modal cancel');
  });
});
