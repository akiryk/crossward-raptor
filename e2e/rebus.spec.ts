  test('17-S10-4 the open entry: 4/3 of the cell, centered and above it, white, with the rebus shadow', async ({ page }) => {
    const id = await seedBuilder(createGrid({ cols: 15, rows: 15 }), 'grid');
    await openBuilder(page, id);
    const target = cell(page, '7,7');
    await target.click();
    const before = { cell: await box(target), neighbor: await box(cell(page, '8,7')), grid: await box(editorGrid(page)) };

    await page.keyboard.press('Escape');
    await expectOpen(page, '');
    const open = await box(entry(page));
    expectNear(open.width, before.cell.width * 4 / 3, 1.5, 'width');
    expectNear(open.height, before.cell.height * 4 / 3, 1.5, 'height');
    expectNear(open.left + open.width / 2, before.cell.left + before.cell.width / 2, 1, 'center x');
    expectNear(open.top + open.height / 2, before.cell.top + before.cell.height / 2, 1, 'center y');

    // Nothing else moves.
    expect(await box(target)).toEqual(before.cell);
    expect(await box(cell(page, '8,7'))).toEqual(before.neighbor);
    expect(await box(editorGrid(page))).toEqual(before.grid);

    // Above its neighbors: the point over the next cell, inside the box, is the entry's.
    const onTop = await entry(page).evaluate((el, point) => {
      const hit = document.elementFromPoint(point.x, point.y);
      return hit !== null && el.contains(hit);
    }, { x: open.right - 3, y: open.top + open.height / 2 });
    expect(onTop, 'the entry is above the next cell').toBe(true);

    const white = await token(page, 'build-cell-on');
    const fill = parseColor(await css(entry(page), 'background-color'));
    expect(fill).toEqual({ ...white, a: 1 });

    // Layers that paint nothing (transparent, as a ring's when unused) are ignored.
    const shadow = (await css(entry(page), 'box-shadow'))
      .split(/,(?![^(]*\))/)
      .map((layer) => layer.trim())
      .filter((layer) => !/^rgba\(0, 0, 0, 0\) 0px 0px 0px 0px$/.test(layer))
      .join(', ');
    const expected = await page.evaluate(() => {
      const probe = document.createElement('div');
      probe.style.boxShadow = 'var(--shadow-rebus-cell)';
      document.body.appendChild(probe);
      const resolved = getComputedStyle(probe).boxShadow;
      probe.remove();
      return resolved;
    });
    expect(expected, '--shadow-rebus-cell is declared').not.toBe('none');
    expect(shadow).toBe(expected);
    expect(shadow).toMatch(/\b0px 4px 4px 0px\b/);
    const shadowColor = parseColor(shadow.replace(/\s*-?\d+(\.\d+)?px/g, '').trim());
    expect(shadowColor).toEqual({ r: 0, g: 0, b: 0, a: 0.25 });

    // Its text fits the box.
    await page.keyboard.type('abcdefghij');
    const fits = await entryInput(page).evaluate((el) => el.scrollWidth <= el.clientWidth + 1);
    expect(fits, 'ten characters fit the entry').toBe(true);

    await page.keyboard.press('Enter');
    await expectClosed(page);
  });

