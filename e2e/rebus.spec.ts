// Story 17-S10 — Rebus.
//
// Wherever letters can be typed (the build phase, Preview included, the
// hints phase unless Lock Grid Letters is on, and play), Escape with the
// grid focused opens a rebus entry on the cursor cell, starting from its
// letters. The entry (`rebus-entry`, a text box named "Rebus entry") has
// focus; it keeps letters and digits, uppercase, at most 10. Enter or
// Escape closes it and places the whole string in the cell, and the
// cursor advances as after a single letter. Leaving it (a click elsewhere,
// Tab) also places it, without advancing. An empty entry clears the cell,
// except in the hints phase, where it changes nothing. The grid has focus
// again after Enter or Escape.
//
// While open, the entry is a box 4/3 of the cell, centered on it, above its
// neighbors, in the grid's white, with the `--shadow-rebus-cell` shadow
// (x 0, y 4, blur 4, spread 0, black at 25%); nothing else moves. Its text
// fits the box. A placed rebus is as large as fits the cell, up to the
// letter size, on one line, clear of the number. It never shrinks below a
// third of the letter size: longer, it stays at that size, centered on the
// cell, and is cut off at the cell's edges.
//
// The Rebus control (`rebus-control`, a button named "Rebus") does what
// Escape does, and closes an open entry as Enter does. In the builder it is
// a text link at the right end of the toggle row, 16px in (12px below a
// 748px window), `link-muted`, the toggle label's size (20-S1 put Start
// Over after it; 20-S4 moved it under the grid); inactive (disabled,
// 50% opacity, not-allowed cursor) while Lock Grid Letters is on, and
// absent when published. In play it is an outlined pill: wide, at the top
// of the hints column, at its left edge, centered on the Prominent Hint;
// narrow, under the hint bar at the grid's right edge, 12px down. 32px
// tall, 1px `button-fill` border and text, no fill. A completed puzzle
// has none (19-S1).
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const PHONE = { width: 375, height: 900 };

type Rgb = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+))?/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: rgb[4] === undefined ? 1 : Number(rgb[4]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: srgb[4] === undefined ? 1 : Number(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

const css = (locator: Locator, property: string) =>
  locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

const visible = (locator: Locator) => locator.filter({ visible: true });
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const entry = (page: Page) => page.getByTestId('rebus-entry');
const entryInput = (page: Page) => page.getByRole('textbox', { name: 'Rebus entry', exact: true });
const control = (page: Page) => visible(page.getByTestId('rebus-control'));
const editorGrid = (page: Page) => page.getByTestId('grid-region');
const playGrid = (page: Page) => page.getByTestId('play-grid-region');

/** A cell's letters, without its number. */
function cellText(page: Page, coord: string) {
  return cell(page, coord).evaluate((element) => {
    const clone = element.cloneNode(true) as HTMLElement;
    clone.querySelectorAll('[data-testid="cell-number"]').forEach((number) => number.remove());
    clone.querySelectorAll('[data-testid="rebus-entry"]').forEach((open) => open.remove());
    return clone.textContent?.trim() ?? '';
  });
}

async function expectText(page: Page, coord: string, text: string) {
  await expect.poll(() => cellText(page, coord), `cell ${coord}`).toBe(text);
}

async function expectSelected(page: Page, coord: string) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(1);
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
}

async function expectOpen(page: Page, value: string) {
  await expect(entry(page)).toHaveCount(1);
  await expect(entryInput(page)).toBeFocused();
  await expect(entryInput(page)).toHaveValue(value);
}

async function expectClosed(page: Page) {
  await expect(entry(page)).toHaveCount(0);
  await expect(entryInput(page)).toHaveCount(0);
}

function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((line, row) => {
    [...line].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/** A 3×3 word square, CAT / ARE / TEA. */
const wordSquare = () => gridOf(['CAT', 'ARE', 'TEA']);

function hintsFor(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  return Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
}

let titleCounter = 0;
async function seedBuilder(grid: Grid, phase: Phase, options: { published?: boolean } = {}) {
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid, hints: phase === 'hints' ? hintsFor(grid) : {}, phase },
    `S10 ${phase} ${Date.now()}-${titleCounter}`,
  );
  if (options.published) {
    const client = ownershipTestClient();
    try {
      await client.puzzle.update({
        where: { id },
        data: { publishedAt: new Date('2026-10-01T00:00:00Z'), visibility: 'public' },
      });
    } finally {
      await client.$disconnect();
    }
  }
  return id;
}

async function openBuilder(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

/** The saved builder letter at a cell, polled past the autosave. */
async function expectSavedLetter(id: string, col: number, row: number, letter: string | null) {
  await expect.poll(async () => {
    const stored = (await readPlayPuzzle(id)).grid as unknown as SerializedGrid;
    const saved = stored.cells[row][col];
    return saved.kind === 'active' ? saved.letter : 'black';
  }, `saved (${col},${row})`).toBe(letter);
}

async function seedPlay(page: Page, entries?: Grid) {
  const builderId = await currentBuilderId(page);
  const fixture = await seedPlayPuzzle({ builderId, puzzle: playPuzzleFixture() });
  if (entries) await seedPlaySession(builderId, fixture.id, entries);
  return fixture;
}

async function openPlay(page: Page, id: string) {
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
  await expect(playGrid(page)).toHaveAttribute('data-ready', 'true');
}

async function expectSavedEntry(puzzleId: string, col: number, row: number, letter: string | null) {
  await expect.poll(async () => {
    const [session] = await readPlaySessions(puzzleId);
    const saved = session?.entries.cells[row][col];
    return saved && saved.kind === 'active' ? saved.letter : undefined;
  }, `saved entry (${col},${row})`).toBe(letter);
}

/** A cell's text node (not its number): one rect per line, its font size. */
function placedText(page: Page, coord: string) {
  return cell(page, coord).evaluate((element) => {
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let node: Node | null;
    while ((node = walker.nextNode())) {
      if (!node.textContent?.trim()) continue;
      if ((node.parentElement as HTMLElement).closest('[data-testid="cell-number"]')) continue;
      const range = document.createRange();
      range.selectNodeContents(node);
      const rects = Array.from(range.getClientRects()).filter((r) => r.width > 0);
      const all = range.getBoundingClientRect();
      const number = element.querySelector('[data-testid="cell-number"]')?.getBoundingClientRect();
      const own = element.getBoundingClientRect();
      return {
        text: node.textContent.trim(),
        lines: rects.length,
        rect: { left: all.left, right: all.right, top: all.top, bottom: all.bottom },
        cell: { left: own.left, right: own.right, top: own.top, bottom: own.bottom },
        number: number ? { left: number.left, right: number.right, top: number.top, bottom: number.bottom } : null,
        fontSize: parseFloat(getComputedStyle(node.parentElement as HTMLElement).fontSize),
      };
    }
    throw new Error('no letters in the cell');
  });
}

