import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S12 — the lock button before the word.
//
// The lock button beside a word (21-S2) sits just before its first letter:
// left of it for an across word, above it for a down word, so it is never
// in the way of typing on through the word. Where the word starts at the
// grid's left or top edge it sits outside the grid, and the page has room
// for it there: it is never cut off by the window or drawn over the
// toggle row. The grid has at least 36px left of it wherever the button
// shows (12px more than the page's 24px in the wide layout; a narrower
// window that leaves less uses the toggle row's Lock Word, 21-S5), and
// 36px between the toggle row and the grid (16px where the toggle row's
// Lock Word is used).
//
// Hooks: the button is 21-S2's "Lock word" / "Unlock word"; the toggle row
// [data-testid="toggle-row"]; its Lock Word [data-testid="lock-word-control"].
//
// Amended by 21-S16: the button beside a word waits 3 seconds (was 1);
// every wait timed against it is 2000ms longer.
//
// Do not edit this file to match an implementation.

const LOCK_WAIT_MS = 4500;

/** Every cell lettered: every row and column is one complete word. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'M');
  }
  return grid;
}

/** A daily: TANGENT across row 3 (3–9), ends (2,3) and (10,3); ONE down
 *  column 11 (6–8), ends (11,5) and (11,9). Both end cells of each are
 *  Preview-black. */
function wordsGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  [...'TANGENT'].forEach((letter, i) => (grid = withLetter(grid, { col: 3 + i, row: 3 }, letter)));
  [...'ONE'].forEach((letter, i) => (grid = withLetter(grid, { col: 11, row: 6 + i }, letter)));
  return grid;
}

async function open(page: Page, grid: Grid, width: number) {
  await page.setViewportSize({ width, height: 1000 });
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, `21-S12 ${Date.now()}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const lockControl = (page: Page) => page.getByTestId('lock-word-control').filter({ visible: true });
const ticks = (page: Page) => page.getByTestId('lock-tick');
const grid = (page: Page) => page.getByTestId('puzzle-grid');
const toggleRow = (page: Page) => page.getByTestId('toggle-row');

async function rect(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

function near(a: number, b: number, tolerance = 2) {
  return Math.abs(a - b) <= tolerance;
}

/** The cursor on this cell, in this direction, its button shown. */
async function inWord(page: Page, coord: string, orientation: 'across' | 'down') {
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  if (orientation === 'down') await page.keyboard.press(' ');
  await expect(lockButton(page)).toBeVisible({ timeout: LOCK_WAIT_MS });
}

/** The topmost element at the button's middle is the button: not cut off,
 *  not under anything. */
async function isOnTop(page: Page) {
  const b = await rect(lockButton(page));
  return page.evaluate(
    ({ x, y }) => {
      const el = document.elementFromPoint(x, y);
      return !!el?.closest('button')?.getAttribute('aria-label')?.match(/^(Lock|Unlock) word$/);
    },
    { x: b.x + b.width / 2, y: b.y + b.height / 2 }
  );
}

function noHorizontalOverflow(page: Page) {
  return page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth);
}

// --- 21-S12-1: out of the way of typing ---
test.describe('21-S12-1 the end cell after the word is free', () => {
  test('across: a click in the middle of the cell after TANGENT moves the cursor there; nothing locks', async ({ page }) => {
    await open(page, wordsGrid(), 1440);
    await inWord(page, '6,3', 'across');
    const after = await rect(cell(page, '10,3'));
    const b = await rect(lockButton(page));
    expect(b.x >= after.right || b.right <= after.x, 'the button is not over the end cell after the word').toBe(true);

    await page.mouse.click(after.x + after.width / 2, after.y + after.height / 2);
    await expect(cell(page, '10,3')).toHaveAttribute('data-selected', 'true');
    await expect(ticks(page)).toHaveCount(0);
  });

  test('down: a click in the middle of the cell after ONE moves the cursor there; nothing locks', async ({ page }) => {
    await open(page, wordsGrid(), 1440);
    await inWord(page, '11,7', 'down');
    const after = await rect(cell(page, '11,9'));
    const b = await rect(lockButton(page));
    expect(b.y >= after.bottom || b.bottom <= after.y, 'the button is not over the end cell after the word').toBe(true);

    await page.mouse.click(after.x + after.width / 2, after.y + after.height / 2);
    await expect(cell(page, '11,9')).toHaveAttribute('data-selected', 'true');
    await expect(ticks(page)).toHaveCount(0);
  });
});

// --- 21-S12-2: at the grid's left and top edges ---
test.describe('21-S12-2 a word at the grid\'s edge', () => {
  // [name, size, window width]: wide, the narrowest wide, one column, and
  // the narrowest window with the button beside the word, for each size.
  const cases: [string, number, number][] = [
    ['a Daily at 1440px', 15, 1440],
    ['a Daily at 1140px', 15, 1140],
    ['a Daily at 1000px', 15, 1000],
    ['a Daily at 692px', 15, 692],
    ['a Mini at 1440px (a 32px button)', 5, 1440],
    ['a Mini at 692px (a 32px button)', 5, 692],
    ['a Sunday at 1440px', 21, 1440],
    ['a Sunday at 772px', 21, 772],
  ];
  for (const [name, size, width] of cases) {
    test(`${name}: left of the grid for across, above it for down; whole, on top, not over the toggle row`, async ({ page }) => {
      await open(page, filled(size), width);
      const mid = Math.floor(size / 2);
      const g = await rect(grid(page));
      expect(g.x, 'at least 36px left of the grid').toBeGreaterThanOrEqual(36 - 0.5);

      // Across: row `mid`, from the left edge.
      await inWord(page, `${mid},${mid}`, 'across');
      const first = await rect(cell(page, `0,${mid}`));
      let b = await rect(lockButton(page));
      expect(near(b.right, first.x), `left of the first letter: right ${b.right}`).toBe(true);
      expect(near(b.y + b.height / 2, first.y + first.height / 2, 1), 'vertically centered').toBe(true);
      expect(b.right, 'outside the grid').toBeLessThanOrEqual(g.x + 0.5);
      expect(b.x, 'within the window').toBeGreaterThanOrEqual(0);
      expect(await isOnTop(page), 'the button is on top at its middle').toBe(true);
      expect(await noHorizontalOverflow(page), 'nothing past the window').toBe(true);

      // Down: column `mid`, from the top edge.
      await page.keyboard.press(' ');
      const top = await rect(cell(page, `${mid},0`));
      await expect
        .poll(async () => near((await rect(lockButton(page))).bottom, top.y), { timeout: LOCK_WAIT_MS, message: 'above the first letter' })
        .toBe(true);
      b = await rect(lockButton(page));
      expect(near(b.x + b.width / 2, top.x + top.width / 2, 1), 'horizontally centered').toBe(true);
      expect(b.bottom, 'outside the grid').toBeLessThanOrEqual(g.y + 0.5);
      const row = await rect(toggleRow(page));
      expect(b.y, 'below the toggle row, not over it').toBeGreaterThanOrEqual(row.bottom - 0.5);
      expect(await isOnTop(page), 'the button is on top at its middle').toBe(true);
    });
  }
});

// --- 21-S12-3: room, or the toggle row's Lock Word ---
test.describe('21-S12-3 the button only where it has room', () => {
  // [name, size, window, where]: the narrowest window with 36px left of a
  // full grid, and 1px less, where the full grid has only 35.5px.
  const cases: [string, number, number, 'beside' | 'row'][] = [
    ['a Daily at 692px', 15, 692, 'beside'],
    ['a Daily at 691px', 15, 691, 'row'],
    ['a Mini at 692px', 5, 692, 'beside'],
    ['a Mini at 691px', 5, 691, 'row'],
    ['a Sunday at 772px', 21, 772, 'beside'],
    ['a Sunday at 771px', 21, 771, 'row'],
  ];
  for (const [name, size, width, where] of cases) {
    test(`${name}: ${where === 'beside' ? 'the button beside the word, 36px from the toggle row to the grid' : 'the toggle row’s Lock Word, 16px from the toggle row to the grid'}`, async ({ page }) => {
      await open(page, filled(size), width);
      const g = await rect(grid(page));
      const row = await rect(toggleRow(page));
      expect(g.width, 'the grid at its full width').toBeCloseTo(size === 21 ? 700 : 620, 0);

      await cell(page, '1,1').click();
      await expect(cell(page, '1,1')).toHaveAttribute('data-selected', 'true');
      if (where === 'beside') {
        expect(g.y - row.bottom, 'toggle row to grid').toBeCloseTo(36, 0);
        await expect(lockButton(page)).toBeVisible({ timeout: LOCK_WAIT_MS });
        await expect(lockControl(page)).toHaveCount(0);
      } else {
        expect(g.y - row.bottom, 'toggle row to grid').toBeCloseTo(16, 0);
        await expect(lockControl(page)).toBeVisible();
        await expect(lockControl(page)).toHaveText('Lock Word');
        await page.waitForTimeout(3500);
        await expect(lockButton(page)).toHaveCount(0);
      }
    });
  }

  test('the hints phase keeps the build phase\'s 36px, so the grid stays put', async ({ page }) => {
    await page.setViewportSize({ width: 1000, height: 1000 });
    for (const phase of ['grid', 'hints'] as const) {
      const { id } = await seedPuzzle({ grid: filled(15), hints: {}, phase }, `21-S12 ${Date.now()}`);
      await page.goto(`/puzzles/${id}`);
      await waitForEditorReady(page);
      const g = await rect(grid(page));
      const row = await rect(toggleRow(page));
      expect(g.y - row.bottom, `${phase}: toggle row to grid`).toBeCloseTo(36, 0);
    }
  });
});
