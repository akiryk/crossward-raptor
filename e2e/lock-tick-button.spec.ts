const run = (from: number, word: string) => [...word].map((_, i) => from + i);
const across = (row: number, cols: number[]) => cols.map((col) => `${col},${row}`);
const down = (col: number, rows: number[]) => rows.map((row) => `${col},${row}`);

// 21-S11's daily (counterpart of (c,r) is (14−c, 14−r)), every word
// complete and lockable, every end cell named below Preview-black:
//   TANGENT across row 2 (3–9), ends (2,2) and (10,2);
//   CAT across row 7 (2–4), ends (1,7) and (5,7);
//   DOG across row 7 (6–8), ends (5,7) and (9,7);
//   OWL down column 5 (8–10), ends (5,7) and (5,11).
