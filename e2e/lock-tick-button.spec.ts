// Story 21-S13 — hovering a ticked end cell shows its word's lock button.
//
// In the build phase with Preview off, a locked word's end cells carry a
// tick (21-S2). The mouse anywhere on a ticked end cell (not only on the
// tick's square) darkens every locked word ending there at once (21-S11).
// After a second there, one of those words' lock button (21-S2) shows
// too: the one in the cursor's direction if any, else the other
// direction's; within a direction, the word starting just after the cell
// wins over the one ending just before it. A turn of the cursor while the
// mouse rests on the cell picks again, and the new word's second starts
// over. Once shown, the button is a 21-S10 hover of that word, under 21-S10's
// rules: it stays while the mouse is on the end cell, the word's cells
// (its other end cell included) or the button, and goes at once when the
// mouse moves elsewhere. Clicking it toggles the word without moving the
// cursor or taking focus. Hover wins over the cursor's button, except a
// lock button with keyboard focus. A click in a cell ends the hover, and
// a mouse resting on the clicked cell starts none. The darkening goes when
// the mouse leaves the end cell, except onto the button of the tick's
// word, where it stays (a button that comes up under the resting mouse
// doesn't end it). Where the button can't show beside a word (21-S5,
// 21-S12) and on a touch screen, no button comes.
//
// Hooks: 21-S2's "Lock word" / "Unlock word" button and its tick
// [data-testid="lock-tick"]; the toggle row's Lock Word
// [data-testid="lock-word-control"] (21-S5). The darkening is read as in
// 21-S11, from a grid screenshot at each cell's lower left (1/10 across,
// 92/100 down).
//
// Amended by 21-S15: a tick hover no longer darkens its words; it outlines
// each in black, around its letters (not its end cells), and their paint
// is unchanged. Where this file says "darker" or "the darkening", read
// "outlined" or "the outline"; expectPaint and expectPaintNow check it.
//
// Amended by 21-S16: the button's wait is 3 seconds (was 1). "Not yet"
// is at 2500ms, "long enough" 3500ms, and the cursor's button is awaited
// 4000ms (was 2000ms). Where this file says "a second", read three.
//
// Timing: "not yet" is checked once after 500ms of hover (a timer can
// fire late under load, never early); "shown" allows up to 1500ms more;
// "at once" is 300ms for the button and 500ms for paint (a screenshot is
// taken each try).
//
// Do not edit this file to match an implementation.

