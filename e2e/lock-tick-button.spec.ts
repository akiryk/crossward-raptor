const TANGENT = across(2, run(3, 'TANGENT'));
const TANGENT_ENDS = ['2,2', '10,2'];
const CAT = across(7, run(2, 'CAT'));
const DOG = across(7, run(6, 'DOG'));
const OWL = down(5, run(8, 'OWL'));
const SHARED = '5,7';
const EMPTY = '13,13';
