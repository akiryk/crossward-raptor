type Box = { x: number; y: number; width: number; height: number };

async function boxOf(locator: Locator): Promise<Box> {
  const box = await locator.boundingBox();
  if (!box) throw new Error('no bounding box');
  return box;
}

function near(a: number, b: number, tolerance = 2) {
  return Math.abs(a - b) <= tolerance;
}

/** Whether the one lock button sits just before this first letter
 *  (21-S12): left of it, vertically centered, for across; above it,
 *  horizontally centered, for down. */
async function isButtonBeside(page: Page, first: string, orientation: 'across' | 'down') {
  if ((await lockButton(page).count()) !== 1) return false;
  const b = await lockButton(page).boundingBox();
  const c = await cell(page, first).boundingBox();
  if (!b || !c) return false;
  return orientation === 'across'
    ? near(b.x + b.width, c.x) && near(b.y + b.height / 2, c.y + c.height / 2, 1)
    : near(b.y + b.height, c.y) && near(b.x + b.width / 2, c.x + c.width / 2, 1);
}

async function expectButtonBeside(page: Page, first: string, orientation: 'across' | 'down') {
  await expect(lockButton(page)).toHaveCount(1);
  expect(await isButtonBeside(page, first, orientation), `the button is just before ${first}, ${orientation}`).toBe(
    true
  );
}

/** Within `timeout`, the one button is just before this first letter. */
async function expectButtonBesideWithin(
  page: Page,
  first: string,
  orientation: 'across' | 'down',
  timeout: number
) {
  await expect
    .poll(() => isButtonBeside(page, first, orientation), {
      timeout,
      message: `the button is just before ${first}, ${orientation}`,
    })
    .toBe(true);
}

async function select(page: Page, coord: string) {
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
}

/** Locks the cursor's word through 21-S2's button beside it. */
async function lockWithButton(page: Page) {
  await expect(lockButton(page)).toHaveAccessibleName('Lock word', { timeout: 4000 });
  await lockButton(page).click();
  await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
}

/** Locks the across word through `coord`. */
async function lockAcross(page: Page, coord: string) {
  await select(page, coord);
  await lockWithButton(page);
}

/** Locks OWL from its W, Down, then turns the cursor back Across. The W
 *  is alone across, so ArrowDown and ArrowRight only turn the cursor. */
async function lockOwl(page: Page) {
  await select(page, '5,9');
  await page.keyboard.press('ArrowDown');
  await expect(cell(page, '5,9')).toHaveAttribute('data-selected', 'true');
  await expect(cell(page, '5,8')).toHaveAttribute('data-highlight', 'slot');
  await lockWithButton(page);
  await page.keyboard.press('ArrowRight');
  await expect(cell(page, '5,9')).toHaveAttribute('data-selected', 'true');
  await expect(cell(page, '4,9')).toHaveAttribute('data-highlight', 'slot');
}

/** The cursor to an empty cell far from every word, Across: no button. */
async function leave(page: Page) {
  await select(page, EMPTY);
  await expect(lockButton(page)).toHaveCount(0);
}

/** On the empty cursor cell, ArrowDown turns the cursor Down. */
async function turnDown(page: Page) {
  await page.keyboard.press('ArrowDown');
  await expect(cell(page, EMPTY)).toHaveAttribute('data-selected', 'true');
  await expect(cell(page, '13,12')).toHaveAttribute('data-highlight', 'slot');
  await expect(cell(page, '12,13')).not.toHaveAttribute('data-highlight', 'slot');
}

async function pointIn(page: Page, coord: string, fx: number, fy: number) {
  const c = await boxOf(cell(page, coord));
  return { x: c.x + c.width * fx, y: c.y + c.height * fy };
}

async function mouseTo(page: Page, coord: string, [fx, fy]: readonly [number, number]) {
  const p = await pointIn(page, coord, fx, fy);
  await page.mouse.move(p.x, p.y);
}

// The tick's middle: 11/12 across and 1/12 down its cell, clear of any
// lock button (21-S12).
const TICK_MIDDLE = [11 / 12, 1 / 12] as const;
const MIDDLE = [0.5, 0.5] as const;

const mouseOnTick = (page: Page, coord: string) => mouseTo(page, coord, TICK_MIDDLE);

async function mouseAway(page: Page) {
  await page.mouse.move(5, 5);
}

/** The painted color at each cell's lower left, from a grid screenshot. */
async function paints(page: Page, coords: string[]): Promise<Record<string, Rgb>> {
  const grid = page.getByTestId('puzzle-grid');
  const g = await boxOf(grid);
  const points = await Promise.all(
    coords.map(async (coord) => {
      const c = await boxOf(cell(page, coord));
      return { coord, x: Math.round(c.x - g.x + c.width * 0.1), y: Math.round(c.y - g.y + c.height * 0.92) };
    })
  );
  const png = (await grid.screenshot({ caret: 'hide' })).toString('base64');
  return page.evaluate(
    async ({ base64, points }) => {
      const image = new Image();
      image.src = `data:image/png;base64,${base64}`;
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = image.width;
      canvas.height = image.height;
      const context = canvas.getContext('2d')!;
      context.drawImage(image, 0, 0);
      const out: Record<string, [number, number, number]> = {};
      for (const { coord, x, y } of points) {
        const [r, g, b] = context.getImageData(x, y, 1, 1).data;
        out[coord] = [r, g, b];
      }
      return out;
    },
    { base64: png, points }
  );
}

const isNear = (got: Rgb, want: Rgb, tolerance: number) =>
  got.every((channel, i) => Math.abs(channel - want[i]) <= tolerance);

function mismatches(got: Record<string, Rgb>, want: Record<string, Rgb>, tolerance: number) {
  return Object.keys(want)
    .filter((coord) => !isNear(got[coord], want[coord], tolerance))
    .map((coord) => `${coord}: ${got[coord].join(',')} (want ${want[coord].map(Math.round).join(',')})`);
}

// Amended by 21-S15: the hovered tick's words keep their paint (were 15%
// darker) and are outlined in black instead. `dark` names those words'
// cells.
async function paintMismatches(page: Page, base: Record<string, Rgb>, dark: string[], same: string[]) {
  const got = await paints(page, [...dark, ...same]);
  const want = Object.fromEntries([...dark, ...same].map((coord) => [coord, base[coord]]));
  return [...mismatches(got, want, SAME_TOLERANCE), ...(await tickOutlineMismatches(page, dark))];
}

/** 21-S15: the tick hover's outlines [data-testid="tick-hover-outline"]
 *  are a 1px black line on the grid lines around each hovered word's
 *  cells (not its end cells), and they surround exactly `cells`. What's
 *  amiss, for a readable failure. */
async function tickOutlineMismatches(page: Page, cells: string[]): Promise<string[]> {
  const found = await page.evaluate(() => {
    const cellRects = [...document.querySelectorAll<HTMLElement>('[data-testid="puzzle-grid"] [data-coord]')].map(
      (el) => ({ coord: el.dataset.coord!, r: el.getBoundingClientRect() })
    );
    return [...document.querySelectorAll<HTMLElement>('[data-testid="tick-hover-outline"]')].map((el) => {
      const cs = getComputedStyle(el);
      const o = el.getBoundingClientRect();
      const inside = cellRects.filter(({ r }) => {
        const x = r.x + r.width / 2;
        const y = r.y + r.height / 2;
        return x > o.left && x < o.right && y > o.top && y < o.bottom;
      });
      const sides = ['Top', 'Right', 'Bottom', 'Left'] as const;
      const isLine = sides.every(
        (side) =>
          cs.getPropertyValue(`border-${side.toLowerCase()}-color`) === 'rgb(0, 0, 0)' &&
          cs.getPropertyValue(`border-${side.toLowerCase()}-width`) === '1px' &&
          cs.getPropertyValue(`border-${side.toLowerCase()}-style`) === 'solid'
      );
      // On the grid lines: 1px outside the cells' own boxes on every side.
      const fits =
        inside.length > 0 &&
        Math.abs(o.left - (Math.min(...inside.map((c) => c.r.left)) - 1)) <= 1.5 &&
        Math.abs(o.top - (Math.min(...inside.map((c) => c.r.top)) - 1)) <= 1.5 &&
        Math.abs(o.right - (Math.max(...inside.map((c) => c.r.right)) + 1)) <= 1.5 &&
        Math.abs(o.bottom - (Math.max(...inside.map((c) => c.r.bottom)) + 1)) <= 1.5;
      return { coords: inside.map((c) => c.coord), isLine, fits };
    });
  });
  const problems = found.flatMap(({ coords, isLine, fits }) => [
    ...(isLine ? [] : [`outline around ${coords.join(' ')}: not a 1px black line`]),
    ...(fits ? [] : [`outline around ${coords.join(' ') || 'no cell'}: not on the lines around its cells`]),
  ]);
  const got = [...new Set(found.flatMap(({ coords }) => coords))].sort();
  const want = [...new Set(cells)].sort();
  if (got.join(' ') !== want.join(' ')) problems.push(`outlined: ${got.join(' ') || 'none'} (want ${want.join(' ') || 'none'})`);
  return problems;
}

/** Within 500ms, the `dark` cells are outlined in black (21-S15: were 15%
 *  darker), and they and the `same` cells keep their paint from `base`. */
async function expectPaint(
  page: Page,
  base: Record<string, Rgb>,
  { dark = [], same = [] }: { dark?: string[]; same?: string[] }
) {
  await expect
    .poll(() => paintMismatches(page, base, dark, same), {
      timeout: PAINT_AT_ONCE_MS,
      message: `outlined: ${dark.join(' ') || 'none'}; unchanged: ${same.join(' ') || 'none'}`,
    })
    .toEqual([]);
}

/** As expectPaint, checked once, now. */
async function expectPaintNow(
  page: Page,
  base: Record<string, Rgb>,
  { dark = [], same = [] }: { dark?: string[]; same?: string[] }
) {
  expect(await paintMismatches(page, base, dark, same)).toEqual([]);
}

/** The element under the mouse at a point is the lock button. */
async function isButtonAt(page: Page, p: { x: number; y: number }) {
  return page.evaluate(({ x, y }) => {
    const el = document.elementFromPoint(x, y);
    const button = el?.closest('button');
    return !!button && /^(Lock|Unlock) word$/.test(button.getAttribute('aria-label') ?? button.textContent ?? '');
  }, p);
}

test.describe('21-S13-2 a second on a ticked end cell shows its word\'s button', () => {
  test('the darkening at once, the button after a second; it stays on the cell, the word and the button', async ({
    page,
  }) => {
    await open(page);
    await lockAcross(page, '6,2');
    await leave(page);
    const all = [...TANGENT, ...TANGENT_ENDS];
    const base = await paints(page, all);

    // TANGENT's after tick: no button yet, TANGENT already darker.
    await mouseOnTick(page, '10,2');
    await page.waitForTimeout(NOT_YET_MS);
    await expect(lockButton(page)).toHaveCount(0);
    await expectPaintNow(page, base, { dark: TANGENT, same: TANGENT_ENDS });

    // Then TANGENT's "Unlock word", before its T; still darker; the
    // cursor and focus as they were.
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word', { timeout: SHOWN_WITHIN_MS });
    await expectButtonBeside(page, '3,2', 'across');
    await expectPaintNow(page, base, { dark: TANGENT, same: TANGENT_ENDS });
    await expect(cell(page, EMPTY)).toHaveAttribute('data-selected', 'true');
    await expect(gridRegion(page)).toBeFocused();

    // It stays: elsewhere in the end cell (still darker), on a letter
    // (no longer darker), on the other end cell's part left of the button
    // (darker again), and on the button.
    await mouseTo(page, '10,2', MIDDLE);
    await page.waitForTimeout(AT_ONCE_MS);
    await expectButtonBeside(page, '3,2', 'across');
    await expectPaintNow(page, base, { dark: TANGENT, same: TANGENT_ENDS });

    await mouseTo(page, '6,2', MIDDLE);
    await expectPaint(page, base, { same: all });
    await expectButtonBeside(page, '3,2', 'across');

    await mouseTo(page, '2,2', [0.12, 0.5]);
    await expectPaint(page, base, { dark: TANGENT, same: TANGENT_ENDS });
    await expectButtonBeside(page, '3,2', 'across');

    await lockButton(page).hover();
    await page.waitForTimeout(AT_ONCE_MS);
    await expectButtonBeside(page, '3,2', 'across');
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');

    // Onto a cell outside the word: the button goes at once.
    await mouseTo(page, ELSEWHERE, MIDDLE);
    await expect(lockButton(page)).toHaveCount(0, { timeout: AT_ONCE_MS });
    await expectPaint(page, base, { same: all });
  });

  test('without the grid\'s focus: clicking the button unlocks the word, cursor and focus untouched', async ({
    page,
  }) => {
    await open(page);
    await lockAcross(page, '6,2');
    await leave(page);
    await page.evaluate(() => (document.activeElement as HTMLElement | null)?.blur());
    await expect(gridRegion(page)).not.toBeFocused();

    await mouseOnTick(page, '10,2');
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word', { timeout: NOT_YET_MS + SHOWN_WITHIN_MS });
    await expectButtonBeside(page, '3,2', 'across');

    await lockButton(page).click();
    await expect(ticks(page)).toHaveCount(0);
    // The button stays, in its new state, while the mouse is on it.
    await expect(lockButton(page)).toHaveAccessibleName('Lock word');
    await expectButtonBeside(page, '3,2', 'across');
    await expect(gridRegion(page)).not.toBeFocused();
    await expect(lockButton(page)).not.toBeFocused();

    await mouseAway(page);
    await expect(lockButton(page)).toHaveCount(0, { timeout: AT_ONCE_MS });
    // The cursor is where it was (shown once the grid has focus again).
    await gridRegion(page).focus();
    await expect(cell(page, EMPTY)).toHaveAttribute('data-selected', 'true');
  });
});

