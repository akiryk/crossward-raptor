import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { currentBuilderId } from './helpers/ownership';
import { seedPlayPuzzle } from './helpers/play-route';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 15-S1 — 560px grid, 700px since 17-S7.
//
// The builder's and play's grids fit 700×700px at most at every size
// (cells sharing 1px lines, so a pitch of 699px / size). Neither grid
// shrinks with the window's height: on a short window the grid stays
// 700px and the page scrolls. The hint lists beside a grid scroll in their
// own box at the grid's height. Focusing the grid on load or on a
// click doesn't scroll the page. The default test viewport is 1440×900.
//
// Do not edit this file to match an implementation.

const GRID_PX = 700;
const SHORT = { width: 1440, height: 600 };

/** Every cell on, with letters across the top and down the left. */
function lettered(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let i = 0; i < size; i++) {
    grid = withLetter(grid, { col: i, row: 0 }, 'A');
    grid = withLetter(grid, { col: 0, row: i }, 'B');
  }
  return grid;
}

/** Every cell lettered, so the hints phase keeps every word. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

/** A hint for every word of an all-on square, so the lists run long. */
function everyHint(size: number): Record<string, string> {
  const hints: Record<string, string> = {};
  for (let n = 1; n <= size; n++) hints[`${n}-down`] = `Down hint ${n}`;
  hints['1-across'] = 'Across hint 1';
  for (let row = 1; row < size; row++) hints[`${size + row}-across`] = `Across hint ${size + row}`;
  return hints;
}

async function openBuilder(page: Page, grid: Grid, phase: 'grid' | 'hints' = 'grid') {
  const hints = phase === 'hints' ? everyHint(grid.cols) : {};
  const { id } = await seedPuzzle({ grid, hints, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function openPlay(page: Page, size: number) {
  const fixture = await seedPlayPuzzle({
    builderId: await currentBuilderId(page),
    puzzle: { grid: lettered(size), phase: 'hints', hints: everyHint(size) },
  });
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return b;
}

const scrollY = (page: Page) => page.evaluate(() => window.scrollY);
const pageScrolls = (page: Page) =>
  page.evaluate(() => document.documentElement.scrollHeight > document.documentElement.clientHeight);

async function expectGridSize(page: Page, size: number) {
  const g = await box(grid(page));
  expect(g.width, 'width').toBeCloseTo(GRID_PX, 0);
  expect(g.height, 'height').toBeCloseTo(GRID_PX, 0);
  const first = await box(cell(page, '0,0'));
  const next = await box(cell(page, '1,0'));
  expect(next.x - first.x, 'cell pitch').toBeCloseTo((GRID_PX - 1) / size, 0);
}

/** A scroll box's own height and whether its content overflows it. */
function scrollBox(locator: Locator) {
  return locator.evaluate((el) => ({
    overflowY: getComputedStyle(el).overflowY,
    overflows: el.scrollHeight > el.clientHeight + 1,
  }));
}

test.describe('15-S1-1 the default viewport', () => {
  test('a test that names no viewport runs at 1440×900', async ({ page }) => {
    expect(page.viewportSize()).toEqual({ width: 1440, height: 900 });
  });
});

test.describe('15-S1-2 the builder grid on a short window', () => {
  test.use({ viewport: SHORT });

  for (const size of [15, 21]) {
    test(`a ${size}×${size} in the build phase stays 700px and the page scrolls`, async ({ page }) => {
      await openBuilder(page, lettered(size));
      await expectGridSize(page, size);
      expect(await pageScrolls(page), 'the page scrolls').toBe(true);
    });
  }

  test('a 15×15 in the hints phase stays 700px', async ({ page }) => {
    await openBuilder(page, filled(15), 'hints');
    await expectGridSize(page, 15);
  });

  test('opening the build phase and clicking a cell leave the page where it was', async ({ page }) => {
    await openBuilder(page, lettered(15));
    await expect(page.getByTestId('grid-region')).toBeFocused();
    expect(await scrollY(page), 'after opening').toBe(0);
    await cell(page, '3,3').click();
    await expect(cell(page, '3,3')).toHaveAttribute('data-cell-state', 'selected');
    expect(await scrollY(page), 'after a click').toBe(0);
  });

  test('the hints scroll in their own box at the grid\'s height', async ({ page }) => {
    await openBuilder(page, filled(15), 'hints');
    const region = page.getByTestId('hints-region');
    const r = await box(region);
    const g = await box(grid(page));
    expect(r.y, 'top level with the grid').toBeCloseTo(g.y, 0);
    expect(r.height, "the grid's height").toBeCloseTo(g.height, 0);
    expect(await scrollBox(region)).toEqual({ overflowY: 'auto', overflows: true });
  });
});

test.describe('15-S1-3 the play grid', () => {
  for (const size of [5, 15, 21]) {
    test(`a ${size}×${size} is 700px wide, its cells sharing 1px lines`, async ({ page }) => {
      await openPlay(page, size);
      await expectGridSize(page, size);
    });
  }

  test.describe('on a short window', () => {
    test.use({ viewport: SHORT });

    test('a 15×15 stays 700px and the page scrolls', async ({ page }) => {
      await openPlay(page, 15);
      await expectGridSize(page, 15);
      expect(await pageScrolls(page), 'the page scrolls').toBe(true);
    });

    test('clicking a cell leaves the page where it was', async ({ page }) => {
      await openPlay(page, 15);
      // The last row in view at 600px, with the grid's bottom below it
      // (row 5 of a 700px grid, 17-S7; row 7 of a 560px one).
      await cell(page, '3,5').click();
      await expect(cell(page, '3,5')).toHaveAttribute('data-selected', 'true');
      expect(await scrollY(page), 'after a click').toBe(0);
    });

    test('the hints scroll in their own box at the grid\'s height', async ({ page }) => {
      // A 21×21's 21 hints a column run past its 700px.
      await openPlay(page, 21);
      const lists = page.getByTestId('play-clues');
      const l = await box(lists);
      const g = await box(grid(page));
      expect(l.y, 'top level with the grid').toBeCloseTo(g.y, 0);
      expect(l.height, "the grid's height").toBeCloseTo(g.height, 0);
      expect(await scrollBox(lists)).toEqual({ overflowY: 'auto', overflows: true });
    });
  });
});
