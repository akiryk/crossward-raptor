import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter, type Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { readSaved, savedRow } from './helpers/operations';
import { addJay, collaboratorContext } from './helpers/collaborators';
import { noteTexts } from './helpers/session';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 24-S7 — conflicts: the four-screen scenario and the rest of the
// two-user browser tests.
//
// Adam (the suite's builder) owns the puzzle; Jay (the second seeded
// account) is made a collaborator in the database. The edit committed last
// wins. When Jay's commit replaces work Adam just did, Adam's grid shows
// Jay's letters with a red outline that comes and goes, and his panel notes
// it; his cursor, direction and focus stay. Routine remote edits are
// silent; a reconnect raises no false conflict.
//
// Do not edit this file to match an implementation.

const name = (label: string) => `24-S7 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const outline = (page: Page) => page.getByTestId('conflict-outline');
const status = (page: Page) => page.getByTestId('save-status');

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
/** Screen 1: a 15×15 in Build with ABRAHAM in 1-Across, shared with Jay. */
async function seedAbraham() {
  const grid = letters(createGrid({ cols: 15, rows: 15 }), [...'ABRAHAM'].map((letter, col) => [col, 0, letter] as [number, number, string]));
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, name('abraham'));
  await addJay(id);
  return id;
}
async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}
/** Types a word down from a cell; the cursor is left on its last letter. */
async function typeDown(page: Page, coord: string, word: string) {
  await cell(page, coord).click();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.type(word);
  await page.keyboard.press('ArrowUp');
}
async function column(page: Page, col: number, rows: number): Promise<string> {
  let text = '';
  for (let row = 0; row < rows; row++) text += (await cell(page, `${col},${row}`).innerText()).replace(/[^A-Z]/g, '') || '.';
  return text;
}
/** Adam and Jay both in the puzzle, each panel showing the other. */
async function together(page: Page, j: Page, id: string) {
  await open(page, id);
  await open(j, id);
  await expect(noteTexts(page)).toHaveText(['Jay joined the session.'], { timeout: 10_000 });
}

test.describe('24-S7 conflicts', () => {
  test('24-S7-E6 MAGIC wins: Adam’s 2-Down is outlined and noted, his cursor and focus untouched', async ({ page, browser }) => {
    const id = await seedAbraham();
    const { context, page: j } = await collaboratorContext(browser);
    try {
      await together(page, j, id);

      // Screen 3: Adam types MASKS; Jay sees it; Adam has no outline or note.
      await typeDown(page, '6,0', 'MASKS');
      await expect(status(page)).toHaveText('Saved', { timeout: 10_000 });
      await expect.poll(() => column(j, 6, 5), { timeout: 10_000 }).toBe('MASKS');
      await expect(outline(page)).toHaveCount(0);
      await expect(noteTexts(page)).toHaveCount(1);

      // Screen 4: Jay types MAGIC over it.
      await typeDown(j, '6,0', 'MAGIC');
      await expect.poll(() => column(page, 6, 5), { timeout: 10_000 }).toBe('MAGIC');
      await expect(outline(page).first()).toBeVisible({ timeout: 5000 });
      await expect(noteTexts(page).last()).toHaveText('Jay changed 2-Down from MASKS to MAGIC.');
      await expect(page.getByTestId('session-note-time').last()).toHaveText(/^\d{2}:\d{2}$/);
      // The outline covers 2-Down's five cells.
      const box = await outline(page).first().boundingBox();
      const first = await cell(page, '6,0').boundingBox();
      const last = await cell(page, '6,4').boundingBox();
      expect(box!.y).toBeLessThanOrEqual(first!.y + 2);
      expect(box!.y + box!.height).toBeGreaterThanOrEqual(last!.y + last!.height - 2);
      expect(box!.x).toBeLessThanOrEqual(first!.x + 2);
      expect(box!.x + box!.width).toBeGreaterThanOrEqual(first!.x + first!.width - 2);
      // The cursor stays on the last cell, Down, with focus on the grid.
      await expect(cell(page, '6,4')).toHaveAttribute('data-highlight', 'selected');
      await expect(cell(page, '6,3')).toHaveAttribute('data-highlight', 'slot');
      await expect(page.getByTestId('grid-region')).toBeFocused();
      // The outline goes by itself.
      await expect(outline(page)).toHaveCount(0, { timeout: 6000 });
      // Jay never saw one.
      await expect(outline(j)).toHaveCount(0);
      expect((await noteTexts(j).allTextContents()).filter((text) => text.includes('changed'))).toEqual([]);
      // Typing carries on where the cursor is.
      await page.keyboard.type('S');
      await expect(cell(page, '6,4')).toContainText('S');
    } finally {
      await context.close();
    }
  });

  test('24-S7-E7 MAGKS: Jay types only MAG', async ({ page, browser }) => {
    const id = await seedAbraham();
    const { context, page: j } = await collaboratorContext(browser);
    try {
      await together(page, j, id);
      await typeDown(page, '6,0', 'MASKS');
      await expect(status(page)).toHaveText('Saved', { timeout: 10_000 });
      await expect.poll(() => column(j, 6, 5), { timeout: 10_000 }).toBe('MASKS');
      await typeDown(j, '6,0', 'MAG');
      await expect.poll(() => column(page, 6, 5), { timeout: 10_000 }).toBe('MAGKS');
      await expect(noteTexts(page).last()).toHaveText('Jay changed 2-Down from MASKS to MAGKS.', { timeout: 5000 });
    } finally {
      await context.close();
    }
  });

  test('24-S7-E8 unrelated edits both persist, with no outline and no note', async ({ page, browser }) => {
    const id = await seedAbraham();
    const { context, page: j } = await collaboratorContext(browser);
    try {
      await together(page, j, id);
      await typeDown(page, '10,3', 'DOG');
      await cell(j, '6,0').click();
      await j.keyboard.type('N');
      await expect(status(page)).toHaveText('Saved', { timeout: 10_000 });
      await expect(status(j)).toHaveText('Saved', { timeout: 10_000 });
      await expect.poll(() => column(j, 10, 6), { timeout: 10_000 }).toBe('...DOG');
      await expect(cell(page, '6,0')).toContainText('N', { timeout: 10_000 });
      await page.waitForTimeout(2000);
      for (const p of [page, j]) {
        await expect(outline(p)).toHaveCount(0);
        await expect(noteTexts(p)).toHaveCount(1);
      }
      const saved = await readSaved(id);
      expect(savedRow(saved.grid, 0).slice(0, 7)).toBe('ABRAHAN');
      expect(saved.grid.cells.slice(3, 6).map((row) => row[10].kind === 'active' ? row[10].letter : '#').join('')).toBe('DOG');
    } finally {
      await context.close();
    }
  });

  test('24-S7-E9 reconnecting: Jay comes back online with no false conflict', async ({ page, browser }) => {
    const id = await seedAbraham();
    const { context, page: j } = await collaboratorContext(browser);
    try {
      await together(page, j, id);
      await context.setOffline(true);
      await typeDown(j, '12,2', 'CAT');
      await j.waitForTimeout(1500);
      await typeDown(page, '3,6', 'EMU');
      await expect(status(page)).toHaveText('Saved', { timeout: 10_000 });
      await context.setOffline(false);
      await expect(status(j)).toHaveText('Saved', { timeout: 20_000 });
      await expect.poll(() => column(j, 3, 9), { timeout: 10_000 }).toBe('A.....EMU');
      await expect.poll(() => column(page, 12, 5), { timeout: 10_000 }).toBe('..CAT');
      await j.waitForTimeout(2000);
      await expect(outline(j)).toHaveCount(0);
      expect((await noteTexts(j).allTextContents()).filter((text) => text.includes('changed'))).toEqual([]);
      const saved = await readSaved(id);
      expect(saved.grid.cells.slice(2, 5).map((row) => row[12].kind === 'active' ? row[12].letter : '#').join('')).toBe('CAT');
      expect(saved.grid.cells.slice(6, 9).map((row) => row[3].kind === 'active' ? row[3].letter : '#').join('')).toBe('EMU');
    } finally {
      await context.close();
    }
  });

  test('24-S7-E10 a hint: Jay replaces the one Adam is writing; it is highlighted and noted', async ({ page, browser }) => {
    let full = createGrid({ cols: 3, rows: 3 });
    for (let row = 0; row < 3; row++) for (let col = 0; col < 3; col++) full = withLetter(full, { col, row }, 'A');
    const { id } = await seedPuzzle({ grid: full, hints: {}, phase: 'hints' }, name('hint'));
    await addJay(id);
    const { context, page: j } = await collaboratorContext(browser);
    const hint = (p: Page) => p.locator('[data-hint-key="1-across"] [data-testid="hint-input"]');
    try {
      await together(page, j, id);
      await hint(page).click();
      await page.keyboard.type('Adam’s hint');
      await expect(status(page)).toHaveText('Saved', { timeout: 10_000 });
      await expect(hint(j)).toHaveValue('Adam’s hint', { timeout: 10_000 });
      await hint(j).fill('Jay’s hint');
      await expect(hint(page)).toHaveValue('Jay’s hint', { timeout: 10_000 });
      await expect(page.locator('[data-hint-key="1-across"]')).toHaveAttribute('data-conflict', 'true', { timeout: 5000 });
      await expect(noteTexts(page).last()).toHaveText('Jay changed your hint for 1-Across.');
      await expect(hint(page)).toBeFocused();
      await expect(page.locator('[data-hint-key="1-across"]')).not.toHaveAttribute('data-conflict', 'true', { timeout: 6000 });
    } finally {
      await context.close();
    }
  });
});
