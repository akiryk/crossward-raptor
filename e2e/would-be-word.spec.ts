import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 22-S5 — the cursor's word is the word its cell would belong to.
//
// In the build phase with Preview off, the cursor's word is the word the
// cursor's cell would belong to, in the cursor's direction, if it held a
// letter. On a cell Preview keeps white (a letter or a symmetric hint) it
// is 21-S8's word, as before. On an off cell (empty, not a symmetric hint)
// it is the run through the cell, in Preview's geometry, of the grid with
// a letter placed there (its symmetric counterpart turning white counts),
// when that run has 2 or more cells. It shows as any word does (21-S1,
// 21-S14): the cursor yellow-bright, the word's other cells blue-medium
// ('slot-letter' for a letter, 'slot-required' for a symmetric hint or the
// counterpart that would become one), the rest of the line as outside the
// highlight. A run of the cursor's cell alone is no word: 21-S14's look,
// the line's off cells dull blue. On a cell where a letter can't be typed
// (a locked word's letter or end cell, 21-S3) the word is 21-S8's, as
// before. Preview, the hints phase and locks are unchanged.
//
// The human's examples: an off cell between CRAP and APE, going across;
// the cell below SIR, going down.
//
// Colors are the human's values, written out here. Do not edit this file
// to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const CURSOR = 'rgb(252, 255, 77)'; // yellow-bright
const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // #CFEEFF
const BLUE_DULL = 'rgb(202, 218, 226)'; // #CADAE2
const OFF = 'rgb(221, 224, 230)'; // gray-200, build-cell-off
const WHITE = 'rgb(255, 255, 255)'; // build-cell-on

/** Seconds enough for any lock button's wait (21-S16: 3s). */
const LONG_MS = 3500;

const line = (fixed: 'row' | 'col', at: number) =>
  Array.from({ length: 15 }, (_, i) => (fixed === 'row' ? `${i},${at}` : `${at},${i}`));

function gridWith(letters: Record<string, string>): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  for (const [coord, letter] of Object.entries(letters)) {
    const [col, row] = coord.split(',').map(Number);
    grid = withLetter(grid, { col, row }, letter);
  }
  return grid;
}

const spell = (coords: string[], word: string) => Object.fromEntries(coords.map((coord, i) => [coord, word[i]]));

// A daily (the counterpart of (c,r) is (14−c, 14−r)). Row 3:
//   . C R A P _ A P E . . . . . .    _ is the off cell (5,3)
// Their counterparts make row 11's (6–8) and (10–13) symmetric hints.
const CRAP = ['1,3', '2,3', '3,3', '4,3'];
const APE = ['6,3', '7,3', '8,3'];
const BETWEEN = '5,3';
const crapApe = () => gridWith({ ...spell(CRAP, 'CRAP'), ...spell(APE, 'APE') });

// SIR down column 9, rows 3–5; (9,6) below it.
const SIR = ['9,3', '9,4', '9,5'];
const BELOW = '9,6';
const sir = () => gridWith(spell(SIR, 'SIR'));

// The center row: A at (7,7), T at (8,7) make (6,7) a symmetric hint. A
// letter at (5,7) would make its counterpart (9,7) white too.
const AT = ['7,7', '8,7'];
const center = () => gridWith(spell(AT, 'AT'));

let titleCounter = 0;
async function open(page: Page, grid: Grid, viewport = { width: 1440, height: 1000 }) {
  titleCounter += 1;
  await page.setViewportSize(viewport);
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, `22-S5 ${Date.now()}-${titleCounter}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const bg = (locator: Locator) => locator.evaluate((el) => getComputedStyle(el).backgroundColor);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });

/** The cursor on `coord`, in `orientation`. A click on a cell keeps the
 *  cursor's direction; a click on the cursor's own cell turns it. */
async function cursorOn(page: Page, coord: string, orientation: 'across' | 'down') {
  const [col, row] = coord.split(',').map(Number);
  const other = orientation === 'across' ? `${col === 0 ? 1 : 0},${row}` : `${col},${row === 0 ? 1 : 0}`;
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  if ((await cell(page, other).getAttribute('data-highlight')) !== 'slot') await cell(page, coord).click();
  await expect(cell(page, other)).toHaveAttribute('data-highlight', 'slot');
}

type Look = { state: string; color: string };
const WORD_LETTER: Look = { state: 'slot-letter', color: BLUE_MEDIUM };
const WORD_STAR: Look = { state: 'slot-required', color: BLUE_MEDIUM };
const LINE_OFF: Look = { state: 'slot', color: BLUE_DULL };
const PLAIN_OFF: Look = { state: 'empty', color: OFF };
const PLAIN_LETTER: Look = { state: 'letter', color: WHITE };
const PLAIN_STAR: Look = { state: 'symmetric-hint', color: WHITE };

/** The cursor yellow-bright on `cursor`; every other cell of `cells` as `want` says. */
async function expectLooks(page: Page, cursor: string, cells: string[], want: (coord: string) => Look) {
  await expect(cell(page, cursor)).toHaveAttribute('data-cell-state', 'selected');
  expect(await bg(cell(page, cursor)), 'the cursor').toBe(CURSOR);
  for (const coord of cells) {
    if (coord === cursor) continue;
    const { state, color } = want(coord);
    await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', state);
    expect(await bg(cell(page, coord)), coord).toBe(color);
  }
}

test.describe('22-S5-5 between two words, across (the human\'s CRAP _ APE)', () => {
  test('the off cell between CRAP and APE: both words blue-medium, the rest of the row as outside', async ({ page }) => {
    await open(page, crapApe());
    await cursorOn(page, BETWEEN, 'across');
    await expectLooks(page, BETWEEN, line('row', 3), (coord) =>
      [...CRAP, ...APE].includes(coord) ? WORD_LETTER : PLAIN_OFF
    );
    await expect(page.locator('[data-cell-state="slot-letter"]')).toHaveCount(7);
  });

  test('the same cell going down, where no letter touches it: 21-S14\'s look (pass today)', async ({ page }) => {
    await open(page, crapApe());
    await cursorOn(page, BETWEEN, 'down');
    await expectLooks(page, BETWEEN, line('col', 5), () => LINE_OFF);
    await expectLooks(page, BETWEEN, line('row', 3), (coord) =>
      [...CRAP, ...APE].includes(coord) ? PLAIN_LETTER : PLAIN_OFF
    );
  });
});

test.describe('22-S5-6 next to one word, down (the human\'s SIR)', () => {
  test('the cell below SIR: SIR blue-medium, the rest of the column as outside', async ({ page }) => {
    await open(page, sir());
    await cursorOn(page, BELOW, 'down');
    await expectLooks(page, BELOW, line('col', 9), (coord) => (SIR.includes(coord) ? WORD_LETTER : PLAIN_OFF));
  });

  test('the cell above SIR, down: the same word from the other end', async ({ page }) => {
    await open(page, sir());
    await cursorOn(page, '9,2', 'down');
    await expectLooks(page, '9,2', line('col', 9), (coord) => (SIR.includes(coord) ? WORD_LETTER : PLAIN_OFF));
  });

  test('the cell below SIR going across, alone that way: 21-S14\'s look (pass today)', async ({ page }) => {
    await open(page, sir());
    await cursorOn(page, BELOW, 'across');
    await expectLooks(page, BELOW, line('row', 6), () => LINE_OFF);
    await expect(page.locator('[data-cell-state="slot-letter"]')).toHaveCount(0);
  });
});

test.describe('22-S5-7 the counterpart that would turn white', () => {
  test('on (5,7) across: the hint, A, T and the counterpart-to-be (9,7) are the word', async ({ page }) => {
    await open(page, center());
    await cursorOn(page, '5,7', 'across');
    await expectLooks(page, '5,7', line('row', 7), (coord) =>
      AT.includes(coord) ? WORD_LETTER : coord === '6,7' || coord === '9,7' ? WORD_STAR : PLAIN_OFF
    );
  });

  test('typing the letter keeps the same word; off it, (9,7) is the symmetric hint it became', async ({ page }) => {
    await open(page, center());
    await cursorOn(page, '5,7', 'across');
    await page.keyboard.type('S');
    await expect(cell(page, '5,7')).toContainText('S');
    await expect(cell(page, '6,7')).toHaveAttribute('data-selected', 'true');
    await expectLooks(page, '6,7', line('row', 7), (coord) =>
      coord === '5,7' || AT.includes(coord) ? WORD_LETTER : coord === '9,7' ? WORD_STAR : PLAIN_OFF
    );

    await cursorOn(page, '0,0', 'across');
    await expect(cell(page, '9,7')).toHaveAttribute('data-cell-state', 'symmetric-hint');
  });

  test('before the letter, with the cursor elsewhere, (9,7) is a plain off cell', async ({ page }) => {
    await open(page, center());
    await cursorOn(page, '5,7', 'across');
    await expect(cell(page, '9,7')).toHaveAttribute('data-cell-state', 'slot-required');
    await cursorOn(page, '0,0', 'across');
    await expect(cell(page, '9,7')).toHaveAttribute('data-cell-state', 'empty');
    expect(await bg(cell(page, '9,7'))).toBe(OFF);
  });
});

test.describe('22-S5-8 an off cell no letter touches in its direction (pass today)', () => {
  test('across: 21-S14\'s look, the row\'s off cells dull blue and its letters white', async ({ page }) => {
    await open(page, crapApe());
    await cursorOn(page, '11,3', 'across');
    await expectLooks(page, '11,3', line('row', 3), (coord) =>
      [...CRAP, ...APE].includes(coord) ? PLAIN_LETTER : LINE_OFF
    );
    // Row 11's symmetric hints, elsewhere, look as they always do.
    await expect(cell(page, '12,11')).toHaveAttribute('data-cell-state', PLAIN_STAR.state);
    expect(await bg(cell(page, '12,11'))).toBe(PLAIN_STAR.color);
  });
});

test.describe('22-S5-9 Preview and locks unchanged (pass today)', () => {
  test('Preview: the cell between CRAP and APE is Preview-black and ends CRAP\'s Preview word', async ({ page }) => {
    await open(page, crapApe());
    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(page.getByTestId('puzzle-grid')).toHaveAttribute('data-grid-mode', 'preview');
    await expect(cell(page, BETWEEN)).toHaveAttribute('data-cell-state', 'black');
    // The cursor on C, across: Preview's word is CRAP alone.
    await cell(page, '1,3').click();
    await expect(cell(page, '1,3')).toHaveAttribute('data-selected', 'true');
    for (const coord of ['2,3', '3,3', '4,3']) {
      await expect(cell(page, coord), coord).toHaveAttribute('data-highlight', 'slot');
      expect(await bg(cell(page, coord)), coord).toBe(BLUE_MEDIUM);
    }
    // A click on the black cell selects nothing in Preview (17-S4): the
    // cursor stays on C, and APE stays out of the word.
    await cell(page, BETWEEN).click();
    await expect(cell(page, '1,3')).toHaveAttribute('data-selected', 'true');
    await expect(cell(page, BETWEEN)).not.toHaveAttribute('data-selected', 'true');
    for (const coord of APE) {
      await expect(cell(page, coord), coord).not.toHaveAttribute('data-highlight', /.+/);
      await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', 'letter');
      expect(await bg(cell(page, coord)), coord).toBe(WHITE);
    }
  });

  test('locks: no lock button or outline for the word an off cell would join', async ({ page }) => {
    await open(page, crapApe());
    await cursorOn(page, BETWEEN, 'across');
    await page.waitForTimeout(LONG_MS);
    await expect(lockButton(page)).toHaveCount(0);
    await expect(page.getByTestId('word-outline')).toHaveCount(0);
  });

  test('locks, narrow: the toggle row\'s Lock Word stays disabled there', async ({ page }) => {
    // A daily's grid leaves no room for the button beside a word at 600px (21-S5).
    await open(page, crapApe(), { width: 600, height: 1000 });
    const control = page.getByTestId('lock-word-control');
    await cursorOn(page, BETWEEN, 'across');
    await expect(control).toHaveAttribute('aria-disabled', 'true');
    await cursorOn(page, '2,3', 'across');
    await expect(control).toHaveAttribute('aria-disabled', 'false');
  });
});

test.describe('22-S5-17 where a letter can\'t be typed, no would-be word (pass today)', () => {
  // CRAP locked (Lock Word in the toggle row, 600px): its end cells (0,3)
  // and (5,3) take no letter (21-S3), so the cursor there keeps today's
  // word, none: 21-S14's look, though (5,3) sits between CRAP and APE.
  test('on a locked word\'s end cells: the row\'s off cells dull blue, no blue-medium', async ({ page }) => {
    await open(page, crapApe(), { width: 600, height: 1000 });
    const control = page.getByTestId('lock-word-control');
    await cursorOn(page, '2,3', 'across');
    await expect(control).toHaveAttribute('aria-disabled', 'false');
    await control.click();
    await expect(control).toHaveText('Unlock Word');
    await expect(page.getByTestId('lock-tick')).toHaveCount(2);

    for (const end of [BETWEEN, '0,3']) {
      await cursorOn(page, end, 'across');
      await expectLooks(page, end, line('row', 3), (coord) =>
        [...CRAP, ...APE].includes(coord) ? PLAIN_LETTER : LINE_OFF
      );
      await expect(page.locator('[data-cell-state="slot-letter"], [data-cell-state="slot-required"]')).toHaveCount(0);
    }
  });
});
