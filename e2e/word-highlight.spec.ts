import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S1 — the word highlight.
//
// In the build phase with Preview off, only the cursor's word is
// blue-medium (build-cell-selected-row-on, data-cell-state "slot-letter").
// Every other cell of its row or column is dull blue
// (build-cell-selected-row-off, "slot"), whether or not it holds a letter.
// The cursor stays yellow-bright. The word is the unbroken run of lettered
// cells through the cursor in its direction; on an empty cell or a lone
// letter there's none. A symmetric hint outside the word is dull blue too.
// Preview is unchanged.
//
// Amended by 21-S14: with the cursor in a word, the rest of the row or
// column is no longer dull blue but looks as it would outside the
// highlight (an off cell gray-200, a lettered cell or a symmetric hint
// white). With the cursor in no word, only the line's off cells are dull
// blue; its lettered cells stay white. Cases 21-S1-2, -3 and -4.
//
// Colors are the human's values, written out here. Do not edit this file
// to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const CURSOR = 'rgb(252, 255, 77)'; // yellow-bright
const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // #CFEEFF
const BLUE_DULL = 'rgb(202, 218, 226)'; // #CADAE2
const OFF = 'rgb(221, 224, 230)'; // gray-200, build-cell-off (21-S14)
const WHITE = 'rgb(255, 255, 255)'; // build-cell-on (21-S14)

function lettered(grid: Grid, cells: [col: number, row: number][], letters: string): Grid {
  cells.forEach(([col, row], i) => {
    grid = withLetter(grid, { col, row }, letters[i]);
  });
  return grid;
}

const run = (from: number, word: string) => [...word].map((_, i) => from + i);

/** A Sunday's top row: NOSYPARKER (0–9), an empty cell, ASNOT (11–15),
 *  then empty cells to the right edge. Z at (2,20) makes (18,0) a
 *  symmetric hint. */
function acrossGrid(): Grid {
  const grid = withLetter(createGrid({ cols: 21, rows: 21 }), { col: 2, row: 20 }, 'Z');
  return lettered(
    grid,
    [...run(0, 'NOSYPARKER'), ...run(11, 'ASNOT')].map((col) => [col, 0]),
    'NOSYPARKER' + 'ASNOT'
  );
}

/** A daily's column 2: DORY (rows 0–3), an empty cell, ORATION (5–11),
 *  two empty cells, V (14). */
function downGrid(): Grid {
  const grid = createGrid({ cols: 15, rows: 15 });
  return lettered(
    grid,
    [...run(0, 'DORY'), ...run(5, 'ORATION'), 14].map((row) => [2, row]),
    'DORY' + 'ORATION' + 'V'
  );
}

const DORY = run(0, 'DORY').map((row) => `2,${row}`);
const ORATION = run(5, 'ORATION').map((row) => `2,${row}`);
const V = '2,14';
const COLUMN_EMPTIES = ['2,4', '2,12', '2,13'];

async function open(page: Page, grid: Grid) {
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);

const bg = (locator: Locator) => locator.evaluate((el) => getComputedStyle(el).backgroundColor);

/** The cell is the cursor's word: blue-medium. */
async function expectWord(page: Page, coord: string) {
  await expect(cell(page, coord), `${coord} in the word`).toHaveAttribute('data-cell-state', 'slot-letter');
  expect(await bg(cell(page, coord)), `${coord} in the word`).toBe(BLUE_MEDIUM);
}

/** The cell is in the cursor's row or column, outside its word: dull blue. */
async function expectLine(page: Page, coord: string) {
  await expect(cell(page, coord), `${coord} outside the word`).toHaveAttribute('data-cell-state', 'slot');
  expect(await bg(cell(page, coord)), `${coord} outside the word`).toBe(BLUE_DULL);
}

/** 21-S14: the cell looks as it would outside the highlight. */
async function expectPlain(page: Page, coord: string, state: 'empty' | 'letter' | 'symmetric-hint') {
  await expect(cell(page, coord), `${coord} as outside`).toHaveAttribute('data-cell-state', state);
  expect(await bg(cell(page, coord)), `${coord} as outside`).toBe(state === 'empty' ? OFF : WHITE);
}

async function expectCursor(page: Page, coord: string) {
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  expect(await bg(cell(page, coord)), 'the cursor').toBe(CURSOR);
}

/** The cursor in ORATION at (2,7), going down. */
async function downInOration(page: Page) {
  await cell(page, '2,7').click();
  await page.keyboard.press('ArrowDown');
  await expect(cell(page, '2,7')).toHaveAttribute('data-selected', 'true');
  await expect(cell(page, '2,5')).toHaveAttribute('data-highlight', 'slot');
}

test.describe('21-S1-2 across', () => {
  // Title and the line's cells amended by 21-S14 (were all dull blue).
  test('cursor on N: NOSYPARKER blue-medium; ASNOT, the empty cells and a symmetric hint as outside', async ({ page }) => {
    await open(page, acrossGrid());
    await cell(page, '1,0').click();
    await page.keyboard.press('ArrowLeft');
    await expect(cell(page, '20,0')).toHaveAttribute('data-highlight', 'slot');

    await expectCursor(page, '0,0');
    for (const col of run(1, 'OSYPARKER')) await expectWord(page, `${col},0`);
    for (const col of run(11, 'ASNOT')) await expectPlain(page, `${col},0`, 'letter');
    for (const col of [10, 16, 17, 19, 20]) await expectPlain(page, `${col},0`, 'empty');
    await expectPlain(page, '18,0', 'symmetric-hint');

    // Out of the highlight, (18,0) shows as the symmetric hint it is.
    await page.keyboard.press('ArrowDown');
    await expect(cell(page, '18,0')).toHaveAttribute('data-cell-state', 'symmetric-hint');
  });
});

test.describe('21-S1-3 another word in the line', () => {
  // Title and the line's cells amended by 21-S14 (were all dull blue).
  test('cursor in ORATION going down: ORATION blue-medium; DORY, V and the empty cells as outside', async ({ page }) => {
    await open(page, downGrid());
    await downInOration(page);

    await expectCursor(page, '2,7');
    for (const coord of ORATION.filter((c) => c !== '2,7')) await expectWord(page, coord);
    for (const coord of [...DORY, V]) await expectPlain(page, coord, 'letter');
    for (const coord of COLUMN_EMPTIES) await expectPlain(page, coord, 'empty');
  });
});

test.describe('21-S1-4 cursor on a lone letter or an empty cell', () => {
  // 21-S14: the column's lettered cells stay white; only its empty cells
  // are dull blue (were all dull blue).
  test('on V, then on an empty cell: no blue-medium cell in the column', async ({ page }) => {
    await open(page, downGrid());
    await downInOration(page);

    await cell(page, V).click();
    await expectCursor(page, V);
    for (const coord of [...DORY, ...ORATION]) await expectPlain(page, coord, 'letter');
    for (const coord of COLUMN_EMPTIES) await expectLine(page, coord);
    await expect(page.locator('[data-cell-state="slot-letter"]')).toHaveCount(0);

    await cell(page, '2,4').click();
    await expectCursor(page, '2,4');
    for (const coord of [...DORY, ...ORATION, V]) await expectPlain(page, coord, 'letter');
    for (const coord of ['2,12', '2,13']) await expectLine(page, coord);
    await expect(page.locator('[data-cell-state="slot-letter"]')).toHaveCount(0);
  });
});

test.describe('21-S1-5 Preview unchanged', () => {
  test("with Preview on, the highlight is Preview's word, bounded by its black cells", async ({ page }) => {
    await open(page, downGrid());
    await downInOration(page);

    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(page.getByTestId('puzzle-grid')).toHaveAttribute('data-grid-mode', 'preview');
    await cell(page, '2,8').click();
    await expectCursor(page, '2,8');

    for (const coord of ORATION.filter((c) => c !== '2,8')) {
      await expect(cell(page, coord), coord).toHaveAttribute('data-highlight', 'slot');
      expect(await bg(cell(page, coord)), coord).toBe(BLUE_MEDIUM);
    }
    for (const coord of [...DORY, V]) {
      await expect(cell(page, coord), coord).not.toHaveAttribute('data-highlight', /.+/);
      await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', 'letter');
    }
  });
});
