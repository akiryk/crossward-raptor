import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { clearLetters, createGrid } from '../src/engine/grid';
import { currentBuilderId, ownershipTestClient, seedOtherBuilder } from './helpers/ownership';
import { playPuzzleFixture, seedPlayPuzzle, seedPlaySession } from './helpers/play-route';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 17-S3 — No Reset in play.
//
// A player resets a puzzle only from the library (/puzzles): the small
// Reset button on a completed Play row, and its confirmation dialog. Play
// has no "Puzzle options", no Reset menu item, no builder's Reset button
// and no Reset dialog, for every player, wide or narrow, in progress or
// completed. The builder (build phase, hints phase, published) has none
// either. A player starts an unfinished puzzle over by deleting letters.
//
// The library's Reset is unchanged; e2e/library-play.spec.ts covers it.
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const NARROW = { width: 768, height: 1000 };

const PLAY_RESET_PARTS = ['play-options', 'play-reset-option', 'play-reset-button', 'play-reset-dialog'];

type Attempt = 'none' | 'partial' | 'complete';

async function seedPlay(page: Page, attempt: Attempt, builder: 'own' | 'other') {
  const playerId = await currentBuilderId(page);
  const builderId = builder === 'own' ? playerId : await seedOtherBuilder();
  const puzzle = playPuzzleFixture();
  const fixture = await seedPlayPuzzle({ builderId, puzzle });
  if (attempt === 'none') return fixture;
  const grid = attempt === 'complete' ? puzzle.grid : clearLetters(puzzle.grid);
  const sessionId = await seedPlaySession(playerId, fixture.id, grid);
  if (attempt === 'complete') {
    const client = ownershipTestClient();
    try {
      await client.playSession.update({ where: { id: sessionId }, data: { completedAt: new Date('2026-01-04T04:05:06Z') } });
    } finally { await client.$disconnect(); }
  }
  return fixture;
}

async function openPlay(page: Page, id: string) {
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

/** Nothing on the page resets: no Reset control, no Puzzle options, no Reset dialog. */
async function expectNoReset(page: Page) {
  for (const id of PLAY_RESET_PARTS) await expect(page.getByTestId(id), id).toHaveCount(0);
  await expect(page.getByRole('button', { name: /reset|puzzle options/i })).toHaveCount(0);
  await expect(page.getByRole('menuitem', { name: /reset/i })).toHaveCount(0);
  await expect(page.getByRole('dialog')).toHaveCount(0);
}

test.describe('17-S3-1 play has no Reset', () => {
  for (const viewport of [WIDE, NARROW]) {
    test.describe(`at ${viewport.width}px`, () => {
      test.use({ viewport });

      for (const [attempt, builder] of [
        ['none', 'own'], ['partial', 'own'], ['complete', 'own'], ['partial', 'other'], ['complete', 'other'],
      ] as const) {
        test(`${builder === 'own' ? "the builder's" : "another builder's"} puzzle, ${attempt === 'none' ? 'first opened' : attempt}`, async ({ page }) => {
          const fixture = await seedPlay(page, attempt, builder);
          await openPlay(page, fixture.id);
          if (attempt === 'complete') await expect(page.getByTestId('play-lock-message')).toBeVisible();
          await expectNoReset(page);
        });
      }
    });
  }

  test("the library's Reset still offers a completed puzzle a fresh start", async ({ page }) => {
    await page.setViewportSize(WIDE);
    const fixture = await seedPlay(page, 'complete', 'own');
    await page.goto('/puzzles');
    await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
    const view = page.getByTestId('library-view').getByRole('radio', { name: 'Play', exact: true });
    await view.check();
    const item = page.getByTestId('puzzle-list-item').filter({ hasText: fixture.title });
    await item.getByTestId('puzzle-reset-button').click();
    await expect(page.getByTestId('play-reset-dialog')).toBeVisible();
    await page.getByTestId('play-reset-confirm').click();
    await expect(page.getByTestId('play-reset-dialog')).toHaveCount(0);
    await expect(item).toHaveAttribute('data-play-state', 'untouched');
  });
});

test.describe('17-S3-2 the builder has no Reset', () => {
  test.use({ viewport: WIDE });

  test('the build phase', async ({ page }) => {
    const { id } = await seedPuzzle(
      { grid: createGrid({ cols: 3, rows: 3 }), hints: {}, phase: 'grid' },
      `17-S3 build ${Date.now()}`,
      await currentBuilderId(page),
    );
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await expectNoReset(page);
  });

  test('the hints phase', async ({ page }) => {
    const { id } = await seedPuzzle(playPuzzleFixture(), `17-S3 hints ${Date.now()}`, await currentBuilderId(page));
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await expectNoReset(page);
  });

  test('a published puzzle the builder has completed', async ({ page }) => {
    const fixture = await seedPlay(page, 'complete', 'own');
    await page.goto(`/puzzles/${fixture.id}`);
    await waitForEditorReady(page);
    await expect(page.getByTestId('publish-state')).toBeVisible();
    await expectNoReset(page);
  });
});
