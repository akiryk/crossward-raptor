test.describe('22-S4 the shared delay over Preview cells', () => {
  test.use({ viewport: WIDE });

  test('22-S4-1 a red cell\'s tooltip shows 500ms after the mouse enters it, not before', async ({ page }) => {
    await open(page, marked());
    await previewOn(page);
    await expectState(page, '4,4', 'required');
    await expect(anyTip(page)).toHaveCount(0);

    await startLog(page);
    await cell(page, '4,4').hover();
    await expect(previewTip(page)).toHaveText(RED, { timeout: 3000 });
    const log = await readLog(page);
    const entered = overAt(log, 'cell:4,4');
    expectDelay(tipAt(log, RED) - entered, 'entering the red cell to its tooltip');
    expect(log.filter((e) => e.tip !== undefined && e.t < entered + DELAY_MIN_MS), 'nothing before the delay').toEqual([]);
    await expectOverCell(page, '4,4', RED);
  });

  test('22-S4-2 within a group the delay runs on from entering the group', async ({ page }) => {
    await open(page, marked());
    await previewOn(page);
    await expectState(page, '1,4', 'required');
    await expectState(page, '2,4', 'required');

    await startLog(page);
    await cell(page, '1,4').hover();
    await page.waitForTimeout(300);
    await cell(page, '2,4').hover();
    await expect(previewTip(page)).toHaveText(RED, { timeout: 3000 });
    const log = await readLog(page);
    const shown = tipAt(log, RED);
    expectDelay(shown - overAt(log, 'cell:1,4'), 'entering the group to its tooltip');
    expect(
      shown - overAt(log, 'cell:2,4'),
      'the move within the group did not restart the delay',
    ).toBeLessThan(DELAY_MIN_MS - 50);
    // Over the group's first cell (20-S3).
    await expectOverCell(page, '1,4', RED);
  });

  test('22-S4-3 skip delay: while one shows, another target\'s shows at once, never hidden between', async ({ page }) => {
    await open(page, marked());
    await previewOn(page);
    await cell(page, '0,2').hover();
    await expect(previewTip(page)).toHaveText(GOLD, { timeout: 3000 });

    await startLog(page);
    // Straight to the red group, not touching the gold one.
    await cell(page, '4,4').hover();
    await expect(previewTip(page)).toHaveText(RED, { timeout: 3000 });
    const log = await readLog(page);
    expectAtOnce(tipAt(log, RED) - overAt(log, 'cell:4,4'), 'the red text after entering 4,4');
    expect(log.filter((e) => e.tip === null), 'never hidden in between').toEqual([]);
    await expectOverCell(page, '4,4', RED);
  });

  test('22-S4-4 skip delay: hidden over an unmarked cell, the next group\'s shows at once', async ({ page }) => {
    await open(page, marked());
    await previewOn(page);
    await expectState(page, '2,2', 'black');
    await cell(page, '1,2').hover();
    await expect(previewTip(page)).toHaveText(GOLD, { timeout: 3000 });

    await startLog(page);
    // One glide from the gold group over black 2,2 to the other gold group.
    const to = await centerOf(cell(page, '3,2'));
    await page.mouse.move(to.x, to.y, { steps: 10 });
    await expectOverCell(page, '3,2', GOLD);
    const log = await readLog(page);
    const overBlack = overAt(log, 'cell:2,2');
    const hidden = tipAt(log, null, overBlack);
    expectAtOnce(hidden - overBlack, 'hidden on entering the black cell');
    const entered = overAt(log, 'cell:3,2', hidden);
    expect(entered - hidden, 'precondition: 3,2 entered inside the skip window').toBeLessThan(SKIP_PRECONDITION_MS);
    expectAtOnce(tipAt(log, GOLD, hidden) - entered, 'shown again on entering 3,2');
  });

  test('22-S4-5 after the skip window the delay applies again', async ({ page }) => {
    await open(page, marked());
    await previewOn(page);
    await cell(page, '1,2').hover();
    await expect(previewTip(page)).toHaveText(GOLD, { timeout: 3000 });

    await mouseAway(page);
    await expect(previewTip(page)).toHaveCount(0, { timeout: 300 });
    await page.waitForTimeout(LONG_MS);

    await startLog(page);
    await cell(page, '4,4').hover();
    await expect(previewTip(page)).toHaveText(RED, { timeout: 3000 });
    const log = await readLog(page);
    expectDelay(tipAt(log, RED) - overAt(log, 'cell:4,4'), 'a fresh hover after the skip window');
  });

  test('22-S4-6 a hover that leaves before the delay shows nothing, then or later', async ({ page }) => {
    await open(page, marked());
    await previewOn(page);

    await startLog(page);
    await cell(page, '4,4').hover();
    await page.waitForTimeout(SHORT_HOVER_MS);
    await mouseAway(page);
    await page.waitForTimeout(LONG_MS);
    const log = await readLog(page);
    expect(log.filter((e) => e.tip !== undefined), 'no tooltip at any moment').toEqual([]);
    await expect(anyTip(page)).toHaveCount(0);
  });
});

test.describe('22-S4 the lock button at the shared delay', () => {
  test.use({ viewport: WIDE });

  async function inTangent(page: Page) {
    await open(page, tangent());
    await cell(page, '6,3').click();
    await expect(cell(page, '6,3')).toHaveAttribute('data-selected', 'true');
    await expect(lockButton(page)).toBeVisible();
    await mouseAway(page);
    await expect(anyTip(page)).toHaveCount(0);
  }

  test('22-S4-7 the lock button\'s tooltip shows 500ms after the mouse enters it', async ({ page }) => {
    await inTangent(page);

    await startLog(page);
    await lockButton(page).hover();
    await expect(lockTip(page)).toHaveText(UNLOCKED_TEXT, { timeout: 3000 });
    const log = await readLog(page);
    expectDelay(tipAt(log, UNLOCKED_TEXT) - overAt(log, 'button:Lock word'), 'entering the button to its tooltip');
    await expectPlaced(page, lockTip(page), lockButton(page), 'the lock tooltip');
  });

  test('22-S4-8 skip delay: off the button and straight back, it shows at once', async ({ page }) => {
    await inTangent(page);
    await lockButton(page).hover();
    await expect(lockTip(page)).toHaveText(UNLOCKED_TEXT, { timeout: 3000 });

    const buttonCenter = await centerOf(lockButton(page));
    const t = await centerOf(cell(page, '3,3'));

    await startLog(page);
    // Onto TANGENT's T (the button stays: the cursor's word; the tooltip
    // goes) and straight back, with no actionability waits between.
    await page.mouse.move(t.x, t.y);
    await page.mouse.move(buttonCenter.x, buttonCenter.y);
    await expect(lockTip(page)).toHaveText(UNLOCKED_TEXT, { timeout: 3000 });
    const log = await readLog(page);
    const hidden = tipAt(log, null);
    expectAtOnce(hidden - overAt(log, 'cell:3,3'), 'hidden on leaving the button');
    const back = overAt(log, 'button:Lock word', hidden);
    expect(back - hidden, 'precondition: back on the button inside the skip window').toBeLessThan(SKIP_PRECONDITION_MS);
    expectAtOnce(tipAt(log, UNLOCKED_TEXT, hidden) - back, 'shown again on the button');
  });
});

