// Story 22-S4 — One tooltip behavior.
//
// Every tooltip in the app is the shared Tooltip (src/components/ui), which
// alone decides when it shows: after 500ms of mouse hover over its target,
// counted from entering the target. Once one is showing, or one was hidden
// less than 300ms ago, moving straight onto another target shows its
// tooltip at once (the skip delay). It hides at once when the mouse leaves
// the target; a hover that leaves before the delay shows nothing, then or
// later. A Preview cell's target is its group (20-S3): moving within the
// group neither restarts the delay nor hides the tooltip. Mouse only, as
// before: touch and keyboard show none.
//
// The progress bar (22-S2's `build-progress-bar`) gets a tooltip,
// `build-progress-tooltip` (role "tooltip"), on mouse hover over the bar
// itself (not the message or the percentage): "Aim to use about 80–85% of
// the cells to make a standard puzzle." (an en dash), placed and styled as
// every tooltip: 4px above the bar (below it when there's no room above),
// centered on it or held 8px inside the window. The bar stays out of the
// Tab order.
//
// Timing is measured in the page (performance.now), from the pointerover
// that enters a target to the moment the tooltip's text shows, so a slow
// test runner can't make a correct delay look wrong. A timer fires late
// under load, never early: the delay is checked as 450–950ms (950 is below
// the lock button's old 1000ms); "at once" is within 150ms.
//
// Amended by 22-S6: the lock button's tooltip names its word, "Lock
// TANGENT" here (was "Lock this word so you don't accidentally change it").
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const PHONE = { width: 375, height: 900 };

const GOLD = 'Consider avoiding two-letter words.';
const RED = 'Fill in these cells so the puzzle is symmetrical.';
const UNLOCKED_TEXT = 'Lock TANGENT'; // 22-S6: was "Lock this word so you don't accidentally change it"
const BAR_TEXT = 'Aim to use about 80–85% of the cells to make a standard puzzle.';

/** The shared delay is 500ms; shown no sooner than this after entering. */
const DELAY_MIN_MS = 450;
/** ... and no later than this (a late timer's slack; under the old 1000ms). */
const DELAY_MAX_MS = 950;
/** "At once", measured in the page. */
const AT_ONCE_MS = 150;
/** A hide-then-enter this quick is inside the 300ms skip window. */
const SKIP_PRECONDITION_MS = 250;
/** Long past both the delay and the skip window. */
const LONG_MS = 1000;
/** A hover this short is well under the delay. */
const SHORT_HOVER_MS = 150;

// ---------------------------------------------------------------------------
// The in-page log: each pointerover's target, and each change of the
// visible tooltip's text (null when none shows).

type Entry = { t: number; over?: string; tip?: string | null };

async function startLog(page: Page) {
  await page.evaluate(() => {
    type W = {
      __tipLog: { t: number; over?: string; tip?: string | null }[];
      __tipStop?: () => void;
    };
    const w = window as unknown as W;
    w.__tipStop?.();
    w.__tipLog = [];
    const label = (target: EventTarget | null) => {
      const el = target instanceof Element ? target : null;
      if (!el) return 'other';
      const button = el.closest('button[aria-label]');
      if (button) return `button:${button.getAttribute('aria-label')}`;
      const coord = el.closest<HTMLElement>('[data-coord]');
      if (coord) return `cell:${coord.dataset.coord}`;
      // The bar, also over its fill and zone (and any part S3 adds).
      if (el.closest('[data-testid="build-progress-bar"]')) return 'testid:build-progress-bar';
      const testId = el.closest<HTMLElement>('[data-testid]');
      return testId ? `testid:${testId.dataset.testid}` : 'other';
    };
    // The visible tooltips' texts (normally one), or null when none shows.
    const visibleTip = () => {
      const texts = [...document.querySelectorAll<HTMLElement>('[role="tooltip"]')]
        .filter((tip) => tip.checkVisibility({ opacityProperty: true, visibilityProperty: true }))
        .map((tip) => tip.textContent ?? '');
      return texts.length === 0 ? null : texts.join(' | ');
    };
    let last = visibleTip();
    const onOver = (e: PointerEvent) => w.__tipLog.push({ t: performance.now(), over: label(e.target) });
    const check = () => {
      const now = visibleTip();
      if (now !== last) {
        last = now;
        w.__tipLog.push({ t: performance.now(), tip: now });
      }
    };
    document.addEventListener('pointerover', onOver, true);
    const observer = new MutationObserver(check);
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['style', 'class'],
    });
    w.__tipStop = () => {
      document.removeEventListener('pointerover', onOver, true);
      observer.disconnect();
    };
  });
}

const readLog = (page: Page) =>
  page.evaluate(() => (window as unknown as { __tipLog: { t: number; over?: string; tip?: string | null }[] }).__tipLog);

/** The first time the mouse entered this target (after `after`). */
function overAt(log: Entry[], target: string, after = -Infinity) {
  const entry = log.find((e) => e.over === target && e.t >= after);
  expect(entry, `the mouse entered ${target}`).toBeDefined();
  return entry!.t;
}

/** The first time the tooltip showed this text, or none (null), after `after`. */
function tipAt(log: Entry[], text: string | null, after = -Infinity) {
  const entry = log.find((e) => e.tip !== undefined && e.tip === text && e.t >= after);
  expect(entry, `the tooltip ${text === null ? 'went' : `showed "${text}"`}`).toBeDefined();
  return entry!.t;
}

function expectDelay(ms: number, label: string) {
  expect(ms, `${label}: ${ms.toFixed(0)}ms, at least ${DELAY_MIN_MS}`).toBeGreaterThanOrEqual(DELAY_MIN_MS);
  expect(ms, `${label}: ${ms.toFixed(0)}ms, at most ${DELAY_MAX_MS}`).toBeLessThanOrEqual(DELAY_MAX_MS);
}

function expectAtOnce(ms: number, label: string) {
  expect(ms, `${label}: ${ms.toFixed(0)}ms`).toBeGreaterThanOrEqual(0);
  expect(ms, `${label}: ${ms.toFixed(0)}ms, at once`).toBeLessThanOrEqual(AT_ONCE_MS);
}

