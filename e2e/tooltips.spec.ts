type Rgb = { r: number; g: number; b: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

const css = (locator: Locator, property: string) =>
  locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

const windowWidth = (page: Page) => page.evaluate(() => document.documentElement.clientWidth);

/** Placed as every tooltip is: 4px above its target, or 4px below it when
 *  that would come within 8px of the window's top; centered on it, or held
 *  8px inside the window's sides; never over the target. */
async function expectPlaced(page: Page, tip: Locator, target: Locator, label: string) {
  const t = await box(target);
  const b = await box(tip);
  const width = await windowWidth(page);
  if (t.top - 4 - b.height >= 8) {
    expectNear(b.bottom, t.top - 4, 1.5, `${label}: bottom 4px above`);
  } else {
    expectNear(b.top, t.bottom + 4, 1.5, `${label}: top 4px below`);
  }
  const center = Math.min(Math.max(t.left + t.width / 2, 8 + b.width / 2), width - 8 - b.width / 2);
  expectNear(b.left + b.width / 2, center, 1.5, `${label}: centered, or 8px inside the window`);
  expect(b.left, `${label}: 8px inside the window's left`).toBeGreaterThanOrEqual(7.5);
  expect(b.right, `${label}: 8px inside the window's right`).toBeLessThanOrEqual(width - 7.5);
  const overlaps = b.left < t.right && b.right > t.left && b.top < t.bottom && b.bottom > t.top;
  expect(overlaps, `${label}: not over its target`).toBe(false);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const previewTip = (page: Page) => page.getByTestId('preview-tooltip');
const lockTip = (page: Page) => page.getByTestId('lock-tooltip');
const barTip = (page: Page) => page.getByTestId('build-progress-tooltip');
const anyTip = (page: Page) => page.getByRole('tooltip');
const previewToggle = (page: Page) => page.getByTestId('preview-toggle');
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const bar = (page: Page) => page.getByTestId('build-progress-bar');

function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((line, row) => {
    [...line].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/**
 * 20-S2's grid, in Preview (col,row):
 *   L L L L #
 *   L # # # #
 *   g g # G G     g, G: two gold groups, apart
 *   # # # # R
 *   # R R R R     R: one red group, touching G at 4,2
 */
const marked = () => gridOf(['CATS.', 'O....', 'AD...', '.....', '.....']);

/** A daily: TANGENT across row 3 (cols 3–9), as in 21-S4. */
function tangent(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  [...'TANGENT'].forEach((letter, i) => (grid = withLetter(grid, { col: 3 + i, row: 3 }, letter)));
  return grid;
}

/** A daily whose first `lettered` cells, in reading order, hold "A". */
function daily(lettered: number): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  for (let i = 0; i < lettered; i++) grid = withLetter(grid, { col: i % 15, row: Math.floor(i / 15) }, 'A');
  return grid;
}

function hintsFor(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  return Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
}

let titleCounter = 0;
async function open(page: Page, grid: Grid, phase: Phase = 'grid') {
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid, hints: phase === 'hints' ? hintsFor(grid) : {}, phase },
    `22-S4 ${Date.now()}-${titleCounter}`,
  );
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  await page.evaluate(() => document.fonts.ready.then(() => undefined));
}

async function previewOn(page: Page) {
  await previewToggle(page).click();
  await expect(previewToggle(page).locator('input')).toBeChecked();
}

async function expectState(page: Page, coord: string, state: string) {
  await expect(cell(page, coord), `${coord} is ${state}`).toHaveAttribute('data-cell-state', state);
}

/** The mouse off the grid and every target. */
const mouseAway = (page: Page) => page.mouse.move(2, 2);

async function centerOf(locator: Locator) {
  const b = await box(locator);
  return { x: b.left + b.width / 2, y: b.top + b.height / 2 };
}

/** One tooltip, this text, over this cell (4px above, centered). */
async function expectOverCell(page: Page, coord: string, text: string) {
  await expect(previewTip(page)).toHaveCount(1);
  await expect(previewTip(page)).toHaveText(text);
  const target = await box(cell(page, coord));
  const tip = await box(previewTip(page));
  expectNear(tip.bottom, target.top - 4, 1, `4px above ${coord}`);
  expectNear(tip.left + tip.width / 2, target.left + target.width / 2, 1, `centered on ${coord}`);
}

