// Story 21-S9 — The grid's size by puzzle.
//
// A Mini's, Midi's and Daily's grid is at most 620px; a Sunday's (21×21)
// stays at most 700px, in the build phase (Preview included), the hints
// phase and play. Cells share 1px lines: a pitch of (width − 1) / size.
// The toggle row (Preview or Lock Grid Letters, Lock Word, Rebus) is the
// grid's width, as are the bars that already followed it: the Hint Box,
// play's Prominent Hint and its hint bar. Narrow, the builder's and play's
// column is centered at the grid's width.
//
// The page's layout breakpoints stay where they are for every size: the
// builder is narrow below a 1140px window, its two hint columns stack below
// a 1430px window, play is narrow below a 1430px window, and the page's
// side padding is 8px below 748px. So a 620px grid is 620px down to a 636px
// window and narrower is the window less 16px, as a 700px grid is down to a
// 716px window.
//
// S5's "full width" is the puzzle's own: Lock Word is in the toggle row
// whenever the grid is narrower than 620px (700px for a Sunday), and S2's
// button beside the word is used at that width.
//
// Amended by 21-S16: the button beside a word waits 3 seconds (was 1);
// every wait timed against it is 2000ms longer.
//
// Do not edit this file to match an implementation.

const SMALL_PX = 620;
const SUNDAY_PX = 700;
const NARROW_PADDING_PX = 8;
const GAP_PX = 32;
const WIDE = { width: 1440, height: 1000 };

const SIZES: { name: string; size: number; px: number }[] = [
  { name: 'a Mini (5×5)', size: 5, px: SMALL_PX },
  { name: 'a Midi (9×9)', size: 9, px: SMALL_PX },
  { name: 'a Daily (15×15)', size: 15, px: SMALL_PX },
  { name: 'a Sunday (21×21)', size: 21, px: SUNDAY_PX },
];

/** Every cell lettered M, so every word survives into the hints phase. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'M');
  }
  return grid;
}

/** TANGENT across row 3 (3–9) of an empty grid: a complete, lockable word. */
function tangent(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  [...'TANGENT'].forEach((letter, i) => {
    grid = withLetter(grid, { col: 3 + i, row: 3 }, letter);
  });
  return grid;
}

async function openBuilder(page: Page, viewport: { width: number; height: number }, grid: Grid, phase: 'grid' | 'hints') {
  await page.setViewportSize(viewport);
  const { id } = await seedPuzzle({ grid, hints: {}, phase }, 'Grid size by puzzle');
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function openPlay(page: Page, viewport: { width: number; height: number }, grid: Grid) {
  await page.setViewportSize(viewport);
  const builderId = await currentBuilderId(page);
  const fixture = await seedPlayPuzzle({
    builderId,
    puzzle: { grid, phase: 'hints', hints: { '1-across': 'A hint', '1-down': 'Another hint' } },
  });
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

async function rect(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const gridRegion = (page: Page) => page.getByTestId('grid-region');
const toggleRow = (page: Page) => page.getByTestId('toggle-row');
const hintColumn = (page: Page, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="hint-column"][data-orientation="${orientation}"]`);
const playColumn = (page: Page, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="play-clue-column"][data-orientation="${orientation}"]`);
const lockControl = (page: Page) => page.getByTestId('lock-word-control').filter({ visible: true });
const besideButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });

/** The grid is `px` square, its last cell at a pitch of (px − 1) / size. */
async function expectGrid(page: Page, size: number, px: number, label: string) {
  const g = await rect(grid(page));
  expect(g.width, `${label}: width`).toBeCloseTo(px, 0);
  expect(g.height, `${label}: height`).toBeCloseTo(px, 0);
  const last = await rect(page.locator(`[data-coord="${size - 1},${size - 1}"]`).first());
  expect(last.x - g.x, `${label}: the last cell at a pitch of (${px} − 1) / ${size}`).toBeCloseTo(1 + (size - 1) * ((px - 1) / size), 0);
}

/** The toggle row is the grid's width, its left edge the grid's. */
async function expectToggleRowAtGrid(page: Page, label: string) {
  const g = await rect(grid(page));
  const r = await rect(toggleRow(page));
  expect(r.width, `${label}: the toggle row at the grid's width`).toBeCloseTo(g.width, 0);
  expect(r.x, `${label}: the toggle row over the grid`).toBeCloseTo(g.x, 0);
}

// --- 21-S9-1: the build phase and Preview ---
test.describe('21-S9-1 the build phase and Preview', () => {
  for (const { name, size, px } of SIZES) {
    test(`${name} is ${px}px, its toggle row too, with Preview off and on`, async ({ page }) => {
      await openBuilder(page, WIDE, filled(size), 'grid');
      await expectGrid(page, size, px, 'build');
      await expectToggleRowAtGrid(page, 'build');

      await page.getByTestId('preview-toggle').locator('input').click({ force: true });
      await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');
      await expectGrid(page, size, px, 'Preview');
      await expectToggleRowAtGrid(page, 'Preview');
    });
  }
});

// --- 21-S9-2: the hints phase ---
test.describe('21-S9-2 the hints phase', () => {
  for (const { name, size, px } of SIZES) {
    test(`${name} is ${px}px, its toggle row too; the hints 32px beside it`, async ({ page }) => {
      await openBuilder(page, WIDE, filled(size), 'hints');
      await expectGrid(page, size, px, 'hints');
      await expectToggleRowAtGrid(page, 'hints');
      const g = await rect(grid(page));
      expect((await rect(hintColumn(page, 'across'))).x - g.right, 'the hints beside the grid').toBeCloseTo(GAP_PX, 0);
    });
  }

  for (const { name, size, px } of [SIZES[2], SIZES[3]]) {
    test(`narrow (1139px), ${name}'s column is centered at ${px}px: the toggle row and the Hint Box at the grid's width`, async ({ page }) => {
      await openBuilder(page, { width: 1139, height: 1000 }, filled(size), 'hints');
      await expectGrid(page, size, px, 'narrow hints');
      const g = await rect(grid(page));
      const editor = await rect(page.getByTestId('puzzle-editor'));
      expect(g.x - editor.x, 'the grid centered').toBeCloseTo(editor.right - g.right, 0);
      await expectToggleRowAtGrid(page, 'narrow hints');
      const title = await rect(page.getByTestId('puzzle-title'));
      expect(title.x, 'the title over the grid').toBeCloseTo(g.x, 0);
      expect(title.width, 'the title at the grid’s width').toBeCloseTo(g.width, 0);
      await page.locator('[data-coord="0,0"]').click();
      const box = await rect(page.getByTestId('hint-box'));
      expect(box.x, 'the Hint Box under the grid').toBeCloseTo(g.x, 0);
      expect(box.width, 'the Hint Box at the grid’s width').toBeCloseTo(g.width, 0);
    });
  }
});

// --- 21-S9-3: play ---
test.describe('21-S9-3 play', () => {
  for (const { name, size, px } of SIZES) {
    test(`${name} is ${px}px, the Prominent Hint at its width`, async ({ page }) => {
      await openPlay(page, WIDE, filled(size));
      await expectGrid(page, size, px, 'play');
      const g = await rect(grid(page));
      const hint = await rect(page.getByTestId('prominent-hint'));
      expect(hint.x, 'the Prominent Hint over the grid').toBeCloseTo(g.x, 0);
      expect(hint.width, 'the Prominent Hint at the grid’s width').toBeCloseTo(g.width, 0);
    });
  }

  for (const { name, size, px } of [SIZES[2], SIZES[3]]) {
    test(`narrow (1429px), ${name} is centered at ${px}px, the hint bar at its width`, async ({ page }) => {
      await openPlay(page, { width: 1429, height: 1000 }, filled(size));
      await expectGrid(page, size, px, 'narrow play');
      const g = await rect(grid(page));
      expect(g.x + g.width / 2, 'centered').toBeCloseTo(1429 / 2, 0);
      const bar = await rect(page.getByTestId('play-hint-bar'));
      expect(bar.x, 'the hint bar under the grid').toBeCloseTo(g.x, 0);
      expect(bar.width, 'the hint bar at the grid’s width').toBeCloseTo(g.width, 0);
    });
  }
});

// --- 21-S9-4: the breakpoints stay ---
test.describe('21-S9-4 a Daily’s layout breakpoints are a Sunday’s', () => {
  test('the builder: wide at 1140px, narrow at 1139px', async ({ page }) => {
    await openBuilder(page, { width: 1140, height: 1000 }, filled(15), 'hints');
    const g = await rect(grid(page));
    expect((await rect(hintColumn(page, 'across'))).x - g.right, 'the hints beside the grid').toBeCloseTo(GAP_PX, 0);
    expect(await page.getByTestId('puzzle-title').evaluate((el) => getComputedStyle(el).fontSize), 'title-1').toBe('44px');

    await openBuilder(page, { width: 1139, height: 1000 }, filled(15), 'hints');
    await expect(page.getByTestId('hints-region')).toBeHidden();
    expect(await page.getByTestId('puzzle-title').evaluate((el) => getComputedStyle(el).fontSize), 'title-3').toBe('18px');
  });

  test('the builder’s hint columns: side by side at 1430px, stacked at 1429px', async ({ page }) => {
    await openBuilder(page, { width: 1430, height: 1000 }, filled(15), 'hints');
    let across = await rect(hintColumn(page, 'across'));
    let down = await rect(hintColumn(page, 'down'));
    expect(down.y, 'side by side').toBeCloseTo(across.y, 0);
    expect(down.x - across.right, 'between the columns').toBeCloseTo(GAP_PX, 0);

    await openBuilder(page, { width: 1429, height: 1000 }, filled(15), 'hints');
    across = await rect(hintColumn(page, 'across'));
    down = await rect(hintColumn(page, 'down'));
    expect(down.x, 'one column').toBeCloseTo(across.x, 0);
    expect(down.y, 'Down below Across').toBeGreaterThan(across.bottom);
  });

  test('play: wide at 1430px, narrow at 1429px', async ({ page }) => {
    await openPlay(page, { width: 1430, height: 1000 }, filled(15));
    await expect(page.getByTestId('play-title')).toBeVisible();
    await expect(playColumn(page, 'across')).toBeVisible();
    await expect(page.getByTestId('play-hint-bar')).toBeHidden();

    await openPlay(page, { width: 1429, height: 1000 }, filled(15));
    await expect(page.getByTestId('play-title')).toBeHidden();
    await expect(playColumn(page, 'across')).toBeHidden();
    await expect(page.getByTestId('play-hint-bar')).toBeVisible();
  });
});

// --- 21-S9-5: shrinking with the window ---
test.describe('21-S9-5 the grid shrinks with a narrow window', () => {
  // name, size, window, expected width, expected left edge: 8px of page
  // padding below a 748px window, the column centered in the room left.
  const cases: [string, number, number, number, number][] = [
    ['a Daily at 716px is still 620px, centered', 15, 716, SMALL_PX, NARROW_PADDING_PX + (716 - 2 * NARROW_PADDING_PX - SMALL_PX) / 2],
    ['a Daily at 636px is still 620px, 8px in', 15, 636, SMALL_PX, NARROW_PADDING_PX],
    ['a Daily at 635px is the window less 16px, 8px in', 15, 635, 635 - 2 * NARROW_PADDING_PX, NARROW_PADDING_PX],
    ['a Mini at 636px is still 620px, 8px in', 5, 636, SMALL_PX, NARROW_PADDING_PX],
    ['a Mini at 635px is the window less 16px, 8px in', 5, 635, 635 - 2 * NARROW_PADDING_PX, NARROW_PADDING_PX],
    ['a Daily at 375px is the window less 16px, 8px in', 15, 375, 375 - 2 * NARROW_PADDING_PX, NARROW_PADDING_PX],
    ['a Sunday at 716px is still 700px, 8px in', 21, 716, SUNDAY_PX, NARROW_PADDING_PX],
    ['a Sunday at 715px is the window less 16px, 8px in', 21, 715, 715 - 2 * NARROW_PADDING_PX, NARROW_PADDING_PX],
  ];
  for (const [name, size, width, px, left] of cases) {
    test(`${name}, in the builder (its toggle row too) and play`, async ({ page }) => {
      await openBuilder(page, { width, height: 1000 }, filled(size), 'grid');
      let g = await rect(grid(page));
      expect(g.width, 'builder').toBeCloseTo(px, 0);
      expect(g.x, 'builder left').toBeCloseTo(left, 0);
      await expectToggleRowAtGrid(page, 'builder');

      await openPlay(page, { width, height: 1000 }, filled(size));
      g = await rect(grid(page));
      expect(g.width, 'play').toBeCloseTo(px, 0);
      expect(g.x, 'play left').toBeCloseTo(left, 0);
    });
  }
});

// --- 21-S9-6: Lock Word's full width is the puzzle's ---
test.describe('21-S9-6 Lock Word in the toggle row below the puzzle’s own full width', () => {
  // 21-S12 amended the cases: the button beside the word also needs 36px
  // left of the grid. A full 620px grid has it from a 692px window, a
  // full 700px one from 772px; just below, at full width, it's the
  // toggle row's Lock Word.
  const cases: [string, number, number, 'beside' | 'row'][] = [
    ['a Daily at 1440px (620px)', 15, 1440, 'beside'],
    ['a Daily at 692px (620px, 36px in)', 15, 692, 'beside'],
    ['a Daily at 691px (620px, 35.5px in)', 15, 691, 'row'],
    ['a Daily at 635px (619px)', 15, 635, 'row'],
    ['a Sunday at 1440px (700px)', 21, 1440, 'beside'],
    ['a Sunday at 772px (700px, 36px in)', 21, 772, 'beside'],
    ['a Sunday at 771px (700px, 35.5px in)', 21, 771, 'row'],
    ['a Sunday at 715px (699px)', 21, 715, 'row'],
  ];
  for (const [name, size, width, where] of cases) {
    test(`${name}: ${where === 'beside' ? 'the button beside the word only' : 'the toggle row’s Lock Word only'}`, async ({ page }) => {
      await openBuilder(page, { width, height: 1000 }, tangent(size), 'grid');
      const full = size === 21 ? SUNDAY_PX : SMALL_PX;
      const w = (await rect(gridRegion(page))).width;
      if (where === 'beside') expect(w, 'the grid at its full width').toBeCloseTo(full, 0);
      else if (width < full + 16) expect(w, 'the grid has shrunk').toBeLessThan(full);
      else expect(w, 'the grid at its full width, short of room on its left').toBeCloseTo(full, 0);

      await page.locator('[data-coord="6,3"]').click();
      await expect(page.locator('[data-coord="6,3"]')).toHaveAttribute('data-selected', 'true');
      if (where === 'beside') {
        await expect(besideButton(page)).toBeVisible({ timeout: 3500 });
        await expect(besideButton(page)).toHaveAccessibleName('Lock word');
        await expect(lockControl(page)).toHaveCount(0);
      } else {
        await expect(lockControl(page)).toBeVisible();
        await expect(lockControl(page)).toBeEnabled({ timeout: 300 });
        await expect(lockControl(page)).toHaveText('Lock Word');
        await page.waitForTimeout(3500);
        await expect(besideButton(page)).toHaveCount(0);
      }
    });
  }
});
