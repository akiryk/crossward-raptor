import { test, expect, type Locator, type Page } from '@playwright/test';
import { clearLetters } from '../src/engine/grid';
import { currentBuilderId } from './helpers/ownership';
import { playPuzzleFixture, readPlaySessions, seedPlayPuzzle, seedPlaySession } from './helpers/play-route';

// Story 19-S1 — The completed puzzle.
//
// A completed puzzle shows, under the title, only "The puzzle is
// complete." (body-normal, primary, no checkmark) and, at the grid's
// right edge on the same baseline, a Reset link: body-normal, the links'
// blue (`link-muted`), no fill or border. Wide (from 1430px), there's no
// Prominent Hint, no Rebus control and no controls row ("Saved"): the
// message is 32px under the title and the grid 32px under the message,
// the Player Hints level with the grid's top. Narrow, the message and the
// link sit 16px above the grid, there's no Rebus control, and the hint
// bar stays.
//
// Reset opens the Reset confirmation. Cancel changes nothing; confirming
// replaces the attempt with a blank one, and the puzzle plays again from
// 1 Across. A failed reset says so and keeps the completed puzzle.
//
// An unfinished puzzle is unchanged: no Reset, and its Prominent Hint,
// Rebus control and save status stay (guards).
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const NARROW = { width: 768, height: 1000 };

const PRIMARY = 'rgb(0, 0, 0)';
const LINK = 'rgb(86, 179, 229)'; // link-muted: interactive-light #56b3e5
const TRANSPARENT = 'rgba(0, 0, 0, 0)';
const MESSAGE = 'The puzzle is complete.';

type Box = { x: number; y: number; width: number; height: number; right: number; bottom: number };

async function box(locator: Locator): Promise<Box> {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no box');
  return { ...b, right: b.x + b.width, bottom: b.y + b.height };
}

async function css(locator: Locator, property: string) {
  return locator.evaluate((element, name) => getComputedStyle(element).getPropertyValue(name), property);
}

const message = (page: Page) => page.getByTestId('play-lock-message');
const resetLink = (page: Page) => page.getByTestId('play-reset-link');
const grid = (page: Page) => page.getByTestId('puzzle-grid');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const visible = (locator: Locator) => locator.filter({ visible: true });

async function seed(page: Page, attempt: 'partial' | 'complete') {
  const playerId = await currentBuilderId(page);
  const puzzle = playPuzzleFixture();
  const fixture = await seedPlayPuzzle({ builderId: playerId, puzzle });
  const sessionId = await seedPlaySession(playerId, fixture.id, attempt === 'complete' ? puzzle.grid : clearLetters(puzzle.grid));
  return { ...fixture, playerId, sessionId };
}

async function openPlay(page: Page, id: string) {
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

async function letter(page: Page, coord: string) {
  return cell(page, coord).evaluate((element) => {
    const copy = element.cloneNode(true) as HTMLElement;
    copy.querySelectorAll('[data-testid="cell-number"]').forEach((number) => number.remove());
    return copy.textContent?.trim() ?? '';
  });
}

const WHITE_CELLS = ['0,0', '1,0', '2,0', '0,1', '2,1', '0,2', '1,2', '2,2'];

async function expectMessageAndLink(page: Page) {
  await expect(message(page)).toHaveText(MESSAGE);
  await expect(page.getByTestId('play-completed-mark')).toHaveCount(0);
  await expect(page.getByText('✓')).toHaveCount(0);
  await expect(resetLink(page)).toBeVisible();
  await expect(resetLink(page)).toHaveText('Reset');
  const m = await box(message(page));
  const r = await box(resetLink(page));
  const g = await box(grid(page));
  expect(Math.abs(r.right - g.right), 'Reset at the grid\'s right edge').toBeLessThanOrEqual(1);
  expect(Math.abs(r.bottom - m.bottom), 'on the message\'s baseline').toBeLessThanOrEqual(1);
  expect(Math.abs(r.height - m.height), 'the message\'s line').toBeLessThanOrEqual(1);
  expect(m.x, 'the message at the grid\'s left').toBeCloseTo(g.x, 0);
}

test.describe('19-S1-1 wide: only the message and Reset above the grid', () => {
  test.use({ viewport: WIDE });

  test('no Prominent Hint, Rebus or "Saved"; the message body-normal primary; Reset a blue link', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expectMessageAndLink(page);
    await expect(page.getByTestId('prominent-hint')).toHaveCount(0);
    await expect(page.getByTestId('rebus-control')).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Rebus' })).toHaveCount(0);
    await expect(visible(page.getByTestId('play-save-status'))).toHaveCount(0);
    await expect(visible(page.getByText('Saved', { exact: true }))).toHaveCount(0);

    for (const target of [message(page), resetLink(page)]) {
      expect(await css(target, 'font-size')).toBe('14px');
      expect(await css(target, 'line-height')).toBe('20px');
      expect(await css(target, 'font-weight')).toBe('400');
    }
    expect(await css(message(page), 'color')).toBe(PRIMARY);
    expect(await css(resetLink(page), 'color')).toBe(LINK);
    expect(await css(resetLink(page), 'background-color'), 'no fill').toBe(TRANSPARENT);
    for (const side of ['top', 'right', 'bottom', 'left']) {
      expect(parseFloat(await css(resetLink(page), `border-${side}-width`)), `no ${side} border`).toBe(0);
    }
    expect(await css(resetLink(page), 'cursor')).toBe('pointer');
  });

  test('the message 32px under the title, the grid 32px under it, the Player Hints level with the grid', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expect(message(page)).toBeVisible();
    const t = await box(page.getByTestId('play-title'));
    const m = await box(message(page));
    const g = await box(grid(page));
    const clues = await box(page.getByTestId('play-clues'));
    expect(m.y - t.bottom, 'title to message').toBeCloseTo(32, 0);
    expect(g.y - m.bottom, 'message to grid').toBeCloseTo(32, 0);
    expect(clues.y, 'the Player Hints at the grid\'s top').toBeCloseTo(g.y, 0);
  });

  test('a puzzle finished in play shows the same, once its dialog is closed', async ({ page }) => {
    const fixture = await seed(page, 'partial');
    await openPlay(page, fixture.id);
    for (const [row, letters] of ['CAT', 'A#A', 'TEN'].entries()) {
      for (const [col, value] of [...letters].entries()) {
        if (value === '#') continue;
        await cell(page, `${col},${row}`).click();
        await page.keyboard.type(value.toLowerCase());
      }
    }
    await expect(page.getByTestId('play-completion-dialog')).toBeVisible();
    await page.getByTestId('play-completion-ok').click();
    await expectMessageAndLink(page);
    await expect(page.getByTestId('prominent-hint')).toHaveCount(0);
    await expect(page.getByTestId('rebus-control')).toHaveCount(0);
    await expect(visible(page.getByText('Saved', { exact: true }))).toHaveCount(0);
  });
});

test.describe('19-S1-2 narrow: the message and Reset 16px above the grid', () => {
  test.use({ viewport: NARROW });

  test('no checkmark or Rebus; the hint bar stays', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expectMessageAndLink(page);
    const m = await box(message(page));
    const g = await box(grid(page));
    expect(g.y - m.bottom, '16px above the grid').toBeCloseTo(16, 0);
    await expect(page.getByTestId('rebus-control')).toHaveCount(0);
    await expect(page.getByTestId('play-hint-bar')).toBeVisible();
  });
});

test.describe('19-S1-3 Reset plays the puzzle again', () => {
  test.use({ viewport: WIDE });

  test('Cancel keeps the completed puzzle', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expect.poll(async () => (await readPlaySessions(fixture.id))[0]?.completedAt).toBeInstanceOf(Date);
    const before = await readPlaySessions(fixture.id);
    await resetLink(page).click();
    const dialog = page.getByTestId('play-reset-dialog');
    await expect(dialog).toBeVisible();
    await expect(dialog).toContainText(fixture.title);
    await page.getByTestId('play-reset-cancel').click();
    await expect(dialog).toHaveCount(0);
    await expect(message(page)).toHaveText(MESSAGE);
    await expect(resetLink(page)).toBeFocused();
    expect(await readPlaySessions(fixture.id)).toEqual(before);
  });

  test('confirming starts a blank attempt at 1 Across, which plays and completes again', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expect.poll(async () => (await readPlaySessions(fixture.id))[0]?.completedAt).toBeInstanceOf(Date);
    const [before] = await readPlaySessions(fixture.id);
    await resetLink(page).click();
    await page.getByTestId('play-reset-confirm').click();
    await expect(page.getByTestId('play-reset-dialog')).toHaveCount(0);

    await expect(message(page)).toHaveCount(0);
    await expect(resetLink(page)).toHaveCount(0);
    for (const coord of WHITE_CELLS) await expect.poll(() => letter(page, coord), coord).toBe('');
    const sessions = await readPlaySessions(fixture.id);
    expect(sessions).toHaveLength(1);
    expect(sessions[0].id, 'a new attempt').not.toBe(before.id);
    expect(sessions[0].completedAt).toBeNull();
    for (const row of sessions[0].entries.cells) {
      for (const value of row) if (value.kind === 'active') expect(value.letter).toBeNull();
    }

    await expect(page.getByTestId('play-grid-region')).toBeFocused();
    await expect(cell(page, '0,0')).toHaveAttribute('data-selected', 'true');
    await expect(page.getByTestId('prominent-hint')).toHaveText(/^1A\s*Feline$/);
    await expect(visible(page.getByTestId('rebus-control'))).toHaveCount(1);
    await expect(page.getByTestId('play-save-status')).toBeVisible();

    await page.keyboard.type('cat');
    await expect.poll(async () => (await readPlaySessions(fixture.id))[0]?.entries.cells[0][2])
      .toEqual({ kind: 'active', letter: 'T' });
    for (const [coord, value] of [['0,1', 'a'], ['2,1', 'a'], ['0,2', 't'], ['1,2', 'e'], ['2,2', 'n']]) {
      await cell(page, coord).click();
      await page.keyboard.type(value);
    }
    await expect(page.getByTestId('play-completion-dialog')).toBeVisible();
    await expect.poll(async () => (await readPlaySessions(fixture.id))[0]?.completedAt).toBeInstanceOf(Date);
    await page.getByTestId('play-completion-ok').click();
    await expect(message(page)).toHaveText(MESSAGE);
    await expect(resetLink(page)).toBeVisible();
  });

  test('the library shows the reset puzzle unplayed', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expect(message(page)).toBeVisible();
    await resetLink(page).click();
    await page.getByTestId('play-reset-confirm').click();
    await expect(page.getByTestId('play-reset-dialog')).toHaveCount(0);
    await expect(message(page)).toHaveCount(0);
    await page.goto('/puzzles');
    await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
    const item = page.getByTestId('puzzle-list-item').filter({ hasText: fixture.title });
    await expect(item).toHaveAttribute('data-play-state', 'untouched');
  });

  test('a failed reset says so and keeps the completed puzzle', async ({ page }) => {
    const fixture = await seed(page, 'complete');
    await openPlay(page, fixture.id);
    await expect.poll(async () => (await readPlaySessions(fixture.id))[0]?.completedAt).toBeInstanceOf(Date);
    const before = await readPlaySessions(fixture.id);
    await page.route(`**/puzzles/${fixture.id}/play`, async (route) => {
      if (route.request().headers()['next-action']) await route.abort('failed');
      else await route.continue();
    });
    await resetLink(page).click();
    await page.getByTestId('play-reset-confirm').click();
    await expect(page.getByTestId('play-reset-error')).toBeVisible();
    await expect(page.getByTestId('play-reset-dialog')).toBeVisible();
    await page.getByTestId('play-reset-cancel').click();
    await expect(message(page)).toHaveText(MESSAGE);
    await expect(resetLink(page)).toBeVisible();
    for (const [coord, value] of [['0,0', 'C'], ['2,2', 'N']]) expect(await letter(page, coord)).toBe(value);
    expect(await readPlaySessions(fixture.id)).toEqual(before);
  });
});

test.describe('19-S1-4 an unfinished puzzle is unchanged (guards)', () => {
  for (const viewport of [WIDE, NARROW]) {
    test(`at ${viewport.width}px: no Reset; the Rebus control stays`, async ({ page }) => {
      await page.setViewportSize(viewport);
      const fixture = await seed(page, 'partial');
      await openPlay(page, fixture.id);
      await expect(resetLink(page)).toHaveCount(0);
      await expect(message(page)).toHaveCount(0);
      await expect(page.getByRole('button', { name: /reset/i })).toHaveCount(0);
      await expect(visible(page.getByTestId('rebus-control'))).toHaveCount(1);
      if (viewport === WIDE) {
        await expect(page.getByTestId('prominent-hint')).toBeVisible();
        await expect(page.getByTestId('play-save-status')).toHaveText('Saved');
      }
    });
  }
});
