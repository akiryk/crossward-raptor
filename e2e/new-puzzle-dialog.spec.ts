import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { waitForEditorReady, waitForNewPuzzleReady } from './helpers/wait-for-ready';

// Story 14-S3 — New-puzzle dialog.
//
// The dialog is titled "A New Puzzle!". Its content has two `title-4`
// `primary` headings: "Name it!", the name field's label 8px above it, and
// "And pick a size!", 32px below the field's underline, which names the
// size radiogroup through `aria-labelledby`. The four size options sit 12px
// below that heading and 12px apart, with `body-small` `primary` labels.
// Every left edge is on the content's 16px inset, the field spans the
// content, and the footer's buttons sit 24px below the last option.
//
// The name field opens holding a generated "Adjective Noun Noun" name,
// focused and wholly selected, with Create enabled. While the name is
// untouched, every click in the field selects all of it; after the first
// edit, clicks place the caret. Emptying the field shows the "Add name
// here..." placeholder and disables Create.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

test.use({ viewport: { width: 1280, height: 800 } });

const GENERATED_NAME = /^[A-Z][a-z]+ [A-Z][a-z]+ [A-Z][a-z]+$/;
const SIZE_LABELS = ['Mini (5×5)', 'Midi (9×9)', 'Daily (15×15)', 'Sunday (21×21)'];

type Rgb = { r: number; g: number; b: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

/** A text style's size, weight and line height as computed on this page. */
async function textStyleToken(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.fontWeight = `var(--text-${s}--font-weight)`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const c = getComputedStyle(probe);
    const resolved = { fontSize: c.fontSize, fontWeight: c.fontWeight, lineHeight: c.lineHeight };
    probe.remove();
    return resolved;
  }, style);
}

async function expectText(page: Page, locator: Locator, style: string, color: string, label: string) {
  const actual = await locator.evaluate((el) => {
    const c = getComputedStyle(el);
    return {
      fontFamily: c.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      fontSize: c.fontSize,
      fontWeight: c.fontWeight,
      lineHeight: c.lineHeight,
      color: c.color,
    };
  });
  expect(actual.fontFamily, `${label} family`).toBe('Inter');
  const { fontSize, fontWeight, lineHeight } = actual;
  expect({ fontSize, fontWeight, lineHeight }, `${label} ${style}`).toEqual(await textStyleToken(page, style));
  expect(parseColor(actual.color), `${label} ${color}`).toEqual(await token(page, color));
}

async function box(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { x: r.left, y: r.top, width: r.width, height: r.height, bottom: r.bottom, right: r.right };
  });
}

/** The content box of the Modal's content area: its padding edges. */
async function contentInner(page: Page) {
  return page.getByTestId('modal-content').evaluate((el) => {
    const r = el.getBoundingClientRect();
    const c = getComputedStyle(el);
    return {
      left: r.left + parseFloat(c.paddingLeft) + parseFloat(c.borderLeftWidth),
      right: r.right - parseFloat(c.paddingRight) - parseFloat(c.borderRightWidth),
    };
  });
}

function near(actual: number, expected: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(1);
}

async function selection(locator: Locator) {
  return locator.evaluate((el) => {
    const input = el as HTMLInputElement;
    return { start: input.selectionStart, end: input.selectionEnd, length: input.value.length };
  });
}

async function openDialog(page: Page) {
  await page.goto('/puzzles');
  await waitForNewPuzzleReady(page);
  await page.getByTestId('new-puzzle-button').click();
  const dialog = page.getByTestId('new-puzzle-dialog');
  await expect(dialog).toBeVisible();
  await expect(page.getByTestId('new-puzzle-name')).toBeFocused();
  return dialog;
}

function sizeOptions(page: Page) {
  return page.getByTestId('new-puzzle-size-option');
}

test.describe('14-S3-1 copy and semantics', () => {
  test('the title, two title-4 headings naming the field and the size group, the placeholder and body-small options', async ({ page }) => {
    const dialog = await openDialog(page);

    await expect(dialog).toHaveAccessibleName('A New Puzzle!');
    await expect(page.getByTestId('modal-title')).toHaveText('A New Puzzle!');

    const nameLabel = page.getByTestId('new-puzzle-name-label');
    const sizeLabel = page.getByTestId('new-puzzle-size-label');
    await expect(nameLabel).toHaveText('Name it!');
    await expect(sizeLabel).toHaveText('And pick a size!');
    await expectText(page, nameLabel, 'title-4', 'primary', 'name heading');
    await expectText(page, sizeLabel, 'title-4', 'primary', 'size heading');

    const field = page.getByTestId('new-puzzle-name');
    await expect(field).toHaveAccessibleName('Name it!');
    await expect(page.getByRole('textbox', { name: 'Name it!', exact: true })).toBeFocused();

    const group = page.getByTestId('new-puzzle-size');
    await expect(group).toHaveAttribute('role', 'radiogroup');
    const sizeLabelId = await sizeLabel.getAttribute('id');
    expect(sizeLabelId, 'the size heading has an id').toBeTruthy();
    await expect(group).toHaveAttribute('aria-labelledby', sizeLabelId!);
    await expect(group).not.toHaveAttribute('aria-label', /.*/);
    await expect(group).toHaveAccessibleName('And pick a size!');

    const labels = sizeOptions(page).locator('[data-radio-label]');
    await expect(labels).toHaveText(SIZE_LABELS);
    for (let i = 0; i < SIZE_LABELS.length; i++) {
      await expectText(page, labels.nth(i), 'body-small', 'primary', SIZE_LABELS[i]);
    }

    await field.fill('');
    await expect(field).toHaveAttribute('placeholder', 'Add name here...');
  });
});

test.describe('14-S3-2 layout', () => {
  test('8px label to field, 32px underline to the size heading, 12px to and between options, 24px to the footer, all on the content inset', async ({ page }) => {
    await openDialog(page);
    const inner = await contentInner(page);

    const nameLabel = await box(page.getByTestId('new-puzzle-name-label'));
    const field = await box(page.getByTestId('new-puzzle-name'));
    const sizeLabel = await box(page.getByTestId('new-puzzle-size-label'));
    const options = sizeOptions(page);
    await expect(options).toHaveCount(4);
    const rows = [];
    for (let i = 0; i < 4; i++) rows.push(await box(options.nth(i)));
    const create = await box(page.getByTestId('new-puzzle-create'));

    near(field.y - nameLabel.bottom, 8, 'name label to field');
    near(sizeLabel.y - field.bottom, 32, 'field underline to size heading');
    near(rows[0].y - sizeLabel.bottom, 12, 'size heading to first option');
    for (let i = 1; i < 4; i++) near(rows[i].y - rows[i - 1].bottom, 12, `option ${i - 1} to ${i}`);
    near(create.y - rows[3].bottom, 24, 'last option to the footer buttons');

    near(field.x, inner.left, 'field left');
    near(field.right, inner.right, 'field right');
    near(nameLabel.x, inner.left, 'name label left');
    near(sizeLabel.x, inner.left, 'size heading left');
    for (let i = 0; i < 4; i++) near(rows[i].x, inner.left, `option ${i} left`);
    near(create.x, inner.left, 'Create left');
    near(inner.left - (await box(page.getByTestId('modal-content'))).x, 16, 'content inset');
  });
});

test.describe('14-S3-3 generated name', () => {
  test('the dialog opens with a generated name, focused and wholly selected, and Create enabled', async ({ page }) => {
    await openDialog(page);
    const field = page.getByTestId('new-puzzle-name');

    const name = await field.inputValue();
    expect(name).toMatch(GENERATED_NAME);
    const [, first, second] = name.split(' ');
    expect(first, 'two different nouns').not.toBe(second);
    expect(name.length).toBeLessThanOrEqual(80);
    expect(await selection(field)).toEqual({ start: 0, end: name.length, length: name.length });
    await expect(page.getByTestId('new-puzzle-create')).toBeEnabled();
  });

  test('each opening generates a fresh name', async ({ page }) => {
    const names = new Set<string>();
    for (let i = 0; i < 3; i++) {
      await openDialog(page);
      const name = await page.getByTestId('new-puzzle-name').inputValue();
      expect(name).toMatch(GENERATED_NAME);
      names.add(name);
      await page.getByTestId('new-puzzle-cancel').click();
      await expect(page.getByTestId('new-puzzle-dialog')).toHaveCount(0);
    }
    // Three equal draws from about a million names would be a one-in-10^12 event.
    expect(names.size).toBeGreaterThan(1);
  });

  test('typing replaces the name; emptying it disables Create; typing enables it again', async ({ page }) => {
    await openDialog(page);
    const field = page.getByTestId('new-puzzle-name');
    const create = page.getByTestId('new-puzzle-create');
    await expect(field).toHaveValue(GENERATED_NAME);

    await page.keyboard.type('Q');
    await expect(field).toHaveValue('Q');
    await expect(create).toBeEnabled();

    await page.keyboard.press('Backspace');
    await expect(field).toHaveValue('');
    await expect(create).toBeDisabled();

    await page.keyboard.type('My Own Name');
    await expect(field).toHaveValue('My Own Name');
    await expect(create).toBeEnabled();
  });

  test('Backspace at open empties the whole name', async ({ page }) => {
    await openDialog(page);
    await expect(page.getByTestId('new-puzzle-name')).toHaveValue(GENERATED_NAME);
    await page.keyboard.press('Backspace');
    await expect(page.getByTestId('new-puzzle-name')).toHaveValue('');
    await expect(page.getByTestId('new-puzzle-create')).toBeDisabled();
  });

  test('while untouched, a click anywhere in the field selects the whole name; after an edit, a click places the caret', async ({ page }) => {
    await openDialog(page);
    const field = page.getByTestId('new-puzzle-name');
    const name = await field.inputValue();
    const middle = async () => {
      const b = await box(field);
      // Inside the drawn name, away from both ends.
      const textWidth = await field.evaluate((el) => {
        const input = el as HTMLInputElement;
        const c = getComputedStyle(input);
        const ctx = document.createElement('canvas').getContext('2d')!;
        ctx.font = `${c.fontWeight} ${c.fontSize} ${c.fontFamily}`;
        return ctx.measureText(input.value).width;
      });
      return { x: Math.min(b.width - 2, 4 + textWidth / 2), y: b.height / 2 };
    };

    // Clicking while already focused.
    await field.click({ position: await middle() });
    expect(await selection(field), 'click while focused').toEqual({ start: 0, end: name.length, length: name.length });

    // Clicking back in after focus has left the field.
    await page.getByTestId('new-puzzle-size-label').click();
    await expect(field).not.toBeFocused();
    await field.click({ position: await middle() });
    await expect(field).toBeFocused();
    expect(await selection(field), 'click from outside').toEqual({ start: 0, end: name.length, length: name.length });

    // After an edit, clicks behave normally.
    await page.keyboard.press('End');
    await page.keyboard.type('s');
    await expect(field).toHaveValue(`${name}s`);
    await field.click({ position: await middle() });
    const after = await selection(field);
    expect(after.start, 'caret, not a selection').toBe(after.end);
    expect(after.start, 'caret inside the name').toBeGreaterThan(0);
    expect(after.start, 'caret inside the name').toBeLessThan(after.length);
  });

  test('creating with the untouched name opens the editor titled with it', async ({ page }) => {
    await openDialog(page);
    const name = await page.getByTestId('new-puzzle-name').inputValue();
    await page.locator('[data-testid="new-puzzle-size"] [data-size="mini"]').click();
    await page.getByTestId('new-puzzle-create').click();
    await page.waitForURL(/\/puzzles\/[^/]+$/);
    await waitForEditorReady(page);
    await expect(page.getByTestId('puzzle-title')).toHaveValue(name);
    await expect(page.getByTestId('grid-cell')).toHaveCount(25);
  });
});

test.describe('14-S3-4 style guide', () => {
  test('the sample opens the dialog with its headings and a generated name, and its Create sends nothing', async ({ page }) => {
    await page.goto('/style-guide');
    const section = page.getByTestId('sg-new-puzzle-dialog');
    await expect(section).toBeVisible();
    await section.getByRole('button').first().click();

    const dialog = page.getByRole('dialog', { name: 'A New Puzzle!' });
    await expect(dialog).toBeVisible();
    await expect(dialog.getByText('Name it!', { exact: true })).toBeVisible();
    await expect(dialog.getByText('And pick a size!', { exact: true })).toBeVisible();
    await expect(dialog.getByRole('radiogroup', { name: 'And pick a size!' })).toBeVisible();
    await expect(dialog.getByRole('textbox', { name: 'Name it!' })).toHaveValue(GENERATED_NAME);

    const posts: string[] = [];
    page.on('request', (request) => {
      if (request.method() !== 'GET') posts.push(request.url());
    });
    const url = page.url();
    await dialog.getByRole('button', { name: 'Create', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await page.waitForTimeout(300);
    expect(posts).toEqual([]);
    expect(page.url()).toBe(url);
  });
});
