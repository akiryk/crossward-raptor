// Story 26-S1 — recognized linked clues.
//
// A hint that opens `With <number>-Across` or `With <number>-Down`, in any
// letter case, naming another entry the puzzle has in that direction, is a
// linked clue. Its first word is highlighted in interactive-faint-hover
// (#E8F7FF) wherever the hint appears: the builder's hint fields as the
// builder types (HintsPanel wide, HintBox narrow), and every solver-facing
// display (Player Hints in play and in the hints-phase Preview, the
// Prominent Hint, narrow play's hint bar).
//
// The highlight is found as `linked-clue-with`. Its text is the hint's
// first four characters, as typed. It is painted #E8F7FF: its background,
// and most of the pixels in its box on screen, so it is visible over a
// filled field. In a field it starts at the field's text start (the
// content box's top left) and is as wide as those four characters in the
// field's font. In a display it is the hint element's first child, and the
// element's text is the hint, unchanged. An ordinary hint has none, and a
// display shows its text with no extra element.
//
// Colors written out. Do not edit this file to match an implementation.

const PALE = { r: 232, g: 247, b: 255 }; // interactive-faint-hover #E8F7FF

// The fixture: a 3×3, CAT / A#A / TEN, off cell (1,1). 1-Across (0,0)–(2,0),
// 3-Across (0,2)–(2,2), 1-Down (0,0)–(0,2), 2-Down (2,0)–(2,2). The Hint
// Box's order is 1A, 3A, 1D, 2D.
function fixture(hints: Record<string, string>): Puzzle {
  const base = playPuzzleFixture();
  return { ...base, hints: { ...base.hints, ...hints } };
}

const visible = (locator: Locator) => locator.filter({ visible: true });
const highlight = (scope: Locator) => scope.getByTestId('linked-clue-with');
const hintRow = (page: Page, key: string) => page.locator(`[data-testid="hint-row"][data-hint-key="${key}"]`);
const hintInput = (page: Page, key: string) => hintRow(page, key).getByTestId('hint-input');

async function openBuilder(page: Page, hints: Record<string, string> = {}) {
  const { id } = await seedPuzzle(fixture(hints));
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

async function openPlay(page: Page, hints: Record<string, string>) {
  const { id } = await seedPlayPuzzle({
    builderId: await currentBuilderId(page),
    puzzle: fixture(hints),
  });
  await page.goto(`/puzzles/${id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return b;
}

function rgb(value: string) {
  const m = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (!m) throw new Error(`unparseable colour: "${value}"`);
  return { r: Number(m[1]), g: Number(m[2]), b: Number(m[3]) };
}

/** The share of the pixels inside `locator`'s box (1px in) painted `color`. */
async function paintedShare(page: Page, locator: Locator, color: typeof PALE) {
  const b = await box(locator);
  const clip = { x: b.x + 1, y: b.y + 1, width: b.width - 2, height: b.height - 2 };
  const png = (await page.screenshot({ clip })).toString('base64');
  return page.evaluate(
    async ({ png, color }) => {
      const img = new Image();
      img.src = `data:image/png;base64,${png}`;
      await img.decode();
      const canvas = document.createElement('canvas');
      canvas.width = img.width;
      canvas.height = img.height;
      const ctx = canvas.getContext('2d');
      if (!ctx) throw new Error('no canvas');
      ctx.drawImage(img, 0, 0);
      const data = ctx.getImageData(0, 0, img.width, img.height).data;
      let matching = 0;
      for (let i = 0; i < data.length; i += 4) {
        const close =
          Math.abs(data[i] - color.r) <= 3 &&
          Math.abs(data[i + 1] - color.g) <= 3 &&
          Math.abs(data[i + 2] - color.b) <= 3;
        if (close) matching++;
      }
      return matching / (data.length / 4);
    },
    { png, color }
  );
}

/** The highlight's style and paint: pale blue, and visible on screen. */
async function expectPale(page: Page, mark: Locator) {
  expect(rgb(await mark.evaluate((el) => getComputedStyle(el).backgroundColor)), 'background').toEqual(PALE);
  expect(await paintedShare(page, mark, PALE), 'painted pale on screen').toBeGreaterThan(0.5);
}

/** A field's highlight: its first four characters, at its text start, as
 *  wide as they are in the field's font, painted pale. */
async function expectFieldHighlight(page: Page, scope: Locator, field: Locator) {
  const mark = highlight(scope);
  await expect(mark).toHaveCount(1);
  const value = await field.inputValue();
  await expect(mark).toHaveText(value.slice(0, 4));

  const f = await box(field);
  const m = await box(mark);
  expect(m.x, 'inside the field, left').toBeGreaterThanOrEqual(f.x - 0.5);
  expect(m.y, 'inside the field, top').toBeGreaterThanOrEqual(f.y - 0.5);
  expect(m.x + m.width, 'inside the field, right').toBeLessThanOrEqual(f.x + f.width + 0.5);
  expect(m.y + m.height, 'inside the field, bottom').toBeLessThanOrEqual(f.y + f.height + 0.5);

  const metrics = await field.evaluate((el) => {
    const style = getComputedStyle(el);
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('no canvas');
    ctx.font = style.font;
    const text = (el as HTMLTextAreaElement).value.slice(0, 4);
    return {
      left: parseFloat(style.borderLeftWidth) + parseFloat(style.paddingLeft),
      top: parseFloat(style.borderTopWidth) + parseFloat(style.paddingTop),
      width: ctx.measureText(text).width,
    };
  });
  expect(Math.abs(m.x - (f.x + metrics.left)), 'at the text start, x').toBeLessThanOrEqual(1);
  expect(Math.abs(m.y - (f.y + metrics.top)), 'at the text start, y').toBeLessThanOrEqual(1);
  expect(Math.abs(m.width - metrics.width), 'as wide as the four characters').toBeLessThanOrEqual(1);

  await expectPale(page, mark);
}

/** A display's highlight: the hint element's first child, its text the
 *  hint's first four characters, the element's text the hint unchanged. */
async function expectDisplayHighlight(page: Page, text: Locator, hint: string) {
  const mark = highlight(text);
  await expect(mark).toHaveCount(1);
  await expect(mark).toHaveText(hint.slice(0, 4));
  await expect(text).toHaveText(hint);
  expect(
    await text.evaluate(
      (el) => el.firstChild instanceof HTMLElement && el.firstChild.dataset.testid === 'linked-clue-with'
    ),
    'at the text start'
  ).toBe(true);
  const t = await box(text);
  const m = await box(mark);
  expect(m.x).toBeGreaterThanOrEqual(t.x - 0.5);
  expect(m.y).toBeGreaterThanOrEqual(t.y - 0.5);
  expect(m.x + m.width).toBeLessThanOrEqual(t.x + t.width + 0.5);
  expect(m.y + m.height).toBeLessThanOrEqual(t.y + t.height + 0.5);
  await expectPale(page, mark);
}

/** An ordinary hint in a display: its text exactly, with no element. */
async function expectPlainDisplay(text: Locator, hint: string) {
  await expect(highlight(text)).toHaveCount(0);
  await expect(text).toHaveText(hint);
  expect(await text.evaluate((el) => el.childElementCount)).toBe(0);
}

/** Moves the field's caret to just after its first `n` characters. */
async function caretAfter(page: Page, field: Locator, n: number) {
  await field.click();
  await page.keyboard.press('Home');
  for (let i = 0; i < n; i++) await page.keyboard.press('ArrowRight');
}

test.describe('26-S1 the builder, wide', () => {
  test.use({ viewport: { width: 1440, height: 900 } });

  test('26-S1-6 typing a linked clue highlights its With; the text is saved as typed', async ({ page }) => {
    await openBuilder(page, { '1-down': '' });
    const field = hintInput(page, '1-down');
    await field.click();
    const saved = page.waitForResponse(
      (response) =>
        response.request().method() === 'POST' && response.request().headers()['next-action'] !== undefined
    );
    await page.keyboard.type('With 1-Across, a dish');
    await expect(field).toHaveValue('With 1-Across, a dish');
    await expectFieldHighlight(page, hintRow(page, '1-down'), field);
    await saved;

    await page.reload();
    await waitForEditorReady(page);
    await expect(hintInput(page, '1-down')).toHaveValue('With 1-Across, a dish');
    await expectFieldHighlight(page, hintRow(page, '1-down'), hintInput(page, '1-down'));
  });

  test('26-S1-7 the highlight follows the text as it is edited', async ({ page }) => {
    await openBuilder(page, {
      '1-down': 'With 1-Across, a dish',
      '2-down': 'With 1 Across, x',
    });
    const row = hintRow(page, '1-down');
    const field = hintInput(page, '1-down');
    await expectFieldHighlight(page, row, field);

    // 1 → 82: no 82-Across, so no highlight, at once.
    await caretAfter(page, field, 5);
    await page.keyboard.press('Delete');
    await page.keyboard.type('82');
    await expect(field).toHaveValue('With 82-Across, a dish');
    await expect(highlight(row)).toHaveCount(0);

    // And back.
    await page.keyboard.press('Backspace');
    await page.keyboard.press('Backspace');
    await page.keyboard.type('1');
    await expect(field).toHaveValue('With 1-Across, a dish');
    await expectFieldHighlight(page, row, field);

    // Its own entry: no highlight.
    await field.fill('With 1-Down, a dish');
    await expect(highlight(row)).toHaveCount(0);

    // Any case: its `with` is highlighted.
    await field.fill('with 1-across, x');
    await expectFieldHighlight(page, row, field);
    await expect(highlight(row)).toHaveText('with');

    // Ordinary hints, and `With 1 Across,`: none, and their fields look
    // like an untouched field (1-Across's).
    await page.getByRole('heading', { name: 'Across' }).first().click();
    const untouched = hintInput(page, '1-across');
    const look = (l: Locator) =>
      l.evaluate((el) => {
        const s = getComputedStyle(el);
        return { color: s.backgroundColor, image: s.backgroundImage };
      });
    for (const key of ['3-across', '2-down']) {
      await expect(highlight(hintRow(page, key)), key).toHaveCount(0);
      expect(await look(hintInput(page, key)), key).toEqual(await look(untouched));
    }
    await expect(highlight(hintRow(page, '1-across'))).toHaveCount(0);
  });
});

test.describe('26-S1-8 the builder, narrow', () => {
  test.use({ viewport: { width: 390, height: 900 } });

  test('the Hint Box highlights a linked clue, and not once it is broken', async ({ page }) => {
    await openBuilder(page, { '1-down': 'With 1-Across, x' });
    const hintBox = page.getByTestId('hint-box');
    const field = hintBox.getByTestId('hint-box-input');
    const next = hintBox.getByRole('button', { name: 'Next word' });
    // 1A → 3A → 1D.
    await next.click();
    await next.click();
    await expect(field).toHaveValue('With 1-Across, x');
    await expectFieldHighlight(page, hintBox, field);

    // Without the hyphen it is ordinary text.
    await caretAfter(page, field, 7);
    await page.keyboard.press('Backspace');
    await expect(field).toHaveValue('With 1Across, x');
    await expect(highlight(hintBox)).toHaveCount(0);
  });
});

const LINKED = 'With 1-Across, a pet that purrs';
const ORDINARY = 'Twice five';

test.describe('26-S1-9 play', () => {
  test('wide: Player Hints and the Prominent Hint', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await openPlay(page, { '1-down': LINKED });

    const clueText = (key: string) =>
      page.locator(`[data-testid="play-clue"][data-clue-key="${key}"]`).getByTestId('play-clue-text');
    await expectDisplayHighlight(page, clueText('1-down'), LINKED);
    await expectPlainDisplay(clueText('3-across'), ORDINARY);

    // The Prominent Hint shows the selected word's hint.
    await page.locator('[data-testid="play-clue"][data-clue-key="1-down"]').click();
    const prominent = page.getByTestId('prominent-hint-text');
    await expectDisplayHighlight(page, prominent, LINKED);

    await page.locator('[data-testid="play-clue"][data-clue-key="3-across"]').click();
    await expectPlainDisplay(prominent, ORDINARY);
  });

  test('narrow: the play hint bar', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 900 });
    await openPlay(page, { '1-down': LINKED });

    const bar = page.getByTestId('play-hint-bar');
    const text = bar.getByTestId('play-hint-bar-text');
    const next = bar.getByRole('button', { name: 'Next word' });
    // Play opens on 1A; → 3A (ordinary) → 1D (linked).
    await next.click();
    await expectPlainDisplay(text, ORDINARY);
    await next.click();
    await expectDisplayHighlight(page, text, LINKED);
  });
});

test.describe('26-S1-10 the hints-phase Preview', () => {
  test.use({ viewport: { width: 1440, height: 900 } });

  test('Preview Hints highlights the linked clue', async ({ page }) => {
    await openBuilder(page, { '1-down': LINKED });
    const toggle = visible(page.getByTestId('preview-hints-toggle'));
    await toggle.click();
    await expect(toggle.locator('input')).toBeChecked();

    const clueText = (key: string) =>
      page.locator(`[data-testid="play-clue"][data-clue-key="${key}"]`).getByTestId('play-clue-text');
    await expectDisplayHighlight(page, clueText('1-down'), LINKED);
    await expectPlainDisplay(clueText('3-across'), ORDINARY);
  });
});
