// Story 18-S5 — the DONE icon.
//
// A published puzzle the signed-in player has completed (their own attempt,
// whoever built the puzzle, public or unlisted) shows a fourth status icon,
// DONE: the human's export (`complete-icon.svg`), cleaned like 18-S3's three
// (46×34, the 34px outlined 3×3 grid at x 6 under a 42×12 band at x 2, y 11,
// the label in white), drawn in the new `orange` (#EF9D05) through the
// `status-complete` style. Every other published row keeps Play; a puzzle
// completed only by someone else is Play for the caller. The icon is
// aria-hidden and sits where the other icons do.
//
// The row's visually hidden status text reads "Complete", so its link reads
// "<title> Complete". The visible `[complete]` marker is gone; `[in-play]`
// stays. The completed row keeps Reset (19-S3: the caller's own row in
// its menu); resetting it from the library
// turns it back to Play. 19-S2: the completed row is orange
// (`puzzle-row-complete` #F9F2E6, `puzzle-row-complete-hover` #F7ECD7),
// not green.
//
// Colors are the human's values written out, not read from the styles.
// Measured at 1280×800. Do not edit this file to match an implementation.

test.use({ storageState: { cookies: [], origins: [] } });

type Rgb = { r: number; g: number; b: number };
type Rgba = Rgb & { a: number };

const ORANGE = '#EF9D05';
const GREEN = '#84C600';
const WHITE = '#FFFFFF';
const PLAY_ROW = '#F0F5E5';
// 19-S2: the completed rows.
const COMPLETE_ROW = '#F9F2E6';
const COMPLETE_ROW_HOVER = '#F7ECD7';

type Status = 'play' | 'done';
// status -> the grid and band color, the hidden text
const STATUS: Record<Status, { color: string; text: string }> = {
  play: { color: GREEN, text: 'Ready to play' },
  done: { color: ORANGE, text: 'Complete' },
};

function hex(value: string): Rgb {
  const n = parseInt(value.replace('#', ''), 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}

/** The forms getComputedStyle reports for a colour: rgb(), rgba() and color(srgb ...). */
function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function rgbOf(color: Rgba): Rgb {
  return { r: color.r, g: color.g, b: color.b };
}

/** The colour a CSS value paints as a background on this page. */
async function resolve(page: Page, cssValue: string) {
  return parseColor(
    await page.evaluate((value) => {
      const probe = document.createElement('div');
      probe.style.backgroundColor = value;
      document.body.appendChild(probe);
      const resolved = getComputedStyle(probe).backgroundColor;
      probe.remove();
      return resolved;
    }, cssValue)
  );
}

async function bgOf(locator: Locator) {
  return parseColor(await locator.evaluate((el) => getComputedStyle(el).backgroundColor));
}

async function box(locator: Locator) {
  return locator.evaluate((el) => {
    const r = el.getBoundingClientRect();
    return { x: r.left + window.scrollX, y: r.top + window.scrollY, width: r.width, height: r.height };
  });
}

function uniqueTitle(label: string) {
  return `S5 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

async function freshBuilder(page: Page) {
  await page.setViewportSize({ width: 1280, height: 800 });
  await signInSeededUser(page);
  return currentBuilderId(page);
}

async function seedOwn(builderId: string, state: BuilderEditState, label: string = state) {
  const title = uniqueTitle(label);
  const { id } = await seedBuilderEditPuzzle(title, builderId, state);
  return { id, title };
}

const solved: SerializedGrid = {
  cols: 3, rows: 3,
  cells: [
    [{ kind: 'active', letter: 'C' }, { kind: 'active', letter: 'A' }, { kind: 'active', letter: 'T' }],
    [{ kind: 'active', letter: 'A' }, { kind: 'black' }, { kind: 'active', letter: 'A' }],
    [{ kind: 'active', letter: 'T' }, { kind: 'active', letter: 'E' }, { kind: 'active', letter: 'N' }],
  ],
};

/** A published puzzle, retitled, and one player's attempt at it: none, part-filled, or completed and stamped. */
async function seedPublished(
  builderId: string,
  playerId: string,
  attempt: 'none' | 'in-play' | 'complete',
  options: { visibility?: 'public' | 'private'; label?: string } = {}
) {
  const fixture = await seedPlayPuzzle({ builderId, visibility: options.visibility ?? 'public' });
  const title = uniqueTitle(options.label ?? `published ${attempt}`);
  const client = ownershipTestClient();
  try {
    await client.puzzle.update({ where: { id: fixture.id }, data: { title } });
    if (attempt !== 'none') {
      const entries = structuredClone(solved);
      if (attempt === 'in-play') entries.cells[0][0] = { kind: 'active', letter: null };
      const sessionId = await seedPlaySession(playerId, fixture.id, deserializeGrid(entries));
      if (attempt === 'complete') {
        await client.playSession.update({ where: { id: sessionId }, data: { completedAt: new Date('2026-01-04T04:05:06Z') } });
      }
    }
  } finally {
    await client.$disconnect();
  }
  return { id: fixture.id, title };
}

async function openLibrary(page: Page) {
  await page.goto('/puzzles');
  await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
}

function row(page: Page, title: string) {
  return page.getByTestId('puzzle-list-item').filter({ hasText: title });
}

/** The icon's pixels as RGB, decoded in the page from Playwright's screenshot of its 46×34 box. */
async function iconPixels(page: Page, icon: Locator) {
  const png = (await icon.screenshot()).toString('base64');
  const data = await page.evaluate(async (base64) => {
    const image = new Image();
    image.src = `data:image/png;base64,${base64}`;
    await image.decode();
    const canvas = document.createElement('canvas');
    canvas.width = image.width;
    canvas.height = image.height;
    const context = canvas.getContext('2d')!;
    context.drawImage(image, 0, 0);
    const { data: rgba, width, height } = context.getImageData(0, 0, image.width, image.height);
    return { rgba: Array.from(rgba), width, height };
  }, png);
  const at = (x: number, y: number): Rgb => {
    const i = (y * data.width + x) * 4;
    return { r: data.rgba[i], g: data.rgba[i + 1], b: data.rgba[i + 2] };
  };
  return { at, width: data.width, height: data.height };
}

function expectPixel(actual: Rgb, expected: string, label: string) {
  const want = hex(expected);
  for (const channel of ['r', 'g', 'b'] as const) {
    expect(Math.abs(actual[channel] - want[channel]), `${label}: ${JSON.stringify(actual)} is ${expected}`).toBeLessThanOrEqual(2);
  }
}

/** Checks the drawing at pixel centres well inside each region ((x, y) relative to the 46×34 box)
 *  and returns the label's white pixels on the band, as "x,y" keys. */
async function expectIcon(page: Page, item: Locator, status: Status, background: string) {
  const icon = item.getByTestId('puzzle-icon');
  await expect(icon).toHaveAttribute('aria-hidden', 'true');
  const { at, width, height } = await iconPixels(page, icon);
  expect({ width, height }, `${status} icon size`).toEqual({ width: 46, height: 34 });
  const { color } = STATUS[status];

  // The grid: its 34px square at x 6, three 10px cells per row 1px apart inside a 1px outline.
  expectPixel(at(12, 6), WHITE, `${status} cell 0,0`);
  expectPixel(at(23, 6), color, `${status} cell 1,0 dark`);
  expectPixel(at(34, 6), WHITE, `${status} cell 2,0`);
  expectPixel(at(12, 28), WHITE, `${status} cell 0,2`);
  expectPixel(at(23, 28), WHITE, `${status} cell 1,2`);
  expectPixel(at(34, 28), color, `${status} cell 2,2 dark`);
  expectPixel(at(17, 28), color, `${status} line between white cells`);
  expectPixel(at(23, 33), color, `${status} bottom outline`);
  expectPixel(at(39, 9), color, `${status} right outline`);
  expectPixel(at(6, 0), background, `${status} rounded corner`);
  expectPixel(at(7, 1), background, `${status} rounded corner`);
  expectPixel(at(39, 33), background, `${status} rounded corner`);

  // The band: 42×12 at x 2, y 11, across the grid's middle row, its label in white.
  expectPixel(at(3, 17), color, `${status} band's left end`);
  expectPixel(at(42, 17), color, `${status} band's right end`);
  expectPixel(at(1, 17), background, `${status} left of the band`);
  expectPixel(at(44, 17), background, `${status} right of the band`);
  expectPixel(at(3, 9), background, `${status} above the band, left of the grid`);
  expectPixel(at(3, 24), background, `${status} below the band, left of the grid`);
  const label = new Set<string>();
  for (let y = 12; y <= 21; y++) {
    for (let x = 3; x <= 42; x++) {
      const p = at(x, y);
      if (p.r > 200 && p.g > 200 && p.b > 200) label.add(`${x},${y}`);
    }
  }
  expect(label.size, `${status} label drawn in white`).toBeGreaterThan(40);
  return label;
}

/** How many label pixels two icons do not share. */
function labelDifference(a: Set<string>, b: Set<string>) {
  let differ = 0;
  for (const key of a) if (!b.has(key)) differ += 1;
  for (const key of b) if (!a.has(key)) differ += 1;
  return differ;
}

async function expectHiddenStatus(item: Locator, title: string, status: Status, marker: string | null) {
  const link = item.getByTestId('puzzle-play-link');
  const hidden = link.getByTestId('puzzle-status');
  await expect(hidden, `${title}: one status text, inside the link`).toHaveCount(1);
  await expect(hidden).toHaveText(STATUS[status].text);
  const b = await box(hidden);
  expect(b.width * b.height, 'visually hidden: at most a 1px box').toBeLessThanOrEqual(1);
  expect(
    await hidden.evaluate((el) => {
      const s = getComputedStyle(el);
      return s.overflow === 'hidden' && (s.clip === 'rect(0px, 0px, 0px, 0px)' || s.clipPath === 'inset(50%)');
    }),
    'clipped away'
  ).toBe(true);
  await expect(link).toHaveAccessibleName(
    marker === null ? `${title} ${STATUS[status].text}` : `${title} ${STATUS[status].text} ${marker}`
  );
}

test.describe('18-S5-1 orange is a palette variable, and status-complete references it', () => {
  test('orange holds the human value, status-complete follows it live, and both are in the catalog', async ({ page }) => {
    await freshBuilder(page);
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-colors')).toBeVisible();

    expect(
      (await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--palette-orange').trim())).toLowerCase(),
      '--palette-orange'
    ).toBe(ORANGE.toLowerCase());
    expect(rgbOf(await resolve(page, 'var(--palette-orange)')), '--palette-orange').toEqual(hex(ORANGE));
    expect(rgbOf(await resolve(page, 'var(--color-status-complete)')), '--color-status-complete').toEqual(hex(ORANGE));

    await page.evaluate(() => document.documentElement.style.setProperty('--palette-orange', '#123456'));
    expect(rgbOf(await resolve(page, 'var(--color-status-complete)')), 'status-complete follows orange').toEqual(hex('#123456'));
    await page.evaluate(() => document.documentElement.style.removeProperty('--palette-orange'));
    expect(rgbOf(await resolve(page, 'var(--color-status-complete)')), 'status-complete restored').toEqual(hex(ORANGE));

    const variable = page.locator('[data-testid="sg-color-variable"][data-variable="orange"]');
    await expect(variable, 'a catalog row for orange').toBeVisible();
    await expect(variable).toContainText(/EF9D05/i);
    expect(rgbOf(await bgOf(variable.getByTestId('sg-swatch'))), 'orange swatch').toEqual(hex(ORANGE));

    const style = page.locator('[data-testid="sg-color-style"][data-style="status-complete"]');
    await expect(style, 'a catalog row for status-complete').toBeVisible();
    await expect(style).toContainText('status-complete');
    await expect(style).toContainText('orange');
    expect(rgbOf(await bgOf(style.getByTestId('sg-swatch'))), 'status-complete swatch').toEqual(hex(ORANGE));
  });
});

test.describe('18-S5-2 a puzzle the caller has completed draws DONE', () => {
  test('the caller’s completed puzzles draw DONE, whoever built them; every other published row keeps Play', async ({ page }) => {
    const me = await freshBuilder(page);
    const other = await seedOtherBuilder();
    const done = [
      await seedPublished(me, me, 'complete', { label: 'own complete' }),
      await seedPublished(other, me, 'complete', { label: 'foreign complete' }),
      await seedPublished(other, me, 'complete', { visibility: 'private', label: 'foreign unlisted complete' }),
    ];
    const play = [
      await seedOwn(me, 'public published', 'own untouched'),
      await seedPublished(other, me, 'none', { label: 'foreign untouched' }),
      await seedPublished(other, me, 'in-play', { label: 'foreign in play' }),
      // Completed by someone else, not by the caller.
      await seedPublished(me, other, 'complete', { label: 'own completed by another' }),
      await seedPublished(other, other, 'complete', { label: 'foreign completed by another' }),
    ];
    await openLibrary(page);

    const labels: Partial<Record<Status, Set<string>>> = {};
    for (const [fixtures, status] of [[done, 'done'], [play, 'play']] as const) {
      for (const fixture of fixtures) {
        const item = row(page, fixture.title);
        await expect(item).toHaveCount(1);
        await item.scrollIntoViewIfNeeded();
        await page.mouse.move(0, 0);
        labels[status] = await expectIcon(page, item, status, status === 'done' ? COMPLETE_ROW : PLAY_ROW);
      }
    }
    // The label reads DONE, not PLAY.
    expect(labelDifference(labels.done!, labels.play!), 'DONE’s label differs from PLAY’s').toBeGreaterThan(20);
  });

  test('the DONE icon is 46×34, 4px in, centered, and the title stays 56px in', async ({ page }) => {
    const me = await freshBuilder(page);
    const fixture = await seedPublished(me, me, 'complete');
    await openLibrary(page);

    const item = row(page, fixture.title);
    const r = await box(item);
    const i = await box(item.getByTestId('puzzle-icon'));
    const t = await box(item.getByTestId('puzzle-list-title'));
    expect(i.width, 'icon width').toBeCloseTo(46, 0);
    expect(i.height, 'icon height').toBeCloseTo(34, 0);
    expect(i.x - r.x, 'icon inset').toBeCloseTo(4, 0);
    expect(i.y + i.height / 2, 'icon centered').toBeCloseTo(r.y + r.height / 2, 0);
    expect(t.x - r.x, 'title inset, 12px after the grid').toBeCloseTo(56, 0);
  });

  test('the style guide’s completed sample row draws DONE', async ({ page }) => {
    await freshBuilder(page);
    await page.goto('/style-guide');
    const sample = page.getByTestId('sg-puzzle-row').getByTestId('puzzle-list-item').filter({ has: page.getByTestId('puzzle-play-link') });
    await expect(sample).toHaveCount(1);
    await sample.scrollIntoViewIfNeeded();
    await page.mouse.move(0, 0);
    await expectIcon(page, sample, 'done', COMPLETE_ROW);
  });
});

test.describe('18-S5-3 the hidden status names the completed state; [complete] is gone', () => {
  test('a completed row reads "Complete" in hidden text, shows no marker and keeps Reset; [in-play] stays', async ({ page }) => {
    const me = await freshBuilder(page);
    const other = await seedOtherBuilder();
    const ownComplete = await seedPublished(me, me, 'complete');
    const foreignComplete = await seedPublished(other, me, 'complete');
    const inPlay = await seedPublished(other, me, 'in-play');
    const untouched = await seedPublished(other, me, 'none');
    await openLibrary(page);

    for (const fixture of [ownComplete, foreignComplete]) {
      const item = row(page, fixture.title);
      await expect(item).toHaveAttribute('data-play-state', 'completed');
      await expectHiddenStatus(item, fixture.title, 'done', null);
      await expect(item).not.toContainText('[complete]');
      await expect(item.getByTestId('puzzle-play-state')).toHaveCount(0);
      // 19-S3: the caller's own row offers Reset in its menu.
      if (fixture === foreignComplete) await expect(item.getByTestId('puzzle-reset-button')).toBeVisible();
      else {
        await expect(item.getByTestId('puzzle-reset-button')).toHaveCount(0);
        await item.getByTestId('puzzle-menu-button').click();
        await expect(page.getByTestId('puzzle-menu').getByTestId('puzzle-menu-reset')).toBeVisible();
        await page.keyboard.press('Escape');
      }
    }

    const playing = row(page, inPlay.title);
    await expectHiddenStatus(playing, inPlay.title, 'play', '[in-play]');
    await expect(playing.getByTestId('puzzle-play-state')).toHaveText('[in-play]');
    await expect(playing.getByTestId('puzzle-play-state')).toBeVisible();
    await expectHiddenStatus(row(page, untouched.title), untouched.title, 'play', null);
  });
});

test.describe('18-S5-4 a completed row is orange (19-S2)', () => {
  test('the caller’s own completed row is puzzle-row-complete, puzzle-row-complete-hover on hover and keyboard focus, not on mouse focus', async ({ page }) => {
    const me = await freshBuilder(page);
    const fixture = await seedPublished(me, me, 'complete');
    await openLibrary(page);
    await expectRowColors(page, row(page, fixture.title), COMPLETE_ROW, COMPLETE_ROW_HOVER, fixture.title);
  });
});

test.describe('18-S5-5 resetting a completed puzzle from the library turns DONE back to Play', () => {
  test('after Reset the row draws Play and reads "Ready to play"', async ({ page }) => {
    const me = await freshBuilder(page);
    const other = await seedOtherBuilder();
    const fixture = await seedPublished(other, me, 'complete');
    await openLibrary(page);

    const item = row(page, fixture.title);
    await item.scrollIntoViewIfNeeded();
    await page.mouse.move(0, 0);
    await expectIcon(page, item, 'done', COMPLETE_ROW);
    await item.getByTestId('puzzle-reset-button').click();
    await expect(page.getByTestId('play-reset-dialog')).toBeVisible();
    await page.getByTestId('play-reset-confirm').click();
    await expect(page.getByTestId('play-reset-dialog')).toHaveCount(0);
    await expect(item).toHaveAttribute('data-play-state', 'untouched');

    await page.mouse.move(0, 0);
    await expectIcon(page, item, 'play', PLAY_ROW);
    await expectHiddenStatus(item, fixture.title, 'play', null);
  });
});

async function expectRowColors(page: Page, item: Locator, rest: string, hover: string, label: string) {
  const link = item.getByTestId('puzzle-play-link');
  const isColor = async (expected: string) => JSON.stringify(rgbOf(await bgOf(item))) === JSON.stringify(hex(expected));

  await item.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await expect.poll(() => isColor(rest), { message: `${label} at rest` }).toBe(true);
  const transition = await item.evaluate((el) => {
    const s = getComputedStyle(el);
    return { property: s.transitionProperty, duration: s.transitionDuration };
  });
  expect(transition.duration.split(',').map((d) => d.trim()), `${label} transition`).toContain('0.15s');
  expect(transition.property).toMatch(/\b(all|background-color)\b/);

  const date = await item.getByTestId('puzzle-list-updated').boundingBox();
  if (!date) throw new Error('no date box');
  await page.mouse.move(date.x + date.width / 2, date.y + date.height / 2);
  await expect.poll(() => isColor(hover), { message: `${label} on hover` }).toBe(true);
  await page.mouse.move(0, 0);
  await expect.poll(() => isColor(rest), { message: `${label} after hover` }).toBe(true);

  await link.evaluate((el) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled])'));
    all[all.indexOf(el as HTMLElement) - 1].focus();
  });
  await page.keyboard.press('Tab');
  await expect(link).toBeFocused();
  await expect.poll(() => isColor(hover), { message: `${label} on keyboard focus` }).toBe(true);
  await link.blur();
  await expect.poll(() => isColor(rest), { message: `${label} after keyboard focus` }).toBe(true);

  // Press on the title without releasing, then leave: the link has mouse focus only.
  const title = await item.getByTestId('puzzle-list-title').boundingBox();
  if (!title) throw new Error('no title box');
  await page.mouse.move(title.x + 4, title.y + title.height / 2);
  await page.mouse.down();
  await page.mouse.move(0, 0);
  expect(await link.evaluate((el) => el === document.activeElement), `${label}: link focused by the mouse`).toBe(true);
  await page.waitForTimeout(300);
  expect(await isColor(rest), `${label} on mouse focus`).toBe(true);
  await page.mouse.up();
}
