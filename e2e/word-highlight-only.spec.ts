import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S14 — only the word is highlighted.
//
// In the build phase with Preview off, with the cursor in a word (21-S8:
// the run of Preview-white cells through it in its direction, 2 or more),
// only that word is highlighted: its cells blue-medium, the cursor yellow.
// Every other cell of the row or column looks as it would outside the
// highlight: an off cell gray-200, a lettered cell or a symmetric hint
// white. With the cursor in no word (on a Preview-black cell, or a lone
// white cell), the row or column's off cells are dull blue, showing the
// direction, and its lettered cells and symmetric hints stay white.
//
// The human's example, across (x Preview-black, _ Preview-red, a letter a
// lettered cell):  x x x _ _ B A R x x x x x x x
//
// Colors are the human's values, written out here. Do not edit this file
// to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const CURSOR = 'rgb(252, 255, 77)'; // yellow-bright
const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // #CFEEFF
const BLUE_DULL = 'rgb(202, 218, 226)'; // #CADAE2
const OFF = 'rgb(221, 224, 230)'; // gray-200, build-cell-off
const WHITE = 'rgb(255, 255, 255)'; // build-cell-on

// A daily (the counterpart of (c,r) is (14−c, 14−r)):
//   row 2: BAR at 5–7; NO at (10,12), (11,12) makes (4,2) and (3,2)
//   Preview-red, so the across word is (3–7, 2): _ _ B A R.
//   column 6: A at (6,2) is alone down; HI at (6,9), (6,10) is a down word.
const ROW = Array.from({ length: 15 }, (_, col) => `${col},2`);
const COLUMN = Array.from({ length: 15 }, (_, row) => `6,${row}`);
const STARS = ['3,2', '4,2'];
const BAR = ['5,2', '6,2', '7,2'];
const WORD = [...STARS, ...BAR];
const HI = ['6,9', '6,10'];

function exampleGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  const put = (cells: string[], letters: string) =>
    cells.forEach((coord, i) => {
      const [col, row] = coord.split(',').map(Number);
      grid = withLetter(grid, { col, row }, letters[i]);
    });
  put(BAR, 'BAR');
  put(['10,12', '11,12'], 'NO');
  put(HI, 'HI');
  return grid;
}

async function open(page: Page) {
  const { id } = await seedPuzzle({ grid: exampleGrid(), hints: {}, phase: 'grid' }, `21-S14 ${Date.now()}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const bg = (locator: Locator) => locator.evaluate((el) => getComputedStyle(el).backgroundColor);

/** The cursor on `coord`, in `orientation`. A click on a cell keeps the
 *  cursor's direction; a click on the cursor's own cell turns it. */
async function cursorOn(page: Page, coord: string, orientation: 'across' | 'down') {
  const [col, row] = coord.split(',').map(Number);
  const other = orientation === 'across' ? `${col === 0 ? 1 : 0},${row}` : `${col},${row === 0 ? 1 : 0}`;
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  if ((await cell(page, other).getAttribute('data-highlight')) !== 'slot') await cell(page, coord).click();
  await expect(cell(page, other)).toHaveAttribute('data-highlight', 'slot');
}

type Look = { state: string; color: string };
const IN_WORD_LETTER: Look = { state: 'slot-letter', color: BLUE_MEDIUM };
const IN_WORD_STAR: Look = { state: 'slot-required', color: BLUE_MEDIUM };
const LINE_OFF: Look = { state: 'slot', color: BLUE_DULL };
const PLAIN_OFF: Look = { state: 'empty', color: OFF };
const PLAIN_LETTER: Look = { state: 'letter', color: WHITE };
const PLAIN_STAR: Look = { state: 'symmetric-hint', color: WHITE };

async function expectLooks(page: Page, cursor: string, want: (coord: string) => Look) {
  await expect(cell(page, cursor)).toHaveAttribute('data-cell-state', 'selected');
  expect(await bg(cell(page, cursor)), 'the cursor').toBe(CURSOR);
  const line = ROW.includes(cursor) && COLUMN.includes(cursor) ? [...ROW, ...COLUMN] : ROW.includes(cursor) ? ROW : COLUMN;
  for (const coord of new Set(line)) {
    if (coord === cursor) continue;
    const { state, color } = want(coord);
    await expect(cell(page, coord), coord).toHaveAttribute('data-cell-state', state);
    expect(await bg(cell(page, coord)), coord).toBe(color);
  }
}

/** Outside any highlight: how the example's cells look. */
function plain(coord: string): Look {
  if (STARS.includes(coord)) return PLAIN_STAR;
  if (BAR.includes(coord) || HI.includes(coord)) return PLAIN_LETTER;
  return PLAIN_OFF;
}

test.describe('21-S14-1 the cursor in an across word, going across', () => {
  test('on B: only _ _ B A R is highlighted; the row\'s off cells stay gray', async ({ page }) => {
    await open(page);
    await cursorOn(page, '5,2', 'across');
    await expectLooks(page, '5,2', (coord) =>
      STARS.includes(coord) ? IN_WORD_STAR : BAR.includes(coord) ? IN_WORD_LETTER : plain(coord)
    );
  });

  test('on a Preview-red cell: the same word, and nothing else changes', async ({ page }) => {
    await open(page);
    await cursorOn(page, '3,2', 'across');
    await expectLooks(page, '3,2', (coord) =>
      STARS.includes(coord) ? IN_WORD_STAR : BAR.includes(coord) ? IN_WORD_LETTER : plain(coord)
    );
  });
});

test.describe('21-S14-2 the cursor on an off cell', () => {
  test('across: the row\'s other off cells dull blue; _ _ B A R stay white', async ({ page }) => {
    await open(page);
    await cursorOn(page, '1,2', 'across');
    await expectLooks(page, '1,2', (coord) => (WORD.includes(coord) ? plain(coord) : LINE_OFF));
  });
});

test.describe('21-S14-3 the other direction', () => {
  test('on A going down (alone down): the column\'s off cells dull blue, H and I white, the across word not highlighted', async ({
    page,
  }) => {
    await open(page);
    await cursorOn(page, '6,2', 'down');
    await expectLooks(page, '6,2', (coord) => {
      if (ROW.includes(coord)) return plain(coord);
      return HI.includes(coord) ? PLAIN_LETTER : LINE_OFF;
    });
  });

  test('on H going down: only HI is highlighted; the column\'s off cells and A stay as they are', async ({ page }) => {
    await open(page);
    await cursorOn(page, '6,9', 'down');
    await expectLooks(page, '6,9', (coord) => (coord === '6,10' ? IN_WORD_LETTER : plain(coord)));
  });
});
