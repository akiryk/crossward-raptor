test.describe('16-S2-1 the three-dot button', () => {
  test('every Build row has one in place of Delete; Play rows have none', async ({ page }) => {
    const me = await currentBuilderId(page);
    const fixtures = [
      await seedOwn(me, 'grid'),
      await seedOwn(me, 'hints'),
      await seedOwn(me, 'private published'),
      await seedOwn(me, 'public published'),
    ];
    await library(page);
    await showView(page, 'Build');
    for (const fixture of fixtures) {
      const item = row(page, fixture.title);
      await expect(trigger(item)).toHaveCount(1);
      await expect(item.getByTestId('puzzle-delete-button')).toHaveCount(0);
      await expect(item.locator('button')).toHaveCount(1);
      await expect(trigger(item)).toHaveAccessibleName(`Actions for ${fixture.title}`);
      await expect(trigger(item)).toHaveAttribute('aria-haspopup', 'menu');
      await expect(trigger(item)).toHaveAttribute('aria-expanded', 'false');
    }
    await expect(menu(page)).toHaveCount(0);

    await showView(page, 'Play');
    for (const fixture of fixtures.slice(2)) {
      await expect(row(page, fixture.title)).toHaveCount(1);
      await expect(trigger(row(page, fixture.title))).toHaveCount(0);
    }
  });

  test('it is a 24px button of three dots, 12px from the right, centered on the title line, muted, primary on hover and keyboard focus, with the focus ring', async ({ page }) => {
    const draft = await seedOwn(await currentBuilderId(page), 'grid');
    await library(page);
    const item = row(page, draft.title);
    const button = trigger(item);

    expect(await button.evaluate((el) => el.tagName.toLowerCase())).toBe('button');
    expect((await button.textContent())?.trim(), 'no visible text').toBe('');
    await expect(button.locator('svg circle')).toHaveCount(3);
    expect(await css(button, 'cursor')).toBe('pointer');

    const b = await box(button);
    const r = await box(item);
    const title = await box(item.getByTestId('puzzle-list-title'));
    expect(b.width, 'width').toBeCloseTo(24, 0);
    expect(b.height, 'height').toBeCloseTo(24, 0);
    expect(r.x + r.width - (b.x + b.width), 'right inset').toBeCloseTo(12, 0);
    expect(b.y + b.height / 2, 'centered on the title line').toBeCloseTo(title.y + title.height / 2, 0);

    await page.mouse.move(0, 0);
    expect(await colorOf(button, 'color'), 'at rest').toEqual(await token(page, 'muted'));
    await button.hover();
    await expect.poll(() => colorOf(button, 'color'), { message: 'on hover' }).toEqual(await token(page, 'primary'));
    await page.mouse.move(0, 0);
    await expect.poll(() => colorOf(button, 'color')).toEqual(await token(page, 'muted'));
    await tabTo(page, button);
    await expect.poll(() => colorOf(button, 'color'), { message: 'on keyboard focus' }).toEqual(await token(page, 'primary'));
    expect(await ringOf(button), 'focus ring').toBe(FOCUS_RING);
  });
});

