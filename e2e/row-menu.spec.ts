test.describe('16-S2-7 changing visibility', () => {
  test('Make public, then Make unlisted: only visibility changes, in place, and the menu then offers the other', async ({ page }) => {
    const me = await currentBuilderId(page);
    const fixture = await seedOwn(me, 'private published');
    await seedPlaySession(await seedOtherBuilder(), fixture.id, deserializeGrid(partial));
    const before = await snapshot(fixture.id);
    expect(before.visibility).toBe('private');
    await library(page);
    await page.evaluate(() => { (window as unknown as { s2Marker: boolean }).s2Marker = true; });
    const item = row(page, fixture.title);

    for (const [choice, stored, next] of [
      ['Make public', 'public', 'Make unlisted'],
      ['Make unlisted', 'private', 'Make public'],
    ] as const) {
      await openMenu(page, item);
      await items(page).filter({ hasText: choice }).click();
      await expect(menu(page), `${choice} closes the menu`).toHaveCount(0);
      await expect(trigger(item)).toBeFocused();
      await expect(item).toHaveAttribute('data-visibility', stored);
      await expect.poll(async () => (await snapshot(fixture.id)).visibility).toBe(stored);
      const after = await snapshot(fixture.id);
      expect(after.rest, `${choice}: id, title, grid, hints, phase, dates unchanged`).toEqual(before.rest);
      expect(after.sessions, `${choice}: play sessions unchanged`).toEqual(before.sessions);
      await expect(item.getByTestId('puzzle-status-badge')).toHaveText('[published]');

      await openMenu(page, item);
      expect(await itemTexts(page)).toEqual(['Duplicate', next, 'Delete']); // 16-S3: Delete follows; 16-S4: Duplicate leads
      await page.keyboard.press('Escape');
    }
    expect(await page.evaluate(() => (window as unknown as { s2Marker?: boolean }).s2Marker), 'no reload').toBe(true);
    await expect(page).toHaveURL(/\/puzzles$/);

    await library(page);
    await expect(row(page, fixture.title)).toHaveAttribute('data-visibility', 'private');
  });

  test('a pending change disables the item and keeps the menu open; a failed one says so and can be retried', async ({ page }) => {
    const fixture = await seedOwn(await currentBuilderId(page), 'private published');
    await library(page);
    const item = row(page, fixture.title);
    const held = gate();
    let requests = 0;
    let failNext = false;
    await page.route('**/puzzles', async (route) => {
      if (!route.request().headers()['next-action']) return route.continue();
      requests++;
      if (failNext) { failNext = false; return route.abort('failed'); }
      await held.promise;
      return route.continue();
    });

    await openMenu(page, item);
    const choice = menu(page).getByTestId('puzzle-menu-visibility');
    try {
      await choice.click();
      await expect.poll(() => requests).toBe(1);
      await expect(choice).toHaveAttribute('aria-disabled', 'true');
      await page.keyboard.press('Escape');
      await page.getByTestId('page-heading').click();
      await expect(menu(page), 'stays open while pending').toBeVisible();
      await choice.click({ force: true });
      expect(requests, 'no second request while pending').toBe(1);
    } finally {
      held.release();
    }
    await expect(menu(page)).toHaveCount(0);
    await expect(item).toHaveAttribute('data-visibility', 'public');

    failNext = true;
    await openMenu(page, item);
    await menu(page).getByTestId('puzzle-menu-visibility').click();
    const alert = page.getByTestId('puzzle-menu-error');
    await expect(alert).toHaveText('Could not make the puzzle unlisted. Please try again.');
    await expect(alert).toHaveAttribute('role', 'alert');
    await expect(menu(page)).toBeVisible();
    await expect(menu(page).getByTestId('puzzle-menu-visibility')).not.toHaveAttribute('aria-disabled', 'true');
    await expect(item).toHaveAttribute('data-visibility', 'public');
    expect((await snapshot(fixture.id)).visibility).toBe('public');

    await menu(page).getByTestId('puzzle-menu-visibility').click();
    await expect(menu(page)).toHaveCount(0);
    await expect(page.getByTestId('puzzle-menu-error')).toHaveCount(0);
    await expect(item).toHaveAttribute('data-visibility', 'private');
    await expect.poll(async () => (await snapshot(fixture.id)).visibility).toBe('private');
  });
});

