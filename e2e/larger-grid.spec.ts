// Story 17-S7 — Larger grid.
//
// The builder's and play's grids are at most 700px (was 560px), held down
// to a 748px window (700 plus the page's 24px padding each side). The
// layout's thresholds move by the same 140px: the builder is narrow below
// a 1140px window (1092px of room), its hint columns stack below a 1430px
// window (650px beside the grid), and play is narrow below a 1430px window
// (1382px of room).
//
// Letters and numbers sit as in the NYT's grid, measured from its 21×21
// at 535px and given here as fractions of the cell's pitch (the grid's
// width less 1px, over its size): the number's digits at the top left,
// 0.24 of the pitch tall, 0.10 from the cell's top; the letter's capitals
// 0.475 tall, centered across, their bottom 0.91 down. Both scale with the
// pitch, so the number never touches the letter at any grid size or width.
// They are measured by their ink, in screenshots at twice the pixel
// density, with the other hidden.
//
// Do not edit this file to match an implementation.

const GRID_PX = 700;
const PAGE_PADDING_PX = 24;
const GAP_PX = 32;
const PHONE = { width: 375, height: 900 };

// The NYT's measurements, per pitch.
const NUMBER_HEIGHT = 0.24;
const NUMBER_TOP = 0.1;
const LETTER_HEIGHT = 0.475;
const LETTER_BOTTOM = 0.91;
const TOLERANCE = 0.03;

test.use({ deviceScaleFactor: 2 });

/** Every cell lettered with `letter`, so every word survives. */
function filled(size: number, letter = 'M'): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, letter);
  }
  return grid;
}

/**
 * A 21×21 with a black cell at every third row and column (1, 4, … 19),
 * the rest lettered QWOM in turn, or all `letter`: 111 numbers, 100 to 111
 * in its last four rows. Q, O and W are the letters with the most ink.
 */
function lattice(letter?: string): Grid {
  const black = [];
  for (let row = 1; row < 21; row += 3) {
    for (let col = 1; col < 21; col += 3) black.push({ col, row });
  }
  let grid = createGrid({ cols: 21, rows: 21, black });
  for (let row = 0; row < 21; row++) {
    for (let col = 0; col < 21; col++) {
      if (col % 3 === 1 && row % 3 === 1) continue;
      grid = withLetter(grid, { col, row }, letter ?? 'QWOM'[(col + row) % 4]);
    }
  }
  return grid;
}

/** A hint for every word of an all-on square. */
function everyHint(size: number): Record<string, string> {
  const hints: Record<string, string> = {};
  for (let n = 1; n <= size; n++) hints[`${n}-down`] = `Down hint ${n}`;
  hints['1-across'] = 'Across hint 1';
  for (let row = 1; row < size; row++) hints[`${size + row}-across`] = `Across hint ${size + row}`;
  return hints;
}

async function openBuilder(page: Page, viewport: { width: number; height: number }, grid: Grid, phase: 'grid' | 'hints' = 'hints') {
  await page.setViewportSize(viewport);
  const { id } = await seedPuzzle({ grid, hints: phase === 'hints' && grid.cols === 5 ? everyHint(5) : {}, phase }, 'Larger grid');
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

/** Play, as its builder; `entries`, if given, are the player's letters so far. */
async function openPlay(page: Page, viewport: { width: number; height: number }, grid: Grid, entries?: Grid) {
  await page.setViewportSize(viewport);
  const builderId = await currentBuilderId(page);
  const fixture = await seedPlayPuzzle({
    builderId,
    puzzle: { grid, phase: 'hints', hints: grid.cols === 5 ? everyHint(5) : { '1-across': 'A hint' } },
  });
  if (entries) await seedPlaySession(builderId, fixture.id, entries);
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

async function rect(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const column = (page: Page, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="hint-column"][data-orientation="${orientation}"]`);
const playColumn = (page: Page, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="play-clue-column"][data-orientation="${orientation}"]`);

interface Ink { left: number; top: number; right: number; bottom: number }
interface CellInk { coord: string; size: number; number: Ink | null; letter: Ink | null }

// Each measurement paints the cells white, without lines, and shows only
// the numbers or only the letters, in black.
const SHOW: Record<'number' | 'letter', string> = {
  number: `
    [data-testid="puzzle-grid"], [data-testid="grid-cell"] { background: #fff !important; }
    [data-testid="grid-cell"], [data-testid="grid-cell"] * { color: transparent !important; }
    [data-testid="grid-cell"] [data-testid="cell-number"] { color: #000 !important; }`,
  letter: `
    [data-testid="puzzle-grid"], [data-testid="grid-cell"] { background: #fff !important; }
    [data-testid="grid-cell"], [data-testid="grid-cell"] * { color: #000 !important; }
    [data-testid="grid-cell"] [data-testid="cell-number"] { visibility: hidden !important; }`,
};

/**
 * The ink of each white cell wholly inside `area`, in CSS px from the
 * cell's top left: the darkest pixels (luminance under half) of a
 * screenshot showing only the numbers, or only the letters.
 */
async function inkOf(page: Page, area: Locator, show: 'number' | 'letter') {
  const style = await page.addStyleTag({ content: SHOW[show] });
  const png = await area.screenshot({ animations: 'disabled', caret: 'hide' });
  await style.evaluate((el) => (el as Element).remove());
  return area.evaluate(async (el, b64) => {
    const img = new Image();
    img.src = `data:image/png;base64,${b64}`;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = img.width;
    canvas.height = img.height;
    const ctx = canvas.getContext('2d')!;
    ctx.drawImage(img, 0, 0);
    const data = ctx.getImageData(0, 0, img.width, img.height).data;
    const a = el.getBoundingClientRect();
    const scale = img.width / a.width;
    const out: Record<string, { left: number; top: number; right: number; bottom: number } | null> = {};
    for (const cell of el.querySelectorAll<HTMLElement>('[data-testid="grid-cell"][data-kind="active"]')) {
      const r = cell.getBoundingClientRect();
      if (r.left < a.left - 0.5 || r.top < a.top - 0.5 || r.right > a.right + 0.5 || r.bottom > a.bottom + 0.5) continue;
      const x0 = Math.ceil((r.left - a.left) * scale);
      const y0 = Math.ceil((r.top - a.top) * scale);
      const x1 = Math.floor((r.right - a.left) * scale);
      const y1 = Math.floor((r.bottom - a.top) * scale);
      let box: { left: number; top: number; right: number; bottom: number } | null = null;
      for (let y = y0; y < y1; y++) {
        for (let x = x0; x < x1; x++) {
          const i = (y * img.width + x) * 4;
          const lum = 0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2];
          if (lum >= 128) continue;
          const px = (x - (r.left - a.left) * scale) / scale;
          const py = (y - (r.top - a.top) * scale) / scale;
          if (!box) box = { left: px, top: py, right: px + 1 / scale, bottom: py + 1 / scale };
          else {
            box.left = Math.min(box.left, px);
            box.top = Math.min(box.top, py);
            box.right = Math.max(box.right, px + 1 / scale);
            box.bottom = Math.max(box.bottom, py + 1 / scale);
          }
        }
      }
      out[cell.dataset.coord!] = box;
    }
    return out;
  }, png.toString('base64'));
}

/** Each numbered, lettered cell inside `area`, with its two inks. */
async function cellInks(page: Page, area: Locator): Promise<CellInk[]> {
  const numbers = await inkOf(page, area, 'number');
  const letters = await inkOf(page, area, 'letter');
  const sizes = await area.locator('[data-testid="grid-cell"][data-kind="active"]').evaluateAll((cells) =>
    Object.fromEntries(cells.map((c) => [(c as HTMLElement).dataset.coord!, c.getBoundingClientRect().width]))
  );
  return Object.keys(numbers)
    .filter((coord) => numbers[coord] && letters[coord])
    .map((coord) => ({ coord, size: sizes[coord], number: numbers[coord], letter: letters[coord] }));
}

/** The number's ink ends above the letter's, with clear space between. */
function expectClear(inks: CellInk[], label: string) {
  expect(inks.length, `${label}: numbered, lettered cells measured`).toBeGreaterThan(0);
  for (const { coord, size, number, letter } of inks) {
    expect(number!.bottom, `${label} ${coord}: the number above the letter`).toBeLessThan(letter!.top);
    expect(letter!.left, `${label} ${coord}: the letter inside its cell`).toBeGreaterThanOrEqual(0);
    expect(letter!.right, `${label} ${coord}: the letter inside its cell`).toBeLessThanOrEqual(size);
    expect(letter!.bottom, `${label} ${coord}: the letter inside its cell`).toBeLessThanOrEqual(size);
    expect(number!.right, `${label} ${coord}: the number inside its cell`).toBeLessThanOrEqual(size);
  }
}

/** The NYT's proportions, in the cell (0,0) of a grid of `size`. */
async function expectNytProportions(page: Page, size: number) {
  const g = await rect(grid(page));
  const pitch = (g.width - 1) / size;
  const ink = (await cellInks(page, grid(page))).find((c) => c.coord === '0,0');
  expect(ink, 'cell 0,0 has a number and a letter').toBeTruthy();
  const { number, letter, size: cellSize } = ink!;
  const near = (actual: number, ratio: number, name: string) =>
    expect(Math.abs(actual / pitch - ratio), `${name}: ${(actual / pitch).toFixed(3)} of the pitch, expected ${ratio}`).toBeLessThanOrEqual(TOLERANCE);

  near(number!.bottom - number!.top, NUMBER_HEIGHT, 'the number’s height');
  near(number!.top, NUMBER_TOP, 'the number from the cell’s top');
  expect(number!.left / pitch, 'the number at the left').toBeLessThanOrEqual(0.15);
  near(letter!.bottom - letter!.top, LETTER_HEIGHT, 'the letter’s height');
  near(letter!.bottom, LETTER_BOTTOM, 'the letter’s bottom');
  near((letter!.left + letter!.right) / 2, cellSize / 2 / pitch, 'the letter centered');
}

// --- 17-S7-1: 700px ---
test.describe('17-S7-1 the grid is 700px', () => {
  for (const size of [5, 15, 21]) {
    test(`a ${size}×${size} in the build phase is 700px, its cells sharing 1px lines`, async ({ page }) => {
      await openBuilder(page, { width: 1440, height: 900 }, filled(size), 'grid');
      const g = await rect(grid(page));
      expect(g.width, 'width').toBeCloseTo(GRID_PX, 0);
      expect(g.height, 'height').toBeCloseTo(GRID_PX, 0);
      const pitch = (GRID_PX - 1) / size;
      const last = await rect(page.locator(`[data-coord="${size - 1},${size - 1}"]`));
      expect(last.x - g.x, 'the last cell at its pitch').toBeCloseTo(1 + (size - 1) * pitch, 0);
    });
  }

  test('a 15×15 in the hints phase and in Preview is 700px', async ({ page }) => {
    await openBuilder(page, { width: 1440, height: 900 }, filled(15), 'hints');
    expect((await rect(grid(page))).width, 'hints phase').toBeCloseTo(GRID_PX, 0);
    await openBuilder(page, { width: 1440, height: 900 }, filled(15), 'grid');
    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');
    expect((await rect(grid(page))).width, 'Preview').toBeCloseTo(GRID_PX, 0);
  });

  test('a 15×15 in play is 700px', async ({ page }) => {
    await openPlay(page, { width: 1440, height: 900 }, filled(15));
    expect((await rect(grid(page))).width).toBeCloseTo(GRID_PX, 0);
  });
});

// --- 17-S7-2: the grid shrinks last ---
