// --- 17-S7-6: numbers clear of letters ---
test.describe('17-S7-6 numbers never touch letters', () => {
  const cases: [string, { width: number; height: number }][] = [
    ['at 700px', { width: 1440, height: 900 }],
    ['at 375px', PHONE],
  ];
  for (const [name, viewport] of cases) {
    test(`a Sunday’s one- to three-digit numbers ${name}, in the hints phase`, async ({ page }) => {
      await openBuilder(page, viewport, lattice(), 'hints');
      const inks = await cellInks(page, grid(page));
      expect(inks.some((c) => c.coord === '0,20'), 'number 111 measured').toBe(true);
      expectClear(inks, name);
    });
  }

  test('a Sunday at 700px in play', async ({ page }) => {
    // Answers all A, so the player's QWOM letters don't solve it.
    await openPlay(page, { width: 1440, height: 900 }, lattice('A'), lattice());
    await expect(page.locator('[data-coord="0,20"]')).toContainText('Q');
    expectClear(await cellInks(page, grid(page)), 'play');
  });

  for (const size of [5, 15]) {
    test(`a ${size}×${size} at 700px`, async ({ page }) => {
      await openBuilder(page, { width: 1440, height: 900 }, filled(size, 'Q'), 'grid');
      expectClear(await cellInks(page, grid(page)), `${size}×${size}`);
    });
  }
});

// --- 17-S7-7: the style guide's Sunday corner ---
test.describe('17-S7-7 the style guide’s Sunday corner', () => {
  test('sg-grid-corner shows a 21×21’s cells at the 700px pitch, three-digit numbers clear of their letters', async ({ page }) => {
    await page.goto('/style-guide');
    const sample = page.getByTestId('sg-grid-corner');
    await expect(sample).toBeVisible();
    const cells = sample.locator('[data-testid="grid-cell"]');
    const first = await rect(cells.first());
    const second = await rect(cells.nth(1));
    expect(second.x - first.x, 'the 700px grid’s pitch').toBeCloseTo((GRID_PX - 1) / 21, 1);
    const numbers = await sample.getByTestId('cell-number').allTextContents();
    expect(numbers.some((n) => n.length === 3), 'a three-digit number').toBe(true);
    const inks = await cellInks(page, sample);
    const three = [];
    for (const ink of inks) {
      const n = await sample.locator(`[data-coord="${ink.coord}"]`).getByTestId('cell-number').textContent();
      if (n?.length === 3) three.push(ink);
    }
    expect(three.length, 'a visible three-digit number over a letter').toBeGreaterThan(0);
    expectClear(three, 'sg-grid-corner');
  });
});
