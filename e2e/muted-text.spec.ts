// Story 18-S1 — Muted text.
//
// The `muted` color style is black at 40% opacity (mixed from the `black`
// palette variable, like `modal-backdrop`), app-wide, so muted text takes
// on the background it sits on. `gray-500` stays in the palette for its
// other styles. Colors are the human's values written out, not read from
// the styles. Do not edit this file to match an implementation.

test.use({ storageState: { cookies: [], origins: [] } });

type Rgba = { r: number; g: number; b: number; a: number };

/** Black at 40% opacity. */
const MUTED: Rgba = { r: 0, g: 0, b: 0, a: 0.4 };

/** The forms getComputedStyle reports for a colour: rgb(), rgba() and color(srgb ...). */
function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: Rgba, expected: Rgba, label: string) {
  expect({ r: actual.r, g: actual.g, b: actual.b }, label).toEqual({ r: expected.r, g: expected.g, b: expected.b });
  expect(actual.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

async function computed(locator: Locator, property: 'color' | 'backgroundColor') {
  return parseColor(await locator.evaluate((el, p) => getComputedStyle(el)[p], property));
}

/** The colour a CSS value paints as a background on this page. */
async function resolve(page: Page, cssValue: string) {
  return parseColor(
    await page.evaluate((value) => {
      const probe = document.createElement('div');
      probe.style.backgroundColor = value;
      document.body.appendChild(probe);
      const resolved = getComputedStyle(probe).backgroundColor;
      probe.remove();
      return resolved;
    }, cssValue)
  );
}

async function freshBuilder(page: Page) {
  await page.setViewportSize({ width: 1280, height: 800 });
  await signInSeededUser(page);
  const id = await currentBuilderId(page);
  const client = ownershipTestClient();
  try {
    await client.user.update({ where: { id }, data: { displayName: 'Ada Builder' } });
  } finally {
    await client.$disconnect();
  }
  return id;
}

test.describe('18-S1-1 muted text is black at 40%', () => {
  test('on the page and on a puzzle row, so the row shows through', async ({ page }) => {
    const me = await freshBuilder(page);
    const title = `18-S1 muted ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
    await seedPuzzle(createBlankPuzzle('mini'), title, me);
    await page.goto('/puzzles');
    await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');

    expectColor(await resolve(page, 'var(--color-muted)'), MUTED, 'the muted style');

    // On the page's white: a size group's dimensions.
    const group = page.getByTestId('puzzle-group').filter({ hasText: title });
    expectColor(await computed(group.getByTestId('puzzle-group-dimensions'), 'color'), MUTED, 'dimensions');

    // On a puzzle row, whose faint fill is not white.
    const item = page.getByTestId('puzzle-list-item').filter({ hasText: title });
    const fill = await computed(item, 'backgroundColor');
    expect(fill, 'the row is filled').not.toEqual({ r: 255, g: 255, b: 255, a: 1 });
    expect(fill.a, 'the row is opaque').toBe(1);
    await expect(item.getByTestId('puzzle-builder-name')).toHaveText('Ada Builder');
    expectColor(await computed(item.getByTestId('puzzle-builder-name'), 'color'), MUTED, 'builder name');
    expectColor(await computed(item.getByTestId('puzzle-list-updated'), 'color'), MUTED, 'date');
  });
});

test.describe('18-S1-2 gray-500 keeps its other styles', () => {
  test('the borders and alternate button stay gray-500; the catalog names muted black at 40%', async ({ page }) => {
    await freshBuilder(page);
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-colors')).toBeVisible();

    const gray500: Rgba = { r: 139, g: 144, b: 154, a: 1 };
    expectColor(await resolve(page, 'var(--palette-gray-500)'), gray500, '--palette-gray-500');
    for (const style of [
      'preview-cell-border',
      'play-cell-border',
      'hint-cell-border',
      'button-alternate-border',
      'button-alternate-hover',
    ]) {
      expectColor(await resolve(page, `var(--color-${style})`), gray500, style);
    }

    const row = page.locator('[data-testid="sg-color-style"][data-style="muted"]');
    await expect(row).toContainText('black at 40%');
    await expect(row).not.toContainText('gray-500');
    expectColor(await computed(row.getByTestId('sg-swatch'), 'backgroundColor'), MUTED, 'muted swatch');
  });
});
