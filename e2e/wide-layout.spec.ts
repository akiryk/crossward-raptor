import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { currentBuilderId } from './helpers/ownership';
import { seedPlayPuzzle } from './helpers/play-route';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 15-S2 — Wide layout.
//
// Below the full-width masthead, the main area is at most 1800px wide and
// centered. In the builder and play, the hints start 32px right of the
// grid and their Across and Down columns, 32px apart, share the room left.
// In the builder the grid holds 560px; with less than 650px beside it
// (a window under 1290px) the two columns stack into one, still beside
// the grid.
//
// Do not edit this file to match an implementation.

const GRID_PX = 560;
const GAP_PX = 32;
const PAGE_PADDING_PX = 24;
const MAIN_MAX_PX = 1800;
const HUGE = { width: 2400, height: 900 };

/** Every cell lettered, so every word survives into the hints phase. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

/** A hint for every word of an all-on square. */
function everyHint(size: number): Record<string, string> {
  const hints: Record<string, string> = {};
  for (let n = 1; n <= size; n++) hints[`${n}-down`] = `Down hint ${n}`;
  hints['1-across'] = 'Across hint 1';
  for (let row = 1; row < size; row++) hints[`${size + row}-across`] = `Across hint ${size + row}`;
  return hints;
}

async function openBuilder(page: Page, phase: 'grid' | 'hints', size = 5) {
  const { id } = await seedPuzzle({ grid: filled(size), hints: phase === 'hints' ? everyHint(size) : {}, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function openPlay(page: Page, size = 5) {
  const fixture = await seedPlayPuzzle({
    builderId: await currentBuilderId(page),
    puzzle: { grid: filled(size), phase: 'hints', hints: everyHint(size) },
  });
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');

type Phase = 'grid' | 'hints';
const COLUMN: Record<Phase, string> = { grid: 'hint-skeleton-column', hints: 'hint-column' };
const column = (page: Page, phase: Phase, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="${COLUMN[phase]}"][data-orientation="${orientation}"]`);
/** The skeleton's line, or the Hint Input that takes its place. */
const firstLine = (page: Page, phase: Phase) =>
  column(page, phase, 'across').getByTestId(phase === 'grid' ? 'hint-skeleton-line' : 'hint-input').first();

const playColumn = (page: Page, orientation: 'across' | 'down') =>
  page.locator(`[data-testid="play-clue-column"][data-orientation="${orientation}"]`);

// --- 15-S2-1: the main area ---
test.describe('15-S2-1 the main area', () => {
  test('at 2400px: the masthead spans the window, the main area is 1800px and centered', async ({ page }) => {
    await page.setViewportSize(HUGE);
    await openBuilder(page, 'grid');
    const header = await box(page.getByTestId('app-header'));
    const main = await box(page.getByTestId('app-main'));
    expect(header.x, 'masthead left').toBeCloseTo(0, 0);
    expect(header.width, 'masthead width').toBeCloseTo(HUGE.width, 0);
    expect(main.width, 'main width').toBeCloseTo(MAIN_MAX_PX, 0);
    expect(main.x, 'main centered').toBeCloseTo((HUGE.width - MAIN_MAX_PX) / 2, 0);
    const editor = await box(page.getByTestId('puzzle-editor'));
    expect(editor.x, 'the page padding inside the main area').toBeCloseTo(main.x + PAGE_PADDING_PX, 0);
  });

  test('at 1440px the main area is the window’s width', async ({ page }) => {
    await openBuilder(page, 'grid');
    const main = await box(page.getByTestId('app-main'));
    expect(main.x).toBeCloseTo(0, 0);
    expect(main.width).toBeCloseTo(1440, 0);
  });
});

// --- 15-S2-2 and -3: the builder's two columns ---
for (const [id, phase] of [['15-S2-2', 'grid'], ['15-S2-3', 'hints']] as const) {
  const name = phase === 'grid' ? 'the build phase’s skeleton' : 'the hints phase’s Hint Inputs';

  test.describe(`${id} ${name}, two columns`, () => {
    for (const viewport of [{ width: 1440, height: 900 }, HUGE, { width: 1290, height: 900 }]) {
      test(`at ${viewport.width}px: 32px from a 560px grid, two equal columns 32px apart filling the room`, async ({ page }) => {
        await page.setViewportSize(viewport);
        await openBuilder(page, phase);
        const g = await box(grid(page));
        const editor = await box(page.getByTestId('puzzle-editor'));
        const across = await box(column(page, phase, 'across'));
        const down = await box(column(page, phase, 'down'));

        expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
        expect(across.x - g.right, 'from the grid').toBeCloseTo(GAP_PX, 0);
        expect(down.y, 'side by side').toBeCloseTo(across.y, 0);
        expect(down.x - across.right, 'between the columns').toBeCloseTo(GAP_PX, 0);
        expect(down.width, 'equal columns').toBeCloseTo(across.width, 0);
        expect(down.right, 'to the editor’s right edge').toBeCloseTo(editor.right, 0);

        const line = await box(firstLine(page, phase));
        expect(line.right, 'the line fills its column').toBeCloseTo(across.right, 0);
      });
    }
  });
}

// --- 15-S2-4: one column beside the grid ---
test.describe('15-S2-4 one column below 1290px', () => {
  for (const phase of ['grid', 'hints'] as const) {
    for (const width of [1289, 1100, 1024]) {
      test(`${phase === 'grid' ? 'build' : 'hints'} phase at ${width}px: Down below Across, beside a 560px grid`, async ({ page }) => {
        await page.setViewportSize({ width, height: 900 });
        await openBuilder(page, phase);
        const g = await box(grid(page));
        const editor = await box(page.getByTestId('puzzle-editor'));
        const across = await box(column(page, phase, 'across'));
        const down = await box(column(page, phase, 'down'));

        expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
        expect(across.x - g.right, 'from the grid').toBeCloseTo(GAP_PX, 0);
        expect(across.y, 'level with the grid').toBeCloseTo(g.y, 0);
        expect(down.x, 'one column').toBeCloseTo(across.x, 0);
        expect(down.y - across.bottom, 'Down 32px below Across').toBeCloseTo(GAP_PX, 0);
        expect(across.right, 'the column fills the room').toBeCloseTo(editor.right, 0);
        expect(down.width, 'Down as wide').toBeCloseTo(across.width, 0);
      });
    }
  }

  test('the hints phase’s one column scrolls in its box at the grid’s height', async ({ page }) => {
    await page.setViewportSize({ width: 1100, height: 900 });
    await openBuilder(page, 'hints', 15);
    const g = await box(grid(page));
    const region = page.getByTestId('hints-region');
    const r = await box(region);
    expect(r.y, 'top').toBeCloseTo(g.y, 0);
    expect(r.height, 'height').toBeCloseTo(g.height, 0);
    expect(await region.evaluate((el) => getComputedStyle(el).overflowY)).toBe('auto');
    expect(await region.evaluate((el) => el.scrollHeight > el.clientHeight), 'content taller').toBe(true);
  });
});

// --- 15-S2-5: Preview's legend ---
test.describe('15-S2-5 Preview’s legend', () => {
  for (const width of [1440, 1100]) {
    test(`at ${width}px the legend sits under the grid, within its width, the skeleton 32px from the grid`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 });
      // A corner letter without its symmetric partner is an error, so the
      // legend shows.
      const { id } = await seedPuzzle({ grid: withLetter(createGrid({ cols: 5, rows: 5 }), { col: 0, row: 0 }, 'A'), hints: {}, phase: 'grid' });
      await page.goto(`/puzzles/${id}`);
      await waitForEditorReady(page);
      await page.getByTestId('preview-toggle').locator('input').click({ force: true });
      await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');

      await expect(page.getByTestId('preview-legend')).toBeVisible();
      const g = await box(grid(page));
      const legend = await box(page.getByTestId('preview-legend'));
      expect(legend.y, 'below the grid').toBeGreaterThanOrEqual(g.bottom - 0.5);
      expect(legend.x, 'from the grid’s left').toBeCloseTo(g.x, 0);
      expect(legend.right, 'within the grid’s width').toBeLessThanOrEqual(g.right + 0.5);
      expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
      const across = await box(column(page, 'grid', 'across'));
      expect(across.x - g.right, 'skeleton from the grid').toBeCloseTo(GAP_PX, 0);
    });
  }
});

// --- 15-S2-6: wide play ---
test.describe('15-S2-6 wide play', () => {
  for (const viewport of [{ width: 1440, height: 900 }, HUGE]) {
    test(`at ${viewport.width}px: the numbers 32px from a 560px grid, two equal columns 32px apart filling the room`, async ({ page }) => {
      await page.setViewportSize(viewport);
      await openPlay(page);
      const g = await box(grid(page));
      const playArea = await box(page.getByTestId('play-puzzle'));
      const across = await box(playColumn(page, 'across'));
      const down = await box(playColumn(page, 'down'));
      const number = await box(playColumn(page, 'across').getByTestId('play-clue-number').first());

      expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
      expect(number.x - g.right, 'the number from the grid').toBeCloseTo(GAP_PX, 0);
      expect(down.y, 'side by side').toBeCloseTo(across.y, 0);
      expect(down.x - across.right, 'between the columns').toBeCloseTo(GAP_PX, 0);
      expect(down.width, 'equal columns').toBeCloseTo(across.width, 0);
      expect(down.right, 'to the play area’s content edge').toBeCloseTo(playArea.right - PAGE_PADDING_PX, 0);
    });
  }

  test('the Prominent Hint stays above the grid at its width', async ({ page }) => {
    await page.setViewportSize(HUGE);
    await openPlay(page);
    const g = await box(grid(page));
    const prominent = await box(page.getByTestId('prominent-hint'));
    expect(prominent.bottom, 'above the grid').toBeLessThanOrEqual(g.y + 0.5);
    expect(prominent.x, 'left').toBeCloseTo(g.x, 0);
    expect(prominent.width, 'the grid’s width').toBeCloseTo(g.width, 0);
  });
});
