// Story 22-S6 — the lock button's word.
//
// In the build phase with Preview off, the lock button beside a word
// (21-S2, 21-S12):
//
// - Its tooltip (21-S4, timed by 22-S4's shared Tooltip) names the word:
//   "Lock " or "Unlock " followed by the word's letters, uppercase, each
//   cell's whole content in reading order (a rebus cell's letters all
//   count), no closing period. It was "Lock this word so you don't
//   accidentally change it" / "Enable changing this word". The button's
//   accessible name stays "Lock word" / "Unlock word".
// - It shows 2 seconds (was 3, 21-S16) after the cursor settles in an
//   unlocked word, or after the mouse comes to rest on one (21-S10): the
//   one wait, LOCK_BUTTON_DELAY_MS. A locked word's button still shows at
//   once.
// - The mouse on it outlines its word in 2px black around the word's
//   letters (not its end cells), the tick hover's outline (21-S15, 21-S17,
//   [data-testid="tick-hover-outline"]): at once, not waiting for the
//   tooltip; gone at once when the mouse leaves the button or the button
//   goes. Locked or not, and across a click that locks or unlocks it.
//   Where a tick hover already outlines that word, it is one outline, not
//   two. Mouse only: keyboard focus and a touch tap outline nothing.
//
// Timing is measured in the page (performance.now): an in-page log
// records each pointerdown's and pointerover's target and each moment the
// lock button appears or goes, so a slow runner can't make a correct wait
// look wrong. A timer fires late under load, never early: the wait is
// checked as 1950–2900ms (a 3-second wait fails it). "At once" for the
// outline is within 300ms, before the tooltip's 500ms.
//
// Do not edit this file to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });
// Several cases lock words through the button, each a 2-second wait.
test.describe.configure({ timeout: 60_000 });

/** The button's wait is 2 seconds; never sooner than this after it starts. */
const WAIT_MIN_MS = 1950;
/** ... and no later than this (a late timer's slack; under the old 3000ms). */
const WAIT_MAX_MS = 2900;
/** Waiting for a button that must come (2s wait, with room under load). */
const BUTTON_WITHIN_MS = 4000;
/** The outline's "at once". */
const AT_ONCE_MS = 300;
/** Longer than the tooltip's delay: long enough for a delayed outline. */
const PAST_TOOLTIP_MS = 700;

// ---------------------------------------------------------------------------
// Grids.

const run = (from: number, length: number) => Array.from({ length }, (_, i) => from + i);
const across = (row: number, cols: number[]) => cols.map((col) => `${col},${row}`);

// A daily (counterpart of (c,r) is (14−c, 14−r)):
//   TANGENT across row 3 (3–9), ends (2,3) and (10,3);
//   ROBIN across row 5 (3–7), ends (2,5) and (8,5);
//   PARTY across row 8 (3–5), its middle cell the rebus "ART".
// Every end cell named is Preview-black.
const TANGENT = across(3, run(3, 7));
const ROBIN = across(5, run(3, 5));
const PARTY = across(8, run(3, 3));
const EMPTY = '13,13';

function put(grid: Grid, cells: string[], contents: string[]): Grid {
  cells.forEach((coord, i) => {
    const [col, row] = coord.split(',').map(Number);
    grid = withLetter(grid, { col, row }, contents[i]);
  });
  return grid;
}

function wordsGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  grid = put(grid, TANGENT, [...'TANGENT']);
  grid = put(grid, ROBIN, [...'ROBIN']);
  grid = put(grid, PARTY, ['P', 'ART', 'Y']);
  return grid;
}

// 21-S11's tick grid, without TANGENT and OWL: CAT across row 7 (2–4) and
// DOG across row 7 (6–8) share the end cell (5,7).
const CAT = across(7, run(2, 3));
const DOG = across(7, run(6, 3));
const SHARED = '5,7';

function tickGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  grid = put(grid, CAT, [...'CAT']);
  grid = put(grid, DOG, [...'DOG']);
  return grid;
}

let titleCounter = 0;
async function open(page: Page, grid: Grid) {
  titleCounter += 1;
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, `22-S6 ${Date.now()}-${titleCounter}`);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

