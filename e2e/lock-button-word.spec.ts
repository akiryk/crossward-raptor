// Hooks and moves.

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const tooltip = (page: Page) => page.getByTestId('lock-tooltip');
const wordOutlines = (page: Page) => page.getByTestId('word-outline');
const ticks = (page: Page) => page.getByTestId('lock-tick');
const gridRegion = (page: Page) => page.getByTestId('grid-region');

type Box = { x: number; y: number; width: number; height: number };

async function boxOf(locator: Locator): Promise<Box> {
  const box = await locator.boundingBox();
  if (!box) throw new Error('no bounding box');
  return box;
}

function near(a: number, b: number, tolerance = 2) {
  return Math.abs(a - b) <= tolerance;
}

async function select(page: Page, coord: string) {
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
}

/** The mouse off the grid and the button. */
const mouseAway = (page: Page) => page.mouse.move(5, 5);

/** A point in a cell, as fractions of its box. */
async function pointIn(page: Page, coord: string, fx: number, fy: number) {
  const c = await boxOf(cell(page, coord));
  return { x: c.x + c.width * fx, y: c.y + c.height * fy };
}

async function mouseTo(page: Page, coord: string, fx: number, fy: number) {
  const p = await pointIn(page, coord, fx, fy);
  await page.mouse.move(p.x, p.y);
}

/** The tick's middle (21-S11): 11/12 across, 1/12 down its end cell, clear
 *  of an across word's button (from 1/6 down). */
const mouseOnTick = (page: Page, coord: string) => mouseTo(page, coord, 11 / 12, 1 / 12);

/** The one lock button sits just before this first letter (21-S12). */
async function expectButtonBeside(page: Page, first: string) {
  await expect(lockButton(page)).toHaveCount(1);
  const c = await boxOf(cell(page, first));
  const b = await boxOf(lockButton(page));
  expect(near(b.x + b.width, c.x), `button left of ${first}: right ${b.x + b.width}`).toBe(true);
  expect(near(b.y + b.height / 2, c.y + c.height / 2, 1), `centered on ${first}`).toBe(true);
}

/** Within the wait, the one lock button comes beside this first letter. */
async function expectButtonComesBeside(page: Page, first: string, timeout = BUTTON_WITHIN_MS) {
  await expect
    .poll(
      async () => {
        if ((await lockButton(page).count()) !== 1) return false;
        const b = await boxOf(lockButton(page));
        const c = await boxOf(cell(page, first));
        return near(b.x + b.width, c.x) && near(b.y + b.height / 2, c.y + c.height / 2, 1);
      },
      { timeout, message: `the button beside ${first}` }
    )
    .toBe(true);
}

/** The cursor in a word, its button shown (after the wait if unlocked). */
async function cursorIn(page: Page, coord: string) {
  await select(page, coord);
  await expect(lockButton(page)).toBeVisible({ timeout: BUTTON_WITHIN_MS });
}

/** Locks the cursor's word through its button; the mouse stays on it. */
async function lockThroughButton(page: Page, coord: string) {
  await cursorIn(page, coord);
  await expect(lockButton(page)).toHaveAccessibleName('Lock word');
  await lockButton(page).click();
  await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
}

/** The mouse onto the button's middle. */
async function mouseOnButton(page: Page) {
  const b = await boxOf(lockButton(page));
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
}

// ---------------------------------------------------------------------------
// The black outline: what's amiss, for a readable failure. Each
// [data-testid="tick-hover-outline"] must be a 2px solid black line whose
// outer edge is on the grid lines around its cells (1px outside the cells'
// boxes), and together they must surround exactly `cells`; `count`, when
// given, is how many outline elements there must be.

async function blackOutlineMismatches(page: Page, cells: string[], count?: number): Promise<string[]> {
  const found = await page.evaluate(() => {
    const cellRects = [...document.querySelectorAll<HTMLElement>('[data-testid="puzzle-grid"] [data-coord]')].map(
      (el) => ({ coord: el.dataset.coord!, r: el.getBoundingClientRect() })
    );
    return [...document.querySelectorAll<HTMLElement>('[data-testid="tick-hover-outline"]')].map((el) => {
      const cs = getComputedStyle(el);
      const o = el.getBoundingClientRect();
      const inside = cellRects.filter(({ r }) => {
        const x = r.x + r.width / 2;
        const y = r.y + r.height / 2;
        return x > o.left && x < o.right && y > o.top && y < o.bottom;
      });
      const isLine = ['top', 'right', 'bottom', 'left'].every(
        (side) =>
          cs.getPropertyValue(`border-${side}-color`) === 'rgb(0, 0, 0)' &&
          cs.getPropertyValue(`border-${side}-width`) === '2px' &&
          cs.getPropertyValue(`border-${side}-style`) === 'solid'
      );
      const fits =
        inside.length > 0 &&
        Math.abs(o.left - (Math.min(...inside.map((c) => c.r.left)) - 1)) <= 1.5 &&
        Math.abs(o.top - (Math.min(...inside.map((c) => c.r.top)) - 1)) <= 1.5 &&
        Math.abs(o.right - (Math.max(...inside.map((c) => c.r.right)) + 1)) <= 1.5 &&
        Math.abs(o.bottom - (Math.max(...inside.map((c) => c.r.bottom)) + 1)) <= 1.5;
      const visible = el.checkVisibility({ opacityProperty: true, visibilityProperty: true });
      return { coords: inside.map((c) => c.coord), isLine, fits, visible };
    });
  });
  const problems = found.flatMap(({ coords, isLine, fits, visible }) => [
    ...(visible ? [] : [`outline around ${coords.join(' ')}: not visible`]),
    ...(isLine ? [] : [`outline around ${coords.join(' ')}: not a 2px black line`]),
    ...(fits ? [] : [`outline around ${coords.join(' ') || 'no cell'}: not on the lines around its cells`]),
  ]);
  const got = [...new Set(found.flatMap(({ coords }) => coords))].sort();
  const want = [...new Set(cells)].sort();
  if (got.join(' ') !== want.join(' ')) problems.push(`outlined: ${got.join(' ') || 'none'} (want ${want.join(' ') || 'none'})`);
  if (count !== undefined && found.length !== count) problems.push(`${found.length} outline elements (want ${count})`);
  return problems;
}

/** Within `timeout`, exactly these cells outlined in black. */
async function expectBlackOutline(page: Page, cells: string[], { count, timeout = AT_ONCE_MS }: { count?: number; timeout?: number } = {}) {
  await expect
    .poll(() => blackOutlineMismatches(page, cells, count), {
      timeout,
      message: `black outline around: ${cells.join(' ') || 'none'}`,
    })
    .toEqual([]);
}

/** Checked once, now. */
async function expectBlackOutlineNow(page: Page, cells: string[], count?: number) {
  expect(await blackOutlineMismatches(page, cells, count)).toEqual([]);
}

// ---------------------------------------------------------------------------
// The in-page log: pointerdown and pointerover targets, and the lock
// button appearing (true) or going (false).

type Entry = { t: number; down?: string; over?: string; button?: boolean };

async function startLog(page: Page) {
  await page.evaluate(() => {
    type W = {
      __s6Log: { t: number; down?: string; over?: string; button?: boolean }[];
      __s6Stop?: () => void;
    };
    const w = window as unknown as W;
    w.__s6Stop?.();
    w.__s6Log = [];
    const label = (target: EventTarget | null) => {
      const el = target instanceof Element ? target : null;
      if (!el) return 'other';
      const button = el.closest('button[aria-label]');
      if (button) return `button:${button.getAttribute('aria-label')}`;
      const coord = el.closest<HTMLElement>('[data-coord]');
      return coord ? `cell:${coord.dataset.coord}` : 'other';
    };
    const hasButton = () =>
      [...document.querySelectorAll('[data-testid="puzzle-grid"] button[aria-label]')].some((b) =>
        /^(Lock|Unlock) word$/.test(b.getAttribute('aria-label') ?? '')
      );
    let last = hasButton();
    const onDown = (e: PointerEvent) => w.__s6Log.push({ t: performance.now(), down: label(e.target) });
    const onOver = (e: PointerEvent) => w.__s6Log.push({ t: performance.now(), over: label(e.target) });
    const check = () => {
      const now = hasButton();
      if (now !== last) {
        last = now;
        w.__s6Log.push({ t: performance.now(), button: now });
      }
    };
    document.addEventListener('pointerdown', onDown, true);
    document.addEventListener('pointerover', onOver, true);
    const observer = new MutationObserver(check);
    observer.observe(document.body, { childList: true, subtree: true });
    w.__s6Stop = () => {
      document.removeEventListener('pointerdown', onDown, true);
      document.removeEventListener('pointerover', onOver, true);
      observer.disconnect();
    };
  });
}

const readLog = (page: Page) => page.evaluate(() => (window as unknown as { __s6Log: Entry[] }).__s6Log);

function firstAt(log: Entry[], match: (e: Entry) => boolean, label: string, after = -Infinity) {
  const entry = log.find((e) => e.t >= after && match(e));
  expect(entry, label).toBeDefined();
  return entry!.t;
}

function expectTwoSeconds(ms: number, label: string) {
  expect(ms, `${label}: ${ms.toFixed(0)}ms, at least ${WAIT_MIN_MS}`).toBeGreaterThanOrEqual(WAIT_MIN_MS);
  expect(ms, `${label}: ${ms.toFixed(0)}ms, at most ${WAIT_MAX_MS}`).toBeLessThanOrEqual(WAIT_MAX_MS);
}

