import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { waitForNewPuzzleReady } from './helpers/wait-for-ready';

// Story 14-S9 — Modal entrance.
//
// Every dialog fades and grows slightly into place when it opens: the
// panel from opacity 0 and scale 0.97 to opacity 1 and scale 1, growing
// from its center, and the backdrop from opacity 0 to 1. Both run once,
// 150ms ease-out, starting together, and leave nothing behind when they
// end. Under reduced motion the panel only fades. Closing is instant.
//
// The suite runs with reducedMotion 'reduce' (playwright.config.ts), so
// this file opts back into full motion. The new-puzzle dialog stands in
// for every dialog, since they all render the same Modal.
//
// Measured at 1280×800. Do not edit this file to match an implementation.

test.use({ viewport: { width: 1280, height: 800 }, contextOptions: { reducedMotion: 'no-preference' } });

const PANEL = '[data-testid="new-puzzle-dialog"]';
const BACKDROP = '[data-testid="modal-backdrop"]';

// ease-out is cubic-bezier(0, 0, 0.58, 1): halfway through its time, the
// output is about 0.684 (linear 0.5, ease 0.802, ease-in 0.315).
const EASE_OUT_AT_HALF = 0.684;

type Frame = {
  opacity: number;
  x: number;
  y: number;
  width: number;
  height: number;
  centerX: number;
  centerY: number;
};

type Observed = {
  panelCount: number;
  backdropCount: number;
  panelDuration: number;
  backdropDuration: number;
  panelDelay: number;
  backdropDelay: number;
  panelStart: Frame;
  panelHalf: Frame;
  panelEnd: Frame;
  backdropStart: number;
  backdropHalf: number;
  backdropEnd: number;
};

/**
 * Arms a watcher that, the moment the dialog is inserted, pauses the
 * panel's and backdrop's animations at their start so they can be read
 * at chosen times, however slow the test is.
 */
async function armWatcher(page: Page) {
  await page.evaluate(
    ({ panelSelector, backdropSelector }) => {
      const w = window as unknown as { __s9?: { panel: Animation[]; backdrop: Animation[] } };
      w.__s9 = undefined;
      const observer = new MutationObserver(() => {
        const panel = document.querySelector(panelSelector);
        const backdrop = document.querySelector(backdropSelector);
        if (!panel || !backdrop) return;
        observer.disconnect();
        const panelAnimations = panel.getAnimations();
        const backdropAnimations = backdrop.getAnimations();
        for (const a of [...panelAnimations, ...backdropAnimations]) {
          a.pause();
          a.currentTime = 0;
        }
        w.__s9 = { panel: panelAnimations, backdrop: backdropAnimations };
      });
      observer.observe(document.body, { childList: true, subtree: true });
    },
    { panelSelector: PANEL, backdropSelector: BACKDROP }
  );
}

/** Reads the paused animations' timing and the panel/backdrop at 0, 75 and 150ms. */
async function observe(page: Page): Promise<Observed> {
  await page.waitForFunction(() => (window as unknown as { __s9?: unknown }).__s9 !== undefined);
  return page.evaluate(
    ({ panelSelector, backdropSelector }) => {
      const w = window as unknown as { __s9: { panel: Animation[]; backdrop: Animation[] } };
      const { panel: panelAnimations, backdrop: backdropAnimations } = w.__s9;
      const panel = document.querySelector(panelSelector)!;
      const backdrop = document.querySelector(backdropSelector)!;
      const all = [...panelAnimations, ...backdropAnimations];

      function frame(): Frame {
        const r = panel.getBoundingClientRect();
        return {
          opacity: Number(getComputedStyle(panel).opacity),
          x: r.left,
          y: r.top,
          width: r.width,
          height: r.height,
          centerX: r.left + r.width / 2,
          centerY: r.top + r.height / 2,
        };
      }
      function at(ms: number) {
        for (const a of all) a.currentTime = ms;
        return { panel: frame(), backdrop: Number(getComputedStyle(backdrop).opacity) };
      }
      function timing(list: Animation[]) {
        const t = list[0]?.effect?.getComputedTiming();
        return { duration: Number(t?.duration ?? NaN), delay: Number(t?.delay ?? NaN) };
      }

      const start = at(0);
      const half = at(75);
      // Just short of the end, while the animations still apply.
      const end = at(149.999);
      const panelTiming = timing(panelAnimations);
      const backdropTiming = timing(backdropAnimations);
      for (const a of all) a.play();

      return {
        panelCount: panelAnimations.length,
        backdropCount: backdropAnimations.length,
        panelDuration: panelTiming.duration,
        backdropDuration: backdropTiming.duration,
        panelDelay: panelTiming.delay,
        backdropDelay: backdropTiming.delay,
        panelStart: start.panel,
        panelHalf: half.panel,
        panelEnd: end.panel,
        backdropStart: start.backdrop,
        backdropHalf: half.backdrop,
        backdropEnd: end.backdrop,
      };
    },
    { panelSelector: PANEL, backdropSelector: BACKDROP }
  );
}

async function gotoLibrary(page: Page) {
  await page.goto('/puzzles');
  await waitForNewPuzzleReady(page);
}

/** Opens the dialog with the watcher armed, and reads its entrance. */
async function openAndObserve(page: Page) {
  await armWatcher(page);
  await page.getByTestId('new-puzzle-button').click();
  return observe(page);
}

/** The panel's resting state, once nothing animates on it or the backdrop. */
async function rested(page: Page) {
  const panel = page.locator(PANEL);
  const backdrop = page.locator(BACKDROP);
  await expect.poll(() => panel.evaluate((el) => el.getAnimations().length)).toBe(0);
  await expect.poll(() => backdrop.evaluate((el) => el.getAnimations().length)).toBe(0);
  return panel.evaluate((el) => {
    const c = getComputedStyle(el);
    const r = el.getBoundingClientRect();
    return {
      transform: c.transform,
      scale: c.scale,
      opacity: c.opacity,
      x: r.left,
      y: r.top,
      width: r.width,
      height: r.height,
    };
  });
}

function near(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

async function cancel(page: Page) {
  await page.getByTestId('new-puzzle-cancel').click();
  await expect(page.getByTestId('modal')).toHaveCount(0);
}

test.describe('14-S9-1 full motion', () => {
  test('the panel fades and grows from 0.97 at its center, and the backdrop fades, both once over 150ms ease-out', async ({ page }) => {
    await gotoLibrary(page);
    const o = await openAndObserve(page);

    expect(o.panelCount, 'animations on the panel').toBe(1);
    expect(o.backdropCount, 'animations on the backdrop').toBe(1);
    expect(o.panelDuration, 'panel duration').toBe(150);
    expect(o.backdropDuration, 'backdrop duration').toBe(150);
    expect(o.panelDelay, 'panel delay').toBe(0);
    expect(o.backdropDelay, 'backdrop delay').toBe(0);

    // Opacity 0 to 1, ease-out.
    near(o.panelStart.opacity, 0, 0.001, 'panel opacity at 0ms');
    near(o.panelHalf.opacity, EASE_OUT_AT_HALF, 0.02, 'panel opacity at 75ms');
    near(o.panelEnd.opacity, 1, 0.001, 'panel opacity at 150ms');
    near(o.backdropStart, 0, 0.001, 'backdrop opacity at 0ms');
    near(o.backdropHalf, EASE_OUT_AT_HALF, 0.02, 'backdrop opacity at 75ms');
    near(o.backdropEnd, 1, 0.001, 'backdrop opacity at 150ms');

    // Scale 0.97 to 1, on the same curve, about the panel's center.
    const full = o.panelEnd;
    near(o.panelStart.width, full.width * 0.97, 0.5, 'panel width at 0ms');
    near(o.panelStart.height, full.height * 0.97, 0.5, 'panel height at 0ms');
    const halfScale = 0.97 + 0.03 * EASE_OUT_AT_HALF;
    near(o.panelHalf.width, full.width * halfScale, 0.5, 'panel width at 75ms');
    near(o.panelStart.centerX, full.centerX, 0.5, 'panel center x at 0ms');
    near(o.panelStart.centerY, full.centerY, 0.5, 'panel center y at 0ms');
  });
});

test.describe('14-S9-2 it leaves nothing behind', () => {
  test('once finished, the panel has no animation, transform or partial opacity, and sits where it does under reduced motion', async ({ page }) => {
    await gotoLibrary(page);
    await page.getByTestId('new-puzzle-button').click();
    const full = await rested(page);

    expect(full.transform, 'panel transform').toBe('none');
    expect(full.scale, 'panel scale').toBe('none');
    expect(full.opacity, 'panel opacity').toBe('1');

    await cancel(page);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.getByTestId('new-puzzle-button').click();
    const reduced = await rested(page);

    near(full.x, reduced.x, 1, 'panel x');
    near(full.y, reduced.y, 1, 'panel y');
    near(full.width, reduced.width, 1, 'panel width');
    near(full.height, reduced.height, 1, 'panel height');
  });
});

test.describe('14-S9-3 reduced motion', () => {
  test('the panel only fades, already at its full size, and the backdrop still fades', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await gotoLibrary(page);
    const o = await openAndObserve(page);

    expect(o.panelCount, 'animations on the panel').toBe(1);
    expect(o.backdropCount, 'animations on the backdrop').toBe(1);
    expect(o.panelDuration, 'panel duration').toBe(150);
    expect(o.backdropDuration, 'backdrop duration').toBe(150);

    near(o.panelStart.opacity, 0, 0.001, 'panel opacity at 0ms');
    near(o.panelHalf.opacity, EASE_OUT_AT_HALF, 0.02, 'panel opacity at 75ms');
    near(o.backdropStart, 0, 0.001, 'backdrop opacity at 0ms');
    near(o.backdropHalf, EASE_OUT_AT_HALF, 0.02, 'backdrop opacity at 75ms');

    // No scale at any point.
    for (const [label, f] of [['0ms', o.panelStart], ['75ms', o.panelHalf]] as const) {
      near(f.x, o.panelEnd.x, 0.5, `panel x at ${label}`);
      near(f.y, o.panelEnd.y, 0.5, `panel y at ${label}`);
      near(f.width, o.panelEnd.width, 0.5, `panel width at ${label}`);
      near(f.height, o.panelEnd.height, 0.5, `panel height at ${label}`);
    }
  });
});

test.describe('14-S9-4 reopen', () => {
  test('opening the dialog again after Cancel runs the entrance again', async ({ page }) => {
    await gotoLibrary(page);
    const first = await openAndObserve(page);
    expect(first.panelCount, 'first open: animations on the panel').toBe(1);
    await rested(page);
    await cancel(page);

    const second = await openAndObserve(page);
    expect(second.panelCount, 'reopen: animations on the panel').toBe(1);
    expect(second.backdropCount, 'reopen: animations on the backdrop').toBe(1);
    near(second.panelStart.opacity, 0, 0.001, 'reopen: panel opacity at 0ms');
    near(second.panelStart.width, second.panelEnd.width * 0.97, 0.5, 'reopen: panel width at 0ms');
  });
});

test.describe('14-S9-5 instant close', () => {
  test('Cancel removes the dialog by the next animation frame, and focus returns to Create A Puzzle', async ({ page }) => {
    await gotoLibrary(page);
    await page.getByTestId('new-puzzle-button').click();
    await rested(page);

    const remaining = await page.evaluate(async () => {
      (document.querySelector('[data-testid="new-puzzle-cancel"]') as HTMLElement).click();
      await new Promise((resolve) => requestAnimationFrame(() => resolve(null)));
      return document.querySelectorAll('[data-testid="modal"]').length;
    });
    expect(remaining, 'dialogs left one frame after Cancel').toBe(0);
    await expect(page.getByTestId('new-puzzle-button')).toBeFocused();
  });
});
