// Story 15-S6 — Small screens.
//
// The grid is 700px down to a 748px window (700 plus the page's 24px
// padding on each side; 17-S7, was 560px and 608px). Below 748px the
// page's padding on each side is 8px (17-S7's correction), so the grid is
// still 700px down to a 716px window; narrower, it is the window less
// 16px, square and 8px from the left, in the builder and in play, with the
// Hint Box and the play hint bar at its width. Except on a Sunday (21×21),
// letters keep 14-S5's ratio to the cell (16px in a 35px pitch). Numbers
// are cell-number's 10px in any cell at least a 21×21's at 560px
// ((560 - 1) / 21 pitch); in a smaller cell they shrink in proportion to
// the pitch, but never below 8px. A Sunday's letters and numbers are
// 17-S7's (larger-grid.spec.ts).
//
// The editor's title wraps onto as many lines as it needs, at every
// width, the buttons keeping their distance below it. Nothing in the Hint
// Box is ever cut off: a long hint wraps and the box grows; the word sits
// beside the hint while the hint keeps at least 120px, and otherwise gets
// its own row above it; the arrows stay level with the first row. The
// wide Hint Inputs wrap a long hint too, the answer 4px below. Enter adds
// no line break to the title or a hint. When the narrow builder's buttons
// and toggle wrap, their rows are 10px apart.
//
// At 375×667 nothing runs past the window's right edge, and no dialog is
// taller than the window.
//
// Do not edit this file to match an implementation.

const GRID_MAX_PX = 700;
const NARROW_PADDING_PX = 8;
const LETTER_PX = 16;
const LETTER_PITCH_PX = 35;
const NUMBER_PX = 10;
const NUMBER_MIN_PX = 8;
const FULL_NUMBER_PITCH_PX = (560 - 1) / 21;
const HINT_INPUT_MIN_PX = 120;
const HINT_BOX_INPUT_PX = 30;
const BOX_PX = 48;
const ANSWER_GAP_PX = 4;
const NARROW_GAP_PX = 16;
const WIDE_GAP_PX = 32;
const TITLE_3_LINE_PX = 24;
const TITLE_1_LINE_PX = 54;
const WRAP_GAP_PX = 10;
const PHONE = { width: 375, height: 667 };

const LONG_TITLE = 'An extraordinarily long puzzle title that keeps going well past the edge';
const VERY_LONG_TITLE = `${LONG_TITLE}, and then keeps on going even further, well past any window`;
const LONG_HINT =
  'A small domesticated carnivorous mammal with soft fur, a short snout and retractable claws, kept as a pet or for catching mice, often seen ignoring its owners';

/** Every cell lettered, so every word survives into the hints phase. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'W');
  }
  return grid;
}

/** The number expected in a grid `width` wide with `size` cells a side. */
function numberPx(width: number, size: number) {
  const pitch = (width - 1) / size;
  return Math.max(NUMBER_MIN_PX, Math.min(NUMBER_PX, (NUMBER_PX * pitch) / FULL_NUMBER_PITCH_PX));
}

function letterPx(width: number, size: number) {
  return ((width - 1) / size) * (LETTER_PX / LETTER_PITCH_PX);
}

async function openBuilder(
  page: Page,
  viewport: { width: number; height: number },
  options: { size?: number; phase?: 'grid' | 'hints'; title?: string; hints?: Record<string, string> } = {}
) {
  await page.setViewportSize(viewport);
  const { id } = await seedPuzzle(
    { grid: filled(options.size ?? 5), hints: options.hints ?? {}, phase: options.phase ?? 'grid' },
    options.title ?? 'Small screens'
  );
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

async function openPlay(page: Page, viewport: { width: number; height: number }, size = 5) {
  await page.setViewportSize(viewport);
  const builderId = await currentBuilderId(page);
  const fixture = await seedPlayPuzzle({
    builderId,
    puzzle: { grid: filled(size), phase: 'hints', hints: { '1-across': 'A hint' } },
  });
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
  return fixture;
}

async function rect(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

function css(locator: Locator, property: string) {
  return locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);
}

async function fontPx(locator: Locator) {
  return parseFloat(await css(locator, 'font-size'));
}

/** Nothing of an element's text is scrolled out of sight. */
function showsWhole(locator: Locator) {
  return locator.evaluate((el) => el.scrollWidth <= el.clientWidth + 1 && el.scrollHeight <= el.clientHeight + 1);
}

function noHorizontalOverflow(page: Page) {
  return page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth);
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const number = (page: Page, coord = '0,0') => cell(page, coord).getByTestId('cell-number');
/** The element holding a cell's letter: the number's parent. */
const letterIn = (page: Page, coord: string) => number(page, coord).locator('..');
const hintBox = (page: Page) => page.getByTestId('hint-box');
const dialog = (page: Page) => page.getByRole('dialog');

// --- 15-S6-1: the grid shrinks last ---
test.describe('15-S6-1 the grid shrinks last', () => {
  test('at 748px the builder’s and play’s grids are still 700px', async ({ page }) => {
    await openBuilder(page, { width: 748, height: 900 });
    expect((await rect(grid(page))).width, 'builder').toBeCloseTo(GRID_MAX_PX, 0);
    await openPlay(page, { width: 748, height: 900 });
    expect((await rect(grid(page))).width, 'play').toBeCloseTo(GRID_MAX_PX, 0);
  });

  test('at 716px the builder’s and play’s grids are still 700px, 8px in', async ({ page }) => {
    await openBuilder(page, { width: 716, height: 900 });
    let g = await rect(grid(page));
    expect(g.width, 'builder').toBeCloseTo(GRID_MAX_PX, 0);
    expect(g.x, 'builder left').toBeCloseTo(NARROW_PADDING_PX, 0);
    await openPlay(page, { width: 716, height: 900 });
    g = await rect(grid(page));
    expect(g.width, 'play').toBeCloseTo(GRID_MAX_PX, 0);
    expect(g.x, 'play left').toBeCloseTo(NARROW_PADDING_PX, 0);
  });

  for (const width of [715, 414, 375]) {
    test(`at ${width}px the builder’s grid is the window less 16px, square, 8px in, the Hint Box at its width`, async ({ page }) => {
      await openBuilder(page, { width, height: 900 }, { phase: 'hints' });
      const g = await rect(grid(page));
      expect(g.width, 'width').toBeCloseTo(width - 2 * NARROW_PADDING_PX, 0);
      expect(g.height, 'square').toBeCloseTo(g.width, 0);
      expect(g.x, 'left').toBeCloseTo(NARROW_PADDING_PX, 0);
      await cell(page, '0,0').click();
      const b = await rect(hintBox(page));
      expect(b.x, 'box left').toBeCloseTo(g.x, 0);
      expect(b.width, 'box width').toBeCloseTo(g.width, 0);
    });

    test(`at ${width}px play’s grid is the window less 16px, square, 8px in, the hint bar at its width`, async ({ page }) => {
      await openPlay(page, { width, height: 900 });
      const g = await rect(grid(page));
      expect(g.width, 'width').toBeCloseTo(width - 2 * NARROW_PADDING_PX, 0);
      expect(g.height, 'square').toBeCloseTo(g.width, 0);
      expect(g.x, 'left').toBeCloseTo(NARROW_PADDING_PX, 0);
      const bar = await rect(page.getByTestId('play-hint-bar'));
      expect(bar.x, 'bar left').toBeCloseTo(g.x, 0);
      expect(bar.width, 'bar width').toBeCloseTo(g.width, 0);
    });
  }
});

// --- 15-S6-2: letters scale with the cell ---
// 17-S7's correction: except on a Sunday (larger-grid.spec.ts, 17-S7-5).
test.describe('15-S6-2 letters scale with the cell', () => {
  test('at 375px a 15×15 builder grid’s letters keep 16px in a 35px pitch', async ({ page }) => {
    await openBuilder(page, PHONE, { size: 15 });
    const g = await rect(grid(page));
    const px = await fontPx(letterIn(page, '0,0'));
    expect(Math.abs(px - letterPx(g.width, 15)), `letter ${px}px`).toBeLessThanOrEqual(0.3);
  });

  test('at 375px a 15×15 play grid’s guesses keep 16px in a 35px pitch', async ({ page }) => {
    await openPlay(page, PHONE, 15);
    await cell(page, '0,0').click();
    await page.keyboard.type('Q');
    await expect(cell(page, '0,0')).toContainText('Q');
    const g = await rect(grid(page));
    const px = await fontPx(letterIn(page, '0,0'));
    expect(Math.abs(px - letterPx(g.width, 15)), `letter ${px}px`).toBeLessThanOrEqual(0.3);
  });
});

// --- 15-S6-3: numbers keep a readable minimum ---
// 17-S7's correction: except on a Sunday, whose numbers have no minimum
// (larger-grid.spec.ts, 17-S7-5); its 21×21 cases became a 15×15 at 320px.
test.describe('15-S6-3 numbers keep a readable minimum', () => {
  const cases: [string, { width: number; height: number }, number][] = [
    ['a 15×15 at 414px: in proportion to the cell', { width: 414, height: 900 }, 15],
    ['a 15×15 at 375px: in proportion to the cell', PHONE, 15],
    ['a 15×15 at 320px: the 8px minimum', { width: 320, height: 667 }, 15],
    ['a 5×5 at 375px: still 10px', PHONE, 5],
  ];
  for (const [name, viewport, size] of cases) {
    test(`builder, ${name}`, async ({ page }) => {
      await openBuilder(page, viewport, { size });
      const g = await rect(grid(page));
      const expected = numberPx(g.width, size);
      const px = await fontPx(number(page));
      expect(Math.abs(px - expected), `number ${px}px, expected ${expected.toFixed(2)}px`).toBeLessThanOrEqual(0.3);
    });
  }

  test('play, a 15×15 at 375px: in proportion to the cell', async ({ page }) => {
    await openPlay(page, PHONE, 15);
    const g = await rect(grid(page));
    const expected = numberPx(g.width, 15);
    const px = await fontPx(number(page));
    expect(Math.abs(px - expected), `number ${px}px, expected ${expected.toFixed(2)}px`).toBeLessThanOrEqual(0.3);
  });
});

// --- 15-S6-4: the editor's title wraps ---
test.describe('15-S6-4 the editor’s title wraps', () => {
  test('at 375px a long title wraps onto more lines, whole, in its column, the buttons 16px below', async ({ page }) => {
    await openBuilder(page, PHONE, { title: LONG_TITLE });
    const title = page.getByTestId('puzzle-title');
    const t = await rect(title);
    const g = await rect(grid(page));
    expect(t.x, 'left with the grid').toBeCloseTo(g.x, 0);
    expect(t.right, 'within the grid’s width').toBeLessThanOrEqual(g.right + 0.5);
    expect(t.height, 'more than one title-3 line').toBeGreaterThan(1.5 * TITLE_3_LINE_PX);
    expect(await showsWhole(title), 'the whole title visible').toBe(true);
    await expect(title, 'the whole title kept').toHaveValue(LONG_TITLE);
    const steps = await rect(page.getByTestId('builder-steps'));
    expect(steps.y - t.bottom, 'title to buttons').toBeCloseTo(NARROW_GAP_PX, 0);
  });

  test('at 375px a short title is still one line', async ({ page }) => {
    await openBuilder(page, PHONE, { title: 'Small screens' });
    const t = await rect(page.getByTestId('puzzle-title'));
    expect(t.height, 'one title-3 line').toBeLessThan(1.5 * TITLE_3_LINE_PX);
  });

  test('at 1440px a very long title wraps too, whole, the buttons 32px below', async ({ page }) => {
    await openBuilder(page, { width: 1440, height: 900 }, { title: VERY_LONG_TITLE });
    const title = page.getByTestId('puzzle-title');
    const t = await rect(title);
    expect(t.height, 'more than one title-1 line').toBeGreaterThan(1.5 * TITLE_1_LINE_PX);
    expect(await showsWhole(title), 'the whole title visible').toBe(true);
    const steps = await rect(page.getByTestId('builder-steps'));
    expect(steps.y - t.bottom, 'title to buttons').toBeCloseTo(WIDE_GAP_PX, 0);
  });

  test('Enter adds no line break to the title', async ({ page }) => {
    await openBuilder(page, PHONE, { title: 'Small screens' });
    const title = page.getByTestId('puzzle-title');
    await title.click();
    await page.keyboard.press('End');
    await page.keyboard.press('Enter');
    await page.keyboard.type('X');
    await expect(title).toHaveValue('Small screensX');
  });
});

// --- 15-S6-5: the Hint Box shows everything ---
test.describe('15-S6-5 the Hint Box shows everything', () => {
  for (const width of [414, 375]) {
    test(`at ${width}px a 21-letter word gets its own row, whole, the input under it, the arrows level with the word`, async ({ page }) => {
      await openBuilder(page, { width, height: 900 }, { size: 21, phase: 'hints' });
      const box = await rect(hintBox(page));
      const word = page.getByTestId('hint-box-word');
      const w = await rect(word);
      const input = await rect(page.getByTestId('hint-box-input'));
      expect(await noHorizontalOverflow(page), 'no horizontal overflow').toBe(true);
      expect(box.right, 'box within the window').toBeLessThanOrEqual(width);
      await expect(word).toHaveText('W'.repeat(21));
      expect(await showsWhole(word), 'the whole word visible').toBe(true);
      expect(input.y, 'the input under the word').toBeGreaterThanOrEqual(w.bottom - 0.5);
      expect(input.x, 'the input starts with the word').toBeCloseTo(w.x, 0);
      expect(input.right, 'the input inside the box').toBeLessThanOrEqual(box.right);
      for (const name of ['Previous word', 'Next word']) {
        const arrow = await rect(hintBox(page).getByRole('button', { name }));
        expect(arrow.x, `${name} inside the box`).toBeGreaterThanOrEqual(box.x);
        expect(arrow.right, `${name} inside the box`).toBeLessThanOrEqual(box.right);
        const centre = arrow.y + arrow.height / 2;
        expect(centre, `${name} level with the word`).toBeGreaterThanOrEqual(w.y - 0.5);
        expect(centre, `${name} level with the word`).toBeLessThanOrEqual(w.bottom + 0.5);
      }
      expect(box.height, 'the box grows').toBeGreaterThan(BOX_PX);
    });
  }

  test('at 768px a 21-letter word fits beside the input: one row, 48px', async ({ page }) => {
    await openBuilder(page, { width: 768, height: 900 }, { size: 21, phase: 'hints' });
    const word = page.getByTestId('hint-box-word');
    await expect(word).toHaveText('W'.repeat(21));
    expect(await showsWhole(word), 'the whole word visible').toBe(true);
    const w = await rect(word);
    const input = await rect(page.getByTestId('hint-box-input'));
    expect(w.right, 'the word before the input').toBeLessThanOrEqual(input.x);
    expect(input.width, 'the input at least 120px').toBeGreaterThanOrEqual(HINT_INPUT_MIN_PX - 0.5);
    expect((await rect(hintBox(page))).height, 'still 48px').toBeCloseTo(BOX_PX, 0);
  });

  test('at 768px a long hint wraps, whole, the box growing, the word and arrows level with its first line', async ({ page }) => {
    await openBuilder(page, { width: 768, height: 900 }, { phase: 'hints', hints: { '1-across': LONG_HINT } });
    const box = await rect(hintBox(page));
    const field = page.getByTestId('hint-box-input');
    const input = await rect(field);
    const w = await rect(page.getByTestId('hint-box-word'));
    await expect(field).toHaveValue(LONG_HINT);
    expect(await showsWhole(field), 'the whole hint visible').toBe(true);
    expect(box.height, 'the box grows').toBeGreaterThan(BOX_PX + 20);
    expect(w.right, 'the word beside the hint').toBeLessThanOrEqual(input.x);
    const firstLine = { top: input.y, bottom: input.y + HINT_BOX_INPUT_PX };
    const wordCentre = w.y + w.height / 2;
    expect(wordCentre, 'the word level with the first line').toBeGreaterThanOrEqual(firstLine.top);
    expect(wordCentre, 'the word level with the first line').toBeLessThanOrEqual(firstLine.bottom);
    for (const name of ['Previous word', 'Next word']) {
      const arrow = await rect(hintBox(page).getByRole('button', { name }));
      const centre = arrow.y + arrow.height / 2;
      expect(centre, `${name} level with the first line`).toBeGreaterThanOrEqual(firstLine.top);
      expect(centre, `${name} level with the first line`).toBeLessThanOrEqual(firstLine.bottom);
      expect(arrow.right, `${name} inside the box`).toBeLessThanOrEqual(box.right);
    }
  });

  test('Enter adds no line break to a hint in the box', async ({ page }) => {
    await openBuilder(page, { width: 768, height: 900 }, { phase: 'hints' });
    const field = page.getByTestId('hint-box-input');
    await field.click();
    await page.keyboard.type('Felines');
    await page.keyboard.press('Enter');
    await page.keyboard.type('X');
    await expect(field).toHaveValue('FelinesX');
  });
});

// --- 15-S6-6: wrapped controls ---
test.describe('15-S6-6 wrapped controls', () => {
  for (const phase of ['grid', 'hints'] as const) {
    test(`${phase} phase at 375px: the toggle’s row 10px under the buttons`, async ({ page }) => {
      await openBuilder(page, PHONE, { phase });
      const toggleId = phase === 'grid' ? 'preview-toggle' : 'lock-letters-toggle';
      const buttons = page.getByTestId('builder-steps').getByRole('button');
      let buttonsBottom = 0;
      for (const b of await buttons.all()) buttonsBottom = Math.max(buttonsBottom, (await rect(b)).bottom);
      const toggleRow = page.getByTestId(toggleId).locator('..');
      const t = await rect(toggleRow);
      expect(t.y, 'the toggle wraps to its own row').toBeGreaterThan(buttonsBottom - 1);
      expect(t.y - buttonsBottom, '10px between the rows').toBeCloseTo(WRAP_GAP_PX, 0);
    });
  }
});

// --- 15-S6-7: nothing clips at 375×667 ---
test.describe('15-S6-7 nothing clips at 375×667', () => {
  test('the library', async ({ page }) => {
    await page.setViewportSize(PHONE);
    await seedPuzzle({ grid: filled(5), hints: {}, phase: 'grid' }, LONG_TITLE);
    await page.goto('/puzzles');
    await expect(page.getByTestId('puzzle-library')).toBeVisible();
    expect(await noHorizontalOverflow(page)).toBe(true);
  });

  for (const phase of ['grid', 'hints'] as const) {
    test(`the builder, a 21×21 in the ${phase} phase with a long title`, async ({ page }) => {
      await openBuilder(page, PHONE, { size: 21, phase, title: LONG_TITLE });
      await cell(page, '0,0').click();
      expect(await noHorizontalOverflow(page)).toBe(true);
    });
  }

  test('play, a 21×21', async ({ page }) => {
    await openPlay(page, PHONE, 21);
    await cell(page, '0,0').click();
    expect(await noHorizontalOverflow(page)).toBe(true);
  });

  async function fitsTheWindow(page: Page) {
    const d = await rect(dialog(page));
    expect(d.y, 'top inside the window').toBeGreaterThanOrEqual(0);
    expect(d.bottom, 'bottom inside the window').toBeLessThanOrEqual(PHONE.height);
    expect(d.x, 'left inside the window').toBeGreaterThanOrEqual(0);
    expect(d.right, 'right inside the window').toBeLessThanOrEqual(PHONE.width);
    const clipped = await dialog(page).evaluate((el) => el.scrollHeight > el.clientHeight + 0.5);
    expect(clipped, 'nothing cut off').toBe(false);
  }

  test('the New puzzle dialog fits', async ({ page }) => {
    await page.setViewportSize(PHONE);
    await page.goto('/puzzles');
    await page.getByTestId('new-puzzle-button').click();
    await expect(dialog(page)).toBeVisible();
    await fitsTheWindow(page);
  });

  test('the Publish dialog fits, with every finding it can show', async ({ page }) => {
    // Every hint written (Publish needs them), but unfilled cells, a
    // two-letter word and broken symmetry.
    let g = createGrid({ cols: 15, rows: 15, black: [{ col: 2, row: 0 }] });
    g = withLetter(g, { col: 0, row: 0 }, 'A');
    const { across, down } = requiredHints(g);
    const hints = Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), 'A hint']));
    await page.setViewportSize(PHONE);
    const { id } = await seedPuzzle({ grid: g, hints, phase: 'hints' }, LONG_TITLE);
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await page.locator('[data-step-id="publish"]').click();
    await expect(page.getByTestId('publish-dialog')).toBeVisible();
    await expect(page.locator('[data-finding-kind]')).toHaveCount(3);
    await fitsTheWindow(page);
  });

  test('the Create Hints dialog fits', async ({ page }) => {
    await page.setViewportSize(PHONE);
    const { id } = await seedPuzzle({ grid: createGrid({ cols: 15, rows: 15 }), hints: {}, phase: 'grid' }, LONG_TITLE);
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await page.locator('[data-step-id="hints"]').click();
    await expect(dialog(page)).toBeVisible();
    await fitsTheWindow(page);
  });
});

