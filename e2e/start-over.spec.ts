// Story 20-S1 — Start Over.
//
// In the build phase the toggle row ends with Start Over (`start-over`, a
// button named "Start Over"), styled as a link: the toggle label's size,
// `subtle`, no fill or border, a pointer; `primary` on hover and keyboard
// focus. It is the row's right end, 16px in (12px below a 748px window),
// centered on the row, with Rebus 20px before it. It is always enabled.
// The hints phase and a published puzzle have none.
//
// It opens a dialog (`start-over-dialog`): title "Clear Puzzle", body
// "Are you sure? This will remove every letter from the grid.", then
// "Clear Puzzle" (`start-over-confirm`) and "Cancel" (`start-over-cancel`).
// Cancel or Escape changes nothing; after a click on Start Over, focus is
// back on the grid. Confirming makes every cell white and empty, keeping
// the size and the title, and saves it. The cursor is on the first cell,
// Across, with the grid focused. An open rebus entry is closed first.
// Preview stays as it was.
//
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 1000 };
const PHONE = { width: 375, height: 900 };
const BODY = 'Are you sure? This will remove every letter from the grid.';

type Rgb = { r: number; g: number; b: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

const css = (locator: Locator, property: string) =>
  locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

const startOver = (page: Page) => page.getByTestId('start-over');
const dialog = (page: Page) => page.getByTestId('start-over-dialog');
const confirm = (page: Page) => page.getByTestId('start-over-confirm');
const cancel = (page: Page) => page.getByTestId('start-over-cancel');
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const editorGrid = (page: Page) => page.getByTestId('grid-region');

function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((line, row) => {
    [...line].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/** Letters across a 5×5, some without their symmetric partners. */
const lettered = () => gridOf(['CAT..', 'A....', 'T..E.', '.....', '....S']);

function hintsFor(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  return Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
}

let titleCounter = 0;
async function seedBuilder(grid: Grid, phase: Phase = 'grid', options: { published?: boolean } = {}) {
  titleCounter += 1;
  const title = `20-S1 ${phase} ${Date.now()}-${titleCounter}`;
  const { id } = await seedPuzzle({ grid, hints: phase === 'hints' ? hintsFor(grid) : {}, phase }, title);
  if (options.published) {
    const client = ownershipTestClient();
    try {
      await client.puzzle.update({
        where: { id },
        data: { publishedAt: new Date('2026-10-01T00:00:00Z'), visibility: 'public' },
      });
    } finally {
      await client.$disconnect();
    }
  }
  return { id, title };
}

async function openBuilder(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

/** A cell's letters, without its number. */
function cellText(page: Page, coord: string) {
  return cell(page, coord).evaluate((element) => {
    const clone = element.cloneNode(true) as HTMLElement;
    clone.querySelectorAll('[data-testid="cell-number"]').forEach((number) => number.remove());
    clone.querySelectorAll('[data-testid="rebus-entry"]').forEach((open) => open.remove());
    return clone.textContent?.trim() ?? '';
  });
}

/** Every rendered cell's kind and letters, row by row. */
function renderedCells(page: Page) {
  return page.getByTestId('grid-cell').evaluateAll((cells) =>
    cells.map((element) => {
      const clone = element.cloneNode(true) as HTMLElement;
      clone.querySelectorAll('[data-testid="cell-number"]').forEach((number) => number.remove());
      return `${element.getAttribute('data-kind')}:${clone.textContent?.trim() ?? ''}`;
    }),
  );
}

async function expectBlankOnScreen(page: Page, size: number) {
  await expect.poll(() => renderedCells(page), 'every cell white and empty').toEqual(Array(size * size).fill('active:'));
}

/** The saved builder grid, as `kind:letter` per cell. */
async function savedCells(id: string) {
  const stored = (await readPlayPuzzle(id)).grid as unknown as SerializedGrid;
  return stored.cells.flat().map((saved) => (saved.kind === 'active' ? `active:${saved.letter ?? ''}` : 'black'));
}

async function expectBlankSaved(id: string, size: number) {
  await expect.poll(() => savedCells(id), 'saved blank').toEqual(Array(size * size).fill('active:'));
}

async function expectAcrossAtOrigin(page: Page) {
  await expect(page.locator('[data-selected="true"]')).toHaveCount(1);
  await expect(cell(page, '0,0')).toHaveAttribute('data-highlight', 'selected');
  await expect(cell(page, '1,0')).toHaveAttribute('data-highlight', 'slot');
  await expect(cell(page, '0,1')).not.toHaveAttribute('data-highlight', 'slot');
}

async function openDialog(page: Page) {
  await startOver(page).click();
  await expect(dialog(page)).toBeVisible();
}

test.describe('20-S1 Start Over', () => {
  test.beforeEach(async ({ page }) => {
    await page.setViewportSize(WIDE);
  });

  test('20-S1-1 the link: its look, the toggle row\'s right end, Rebus 20px before it', async ({ page }) => {
    const { id } = await seedBuilder(lettered());
    await openBuilder(page, id);
    const row = page.getByTestId('toggle-row');
    const link = startOver(page);
    await expect(link).toHaveCount(1);
    await expect(row.getByTestId('start-over')).toHaveCount(1);
    await expect(link).toHaveText('Start Over');
    await expect(link).toHaveRole('button');
    await expect(link).toBeEnabled();

    const label = page.getByTestId('preview-toggle').locator('[data-toggle-label]');
    expect(await css(link, 'font-size'), 'the toggle label\'s size').toBe(await css(label, 'font-size'));
    expect(parseColor(await css(link, 'color')), 'subtle').toEqual(await token(page, 'subtle'));
    expect(await css(link, 'background-color'), 'no fill').toBe('rgba(0, 0, 0, 0)');
    expect(await css(link, 'border-top-width'), 'no border').toBe('0px');
    expect(await css(link, 'cursor')).toBe('pointer');

    const panel = await box(row);
    const at = await box(link);
    const rebus = await box(page.getByTestId('rebus-control'));
    expectNear(panel.right - at.right, 16, 1, 'right inset');
    expectNear(at.top + at.height / 2, panel.top + panel.height / 2, 1, 'centered on the row');
    expectNear(at.left - rebus.right, 20, 1, 'Rebus 20px before it');
    expectNear(rebus.top + rebus.height / 2, at.top + at.height / 2, 1, 'on Rebus\'s line');

    await link.hover();
    await expect.poll(async () => parseColor(await css(link, 'color')), 'primary on hover').toEqual(await token(page, 'primary'));
    await page.mouse.move(0, 0);
    await expect.poll(async () => parseColor(await css(link, 'color')), 'subtle again').toEqual(await token(page, 'subtle'));

    await page.getByTestId('rebus-control').focus();
    await page.keyboard.press('Tab');
    await expect(link).toBeFocused();
    await expect.poll(async () => parseColor(await css(link, 'color')), 'primary on keyboard focus').toEqual(await token(page, 'primary'));

    await page.setViewportSize(PHONE);
    const narrowPanel = await box(row);
    const narrowAt = await box(startOver(page));
    const narrowRebus = await box(page.getByTestId('rebus-control'));
    expectNear(narrowPanel.right - narrowAt.right, 12, 1, 'narrow right inset');
    expectNear(narrowAt.top + narrowAt.height / 2, narrowPanel.top + narrowPanel.height / 2, 1, 'narrow centered');
    expectNear(narrowAt.left - narrowRebus.right, 20, 1, 'narrow: Rebus 20px before it');
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    expect(overflow).toBeLessThanOrEqual(0);
  });

  test('20-S1-2 the dialog; Cancel and Escape change nothing and leave the grid focused', async ({ page }) => {
    const { id } = await seedBuilder(lettered());
    await openBuilder(page, id);
    const before = await renderedCells(page);
    const savedBefore = await savedCells(id);

    await openDialog(page);
    await expect(dialog(page).getByRole('heading', { name: 'Clear Puzzle', exact: true })).toBeVisible();
    await expect(dialog(page)).toContainText(BODY);
    await expect(confirm(page)).toHaveText('Clear Puzzle');
    await expect(cancel(page)).toHaveText('Cancel');
    const confirmBox = await box(confirm(page));
    const cancelBox = await box(cancel(page));
    expect(confirmBox.left, 'Clear Puzzle first').toBeLessThan(cancelBox.left);

    await cancel(page).click();
    await expect(dialog(page)).toHaveCount(0);
    await expect(editorGrid(page)).toBeFocused();
    expect(await renderedCells(page)).toEqual(before);

    await openDialog(page);
    await page.keyboard.press('Escape');
    await expect(dialog(page)).toHaveCount(0);
    await expect(editorGrid(page)).toBeFocused();
    expect(await renderedCells(page)).toEqual(before);

    await page.waitForTimeout(1500);
    expect(await savedCells(id), 'nothing saved').toEqual(savedBefore);
  });

  test('20-S1-3 confirming clears every letter, saves it, and starts on the first cell, Across', async ({ page }) => {
    const { id, title } = await seedBuilder(lettered());
    await openBuilder(page, id);
    await cell(page, '3,2').click();
    await page.keyboard.press('ArrowDown');

    await openDialog(page);
    await confirm(page).click();
    await expect(dialog(page)).toHaveCount(0);
    await expectBlankOnScreen(page, 5);
    await expectAcrossAtOrigin(page);
    await expect(editorGrid(page)).toBeFocused();
    await expect(page.getByTestId('puzzle-title')).toHaveValue(title);
    await expectBlankSaved(id, 5);

    await page.keyboard.type('h');
    await expect.poll(() => cellText(page, '0,0')).toBe('H');
    await expect.poll(async () => (await savedCells(id))[0], 'H saved').toBe('active:H');

    await page.reload();
    await waitForEditorReady(page);
    await expect.poll(() => cellText(page, '0,0')).toBe('H');
    await expect.poll(() => cellText(page, '0,1')).toBe('');
    await expect(page.getByTestId('grid-cell')).toHaveCount(25);
  });

  test('20-S1-4 black cells and rebuses go too', async ({ page }) => {
    const grid = withLetter(toggleBlackSymmetric(lettered(), { col: 4, row: 0 }), { col: 2, row: 2 }, 'OW');
    const { id } = await seedBuilder(grid);
    await openBuilder(page, id);
    await expect(cell(page, '4,0')).toHaveAttribute('data-kind', 'black');

    await openDialog(page);
    await confirm(page).click();
    await expectBlankOnScreen(page, 5);
    await expectBlankSaved(id, 5);
  });

  test('20-S1-5 in Preview: Preview stays on, every cell shows black, no legend', async ({ page }) => {
    const { id } = await seedBuilder(lettered());
    await openBuilder(page, id);
    await page.getByTestId('preview-toggle').click();
    await expect(page.getByTestId('preview-legend')).toBeVisible();
    await expect(startOver(page)).toBeEnabled();

    await openDialog(page);
    await confirm(page).click();
    await expect(dialog(page)).toHaveCount(0);
    await expect(page.getByTestId('preview-toggle').locator('input')).toBeChecked();
    await expect.poll(
      () => page.getByTestId('grid-cell').evaluateAll((cells) => cells.map((c) => c.getAttribute('data-cell-state'))),
      'Preview shows every cell black',
    ).toEqual(Array(25).fill('black'));
    await expect(page.getByTestId('preview-legend')).toHaveCount(0);
    await expectBlankSaved(id, 5);

    await page.getByTestId('preview-toggle').click();
    await expectBlankOnScreen(page, 5);
    // The toggle took focus; the cursor shows once the grid has it again.
    await editorGrid(page).focus();
    await expectAcrossAtOrigin(page);
  });

  test('20-S1-6 an open rebus entry closes; confirming still clears it', async ({ page }) => {
    const { id } = await seedBuilder(lettered());
    await openBuilder(page, id);
    await cell(page, '1,1').click();
    await page.keyboard.press('Escape');
    await expect(page.getByTestId('rebus-entry')).toHaveCount(1);
    await page.keyboard.type('ow');

    await openDialog(page);
    await expect(page.getByTestId('rebus-entry')).toHaveCount(0);
    await confirm(page).click();
    await expect(page.getByTestId('rebus-entry')).toHaveCount(0);
    await expectBlankOnScreen(page, 5);
    await expectBlankSaved(id, 5);
  });

  test('20-S1-7 an empty grid: enabled, and confirming leaves it empty', async ({ page }) => {
    const { id } = await seedBuilder(createGrid({ cols: 5, rows: 5 }));
    await openBuilder(page, id);
    await expect(startOver(page)).toBeEnabled();
    await openDialog(page);
    await confirm(page).click();
    await expect(dialog(page)).toHaveCount(0);
    await expectBlankOnScreen(page, 5);
    await expectAcrossAtOrigin(page);
  });

  test('20-S1-8 guards: no Start Over in the hints phase or once published (pass today)', async ({ page }) => {
    const square = gridOf(['CAT', 'ARE', 'TEA']);
    const hints = await seedBuilder(square, 'hints');
    await openBuilder(page, hints.id);
    await expect(page.getByTestId('rebus-control').filter({ visible: true })).toHaveCount(1);
    await expect(startOver(page)).toHaveCount(0);

    const published = await seedBuilder(square, 'hints', { published: true });
    await openBuilder(page, published.id);
    await expect(page.getByTestId('publish-state')).toBeVisible();
    await expect(startOver(page)).toHaveCount(0);
  });
});
