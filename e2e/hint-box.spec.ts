// Story 15-S4 — Builder Hint Box.
//
// Below a 1000px window in the hints phase, the hint list gives way to the
// Hint Box: one hint at a time, directly under the grid at its width. A 4px
// hint-rule (gray-700) along its top, its other sides a 1px hint-box-border
// (gray-700), 48px tall with the rule. Inside, one row centered vertically,
// 12px inside the outline: the Previous arrow, 12px, the word (the slot's
// answer in `label`, 0.1em, muted), 8px, the input (30px, filled
// hint-box-input blue-medium, its text body-normal primary 10px in, no
// underline at rest and a 1px line-highlight one on focus, named for its
// word), 12px, the Next arrow. The arrows are 24px buttons named
// "Previous word" and "Next word".
//
// The order is every Across word by number, then every Down word, wrapping
// both ways. The box shows the cursor's word; on a cell with no word in the
// cursor's direction it keeps the word it showed. An arrow moves the cursor
// to its word's first cell and focuses the box's input, so the grid shows
// the focused hint's blue. Lock Grid Letters changes nothing in the box;
// published, the input is disabled and the arrows still step.
//
// From 1000px up there's no box and S2's hint columns hold. Colors are the
// tokens' resolved hex values (pinned by color-tokens).
//
// Do not edit this file to match an implementation.

const GRAY_700 = 'rgb(20, 21, 27)';
const BLUE_MEDIUM = 'rgb(207, 238, 255)';
const BLUE_BRIGHT = 'rgb(75, 192, 255)'; // line-highlight
const BLACK = 'rgb(0, 0, 0)'; // primary
const MUTED = 'rgb(139, 144, 154)'; // gray-500

const BOX_PX = 48;
const RULE_PX = 4;
const OUTLINE_PX = 1;
const INSET_PX = 12;
const ARROW_PX = 24;
const ARROW_TO_WORD_PX = 12;
const WORD_TO_INPUT_PX = 8;
const INPUT_TO_ARROW_PX = 12;
const INPUT_PX = 30;
const INPUT_TEXT_INSET_PX = 10;

/** Every cell lettered, so every word survives into the hints phase. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

async function open(page: Page, width: number, grid: Grid = filled(5), phase: 'grid' | 'hints' = 'hints') {
  await page.setViewportSize({ width, height: 900 });
  const { id } = await seedPuzzle({ grid, hints: {}, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  return id;
}

async function rect(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

function css(locator: Locator, property: string) {
  return locator.evaluate((el, p) => getComputedStyle(el).getPropertyValue(p), property);
}

/** A design token's value in px, resolved the way the page resolves it. */
function tokenPx(page: Page, name: string) {
  return page.evaluate((n) => {
    const probe = document.createElement('div');
    probe.style.width = `var(${n})`;
    document.body.appendChild(probe);
    const width = getComputedStyle(probe).width;
    probe.remove();
    return width;
  }, name);
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const hintBox = (page: Page) => page.getByTestId('hint-box');
const word = (page: Page) => hintBox(page).getByTestId('hint-box-word');
const input = (page: Page) => hintBox(page).getByTestId('hint-box-input');
const previous = (page: Page) => hintBox(page).getByRole('button', { name: 'Previous word' });
const next = (page: Page) => hintBox(page).getByRole('button', { name: 'Next word' });
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);

function noHorizontalOverflow(page: Page) {
  return page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth);
}

// --- 15-S4-1: where it shows ---
test.describe('15-S4-1 where it shows', () => {
  for (const width of [999, 768]) {
    test(`hints phase at ${width}px: the box under the grid at its width, the list hidden`, async ({ page }) => {
      await open(page, width);
      await expect(hintBox(page)).toBeVisible();
      await expect(page.getByTestId('hints-region')).toBeHidden();
      const g = await rect(grid(page));
      const b = await rect(hintBox(page));
      expect(b.y, 'directly under the grid').toBeCloseTo(g.bottom, 0);
      expect(b.x, 'from the grid’s left').toBeCloseTo(g.x, 0);
      expect(b.width, 'at the grid’s width').toBeCloseTo(g.width, 0);
    });
  }

  test('hints phase at 1000px: no box, the list beside the grid', async ({ page }) => {
    await open(page, 1000);
    await expect(hintBox(page)).toBeHidden();
    await expect(page.getByTestId('hints-region')).toBeVisible();
    const g = await rect(grid(page));
    const hints = await rect(page.getByTestId('hints-region'));
    expect(hints.x, 'beside the grid').toBeGreaterThan(g.right);
  });

  test('build phase at 768px: no box', async ({ page }) => {
    await open(page, 768, filled(5), 'grid');
    await expect(hintBox(page)).toBeHidden();
  });
});

// --- 15-S4-2: the box ---
test.describe('15-S4-2 the box', () => {
  test('at 768px: the rule, the outline, 48px tall and the row’s spacing', async ({ page }) => {
    await open(page, 768);
    const box = hintBox(page);

    expect(await css(box, 'border-top-width'), 'the rule').toBe(`${RULE_PX}px`);
    expect(await css(box, 'border-top-color'), 'the rule is hint-rule').toBe(GRAY_700);
    for (const side of ['left', 'right', 'bottom']) {
      expect(await css(box, `border-${side}-width`), `${side} outline`).toBe(`${OUTLINE_PX}px`);
      expect(await css(box, `border-${side}-color`), `${side} is hint-box-border`).toBe(GRAY_700);
    }

    const b = await rect(box);
    expect(b.height, '48px with the rule').toBeCloseTo(BOX_PX, 0);

    const prev = await rect(previous(page));
    const w = await rect(word(page));
    const i = await rect(input(page));
    const nxt = await rect(next(page));
    expect(prev.width, 'Previous is 24px').toBeCloseTo(ARROW_PX, 0);
    expect(prev.height, 'Previous is 24px').toBeCloseTo(ARROW_PX, 0);
    expect(nxt.width, 'Next is 24px').toBeCloseTo(ARROW_PX, 0);
    expect(nxt.height, 'Next is 24px').toBeCloseTo(ARROW_PX, 0);

    expect(prev.x - (b.x + OUTLINE_PX), 'Previous 12px inside the outline').toBeCloseTo(INSET_PX, 0);
    expect(w.x - prev.right, 'Previous to the word').toBeCloseTo(ARROW_TO_WORD_PX, 0);
    expect(i.x - w.right, 'the word to the input').toBeCloseTo(WORD_TO_INPUT_PX, 0);
    expect(nxt.x - i.right, 'the input to Next').toBeCloseTo(INPUT_TO_ARROW_PX, 0);
    expect(b.right - OUTLINE_PX - nxt.right, 'Next 12px inside the outline').toBeCloseTo(INSET_PX, 0);

    // Centered between the rule and the bottom outline.
    const middle = (b.y + RULE_PX + b.bottom - OUTLINE_PX) / 2;
    for (const [name, r] of [['Previous', prev], ['the word', w], ['the input', i], ['Next', nxt]] as const) {
      expect(r.y + r.height / 2, `${name} vertically centered`).toBeCloseTo(middle, 0);
    }
  });
});

// --- 15-S4-3: the word and the input ---
test.describe('15-S4-3 the word and the input', () => {
  test('at 768px: the word in label, 0.1em, muted; the input filled, 30px, body-normal, primary, 10px in', async ({ page }) => {
    await open(page, 768);
    const w = word(page);
    await expect(w).toHaveText('AAAAA');
    expect(await css(w, 'font-size'), 'label size').toBe(await tokenPx(page, '--text-label'));
    expect(await css(w, 'line-height'), 'label line height').toBe(await tokenPx(page, '--text-label--line-height'));
    const fontSize = parseFloat(await css(w, 'font-size'));
    expect(parseFloat(await css(w, 'letter-spacing')), '0.1em').toBeCloseTo(fontSize * 0.1, 1);
    expect(await css(w, 'color'), 'muted').toBe(MUTED);

    const i = input(page);
    await expect(i).toHaveAccessibleName('1 Across hint');
    expect((await rect(i)).height, '30px').toBeCloseTo(INPUT_PX, 0);
    expect(await css(i, 'background-color'), 'hint-box-input').toBe(BLUE_MEDIUM);
    expect(await css(i, 'font-size'), 'body-normal').toBe(await tokenPx(page, '--text-body-normal'));
    expect(await css(i, 'color'), 'primary').toBe(BLACK);
    expect(await css(i, 'padding-left'), 'the text 10px in').toBe(`${INPUT_TEXT_INSET_PX}px`);
  });

  test('no underline at rest; a 1px line-highlight underline on focus', async ({ page }) => {
    await open(page, 768);
    const i = input(page);
    const restWidth = parseFloat(await css(i, 'border-bottom-width'));
    const restColor = await css(i, 'border-bottom-color');
    expect(restWidth === 0 || /rgba\(.*,\s*0\)$/.test(restColor), `no underline at rest (${restWidth}px ${restColor})`).toBe(true);

    await i.focus();
    expect(await css(i, 'border-bottom-width'), 'focused underline').toBe('1px');
    expect(await css(i, 'border-bottom-color'), 'line-highlight').toBe(BLUE_BRIGHT);
  });
});

// --- 15-S4-4: the order ---
test.describe('15-S4-4 the order', () => {
  test('Next visits the Across words, then the Down words, and wraps; Previous wraps back', async ({ page }) => {
    await open(page, 768);
    await expect(input(page)).toHaveAccessibleName('1 Across hint');
    const order = ['6 Across', '7 Across', '8 Across', '9 Across', '1 Down', '2 Down', '3 Down', '4 Down', '5 Down', '1 Across'];
    for (const name of order) {
      await next(page).click();
      await expect(input(page)).toHaveAccessibleName(`${name} hint`);
    }
    await previous(page).click();
    await expect(input(page)).toHaveAccessibleName('5 Down hint');
  });

  test('on a grid with a black square, the numbers skip as the numbering does', async ({ page }) => {
    // CAT / A#A / TEN: 1 and 3 Across, 1 and 2 Down.
    await open(page, 768, playPuzzleFixture().grid);
    await expect(input(page)).toHaveAccessibleName('1 Across hint');
    for (const name of ['3 Across', '1 Down', '2 Down', '1 Across']) {
      await next(page).click();
      await expect(input(page)).toHaveAccessibleName(`${name} hint`);
    }
    await expect(word(page)).toHaveText('CAT');
  });
});

// --- 15-S4-5: an arrow selects its word ---
test.describe('15-S4-5 an arrow selects its word', () => {
  test('after Next the cursor is on 6 Across, its cells the hint’s blue, and the box’s input has focus', async ({ page }) => {
    await open(page, 768);
    await next(page).click();
    await expect(input(page)).toHaveAccessibleName('6 Across hint');
    await expect(input(page)).toBeFocused();
    await expect(cell(page, '0,1')).toHaveAttribute('data-highlight', 'selected');
    for (let col = 0; col < 5; col++) {
      await expect(cell(page, `${col},1`)).toHaveCSS('background-color', BLUE_MEDIUM);
    }
    await expect(cell(page, '0,0')).not.toHaveAttribute('data-highlight', /.+/);
  });
});

// --- 15-S4-6: it follows the cursor ---
test.describe('15-S4-6 it follows the cursor', () => {
  test('clicking a cell of 3 Down, toggled to Down, shows 3 Down', async ({ page }) => {
    await open(page, 768);
    await cell(page, '2,1').click();
    await expect(input(page)).toHaveAccessibleName('6 Across hint');
    await cell(page, '2,1').click();
    await expect(input(page)).toHaveAccessibleName('3 Down hint');
  });

  test('on a cell with no word in the cursor’s direction, the box keeps its word', async ({ page }) => {
    // CAT / A#A / TEN: the A at (1,0) is in 1 Across only.
    await open(page, 768, playPuzzleFixture().grid);
    // The cursor starts here, Across, so a click toggles it to Down.
    await cell(page, '0,0').click();
    await expect(input(page)).toHaveAccessibleName('1 Down hint');
    await cell(page, '1,0').click();
    await expect(cell(page, '1,0')).toHaveAttribute('data-highlight', 'selected');
    await expect(input(page)).toHaveAccessibleName('1 Down hint');
    await expect(word(page)).toHaveText('CAT');
  });
});

// --- 15-S4-7: editing saves ---
test.describe('15-S4-7 editing saves', () => {
  test('a hint typed in the box survives a reload and shows in the list at 1440px', async ({ page }) => {
    await open(page, 768);
    await next(page).click();
    await expect(input(page)).toHaveAccessibleName('6 Across hint');

    const saved = page.waitForResponse(
      (response) =>
        response.request().method() === 'POST' &&
        response.request().headers()['next-action'] !== undefined
    );
    await page.keyboard.type('Sky color');
    await expect(input(page)).toHaveValue('Sky color');
    await saved;

    await page.reload();
    await waitForEditorReady(page);
    await next(page).click();
    await expect(input(page)).toHaveAccessibleName('6 Across hint');
    await expect(input(page)).toHaveValue('Sky color');

    await page.setViewportSize({ width: 1440, height: 900 });
    await expect(page.locator('[data-hint-key="6-across"] [data-testid="hint-input"]')).toHaveValue('Sky color');
  });
});

// --- 15-S4-8: locked and published ---
test.describe('15-S4-8 locked and published', () => {
  test('with Lock Grid Letters on, the arrows and the input work', async ({ page }) => {
    await open(page, 768);
    await page.getByTestId('lock-letters-toggle').locator('input').click({ force: true });
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'hints-locked');

    await next(page).click();
    await expect(input(page)).toHaveAccessibleName('6 Across hint');
    await expect(input(page)).toBeFocused();
    await page.keyboard.type('Locked');
    await expect(input(page)).toHaveValue('Locked');
    await previous(page).click();
    await expect(input(page)).toHaveAccessibleName('1 Across hint');
  });

  test('published, the input is disabled and the arrows step', async ({ page }) => {
    await page.setViewportSize({ width: 768, height: 900 });
    const { id } = await seedPlayPuzzle({
      builderId: await currentBuilderId(page),
      puzzle: { grid: filled(5), phase: 'hints', hints: { '1-across': 'First', '6-across': 'Second' } },
    });
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);

    await expect(input(page)).toBeDisabled();
    await expect(input(page)).toHaveValue('First');
    await next(page).click();
    await expect(input(page)).toHaveAccessibleName('6 Across hint');
    await expect(input(page)).toHaveValue('Second');
    await expect(input(page)).toBeDisabled();
    await previous(page).click();
    await previous(page).click();
    await expect(input(page)).toHaveAccessibleName('5 Down hint');
  });
});

