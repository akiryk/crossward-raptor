import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter, type Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { addJay, collaboratorContext } from './helpers/collaborators';
import { markPublished, readInvitations, readMembers, readOwnerAndTitle, readUser } from './helpers/collaborator-management';
import { COLLABORATOR_EMAIL, COLLABORATOR_ID, readPuzzleBuilderId } from './helpers/ownership';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 24-S6 — collaborator management and the library.
//
// Adam (the suite's builder) manages his puzzle's collaborators in the
// "Collaborators…" dialog, from the row menu of an unpublished puzzle and
// from its editor. Jay (the second seeded account) then finds the puzzle in
// his library, under Adam's username, among the puzzles his Create filters
// count, with Duplicate as his only row action. Adam removing Jay in the
// dialog while Jay edits stops Jay's editor (24-S5's loss).
//
// Do not edit this file to match an implementation.

const REMOVED = 'This puzzle is no longer available to you: it was deleted, or you were removed from it. Nothing more can be saved here.';

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
const name = (label: string) => `24-S6 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);

async function seedCat(title: string) {
  const grid = letters(createGrid({ cols: 5, rows: 5 }), [[0, 0, 'C'], [1, 0, 'A'], [2, 0, 'T']]);
  return (await seedPuzzle({ grid, hints: {}, phase: 'grid' }, title)).id;
}
async function seedHints(title: string) {
  let grid = createGrid({ cols: 3, rows: 3 });
  for (let row = 0; row < 3; row++) for (let col = 0; col < 3; col++) grid = withLetter(grid, { col, row }, 'A');
  return (await seedPuzzle({ grid, hints: {}, phase: 'hints' }, title)).id;
}

async function library(page: Page, query = '') {
  await page.goto(`/puzzles${query}`);
  await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
}
async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}
/** The row whose title is exactly `title`. */
function row(page: Page, title: string) {
  return page.getByTestId('puzzle-list-item')
    .filter({ has: page.getByTestId('puzzle-list-title').getByText(title, { exact: true }) });
}
const trigger = (item: Locator) => item.getByTestId('puzzle-menu-button');
const menu = (page: Page) => page.getByTestId('puzzle-menu');
const itemTexts = async (page: Page) =>
  (await menu(page).getByRole('menuitem').allTextContents()).map((text) => text.trim());
const dialog = (page: Page) => page.getByTestId('collaborators-dialog');
const email = (page: Page) => dialog(page).getByTestId('collaborators-email');

async function add(page: Page, address: string) {
  await email(page).fill(address);
  await dialog(page).getByTestId('collaborators-add').click();
}

test.describe('24-S6-E1 adding from the row menu', () => {
  test('Adam adds Jay in the dialog; Jay’s library lists the puzzle under Adam’s username', async ({ page, browser }) => {
    const title = name('row menu');
    const id = await seedCat(title);
    const adam = await readUser(await readPuzzleBuilderId(id));

    await library(page);
    const item = row(page, title);
    await trigger(item).click();
    await expect(menu(page)).toBeVisible();
    expect(await itemTexts(page)).toEqual(['Duplicate', 'Collaborators…', 'Delete']);
    await menu(page).getByTestId('puzzle-menu-collaborators').click();

    await expect(dialog(page)).toBeVisible();
    await expect(dialog(page).getByTestId('modal-title')).toHaveText('Collaborators');
    await expect(email(page)).toBeFocused();
    await expect(dialog(page).getByTestId('collaborators-empty')).toHaveText('No collaborators yet.');

    await email(page).fill(`  ${COLLABORATOR_EMAIL.toUpperCase()} `);
    await email(page).press('Enter');
    const member = dialog(page).getByTestId('collaborator-row');
    await expect(member).toHaveCount(1);
    await expect(member).toHaveAttribute('data-user-id', COLLABORATOR_ID);
    await expect(member).toContainText('Jay');
    await expect(member.getByTestId('collaborator-remove')).toHaveText('Remove');
    await expect(dialog(page).getByTestId('collaborators-message')).toHaveText('Added Jay. They can edit this puzzle now.');
    await expect(email(page)).toHaveValue('');
    await expect(dialog(page).getByTestId('collaborators-empty')).toHaveCount(0);
    expect(await readMembers(id)).toEqual([COLLABORATOR_ID]);

    await page.keyboard.press('Escape');
    await expect(dialog(page)).toHaveCount(0);
    await expect(trigger(item)).toBeFocused();

    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await library(j);
      const shared = row(j, title);
      await expect(shared).toHaveCount(1);
      await expect(shared).toHaveAttribute('data-shared', 'true');
      await expect(shared.getByTestId('puzzle-builder-name')).toHaveText(adam.displayName!.trim());
      await shared.getByTestId('puzzle-edit-link').click();
      await expect(j).toHaveURL(new RegExp(`/puzzles/${id}$`));
      await waitForEditorReady(j);
      await expect(j.getByTestId('puzzle-title')).toHaveValue(title);
    } finally {
      await jay.context.close();
    }
  });
});

test.describe('24-S6-E2 invitations and refusals', () => {
  test('an address without an account is Pending; Revoke removes it; a malformed or own address is refused', async ({ page }) => {
    const title = name('invite');
    const id = await seedCat(title);
    const adam = await readUser(await readPuzzleBuilderId(id));
    const invitee = `s6-${Date.now()}-${Math.random().toString(36).slice(2, 8)}@example.test`;

    await library(page);
    await trigger(row(page, title)).click();
    await menu(page).getByTestId('puzzle-menu-collaborators').click();
    await expect(dialog(page).getByTestId('collaborators-empty')).toBeVisible();

    await add(page, `  ${invitee.toUpperCase()}`);
    const pending = dialog(page).getByTestId('invitation-row');
    await expect(pending).toHaveCount(1);
    await expect(pending).toHaveAttribute('data-email', invitee);
    await expect(pending).toContainText(invitee);
    await expect(pending).toContainText('Pending');
    await expect(dialog(page).getByTestId('collaborators-message'))
      .toHaveText(`Invited ${invitee}. The puzzle will be in their library once they sign in with that address.`);
    expect(await readInvitations(id)).toEqual([invitee]);

    await pending.getByTestId('invitation-revoke').click();
    await expect(pending).toHaveCount(0);
    await expect(dialog(page).getByTestId('collaborators-message')).toHaveText(`Revoked the invitation to ${invitee}.`);
    await expect(dialog(page).getByTestId('collaborators-empty')).toBeVisible();
    await expect(email(page)).toBeFocused();
    expect(await readInvitations(id)).toEqual([]);

    await add(page, 'not-an-address');
    await expect(dialog(page).getByTestId('collaborators-error')).toHaveText('Enter a valid email address.');
    await expect(email(page)).toHaveValue('not-an-address');

    await add(page, adam.email);
    await expect(dialog(page).getByTestId('collaborators-error')).toHaveText("That's your own address.");
    expect(await readMembers(id)).toEqual([]);
    expect(await readInvitations(id)).toEqual([]);

    await dialog(page).getByTestId('collaborators-done').click();
    await expect(dialog(page)).toHaveCount(0);
  });
});

test.describe('24-S6-E3 the editor’s Collaborators…', () => {
  test('Adam has it in Build and Create Hints; Jay has none; a published puzzle has none', async ({ page, browser }) => {
    const build = await seedCat(name('editor build'));
    const hints = await seedHints(name('editor hints'));
    const published = await seedCat(name('editor published'));
    await addJay(build);
    await markPublished(published);

    await open(page, build);
    const button = page.getByTestId('editor-collaborators');
    await expect(button).toHaveText('Collaborators…');
    await button.click();
    await expect(dialog(page)).toBeVisible();
    await expect(dialog(page).getByTestId('collaborator-row')).toContainText('Jay');
    await page.keyboard.press('Escape');
    await expect(dialog(page)).toHaveCount(0);
    await expect(button).toBeFocused();

    await open(page, hints);
    await expect(page.getByTestId('editor-collaborators')).toBeVisible();

    await open(page, published);
    await expect(page.getByTestId('publish-state')).toBeVisible();
    await expect(page.getByTestId('editor-collaborators')).toHaveCount(0);

    const jay = await collaboratorContext(browser);
    try {
      await open(jay.page, build);
      await expect(jay.page.getByTestId('builder-steps')).toBeVisible();
      await expect(jay.page.getByTestId('editor-collaborators')).toHaveCount(0);
    } finally {
      await jay.context.close();
    }
  });
});

test.describe('24-S6-E4 removal in the dialog while Jay edits', () => {
  test('Jay’s editor explains, becomes read-only, and the puzzle leaves his library', async ({ page, browser }) => {
    const title = name('removal');
    const id = await seedCat(title);
    await addJay(id);
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await open(j, id);
      await cell(j, '0,2').click();
      await j.keyboard.type('DOG');
      await expect(j.getByTestId('save-status')).toHaveText('Saved');

      await open(page, id);
      await page.getByTestId('editor-collaborators').click();
      const member = dialog(page).getByTestId('collaborator-row');
      await expect(member).toContainText('Jay');
      await member.getByTestId('collaborator-remove').click();
      await expect(member).toHaveCount(0);
      await expect(dialog(page).getByTestId('collaborators-message')).toHaveText('Removed Jay.');
      expect(await readMembers(id)).toEqual([]);

      await expect(j.getByTestId('access-lost-state')).toHaveText('No longer available', { timeout: 6000 });
      await expect(j.getByTestId('save-notice-message')).toContainText([REMOVED]);
      await expect(j.getByTestId('grid-region')).not.toHaveAttribute('tabindex');

      await library(j);
      await expect(row(j, title)).toHaveCount(0);
    } finally {
      await jay.context.close();
    }
  });
});

test.describe('24-S6-E5 Jay’s library', () => {
  test('the shared draft counts under Build Phase; Duplicate is its only action and makes Jay’s own copy', async ({ browser }) => {
    const title = name('jay library');
    const id = await seedCat(title);
    await addJay(id);
    const before = await readOwnerAndTitle(id);
    const jay = await collaboratorContext(browser);
    try {
      const j = jay.page;
      await library(j, '?create=build');
      const shared = row(j, title);
      await expect(shared).toHaveCount(1);
      await expect(shared).toHaveAttribute('data-shared', 'true');

      await trigger(shared).click();
      await expect(menu(j)).toBeVisible();
      expect(await itemTexts(j)).toEqual(['Duplicate']);
      await menu(j).getByTestId('puzzle-menu-duplicate').click();

      await expect(j).toHaveURL(/\/puzzles\/[^/]+$/);
      await expect(j).not.toHaveURL(new RegExp(`/puzzles/${id}$`));
      await waitForEditorReady(j);
      const copyId = new URL(j.url()).pathname.split('/').pop()!;
      const copy = await readOwnerAndTitle(copyId);
      expect(copy.builderId).toBe(COLLABORATOR_ID);
      expect(copy.title).toBe(`${title} (copy)`);
      expect(await readMembers(copyId)).toEqual([]);
      expect(await readInvitations(copyId)).toEqual([]);
      expect(await readOwnerAndTitle(id)).toEqual(before);
      expect(await readMembers(id)).toEqual([COLLABORATOR_ID]);
    } finally {
      await jay.context.close();
    }
  });
});
