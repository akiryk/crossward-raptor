/** Gives `target` keyboard focus: focus whatever precedes it, then press Tab. */
async function tabTo(page: Page, target: Locator) {
  await target.evaluate((el) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input:not([disabled])'));
    all[all.indexOf(el as HTMLElement) - 1].focus();
  });
  await page.keyboard.press('Tab');
  await expect(target).toBeFocused();
}

/** A real pointer at the centre of `target`. The row's overlay link sits above everything but its control, by design. */
async function pointAt(page: Page, target: Locator) {
  await target.scrollIntoViewIfNeeded();
  const b = await target.boundingBox();
  if (!b) throw new Error('element has no box');
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
}

/**
 * The icon's pixels, decoded in the page from Playwright's screenshot: a
 * function from (x, y) inside the 34px icon to that pixel's luminance.
 */
async function iconPixels(page: Page, icon: Locator) {
  const png = (await icon.screenshot()).toString('base64');
  const data = await page.evaluate(async (base64) => {
    const image = new Image();
    image.src = `data:image/png;base64,${base64}`;
    await image.decode();
    const canvas = document.createElement('canvas');
    canvas.width = image.width;
    canvas.height = image.height;
    const context = canvas.getContext('2d')!;
    context.drawImage(image, 0, 0);
    const { data: rgba, width } = context.getImageData(0, 0, image.width, image.height);
    const luminance: number[] = [];
    for (let i = 0; i < rgba.length; i += 4) {
      luminance.push(0.2126 * rgba[i] + 0.7152 * rgba[i + 1] + 0.0722 * rgba[i + 2]);
    }
    return { luminance, width };
  }, png);
  return (x: number, y: number) => data.luminance[y * data.width + x];
}

function gate() {
  let release!: () => void;
  const promise = new Promise<void>((resolve) => { release = resolve; });
  return { promise, release };
}

