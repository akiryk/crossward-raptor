import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter, type Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { addJay, collaboratorContext } from './helpers/collaborators';
import { secondContext } from './helpers/live-sync';
import { COLLABORATOR_ID, readPuzzleBuilderId } from './helpers/ownership';
import { addPresentBuilder, commitAs, noteTexts, todayHeading } from './helpers/session';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 24-S7 — presence and the session panel.
//
// Adam (the suite's builder, "E2E Suite Builder") owns the puzzle; Jay (the
// second seeded account) is made a collaborator in the database. The panel
// appears between the toggle row and the grid when another builder is
// there, with a date heading and timestamped notes of joins, leaves and
// another builder's Enter Hints or Start Over; new notes never move the
// grid. Two tabs of one account raise nothing.
//
// Do not edit this file to match an implementation.

const ADAM = 'E2E Suite Builder';
const name = (label: string) => `24-S7 ${label} ${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const panel = (page: Page) => page.getByTestId('session-panel');

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
/** A 15×15 in Build with ABRAHAM in 1-Across, shared with Jay. */
async function seedShared(label: string) {
  const grid = letters(createGrid({ cols: 15, rows: 15 }), [...'ABRAHAM'].map((letter, col) => [col, 0, letter] as [number, number, string]));
  const { id } = await seedPuzzle({ grid, hints: {}, phase: 'grid' }, name(label));
  await addJay(id);
  return id;
}
async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}
async function top(page: Page, testId: string) {
  const box = await page.getByTestId(testId).first().boundingBox();
  if (!box) throw new Error(`${testId} has no box`);
  return box;
}

test.describe('24-S7 presence and the session panel', () => {
  test('24-S7-E1 joining: no panel alone; Jay joins and both panels say so, between the toggle row and the grid', async ({ page, browser }) => {
    const id = await seedShared('join');
    await open(page, id);
    await page.waitForTimeout(2500);
    await expect(panel(page)).toHaveCount(0);

    const { context, page: j } = await collaboratorContext(browser);
    try {
      await open(j, id);
      await expect(noteTexts(j)).toHaveText([`You joined. ${ADAM} is here.`], { timeout: 10_000 });
      await expect(noteTexts(page)).toHaveText(['Jay joined the session.'], { timeout: 10_000 });
      await expect(page.getByTestId('session-date')).toHaveText([todayHeading()]);
      await expect(page.getByTestId('session-note-time')).toHaveText([/^\d{2}:\d{2}$/]);

      const toggle = await top(page, 'toggle-row');
      const box = await top(page, 'session-panel');
      const grid = await top(page, 'puzzle-grid');
      expect(box.y).toBeGreaterThanOrEqual(toggle.y + toggle.height);
      expect(box.y + box.height).toBeLessThanOrEqual(grid.y);
      expect(Math.abs(box.x - toggle.x)).toBeLessThanOrEqual(1);
    } finally {
      await context.close();
    }
  });

  test('24-S7-E2 leaving: Jay closes his page and Adam’s panel says so, and stays', async ({ page, browser }) => {
    const id = await seedShared('leave');
    await open(page, id);
    const { context, page: j } = await collaboratorContext(browser);
    try {
      await open(j, id);
      await expect(noteTexts(page)).toHaveText(['Jay joined the session.'], { timeout: 10_000 });
      await j.close({ runBeforeUnload: true });
      await expect(noteTexts(page)).toHaveText(['Jay joined the session.', 'Jay left the session.'], { timeout: 25_000 });
      await page.waitForTimeout(2000);
      await expect(panel(page)).toBeVisible();
    } finally {
      await context.close();
    }
  });

  test('24-S7-E3 notes don’t move the grid; the newest stays in view', async ({ page }) => {
    const id = await seedShared('fill');
    await addPresentBuilder(id, 'Kim');
    await open(page, id);
    await expect(noteTexts(page)).toHaveText(['You joined. Kim is here.'], { timeout: 10_000 });
    const before = await top(page, 'puzzle-grid');
    const height = (await top(page, 'session-panel')).height;
    const names = ['Lee', 'Max', 'Noa', 'Oli', 'Pat', 'Quin'];
    for (const builder of names) await addPresentBuilder(id, builder);
    await expect(noteTexts(page)).toHaveCount(1 + names.length, { timeout: 15_000 });
    const after = await top(page, 'puzzle-grid');
    expect(after.y).toBe(before.y);
    expect((await top(page, 'session-panel')).height).toBe(height);
    const newest = noteTexts(page).last();
    await expect(newest).toBeInViewport();
    const panelBox = await top(page, 'session-panel');
    const newestBox = await newest.boundingBox();
    expect(newestBox!.y + newestBox!.height).toBeLessThanOrEqual(panelBox.y + panelBox.height + 1);
  });

  test('24-S7-E4 another builder’s Create Hints and Start Over are noted; in Create Hints the panel is under Lock Grid Letters', async ({ page, browser }) => {
    // A full 3×3, ready for Create Hints.
    let full = createGrid({ cols: 3, rows: 3 });
    for (let row = 0; row < 3; row++) for (let col = 0; col < 3; col++) full = withLetter(full, { col, row }, 'A');
    const { id } = await seedPuzzle({ grid: full, hints: {}, phase: 'grid' }, name('hints'));
    await addJay(id);
    await open(page, id);
    expect((await commitAs(COLLABORATOR_ID, id, { kind: 'enterHints' })).status).toBe('accepted');
    await expect(noteTexts(page)).toHaveText(['Jay moved the puzzle to Create Hints.'], { timeout: 10_000 });
    await expect(page.getByTestId('lock-letters-toggle')).toBeVisible();
    const toggle = await top(page, 'toggle-row');
    const box = await top(page, 'session-panel');
    const grid = await top(page, 'puzzle-grid');
    expect(box.y).toBeGreaterThanOrEqual(toggle.y + toggle.height);
    expect(box.y + box.height).toBeLessThanOrEqual(grid.y);

    const other = await seedShared('start over');
    const { context, page: j } = await collaboratorContext(browser);
    try {
      await open(j, other);
      expect((await commitAs(await readPuzzleBuilderId(other), other, { kind: 'startOver', keepLockedWords: false })).status).toBe('accepted');
      await expect(noteTexts(j)).toContainText([`${ADAM} started over.`], { timeout: 10_000 });
      await expect(cell(j, '0,0')).not.toContainText('A', { timeout: 10_000 });
    } finally {
      await context.close();
    }
  });

  test('24-S7-E5 same account, two tabs: edits sync with no panel and no outline', async ({ page, browser }) => {
    const id = await seedShared('same account');
    await open(page, id);
    const { context, page: second } = await secondContext(browser);
    try {
      await open(second, id);
      await cell(page, '6,0').click();
      await page.keyboard.press('ArrowDown');
      await page.keyboard.type('MASKS');
      await page.keyboard.press('ArrowUp');
      await expect(cell(second, '6,4')).toContainText('S', { timeout: 10_000 });
      await cell(second, '6,0').click();
      await second.keyboard.press('ArrowDown');
      await second.keyboard.type('MAGIC');
      await expect(cell(page, '6,4')).toContainText('C', { timeout: 10_000 });
      await page.waitForTimeout(3000);
      for (const p of [page, second]) {
        await expect(panel(p)).toHaveCount(0);
        await expect(p.getByTestId('conflict-outline')).toHaveCount(0);
      }
    } finally {
      await context.close();
    }
  });
});
