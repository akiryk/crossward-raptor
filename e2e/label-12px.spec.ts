// Story 23-S1 — The 12px label.
//
// The `label` text style is 12px (was 14px), weight 400 (unchanged), line
// height 16px (was 20px), everywhere it's used: the hint answers under the
// Hint Inputs, the Hint Box's word, the Preview toggle's label, Rebus,
// Lock Word, Reset Grid, every tooltip, a size group's dimensions and the
// style guide's catalog row.
//
// A caption sits as close to its line as today, or closer: a Hint Input's
// answer still starts 4px under the field's bottom edge, and the gap from
// the line to the top of its capitals is at most today's (9.3px at 14px /
// 20px) and at least 7px (7.77px measured at 12px / 16px). The hint rows keep
// their 58px pitch (14-S6-5). The Hint Box's word keeps its 30px box,
// centered as 15-S4 froze it, and stays on the hint's first-line baseline
// (within 1px).
//
// `TextInput` gains a caption under its line (EPIC "The caption"): `label`
// style, uppercase, 0.1em tracking, `muted`, right-aligned to the line,
// starting 4px under it like the hint answers. The field's accessible name
// is the caption's text, and the caption is not a second node in the
// accessibility tree (the caption is aria-hidden; caption and aria-label
// are exclusive), and it stays `muted` while the field has focus.
// `/style-guide` shows one: `sg-input-captioned`, large, caption
// "Username", its caption `sg-input-captioned-caption`.
//
// The cap-top position is derived from the element's line box and the
// font's own metrics (canvas `measureText`), not read from pixels.
// Do not edit this file to match an implementation.

const WIDE = { width: 1440, height: 900 };
const LABEL = { size: 12, weight: 400, lineHeight: 16 };
const TRACKING_PX = 1.2; // 0.1em at 12px
const ANSWER_GAP_PX = 4; // the caption's box under the line (15-S6)
/** Line to the caption's cap top, measured on main before S1 (14px / 20px): 9.31px. */
const TODAY_CAP_GAP_PX = 9.4;
const MIN_CAP_GAP_PX = 7;
const MUTED = 'color(srgb 0 0 0 / 0.4)'; // `muted`: black at 40% (18-S1)
const HINT_BOX_INPUT_PX = 30;

/**
 *   C A T
 *   A . .
 *   T . .
 */
function letteredGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'C');
  grid = withLetter(grid, { col: 1, row: 0 }, 'A');
  grid = withLetter(grid, { col: 2, row: 0 }, 'T');
  grid = withLetter(grid, { col: 0, row: 1 }, 'A');
  grid = withLetter(grid, { col: 0, row: 2 }, 'T');
  return grid;
}

/** A daily, its first 15 cells lettered: TANGENTSANDMORE across the top. */
function dailyGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  [...'TANGENTSANDMORE'].forEach((letter, col) => {
    grid = withLetter(grid, { col, row: 0 }, letter);
  });
  return grid;
}

let counter = 0;
async function openPuzzle(
  page: Page,
  grid: Grid,
  phase: 'grid' | 'hints',
  viewport = WIDE,
) {
  counter += 1;
  const { id } = await seedPuzzle({ grid, hints: {}, phase }, `23-S1 ${phase} ${Date.now()}-${counter}`);
  await page.setViewportSize(viewport);
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  await page.evaluate(() => document.fonts.ready.then(() => undefined));
}

type TextStyle = { size: number; weight: number; lineHeight: number; tracking: number };

function textStyleOf(locator: Locator): Promise<TextStyle> {
  return locator.evaluate((el) => {
    const cs = getComputedStyle(el);
    return {
      size: parseFloat(cs.fontSize),
      weight: Number(cs.fontWeight),
      lineHeight: parseFloat(cs.lineHeight),
      tracking: cs.letterSpacing === 'normal' ? 0 : parseFloat(cs.letterSpacing),
    };
  });
}

async function expectLabel(locator: Locator, name: string) {
  await expect(locator, name).toBeVisible();
  const s = await textStyleOf(locator);
  expect(s.size, `${name} size`).toBe(LABEL.size);
  expect(s.weight, `${name} weight`).toBe(LABEL.weight);
  expect(s.lineHeight, `${name} line height`).toBe(LABEL.lineHeight);
}

/**
 * Where an element's first line of text sits, from its line box and the
 * font's metrics: the baseline and the top of its capitals, in page px.
 */
function firstLine(locator: Locator) {
  return locator.evaluate((el) => {
    const cs = getComputedStyle(el);
    const ctx = document.createElement('canvas').getContext('2d')!;
    ctx.font = `${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`;
    const m = ctx.measureText('H');
    const lineHeight = parseFloat(cs.lineHeight);
    const top =
      el.getBoundingClientRect().top + parseFloat(cs.borderTopWidth) + parseFloat(cs.paddingTop);
    const content = m.fontBoundingBoxAscent + m.fontBoundingBoxDescent;
    const baseline = top + (lineHeight - content) / 2 + m.fontBoundingBoxAscent;
    return { baseline, capTop: baseline - m.actualBoundingBoxAscent };
  });
}

async function rect(locator: Locator) {
  const box = await locator.boundingBox();
  if (!box) throw new Error('no bounding box');
  return { ...box, right: box.x + box.width, bottom: box.y + box.height };
}

// --- 23-S1-1: the style ---
test.describe('23-S1-1 the label style', () => {
  test('`label` resolves to 12px, weight 400, 16px line height', async ({ page }) => {
    await page.goto('/puzzles');
    const resolved = await page.evaluate(() => {
      const probe = document.createElement('div');
      probe.className = 'text-label';
      probe.textContent = 'x';
      document.body.appendChild(probe);
      const cs = getComputedStyle(probe);
      const out = {
        size: parseFloat(cs.fontSize),
        weight: Number(cs.fontWeight),
        lineHeight: parseFloat(cs.lineHeight),
      };
      probe.remove();
      return out;
    });
    expect(resolved).toEqual(LABEL);
  });

  test('the style guide catalogs label as 12px · 400, its sample 12px on 16px', async ({ page }) => {
    await page.goto('/style-guide');
    const row = page.locator('[data-testid="sg-text-style"][data-text-style="label"]');
    await expect(row).toContainText('12px · 400');
    await expectLabel(row.getByTestId('sg-text-sample'), 'label sample');
  });
});

// --- 23-S1-2: every use ---
test.describe('23-S1-2 every use is 12px', () => {
  test('the hints phase: the hint answers, tracked 0.1em', async ({ page }) => {
    await openPuzzle(page, letteredGrid(), 'hints');
    const answers = page.getByTestId('hint-answer');
    await expect(answers.first()).toHaveText('CAT');
    for (const i of [0, 1]) {
      const answer = answers.nth(i);
      await expectLabel(answer, `hint answer ${i}`);
      expect((await textStyleOf(answer)).tracking, `hint answer ${i} tracking`).toBeCloseTo(TRACKING_PX, 1);
    }
  });

  test('the Hint Box: its word, tracked 0.1em', async ({ page }) => {
    await openPuzzle(page, letteredGrid(), 'hints', { width: 768, height: 900 });
    const word = page.getByTestId('hint-box-word');
    await expectLabel(word, 'Hint Box word');
    expect((await textStyleOf(word)).tracking, 'Hint Box word tracking').toBeCloseTo(TRACKING_PX, 1);
  });

  test('the build phase: Preview, Rebus, Reset Grid and the progress tooltip', async ({ page }) => {
    await openPuzzle(page, dailyGrid(), 'grid');
    const toggle = page.getByTestId('preview-toggle');
    await expectLabel(toggle.locator('[data-toggle-label]'), 'Preview label');
    await expectLabel(page.getByTestId('rebus-control').filter({ visible: true }), 'Rebus');
    await expectLabel(page.getByTestId('start-over'), 'Reset Grid');

    await toggle.click();
    await expect(toggle.locator('input')).toBeChecked();
    const bar = page.getByTestId('build-progress-bar');
    await expect(bar).toBeVisible();
    await bar.hover();
    const tip = page.getByTestId('build-progress-tooltip');
    await expect(tip).toBeVisible({ timeout: 3000 });
    await expectLabel(tip, 'tooltip');
    expect(await tip.evaluate((el) => getComputedStyle(el).maxWidth), 'still at most 280px wide').toBe('280px');
  });

  test('Lock Word in the toggle row, below the full grid width', async ({ page }) => {
    await openPuzzle(page, dailyGrid(), 'grid', { width: 635, height: 1000 });
    await expectLabel(page.getByTestId('lock-word-control').filter({ visible: true }), 'Lock Word');
  });

  test('the library: a size group\'s dimensions', async ({ page }) => {
    await seedPuzzle(createBlankPuzzle('mini'), `23-S1 mini ${Date.now()}`);
    await page.goto('/puzzles');
    await page.waitForSelector('[data-testid="puzzle-library"][data-ready="true"]');
    const dimensions = page
      .locator('[data-testid="puzzle-group"][data-size="mini"]')
      .getByTestId('puzzle-group-dimensions');
    await expect(dimensions).toHaveText('5 × 5');
    await expectLabel(dimensions, 'dimensions');
  });
});

// --- 23-S1-3: the hint answers sit no farther from their lines ---
test.describe('23-S1-3 hint answers close to their lines', () => {
  test('each answer starts 4px under its Hint Input; its capitals 7–9.4px under the line', async ({ page }) => {
    await openPuzzle(page, letteredGrid(), 'hints');
    const rows = page.getByTestId('hint-row');
    await expect(rows.first()).toBeVisible();
    const count = await rows.count();
    expect(count).toBeGreaterThanOrEqual(2);
    for (let i = 0; i < count; i += 1) {
      const row = rows.nth(i);
      const field = await rect(row.getByTestId('hint-input'));
      const answer = row.getByTestId('hint-answer');
      const box = await rect(answer);
      expect(box.y - field.bottom, `row ${i}: the answer's box under the line`).toBeCloseTo(ANSWER_GAP_PX, 0);
      const gap = (await firstLine(answer)).capTop - field.bottom;
      expect(gap, `row ${i}: line to cap top`).toBeLessThanOrEqual(TODAY_CAP_GAP_PX);
      expect(gap, `row ${i}: line to cap top`).toBeGreaterThanOrEqual(MIN_CAP_GAP_PX);
      expect(box.height, `row ${i}: one 16px line`).toBeCloseTo(LABEL.lineHeight, 0);
    }
  });
});

// --- 23-S1-4: the Hint Box's word ---
test.describe('23-S1-4 the Hint Box word', () => {
  test('keeps its 30px box and sits on the hint\'s first-line baseline', async ({ page }) => {
    await openPuzzle(page, letteredGrid(), 'hints', { width: 768, height: 900 });
    const word = page.getByTestId('hint-box-word');
    const input = page.getByTestId('hint-box-input');
    await expectLabel(word, 'Hint Box word');
    const w = await rect(word);
    const i = await rect(input);
    expect(w.height, 'the word\'s box').toBeCloseTo(HINT_BOX_INPUT_PX, 0);
    expect(w.y, 'level with the input').toBeCloseTo(i.y, 0);
    const wordBaseline = (await firstLine(word)).baseline;
    const hintBaseline = (await firstLine(input)).baseline;
    expect(Math.abs(wordBaseline - hintBaseline), 'on the hint\'s baseline').toBeLessThanOrEqual(1);
  });
});

// --- 23-S1-5: the TextInput caption ---
test.describe('23-S1-5 the TextInput caption', () => {
  const field = (page: Page) => page.getByTestId('sg-input-captioned');
  const caption = (page: Page) => page.getByTestId('sg-input-captioned-caption');

  async function open(page: Page) {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-inputs')).toBeVisible();
    await page.evaluate(() => document.fonts.ready.then(() => undefined));
  }

  test('the style guide shows a large field captioned "Username"', async ({ page }) => {
    await open(page);
    await expect(page.getByTestId('sg-inputs').getByTestId('sg-input-captioned')).toHaveCount(1);
    await expect(field(page)).toHaveAttribute('type', 'text');
    expect(parseFloat(await field(page).evaluate((el) => getComputedStyle(el).fontSize)), 'large').toBe(18);
    await expect(caption(page)).toHaveText('Username');
  });

  test('the caption: label, uppercase, 0.1em, muted, right-aligned 4px under the line', async ({ page }) => {
    await open(page);
    const c = caption(page);
    await expectLabel(c, 'caption');
    const s = await c.evaluate((el) => {
      const cs = getComputedStyle(el);
      return { transform: cs.textTransform, align: cs.textAlign, color: cs.color };
    });
    expect(s.transform, 'uppercase').toBe('uppercase');
    expect(['right', 'end'], 'right-aligned').toContain(s.align);
    expect(s.color, 'muted').toBe(MUTED);
    expect((await textStyleOf(c)).tracking, '0.1em').toBeCloseTo(TRACKING_PX, 1);

    const f = await rect(field(page));
    const box = await rect(c);
    expect(box.y - f.bottom, 'its box 4px under the line').toBeCloseTo(ANSWER_GAP_PX, 0);
    expect(box.right, 'its right edge on the line\'s').toBeCloseTo(f.right, 0);
    const gap = (await firstLine(c)).capTop - f.bottom;
    expect(gap, 'line to cap top').toBeLessThanOrEqual(TODAY_CAP_GAP_PX);
    expect(gap, 'line to cap top').toBeGreaterThanOrEqual(MIN_CAP_GAP_PX);
  });

  test('the caption stays muted while the field has focus', async ({ page }) => {
    await open(page);
    await field(page).focus();
    await expect(field(page)).toBeFocused();
    await expect(caption(page)).toHaveCSS('color', MUTED);
  });

  test('the field is named by the caption, which isn\'t announced again', async ({ page }) => {
    await open(page);
    await expect(field(page)).toHaveAccessibleName('Username');
    await expect(field(page)).toHaveAccessibleDescription('');
    // TextInput's own root: the field's parent, which holds the caption.
    const root = field(page).locator('..');
    await expect(root.getByTestId('sg-input-captioned-caption')).toHaveCount(1);
    const lines = (await root.ariaSnapshot()).split('\n');
    expect(lines[0], 'the textbox, named Username').toMatch(/^- textbox "Username"/);
    expect(lines.filter((l) => /username/i.test(l)), 'the caption not a second node').toHaveLength(1);
  });
});
