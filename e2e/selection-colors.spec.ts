import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 17-S5 — Selection colors.
//
// The word around the cursor is blue, so the yellow-bright cursor cell
// stands out. In the build phase the cursor cell stays
// build-cell-selected-cell (yellow-bright); the rest of its word is
// build-cell-selected-row-on, now blue-medium, where a cell holds a letter
// or is a symmetric hint, and build-cell-selected-row-off, now a new
// palette variable blue-dull (#CADAE2), otherwise. S4's Preview word
// follows. In the hints phase, with the grid focused, the cursor's word is
// hint-cell-cursor-word, now blue-medium: the same blue as a focused hint
// input's word. yellow-medium and yellow-dull are removed from the palette
// and the style guide.
//
// Colors are the human's values, written out here. Do not edit this file
// to match an implementation.

test.use({ viewport: { width: 1440, height: 1000 } });

const CURSOR = 'rgb(252, 255, 77)'; // yellow-bright
const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // #CFEEFF
const BLUE_DULL = 'rgb(202, 218, 226)'; // #CADAE2
const BUILD_OFF = 'rgb(221, 224, 230)'; // gray-200
const WHITE = 'rgb(255, 255, 255)';

/**
 * A 15×15: ABC across the top, ADE down the left, Z at (5,14). (9,0) is
 * a symmetric hint for Z; the rest of the top row is empty (off).
 */
function buildGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'A');
  grid = withLetter(grid, { col: 1, row: 0 }, 'B');
  grid = withLetter(grid, { col: 2, row: 0 }, 'C');
  grid = withLetter(grid, { col: 0, row: 1 }, 'D');
  grid = withLetter(grid, { col: 0, row: 2 }, 'E');
  grid = withLetter(grid, { col: 5, row: 14 }, 'Z');
  return grid;
}

/** 17-S4's grid: in Preview, 1 Across is (0,0) error, (1,0) letter,
 *  (2,0) warning. */
function previewGrid(): Grid {
  let grid = createGrid({ cols: 5, rows: 5 });
  grid = withLetter(grid, { col: 1, row: 0 }, 'B');
  grid = withLetter(grid, { col: 2, row: 0 }, 'C');
  grid = withLetter(grid, { col: 2, row: 1 }, 'D');
  grid = withLetter(grid, { col: 4, row: 4 }, 'E');
  return grid;
}

/** A 5×5 with off corners at (4,0) and (0,4), every other cell lettered.
 *  1 Across is CATS, (0,0)–(3,0). */
function hintsGrid(): Grid {
  const rows = ['CATS.', 'AREAS', 'RENTS', 'TANKS', '.SEES'];
  let grid = createGrid({ cols: 5, rows: 5, black: [{ col: 4, row: 0 }, { col: 0, row: 4 }] });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

async function open(page: Page, grid: Grid, phase: 'grid' | 'hints') {
  const { id } = await seedPuzzle({ grid, hints: {}, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const grid = (page: Page) => page.getByTestId('puzzle-grid');
const hintInput = (page: Page, key: string) =>
  page.locator(`[data-hint-key="${key}"]`).getByTestId('hint-input');

const bg = (locator: Locator) =>
  locator.evaluate((el) => getComputedStyle(el).backgroundColor);

function rootVariable(page: Page, name: string) {
  return page.evaluate(
    (n) => getComputedStyle(document.documentElement).getPropertyValue(n).trim(),
    name
  );
}

test.describe('17-S5-1 the build phase', () => {
  test('the cursor yellow-bright; its word blue-medium where on, blue-dull where off', async ({ page }) => {
    await open(page, buildGrid(), 'grid');
    await cell(page, '3,0').click();
    await expect(cell(page, '4,0')).toHaveAttribute('data-highlight', 'slot');

    const expected: [string, string, string][] = [
      ['3,0', CURSOR, 'the cursor cell'],
      ['1,0', BLUE_MEDIUM, 'a lettered cell in its word'],
      ['9,0', BLUE_MEDIUM, 'a symmetric hint in its word'],
      ['4,0', BLUE_DULL, 'an off cell in its word'],
      ['0,1', WHITE, 'a lettered cell outside it'],
      ['5,5', BUILD_OFF, 'an off cell outside it'],
    ];
    for (const [coord, color, label] of expected) {
      expect(await bg(cell(page, coord)), label).toBe(color);
    }
  });
});

test.describe('17-S5-2 Preview', () => {
  test("the selected Preview word is blue-medium, around a yellow-bright cursor", async ({ page }) => {
    await open(page, previewGrid(), 'grid');
    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');
    await cell(page, '1,0').click();
    await expect(cell(page, '1,0')).toHaveAttribute('data-selected', 'true');

    expect(await bg(cell(page, '1,0')), 'the cursor cell').toBe(CURSOR);
    for (const coord of ['0,0', '2,0']) {
      expect(await bg(cell(page, coord)), `the word's ${coord}`).toBe(BLUE_MEDIUM);
    }
  });
});

test.describe('17-S5-3 the hints phase', () => {
  test("with the grid focused, the cursor yellow-bright and its word blue-medium", async ({ page }) => {
    await open(page, hintsGrid(), 'hints');
    await cell(page, '1,0').click();

    await expect.poll(() => bg(cell(page, '1,0')), 'the cursor cell').toBe(CURSOR);
    for (const coord of ['0,0', '2,0', '3,0']) {
      expect(await bg(cell(page, coord)), `its word, ${coord}`).toBe(BLUE_MEDIUM);
    }
  });

  test("the grid's word is the same blue as a focused hint input's word", async ({ page }) => {
    await open(page, hintsGrid(), 'hints');
    await hintInput(page, '1-across').click();
    await expect.poll(() => bg(cell(page, '0,0'))).not.toBe(WHITE);
    const hintWord = await bg(cell(page, '2,0'));

    await cell(page, '1,0').click();
    await expect.poll(() => bg(cell(page, '1,0'))).toBe(CURSOR);
    expect(await bg(cell(page, '2,0')), 'the grid-focused word').toBe(hintWord);
  });
});

test.describe('17-S5-4 the palette', () => {
  test('blue-dull is #CADAE2; yellow-medium and yellow-dull no longer exist', async ({ page }) => {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-colors')).toBeVisible();

    expect((await rootVariable(page, '--palette-blue-dull')).toLowerCase()).toBe('#cadae2');
    for (const name of ['yellow-medium', 'yellow-dull']) {
      expect(await rootVariable(page, `--palette-${name}`), `--palette-${name}`).toBe('');
      await expect(
        page.locator(`[data-testid="sg-color-variable"][data-variable="${name}"]`),
        `no ${name} swatch`
      ).toHaveCount(0);
    }
    await expect(page.getByTestId('sg-colors')).not.toContainText(/yellow-medium|yellow-dull/);
  });

  test('the three styles show their new variables in the catalog', async ({ page }) => {
    await page.goto('/style-guide');

    const expected: [string, string, string][] = [
      ['build-cell-selected-row-on', 'blue-medium', BLUE_MEDIUM],
      ['build-cell-selected-row-off', 'blue-dull', BLUE_DULL],
      ['hint-cell-cursor-word', 'blue-medium', BLUE_MEDIUM],
    ];
    for (const [style, variable, color] of expected) {
      const row = page.locator(`[data-testid="sg-color-style"][data-style="${style}"]`);
      await expect(row).toContainText(variable);
      expect(await bg(row.getByTestId('sg-swatch')), `${style} swatch`).toBe(color);
    }
  });
});
