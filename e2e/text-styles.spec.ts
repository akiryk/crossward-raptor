import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';

// Story F2 — typography: Inter only, and the redesign's text styles.
//
// Inter is the only typeface, loaded at 400 and 600; Space Grotesk is gone
// and headings render in Inter. Each text style is a Tailwind
// `--text-<name>` token carrying a size, a weight and a line height. Sizes and
// weights are exact; line heights are defaults the user tunes later, so only
// their presence and sanity are asserted. `/style-guide` catalogs the styles.
// Do not edit this file to match an implementation.

// token name -> [size in px, weight]
const TEXT_STYLES: Record<string, [number, number]> = {
  label: [14, 400],
  'title-1': [44, 600],
  'title-2': [32, 600],
  'title-3': [18, 600],
  'title-4': [14, 600],
  'button-large': [18, 600],
  'button-normal': [14, 600],
  'body-large': [18, 400],
  'body-normal': [14, 400],
  'body-small': [12, 400],
  'hint-number': [14, 600],
  'cell-letter': [16, 400],
  'cell-number': [10, 400],
};

const UPPERCASE_STYLES = ['cell-letter'];

/** Resolves a text style's three tokens the way an element using them would. */
function resolveStyle(page: Page, name: string) {
  return page.evaluate((n) => {
    const root = getComputedStyle(document.documentElement);
    const raw = {
      size: root.getPropertyValue(`--text-${n}`).trim(),
      weight: root.getPropertyValue(`--text-${n}--font-weight`).trim(),
      lineHeight: root.getPropertyValue(`--text-${n}--line-height`).trim(),
    };
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${n})`;
    probe.style.fontWeight = `var(--text-${n}--font-weight)`;
    probe.style.lineHeight = `var(--text-${n}--line-height)`;
    document.body.appendChild(probe);
    const cs = getComputedStyle(probe);
    const resolved = {
      size: parseFloat(cs.fontSize),
      weight: Number(cs.fontWeight),
      lineHeight: parseFloat(cs.lineHeight),
    };
    probe.remove();
    return { raw, resolved };
  }, name);
}

function firstFamily(fontFamily: string) {
  return fontFamily.split(',')[0].trim().replace(/^["']|["']$/g, '');
}

/** Every font face the document knows about, after loading settles. */
async function fontFaces(page: Page) {
  return page.evaluate(async () => {
    await document.fonts.ready;
    return Array.from(document.fonts, (f) => ({
      family: f.family.replace(/^["']|["']$/g, ''),
      weight: f.weight,
      status: f.status,
    }));
  });
}

/**
 *   C A T
 *   A . .
 *   T . .
 */
function letteredGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'C');
  grid = withLetter(grid, { col: 1, row: 0 }, 'A');
  grid = withLetter(grid, { col: 2, row: 0 }, 'T');
  grid = withLetter(grid, { col: 0, row: 1 }, 'A');
  grid = withLetter(grid, { col: 0, row: 2 }, 'T');
  return grid;
}

// --- F2-1: the text-style tokens ---
test.describe('F2-1 text-style tokens', () => {
  test('every style resolves to its size, weight and a line height on /puzzles', async ({
    page,
  }) => {
    await page.goto('/puzzles');

    for (const [name, [size, weight]] of Object.entries(TEXT_STYLES)) {
      const { raw, resolved } = await resolveStyle(page, name);
      expect(raw.size, `--text-${name}`).not.toBe('');
      expect(raw.weight, `--text-${name}--font-weight`).not.toBe('');
      expect(raw.lineHeight, `--text-${name}--line-height`).not.toBe('');

      expect(resolved.size, `${name} size`).toBe(size);
      expect(resolved.weight, `${name} weight`).toBe(weight);
      // a default, tuned later: just never tighter than the type itself
      // and never absurdly loose
      expect(resolved.lineHeight, `${name} line height`).toBeGreaterThanOrEqual(size);
      expect(resolved.lineHeight, `${name} line height`).toBeLessThanOrEqual(size * 2);
    }
  });

  test('label replaces the old 12px label, so existing labels grow to 14px', async ({
    page,
  }) => {
    const { id } = await seedPuzzle({ grid: letteredGrid(), hints: {}, phase: 'hints' });
    await page.goto(`/puzzles/${id}`);

    const label = page.getByTestId('hint-row').first().getByTestId('hint-label');
    await expect(label).toBeVisible();
    expect(await label.evaluate((el) => getComputedStyle(el).fontSize)).toBe('14px');
  });
});

// --- F2-2: Inter is the only typeface ---
test.describe('F2-2 Inter only', () => {
  for (const path of ['/puzzles', '/style-guide']) {
    test(`${path} knows no font but Inter, loaded at 400 and 600`, async ({ page }) => {
      await page.goto(path);

      const faces = await fontFaces(page);
      const families = new Set(faces.map((f) => f.family));
      expect([...families].filter((f) => /grotesk/i.test(f))).toEqual([]);

      // next/font may add a metric-matched local fallback face; only the
      // real Inter faces carry a weight
      const inter = faces.filter((f) => f.family === 'Inter');
      expect(inter.length).toBeGreaterThan(0);
      expect(new Set(inter.map((f) => f.weight))).toEqual(new Set(['400', '600']));
    });
  }

  test('headings render in Inter', async ({ page }) => {
    await seedPuzzle({ grid: letteredGrid(), hints: {}, phase: 'grid' });
    await page.goto('/puzzles');

    for (const testid of ['page-heading', 'app-header']) {
      const family = await page
        .getByTestId(testid)
        .first()
        .evaluate((el) => getComputedStyle(el).fontFamily);
      expect(firstFamily(family), `${testid} font`).toBe('Inter');
    }
  });

  test('both loaded weights are actually used on the style guide', async ({ page }) => {
    await page.goto('/style-guide');
    await expect(page.getByTestId('sg-text-styles')).toBeVisible();

    const loaded = (await fontFaces(page)).filter(
      (f) => f.family === 'Inter' && f.status === 'loaded'
    );
    expect(new Set(loaded.map((f) => f.weight))).toEqual(new Set(['400', '600']));
  });
});

// --- F2-3: the catalog ---
test.describe('F2-3 text-style catalog', () => {
  test('every style has a row with its name, size, weight and a sample', async ({ page }) => {
    await page.goto('/style-guide');

    const section = page.getByTestId('sg-text-styles');
    await expect(section).toBeVisible();
    await expect(section.getByTestId('sg-text-style')).toHaveCount(
      Object.keys(TEXT_STYLES).length
    );

    for (const [name, [size, weight]] of Object.entries(TEXT_STYLES)) {
      const row = section.locator(`[data-testid="sg-text-style"][data-text-style="${name}"]`);
      await expect(row, `row for ${name}`).toHaveCount(1);
      await expect(row).toContainText(name);
      await expect(row).toContainText(String(size));
      await expect(row).toContainText(String(weight));

      const sample = row.getByTestId('sg-text-sample');
      await expect(sample, `sample for ${name}`).toBeVisible();
      const cs = await sample.evaluate((el) => {
        const s = getComputedStyle(el);
        return {
          size: parseFloat(s.fontSize),
          weight: Number(s.fontWeight),
          lineHeight: parseFloat(s.lineHeight),
          family: s.fontFamily,
          transform: s.textTransform,
        };
      });
      const { resolved } = await resolveStyle(page, name);

      expect(cs.size, `${name} sample size`).toBe(size);
      expect(cs.weight, `${name} sample weight`).toBe(weight);
      expect(cs.lineHeight, `${name} sample line height`).toBe(resolved.lineHeight);
      expect(firstFamily(cs.family), `${name} sample font`).toBe('Inter');
      if (UPPERCASE_STYLES.includes(name)) {
        expect(cs.transform, `${name} sample case`).toBe('uppercase');
      }
    }
  });

  test('a sample follows a live edit of its token and restores without it', async ({ page }) => {
    await page.goto('/style-guide');

    for (const name of Object.keys(TEXT_STYLES)) {
      const sample = page
        .locator(`[data-testid="sg-text-style"][data-text-style="${name}"]`)
        .getByTestId('sg-text-sample');
      const sizeOf = () => sample.evaluate((el) => getComputedStyle(el).fontSize);
      const before = await sizeOf();

      await page.evaluate(
        (n) => document.documentElement.style.setProperty(`--text-${n}`, '37px'),
        name
      );
      expect(await sizeOf(), `${name} follows the edit`).toBe('37px');

      await page.evaluate(
        (n) => document.documentElement.style.removeProperty(`--text-${n}`),
        name
      );
      expect(await sizeOf(), `${name} restores`).toBe(before);
    }
  });

  for (const viewport of [
    { width: 1280, height: 800 },
    { width: 375, height: 812 },
  ]) {
    test(`no horizontal overflow at ${viewport.width}px`, async ({ page }) => {
      await page.setViewportSize(viewport);
      await page.goto('/style-guide');

      await expect(page.getByTestId('sg-text-styles')).toBeVisible();
      const overflow = await page.evaluate(
        () => document.documentElement.scrollWidth > document.documentElement.clientWidth
      );
      expect(overflow).toBe(false);
    });
  }
});
