// Story 17-S8 — Step controls.
//
// The builder's three step buttons give way to a step row: the current
// step as a label (`builder-step-current`: a 24px `primary` circle with
// its `inverse` number, then the step's name, all `title-4` `primary`)
// and one numbered Button for the next step, 20px after it: "1 Build the
// Grid" then 2 Create Hints, or "2 Create Hints" then 3 Publish. The row
// is inset 16px, so the circle lines up with the toggle below.
//
// The label carries the current step's `data-step-id`, marked
// `aria-current="true"`; the button the next step's.
//
// Below it, the toggle row (`toggle-row`) is a panel at the grid's width:
// `toggle-row` (interactive-faint), 10px corners, 48px tall, its content
// 16px in. Wide, the step row, the panel and the grid are 20px apart, the
// step row 32px under the title, and a published puzzle's panel is empty
// and invisible, so the grid doesn't move. In one column (below a 1140px
// window) those gaps are 16px, as 15-S3's, and a published puzzle has no
// panel. Below a 748px window (a phone) the row and panel are inset 12px,
// the label and button 12px apart and the panel 40px tall.
//
// The build phase has no Publish and no "Lol." or "Nope.".
//
// Do not edit this file to match an implementation.

type Rgb = { r: number; g: number; b: number };

function parseColor(value: string): Rgb {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/);
  if (rgb) return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]) };
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.color = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).color;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

/** A text style's size, weight and line height as computed on this page. */
async function textStyleToken(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.fontWeight = `var(--text-${s}--font-weight)`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const c = getComputedStyle(probe);
    const resolved = { fontSize: c.fontSize, fontWeight: c.fontWeight, lineHeight: c.lineHeight };
    probe.remove();
    return resolved;
  }, style);
}

async function computed(locator: Locator) {
  return locator.evaluate((el) => {
    const c = getComputedStyle(el);
    return {
      fontSize: c.fontSize,
      fontWeight: c.fontWeight,
      lineHeight: c.lineHeight,
      color: c.color,
      background: c.backgroundColor,
      radius: c.borderTopLeftRadius,
      radii: [c.borderTopLeftRadius, c.borderTopRightRadius, c.borderBottomRightRadius, c.borderBottomLeftRadius],
    };
  });
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return { left: b.x, top: b.y, right: b.x + b.width, bottom: b.y + b.height, width: b.width, height: b.height };
}

function expectNear(actual: number, expected: number, tolerance: number, label: string) {
  expect(Math.abs(actual - expected), `${label}: ${actual} vs ${expected}`).toBeLessThanOrEqual(tolerance);
}

/** A 3×3 word square, CAT / ARE / TEA. */
function wordSquare(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  ['CAT', 'ARE', 'TEA'].forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

function allHints(grid: Grid): Record<string, string> {
  const { across, down } = requiredHints(grid);
  return Object.fromEntries([...across, ...down].map((ref) => [hintKey(ref), `Hint ${hintKey(ref)}`]));
}

let titleCounter = 0;
async function seed(phase: Phase, options: { hints?: 'all'; published?: boolean } = {}) {
  const grid = wordSquare();
  titleCounter += 1;
  const { id } = await seedPuzzle(
    { grid, hints: options.hints === 'all' ? allHints(grid) : {}, phase },
    `S8 ${phase} ${Date.now()}-${titleCounter}`
  );
  if (options.published) {
    const client = ownershipTestClient();
    try {
      await client.puzzle.update({
        where: { id },
        data: { publishedAt: new Date('2026-10-01T00:00:00Z'), visibility: 'public' },
      });
    } finally {
      await client.$disconnect();
    }
  }
  return id;
}

async function open(page: Page, id: string) {
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const steps = (page: Page) => page.getByTestId('builder-steps');
const current = (page: Page) => page.getByTestId('builder-step-current');
const toggleRow = (page: Page) => page.getByTestId('toggle-row');
const grid = (page: Page) => page.getByTestId('puzzle-grid');

/** The step row's label and buttons as a reader sees them. */
async function readRow(page: Page) {
  const label = current(page);
  const circle = label.locator('[data-step-number]');
  const buttons = await steps(page).getByRole('button').evaluateAll((all) =>
    all.map((button) => ({
      id: button.getAttribute('data-step-id'),
      type: button.getAttribute('data-button-type'),
      number: button.querySelector('[data-button-number]')?.textContent?.trim() ?? null,
      label: (button.textContent ?? '').replace(button.querySelector('[data-button-number]')?.textContent ?? '', '').trim(),
      selected: button.getAttribute('aria-current') === 'true',
    }))
  );
  return {
    number: (await circle.textContent())?.trim(),
    label: (await label.textContent())?.replace((await circle.textContent()) ?? '', '').trim(),
    buttons,
  };
}

const PHASES = [
  {
    phase: 'grid' as const,
    number: '1',
    label: 'Build the Grid',
    next: { id: 'hints', type: 'numbered', number: '2', label: 'Create Hints', selected: false },
    toggle: 'preview-toggle',
  },
  {
    phase: 'hints' as const,
    number: '2',
    label: 'Create Hints',
    next: { id: 'publish', type: 'numbered', number: '3', label: 'Publish', selected: false },
    toggle: 'lock-letters-toggle',
  },
];

test.describe('17-S8-1 the step row', () => {
  test.use({ viewport: { width: 1280, height: 800 } });

  for (const p of PHASES) {
    test(`${p.phase} phase: "${p.number} ${p.label}" as a label and one button, ${p.next.number} ${p.next.label}`, async ({ page }) => {
      await open(page, await seed(p.phase));
      expect(await readRow(page)).toEqual({ number: p.number, label: p.label, buttons: [p.next] });
      // The label is text, not a control: no button, link or tab stop. It
      // is the current step: its step id, marked current.
      await expect(current(page).locator('button, a, input, [tabindex]')).toHaveCount(0);
      await expect(page.getByRole('button', { name: new RegExp(p.label) })).toHaveCount(0);
      await expect(current(page)).toHaveAttribute('data-step-id', p.phase === 'grid' ? 'build' : 'hints');
      await expect(current(page)).toHaveAttribute('aria-current', 'true');
      await expect(page.locator('[data-step-id]')).toHaveCount(2);
      if (p.phase === 'grid') {
        await expect(page.locator('[data-step-id="publish"]')).toHaveCount(0);
        await expect(page.getByRole('button', { name: /publish/i })).toHaveCount(0);
      } else {
        await expect(page.locator('[data-step-id="build"]')).toHaveCount(0);
      }
    });

    test(`${p.phase} phase: the label is title-4 primary, its number an inverse 24px primary circle`, async ({ page }) => {
      await open(page, await seed(p.phase));
      const label = await computed(current(page));
      const { fontSize, fontWeight, lineHeight } = label;
      expect({ fontSize, fontWeight, lineHeight }, 'label title-4').toEqual(await textStyleToken(page, 'title-4'));
      expect(parseColor(label.color), 'label primary').toEqual(await token(page, 'primary'));

      const circle = current(page).locator('[data-step-number]');
      const circleBox = await box(circle);
      expectNear(circleBox.width, 24, 0.5, 'circle width');
      expectNear(circleBox.height, 24, 0.5, 'circle height');
      const look = await computed(circle);
      expect(parseColor(look.background), 'circle primary').toEqual(await token(page, 'primary'));
      expect(parseColor(look.color), 'number inverse').toEqual(await token(page, 'inverse'));
      expect(parseFloat(look.radius), 'circle round').toBeGreaterThanOrEqual(12);

      // The circle and the name sit on one line, 8px apart, as in a
      // numbered Button.
      const name = await current(page).evaluate((el) => {
        const range = document.createRange();
        const text = Array.from(el.childNodes).find((n) => n.nodeType === Node.TEXT_NODE && n.textContent?.trim())!;
        range.selectNodeContents(text);
        const r = range.getBoundingClientRect();
        return { left: r.left, top: r.top, bottom: r.bottom };
      });
      expectNear(name.left - circleBox.right, 8, 1, 'circle to name');
      expectNear((name.top + name.bottom) / 2, circleBox.top + 12, 1.5, 'name centred on the circle');
    });
  }

  test('the button behaves as before: 2 opens the enter-hints dialog, 3 says "Not quite!" or opens the Publish dialog', async ({ page }) => {
    await open(page, await seed('grid'));
    await page.locator('[data-testid="builder-steps"] [data-step-id="hints"]').click();
    await expect(page.getByTestId('enter-hints-dialog')).toBeVisible();

    await open(page, await seed('hints'));
    await page.locator('[data-testid="builder-steps"] [data-step-id="publish"]').click();
    await expect(page.getByTestId('too-early-dialog')).toBeVisible();
    await expect(page.getByTestId('too-early-dialog').getByTestId('modal-title')).toHaveText('Not quite!');

    await open(page, await seed('hints', { hints: 'all' }));
    await page.locator('[data-testid="builder-steps"] [data-step-id="publish"]').click();
    await expect(page.getByTestId('publish-dialog')).toBeVisible();
  });

  test('the button is a Tab stop and Enter presses it; the label is skipped', async ({ page }) => {
    await open(page, await seed('grid'));
    await page.getByTestId('puzzle-title').focus();
    await page.keyboard.press('Tab');
    await expect(page.locator('[data-testid="builder-steps"] [data-step-id="hints"]')).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(page.getByTestId('enter-hints-dialog')).toBeVisible();
  });

  test('a published puzzle shows "Published" and "Play it!" instead', async ({ page }) => {
    await open(page, await seed('hints', { hints: 'all', published: true }));
    await expect(page.getByTestId('publish-state')).toHaveText('Published');
    await expect(page.getByTestId('play-link')).toBeVisible();
    await expect(steps(page)).toHaveCount(0);
    await expect(current(page)).toHaveCount(0);
  });
});

/** The step row, the toggle row and the grid, as measured at one width. */
async function measure(page: Page, toggleId: string) {
  return {
    title: await box(page.getByTestId('puzzle-title')),
    steps: await box(steps(page)),
    circle: await box(current(page).locator('[data-step-number]')),
    label: await box(current(page)),
    button: await box(steps(page).getByRole('button')),
    row: await box(toggleRow(page)),
    toggle: await box(page.getByTestId(toggleId).locator('[data-toggle-pill]')),
    grid: await box(grid(page)),
  };
}

const LAYOUTS = [
  // Wide: the hints list beside the grid. One column, still wider than a
  // phone. A phone, and the narrowest supported window.
  { name: 'wide', width: 1280, title: 32, inset: 16, between: 20, height: 48, gap: 20 },
  { name: 'one column', width: 1000, title: 16, inset: 16, between: 20, height: 48, gap: 16 },
  { name: 'phone', width: 375, title: 16, inset: 12, between: 12, height: 40, gap: 16 },
  { name: 'narrowest', width: 320, title: 16, inset: 12, between: 12, height: 40, gap: 16 },
];

test.describe('17-S8-2 layout', () => {
  for (const l of LAYOUTS) {
    for (const p of PHASES) {
      test(`${l.name} (${l.width}px), ${p.phase} phase`, async ({ page }) => {
        await page.setViewportSize({ width: l.width, height: 900 });
        await open(page, await seed(p.phase));
        const m = await measure(page, p.toggle);

        expectNear(m.steps.top - m.title.bottom, l.title, 1, 'title to step row');
        expectNear(m.circle.left - m.grid.left, l.inset, 1, 'circle inset from the grid');
        expectNear(m.button.left - m.label.right, l.between, 1, 'label to button');
        expectNear((m.button.top + m.button.bottom) / 2, (m.circle.top + m.circle.bottom) / 2, 1, 'label and button on one line');
        expect(m.button.right, 'the button within the grid’s width').toBeLessThanOrEqual(m.grid.right + 0.5);

        expectNear(m.row.left, m.grid.left, 1, 'toggle row left = grid left');
        expectNear(m.row.right, m.grid.right, 1, 'toggle row right = grid right');
        expectNear(m.row.height, l.height, 0.5, 'toggle row height');
        expectNear(m.row.top - m.steps.bottom, l.gap, 1, 'step row to toggle row');
        expectNear(m.grid.top - m.row.bottom, l.gap, 1, 'toggle row to grid');
        expectNear(m.toggle.left - m.row.left, l.inset, 1, 'toggle inset');
        expectNear(m.toggle.left, m.circle.left, 1, 'toggle under the circle');
        expectNear((m.toggle.top + m.toggle.bottom) / 2, (m.row.top + m.row.bottom) / 2, 1, 'toggle centred in the row');

        const look = await computed(toggleRow(page));
        expect(parseColor(look.background), 'toggle-row fill').toEqual(await token(page, 'toggle-row'));
        expect(look.radii, '10px corners').toEqual(['10px', '10px', '10px', '10px']);
      });
    }
  }

  test('wide, the grid stays put from the build phase to the hints phase to published', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 900 });
    await open(page, await seed('grid'));
    const buildGrid = await box(grid(page));
    const buildRow = await box(toggleRow(page));

    await open(page, await seed('hints'));
    expectNear((await box(grid(page))).top, buildGrid.top, 0.5, 'hints grid');
    expectNear((await box(toggleRow(page))).top, buildRow.top, 0.5, 'hints toggle row');

    await open(page, await seed('hints', { hints: 'all', published: true }));
    expectNear((await box(grid(page))).top, buildGrid.top, 0.5, 'published grid');
    // The empty panel keeps its space but shows nothing.
    await expect(toggleRow(page)).toBeHidden();
    await expect(page.getByTestId('lock-letters-toggle')).toHaveCount(0);
  });

  for (const width of [375, 1000]) {
    test(`at ${width}px a published puzzle has no toggle row; the grid is 16px under "Published"`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 });
      await open(page, await seed('hints', { hints: 'all', published: true }));
      await expect(toggleRow(page)).toBeHidden();
      const published = await box(page.getByTestId('publish-state'));
      expectNear((await box(grid(page))).top - published.bottom, 16, 1.5, 'Published to grid');
    });
  }

  test('no horizontal overflow at 320px in either phase', async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 900 });
    for (const phase of ['grid', 'hints'] as const) {
      await open(page, await seed(phase));
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
      expect(overflow, phase).toBeLessThanOrEqual(0);
    }
  });
});

