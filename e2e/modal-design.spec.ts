// Story F4 — Modal.
//
// The Modal is a panel in `modal-background` with a 2px border of the same
// style and 10px corners, between 300px and 500px wide, over the
// `modal-backdrop`. A yellow `modal-title-background` header fills the
// panel inside its border and follows its curved top corners; it holds the
// `title-3` title and the ✕ close control. Content is `body-normal` in
// `primary`. The footer holds the buttons, left-aligned, confirm first.
// Play's message dialogs gain an OK button. Accessibility behavior is
// unchanged and stays covered by modal.spec.ts and modal-a11y.spec.ts.
// Asserted by color style; paddings are not pinned.
// Do not edit this file to match an implementation.

const SENTINEL = '#123456';

type Rgba = { r: number; g: number; b: number; a: number };

function parseColor(value: string): Rgba {
  const rgb = value.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/);
  if (rgb) {
    return { r: Number(rgb[1]), g: Number(rgb[2]), b: Number(rgb[3]), a: alpha(rgb[4]) };
  }
  const srgb = value.match(/^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+%?))?\s*\)$/);
  if (srgb) {
    return {
      r: Math.round(Number(srgb[1]) * 255),
      g: Math.round(Number(srgb[2]) * 255),
      b: Math.round(Number(srgb[3]) * 255),
      a: alpha(srgb[4]),
    };
  }
  throw new Error(`unparseable colour: "${value}"`);
}

function alpha(raw: string | undefined) {
  if (raw === undefined) return 1;
  return raw.endsWith('%') ? Number(raw.slice(0, -1)) / 100 : Number(raw);
}

function expectColor(actual: string, expected: Rgba, label: string) {
  const parsed = parseColor(actual);
  expect({ r: parsed.r, g: parsed.g, b: parsed.b }, label).toEqual({
    r: expected.r,
    g: expected.g,
    b: expected.b,
  });
  expect(parsed.a, `${label} alpha`).toBeCloseTo(expected.a, 2);
}

/** The colour a color style resolves to on this page. */
async function token(page: Page, style: string) {
  const raw = await page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.backgroundColor = `var(--color-${s})`;
    document.body.appendChild(probe);
    const resolved = getComputedStyle(probe).backgroundColor;
    probe.remove();
    return resolved;
  }, style);
  return parseColor(raw);
}

function styleOf(locator: Locator) {
  return locator.evaluate((el) => {
    const s = getComputedStyle(el);
    return {
      background: s.backgroundColor,
      color: s.color,
      borderColors: [s.borderTopColor, s.borderRightColor, s.borderBottomColor, s.borderLeftColor],
      borderWidths: [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth],
      borderStyles: [s.borderTopStyle, s.borderRightStyle, s.borderBottomStyle, s.borderLeftStyle],
      radii: [s.borderTopLeftRadius, s.borderTopRightRadius, s.borderBottomRightRadius, s.borderBottomLeftRadius],
      overflow: [s.overflowX, s.overflowY],
      fontSize: parseFloat(s.fontSize),
      fontWeight: Number(s.fontWeight),
      fontFamily: s.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      lineHeight: s.lineHeight,
      outline:
        s.outlineStyle === 'none' || parseFloat(s.outlineWidth) === 0
          ? 'none'
          : `${s.outlineStyle} ${s.outlineWidth} ${s.outlineColor}`,
    };
  });
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('element has no box');
  return b;
}

/** Where an element's content starts: its left edge inside border and padding. */
function innerLeft(locator: Locator) {
  return locator.evaluate((el) => {
    const s = getComputedStyle(el);
    return el.getBoundingClientRect().left + parseFloat(s.borderLeftWidth) + parseFloat(s.paddingLeft);
  });
}

async function tokenLineHeight(page: Page, style: string) {
  return page.evaluate((s) => {
    const probe = document.createElement('div');
    probe.style.fontSize = `var(--text-${s})`;
    probe.style.lineHeight = `var(--text-${s}--line-height)`;
    document.body.appendChild(probe);
    const lh = getComputedStyle(probe).lineHeight;
    probe.remove();
    return lh;
  }, style);
}

/** The open dialog's parts. */
function parts(page: Page) {
  const overlay = page.getByTestId('modal');
  const panel = overlay.getByRole('dialog');
  return {
    overlay,
    panel,
    backdrop: page.getByTestId('modal-backdrop'),
    header: panel.getByTestId('modal-header'),
    title: panel.getByTestId('modal-title'),
    close: panel.getByTestId('modal-close'),
    content: panel.getByTestId('modal-content'),
    footer: panel.getByTestId('modal-footer'),
  };
}

async function openSample(page: Page) {
  await page.goto('/style-guide');
  await expect(page.getByTestId('sg-modal')).toBeVisible();
  await page.getByTestId('sg-modal-open').click();
  await expect(page.getByTestId('sg-modal-dialog')).toBeVisible();
  await page.mouse.move(1, 1);
}

/** CAT across the top row of a 3x3; every other cell active but empty. */
function catGrid(): Grid {
  let grid = createGrid({ cols: 3, rows: 3 });
  grid = withLetter(grid, { col: 0, row: 0 }, 'C');
  grid = withLetter(grid, { col: 1, row: 0 }, 'A');
  grid = withLetter(grid, { col: 2, row: 0 }, 'T');
  return grid;
}

async function openHintsDialog(page: Page) {
  const { id } = await seedPuzzle({ grid: catGrid(), hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
  // 14-S4: the stepper's "clues" step is now 2 Create Hints.
  await page.locator('[data-testid="builder-steps"] [data-step-id="hints"]').click();
  await expect(page.getByTestId('enter-hints-dialog')).toBeVisible();
  await page.mouse.move(1, 1);
}

async function openNewPuzzleDialog(page: Page) {
  await page.goto('/puzzles');
  await waitForNewPuzzleReady(page);
  await page.getByTestId('new-puzzle-button').click();
  await expect(page.getByTestId('new-puzzle-dialog')).toBeVisible();
}

// A 3x3 play puzzle: CAT / A.A / TEN.
const correct: SerializedGrid = {
  cols: 3, rows: 3,
  cells: [
    [{ kind: 'active', letter: 'C' }, { kind: 'active', letter: 'A' }, { kind: 'active', letter: 'T' }],
    [{ kind: 'active', letter: 'A' }, { kind: 'black' }, { kind: 'active', letter: 'A' }],
    [{ kind: 'active', letter: 'T' }, { kind: 'active', letter: 'E' }, { kind: 'active', letter: 'N' }],
  ],
};

function entries(options: { wrong?: boolean; lastBlank?: boolean } = {}): SerializedGrid {
  const value = structuredClone(correct);
  if (options.wrong) value.cells[0][0] = { kind: 'active', letter: 'Z' };
  if (options.lastBlank) value.cells[2][2] = { kind: 'active', letter: null };
  return value;
}

async function openPlay(page: Page, initial: SerializedGrid) {
  const playerId = await currentBuilderId(page);
  const fixture = await seedPlayPuzzle({ builderId: playerId });
  await seedPlaySession(playerId, fixture.id, deserializeGrid(initial));
  await page.goto(`/puzzles/${fixture.id}/play`);
  await expect(page.getByTestId('play-puzzle')).toHaveAttribute('data-session-state', 'ready');
  return fixture;
}

async function finishPlay(page: Page) {
  await page.locator('[data-coord="2,2"]').click();
  await page.keyboard.type('n');
}

/** The footer's buttons, in order, and where it sits. */
async function expectFooter(
  page: Page,
  confirm: Locator,
  cancel: Locator,
  label: string
) {
  const { content, footer } = parts(page);
  await expect(footer, `${label} footer`).toBeVisible();
  await expect(footer.locator('button'), `${label} footer buttons`).toHaveCount(2);
  await expect(footer.locator('button').nth(0), `${label} confirm first`).toHaveAttribute(
    'data-testid',
    (await confirm.getAttribute('data-testid'))!
  );
  await expect(footer.locator('button').nth(1), `${label} cancel second`).toHaveAttribute(
    'data-testid',
    (await cancel.getAttribute('data-testid'))!
  );
  await expect(confirm).toHaveAttribute('data-button-type', 'normal');
  await expect(cancel).toHaveAttribute('data-button-type', 'alternate');

  const contentBox = await box(content);
  const footerBox = await box(footer);
  const confirmBox = await box(confirm);
  const cancelBox = await box(cancel);
  expect(footerBox.y, `${label} footer below the content`).toBeGreaterThanOrEqual(
    contentBox.y + contentBox.height - 0.5
  );
  expect(confirmBox.x, `${label} confirm left of cancel`).toBeLessThan(cancelBox.x);
  expect(Math.abs(confirmBox.x - (await innerLeft(content))), `${label} footer left-aligned`).toBeLessThanOrEqual(1);
}

// --- F4-1: the catalog ---
test.describe('F4-1 modal catalog', () => {
  test('the sample opens with a header, content and a two-button footer, and either button closes it', async ({ page }) => {
    for (const button of ['sg-modal-confirm', 'sg-modal-cancel']) {
      await openSample(page);
      const p = parts(page);
      await expect(p.panel).toHaveAttribute('data-testid', 'sg-modal-dialog');
      await expect(p.header).toBeVisible();
      await expect(p.header.getByTestId('modal-title')).toHaveCount(1);
      await expect(p.header.getByTestId('modal-close')).toHaveCount(1);
      expect((await p.title.innerText()).trim().length).toBeGreaterThan(0);
      expect((await p.content.innerText()).trim().length).toBeGreaterThan(0);
      await expect(p.footer.locator('button')).toHaveCount(2);

      await page.getByTestId(button).click();
      await expect(page.getByTestId('modal')).toHaveCount(0);
      await expect(page.getByTestId('sg-modal-open')).toBeFocused();
    }
  });

  test('no horizontal overflow at 1280px or 375px, open or closed', async ({ page }) => {
    for (const width of [1280, 375]) {
      await page.setViewportSize({ width, height: 800 });
      await page.goto('/style-guide');
      const overflow = () =>
        page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
      expect(await overflow(), `closed at ${width}px`).toBeLessThanOrEqual(0);
      await page.getByTestId('sg-modal-open').click();
      await expect(page.getByTestId('sg-modal-dialog')).toBeVisible();
      expect(await overflow(), `open at ${width}px`).toBeLessThanOrEqual(0);
    }
  });
});

