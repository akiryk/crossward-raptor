// --- F4-3: header ---
test.describe('F4-3 header', () => {
  test('the yellow header fills the panel inside its border and follows its corners', async ({ page }) => {
    await openSample(page);
    const { panel, header, title } = parts(page);
    expectColor((await styleOf(header)).background, await token(page, 'modal-title-background'), 'header');

    const p = await box(panel);
    const h = await box(header);
    expect(h.x, 'header left').toBeCloseTo(p.x + 2, 0);
    expect(h.y, 'header top').toBeCloseTo(p.y + 2, 0);
    expect(h.width, 'header width').toBeCloseTo(p.width - 4, 0);

    // The header's top corners follow the panel's curve: either the panel
    // clips its content, or the header rounds its own top corners.
    const panelStyle = await styleOf(panel);
    const headerStyle = await styleOf(header);
    const clipped = panelStyle.overflow.every((o) => o === 'hidden' || o === 'clip');
    const rounded =
      parseFloat(headerStyle.radii[0]) >= 7.5 && parseFloat(headerStyle.radii[1]) >= 7.5;
    expect(clipped || rounded, 'header follows the curved corners').toBe(true);

    // Sized by padding around the title, which it centres vertically.
    const t = await box(title);
    expect(h.height, 'header is taller than the title').toBeGreaterThan(t.height + 8);
    const above = t.y - h.y;
    const below = h.y + h.height - (t.y + t.height);
    expect(Math.abs(above - below), 'title centred vertically').toBeLessThanOrEqual(2);
  });

  test('the title is title-3 in Inter and primary, left-aligned in the header', async ({ page }) => {
    await openSample(page);
    const { header, title, close } = parts(page);
    const s = await styleOf(title);
    expect(s.fontSize).toBe(18);
    expect(s.fontWeight).toBe(600);
    expect(s.fontFamily).toBe('Inter');
    expect(s.lineHeight).toBe(await tokenLineHeight(page, 'title-3'));
    expectColor(s.color, await token(page, 'primary'), 'title');

    const h = await box(header);
    const t = await box(title);
    const c = await box(close);
    expect(t.x - h.x, 'title inset').toBeGreaterThan(0);
    expect(t.x - h.x, 'title left-aligned').toBeLessThan(h.width / 4);
    expect(c.x, 'close to the right of the title').toBeGreaterThanOrEqual(t.x + t.width - 0.5);
    expect(c.x + c.width, 'close inside the header').toBeLessThanOrEqual(h.x + h.width);
    expect(c.y, 'close inside the header').toBeGreaterThanOrEqual(h.y);
    expect(c.y + c.height, 'close inside the header').toBeLessThanOrEqual(h.y + h.height);
  });

  test('the close control is primary and turns muted on hover and Tab focus, with the focus ring on Tab focus only', async ({ page }) => {
    await openSample(page);
    const { close } = parts(page);
    const primary = await token(page, 'primary');
    const muted = await token(page, 'muted');

    const idle = await styleOf(close);
    expectColor(idle.color, primary, 'close');
    expect(idle.outline).toBe('none');

    await close.hover();
    await expect.poll(async () => parseColor((await styleOf(close)).color)).toEqual(muted);
    await page.mouse.move(1, 1);
    await expect.poll(async () => parseColor((await styleOf(close)).color)).toEqual(primary);

    for (let i = 0; i < 6; i++) {
      await page.keyboard.press('Tab');
      if (await close.evaluate((el) => el === document.activeElement)) break;
    }
    await expect(close).toBeFocused();
    const focused = await styleOf(close);
    expectColor(focused.color, muted, 'close on Tab focus');
    // 14-S11: Tab focus shows the focus ring.
    expect(focused.outline, 'focus ring').toBe('solid 2px rgb(0, 240, 255)');
  });
});

