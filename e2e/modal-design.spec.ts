// --- F4-7: token-driven ---
test.describe('F4-7 token-driven', () => {
  test('live palette and radius edits repaint and reshape the open modal, and restore', async ({ page }) => {
    await openSample(page);
    const { panel, header } = parts(page);
    const before = { panel: await styleOf(panel), header: await styleOf(header) };
    const sentinel = parseColor('rgb(18, 52, 86)');

    const edit = (name: string, value: string | null) =>
      page.evaluate(
        ([n, v]) => {
          if (v === null) document.documentElement.style.removeProperty(n);
          else document.documentElement.style.setProperty(n, v);
        },
        [name, value] as const
      );

    await edit('--palette-yellow-bright', SENTINEL);
    expectColor((await styleOf(header)).background, sentinel, 'header follows yellow-bright');
    await edit('--palette-yellow-bright', null);

    await edit('--palette-white', SENTINEL);
    const repainted = await styleOf(panel);
    expectColor(repainted.background, sentinel, 'panel follows white');
    expectColor(repainted.borderColors[0], sentinel, 'border follows white');
    await edit('--palette-white', null);

    await edit('--radius-modal', '3px');
    expect((await styleOf(panel)).radii[0], 'panel follows --radius-modal').toBe('3px');
    await edit('--radius-modal', null);

    expect(await styleOf(panel)).toEqual(before.panel);
    expect(await styleOf(header)).toEqual(before.header);
  });
});
