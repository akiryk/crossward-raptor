import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { currentBuilderId } from './helpers/ownership';
import { seedPlayPuzzle } from './helpers/play-route';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 15-S3 — Builder, narrow.
//
// Below a 1140px window (1092px of room inside the page's padding; 17-S7,
// was 1000px), the builder is one column at the grid's 700px width
// (17-S7, was 560px), centered: the title in
// `title-3`, the numbered buttons with the toggle 20px after them,
// 16px between the title, that row and the grid. Below the grid, only
// Preview's legend in the build phase and, in the hints phase, S4's Hint
// Box (15-S4 replaced the hint list there). From 1140px up, S2's wide
// layout holds.
//
// Do not edit this file to match an implementation.

const GRID_PX = 700;
const NARROW_GAP_PX = 16;
const TOGGLE_GAP_PX = 20;
const WIDE_GAP_PX = 32;

type Phase = 'grid' | 'hints';
const PHASES: Phase[] = ['grid', 'hints'];
const TOGGLE: Record<Phase, string> = { grid: 'preview-toggle', hints: 'lock-letters-toggle' };

/** Every cell lettered, so every word survives into the hints phase. */
function filled(size: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) grid = withLetter(grid, { col, row }, 'A');
  }
  return grid;
}

async function openBuilder(page: Page, phase: Phase, width: number) {
  await page.setViewportSize({ width, height: 900 });
  const { id } = await seedPuzzle({ grid: filled(5), hints: {}, phase });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

async function box(locator: Locator) {
  const b = await locator.boundingBox();
  if (!b) throw new Error('no bounding box');
  return { x: b.x, y: b.y, width: b.width, height: b.height, right: b.x + b.width, bottom: b.y + b.height };
}

function px(locator: Locator, property: 'fontSize' | 'fontWeight' | 'lineHeight') {
  return locator.evaluate((el, p) => getComputedStyle(el)[p], property);
}

/** A design token's value in px, resolved the way the page resolves it. */
function tokenPx(page: Page, name: string) {
  return page.evaluate((n) => {
    const probe = document.createElement('div');
    probe.style.width = `var(${n})`;
    document.body.appendChild(probe);
    const width = getComputedStyle(probe).width;
    probe.remove();
    return width;
  }, name);
}

const grid = (page: Page) => page.getByTestId('puzzle-grid');
const title = (page: Page) => page.getByTestId('puzzle-title');
const steps = (page: Page) => page.getByTestId('builder-steps');

function noHorizontalOverflow(page: Page) {
  return page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth);
}

// --- 15-S3-1: the threshold ---
test.describe('15-S3-1 the threshold', () => {
  for (const phase of PHASES) {
    test(`${phase} phase at 1140px: the wide layout, the hints 32px right of the grid`, async ({ page }) => {
      await openBuilder(page, phase, 1140);
      const g = await box(grid(page));
      const editor = await box(page.getByTestId('puzzle-editor'));
      const hints = await box(page.getByTestId(phase === 'grid' ? 'hint-skeleton' : 'hints-region'));
      expect(g.x, 'the grid at the editor’s left').toBeCloseTo(editor.x, 0);
      expect(hints.x - g.right, 'beside the grid').toBeCloseTo(WIDE_GAP_PX, 0);
      expect(hints.y, 'level with the grid').toBeCloseTo(g.y, 0);
    });

    test(`${phase} phase at 1139px: the narrow layout, the grid centered`, async ({ page }) => {
      await openBuilder(page, phase, 1139);
      const g = await box(grid(page));
      const editor = await box(page.getByTestId('puzzle-editor'));
      expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
      expect(g.x - editor.x, 'centered').toBeCloseTo(editor.right - g.right, 0);
      if (phase === 'grid') await expect(page.getByTestId('hint-skeleton')).toBeHidden();
      // 15-S4 amended this: the Hint Box, not the hint list, below the grid.
      else expect((await box(page.getByTestId('hint-box'))).y, 'below the grid').toBeGreaterThanOrEqual(g.bottom - 0.5);
    });
  }
});

// --- 15-S3-2: one centered column at the grid's width ---
test.describe('15-S3-2 one centered column', () => {
  for (const phase of PHASES) {
    for (const width of [1139, 768, 748]) {
      test(`${phase} phase at ${width}px: title, buttons, toggle and grid in a centered 700px column`, async ({ page }) => {
        await openBuilder(page, phase, width);
        const g = await box(grid(page));
        const editor = await box(page.getByTestId('puzzle-editor'));
        const t = await box(title(page));
        const s = await box(steps(page));
        const toggle = await box(page.getByTestId(TOGGLE[phase]));

        expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
        expect(g.x - editor.x, 'centered').toBeCloseTo(editor.right - g.right, 0);
        expect(t.x, 'title from the grid’s left').toBeCloseTo(g.x, 0);
        expect(t.right, 'title to the grid’s right').toBeCloseTo(g.right, 0);
        expect(s.x, 'buttons from the grid’s left').toBeCloseTo(g.x, 0);
        expect(toggle.right, 'toggle within the column').toBeLessThanOrEqual(g.right + 0.5);
        expect(await noHorizontalOverflow(page), 'no horizontal overflow').toBe(true);
      });
    }
  }
});

// --- 15-S3-3: the title ---
test.describe('15-S3-3 the title', () => {
  test('at 768px the title is title-3', async ({ page }) => {
    await openBuilder(page, 'grid', 768);
    expect(await px(title(page), 'fontSize')).toBe(await tokenPx(page, '--text-title-3'));
    expect(await px(title(page), 'lineHeight')).toBe(await tokenPx(page, '--text-title-3--line-height'));
    expect(await px(title(page), 'fontWeight')).toBe('600');
  });

  test('at 1140px the title is still title-1', async ({ page }) => {
    await openBuilder(page, 'grid', 1140);
    expect(await px(title(page), 'fontSize')).toBe(await tokenPx(page, '--text-title-1'));
    expect(await px(title(page), 'lineHeight')).toBe(await tokenPx(page, '--text-title-1--line-height'));
  });
});

// --- 15-S3-4: the toggle beside the buttons ---
test.describe('15-S3-4 the toggle beside the buttons', () => {
  for (const phase of PHASES) {
    test(`${phase} phase at 768px: the toggle level with the buttons, 20px after them`, async ({ page }) => {
      await openBuilder(page, phase, 768);
      const s = await box(steps(page));
      const toggle = await box(page.getByTestId(TOGGLE[phase]));
      expect(toggle.x - s.right, '20px after the buttons').toBeCloseTo(TOGGLE_GAP_PX, 0);
      expect(toggle.y + toggle.height / 2, 'centered on the buttons').toBeCloseTo(s.y + s.height / 2, 0);
    });
  }

  test('at 1140px the toggle is still on its own row below the buttons', async ({ page }) => {
    await openBuilder(page, 'grid', 1140);
    const s = await box(steps(page));
    const toggle = await box(page.getByTestId('preview-toggle'));
    expect(toggle.y, 'below the buttons').toBeGreaterThan(s.bottom);
    expect(toggle.x, 'at the editor’s left').toBeCloseTo(s.x, 0);
  });
});

// --- 15-S3-5: tighter spacing ---
test.describe('15-S3-5 tighter spacing', () => {
  for (const phase of PHASES) {
    test(`${phase} phase at 768px: 16px from the title to the buttons and from the buttons to the grid`, async ({ page }) => {
      await openBuilder(page, phase, 768);
      const t = await box(title(page));
      const s = await box(steps(page));
      const g = await box(grid(page));
      expect(s.y - t.bottom, 'title to buttons').toBeCloseTo(NARROW_GAP_PX, 0);
      expect(g.y - s.bottom, 'buttons to grid').toBeCloseTo(NARROW_GAP_PX, 0);
    });
  }
});

// --- 15-S3-6: below the grid, the build phase ---
test.describe('15-S3-6 below the grid, the build phase', () => {
  test('at 768px: no skeleton, and with Preview on only the legend, under the grid within its width', async ({ page }) => {
    await page.setViewportSize({ width: 768, height: 900 });
    // A corner letter without its symmetric partner is an error, so the
    // legend shows.
    const { id } = await seedPuzzle({ grid: withLetter(createGrid({ cols: 5, rows: 5 }), { col: 0, row: 0 }, 'A'), hints: {}, phase: 'grid' });
    await page.goto(`/puzzles/${id}`);
    await waitForEditorReady(page);
    await expect(page.getByTestId('hint-skeleton')).toBeHidden();

    await page.getByTestId('preview-toggle').locator('input').click({ force: true });
    await expect(grid(page)).toHaveAttribute('data-grid-mode', 'preview');
    await expect(page.getByTestId('preview-legend')).toBeVisible();
    await expect(page.getByTestId('hint-skeleton')).toBeHidden();

    const g = await box(grid(page));
    const legend = await box(page.getByTestId('preview-legend'));
    expect(legend.y, 'under the grid').toBeGreaterThan(g.bottom);
    expect(legend.x, 'from the grid’s left').toBeCloseTo(g.x, 0);
    expect(legend.right, 'within the grid’s width').toBeLessThanOrEqual(g.right + 0.5);
  });
});

