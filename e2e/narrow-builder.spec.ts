// --- 15-S3-8: the published state ---
test.describe('15-S3-8 the published state', () => {
  test('at 768px: “Published” and “Play it!” in the column, 16px between the title, them and the grid', async ({ page }) => {
    await page.setViewportSize({ width: 768, height: 900 });
    const fixture = await seedPlayPuzzle({ builderId: await currentBuilderId(page) });
    await page.goto(`/puzzles/${fixture.id}`);
    await waitForEditorReady(page);

    const g = await box(grid(page));
    const t = await box(title(page));
    const state = await box(page.getByTestId('publish-state'));
    const link = await box(page.getByTestId('play-link'));
    expect(g.width, 'grid width').toBeCloseTo(GRID_PX, 0);
    expect(state.x, 'from the grid’s left').toBeCloseTo(g.x, 0);
    expect(link.right, 'within the column').toBeLessThanOrEqual(g.right + 0.5);
    expect(state.y - t.bottom, 'title to the row').toBeCloseTo(NARROW_GAP_PX, 0);
    expect(g.y - state.bottom, 'the row to the grid').toBeCloseTo(NARROW_GAP_PX, 0);
    expect(await noHorizontalOverflow(page), 'no horizontal overflow').toBe(true);
  });
});
