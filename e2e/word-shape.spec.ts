import { test, expect } from '@playwright/test';
import type { Locator, Page } from '@playwright/test';
import { createGrid, withLetter } from '../src/engine/grid';
import type { Grid } from '../src/engine/grid';
import { seedPuzzle } from './helpers/seed-puzzle';
import { waitForEditorReady } from './helpers/wait-for-ready';

// Story 21-S8 — the word is the run of cells Preview keeps white.
//
// In the build phase with Preview off, the cursor's word is the unbroken
// run of cells through it that Preview wouldn't make black: its letters
// and any Preview-red cells (empty, but their symmetric counterpart holds
// a letter). Those are blue-medium; the rest of the row or column is dull
// blue (amended by 21-S14, below). Only a complete word (every cell lettered, 3 or more) can be
// locked: no button beside it, and the toggle row's Lock Word disabled,
// until its empty cells are filled.
//
// The human's example, on a daily's top row (X Preview-black, * Preview-red):
//   X X X B I R D * * X X S O Y X
//
// Amended by 21-S14: the rest of the row or column is no longer dull blue
// but looks as it would outside the highlight (an off cell gray-200, a
// lettered cell or a Preview-red cell white): expectWord and the titles.
//
// Amended by 21-S9: the narrow case's window is 600px (was 700px), since
// a daily's grid is its full 620px at a 700px window.
//
// Amended by 21-S16: the button beside a word waits 3 seconds (was 1);
// every wait timed against it is 2000ms longer.
//
// Colors are the human's values, written out here. Do not edit this file
// to match an implementation.

const BLUE_MEDIUM = 'rgb(207, 238, 255)'; // #CFEEFF
const OFF = 'rgb(221, 224, 230)'; // gray-200, build-cell-off (21-S14)
const WHITE = 'rgb(255, 255, 255)'; // build-cell-on (21-S14)

/** BIRD (3–6) and SOY (11–13) on row 0; O, N at (6,14), (7,14) make
 *  (8,0) and (7,0) Preview-red. */
function shapeGrid(): Grid {
  let grid = createGrid({ cols: 15, rows: 15 });
  const put = (cols: number[], row: number, letters: string) =>
    cols.forEach((col, i) => {
      grid = withLetter(grid, { col, row }, letters[i]);
    });
  put([3, 4, 5, 6], 0, 'BIRD');
  put([11, 12, 13], 0, 'SOY');
  put([6, 7], 14, 'ON');
  return grid;
}

const ROW = Array.from({ length: 15 }, (_, col) => `${col},0`);
const BIRD = ['3,0', '4,0', '5,0', '6,0'];
const STARS = ['7,0', '8,0'];
const SOY = ['11,0', '12,0', '13,0'];

async function open(page: Page, viewport = { width: 1440, height: 1000 }) {
  await page.setViewportSize(viewport);
  const { id } = await seedPuzzle({ grid: shapeGrid(), hints: {}, phase: 'grid' });
  await page.goto(`/puzzles/${id}`);
  await waitForEditorReady(page);
}

const cell = (page: Page, coord: string) => page.locator(`[data-coord="${coord}"]`);
const bg = (locator: Locator) => locator.evaluate((el) => getComputedStyle(el).backgroundColor);
const lockButton = (page: Page) => page.getByRole('button', { name: /^(Lock|Unlock) word$/ });
const outlines = (page: Page) => page.getByTestId('word-outline');
const ticks = (page: Page) => page.getByTestId('lock-tick');

async function cursorOn(page: Page, coord: string) {
  await cell(page, coord).click();
  await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true');
  await expect(cell(page, coord === '0,0' ? '1,0' : '0,0')).toHaveAttribute('data-highlight', 'slot');
}

/** The cursor's word is exactly `word` (the cursor aside): blue-medium,
 *  letters 'slot-letter' and empty cells 'slot-required'; every other cell
 *  of the row as outside the highlight (21-S14: was dull blue 'slot'). */
async function expectWord(page: Page, cursor: string, word: string[]) {
  for (const coord of ROW) {
    if (coord === cursor) continue;
    if (word.includes(coord)) {
      const state = STARS.includes(coord) ? 'slot-required' : 'slot-letter';
      await expect(cell(page, coord), `${coord} in the word`).toHaveAttribute('data-cell-state', state);
      expect(await bg(cell(page, coord)), `${coord} in the word`).toBe(BLUE_MEDIUM);
    } else {
      const [state, color] = STARS.includes(coord)
        ? ['symmetric-hint', WHITE]
        : [...BIRD, ...SOY].includes(coord)
          ? ['letter', WHITE]
          : ['empty', OFF];
      await expect(cell(page, coord), `${coord} outside the word`).toHaveAttribute('data-cell-state', state);
      expect(await bg(cell(page, coord)), `${coord} outside the word`).toBe(color);
    }
  }
}

test.describe('21-S8-3 the highlight takes in Preview-red cells', () => {
  test('cursor on Y: S and O blue-medium, everything else as outside', async ({ page }) => {
    await open(page);
    await cursorOn(page, '13,0');
    await expectWord(page, '13,0', SOY);
  });

  test('cursor on B: I, R, D and the two red cells blue-medium', async ({ page }) => {
    await open(page);
    await cursorOn(page, '3,0');
    await expectWord(page, '3,0', [...BIRD, ...STARS]);
  });

  test('cursor on a red cell: its word, BIRD and the other red cell', async ({ page }) => {
    await open(page);
    await cursorOn(page, '7,0');
    await expectWord(page, '7,0', [...BIRD, ...STARS]);
  });
});

test.describe('21-S8-4 only a complete word locks', () => {
  test('no button or outline on an incomplete word, from a letter or a red cell', async ({ page }) => {
    await open(page);
    for (const coord of ['4,0', '8,0']) {
      await cursorOn(page, coord);
      await page.waitForTimeout(3500);
      await expect(lockButton(page), `no button with the cursor on ${coord}`).toBeHidden();
      await expect(outlines(page)).toHaveCount(0);
    }
    await cursorOn(page, '12,0');
    await expect(lockButton(page)).toBeVisible({ timeout: 4000 });
    await expect(lockButton(page)).toHaveAccessibleName('Lock word');
  });

  test('filled in, the word locks whole, its ends the Preview-black cells', async ({ page }) => {
    await open(page);
    await cursorOn(page, '7,0');
    await page.keyboard.type('ER');
    await expect(cell(page, '8,0')).toContainText('R');

    await cursorOn(page, '4,0');
    await expect(lockButton(page)).toBeVisible({ timeout: 4000 });
    await lockButton(page).click();
    await expect(lockButton(page)).toHaveAccessibleName('Unlock word');
    await expect(ticks(page)).toHaveCount(2);

    // The outline runs from the end cell (2,0) to the end cell (9,0).
    await expect(outlines(page)).toHaveCount(1);
    const outline = (await outlines(page).boundingBox())!;
    const first = (await cell(page, '2,0').boundingBox())!;
    const last = (await cell(page, '9,0').boundingBox())!;
    expect(Math.abs(outline.x - first.x), 'the outline starts at (2,0)').toBeLessThanOrEqual(2);
    expect(Math.abs(outline.x + outline.width - (last.x + last.width)), 'the outline ends at (9,0)').toBeLessThanOrEqual(2);
  });

  test('narrow: the toggle row Lock Word is disabled on an incomplete word', async ({ page }) => {
    await open(page, { width: 600, height: 1000 });
    const control = page.getByTestId('lock-word-control');
    await cursorOn(page, '4,0');
    await expect(control).toHaveAttribute('aria-disabled', 'true');
    await cursorOn(page, '7,0');
    await expect(control).toHaveAttribute('aria-disabled', 'true');
    await cursorOn(page, '12,0');
    await expect(control).toHaveAttribute('aria-disabled', 'false');
    await expect(control).toHaveText('Lock Word');
  });
});
