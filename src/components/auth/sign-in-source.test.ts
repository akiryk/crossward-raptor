import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story 14-S1 — Sign-in and username, checked in the source.
//
// The front door and its form paint only through the redesign's tokens and
// head the page with a size-1 Title. The form and the auth hook share the
// rules in lib/username. The builder-name dialog, its two server actions and
// lib/display-name are gone. The rendered page is checked in the browser by
// e2e/sign-in.spec.ts.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../../', import.meta.url));

function source(path: string) {
  return readFileSync(join(SRC, path), 'utf8');
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

function sourceFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sourceFiles(path);
    return /\.(ts|tsx)$/.test(name) && !/\.test\.tsx?$/.test(name) ? [path] : [];
  });
}

const OLD_COLOR_TOKENS = [
  'background',
  'foreground',
  'ink-2',
  'ink-3',
  'rule',
  'rule-strong',
  'hover-tint',
  'panel-tint',
  'accent',
  'accent-hover',
  'ok-tint',
  'required',
  'recommended',
  'incomplete',
];

function expectRedesignTokensOnly(code: string, label: string) {
  expect(code, label).not.toMatch(/#[0-9a-f]{3,8}\b/i);
  expect(code, label).not.toMatch(/\b(rgb|rgba|hsl|hsla|oklch)\(/);
  expect(code, label).not.toMatch(/\b(text|bg|border)-(white|black)\b/);
  expect(code, label).not.toMatch(/\bring-/);
  expect(code, label).not.toMatch(/\brounded(-[\w[]+)?\b/);
  expect(code, label).not.toMatch(/\bshadow\b|\bshadow-/);
  expect(code, label).not.toMatch(/\bfont-display\b|\btext-(headline|body|help|xl|title)(?![\w-])/);
  expect(code, label).not.toMatch(/\btext-(xs|sm|base|lg|[2-9]xl)\b/);
  expect(code, label).not.toMatch(/\[font-weight:/);
  for (const name of OLD_COLOR_TOKENS) {
    expect(code, `${label}: ${name}`).not.toMatch(
      new RegExp(`(?:^|[\\s'"\`:])(?:text|bg|border)-${name}(?![\\w-])`),
    );
  }
}

describe('14-S1 sign-in source', () => {
  const page = withoutComments(source('app/page.tsx'));
  const form = withoutComments(source('components/auth/SignInForm.tsx'));

  it('the front door and the form use only the redesign tokens, and the page drops its p-6 markup', () => {
    expectRedesignTokensOnly(page, 'app/page.tsx');
    expectRedesignTokensOnly(form, 'SignInForm.tsx');
    expect(page).not.toMatch(/\bp-6\b/);
  });

  it('the heading is a size-1 Title', () => {
    const titles = Array.from(`${page}\n${form}`.matchAll(/<Title\b[^>]*>/g), (m) => m[0]);
    expect(titles.filter((tag) => /\bsize=\{1\}/.test(tag))).toHaveLength(1);
  });

  it('the form and the auth hook share the rules in lib/username', () => {
    expect(form).toMatch(/from ['"]@\/lib\/username['"]/);
    expect(withoutComments(source('lib/auth.ts'))).toMatch(/from ['"]@\/lib\/username['"]/);
  });

  it('the builder-name dialog, its actions and lib/display-name are gone', () => {
    expect(existsSync(join(SRC, 'components/puzzle/DisplayNameDialog.tsx'))).toBe(false);
    expect(existsSync(join(SRC, 'lib/display-name.ts'))).toBe(false);
    const actions = withoutComments(source('app/puzzles/actions.ts'));
    expect(actions).not.toMatch(/\bgetDisplayName\b/);
    expect(actions).not.toMatch(/\bsaveDisplayName\b/);
    const offenders = sourceFiles(SRC).filter((file) =>
      /\bDisplayNameDialog\b|lib\/display-name['"]/.test(withoutComments(readFileSync(file, 'utf8'))),
    );
    expect(offenders.map((file) => file.slice(SRC.length))).toEqual([]);
  });
});
