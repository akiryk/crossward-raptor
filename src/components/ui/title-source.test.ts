import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story F7 — Title, Logo and Masthead, checked in the source.
//
// Title, Logo and Masthead paint only through the redesign's tokens: no
// literal colors (the Logo's SVG included), no old color or type tokens, no
// focus ring, shadow or radius. The app header renders the Masthead, and
// Sign out is the Masthead's link-looking action rather than a Button. The
// rendered look is checked in the browser by e2e/masthead.spec.ts.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../../', import.meta.url));

function source(path: string) {
  return readFileSync(join(SRC, path), 'utf8');
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const OLD_COLOR_TOKENS = [
  'background',
  'foreground',
  'ink-2',
  'ink-3',
  'rule',
  'rule-strong',
  'hover-tint',
  'panel-tint',
  'accent',
  'accent-hover',
  'ok-tint',
  'required',
  'recommended',
  'incomplete',
];

function expectRedesignTokensOnly(code: string) {
  expect(code).not.toMatch(/#[0-9a-f]{3,8}\b/i);
  expect(code).not.toMatch(/\b(rgb|rgba|hsl|hsla|oklch)\(/);
  expect(code).not.toMatch(/\b(text|bg|border|fill|stroke)-(white|black)\b/);
  expect(code).not.toMatch(/\b(fill|stroke)=["'](?!none["'])/);
  expect(code).not.toMatch(/\bring-/);
  expect(code).not.toMatch(/\boutline-(?!none\b|hidden\b)[\w[]/);
  expect(code).not.toMatch(/\brounded(-[\w[]+)?\b/);
  expect(code).not.toMatch(/\bshadow\b|\bshadow-/);
  expect(code).not.toMatch(/\bfont-display\b|\btext-(headline|body|help|xl|title)(?![\w-])/);
  expect(code).not.toMatch(/\[font-weight:/);
  for (const name of OLD_COLOR_TOKENS) {
    expect(code, name).not.toMatch(new RegExp(`(?:^|[\\s'"\`:])(?:text|bg|border|fill|stroke)-${name}(?![\\w-])`));
  }
}

function expectUtilities(code: string, utilities: string[]) {
  for (const utility of utilities) expect(code, utility).toContain(utility);
}

describe('F7 Title, Logo and Masthead source', () => {
  it('Title uses only the redesign tokens and maps every title and text color style', () => {
    const code = withoutComments(source('components/ui/Title.tsx'));
    expectRedesignTokensOnly(code);
    expectUtilities(code, [
      'text-title-1',
      'text-title-2',
      'text-title-3',
      'text-title-4',
      'text-primary',
      'text-muted',
      'text-link-muted',
      'text-highlight',
      'text-error',
      'text-subtle',
      'text-inverse',
    ]);
  });

  it('Logo uses only the redesign tokens, with the logo styles on its cells and letters', () => {
    const code = withoutComments(source('components/ui/Logo.tsx'));
    expectRedesignTokensOnly(code);
    expectUtilities(code, [
      'fill-logo-cell',
      'stroke-logo',
      'fill-logo',
      'stroke-button-hover',
      'fill-button-hover',
      'data-logo-cell',
      'data-logo-letter',
    ]);
  });

  it('Masthead uses only the redesign tokens', () => {
    const code = withoutComments(source('components/layout/Masthead.tsx'));
    expectRedesignTokensOnly(code);
    expectUtilities(code, [
      'bg-masthead',
      'border-line-muted',
      'text-body-large',
      'text-link-muted',
      'text-button-hover',
      'MastheadAction',
    ]);
  });

  it('the app header renders the Masthead, and Sign out is a MastheadAction, not a Button', () => {
    const header = withoutComments(source('components/layout/Header.tsx'));
    expectRedesignTokensOnly(header);
    expect(header).toMatch(/<Masthead\b/);
    const signOut = withoutComments(source('components/auth/SignOutButton.tsx'));
    expect(signOut).toMatch(/<MastheadAction\b/);
    expect(signOut).not.toMatch(/<Button\b/);
  });
});
