import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ComponentProps } from 'react';
import { describe, expect, expectTypeOf, it } from 'vitest';
import type { Modal } from './Modal';

// Story 23-S4 — the Modal's header option, checked in the source and types.
//
// The Modal gains `headerVariant`, a small named set: 'default' (the yellow
// `modal-title-background`, as every existing modal) and 'gray'
// (`modal-title-background-gray`, gray-200). It is not a color value: no
// other string type-checks (the type assertion below is enforced by
// `tsc --noEmit`, part of `npm run verify`). The title keeps `title-3` and
// `primary` in both. Only Account details passes it, as 'gray'; every other
// modal is unchanged. The rendered look is checked in the browser by
// e2e/account-details.spec.ts. Do not edit this file to match an
// implementation.

const SRC = fileURLToPath(new URL('../../', import.meta.url));

function source(path: string) {
  return readFileSync(join(SRC, path), 'utf8');
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

function sourceFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sourceFiles(path);
    return /\.tsx?$/.test(name) && !/\.test\.tsx?$/.test(name) ? [path] : [];
  });
}

describe('23-S4-U5 the header option', () => {
  it('is typed as the named set default | gray, optional', () => {
    expectTypeOf<ComponentProps<typeof Modal>['headerVariant']>().toEqualTypeOf<'default' | 'gray' | undefined>();
  });

  it('Modal paints each option with its own token and keeps the title style', () => {
    const code = withoutComments(source('components/ui/Modal.tsx'));
    expect(code).toMatch(/\bheaderVariant\b/);
    expect(code).toMatch(/\bbg-modal-title-background-gray\b/);
    expect(code).toMatch(/\bbg-modal-title-background(?![\w-])/);
    expect(code).toMatch(/\btext-title-3 text-primary\b/);
  });

  it('globals.css declares the gray header token', () => {
    const css = source('app/globals.css').replace(/\/\*[\s\S]*?\*\//g, '');
    expect(css).toMatch(/--color-modal-title-background-gray\s*:\s*var\(--palette-gray-200\)\s*;/);
  });

  it('only Account details passes headerVariant, and it passes "gray"', () => {
    const users = sourceFiles(SRC)
      .map((path) => [relative(SRC, path), withoutComments(readFileSync(path, 'utf8'))] as const)
      .filter(([path, code]) => path !== 'components/ui/Modal.tsx' && /\bheaderVariant\b/.test(code));
    expect(users.length, 'one user of headerVariant').toBe(1);
    const [, code] = users[0];
    expect(code).toMatch(/headerVariant=["{']+gray["}']+/);
    expect(code).not.toMatch(/headerVariant=["{']+default["}']+/);
    expect(code).toMatch(/title=["{']+Account details["}']+/);
  });
});
