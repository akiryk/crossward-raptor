import { readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story 22-S4 — One tooltip behavior, checked in the source.
//
// Every tooltip is the shared Tooltip (components/ui/Tooltip.tsx), which
// alone owns when it shows (the hover delay and the skip delay), where and
// how it looks. So: only Tooltip.tsx renders role="tooltip"; no other file
// that mentions a tooltip keeps a timer, a tooltip delay constant or a
// delay prop on <Tooltip>; and no element uses the browser's native
// `title` tooltip, which would show on its own timing.
// The behavior is checked in the browser by e2e/tooltips.spec.ts.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../../', import.meta.url));
const TOOLTIP = 'components/ui/Tooltip.tsx';

function runtimeFiles(dir = SRC): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return runtimeFiles(path);
    return /\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : [];
  });
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const files = runtimeFiles().map((path) => ({
  name: relative(SRC, path).split('\\').join('/'),
  code: withoutComments(readFileSync(path, 'utf8')),
}));

describe('22-S4 one tooltip', () => {
  it('22-S4-13a only Tooltip.tsx renders role="tooltip"', () => {
    const roles = files.filter(({ code }) => /role\s*[=:]\s*\{?\s*['"]tooltip['"]/.test(code)).map(({ name }) => name);
    expect(roles).toEqual([TOOLTIP]);
  });

  it('22-S4-13b outside the tooltip module, nothing that mentions a tooltip keeps a timer or a delay', () => {
    // The tooltip modules: Tooltip.tsx and any hook or helper beside it.
    const isTooltipModule = (name: string) => /^components\/ui\/[^/]*tooltip[^/]*\.tsx?$/i.test(name);
    const mentioning = files.filter(({ name, code }) => !isTooltipModule(name) && /tool ?tip/i.test(code));
    for (const { name, code } of mentioning) {
      expect(code, `${name}: no setTimeout`).not.toMatch(/\bsetTimeout\s*\(/);
      expect(code, `${name}: no setInterval`).not.toMatch(/\bsetInterval\s*\(/);
      expect(code, `${name}: no tooltip delay constant`).not.toMatch(/\b\w*TOOLTIP\w*_MS\b/);
      expect(code, `${name}: no delay prop on a Tooltip`).not.toMatch(/<Tooltip\b[^>]*\b\w*[Dd]elay\w*=/);
    }
    // The callers: the grid (Preview cells, the lock button) and the bar's file.
    const callers = mentioning
      .filter(({ code }) => /from\s*['"][^'"]*\/[\w-]*tooltip[\w-]*['"]/i.test(code))
      .map(({ name }) => name);
    expect(callers).toContain('components/grid/PuzzleGrid.tsx');
    expect(callers.length, `callers: ${callers.join(', ')}`).toBeGreaterThanOrEqual(2);
  });

  it('22-S4-13c no element uses the native title tooltip (pass today)', () => {
    for (const { name, code } of files.filter(({ name }) => name.endsWith('.tsx'))) {
      expect(code, `${name}: an HTML element with a title attribute`).not.toMatch(/<[a-z][\w-]*\b[^>]*\stitle=/);
      expect(code, `${name}: an SVG <title>`).not.toMatch(/<title\b/);
    }
  });
});
