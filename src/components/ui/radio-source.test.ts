import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story F6 — Preview toggle and Radio, checked in the source.
//
// The Preview toggle and the Radio paint only through the redesign's
// tokens: no literal colors, no old color or type tokens, no focus ring and
// only the pill radius. The new-puzzle size picker is a Radio rather than
// hand-written radio inputs. The rendered look is checked in the browser by
// e2e/toggle-radio.spec.ts. Corrected 2026-10-24 for the smaller label
// styles and the toggle's on label.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../../', import.meta.url));

function source(path: string) {
  return readFileSync(join(SRC, path), 'utf8');
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const OLD_COLOR_TOKENS = [
  'background',
  'foreground',
  'ink-2',
  'ink-3',
  'rule',
  'rule-strong',
  'hover-tint',
  'panel-tint',
  'accent',
  'accent-hover',
  'ok-tint',
  'required',
  'recommended',
  'incomplete',
];

function expectRedesignTokensOnly(code: string) {
  expect(code).not.toMatch(/#[0-9a-f]{3,8}\b/i);
  expect(code).not.toMatch(/\b(rgb|rgba|hsl|hsla|oklch)\(/);
  expect(code).not.toMatch(/\b(text|bg|border)-(white|black)\b/);
  expect(code).not.toMatch(/\bring-/);
  expect(code).not.toMatch(/\boutline-(?!none\b|hidden\b)[\w[]/);
  expect(code).not.toMatch(/\brounded(?!-pill\b)(-[\w[]+)?\b/);
  expect(code).not.toMatch(/\bshadow\b|\bshadow-/);
  expect(code).not.toMatch(/\bfont-display\b|\btext-(headline|body|help)(?![\w-])/);
  expect(code).not.toMatch(/\[font-weight:/);
  for (const name of OLD_COLOR_TOKENS) {
    expect(code, name).not.toMatch(new RegExp(`(?:^|[\\s'"\`:])(?:text|bg|border)-${name}(?![\\w-])`));
  }
}

describe('F6 Preview toggle and Radio source', () => {
  it('PreviewToggle uses only the redesign tokens', () => {
    const code = withoutComments(source('components/grid/PreviewToggle.tsx'));
    expectRedesignTokensOnly(code);
    for (const utility of [
      'rounded-pill',
      'bg-button-fill',
      'bg-button-active',
      'bg-button-hover',
      'border-button-fill',
      'border-button-active',
      'border-button-hover',
      'bg-inverse',
      'text-label',
      'text-link-muted',
      'text-button-active',
    ]) {
      expect(code, utility).toContain(utility);
    }
  });

  it('Radio uses only the redesign tokens', () => {
    const code = withoutComments(source('components/ui/Radio.tsx'));
    expectRedesignTokensOnly(code);
    for (const utility of [
      'rounded-pill',
      'border-2',
      'border-line-dark',
      'border-link-muted',
      'border-button-active',
      'border-button-hover',
      'bg-button-active',
      'bg-button-hover',
      'text-body-normal',
      'text-primary',
      'text-title-4',
      'text-button-active',
      'text-link-muted',
      'text-button-hover',
    ]) {
      expect(code, utility).toContain(utility);
    }
  });

  it('the new-puzzle size picker is a RadioGroup, not hand-written radio inputs', () => {
    const code = withoutComments(source('components/puzzle/NewPuzzleDialog.tsx'));
    expect(code).toMatch(/<RadioGroup\b[\s\S]*?data-testid="new-puzzle-size"/);
    expect(code).not.toMatch(/type="radio"/);
    expect(code).not.toMatch(/role="radiogroup"/);
  });
});
