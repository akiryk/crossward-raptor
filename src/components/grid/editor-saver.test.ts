// 24-S5 acceptance: the editor's saver (`EditorSaver`) when the server moves
// on underneath it. Runs in Node with the page's globals stubbed (document,
// window, localStorage, fetch), fake timers, and the commit action mocked.
//
// - 24-S5-9 (carried from the S4 review): the half-typed word is sent as an
//   operation of the state it was made in before another tab's Start Over
//   or Enter Hints is applied, so the server judges it.
// - 24-S5-10: losing access (removal, deletion, publication) stops the
//   polling and the queue for good, explains, and keeps the unsaved input
//   copyable; the editor's own Publish is not a loss.
// - 24-S5-11: a lost session isn't retried; the work stays journaled.
//
// Do not edit this file to match an implementation.
