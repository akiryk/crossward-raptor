const PUZZLE = 'p1';
const REMOVED = 'This puzzle is no longer available to you: it was deleted, or you were removed from it. Nothing more can be saved here.';
const PUBLISHED = "This puzzle was published, so it can't be edited any more.";

// --- the page's globals --------------------------------------------------

type Listener = (event: unknown) => void;
let store: Map<string, string>;
let fetchMock: ReturnType<typeof vi.fn>;
function listeners() {
  const map = new Map<string, Listener[]>();
  return {
    addEventListener: (type: string, listener: Listener) => map.set(type, [...(map.get(type) ?? []), listener]),
    removeEventListener: (type: string, listener: Listener) => map.set(type, (map.get(type) ?? []).filter((l) => l !== listener)),
  };
}
beforeEach(() => {
  vi.useFakeTimers();
  mocks.commit.mockReset();
  store = new Map();
  fetchMock = vi.fn();
  vi.stubGlobal('document', { visibilityState: 'visible', ...listeners() });
  vi.stubGlobal('window', {
    ...listeners(),
    localStorage: {
      get length() { return store.size; },
      key: (index: number) => [...store.keys()][index] ?? null,
      getItem: (key: string) => store.get(key) ?? null,
      setItem: (key: string, value: string) => { store.set(key, value); },
      removeItem: (key: string) => { store.delete(key); },
    },
  });
  vi.stubGlobal('fetch', fetchMock);
});
afterEach(() => {
  vi.useRealTimers();
  vi.unstubAllGlobals();
});

// --- answers ---------------------------------------------------------------

function deferred<T>() {
  let resolve!: (value: T) => void;
  const promise = new Promise<T>((done) => { resolve = done; });
  return { promise, resolve };
}
const answer = (status: number, body: unknown) => ({ status, type: 'basic', ok: status < 300, json: async () => body });
const redirected = () => ({ status: 0, type: 'opaqueredirect', ok: false, json: async () => { throw new Error('opaque'); } });
const idle = () => answer(200, { status: 'ops', ops: [] });
/** Lets every pending answer and what it starts run, without moving time. */
async function settle() {
  for (let round = 0; round < 10; round++) await vi.advanceTimersByTimeAsync(0);
}
const journalKeys = () => [...store.keys()].filter((key) => key.startsWith(`crossward:journal:v1:${PUZZLE}:`));

// --- the editor ------------------------------------------------------------

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
const start = letters(createGrid({ cols: 5, rows: 5 }), [[0, 0, 'C'], [1, 0, 'A'], [2, 0, 'T']]);
const content: PuzzleContent = { grid: serializeGrid(start), hints: {}, title: 'Shared', phase: 'grid' };

function editor(options: { published?: boolean } = {}) {
  const notes: { id: string; message: string; input: string | null }[] = [];
  const losses: AccessLoss[] = [];
  let signedOut = 0;
  let view: SavedView = {
    grid: start, lockedWords: [], cursor: { current: { col: 0, row: 2 }, orientation: 'across' },
    phase: 'grid', hints: {}, title: 'Shared',
  };
  const saver: EditorSaver = new EditorSaver({
    puzzleId: PUZZLE,
    initialContent: content,
    initialVersion: 0,
    initialEpoch: 0,
    view,
    published: options.published,
    onChange: () => undefined,
    showContent: (update) => {
      const next = update(viewContent(view));
      const grid = deserializeGrid(next.grid);
      view = { ...view, grid, lockedWords: deserializeLockedWords(next.grid), phase: next.phase, hints: next.hints, title: next.title };
      saver.setView(view);
    },
    notify: (id, notice) => notes.push({ id, ...notice }),
    onAccessLost: (loss) => losses.push(loss),
    onSignedOut: () => { signedOut++; },
  });
  /** Types letters into the grid (the burst stays open: no timers run). */
  const type = (entries: Array<[number, number, string]>, cursor: CursorState['current']) => {
    view = { ...view, grid: letters(view.grid, entries), cursor: { current: cursor, orientation: 'across' } };
    saver.setView(view);
    saver.gridChanged(view.grid, view.cursor);
  };
  return { saver, notes, losses, type, view: () => view, signedOut: () => signedOut };
}
const sent = (): Operation[] => mocks.commit.mock.calls.map(([op]) => op as Operation);
const committed = (op: Record<string, unknown>, version: number) => ({
  opId: crypto.randomUUID(), puzzleId: PUZZLE, clientId: 'other-tab', epoch: 0, baseVersion: version - 1, ...op, version,
});

describe('24-S5-9 the half-typed word before another tab’s reset', () => {
  it('is sent as an operation of the epoch it was made in before a remote Start Over, and its refusal explained with the input', async () => {
    const first = deferred<unknown>();
    fetchMock.mockReturnValueOnce(first.promise).mockResolvedValue(idle());
    const refusal = deferred<unknown>();
    mocks.commit.mockReturnValueOnce(refusal.promise);
    const { saver, notes, type } = editor();
    saver.attachPage();
    type([[0, 2, 'D'], [1, 2, 'O']], { col: 2, row: 2 });
    expect(mocks.commit).not.toHaveBeenCalled();

    first.resolve(answer(200, { status: 'ops', ops: [committed({ kind: 'startOver', keepLockedWords: false }, 1)] }));
    await settle();

    expect(sent()).toHaveLength(1);
    expect(sent()[0]).toMatchObject({ kind: 'cells', epoch: 0, baseVersion: 0, writes: [{ col: 0, row: 2, value: 'D' }, { col: 1, row: 2, value: 'O' }] });
    refusal.resolve({ status: 'refused', opId: sent()[0].opId, code: 'epoch' });
    await settle();
    expect(notes).toEqual([expect.objectContaining({ input: 'DO', message: expect.stringMatching(/^Your DO in .+ wasn't saved: the puzzle was started over\.$/) })]);
  });

  it('is sent against the version it was made against before a remote Enter Hints', async () => {
    const first = deferred<unknown>();
    fetchMock.mockReturnValueOnce(first.promise).mockResolvedValue(idle());
    mocks.commit.mockImplementation(async (op: Operation) => ({ status: 'refused', opId: op.opId, code: 'phase' }));
    const { saver, type } = editor();
    saver.attachPage();
    type([[0, 2, 'D'], [1, 2, 'O']], { col: 2, row: 2 });

    first.resolve(answer(200, { status: 'ops', ops: [committed({ kind: 'enterHints' }, 1)] }));
    await settle();

    expect(sent()[0]).toMatchObject({ kind: 'cells', epoch: 0, baseVersion: 0 });
  });

  it('likewise when the reset arrives as the stored puzzle (past the log’s retention)', async () => {
    const first = deferred<unknown>();
    fetchMock.mockReturnValueOnce(first.promise).mockResolvedValue(idle());
    mocks.commit.mockImplementation(async (op: Operation) => ({ status: 'refused', opId: op.opId, code: 'epoch' }));
    const { saver, type } = editor();
    saver.attachPage();
    type([[0, 2, 'D'], [1, 2, 'O']], { col: 2, row: 2 });

    first.resolve(answer(200, { status: 'snapshot', version: 7, resetEpoch: 1, content }));
    await settle();

    expect(sent()[0]).toMatchObject({ kind: 'cells', epoch: 0, baseVersion: 0 });
  });
});

describe('24-S5-10 losing access while open', () => {
  it('a catch-up not-found stops the polling and the queue for good, explains, and keeps every unsaved input', async () => {
    const first = deferred<unknown>();
    fetchMock.mockReturnValueOnce(first.promise).mockResolvedValue(idle());
    mocks.commit.mockReturnValue(new Promise(() => undefined));
    const { saver, notes, losses, type } = editor();
    saver.attachPage();
    type([[0, 4, 'X']], { col: 1, row: 4 });
    saver.flushGrid();
    expect(sent()).toHaveLength(1);
    type([[4, 4, 'Q']], { col: 4, row: 4 });
    expect(journalKeys()).toHaveLength(1);

    first.resolve(answer(404, { status: 'not-found' }));
    await settle();

    expect(losses).toEqual([{ kind: 'removed' }]);
    expect(notes[0]).toEqual({ id: expect.any(String), message: REMOVED, input: null });
    const dropped = notes.slice(1);
    expect(dropped.every((note) => /wasn't saved: this puzzle is no longer available\.$/.test(note.message))).toBe(true);
    expect(dropped.some((note) => note.input?.includes('X'))).toBe(true);
    expect(dropped.some((note) => note.input?.includes('Q'))).toBe(true);
    expect(journalKeys()).toEqual([]);

    saver.add({ kind: 'title', title: 'After' });
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(1);
    expect(sent()).toHaveLength(1);
    expect(losses).toHaveLength(1);
  });

  it('a catch-up 400 is read, not retried: the same loss', async () => {
    fetchMock.mockResolvedValueOnce(answer(400, { status: 'invalid' })).mockResolvedValue(idle());
    const { saver, losses, notes } = editor();
    saver.attachPage();
    await settle();
    expect(losses).toEqual([{ kind: 'removed' }]);
    expect(notes.map((note) => note.message)).toEqual([REMOVED]);
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });

  it('a commit not-found is the same loss: the rest isn’t sent, the polling stops', async () => {
    fetchMock.mockResolvedValue(idle());
    const { saver, notes, losses, type } = editor();
    mocks.commit.mockImplementation(async () => ({ status: 'not-found' }));
    saver.attachPage();
    await settle();
    type([[0, 4, 'X']], { col: 1, row: 4 });
    saver.flushGrid();
    saver.add({ kind: 'title', title: 'Queued' });
    await settle();

    expect(losses).toEqual([{ kind: 'removed' }]);
    expect(sent()).toHaveLength(1);
    expect(notes.map((note) => note.message)).toContain(REMOVED);
    expect(notes.some((note) => note.input === 'Queued')).toBe(true);
    const polls = fetchMock.mock.calls.length;
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(polls);
    expect(sent()).toHaveLength(1);
    expect(journalKeys()).toEqual([]);
  });

  it('a catch-up published shows the stored puzzle, reports the publication, and stops', async () => {
    const stored = { ...content, title: 'Done' };
    fetchMock.mockResolvedValueOnce(answer(200, {
      status: 'published', version: 3, resetEpoch: 0, content: stored,
      publishedAt: '2026-11-13T10:00:00.000Z', visibility: 'public',
    })).mockResolvedValue(idle());
    const { saver, losses, notes, view } = editor();
    saver.attachPage();
    await settle();

    expect(losses).toEqual([{ kind: 'published', publishedAt: new Date('2026-11-13T10:00:00.000Z'), visibility: 'public' }]);
    expect(notes.map((note) => note.message)).toEqual([PUBLISHED]);
    expect(view().title).toBe('Done');
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });

  it('a commit refused as published stops the queue and asks the catch-up at once', async () => {
    const stored = { ...content, title: 'Done' };
    fetchMock.mockResolvedValueOnce(idle()).mockResolvedValueOnce(answer(200, {
      status: 'published', version: 1, resetEpoch: 0, content: stored, publishedAt: '2026-11-13T10:00:00.000Z', visibility: 'private',
    })).mockResolvedValue(idle());
    mocks.commit.mockImplementation(async (op: Operation) => ({ status: 'refused', opId: op.opId, code: 'published' }));
    const { saver, losses, notes } = editor();
    saver.attachPage();
    await settle();
    saver.add({ kind: 'title', title: 'First' });
    saver.add({ kind: 'title', title: 'Second' });
    await settle();

    expect(sent()).toHaveLength(1);
    expect(notes.filter((note) => note.input === 'First' || note.input === 'Second')).toHaveLength(2);
    expect(notes.every((note) => note.input === null || /wasn't saved: the puzzle was published\.$/.test(note.message))).toBe(true);
    expect(fetchMock).toHaveBeenCalledTimes(2);
    expect(losses).toEqual([{ kind: 'published', publishedAt: new Date('2026-11-13T10:00:00.000Z'), visibility: 'private' }]);
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(2);
    expect(sent()).toHaveLength(1);
  });

  it('the editor’s own Publish is not a loss; once published, it stops quietly', async () => {
    const own = answer(200, {
      status: 'published', version: 0, resetEpoch: 0, content, publishedAt: '2026-11-13T10:00:00.000Z', visibility: 'private',
    });
    fetchMock.mockResolvedValueOnce(idle()).mockResolvedValue(own);
    const { saver, losses, notes } = editor();
    saver.attachPage();
    await settle();
    saver.beginPublish();
    await vi.advanceTimersByTimeAsync(3_500);
    expect(losses).toEqual([]);
    saver.endPublish(true);
    const polls = fetchMock.mock.calls.length;
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(polls);
    expect(losses).toEqual([]);
    expect(notes).toEqual([]);
  });

  it('an editor opened on a published puzzle doesn’t poll', async () => {
    fetchMock.mockResolvedValue(idle());
    const { saver } = editor({ published: true });
    saver.attachPage();
    await vi.advanceTimersByTimeAsync(10_000);
    expect(fetchMock).not.toHaveBeenCalled();
  });
});

describe('24-S5-11 a lost session', () => {
  it('a redirected catch-up isn’t retried; the work stays journaled and the page is told once', async () => {
    const first = deferred<unknown>();
    fetchMock.mockReturnValueOnce(first.promise).mockResolvedValue(idle());
    mocks.commit.mockReturnValue(new Promise(() => undefined));
    const { saver, notes, losses, type, signedOut } = editor();
    saver.attachPage();
    type([[0, 4, 'X']], { col: 1, row: 4 });
    saver.flushGrid();
    type([[4, 4, 'Q']], { col: 4, row: 4 });

    first.resolve(redirected());
    await settle();

    expect(signedOut()).toBe(1);
    expect(losses).toEqual([]);
    expect(notes).toEqual([]);
    const journaled = journalKeys().map((key) => store.get(key) ?? '').join('');
    expect(journaled).toContain(sent()[0].opId);
    expect(journaled).toContain('"Q"');
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock).toHaveBeenCalledTimes(1);
    expect(sent()).toHaveLength(1);
    expect(signedOut()).toBe(1);
  });
});
