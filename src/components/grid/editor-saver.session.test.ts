// 24-S7 acceptance: the saver's session. The catch-up asks as this tab
// (`x-client-id`), so it is also the heartbeat; who is present becomes join
// notes; another account's edit replacing my acknowledged burst is reported
// as an outline and a note without touching the cursor; another account's
// Enter Hints and Start Over are noted, my own account's aren't; hiding the
// page marks the tab away and leaving it says so, and once access is lost
// nothing more is sent. Runs in Node with the page's globals stubbed
// (document, window, localStorage, fetch), fake timers, and the commit
// action mocked, against a small fake server. Do not edit this file to match
// an implementation.
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { createGrid, withLetter, type Coord, type Grid } from '../../engine/grid';
import type { CursorState } from '../../engine/cursor';
import { deserializeGrid, deserializeLockedWords, serializeGrid } from '../../lib/puzzle-storage';
import type { PuzzleContent } from '../../lib/collab/apply';
import type { Operation, OperationBody } from '../../lib/collab/operation';

const mocks = vi.hoisted(() => ({ commit: vi.fn() }));
vi.mock('../../app/puzzles/actions', () => ({ commitOperation: mocks.commit }));

import { EditorSaver, viewContent, type SavedView } from './editor-saver';

const PUZZLE = 'p1';
const jay = { userId: 'jay', username: 'Jay' };
const adam = { userId: 'adam', username: 'Adam' };

// --- the page's globals --------------------------------------------------

type Listener = (event: unknown) => void;
function target() {
  const map = new Map<string, Listener[]>();
  return {
    addEventListener: (type: string, listener: Listener) => map.set(type, [...(map.get(type) ?? []), listener]),
    removeEventListener: (type: string, listener: Listener) => map.set(type, (map.get(type) ?? []).filter((l) => l !== listener)),
    dispatch: (type: string) => (map.get(type) ?? []).forEach((listener) => listener({ type, preventDefault: () => undefined })),
  };
}
let doc: ReturnType<typeof target> & { visibilityState: string };
let win: ReturnType<typeof target>;
let fetchMock: ReturnType<typeof vi.fn>;

// --- a small server ----------------------------------------------------------

interface Committed { op: Operation; version: number; author: { userId: string; username: string } }
let log: Committed[];
let present: { userId: string; username: string | null }[];
let lost: boolean;
const answer = (status: number, body: unknown) => ({ status, type: 'basic', ok: status < 300, json: async () => body });

beforeEach(() => {
  vi.useFakeTimers();
  log = [];
  present = [];
  lost = false;
  mocks.commit.mockReset();
  mocks.commit.mockImplementation(async (op: Operation) => {
    log.push({ op, version: log.length + 1, author: adam });
    return { status: 'accepted', opId: op.opId, version: log.length };
  });
  const store = new Map<string, string>();
  doc = Object.assign(target(), { visibilityState: 'visible' });
  win = target();
  vi.stubGlobal('document', doc);
  vi.stubGlobal('window', {
    ...win,
    localStorage: {
      get length() { return store.size; },
      key: (index: number) => [...store.keys()][index] ?? null,
      getItem: (key: string) => store.get(key) ?? null,
      setItem: (key: string, value: string) => { store.set(key, value); },
      removeItem: (key: string) => { store.delete(key); },
    },
  });
  fetchMock = vi.fn(async (url: string, init: { method?: string; headers?: Record<string, string> } = {}) => {
    if ((init.method ?? 'GET') !== 'GET') return answer(200, { status: 'ok' });
    if (lost) return answer(404, { status: 'not-found' });
    const since = Number(init.headers?.['x-catch-up-since'] ?? 0);
    const fresh = log.filter((entry) => entry.version > since);
    const body: Record<string, unknown> = { status: 'ops', ops: fresh.map(({ op, version }) => ({ ...op, version })), present };
    if (fresh.length > 0) body.authors = Object.fromEntries(fresh.map(({ op, author }) => [op.opId, author]));
    return answer(200, body);
  });
  vi.stubGlobal('fetch', fetchMock);
});
afterEach(() => {
  vi.useRealTimers();
  vi.unstubAllGlobals();
});

async function settle() {
  for (let round = 0; round < 10; round++) await vi.advanceTimersByTimeAsync(0);
}
/** Commits an operation as another builder (or another tab of mine). */
function commitElsewhere(body: OperationBody, author: { userId: string; username: string }): Operation {
  const epoch = log.filter((entry) => entry.op.kind === 'startOver').length;
  const op = { opId: `else-${log.length}`, puzzleId: PUZZLE, clientId: 'elsewhere', epoch, baseVersion: log.length, ...body } as Operation;
  log.push({ op, version: log.length + 1, author });
  return op;
}
const catchUps = () => fetchMock.mock.calls.filter(([url, init]) => String(url).endsWith('/operations') && (init?.method ?? 'GET') === 'GET');
const presencePosts = () => fetchMock.mock.calls
  .filter(([url]) => String(url) === `/api/puzzles/${PUZZLE}/presence`)
  .map(([, init]) => ({ keepalive: init?.keepalive, method: init?.method, body: JSON.parse(String(init?.body)) }));

// --- the editor ------------------------------------------------------------

function letters(grid: Grid, entries: Array<[number, number, string]>): Grid {
  return entries.reduce((next, [col, row, letter]) => withLetter(next, { col, row }, letter), grid);
}
// A 7×7 in Build: ABRAHAM in 1-Across; its M starts 2-Down.
const start = letters(createGrid({ cols: 7, rows: 7 }), [...'ABRAHAM'].map((letter, col) => [col, 0, letter] as [number, number, string]));
const content: PuzzleContent = { grid: serializeGrid(start), hints: {}, title: 'Shared', phase: 'grid' };

function editor() {
  const notes: string[] = [];
  const conflicts: unknown[] = [];
  let view: SavedView = {
    grid: start, lockedWords: [], cursor: { current: { col: 6, row: 0 }, orientation: 'down' },
    phase: 'grid', hints: {}, title: 'Shared',
  };
  const saver: EditorSaver = new EditorSaver({
    puzzleId: PUZZLE,
    userId: 'adam',
    initialContent: content,
    initialVersion: 0,
    initialEpoch: 0,
    view,
    onChange: () => undefined,
    showContent: (update) => {
      const next = update(viewContent(view));
      view = { ...view, grid: deserializeGrid(next.grid), lockedWords: deserializeLockedWords(next.grid), phase: next.phase, hints: next.hints, title: next.title };
      saver.setView(view);
    },
    notify: () => undefined,
    onAccessLost: () => undefined,
    onSignedOut: () => undefined,
    onSessionNote: (text) => notes.push(text),
    onConflict: (conflict) => conflicts.push(conflict),
  });
  const type = (entries: Array<[number, number, string]>, cursor: CursorState) => {
    view = { ...view, grid: letters(view.grid, entries), cursor };
    saver.setView(view);
    saver.gridChanged(view.grid, view.cursor);
    saver.cursorMoved(view.cursor);
  };
  return { saver, notes, conflicts, type, view: () => view };
}
const column = (col: number, from: number, to: number): Coord[] =>
  Array.from({ length: to - from + 1 }, (_, index) => ({ col, row: from + index }));

describe('24-S7-5 the saver’s session', () => {
  it('asks as this tab, and who is present becomes join notes', async () => {
    present = [jay];
    const { saver, notes } = editor();
    saver.attachPage();
    await settle();
    expect(catchUps()[0][1].headers['x-client-id']).toBe(saver.clientId);
    expect(notes).toEqual(['You joined. Jay is here.']);
    present = [jay, { userId: 'kim', username: 'Kim' }];
    await vi.advanceTimersByTimeAsync(1100);
    expect(notes).toEqual(['You joined. Jay is here.', 'Kim joined the session.']);
  });

  it('Jay’s MAGIC over my acknowledged MASKS: the outline and the note, the cursor untouched', async () => {
    present = [jay];
    const { saver, notes, conflicts, type, view } = editor();
    saver.attachPage();
    await settle();
    const last: CursorState = { current: { col: 6, row: 4 }, orientation: 'down' };
    type([[6, 1, 'A'], [6, 2, 'S'], [6, 3, 'K'], [6, 4, 'S']], last);
    saver.flushGrid();
    await settle();
    await vi.advanceTimersByTimeAsync(1100);
    expect(conflicts).toEqual([]);
    expect(notes).toEqual(['You joined. Jay is here.']);

    commitElsewhere({ kind: 'cells', writes: [{ col: 6, row: 2, value: 'G' }, { col: 6, row: 3, value: 'I' }, { col: 6, row: 4, value: 'C' }] }, jay);
    await vi.advanceTimersByTimeAsync(1100);
    expect(conflicts).toEqual([{ cells: column(6, 0, 4) }]);
    expect(notes.at(-1)).toBe('Jay changed 2-Down from MASKS to MAGIC.');
    expect(serializeGrid(view().grid).cells.map((row) => row[6]).slice(0, 5).map((cell) => cell.kind === 'active' ? cell.letter : '#').join(''))
      .toBe('MAGIC');
    expect(view().cursor).toEqual(last);
  });

  it('a remote edit to cells I didn’t just write is silent', async () => {
    const { saver, notes, conflicts } = editor();
    saver.attachPage();
    await settle();
    commitElsewhere({ kind: 'cells', writes: [{ col: 2, row: 3, value: 'Q' }] }, jay);
    await vi.advanceTimersByTimeAsync(1100);
    expect(conflicts).toEqual([]);
    expect(notes).toEqual([]);
  });

  it('another account’s Enter Hints and Start Over are noted; my own account’s are not', async () => {
    const { saver, notes } = editor();
    saver.attachPage();
    await settle();
    commitElsewhere({ kind: 'startOver', keepLockedWords: false }, adam);
    await vi.advanceTimersByTimeAsync(1100);
    expect(notes).toEqual([]);
    commitElsewhere({ kind: 'startOver', keepLockedWords: false }, jay);
    await vi.advanceTimersByTimeAsync(1100);
    expect(notes).toEqual(['Jay started over.']);
  });

  it('Enter Hints by another builder is noted', async () => {
    const { saver, notes } = editor();
    saver.attachPage();
    await settle();
    commitElsewhere({ kind: 'enterHints' }, jay);
    await vi.advanceTimersByTimeAsync(1100);
    expect(notes).toEqual(['Jay moved the puzzle to Create Hints.']);
  });

  it('hidden marks the tab away, pagehide says it left (keepalive); after a loss nothing more is sent', async () => {
    const { saver } = editor();
    const detach = saver.attachPage();
    await settle();
    doc.visibilityState = 'hidden';
    doc.dispatch('visibilitychange');
    win.dispatch('pagehide');
    await settle();
    expect(presencePosts()).toEqual([
      { keepalive: true, method: 'POST', body: { clientId: saver.clientId, state: 'away' } },
      { keepalive: true, method: 'POST', body: { clientId: saver.clientId, state: 'leave' } },
    ]);

    detach();
    doc.visibilityState = 'visible';
    const second = editor();
    second.saver.attachPage();
    await settle();
    lost = true;
    await vi.advanceTimersByTimeAsync(1100);
    const calls = fetchMock.mock.calls.length;
    doc.visibilityState = 'hidden';
    doc.dispatch('visibilitychange');
    win.dispatch('pagehide');
    await vi.advanceTimersByTimeAsync(60_000);
    expect(fetchMock.mock.calls.length).toBe(calls);
  });
});
