import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story 14-S2 — Puzzle library, checked in the source.
//
// The library page and its parts paint only through the redesign's tokens
// and head the page with one size-2 Title. The per-puzzle thumbnail is gone
// in favour of one fixed icon. Play's empty line, which the shared test
// database never lets the browser reach, is checked here. The rendered page
// is checked in the browser by e2e/puzzle-library.spec.ts.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../../', import.meta.url));

const LIBRARY_FILES = [
  'app/puzzles/page.tsx',
  'components/puzzle/PuzzleLibrary.tsx',
  'components/puzzle/PuzzleRow.tsx',
  'components/puzzle/RowHeading.tsx',
  'components/puzzle/CrosswordIcon.tsx',
  'components/puzzle/LibraryDeleteDialog.tsx',
  'components/puzzle/LibraryPlayControls.tsx',
];

function source(path: string) {
  return readFileSync(join(SRC, path), 'utf8');
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

function sourceFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sourceFiles(path);
    return /\.(ts|tsx)$/.test(name) && !/\.test\.tsx?$/.test(name) ? [path] : [];
  });
}

const OLD_COLOR_TOKENS = [
  'background',
  'foreground',
  'ink-2',
  'ink-3',
  'rule',
  'rule-strong',
  'hover-tint',
  'panel-tint',
  'accent',
  'accent-hover',
  'ok-tint',
  'required',
  'recommended',
  'incomplete',
];

function expectRedesignTokensOnly(code: string, label: string) {
  expect(code, label).not.toMatch(/#[0-9a-f]{3,8}\b/i);
  expect(code, label).not.toMatch(/\b(rgb|rgba|hsl|hsla|oklch)\(/);
  expect(code, label).not.toMatch(/\b(text|bg|border|fill|stroke)-(white|black)\b/);
  expect(code, label).not.toMatch(/\bring-/);
  expect(code, label).not.toMatch(/\brounded-(btn|sm|md|lg|grid)\b/);
  expect(code, label).not.toMatch(/\bshadow\b|\bshadow-/);
  expect(code, label).not.toMatch(/\bfont-display\b|\btext-(headline|body|help|xl|title)(?![\w-])/);
  expect(code, label).not.toMatch(/\btext-(xs|sm|base|lg|[2-9]xl)\b/);
  expect(code, label).not.toMatch(/\[font-weight:/);
  for (const name of OLD_COLOR_TOKENS) {
    expect(code, `${label}: ${name}`).not.toMatch(
      new RegExp(`(?:^|[\\s'"\`:])(?:text|bg|border|fill|stroke)-${name}(?![\\w-])`),
    );
  }
}

describe('14-S2 puzzle library source', () => {
  const files = LIBRARY_FILES.map((path) => ({ path, code: withoutComments(source(path)) }));

  it('the library page, Puzzle Row, Row Heading, icon and its dialogs use only the redesign tokens', () => {
    for (const { path, code } of files) expectRedesignTokensOnly(code, path);
  });

  it('the page heading is the one size-2 Title', () => {
    const titles = files.flatMap(({ code }) => Array.from(code.matchAll(/<Title\b[^>]*>/g), (m) => m[0]));
    expect(titles.filter((tag) => /\bsize=\{2\}/.test(tag))).toHaveLength(1);
  });

  it('GridThumbnail is gone and nothing imports it', () => {
    expect(existsSync(join(SRC, 'components/puzzle/GridThumbnail.tsx'))).toBe(false);
    const offenders = sourceFiles(SRC).filter((file) =>
      /\bGridThumbnail\b/.test(withoutComments(readFileSync(file, 'utf8'))),
    );
    expect(offenders.map((file) => file.slice(SRC.length))).toEqual([]);
  });

  it('the Play view has its empty line', () => {
    expect(files.map(({ code }) => code).join('\n')).toContain('No puzzles to play yet.');
  });
});
