import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Coord, type Grid } from '../engine/grid';
import type { CursorState } from '../engine/cursor';
import type { LockedWord } from './locked-words';
import { deleteProtected, isCellProtected, placeProtected } from './locked-keys';

// Story 21-S3 — locked cells hold. A protected cell is a letter of any
// locked word or an end cell of one. Typing on a protected cell changes
// nothing, and the cursor moves on as the engine's `place` would: one cell
// in its direction if that cell is there, otherwise it stays. Backspace
// never clears a protected cell: on one, the cursor moves back a cell (if
// there is one) and clears nothing; from an empty cell whose previous cell
// is protected, it lands there and clears nothing. Elsewhere both keys act
// as the engine's `place` and `deleteAt`. When nothing changes the grid
// is returned as is, so no save follows.
//
// Do not edit this file to match an implementation.

/** A grid from rows of text: a letter is a lettered cell, '.' an empty one, '#' black. */
function gridOf(rows: string[]): Grid {
  const black: Coord[] = [];
  rows.forEach((line, row) => [...line].forEach((ch, col) => ch === '#' && black.push({ col, row })));
  let grid = createGrid({ cols: rows[0].length, rows: rows.length, black });
  rows.forEach((line, row) => {
    [...line].forEach((letter, col) => {
      if (letter !== '.' && letter !== '#') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/** The grid as rows of text, as gridOf reads them. */
function rowsOf(grid: Grid): string[] {
  return Array.from({ length: grid.rows }, (_, row) =>
    Array.from({ length: grid.cols }, (_, col) => {
      const cell = grid.at(col, row);
      if (cell.kind !== 'active') return '#';
      return cell.letter ?? '.';
    }).join('')
  );
}

const across = (col: number, row: number): CursorState => ({ current: { col, row }, orientation: 'across' });
const down = (col: number, row: number): CursorState => ({ current: { col, row }, orientation: 'down' });

//   . . . . . .     row 0
//   . C A T . .     row 1: CAT locked, cols 1–3; end cells (0,1) and (4,1)
//   . . N . . .     column 2: AND, unlocked, crossing CAT's A
//   . . D . . .
//   . . . D O G     row 4: DOG locked, cols 3–5, to the right edge; one end cell (2,4)
const ROWS = ['......', '.CAT..', '..N...', '..D...', '...DOG'];
const GRID = gridOf(ROWS);
const CAT: LockedWord = { col: 1, row: 1, orientation: 'across', length: 3 };
const DOG: LockedWord = { col: 3, row: 4, orientation: 'across', length: 3 };
const LOCKED = [CAT, DOG];

describe('21-S3 a protected cell', () => {
  it('is a letter of a locked word, in either direction', () => {
    expect(isCellProtected(GRID, LOCKED, { col: 1, row: 1 })).toBe(true);
    expect(isCellProtected(GRID, LOCKED, { col: 2, row: 1 })).toBe(true);
    expect(isCellProtected(GRID, LOCKED, { col: 5, row: 4 })).toBe(true);
  });

  it("is an end cell of a locked word, none past the grid's edge", () => {
    expect(isCellProtected(GRID, LOCKED, { col: 0, row: 1 })).toBe(true);
    expect(isCellProtected(GRID, LOCKED, { col: 4, row: 1 })).toBe(true);
    expect(isCellProtected(GRID, LOCKED, { col: 2, row: 4 })).toBe(true);
  });

  it('is nothing else', () => {
    expect(isCellProtected(GRID, LOCKED, { col: 2, row: 2 })).toBe(false); // AND's N
    expect(isCellProtected(GRID, LOCKED, { col: 1, row: 2 })).toBe(false); // below C
    expect(isCellProtected(GRID, LOCKED, { col: 5, row: 1 })).toBe(false); // past an end cell
    expect(isCellProtected(GRID, [], { col: 1, row: 1 })).toBe(false);
  });
});

describe('21-S3-1 typing', () => {
  it('over a locked letter changes nothing; the cursor advances', () => {
    const typed = placeProtected(GRID, LOCKED, across(1, 1), 'X');
    expect(typed.grid).toBe(GRID);
    expect(typed.cursor).toEqual(across(2, 1));

    // CAT's A, typed down: protected though the cursor runs the other way.
    const crossing = placeProtected(GRID, LOCKED, down(2, 1), 'X');
    expect(crossing.grid).toBe(GRID);
    expect(crossing.cursor).toEqual(down(2, 2));
  });

  it('over an end cell changes nothing; the cursor advances', () => {
    const after = placeProtected(GRID, LOCKED, across(4, 1), 'S');
    expect(after.grid).toBe(GRID);
    expect(after.cursor).toEqual(across(5, 1));

    const before = placeProtected(GRID, LOCKED, down(0, 1), 'S');
    expect(before.grid).toBe(GRID);
    expect(before.cursor).toEqual(down(0, 2));

    // DOG's end cell, typed down through: AND does not grow.
    const below = placeProtected(GRID, LOCKED, down(2, 4), 'S');
    expect(below.grid).toBe(GRID);
    expect(below.cursor).toEqual(down(2, 4));
  });

  it("at the grid's edge, or before a black cell, the cursor stays", () => {
    const edge = placeProtected(GRID, LOCKED, across(5, 4), 'X');
    expect(edge.grid).toBe(GRID);
    expect(edge.cursor).toEqual(across(5, 4));

    const walled = gridOf(['CAT#.']);
    const word: LockedWord = { col: 0, row: 0, orientation: 'across', length: 3 };
    const black = placeProtected(walled, [word], across(2, 0), 'X');
    expect(black.grid).toBe(walled);
    expect(black.cursor).toEqual(across(2, 0));
  });

  it('elsewhere places the letter and advances, as before', () => {
    const typed = placeProtected(GRID, LOCKED, down(2, 2), 'X');
    expect(rowsOf(typed.grid)).toEqual(['......', '.CAT..', '..X...', '..D...', '...DOG']);
    expect(typed.cursor).toEqual(down(2, 3));
    expect(rowsOf(GRID)).toEqual(ROWS);
  });

  it('KIND or MIND typed down from a locked K gives K-I-N-D', () => {
    const grid = gridOf(['......', '.KOOK.', '......', '......', '......', '......']);
    const kook: LockedWord = { col: 1, row: 1, orientation: 'across', length: 4 };
    for (const word of ['KIND', 'MIND']) {
      let state = { grid, cursor: down(4, 1) };
      for (const letter of word) state = placeProtected(state.grid, [kook], state.cursor, letter);
      expect(rowsOf(state.grid), word).toEqual(['......', '.KOOK.', '....I.', '....N.', '....D.', '......']);
      expect(state.cursor, word).toEqual(down(4, 5));
    }
  });
});

describe('21-S3-2 deleting', () => {
  it('on a locked letter clears nothing; the cursor moves back', () => {
    const deleted = deleteProtected(GRID, LOCKED, across(3, 1));
    expect(deleted.grid).toBe(GRID);
    expect(deleted.cursor).toEqual(across(2, 1));

    const crossing = deleteProtected(GRID, LOCKED, down(2, 1));
    expect(crossing.grid).toBe(GRID);
    expect(crossing.cursor).toEqual(down(2, 0));
  });

  it("on a locked letter at the grid's edge, the cursor stays", () => {
    const grid = gridOf(['CAT..']);
    const word: LockedWord = { col: 0, row: 0, orientation: 'across', length: 3 };
    const deleted = deleteProtected(grid, [word], across(0, 0));
    expect(deleted.grid).toBe(grid);
    expect(deleted.cursor).toEqual(across(0, 0));
  });

  it('on an end cell clears nothing, not even the cell before it; the cursor moves back', () => {
    const after = deleteProtected(GRID, LOCKED, across(4, 1));
    expect(after.grid).toBe(GRID);
    expect(after.cursor).toEqual(across(3, 1));

    // DOG's end cell, below AND's unlocked D: the D stays.
    const below = deleteProtected(GRID, LOCKED, down(2, 4));
    expect(below.grid).toBe(GRID);
    expect(below.cursor).toEqual(down(2, 3));
  });

  it('an end cell holding a letter is never cleared', () => {
    const grid = gridOf(['XCAT.', '.....']);
    const word: LockedWord = { col: 1, row: 0, orientation: 'across', length: 3 };
    const on = deleteProtected(grid, [word], across(0, 0));
    expect(on.grid).toBe(grid);
    expect(on.cursor).toEqual(across(0, 0));

    const from = deleteProtected(grid, [word], down(0, 1));
    expect(from.grid).toBe(grid);
    expect(from.cursor).toEqual(down(0, 0));
  });

  it('from an empty cell after a locked letter, lands on it and clears nothing', () => {
    const deleted = deleteProtected(GRID, LOCKED, down(1, 2));
    expect(deleted.grid).toBe(GRID);
    expect(deleted.cursor).toEqual(down(1, 1));
  });

  it('elsewhere clears a letter, or moves back and clears, as before', () => {
    const inPlace = deleteProtected(GRID, LOCKED, down(2, 2));
    expect(rowsOf(inPlace.grid)).toEqual(['......', '.CAT..', '......', '..D...', '...DOG']);
    expect(inPlace.cursor).toEqual(down(2, 2));

    const back = deleteProtected(GRID, LOCKED, across(3, 2));
    expect(rowsOf(back.grid)).toEqual(['......', '.CAT..', '......', '..D...', '...DOG']);
    expect(back.cursor).toEqual(across(2, 2));
    expect(rowsOf(GRID)).toEqual(ROWS);
  });

  it('Backspacing out KIND clears D, N and I, rests on the K, then walks back past it', () => {
    const kook: LockedWord = { col: 1, row: 1, orientation: 'across', length: 4 };
    let state = { grid: gridOf(['......', '.KOOK.', '....I.', '....N.', '....D.', '......']), cursor: down(4, 5) };
    const cursors: CursorState[] = [];
    for (let i = 0; i < 5; i++) {
      state = deleteProtected(state.grid, [kook], state.cursor);
      cursors.push(state.cursor);
    }
    expect(rowsOf(state.grid)).toEqual(['......', '.KOOK.', '......', '......', '......', '......']);
    expect(cursors).toEqual([down(4, 4), down(4, 3), down(4, 2), down(4, 1), down(4, 0)]);
  });
});
