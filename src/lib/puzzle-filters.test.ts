import { beforeEach, describe, expect, it } from 'vitest';

// Story 18-S4 — the library's filter function and its URL form.
//
// Play (Unplayed, Underway, Complete) and Create (Build Phase, Hint Phase,
// Unlisted) combine with OR, as one status filter; Size (Mini, Midi, Daily,
// Sunday) narrows with AND. A group with nothing checked doesn't restrict.
// Other sizes match no Size option. Filters live in the URL's query as
// `play`, `create` and `size`, each a comma-separated list in canonical
// order; unknown values are ignored.
//
// The module is loaded through a variable path, with its types declared
// here, so the specification-only baseline type-checks; missing runtime
// stays red. Do not edit this file to match an implementation.

type PlayState = 'untouched' | 'in-progress' | 'completed';
interface Puzzle {
  id: string;
  builderId: string;
  phase: 'grid' | 'hints';
  publishedAt: string | null;
  visibility: 'private' | 'public';
  cols: number;
  rows: number;
  play: { state: PlayState; sessionId: string | null } | null;
}
interface Filters {
  play: ('unplayed' | 'underway' | 'complete')[];
  create: ('build' | 'hint' | 'unlisted')[];
  size: ('mini' | 'midi' | 'daily' | 'sunday')[];
}

let filterPuzzles: (puzzles: readonly Puzzle[], filters: Filters, userId: string) => Puzzle[];
let parseFilters: (params: URLSearchParams) => Filters;
let filtersQuery: (filters: Filters) => string;

beforeEach(async () => {
  const modulePath = './puzzle-filters';
  const implementation = await import(modulePath) as Record<string, unknown>;
  for (const name of ['filterPuzzles', 'parseFilters', 'filtersQuery']) {
    expect(typeof implementation[name], name).toBe('function');
  }
  filterPuzzles = implementation.filterPuzzles as typeof filterPuzzles;
  parseFilters = implementation.parseFilters as typeof parseFilters;
  filtersQuery = implementation.filtersQuery as typeof filtersQuery;
});

const ME = 'me';
const OTHER = 'other';
const SIZES = { mini: [5, 5], midi: [9, 9], daily: [15, 15], sunday: [21, 21], other: [3, 3] } as const;
type Size = keyof typeof SIZES;

function puzzle(id: string, builderId: string, kind: 'grid' | 'hints' | 'unlisted' | 'public', size: Size = 'daily', state: PlayState | null = null): Puzzle {
  const published = kind === 'unlisted' || kind === 'public';
  const [cols, rows] = SIZES[size];
  return {
    id,
    builderId,
    phase: kind === 'grid' ? 'grid' : 'hints',
    publishedAt: published ? '2026-10-01T00:00:00.000Z' : null,
    visibility: kind === 'public' ? 'public' : 'private',
    cols,
    rows,
    play: published ? { state: state ?? 'untouched', sessionId: state && state !== 'untouched' ? `s-${id}` : null } : null,
  };
}

const LIBRARY: Puzzle[] = [
  puzzle('own-grid', ME, 'grid', 'mini'),
  puzzle('own-hints', ME, 'hints', 'midi'),
  puzzle('own-unlisted', ME, 'unlisted', 'daily'),
  puzzle('own-public', ME, 'public', 'sunday', 'completed'),
  puzzle('own-other-size', ME, 'grid', 'other'),
  puzzle('foreign-untouched', OTHER, 'public', 'mini'),
  puzzle('foreign-underway', OTHER, 'public', 'daily', 'in-progress'),
  puzzle('foreign-complete', OTHER, 'public', 'midi', 'completed'),
  puzzle('foreign-unlisted-started', OTHER, 'unlisted', 'other', 'in-progress'),
  puzzle('foreign-other-size', OTHER, 'public', 'other'),
];

function filters(partial: Partial<Filters> = {}): Filters {
  return { play: [], create: [], size: [], ...partial };
}

function ids(partial: Partial<Filters>) {
  return filterPuzzles(LIBRARY, filters(partial), ME).map((p) => p.id);
}

describe('18-S4-1 the filter function', () => {
  it('with nothing checked, keeps every puzzle in order', () => {
    expect(ids({})).toEqual(LIBRARY.map((p) => p.id));
  });

  it('Play: Unplayed, Underway and Complete follow the caller’s play state of published puzzles, own or not', () => {
    expect(ids({ play: ['unplayed'] })).toEqual(['own-unlisted', 'foreign-untouched', 'foreign-other-size']);
    expect(ids({ play: ['underway'] })).toEqual(['foreign-underway', 'foreign-unlisted-started']);
    expect(ids({ play: ['complete'] })).toEqual(['own-public', 'foreign-complete']);
  });

  it('a published puzzle with no attempt reads as Unplayed', () => {
    const bare = { ...puzzle('bare', OTHER, 'public'), play: null };
    expect(filterPuzzles([bare], filters({ play: ['unplayed'] }), ME).map((p) => p.id)).toEqual(['bare']);
    expect(filterPuzzles([bare], filters({ play: ['underway', 'complete'] }), ME)).toEqual([]);
  });

  it('Create: Build Phase, Hint Phase and Unlisted are the caller’s own unpublished grid, unpublished hints and unlisted published puzzles', () => {
    expect(ids({ create: ['build'] })).toEqual(['own-grid', 'own-other-size']);
    expect(ids({ create: ['hint'] })).toEqual(['own-hints']);
    expect(ids({ create: ['unlisted'] })).toEqual(['own-unlisted']);
  });

  it('Create never matches another builder’s puzzle', () => {
    const foreign = [
      puzzle('foreign-grid', OTHER, 'grid'),
      puzzle('foreign-hints', OTHER, 'hints'),
      puzzle('foreign-unlisted', OTHER, 'unlisted'),
    ];
    expect(filterPuzzles(foreign, filters({ create: ['build', 'hint', 'unlisted'] }), ME)).toEqual([]);
  });

  it('options within a group combine with OR', () => {
    expect(ids({ create: ['build', 'hint'] })).toEqual(['own-grid', 'own-hints', 'own-other-size']);
    expect(ids({ play: ['underway', 'complete'] })).toEqual(['own-public', 'foreign-underway', 'foreign-complete', 'foreign-unlisted-started']);
  });

  it('Play and Create combine with OR, as one status filter', () => {
    expect(ids({ play: ['unplayed'], create: ['build'] }))
      .toEqual(['own-grid', 'own-unlisted', 'own-other-size', 'foreign-untouched', 'foreign-other-size']);
  });

  it('Size narrows with AND; options within it combine with OR', () => {
    expect(ids({ size: ['mini'] })).toEqual(['own-grid', 'foreign-untouched']);
    expect(ids({ size: ['mini', 'sunday'] })).toEqual(['own-grid', 'own-public', 'foreign-untouched']);
    expect(ids({ create: ['build', 'hint'], size: ['mini'] })).toEqual(['own-grid']);
    expect(ids({ play: ['unplayed'], create: ['build'], size: ['daily'] })).toEqual(['own-unlisted']);
  });

  it('other sizes show only when no Size option is checked', () => {
    expect(ids({ size: ['mini', 'midi', 'daily', 'sunday'] }))
      .toEqual(['own-grid', 'own-hints', 'own-unlisted', 'own-public', 'foreign-untouched', 'foreign-underway', 'foreign-complete']);
  });

  it('nothing matching gives an empty list', () => {
    expect(ids({ create: ['hint'], size: ['sunday'] })).toEqual([]);
  });

  it('does not change its input', () => {
    const copy = structuredClone(LIBRARY);
    filterPuzzles(LIBRARY, filters({ play: ['complete'], size: ['midi'] }), ME);
    expect(LIBRARY).toEqual(copy);
  });
});

describe('18-S4-2 the filters in the URL', () => {
  it('reads each group from its parameter', () => {
    expect(parseFilters(new URLSearchParams('play=underway,unplayed&create=hint&size=sunday,mini')))
      .toEqual({ play: ['unplayed', 'underway'], create: ['hint'], size: ['mini', 'sunday'] });
  });

  it('reads no parameters as no filters, and ignores unknown or repeated values', () => {
    expect(parseFilters(new URLSearchParams(''))).toEqual(filters());
    expect(parseFilters(new URLSearchParams('play=Unplayed,later,,complete,complete&create=public&size=huge&view=play')))
      .toEqual({ play: ['complete'], create: [], size: [] });
  });

  it('writes the checked options in canonical order, omitting empty groups', () => {
    expect(filtersQuery(filters())).toBe('');
    expect(filtersQuery(filters({ size: ['sunday', 'mini'], play: ['complete', 'unplayed'] })))
      .toBe('?play=unplayed,complete&size=mini,sunday');
    expect(filtersQuery(filters({ create: ['unlisted', 'build', 'hint'] }))).toBe('?create=build,hint,unlisted');
  });

  it('round-trips', () => {
    const all: Filters = {
      play: ['unplayed', 'underway', 'complete'],
      create: ['build', 'hint', 'unlisted'],
      size: ['mini', 'midi', 'daily', 'sunday'],
    };
    expect(parseFilters(new URLSearchParams(filtersQuery(all).slice(1)))).toEqual(all);
  });
});
