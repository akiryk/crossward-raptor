import { describe, expect, it } from 'vitest';
import { createGrid, type Coord, type Grid } from '../engine/grid';
import * as cellAppearanceModule from './cell-appearance';

// Story 25-S1 — the sister word.
//
// The sister word of the cursor's word is its 180° image: the symmetric
// counterpart of each of the word's cells, `sisterWord(grid, word)` in
// cell-appearance.ts, beside symmetricHintKeys. Cells of the word itself
// are left out (a word crossing the center shares cells with its image),
// and so are black cells (a grid saved before 14-S5). The cells keep the
// word's order. An empty word has no sister. The grid is not read for
// letters: the sister is where symmetry puts it, whatever its cells hold.
//
// Imported through the module namespace so this file type-checks before
// the function exists; it then fails at run time. Do not edit this file to
// match an implementation.

type SisterWord = (grid: Grid, word: readonly Coord[]) => Coord[];

function sisterWord(grid: Grid, word: readonly Coord[]): Coord[] {
  const fn = (cellAppearanceModule as unknown as { sisterWord?: SisterWord }).sisterWord;
  if (typeof fn !== 'function') throw new Error('cell-appearance.ts exports no sisterWord');
  return fn(grid, word);
}

const daily = (black: Coord[] = []) => createGrid({ cols: 15, rows: 15, black });
const across = (row: number, from: number, to: number): Coord[] =>
  Array.from({ length: to - from + 1 }, (_, i) => ({ col: from + i, row }));
const down = (col: number, from: number, to: number): Coord[] =>
  Array.from({ length: to - from + 1 }, (_, i) => ({ col, row: from + i }));

describe('25-S1-1 the 180° image', () => {
  it('an across word at the top left: its image at the bottom right, in the word\'s order', () => {
    expect(sisterWord(daily(), across(0, 0, 3))).toEqual([
      { col: 14, row: 14 },
      { col: 13, row: 14 },
      { col: 12, row: 14 },
      { col: 11, row: 14 },
    ]);
  });

  it('a down word: its image is a down word', () => {
    expect(sisterWord(daily(), down(9, 3, 5))).toEqual([
      { col: 5, row: 11 },
      { col: 5, row: 10 },
      { col: 5, row: 9 },
    ]);
  });

  it('a non-square grid uses its own size', () => {
    const grid = createGrid({ cols: 5, rows: 3 });
    expect(sisterWord(grid, across(0, 0, 1))).toEqual([
      { col: 4, row: 2 },
      { col: 3, row: 2 },
    ]);
  });
});

describe('25-S1-2 the word\'s own cells are left out', () => {
  it('a center-row word off center: the image shares the center cell, which is left out', () => {
    expect(sisterWord(daily(), across(7, 5, 7))).toEqual([
      { col: 9, row: 7 },
      { col: 8, row: 7 },
    ]);
  });

  it('a word symmetric about the center is its own image: no sister', () => {
    expect(sisterWord(daily(), across(7, 5, 9))).toEqual([]);
    expect(sisterWord(daily(), down(7, 4, 10))).toEqual([]);
  });
});

describe('25-S1-3 none', () => {
  it('an empty word has no sister', () => {
    expect(sisterWord(daily(), [])).toEqual([]);
  });

  it('a black counterpart (a grid saved before 14-S5) is left out', () => {
    expect(sisterWord(daily([{ col: 13, row: 14 }]), across(0, 0, 2))).toEqual([
      { col: 14, row: 14 },
      { col: 12, row: 14 },
    ]);
  });

  it('the inputs are not changed', () => {
    const grid = daily();
    const word = across(2, 1, 4);
    const before = JSON.stringify(word);
    sisterWord(grid, word);
    expect(JSON.stringify(word)).toBe(before);
    expect(grid.at(13, 12)).toEqual({ kind: 'active', letter: null });
  });
});
