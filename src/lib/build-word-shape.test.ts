import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Coord, type Grid } from '../engine/grid';
import { buildWord } from './build-word';
import { lockableWord } from './locked-words';

// Story 21-S8 — the word is the run of cells Preview keeps white.
//
// A word in the build phase is the unbroken run of cells through a cell,
// in a direction, that are not black in Preview's geometry
// (intendedGeometry): lettered cells and Preview-red cells (empty, but
// their symmetric counterpart holds a letter) alike, ended by a
// Preview-black cell or the grid's edge. A run of 2 or more cells is a
// word; a Preview-black cell or a lone cell has none (null). A lockable
// word is a complete one: every cell lettered, at least 3.
//
// Do not edit this file to match an implementation.

/** A grid from rows of text: a letter is a lettered cell, '.' an empty one. */
function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

const across = (row: number, cols: number[]): Coord[] => cols.map((col) => ({ col, row }));
const down = (col: number, rows: number[]): Coord[] => rows.map((row) => ({ col, row }));
const range = (from: number, to: number) => Array.from({ length: to - from + 1 }, (_, i) => from + i);

// The human's row, on a 14×14 (counterpart of (c,0) is (13−c,13)):
//   row 0:  X X X B I R D * * X X S O Y
//   row 13: * * * X X A T * * * * . . .   (A, T make (8,0), (7,0) red)
// X: Preview-black. *: Preview-red, empty but its counterpart is lettered.
const EMPTY_ROW = '..............';
const ROWS = ['...BIRD....SOY', ...Array(12).fill(EMPTY_ROW), '.....AT.......'];
const GRID = gridOf(ROWS);

describe('21-S8-1 the word is the run Preview keeps white', () => {
  it('a word ended by Preview-black cells, from any of its letters', () => {
    for (const col of [11, 12, 13]) {
      expect(buildWord(GRID, { col, row: 0 }, 'across')).toEqual(across(0, [11, 12, 13]));
    }
  });

  it('takes in the Preview-red cells next to its letters', () => {
    for (const col of [3, 4, 5, 6]) {
      expect(buildWord(GRID, { col, row: 0 }, 'across')).toEqual(across(0, range(3, 8)));
    }
  });

  it('a Preview-red cell selects its word too', () => {
    expect(buildWord(GRID, { col: 7, row: 0 }, 'across')).toEqual(across(0, range(3, 8)));
    expect(buildWord(GRID, { col: 8, row: 0 }, 'across')).toEqual(across(0, range(3, 8)));
  });

  it('a run of Preview-red cells alone is a word', () => {
    expect(buildWord(GRID, { col: 1, row: 13 }, 'across')).toEqual(across(13, [0, 1, 2]));
  });

  it('Preview-red cells after letters join them, from a red cell', () => {
    // Row 13: A, T at 5–6, then red cells 7–10.
    expect(buildWord(GRID, { col: 9, row: 13 }, 'across')).toEqual(across(13, range(5, 10)));
  });

  it('a letter, a Preview-red cell and a letter are one word; a lone red cell has none', () => {
    //   A * B X X     row 0: (1,0) red, as C is lettered; (3,0), (4,0) black
    //   X X X X X
    //   X X X X X
    //   X X X X X
    //   X X * C *
    const split = gridOf(['A.B..', '.....', '.....', '.....', '...C.']);
    for (const col of [0, 1, 2]) {
      expect(buildWord(split, { col, row: 0 }, 'across')).toEqual(across(0, [0, 1, 2]));
    }
    // (1,0) going down: (1,1) is Preview-black.
    expect(buildWord(split, { col: 1, row: 0 }, 'down')).toBeNull();
  });

  it('a Preview-black cell has no word', () => {
    for (const col of [0, 1, 2, 9, 10]) {
      expect(buildWord(GRID, { col, row: 0 }, 'across')).toBeNull();
    }
    expect(buildWord(GRID, { col: 3, row: 13 }, 'across')).toBeNull();
  });

  it('a lone cell has no word in that direction', () => {
    // B (3,0) going down: (3,1) is Preview-black.
    expect(buildWord(GRID, { col: 3, row: 0 }, 'down')).toBeNull();
  });

  it('down, ended by a Preview-black cell, and longer once a red cell joins it', () => {
    //   C . . . .     column 0: CAT; (0,3) black while (4,1) is empty
    //   A . . . .
    //   T . . . .
    //   . . . . .
    //   . . . . .
    const cat = gridOf(['C....', 'A....', 'T....', '.....', '.....']);
    expect(buildWord(cat, { col: 0, row: 1 }, 'down')).toEqual(down(0, [0, 1, 2]));
    const withRed = withLetter(cat, { col: 4, row: 1 }, 'S');
    expect(buildWord(withRed, { col: 0, row: 1 }, 'down')).toEqual(down(0, [0, 1, 2, 3]));
  });

  it('an empty grid has no word', () => {
    const empty = createGrid({ cols: 5, rows: 5 });
    expect(buildWord(empty, { col: 2, row: 2 }, 'across')).toBeNull();
    expect(buildWord(empty, { col: 2, row: 2 }, 'down')).toBeNull();
  });
});

describe('21-S8-2 only a complete word is lockable', () => {
  it('a complete word of 3 or more letters is', () => {
    expect(lockableWord(GRID, { current: { col: 13, row: 0 }, orientation: 'across' })).toEqual({
      col: 11,
      row: 0,
      orientation: 'across',
      length: 3,
    });
  });

  it('a word with an empty cell is not, from a letter or the empty cell', () => {
    for (const col of [3, 4, 5, 6, 7, 8]) {
      expect(lockableWord(GRID, { current: { col, row: 0 }, orientation: 'across' })).toBeNull();
    }
    expect(lockableWord(GRID, { current: { col: 1, row: 13 }, orientation: 'across' })).toBeNull();
  });

  it('once its empty cells are filled, it is, at its full length', () => {
    const filled = withLetter(withLetter(GRID, { col: 7, row: 0 }, 'E'), { col: 8, row: 0 }, 'R');
    expect(lockableWord(filled, { current: { col: 7, row: 0 }, orientation: 'across' })).toEqual({
      col: 3,
      row: 0,
      orientation: 'across',
      length: 6,
    });
  });

  it('a word shorter than 3 is not', () => {
    const two = gridOf(['AB...', '.....', '.....', '.....', '.....']);
    expect(lockableWord(two, { current: { col: 0, row: 0 }, orientation: 'across' })).toBeNull();
  });
});
