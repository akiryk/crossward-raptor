/** A small deterministic random source (mulberry32). */
function seeded(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A random source that returns the given values in turn, and counts calls. */
function scripted(values: number[]) {
  let calls = 0;
  const random = () => {
    if (calls >= values.length) throw new Error(`random called ${calls + 1} times`);
    return values[calls++];
  };
  return { random, calls: () => calls };
}

/** The value whose pick is index `i` of a list of `length`. */
const at = (i: number, length: number) => (i + 0.5) / length;

const WORD = /^[A-Z][a-z]+$/;
const LISTS = [
  ['first adjectives', USERNAME_FIRST_ADJECTIVES],
  ['second adjectives', USERNAME_SECOND_ADJECTIVES],
  ['nouns', USERNAME_NOUNS],
] as const;

afterEach(() => vi.restoreAllMocks());

describe('23-S2-1 the word lists', () => {
  it('are exactly the approved lists, in alphabetical order', () => {
    expect([...USERNAME_FIRST_ADJECTIVES]).toEqual(APPROVED_FIRST);
    expect([...USERNAME_SECOND_ADJECTIVES]).toEqual(APPROVED_SECOND);
    expect([...USERNAME_NOUNS]).toEqual(APPROVED_NOUNS);
  });

  it('each holds 50 to 100 unique single title-case words', () => {
    for (const [label, list] of LISTS) {
      expect(list.length, label).toBeGreaterThanOrEqual(50);
      expect(list.length, label).toBeLessThanOrEqual(100);
      expect(new Set(list).size, `${label} unique`).toBe(list.length);
      for (const word of list) expect(word, label).toMatch(WORD);
    }
  });

  it('share no word with each other (any case)', () => {
    const seen = new Map<string, string>();
    for (const [label, list] of LISTS) {
      for (const word of list) {
        const key = word.toLowerCase();
        expect(seen.get(key), `${word} (${label})`).toBeUndefined();
        seen.set(key, label);
      }
    }
  });
});

describe('23-S2-2 generateUsername', () => {
  it('builds Adjective Adjective Noun from the lists, in slot order, two different adjectives, valid usernames', () => {
    const random = seeded(23);
    for (let i = 0; i < 5000; i++) {
      const name = generateUsername(random);
      expect(name, name).toMatch(/^[A-Z][a-z]+ [A-Z][a-z]+ [A-Z][a-z]+$/);
      const [first, second, noun] = name.split(' ');
      expect(USERNAME_FIRST_ADJECTIVES as readonly string[], name).toContain(first);
      expect(USERNAME_SECOND_ADJECTIVES as readonly string[], name).toContain(second);
      expect(USERNAME_NOUNS as readonly string[], name).toContain(noun);
      expect(first.toLowerCase(), name).not.toBe(second.toLowerCase());
      expect(usernameError(name), name).toBeNull();
      expect(name.trim(), name).toBe(name);
      expect(Array.from(name).length, name).toBeLessThanOrEqual(80);
    }
  });

  it('keeps the adjectives different even when the random source repeats itself', () => {
    for (const value of [0, 0.25, 0.5, 0.75, 0.999999]) {
      const [first, second] = generateUsername(() => value).split(' ');
      expect(first, String(value)).not.toBe(second);
    }
  });

  it('calls the random source three times: first adjective, second adjective, noun', () => {
    const cases: Array<[number, number, number]> = [
      [0, 0, 0],
      [APPROVED_FIRST.length - 1, APPROVED_SECOND.length - 1, APPROVED_NOUNS.length - 1],
      [APPROVED_FIRST.indexOf('Lil'), APPROVED_SECOND.indexOf('Orange'), APPROVED_NOUNS.indexOf('Fox')],
      [APPROVED_FIRST.indexOf('Happy'), APPROVED_SECOND.indexOf('Burly'), APPROVED_NOUNS.indexOf('Finch')],
    ];
    for (const [a, b, c] of cases) {
      const source = scripted([
        at(a, APPROVED_FIRST.length),
        at(b, APPROVED_SECOND.length),
        at(c, APPROVED_NOUNS.length),
      ]);
      expect(generateUsername(source.random)).toBe(
        `${APPROVED_FIRST[a]} ${APPROVED_SECOND[b]} ${APPROVED_NOUNS[c]}`,
      );
      expect(source.calls()).toBe(3);
    }
    // Just above each slot's lower edge: index floor(r × length), not a
    // rounding of r × (length − 1).
    const edge = (i: number, length: number) => (i + 0.01) / length;
    const lil = scripted([
      edge(APPROVED_FIRST.indexOf('Lil'), APPROVED_FIRST.length),
      edge(APPROVED_SECOND.indexOf('Orange'), APPROVED_SECOND.length),
      edge(APPROVED_NOUNS.indexOf('Fox'), APPROVED_NOUNS.length),
    ]);
    expect(generateUsername(lil.random)).toBe('Lil Orange Fox');
    expect(generateUsername(scripted([0, 0, 0]).random)).toBe('Beaming Apricot Alpaca');
    expect(generateUsername(scripted([0.999999, 0.999999, 0.999999]).random)).toBe('Zippy Wavy Wren');
  });

  it('uses only the random source it is given, and Math.random by default', () => {
    const spy = vi.spyOn(Math, 'random').mockImplementation(() => {
      throw new Error('Math.random used');
    });
    expect(() => generateUsername(seeded(1))).not.toThrow();
    spy.mockReset();
    spy.mockReturnValue(0);
    expect(generateUsername()).toBe('Beaming Apricot Alpaca');
    expect(spy).toHaveBeenCalledTimes(3);
  });

  it('is determined by its random source', () => {
    const a = seeded(7);
    const b = seeded(7);
    for (let i = 0; i < 50; i++) expect(generateUsername(a)).toBe(generateUsername(b));
  });

  it('varies, and every word of every list can appear', () => {
    const random = seeded(2311);
    const names = Array.from({ length: 20000 }, () => generateUsername(random));
    expect(new Set(names.slice(0, 200)).size).toBeGreaterThan(195);
    const used = [new Set<string>(), new Set<string>(), new Set<string>()];
    for (const name of names) name.split(' ').forEach((word, i) => used[i].add(word));
    expect([...used[0]].sort()).toEqual(APPROVED_FIRST);
    expect([...used[1]].sort()).toEqual(APPROVED_SECOND);
    expect([...used[2]].sort()).toEqual(APPROVED_NOUNS);
  });
});
