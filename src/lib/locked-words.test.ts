import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Grid } from '../engine/grid';
import {
  endCells,
  isCellLocked,
  lockableWord,
  lockedWordAt,
  toggleLock,
  type LockedWord,
} from './locked-words';

// Story 21-S2 — lock and unlock a word. A lockable word is 21-S1's run
// with at least 3 letters, stored as { col, row, orientation, length }
// from its first cell. Its end cells are the cells just before and after
// it in its direction, none past the grid's edge. A letter is locked if
// any locked word holds it.
//
// Amended by 21-S8, whose lockable word must also be complete (no
// Preview-red cell in its run): GRID gets five empty rows at the bottom, so
// no cell in rows 0–4 is Preview-red and every case fails or passes for
// the reason it names.
//
// Do not edit this file to match an implementation.

/** A grid from rows of text: a letter is a lettered cell, '.' an empty one. */
function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

//   C A T . . .     row 0: CAT from the left edge
//   . . O . . .     column 2: TON, rows 0–2
//   . H N . . .     row 2: HN is 2 letters; column 1 holds H alone
//   . . . . A T     row 3: AT, 2 letters, to the right edge
//   . D O G S .     row 4: DOGS, away from both edges
//   . . . . . .     rows 5–9: empty (21-S8)
const GRID = gridOf(['CAT...', '..O...', '.HN...', '....AT', '.DOGS.', ...Array(5).fill('......')]);

const CAT: LockedWord = { col: 0, row: 0, orientation: 'across', length: 3 };
const TON: LockedWord = { col: 2, row: 0, orientation: 'down', length: 3 };
const DOGS: LockedWord = { col: 1, row: 4, orientation: 'across', length: 4 };

describe('21-S2-1 locked words', () => {
  describe('a lockable word', () => {
    it('is the run through the cursor, from its first cell, by direction', () => {
      expect(lockableWord(GRID, { current: { col: 2, row: 0 }, orientation: 'across' })).toEqual(CAT);
      expect(lockableWord(GRID, { current: { col: 2, row: 0 }, orientation: 'down' })).toEqual(TON);
      expect(lockableWord(GRID, { current: { col: 2, row: 2 }, orientation: 'down' })).toEqual(TON);
      expect(lockableWord(GRID, { current: { col: 3, row: 4 }, orientation: 'across' })).toEqual(DOGS);
    });

    it('has at least 3 letters: none for 2 letters, a lone letter or an empty cell', () => {
      expect(lockableWord(GRID, { current: { col: 2, row: 2 }, orientation: 'across' })).toBeNull();
      expect(lockableWord(GRID, { current: { col: 5, row: 3 }, orientation: 'across' })).toBeNull();
      expect(lockableWord(GRID, { current: { col: 1, row: 2 }, orientation: 'down' })).toBeNull();
      expect(lockableWord(GRID, { current: { col: 4, row: 1 }, orientation: 'across' })).toBeNull();
    });
  });

  describe('end cells', () => {
    it('are the cells before and after the word, away from the edges', () => {
      expect(endCells(GRID, DOGS)).toEqual([
        { col: 0, row: 4 },
        { col: 5, row: 4 },
      ]);
    });

    it('are none past the grid edge', () => {
      expect(endCells(GRID, CAT)).toEqual([{ col: 3, row: 0 }]);
      expect(endCells(GRID, TON)).toEqual([{ col: 2, row: 3 }]);
      const atBothEdges: LockedWord = { col: 0, row: 0, orientation: 'across', length: 6 };
      expect(endCells(GRID, atBothEdges)).toEqual([]);
    });
  });

  describe('a locked cell', () => {
    it('is a letter of any locked word', () => {
      const locked = [CAT, TON];
      expect(isCellLocked(locked, { col: 0, row: 0 })).toBe(true);
      expect(isCellLocked(locked, { col: 2, row: 0 })).toBe(true);
      expect(isCellLocked(locked, { col: 2, row: 2 })).toBe(true);
      expect(isCellLocked(locked, { col: 1, row: 2 })).toBe(false);
      expect(isCellLocked(locked, { col: 3, row: 4 })).toBe(false);
      expect(isCellLocked([], { col: 0, row: 0 })).toBe(false);
    });

    it('stays locked through a crossing word when the other is unlocked', () => {
      expect(isCellLocked(toggleLock([CAT, TON], CAT), { col: 2, row: 0 })).toBe(true);
      expect(isCellLocked(toggleLock([CAT, TON], CAT), { col: 0, row: 0 })).toBe(false);
    });
  });

  describe('the locked word under the cursor', () => {
    it('is the locked word holding its cell in its direction', () => {
      const locked = [CAT, TON];
      expect(lockedWordAt(locked, { current: { col: 2, row: 0 }, orientation: 'across' })).toEqual(CAT);
      expect(lockedWordAt(locked, { current: { col: 2, row: 0 }, orientation: 'down' })).toEqual(TON);
      expect(lockedWordAt(locked, { current: { col: 2, row: 1 }, orientation: 'down' })).toEqual(TON);
    });

    it('is none in the other direction or outside it', () => {
      const locked = [CAT];
      expect(lockedWordAt(locked, { current: { col: 1, row: 0 }, orientation: 'down' })).toBeNull();
      expect(lockedWordAt(locked, { current: { col: 3, row: 0 }, orientation: 'across' })).toBeNull();
      expect(lockedWordAt([], { current: { col: 0, row: 0 }, orientation: 'across' })).toBeNull();
    });
  });

  describe('toggling', () => {
    it('adds a word that is not locked and removes one that is', () => {
      expect(toggleLock([], CAT)).toEqual([CAT]);
      expect(toggleLock([CAT], TON)).toEqual([CAT, TON]);
      expect(toggleLock([CAT, TON], { ...CAT })).toEqual([TON]);
    });

    it('leaves its input unchanged', () => {
      const locked = [CAT];
      toggleLock(locked, TON);
      toggleLock(locked, CAT);
      expect(locked).toEqual([CAT]);
    });
  });
});
