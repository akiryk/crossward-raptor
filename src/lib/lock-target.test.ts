import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Coord, type Grid, type Orientation } from '../engine/grid';
import { lockTargetAt, type LockedWord } from './locked-words';

// Story 21-S10 — the word a lock button acts on, from any cell.
//
// `lockTargetAt(grid, lockedWords, { current, orientation })` is the word
// whose lock button the cell would show, in that direction: the locked
// word holding the cell in that direction ({ word, isLocked: true }),
// otherwise the cell's lockable word (21-S8: the run Preview keeps white,
// complete, at least 3 letters; { word, isLocked: false }), otherwise
// null. The cursor (21-S2) and the mouse's hovered cell (21-S10) both use
// it. It reads its inputs and changes neither.
//
// Do not edit this file to match an implementation.

/** A grid from rows of text: a letter is a lettered cell, '.' an empty one. */
function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

// A daily (counterpart of (c,r) is (14−c, 14−r)):
//   TANGENT across row 3 (3–9); ROBIN across row 5 (3–7); RUN down
//   column 3 (5–7), sharing ROBIN's R; EGG across row 11 (5–7), whose run
//   goes on through TANGENT's four Preview-red counterparts (8–11), so it
//   is incomplete; AT across row 13 (0–1), 2 letters.
const E = '...............';
const ROWS = [
  E, E, E,
  '...TANGENT.....',
  E,
  '...ROBIN.......',
  '...U...........',
  '...N...........',
  E, E, E,
  '.....EGG.......',
  E,
  'AT.............',
  E,
];
const GRID = gridOf(ROWS);

const at = (col: number, row: number, orientation: Orientation) => ({
  current: { col, row } as Coord,
  orientation,
});

const TANGENT: LockedWord = { col: 3, row: 3, orientation: 'across', length: 7 };
const ROBIN: LockedWord = { col: 3, row: 5, orientation: 'across', length: 5 };
const RUN: LockedWord = { col: 3, row: 5, orientation: 'down', length: 3 };

describe('21-S10-1 the lock target of any cell', () => {
  it('a complete word of 3 or more letters, unlocked, from any of its cells', () => {
    for (const col of [3, 4, 5, 6, 7]) {
      expect(lockTargetAt(GRID, [], at(col, 5, 'across'))).toEqual({ word: ROBIN, isLocked: false });
    }
    for (const row of [5, 6, 7]) {
      expect(lockTargetAt(GRID, [], at(3, row, 'down'))).toEqual({ word: RUN, isLocked: false });
    }
  });

  it('a locked word holding the cell in that direction is the target, locked', () => {
    for (const col of [3, 6, 9]) {
      expect(lockTargetAt(GRID, [TANGENT], at(col, 3, 'across'))).toEqual({ word: TANGENT, isLocked: true });
    }
  });

  it('the direction decides: the shared R gives ROBIN across and RUN down', () => {
    expect(lockTargetAt(GRID, [RUN], at(3, 5, 'across'))).toEqual({ word: ROBIN, isLocked: false });
    expect(lockTargetAt(GRID, [RUN], at(3, 5, 'down'))).toEqual({ word: RUN, isLocked: true });
    expect(lockTargetAt(GRID, [ROBIN], at(3, 6, 'down'))).toEqual({ word: RUN, isLocked: false });
  });

  it('none for a lone cell, an incomplete word, 2 letters or a Preview-black cell', () => {
    // TANGENT's G, down: a lone cell.
    expect(lockTargetAt(GRID, [TANGENT], at(6, 3, 'down'))).toBeNull();
    // RUN's U, across: a lone cell.
    expect(lockTargetAt(GRID, [], at(3, 6, 'across'))).toBeNull();
    // EGG and its Preview-red cells, from a letter or a red cell.
    expect(lockTargetAt(GRID, [], at(6, 11, 'across'))).toBeNull();
    expect(lockTargetAt(GRID, [], at(10, 11, 'across'))).toBeNull();
    // AT: complete, but 2 letters.
    expect(lockTargetAt(GRID, [], at(0, 13, 'across'))).toBeNull();
    // An empty, Preview-black cell.
    expect(lockTargetAt(GRID, [], at(13, 13, 'across'))).toBeNull();
    expect(lockTargetAt(GRID, [], at(13, 13, 'down'))).toBeNull();
  });

  it('changes neither the grid nor the locked words', () => {
    const lockedWords = Object.freeze([Object.freeze({ ...TANGENT })]) as readonly LockedWord[];
    const before = JSON.stringify(lockedWords);
    lockTargetAt(GRID, lockedWords, at(5, 3, 'across'));
    lockTargetAt(GRID, lockedWords, at(5, 5, 'across'));
    expect(JSON.stringify(lockedWords)).toBe(before);
    expect(GRID.at(5, 5)).toEqual(gridOf(ROWS).at(5, 5));
  });
});
