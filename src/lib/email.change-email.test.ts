import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

// Story 23-S5 — the email-change confirmation message.
// `sendEmailChangeLink(newEmail, url)` delivers the link that confirms a new
// email, to the new address, by the same routes as the sign-in link (A6):
// the local inbox (Mailpit's send API) in local development, Resend in
// production when a key is set, nothing in unit tests or keyless production
// (the E2E harness). Its subject names confirming the email; its text holds
// the link, says it lasts 15 minutes, and says "If you didn't ask for this,
// ignore this email." A failed delivery rejects without
// the link in the error. The sign-in message is unchanged (email.test.ts).
// Mock transport boundaries only. Do not edit this file to match an
// implementation.

const transport = vi.hoisted(() => ({
  constructed: vi.fn(),
  send: vi.fn(),
  fetch: vi.fn(),
}));

vi.mock('resend', () => ({
  Resend: class {
    constructor(key: string) { transport.constructed(key); }
    emails = { send: transport.send };
  },
}));

const NEW_EMAIL = 's5-new@example.test';
const LINK = 'http://localhost:3000/api/auth/verify-email?token=s5-fixture&callbackURL=%2Fpuzzles';

async function deliver() {
  const email = (await import('./email')) as Record<string, unknown>;
  const send = email.sendEmailChangeLink;
  if (typeof send !== 'function') throw new Error('lib/email exports no sendEmailChangeLink');
  return (send as (e: string, u: string) => Promise<void>)(NEW_EMAIL, LINK);
}

beforeEach(() => {
  vi.resetModules();
  vi.resetAllMocks();
  vi.stubEnv('NODE_ENV', 'production');
  vi.stubEnv('VERCEL', '');
  vi.stubEnv('RESEND_API_KEY', '');
  vi.stubGlobal('fetch', transport.fetch);
  transport.fetch.mockResolvedValue(new Response(JSON.stringify({ ID: 's5-captured' }), {
    status: 200, headers: { 'content-type': 'application/json' },
  }));
  transport.send.mockResolvedValue({ data: { id: 's5-delivered' }, error: null });
});

afterEach(() => {
  vi.unstubAllEnvs();
  vi.unstubAllGlobals();
});

describe('23-S5-E1 the confirmation message', () => {
  it('in local development: one message to the local inbox, to the new address, with the link', async () => {
    vi.stubEnv('NODE_ENV', 'development');
    vi.stubEnv('RESEND_API_KEY', 's5-fake-key');
    await deliver();
    expect(transport.fetch).toHaveBeenCalledTimes(1);
    const [resource, init] = transport.fetch.mock.calls[0] as [string | URL, RequestInit];
    expect(String(resource)).toBe('http://127.0.0.1:8025/api/v1/send');
    expect(init.method?.toUpperCase()).toBe('POST');
    const message = JSON.parse(init.body as string);
    expect(message.From).toEqual(expect.objectContaining({ Email: 'login@crossward.app' }));
    expect(message.To).toEqual([expect.objectContaining({ Email: NEW_EMAIL })]);
    expect(message.Subject).toMatch(/confirm/i);
    expect(message.Subject).toMatch(/email/i);
    expect(message.Subject).not.toMatch(/sign.in link/i);
    expect(message.Text).toContain(LINK);
    expect(message.Text).toMatch(/15 minutes/);
    expect(message.Text).toContain("If you didn't ask for this, ignore this email.");
    expect(transport.send).not.toHaveBeenCalled();
  });

  it('in production with a key: Resend, to the new address, with the link', async () => {
    vi.stubEnv('RESEND_API_KEY', 's5-fake-key');
    await deliver();
    expect(transport.constructed).toHaveBeenCalledWith('s5-fake-key');
    expect(transport.send).toHaveBeenCalledTimes(1);
    expect(transport.send).toHaveBeenCalledWith(expect.objectContaining({
      to: NEW_EMAIL,
      subject: expect.stringMatching(/confirm/i),
      text: expect.stringContaining(LINK),
    }));
    expect(transport.send.mock.calls[0][0].text).toContain("If you didn't ask for this, ignore this email.");
    expect(transport.fetch).not.toHaveBeenCalled();
  });

  it('sends nothing in keyless production (the E2E harness) or in unit tests', async () => {
    await deliver();
    vi.stubEnv('NODE_ENV', 'test');
    vi.stubEnv('RESEND_API_KEY', 's5-fake-key');
    await deliver();
    expect(transport.fetch).not.toHaveBeenCalled();
    expect(transport.constructed).not.toHaveBeenCalled();
    expect(transport.send).not.toHaveBeenCalled();
  });

  it('a failed delivery rejects, without the link in the error', async () => {
    vi.stubEnv('NODE_ENV', 'development');
    transport.fetch.mockResolvedValue(new Response('{}', { status: 503 }));
    await expect(deliver()).rejects.toThrow();
    await expect(deliver()).rejects.not.toThrow(/s5-fixture/);
    expect(transport.fetch, 'delivery was attempted').toHaveBeenCalled();
    transport.fetch.mockRejectedValue(new TypeError('Connection refused'));
    await expect(deliver()).rejects.toThrow();

    vi.stubEnv('NODE_ENV', 'production');
    vi.stubEnv('RESEND_API_KEY', 's5-fake-key');
    transport.send.mockResolvedValue({ data: null, error: { name: 'ProviderRejected' } });
    await expect(deliver()).rejects.toThrow();
    await expect(deliver()).rejects.not.toThrow(/s5-fixture/);
    expect(transport.send, 'delivery was attempted').toHaveBeenCalled();
  });
});
