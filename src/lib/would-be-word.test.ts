import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Coord, type Grid, type Orientation } from '../engine/grid';
import * as buildWordModule from './build-word';
import { buildWord } from './build-word';

// Story 22-S5 — the cursor's word is the word its cell would belong to.
//
// In the build phase with Preview off, the cursor's word is the word the
// cursor's cell would belong to, in the cursor's direction, if it held a
// letter: `wouldBeWord(grid, coord, orientation)` in build-word.ts, beside
// buildWord. On a cell Preview keeps white (a letter or a symmetric hint)
// it is buildWord's word. On an off cell (active, empty, not a symmetric
// hint) it is the run through that cell, in Preview's geometry
// (intendedGeometry), of the grid with a letter placed there -- so the
// cell's symmetric counterpart turning white counts -- when that run has 2
// or more cells; otherwise null. A black cell (a grid saved before 14-S5)
// has none. buildWord itself is unchanged (locks keep using it).
//
// Imported through the module namespace so this file type-checks before
// the function exists; it then fails at run time. Do not edit this file to
// match an implementation.

type WouldBeWord = (grid: Grid, coord: Coord, orientation: Orientation) => Coord[] | null;

function wouldBeWord(grid: Grid, coord: Coord, orientation: Orientation): Coord[] | null {
  const fn = (buildWordModule as unknown as { wouldBeWord?: WouldBeWord }).wouldBeWord;
  if (typeof fn !== 'function') throw new Error('build-word.ts exports no wouldBeWord');
  return fn(grid, coord, orientation);
}

/** A grid from rows of text: a letter is a lettered cell, '.' an empty
 *  one, '#' a black cell (a grid saved before 14-S5). */
function gridOf(rows: string[]): Grid {
  const black: Coord[] = [];
  rows.forEach((letters, row) =>
    [...letters].forEach((letter, col) => {
      if (letter === '#') black.push({ col, row });
    })
  );
  let grid = createGrid({ cols: rows[0].length, rows: rows.length, black });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.' && letter !== '#') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

/** A 15×15 with `put` rows filled in, every other row empty. */
function daily(put: Record<number, string>): Grid {
  return gridOf(Array.from({ length: 15 }, (_, row) => put[row] ?? '...............'));
}

const across = (row: number, cols: number[]): Coord[] => cols.map((col) => ({ col, row }));
const down = (col: number, rows: number[]): Coord[] => rows.map((row) => ({ col, row }));
const range = (from: number, to: number) => Array.from({ length: to - from + 1 }, (_, i) => from + i);

// The human's across example on a daily's row 3 (counterpart of (c,r) is
// (14−c, 14−r)):  . C R A P _ A P E . . . . . .   (_ the off cell (5,3))
const CRAP_APE = daily({ 3: '.CRAP.APE......' });
// The human's down example: SIR down column 9, rows 3–5; (9,6) below it.
const SIR = gridOf(
  Array.from({ length: 15 }, (_, row) => {
    const letter = { 3: 'S', 4: 'I', 5: 'R' }[row];
    return letter ? `.........${letter}.....` : '...............';
  })
);

describe('22-S5-1 on a cell Preview keeps white, the word is buildWord\'s', () => {
  it('a letter in a word, a lone letter, a symmetric hint', () => {
    const coords: [Grid, Coord, Orientation][] = [
      [CRAP_APE, { col: 2, row: 3 }, 'across'],
      [CRAP_APE, { col: 7, row: 3 }, 'across'],
      [CRAP_APE, { col: 2, row: 3 }, 'down'], // R is alone down: null
      [CRAP_APE, { col: 12, row: 11 }, 'across'], // a symmetric hint (R's counterpart)
      [SIR, { col: 9, row: 4 }, 'down'],
      [SIR, { col: 9, row: 4 }, 'across'],
    ];
    for (const [grid, coord, orientation] of coords) {
      expect(wouldBeWord(grid, coord, orientation), `${coord.col},${coord.row} ${orientation}`).toEqual(
        buildWord(grid, coord, orientation)
      );
    }
    expect(wouldBeWord(CRAP_APE, { col: 2, row: 3 }, 'across')).toEqual(across(3, [1, 2, 3, 4]));
    expect(wouldBeWord(CRAP_APE, { col: 2, row: 3 }, 'down')).toBeNull();
  });
});

describe('22-S5-2 on an off cell, the word its letter would join', () => {
  it('between CRAP and APE, across: CRAP, the cell and APE', () => {
    expect(buildWord(CRAP_APE, { col: 5, row: 3 }, 'across')).toBeNull();
    expect(wouldBeWord(CRAP_APE, { col: 5, row: 3 }, 'across')).toEqual(across(3, range(1, 8)));
  });

  it('below SIR, down: SIR and the cell; above it, the cell and SIR', () => {
    expect(wouldBeWord(SIR, { col: 9, row: 6 }, 'down')).toEqual(down(9, [3, 4, 5, 6]));
    expect(wouldBeWord(SIR, { col: 9, row: 2 }, 'down')).toEqual(down(9, [2, 3, 4, 5]));
  });

  it('a word on one side only, at the grid\'s edge', () => {
    expect(wouldBeWord(CRAP_APE, { col: 0, row: 3 }, 'across')).toEqual(across(3, [0, 1, 2, 3, 4]));
    expect(wouldBeWord(CRAP_APE, { col: 9, row: 3 }, 'across')).toEqual(across(3, [6, 7, 8, 9]));
  });

  it('a symmetric hint next to the cell joins it too', () => {
    // Row 11 holds CRAP_APE's counterparts: symmetric hints at 6–8 and
    // 10–13. (9,11) is an off cell between them.
    expect(wouldBeWord(CRAP_APE, { col: 9, row: 11 }, 'across')).toEqual(across(11, range(6, 13)));
  });

  it('the other direction has its own word, or none', () => {
    expect(wouldBeWord(CRAP_APE, { col: 5, row: 3 }, 'down')).toBeNull();
    expect(wouldBeWord(SIR, { col: 9, row: 6 }, 'across')).toBeNull();
  });
});

describe('22-S5-3 the cell\'s symmetric counterpart turning white counts', () => {
  // The center row: A at (7,7) and T at (8,7) make (6,7) a symmetric hint.
  // A letter at (5,7) would make its counterpart (9,7) white as well.
  const CENTER = daily({ 7: '.......AT......' });

  it('the counterpart next to the run joins the word', () => {
    expect(buildWord(CENTER, { col: 5, row: 7 }, 'across')).toBeNull();
    expect(wouldBeWord(CENTER, { col: 5, row: 7 }, 'across')).toEqual(across(7, [5, 6, 7, 8, 9]));
  });

  it('a counterpart elsewhere in the line does not', () => {
    // Only A at (7,7): (6,7) and (8,7) stay off, so a letter at (5,7)
    // stands alone even though (9,7) would turn white.
    const lone = daily({ 7: '.......A.......' });
    expect(wouldBeWord(lone, { col: 5, row: 7 }, 'across')).toBeNull();
    // From the center's neighbor, the counterpart is on the other side.
    expect(wouldBeWord(lone, { col: 6, row: 7 }, 'across')).toEqual(across(7, [6, 7, 8]));
  });
});

describe('22-S5-4 no word, and nothing changed', () => {
  it('an off cell with no white neighbor in that direction has none', () => {
    expect(wouldBeWord(CRAP_APE, { col: 11, row: 3 }, 'across')).toBeNull();
    expect(wouldBeWord(CRAP_APE, { col: 5, row: 6 }, 'down')).toBeNull();
    expect(wouldBeWord(daily({}), { col: 7, row: 7 }, 'across')).toBeNull();
  });

  it('a black cell has none, and a black cell ends a word', () => {
    const old = gridOf(['AB#.C', '.....', '.....', '.....', '.....']);
    expect(wouldBeWord(old, { col: 2, row: 0 }, 'across')).toBeNull();
    expect(wouldBeWord(old, { col: 3, row: 0 }, 'across')).toEqual(across(0, [3, 4]));
  });

  it('leaves the grid as it was', () => {
    const before = JSON.stringify(CRAP_APE);
    wouldBeWord(CRAP_APE, { col: 5, row: 3 }, 'across');
    expect(JSON.stringify(CRAP_APE)).toBe(before);
    expect(CRAP_APE.at(5, 3)).toEqual({ kind: 'active', letter: null });
  });
});
