import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Grid } from '../engine/grid';
import { lockedWordsEndingAt, type LockedWord } from './locked-words';

// Story 21-S11 — hovering a tick mark darkens the locked words ending at
// its cell. A tick marks an end cell of a locked word (21-S2): the cell
// just before or just after it in its direction, none past the grid's
// edge, taken from the word's stored cells. `lockedWordsEndingAt(grid,
// lockedWords, coord)` gives every locked word with that cell as an end
// cell, in the list's order: none, one, or several where words share it
// (across and down alike).
//
// Do not edit this file to match an implementation.

/** A grid from rows of text: a letter is a lettered cell, '.' an empty one. */
function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

//   . . . . . . . .    row 0
//   C A T . D O G .    row 1: CAT from the left edge (no end cell before
//   . . . O . . . .    it), DOG; (3,1) ends both, and OWL down column 3
//   . . . W . . . .    (rows 2–4) too, before it. DOG's after end is (7,1),
//   . . . L . . . E    OWL's (3,5). EGG down column 7, rows 4–6, reaches
//   . . . . . . . G    the bottom edge: only (7,3) before it.
//   . . . . . . . G
const GRID = gridOf([
  '........',
  'CAT.DOG.',
  '...O....',
  '...W....',
  '...L...E',
  '.......G',
  '.......G',
]);

const CAT: LockedWord = { col: 0, row: 1, orientation: 'across', length: 3 };
const DOG: LockedWord = { col: 4, row: 1, orientation: 'across', length: 3 };
const OWL: LockedWord = { col: 3, row: 2, orientation: 'down', length: 3 };
const EGG: LockedWord = { col: 7, row: 4, orientation: 'down', length: 3 };

describe('21-S11-1 the locked words ending at a cell', () => {
  it('a cell three words end at gives all three, in the list\'s order', () => {
    expect(lockedWordsEndingAt(GRID, [CAT, DOG, OWL, EGG], { col: 3, row: 1 })).toEqual([CAT, DOG, OWL]);
    expect(lockedWordsEndingAt(GRID, [OWL, EGG, DOG, CAT], { col: 3, row: 1 })).toEqual([OWL, DOG, CAT]);
  });

  it('an end cell of one word gives that word', () => {
    const all = [CAT, DOG, OWL, EGG];
    expect(lockedWordsEndingAt(GRID, all, { col: 7, row: 1 })).toEqual([DOG]);
    expect(lockedWordsEndingAt(GRID, all, { col: 3, row: 5 })).toEqual([OWL]);
    expect(lockedWordsEndingAt(GRID, all, { col: 7, row: 3 })).toEqual([EGG]);
  });

  it('only locked words count: an unlocked word ending there is left out', () => {
    expect(lockedWordsEndingAt(GRID, [CAT, OWL], { col: 3, row: 1 })).toEqual([CAT, OWL]);
    expect(lockedWordsEndingAt(GRID, [CAT, OWL], { col: 7, row: 1 })).toEqual([]);
    expect(lockedWordsEndingAt(GRID, [], { col: 3, row: 1 })).toEqual([]);
  });

  it('a word\'s own cells, cells beside it and cells past an edge are no end cells', () => {
    const all = [CAT, DOG, OWL, EGG];
    // Letters of the words.
    for (const coord of [{ col: 0, row: 1 }, { col: 1, row: 1 }, { col: 5, row: 1 }, { col: 3, row: 3 }, { col: 7, row: 6 }]) {
      expect(lockedWordsEndingAt(GRID, all, coord), `${coord.col},${coord.row}`).toEqual([]);
    }
    // Beside a word, not in its direction: above CAT's A, left of OWL's W,
    // below DOG's O.
    for (const coord of [{ col: 1, row: 0 }, { col: 2, row: 3 }, { col: 5, row: 2 }]) {
      expect(lockedWordsEndingAt(GRID, all, coord), `${coord.col},${coord.row}`).toEqual([]);
    }
    // CAT touches the left edge and EGG the bottom: nothing wraps around.
    expect(lockedWordsEndingAt(GRID, all, { col: 7, row: 0 })).toEqual([]);
    expect(lockedWordsEndingAt(GRID, all, { col: 7, row: 6 })).toEqual([]);
    expect(lockedWordsEndingAt(GRID, all, { col: 0, row: 0 })).toEqual([]);
  });

  it('the end cells come from the stored words, whatever the grid now holds', () => {
    // The same locks on an empty grid of the same size.
    const empty = createGrid({ cols: 8, rows: 7 });
    expect(lockedWordsEndingAt(empty, [CAT, DOG, OWL], { col: 3, row: 1 })).toEqual([CAT, DOG, OWL]);
  });

  it('leaves its inputs unchanged', () => {
    const words = [CAT, DOG, OWL, EGG].map((word) => ({ ...word }));
    const before = JSON.stringify(words);
    const cells = JSON.stringify(Array.from({ length: GRID.rows }, (_, row) =>
      Array.from({ length: GRID.cols }, (_, col) => GRID.at(col, row))));
    lockedWordsEndingAt(GRID, words, { col: 3, row: 1 });
    expect(JSON.stringify(words)).toBe(before);
    expect(JSON.stringify(Array.from({ length: GRID.rows }, (_, row) =>
      Array.from({ length: GRID.cols }, (_, col) => GRID.at(col, row))))).toBe(cells);
  });
});
