import { describe, expect, it } from 'vitest';
import { createGrid, withLetter } from '../engine/grid';
import type { CursorState } from '../engine/cursor';
import { closeRebus, REBUS_MAX_LENGTH, rebusIntent, rebusText } from './rebus-entry';

// Story 17-S10 — Rebus entry's pure rules, outside the engine.
//
// Escape opens a rebus entry; while one is open, Enter or Escape closes it.
// The entry keeps only letters and digits, uppercase, at most 10. Closing
// places the whole string in the cursor cell with the engine's `place`
// (so the cursor advances as after a single letter) or, when the entry is
// closed by leaving it, without advancing. An empty entry clears the cell
// where clearing is allowed (not the hints phase) and otherwise changes
// nothing. An entry equal to the cell's letters changes nothing.
// keyToIntent is unchanged: P3-1 still maps Escape and Enter to null.
//
// Do not edit this file to match an implementation.

const across = (col: number, row: number): CursorState => ({ current: { col, row }, orientation: 'across' });

function row(letters: (string | null)[]) {
  let grid = createGrid({ cols: letters.length, rows: 1 });
  letters.forEach((letter, col) => {
    if (letter !== null) grid = withLetter(grid, { col, row: 0 }, letter);
  });
  return grid;
}

const letterAt = (grid: ReturnType<typeof row>, col: number) => {
  const cell = grid.at(col, 0);
  return cell.kind === 'active' ? cell.letter : undefined;
};

describe('17-S10-U1 rebusIntent', () => {
  it('Escape opens an entry while none is open', () => {
    expect(rebusIntent('Escape', false)).toBe('open');
  });

  it('Enter and Escape close an open entry', () => {
    expect(rebusIntent('Enter', true)).toBe('close');
    expect(rebusIntent('Escape', true)).toBe('close');
  });

  it('every other key is not a rebus key, and Enter opens nothing', () => {
    for (const key of ['Enter', 'a', 'A', '1', ' ', 'Backspace', 'ArrowLeft', 'Tab', 'Shift', '.']) {
      expect(rebusIntent(key, false), key).toBeNull();
    }
    for (const key of ['a', '1', ' ', 'Backspace', 'ArrowLeft', 'Tab']) {
      expect(rebusIntent(key, true), key).toBeNull();
    }
  });
});

describe('17-S10-U2 rebusText', () => {
  it('uppercases letters and keeps digits', () => {
    expect(rebusText('heart')).toBe('HEART');
    expect(rebusText('a1b2')).toBe('A1B2');
  });

  it('drops everything but letters and digits', () => {
    expect(rebusText(' h-e.a/r t!é')).toBe('HEART');
    expect(rebusText('   ')).toBe('');
  });

  it(`keeps at most ${REBUS_MAX_LENGTH} characters`, () => {
    expect(REBUS_MAX_LENGTH).toBe(10);
    expect(rebusText('abcdefghijklmn')).toBe('ABCDEFGHIJ');
  });
});

describe('17-S10-U3 closeRebus', () => {
  it('places the whole string and advances as a single letter does', () => {
    const grid = row([null, null, null]);
    const result = closeRebus(grid, across(0, 0), 'HEART', { advance: true, canClear: true });
    expect(letterAt(result.grid, 0)).toBe('HEART');
    expect(result.cursor).toEqual(across(1, 0));
  });

  it('at the last cell the cursor stays, as after a single letter', () => {
    const grid = row([null, null]);
    const result = closeRebus(grid, across(1, 0), 'OW', { advance: true, canClear: true });
    expect(letterAt(result.grid, 1)).toBe('OW');
    expect(result.cursor).toEqual(across(1, 0));
  });

  it('replaces the cell\'s letters, and without advance the cursor stays', () => {
    const grid = row(['A', 'B']);
    const result = closeRebus(grid, across(0, 0), 'STAR', { advance: false, canClear: true });
    expect(letterAt(result.grid, 0)).toBe('STAR');
    expect(letterAt(result.grid, 1)).toBe('B');
    expect(result.cursor).toEqual(across(0, 0));
  });

  it('an empty entry clears the cell where allowed, and the cursor stays', () => {
    const grid = row(['HEART', 'B']);
    const result = closeRebus(grid, across(0, 0), '', { advance: true, canClear: true });
    expect(letterAt(result.grid, 0)).toBeNull();
    expect(result.cursor).toEqual(across(0, 0));
  });

  it('an empty entry changes nothing where clearing is not allowed', () => {
    const grid = row(['HEART', 'B']);
    const result = closeRebus(grid, across(0, 0), '', { advance: true, canClear: false });
    expect(result.grid).toBe(grid);
    expect(result.cursor).toEqual(across(0, 0));
  });

  it('an empty entry on an empty cell changes nothing', () => {
    const grid = row([null, null]);
    const result = closeRebus(grid, across(0, 0), '', { advance: true, canClear: true });
    expect(result.grid).toBe(grid);
    expect(result.cursor).toEqual(across(0, 0));
  });

  it('an entry equal to the cell\'s letters keeps the same grid, and still advances', () => {
    const grid = row(['HEART', null]);
    const advanced = closeRebus(grid, across(0, 0), 'HEART', { advance: true, canClear: true });
    expect(advanced.grid).toBe(grid);
    expect(advanced.cursor).toEqual(across(1, 0));
    const kept = closeRebus(grid, across(0, 0), 'HEART', { advance: false, canClear: true });
    expect(kept.grid).toBe(grid);
    expect(kept.cursor).toEqual(across(0, 0));
  });

  it('never changes its input', () => {
    const grid = row(['A', null]);
    const cursor = across(0, 0);
    closeRebus(grid, cursor, 'STAR', { advance: true, canClear: true });
    expect(letterAt(grid, 0)).toBe('A');
    expect(cursor).toEqual(across(0, 0));
  });
});
