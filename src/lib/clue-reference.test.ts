import { beforeAll, describe, expect, it } from 'vitest';
import { createGrid, type Orientation } from '../engine/grid';
import type { NumberedSlot } from '../engine/numbering';
import { buildSlotLookup } from './hint-lookup';

// Story 26-S1, amended by 26-S3 — With/See references; no word decoration.
//
// `parseClueReference(text, slots, ownKey?)` in clue-reference.ts
// recognizes a hint that opens `With <number>-Across/Down` or
// `See <number>-Across/Down`, in any letter case, naming an existing entry:
// `^(?:with|see) ([1-9][0-9]*)-(across|down)\b`, case-insensitive.
// One space after the keyword, no leading zero, a hyphen,
// the direction as a whole word; anything may follow, the customary comma
// included. A hint naming its own entry (`ownKey`) is not recognized. It
// returns the entry's key, number and orientation, or null, and never
// changes its inputs.
//
// Imported through a variable path so this file type-checks before the
// module exists; it then fails at run time. Do not edit this file to
// match an implementation.

type Reference = { key: string; number: number; orientation: Orientation };
type ParseClueReference = (
  text: string,
  slots: ReadonlyMap<string, NumberedSlot>,
  ownKey?: string
) => Reference | null;

let implementation: Record<string, unknown> = {};

beforeAll(async () => {
  const modulePath = './clue-reference';
  implementation = (await import(modulePath)) as Record<string, unknown>;
});

function parseClueReference(
  text: string,
  slots: ReadonlyMap<string, NumberedSlot>,
  ownKey?: string
): Reference | null {
  const fn = implementation.parseClueReference as ParseClueReference | undefined;
  if (typeof fn !== 'function') throw new Error('clue-reference.ts exports no parseClueReference');
  return fn(text, slots, ownKey);
}

// A 3×3 with (2,2) black: 1-Across, 4-Across, 5-Across, 1-Down, 2-Down,
// 3-Down. There is no 4-Down and no 82-Across.
const slots = buildSlotLookup(createGrid({ cols: 3, rows: 3, black: [{ col: 2, row: 2 }] }));

const FOUR_ACROSS: Reference = { key: '4-across', number: 4, orientation: 'across' };
const TWO_DOWN: Reference = { key: '2-down', number: 2, orientation: 'down' };

describe('26-S1-1 valid', () => {
  it('With 4-Across, and With 2-Down, name their entries', () => {
    expect(parseClueReference('With 4-Across, x', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('With 2-Down, x', slots)).toEqual(TWO_DOWN);
  });

  it('nothing after the reference, no comma, or other punctuation', () => {
    expect(parseClueReference('With 4-Across,', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('With 4-Across', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('With 4-Across x', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('With 4-Across: x', slots)).toEqual(FOUR_ACROSS);
  });

  it('any letter case', () => {
    expect(parseClueReference('with 4-across,', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('With 4-across,', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('WITH 4-ACROSS,', slots)).toEqual(FOUR_ACROSS);
    expect(parseClueReference('with 2-DOWN,', slots)).toEqual(TWO_DOWN);
  });
});

describe('26-S1-2 no such entry', () => {
  it('a number the puzzle lacks', () => {
    expect(parseClueReference('With 82-Across,', slots)).toBeNull();
  });

  it('a number the puzzle has, in the wrong direction', () => {
    expect(parseClueReference('With 4-Down,', slots)).toBeNull();
  });
});

describe('26-S1-3 syntax', () => {
  it.each([
    'With 4 Across,',
    'With4-Across,',
    'With -Across,',
    'With 4 horizontal,',
    'With 4-Acrosses,',
    '4-Across has a partner',
    ' With 4-Across,',
    'With 04-Across,',
    'With 1- and 4-Across,',
    'With 4A,',
  ])('%j is ordinary text', (text) => {
    expect(parseClueReference(text, slots)).toBeNull();
  });
});

describe('26-S1-4 self-reference', () => {
  it('a hint naming its own entry is not recognized', () => {
    expect(parseClueReference('With 4-Across,', slots, '4-across')).toBeNull();
  });

  it('on another entry it is', () => {
    expect(parseClueReference('With 4-Across,', slots, '1-down')).toEqual(FOUR_ACROSS);
  });
});

describe('26-S1-5 editing', () => {
  it('re-parsed as the text changes, without changing its inputs', () => {
    const before = new Map(slots);
    const snapshot = JSON.stringify([...slots.entries()]);
    const steps: [string, Reference | null][] = [
      ['With 4-Across, x', FOUR_ACROSS],
      ['With 82-Across, x', null],
      ['With 4-Across, x', FOUR_ACROSS],
    ];
    for (const [text, expected] of steps) {
      const input = text;
      expect(parseClueReference(input, slots, '1-down')).toEqual(expected);
      expect(input).toBe(text);
    }
    expect(slots.size).toBe(before.size);
    expect(JSON.stringify([...slots.entries()])).toBe(snapshot);
  });
});

describe('26-S2-1 linked entry cells', () => {
  it('returns the referenced cells in order, or none, without changing inputs', () => {
    const fn = implementation.linkedEntryCells as ((
      hints: Readonly<Record<string, string>>,
      currentKey: string | null,
      slots: ReadonlyMap<string, NumberedSlot>,
    ) => readonly { col: number; row: number }[]) | undefined;
    if (typeof fn !== 'function') throw new Error('clue-reference.ts exports no linkedEntryCells');
    const hints = Object.freeze({
      '1-down': 'With 4-Across, x',
      '1-across': 'Ordinary hint',
      '2-down': 'With 82-Across, x',
      '3-down': 'With 4 Across, x',
      '4-across': 'With 4-Across, x',
    });
    const before = JSON.stringify({ hints, slots: [...slots] });
    expect(fn(hints, '1-down', slots)).toEqual([
      { col: 0, row: 1 }, { col: 1, row: 1 }, { col: 2, row: 1 },
    ]);
    for (const key of [null, '1-across', '2-down', '3-down', '4-across', '5-across']) {
      expect(fn(hints, key, slots), String(key)).toEqual([]);
    }
    expect(JSON.stringify({ hints, slots: [...slots] })).toBe(before);
  });
});

// Explicit human amendment 26-S3 replaces S1's See-is-ordinary expectation.
describe('26-S3-1 See uses the same validated syntax as With', () => {
  it.each(['See 4-Across, x', 'see 4-across', 'SEE 4-ACROSS: x'])('%s', (text) => {
    expect(parseClueReference(text, slots, '1-down')).toEqual(FOUR_ACROSS);
  });
  it('supports Down, rejects self/nonexistent/malformed references and preserves inputs', () => {
    const before = JSON.stringify([...slots]);
    expect(parseClueReference('sEe 2-dOwN, x', slots, '1-across')).toEqual(TWO_DOWN);
    expect(parseClueReference('See 2-Down', slots, '2-down')).toBeNull();
    for (const text of ['See 82-Across', 'See 4-Down', 'See 4 Across', ' See 4-Across',
      'See4-Across', 'See 04-Across', 'See 4-Acrosses', 'See 4A', 'See 1- and 4-Across']) {
      expect(parseClueReference(text, slots), text).toBeNull();
    }
    const fn = implementation.linkedEntryCells as (
      hints: Readonly<Record<string, string>>, currentKey: string | null,
      slots: ReadonlyMap<string, NumberedSlot>,
    ) => readonly { col: number; row: number }[];
    const hints = Object.freeze({ '1-down': 'See 4-Across, x' });
    expect(fn(hints, '1-down', slots)).toEqual([
      { col: 0, row: 1 }, { col: 1, row: 1 }, { col: 2, row: 1 },
    ]);
    expect(hints['1-down']).toBe('See 4-Across, x');
    expect(JSON.stringify([...slots])).toBe(before);
  });
});
