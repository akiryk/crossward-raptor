import { describe, expect, it } from 'vitest';
import { createGrid, withLetter, type Grid } from '../engine/grid';
import { tickTarget, type LockedWord } from './locked-words';

// Story 21-S13 — hovering a ticked end cell shows one locked word's lock
// button. `tickTarget(grid, lockedWords, coord, orientation)` picks that
// word from the locked words ending at the cell (21-S11's
// `lockedWordsEndingAt`): one in the cursor's direction if there is any,
// else one in the other direction. Within a direction, at most two words
// end at a cell: the one starting just after it wins over the one ending
// just before it. The list's order doesn't matter. No locked word ending
// there gives null.
//
// Do not edit this file to match an implementation.

/** A grid from rows of text: a letter is a lettered cell, '.' an empty one. */
function gridOf(rows: string[]): Grid {
  let grid = createGrid({ cols: rows[0].length, rows: rows.length });
  rows.forEach((letters, row) => {
    [...letters].forEach((letter, col) => {
      if (letter !== '.') grid = withLetter(grid, { col, row }, letter);
    });
  });
  return grid;
}

//   . . . . . . . .    row 0
//   . . . B . . . .    row 1: BEE down column 3 (rows 1–3), ending just
//   . . . E . . . .           above (3,4)
//   . . . E . . . .
//   C A T . D O G .    row 4: CAT ends just left of (3,4), DOG starts
//   . . . O . . . .           just right of it, and OWL down column 3
//   . . . W . . . .           (rows 5–7) just below it. (3,4) ends all
//   . . . L . . . .           four. DOG's after end is (7,4), OWL's (3,8).
//   . . . . . . . .
const GRID = gridOf([
  '........',
  '...B....',
  '...E....',
  '...E....',
  'CAT.DOG.',
  '...O....',
  '...W....',
  '...L....',
  '........',
]);

const BEE: LockedWord = { col: 3, row: 1, orientation: 'down', length: 3 };
const CAT: LockedWord = { col: 0, row: 4, orientation: 'across', length: 3 };
const DOG: LockedWord = { col: 4, row: 4, orientation: 'across', length: 3 };
const OWL: LockedWord = { col: 3, row: 5, orientation: 'down', length: 3 };

const SHARED = { col: 3, row: 4 };
const ALL = [BEE, CAT, DOG, OWL];

describe('21-S13-1 the word a ticked end cell shows the button for', () => {
  it('the cursor\'s direction first; in it, the word starting just after the cell', () => {
    expect(tickTarget(GRID, ALL, SHARED, 'across')).toEqual(DOG);
    expect(tickTarget(GRID, ALL, SHARED, 'down')).toEqual(OWL);
  });

  it('with no word starting just after, the one ending just before', () => {
    expect(tickTarget(GRID, [BEE, CAT, OWL], SHARED, 'across')).toEqual(CAT);
    expect(tickTarget(GRID, [BEE, CAT, DOG], SHARED, 'down')).toEqual(BEE);
  });

  it('with no locked word in the cursor\'s direction, the other direction\'s, by the same rule', () => {
    expect(tickTarget(GRID, [BEE, OWL], SHARED, 'across')).toEqual(OWL);
    expect(tickTarget(GRID, [BEE], SHARED, 'across')).toEqual(BEE);
    expect(tickTarget(GRID, [CAT, DOG], SHARED, 'down')).toEqual(DOG);
    expect(tickTarget(GRID, [CAT], SHARED, 'down')).toEqual(CAT);
  });

  it('the list\'s order doesn\'t matter', () => {
    const reversed = [...ALL].reverse();
    expect(tickTarget(GRID, reversed, SHARED, 'across')).toEqual(DOG);
    expect(tickTarget(GRID, reversed, SHARED, 'down')).toEqual(OWL);
    expect(tickTarget(GRID, [OWL, BEE], SHARED, 'across')).toEqual(OWL);
    expect(tickTarget(GRID, [DOG, CAT], SHARED, 'down')).toEqual(DOG);
  });

  it('an end cell of one word gives that word in either direction', () => {
    expect(tickTarget(GRID, ALL, { col: 7, row: 4 }, 'across')).toEqual(DOG);
    expect(tickTarget(GRID, ALL, { col: 7, row: 4 }, 'down')).toEqual(DOG);
    expect(tickTarget(GRID, ALL, { col: 3, row: 8 }, 'across')).toEqual(OWL);
    expect(tickTarget(GRID, ALL, { col: 3, row: 0 }, 'down')).toEqual(BEE);
  });

  it('no locked word ending at the cell gives null', () => {
    // An unlocked DOG: its after end has no locked word.
    expect(tickTarget(GRID, [BEE, CAT, OWL], { col: 7, row: 4 }, 'across')).toBeNull();
    expect(tickTarget(GRID, [], SHARED, 'across')).toBeNull();
    // A word's own letters, a cell beside a word, a far corner.
    for (const coord of [{ col: 1, row: 4 }, { col: 3, row: 6 }, { col: 2, row: 2 }, { col: 7, row: 8 }]) {
      expect(tickTarget(GRID, ALL, coord, 'across'), `${coord.col},${coord.row}`).toBeNull();
      expect(tickTarget(GRID, ALL, coord, 'down'), `${coord.col},${coord.row}`).toBeNull();
    }
  });

  it('the end cells come from the stored words, whatever the grid now holds', () => {
    const empty = createGrid({ cols: 8, rows: 9 });
    expect(tickTarget(empty, ALL, SHARED, 'across')).toEqual(DOG);
    expect(tickTarget(empty, ALL, SHARED, 'down')).toEqual(OWL);
  });

  it('leaves its inputs unchanged', () => {
    const words = ALL.map((word) => ({ ...word }));
    const before = JSON.stringify(words);
    const cells = () =>
      JSON.stringify(Array.from({ length: GRID.rows }, (_, row) =>
        Array.from({ length: GRID.cols }, (_, col) => GRID.at(col, row))));
    const gridBefore = cells();
    tickTarget(GRID, words, SHARED, 'across');
    tickTarget(GRID, words, SHARED, 'down');
    expect(JSON.stringify(words)).toBe(before);
    expect(cells()).toBe(gridBefore);
  });
});
