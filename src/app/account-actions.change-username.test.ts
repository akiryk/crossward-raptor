import { beforeEach, describe, expect, it, vi } from 'vitest';

// Story 23-S4 — changing a username from Account details.
// `changeUsername(value)` is the masthead's Account details save. Only a
// signed-in account that already has a username may call it (the guard is
// `requireSession()`; an account without one is refused like no session and
// sent to /, where the username step is its one way in). It changes only the
// signed-in account's own `displayName`, to the trimmed value, under the
// username rules (lib/username: 1–80 characters once trimmed), and returns
// `{ ok: true }` without navigating, so the page the user is on stays. A
// value that breaks the rules writes nothing and returns the rule's message.
//
// The write may be `prisma.user.update` or `updateMany`; either way exactly
// one write, keyed by the session user's id alone, setting only displayName.
// Do not edit this file to match an implementation.

const mocks = vi.hoisted(() => ({
  getSession: vi.fn(),
  headers: vi.fn(),
  revalidatePath: vi.fn(),
  userUpdate: vi.fn(),
  userUpdateMany: vi.fn(),
  userFindUnique: vi.fn(),
  other: vi.fn(),
}));

vi.mock('@/lib/auth', () => ({ auth: { api: { getSession: mocks.getSession } } }));
vi.mock('next/headers', () => ({ headers: mocks.headers }));
vi.mock('next/navigation', () => ({
  redirect: (path: string) => { throw new Error(`redirect:${path}`); },
}));
vi.mock('next/cache', () => ({ revalidatePath: mocks.revalidatePath }));
vi.mock('@/lib/prisma', () => {
  const unsupported = new Proxy({}, { get: () => mocks.other });
  return {
    prisma: {
      user: { update: mocks.userUpdate, updateMany: mocks.userUpdateMany, findUnique: mocks.userFindUnique },
      puzzle: unsupported,
      playSession: unsupported,
      session: unsupported,
      account: unsupported,
      verification: unsupported,
      $transaction: mocks.other,
    },
  };
});

import * as accountActions from './account-actions';

const requestHeaders = new Headers({ cookie: 'better-auth.session_token=token' });
const BLANK = 'Oops! You need to add a username.';
const LONG = 'Oops! Use 80 characters or fewer.';

/** The action under test, looked up so a missing export fails each case, not the file. */
function changeUsername(...args: unknown[]): Promise<unknown> {
  const action = (accountActions as Record<string, unknown>).changeUsername;
  if (typeof action !== 'function') throw new Error('account-actions exports no changeUsername');
  return (action as (...a: unknown[]) => Promise<unknown>)(...args);
}

function signedIn(displayName: unknown, id = 'own-user') {
  mocks.getSession.mockResolvedValue({
    user: { id, email: `${id}@example.test`, name: '', displayName },
    session: { id: `session-${id}`, userId: id },
  });
}

/** Every user write, normalized to its where and data. */
function writes() {
  return [...mocks.userUpdate.mock.calls, ...mocks.userUpdateMany.mock.calls].map(([args]) => ({
    where: args.where,
    data: args.data,
  }));
}

function expectNoWrite() {
  expect(writes()).toEqual([]);
  expect(mocks.other).not.toHaveBeenCalled();
}

beforeEach(() => {
  vi.resetAllMocks();
  mocks.headers.mockResolvedValue(requestHeaders);
  mocks.userUpdate.mockImplementation(async ({ data }) => ({ id: 'own-user', ...data }));
  mocks.userUpdateMany.mockResolvedValue({ count: 1 });
  mocks.userFindUnique.mockResolvedValue({ id: 'own-user', displayName: 'Old Name' });
});

describe('23-S4-U1 the module', () => {
  it('exports changeUsername and saveUsername and no other action', () => {
    const exported = Object.entries(accountActions)
      .filter(([, value]) => typeof value === 'function')
      .map(([name]) => name)
      .sort();
    expect(exported).toEqual(['changeUsername', 'saveUsername']);
  });
});

describe('23-S4-U2 changing a username', () => {
  it('sets only the signed-in account’s displayName and returns { ok: true } without navigating', async () => {
    signedIn('Old Name');
    await expect(changeUsername('Lil Orange Fox')).resolves.toEqual({ ok: true });
    expect(mocks.getSession).toHaveBeenCalledWith({ headers: requestHeaders });
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: 'Lil Orange Fox' } }]);
    expect(mocks.other).not.toHaveBeenCalled();
  });

  it('stores the trimmed value', async () => {
    signedIn('Old Name');
    await expect(changeUsername('  Ada Lovelace \t')).resolves.toEqual({ ok: true });
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: 'Ada Lovelace' } }]);
  });

  it('accepts 80 code points', async () => {
    signedIn('Old Name');
    await expect(changeUsername('🦖'.repeat(80))).resolves.toEqual({ ok: true });
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: '🦖'.repeat(80) } }]);
  });

  it('saves a value equal to the current username (no special case)', async () => {
    signedIn('Same');
    await expect(changeUsername('Same')).resolves.toEqual({ ok: true });
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: 'Same' } }]);
  });

  it('writes only the caller’s own account, whatever else is passed', async () => {
    signedIn('Caller', 'caller');
    await expect(
      changeUsername('Ada', 'victim', { id: 'victim', userId: 'victim', email: 'x@example.test' }),
    ).resolves.toEqual({ ok: true });
    expect(writes()).toEqual([{ where: { id: 'caller' }, data: { displayName: 'Ada' } }]);
  });
});

describe('23-S4-U3 the username rules, on the server', () => {
  it.each([
    ['empty', '', BLANK],
    ['spaces', '   ', BLANK],
    ['tabs and newlines', '\t\n', BLANK],
    ['81 code points', '🦖'.repeat(81), LONG],
    ['81 letters after trimming', `  ${'a'.repeat(81)}  `, LONG],
  ])('refuses %s with its message and writes nothing', async (_label, value, message) => {
    signedIn('Old Name');
    await expect(changeUsername(value)).resolves.toEqual({ error: message });
    expectNoWrite();
  });

  it.each([['undefined', undefined], ['null', null], ['a number', 42], ['an object', { toString: () => 'Ada' }], ['an array', ['Ada']]])(
    'refuses %s, which is not text, and writes nothing',
    async (_label, value) => {
      signedIn('Old Name');
      await expect(changeUsername(value)).resolves.toEqual({ error: BLANK });
      expectNoWrite();
    },
  );
});

describe('23-S4-U4 only an account with a username', () => {
  it('without a session: sends the browser to / and writes nothing', async () => {
    mocks.getSession.mockResolvedValue(null);
    await expect(changeUsername('Ada')).rejects.toThrow(/^redirect:\/$/);
    expect(mocks.getSession).toHaveBeenCalledWith({ headers: requestHeaders });
    expectNoWrite();
  });

  it.each([['null', null], ['empty', ''], ['whitespace', ' \t '], ['missing', undefined]])(
    'a session whose username is %s is refused like no session and writes nothing',
    async (_label, displayName) => {
      signedIn(displayName);
      await expect(changeUsername('Ada')).rejects.toThrow(/^redirect:\/$/);
      expectNoWrite();
    },
  );

  it('checks the session before the value', async () => {
    mocks.getSession.mockResolvedValue(null);
    await expect(changeUsername('')).rejects.toThrow(/^redirect:\/$/);
    signedIn(null);
    await expect(changeUsername('')).rejects.toThrow(/^redirect:\/$/);
    expectNoWrite();
  });
});
