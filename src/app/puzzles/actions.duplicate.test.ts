import { beforeEach, describe, expect, it, vi } from 'vitest';
import { Prisma } from '@prisma/client';

// 16-S4 acceptance (16-S4-5): duplicatePuzzle, against an in-memory store that
// applies Prisma's where semantics and models only puzzle reads and `create`.
// Like Prisma, `create` fills the schema defaults for fields it isn't given,
// rejects unknown fields, and rejects a plain `null` (or JSON null) for the
// `Json?` field `gridBeforeHints`: only omitting it or `Prisma.DbNull` stores a
// database null. Updates, deletes, raw SQL and any play-session access throw.
// Never a database connection. Do not edit this file to match an implementation.

const mocks = vi.hoisted(() => ({
  requireSession: vi.fn(), revalidatePath: vi.fn(), unsupported: vi.fn(),
  puzzle: { findUnique: vi.fn(), findFirst: vi.fn(), create: vi.fn() },
}));
vi.mock('@/lib/require-session', () => ({ requireSession: mocks.requireSession }));
vi.mock('next/cache', () => ({ revalidatePath: mocks.revalidatePath }));
vi.mock('@/lib/prisma', () => {
  const unsupported = (name: string) => (...args: unknown[]) => {
    mocks.unsupported(name, ...args);
    throw new Error(`unsupported in this store: ${name}`);
  };
  const puzzle = new Proxy(mocks.puzzle as Record<string, unknown>, {
    get: (target, key: string) => target[key] ?? unsupported(`puzzle.${key}`),
  });
  const playSession = new Proxy({}, { get: (_target, key: string) => unsupported(`playSession.${key}`) });
  const prisma: Record<string, unknown> = {
    puzzle, playSession,
    $executeRaw: unsupported('$executeRaw'), $executeRawUnsafe: unsupported('$executeRawUnsafe'),
    $queryRaw: unsupported('$queryRaw'), $queryRawUnsafe: unsupported('$queryRawUnsafe'),
  };
  prisma.$transaction = async (arg: unknown) => {
    if (typeof arg === 'function') return (arg as (tx: unknown) => unknown)(prisma);
    return Promise.all(arg as Promise<unknown>[]);
  };
  return { prisma };
});
import { duplicatePuzzle } from './actions';

type Row = Record<string, unknown>;
type State = 'grid' | 'hints' | 'private' | 'public';

const CALLER = 'builder-a';
const OTHER = 'builder-b';
const FIELDS = ['id', 'builderId', 'title', 'grid', 'gridBeforeHints', 'hints', 'phase', 'publishedAt', 'visibility', 'createdAt', 'updatedAt'];

let puzzles: Row[];
let nextId: number;

function puzzle(id: string, builderId: string, state: State, title = `Title ${id}`): Row {
  const row: Row = {
    id, builderId, title,
    grid: { cols: 2, rows: 1, cells: [[{ kind: 'active', letter: 'A' }, { kind: 'black' }]] },
    gridBeforeHints: state === 'grid' ? null : { cols: 2, rows: 1, cells: [[{ kind: 'active', letter: null }, { kind: 'active', letter: null }]] },
    hints: state === 'grid' ? {} : { '1-across': 'Clue' },
    phase: state === 'grid' ? 'grid' : 'hints',
    publishedAt: state === 'private' || state === 'public' ? new Date('2026-01-02T03:04:05Z') : null,
    visibility: state === 'public' ? 'public' : 'private',
    createdAt: new Date('2026-01-01T00:00:00Z'),
    updatedAt: new Date('2026-01-03T00:00:00Z'),
  };
  puzzles.push(row);
  return row;
}

function same(a: unknown, b: unknown) {
  return a instanceof Date && b instanceof Date ? a.getTime() === b.getTime() : a === b;
}

/** Prisma's where semantics for the scalar filters a guarded read can use. */
function matches(row: Row, where: Row | undefined): boolean {
  if (!where) return true;
  return Object.entries(where).every(([key, expected]) => {
    if (key === 'AND') return ([] as Row[]).concat(expected as Row | Row[]).every((clause) => matches(row, clause));
    if (key === 'OR') return (expected as Row[]).some((clause) => matches(row, clause));
    if (key === 'NOT') return !([] as Row[]).concat(expected as Row | Row[]).some((clause) => matches(row, clause));
    if (!(key in row)) throw new Error(`unsupported filter: ${key}`);
    const actual = row[key];
    if (expected === null || expected instanceof Date || typeof expected !== 'object') return same(actual, expected);
    return Object.entries(expected as Row).every(([op, value]) => {
      if (op === 'equals') return same(actual, value);
      if (op === 'not') return value === null ? actual !== null : !same(actual, value);
      if (op === 'in') return (value as unknown[]).some((v) => same(actual, v));
      if (op === 'notIn') return !(value as unknown[]).some((v) => same(actual, v));
      throw new Error(`unsupported operator: ${key}.${op}`);
    });
  });
}

function project(row: Row, select: Record<string, unknown> | undefined) {
  if (!select) return structuredClone(row);
  return Object.fromEntries(Object.keys(select).filter((key) => select[key]).map((key) => {
    if (!(key in row)) throw new Error(`unsupported select: ${key}`);
    return [key, structuredClone(row[key])];
  }));
}

/** Prisma's create for this model: schema defaults, `Json?` null handling. */
function create(data: Row): Row {
  for (const key of Object.keys(data)) if (!FIELDS.includes(key)) throw new Error(`unsupported field: ${key}`);
  for (const key of ['builderId', 'grid', 'hints']) if (data[key] === undefined) throw new Error(`missing field: ${key}`);
  if (data.gridBeforeHints === null) throw new Error('Argument gridBeforeHints must not be null: use Prisma.DbNull');
  if (data.gridBeforeHints === Prisma.JsonNull) throw new Error('unsupported in this store: a JSON null gridBeforeHints');
  const now = new Date();
  const { gridBeforeHints, ...rest } = data;
  const row: Row = {
    id: `created-${nextId++}`,
    title: 'Untitled Puzzle',
    phase: 'grid',
    publishedAt: null,
    visibility: 'private',
    createdAt: now,
    updatedAt: now,
    ...structuredClone(rest),
    gridBeforeHints: gridBeforeHints === undefined || gridBeforeHints === Prisma.DbNull ? null : structuredClone(gridBeforeHints),
  };
  if (puzzles.some((existing) => existing.id === row.id)) throw Object.assign(new Error('Unique constraint failed on id'), { code: 'P2002' });
  puzzles.push(row);
  return row;
}

beforeEach(() => {
  vi.resetAllMocks();
  puzzles = [];
  nextId = 1;
  mocks.requireSession.mockResolvedValue({ user: { id: CALLER }, session: { id: 'valid' } });
  mocks.puzzle.findUnique.mockImplementation(async ({ where, select }: { where: Row; select?: Row }) => {
    const found = puzzles.find((row) => matches(row, where));
    return found ? project(found, select) : null;
  });
  mocks.puzzle.findFirst.mockImplementation(async ({ where, select }: { where: Row; select?: Row }) => {
    const found = puzzles.find((row) => matches(row, where));
    return found ? project(found, select) : null;
  });
  mocks.puzzle.create.mockImplementation(async ({ data, select }: { data: Row; select?: Row }) => project(create(data), select));
});

describe('16-S4-5 duplicatePuzzle', () => {
  for (const state of ['grid', 'hints', 'private', 'public'] as const) {
    it(`copies the caller’s ${state} puzzle into a new unpublished one of theirs, leaving the source alone`, async () => {
      const source = puzzle('source', CALLER, state);
      const before = structuredClone(source);

      const result = await duplicatePuzzle('source');
      expect(Object.keys(result)).toEqual(['id']);
      expect(result.id).not.toBe('source');
      expect(puzzles).toHaveLength(2);
      const copy = puzzles.find((row) => row.id === result.id);
      if (!copy) throw new Error('the returned id is not the created puzzle');

      expect(copy.builderId, 'owned by the caller').toBe(CALLER);
      expect(copy.title, 'title').toBe('Title source (copy)');
      expect(copy.grid, 'grid and letters').toEqual(before.grid);
      expect(copy.hints, 'hints').toEqual(before.hints);
      expect(copy.phase, 'phase').toBe(before.phase);
      expect(copy.gridBeforeHints, 'gridBeforeHints').toEqual(before.gridBeforeHints);
      expect(copy.publishedAt, 'unpublished').toBeNull();
      expect(copy.visibility, 'the default visibility').toBe('private');
      expect((copy.createdAt as Date).getTime(), 'created now').toBeGreaterThan((before.updatedAt as Date).getTime());
      expect((copy.updatedAt as Date).getTime(), 'updated now').toBeGreaterThan((before.updatedAt as Date).getTime());

      expect(source, 'the source is unchanged').toEqual(before);
      expect(mocks.puzzle.create).toHaveBeenCalledTimes(1);
      expect(mocks.revalidatePath).toHaveBeenCalledWith('/puzzles');
    });
  }

  it('a copy of a copy appends another " (copy)"', async () => {
    puzzle('source', CALLER, 'hints', 'Sunday');
    const first = await duplicatePuzzle('source');
    const second = await duplicatePuzzle(first.id);
    expect(puzzles.map((row) => row.title)).toEqual(['Sunday', 'Sunday (copy)', 'Sunday (copy) (copy)']);
    expect(second.id).not.toBe(first.id);
  });

  it('refuses another builder’s puzzle, in every state, and a missing one, creating nothing', async () => {
    for (const state of ['grid', 'hints', 'private', 'public'] as const) puzzle(`theirs-${state}`, OTHER, state);
    const before = structuredClone(puzzles);

    for (const id of ['theirs-grid', 'theirs-hints', 'theirs-private', 'theirs-public', 'missing']) {
      await expect(duplicatePuzzle(id), id).rejects.toThrow();
    }
    expect(puzzles).toEqual(before);
    expect(mocks.puzzle.create).not.toHaveBeenCalled();
    expect(mocks.revalidatePath).not.toHaveBeenCalled();
  });

  it('requires a session before touching the database', async () => {
    puzzle('source', CALLER, 'public');
    const before = structuredClone(puzzles);
    mocks.requireSession.mockRejectedValue(new Error('redirect:/'));
    await expect(duplicatePuzzle('source')).rejects.toThrow();
    for (const method of Object.values(mocks.puzzle)) expect(method).not.toHaveBeenCalled();
    expect(mocks.revalidatePath).not.toHaveBeenCalled();
    expect(puzzles).toEqual(before);
  });

  it('never reads or writes play sessions, never writes the source, and uses no raw SQL', async () => {
    for (const state of ['grid', 'hints', 'private', 'public'] as const) puzzle(`own-${state}`, CALLER, state);
    for (const state of ['grid', 'hints', 'private', 'public'] as const) await duplicatePuzzle(`own-${state}`);
    expect(mocks.unsupported).not.toHaveBeenCalled();
  });
});
