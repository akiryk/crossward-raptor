import { isDeepStrictEqual } from 'node:util';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { createGrid, withLetter } from '@/engine/grid';
import { hintKey, requiredHints } from '@/engine/hints';
import { serializePuzzle } from '@/lib/puzzle-storage';

// Story 14-S4 — publishing needs every hint. `publishPuzzle` rejects a
// puzzle with a missing, empty or whitespace-only required hint, the same
// way it rejects any other ineligible puzzle, and leaves it unchanged. The
// check holds at the moment of publishing: a write that blanks a hint
// between the action's read and its write must not be published over. The
// store below applies each write's filter at the write and runs
// `$transaction` without isolation, as Postgres's default isolation would.
//
// Do not edit this file to match an implementation.

const mocks = vi.hoisted(() => ({
  requireSession: vi.fn(), revalidatePath: vi.fn(),
  findUnique: vi.fn(), findUniqueOrThrow: vi.fn(), findFirst: vi.fn(),
  update: vi.fn(), updateMany: vi.fn(),
}));
vi.mock('@/lib/require-session', () => ({ requireSession: mocks.requireSession }));
vi.mock('next/cache', () => ({ revalidatePath: mocks.revalidatePath }));
vi.mock('@/lib/prisma', () => {
  const db = { puzzle: {
    findUnique: mocks.findUnique, findUniqueOrThrow: mocks.findUniqueOrThrow,
    findFirst: mocks.findFirst, update: mocks.update, updateMany: mocks.updateMany,
  } };
  return { prisma: { ...db, $transaction: async (work: (client: typeof db) => unknown) => work(db) } };
});

import * as actions from './actions';

let grid = createGrid({ cols: 3, rows: 3 });
for (let row = 0; row < 3; row++) {
  for (let col = 0; col < 3; col++) grid = withLetter(grid, { col, row }, 'A');
}
const { across, down } = requiredHints(grid);
const KEYS = [...across, ...down].map(hintKey);
const COMPLETE = Object.fromEntries(KEYS.map((key) => [key, `Hint ${key}`]));
const stored = serializePuzzle({ grid, hints: COMPLETE, phase: 'hints' });

type Row = {
  id: string; builderId: string; title: string; phase: string;
  grid: unknown; hints: unknown; gridBeforeHints: unknown;
  publishedAt: Date | null; visibility: string; createdAt: Date; updatedAt: Date;
};
type Where = Record<string, unknown>;
type Query = { where: Where; data?: Record<string, unknown>; select?: Record<string, boolean> };
let rows: Row[];
let writes: Query[];
let afterRead: (() => void) | undefined;

function same(actual: unknown, expected: unknown) {
  if (expected instanceof Date) return actual instanceof Date && actual.getTime() === expected.getTime();
  return isDeepStrictEqual(actual, expected);
}

// The usual Prisma filter forms, including a JSON `equals`.
function matches(row: Row, where: Where): boolean {
  return Object.entries(where).every(([key, value]) => {
    if (key === 'AND') return (Array.isArray(value) ? value : [value]).every((part) => matches(row, part as Where));
    if (key === 'OR') return (value as Where[]).some((part) => matches(row, part));
    if (key === 'NOT') return !(Array.isArray(value) ? value : [value]).some((part) => matches(row, part as Where));
    const actual = row[key as keyof Row];
    if (value === null || typeof value !== 'object' || value instanceof Date) return same(actual, value);
    const filter = value as Record<string, unknown>;
    if ('equals' in filter) return same(actual, filter.equals);
    if ('in' in filter) return (filter.in as unknown[]).some((option) => same(actual, option));
    if ('not' in filter) return !same(actual, filter.not);
    throw new Error(`Unsupported acceptance-store filter: ${key}`);
  });
}
function own() { return rows.find((row) => row.id === 'target')!; }

beforeEach(() => {
  vi.resetAllMocks();
  writes = [];
  afterRead = undefined;
  rows = ['target', 'decoy'].map((id) => ({
    ...structuredClone(stored), id, builderId: 'session-builder', title: `Original ${id}`,
    gridBeforeHints: null, publishedAt: null, visibility: 'private',
    createdAt: new Date('2026-01-01T00:00:00Z'), updatedAt: new Date('2026-01-02T00:00:00Z'),
  }));
  mocks.requireSession.mockResolvedValue({ user: { id: 'session-builder', role: 'user' } });
  const read = async (query: Query, required = false) => {
    const row = rows.find((candidate) => matches(candidate, query.where));
    if (!row && required) throw new Error('No matching puzzle');
    const snapshot = row ? structuredClone(row) : null;
    afterRead?.();
    afterRead = undefined;
    return snapshot && query.select
      ? Object.fromEntries(Object.entries(snapshot).filter(([key]) => query.select?.[key]))
      : snapshot;
  };
  mocks.findUnique.mockImplementation((query: Query) => read(query));
  mocks.findFirst.mockImplementation((query: Query) => read(query));
  mocks.findUniqueOrThrow.mockImplementation((query: Query) => read(query, true));
  const write = async (query: Query, many: boolean) => {
    writes.push(structuredClone(query));
    const selected = rows.filter((row) => matches(row, query.where));
    if (!many && selected.length === 0) throw new Error('No matching puzzle');
    for (const row of selected) Object.assign(row, query.data, { updatedAt: new Date('2026-10-26T12:00:00Z') });
    return many ? { count: selected.length } : structuredClone(selected[0]);
  };
  mocks.update.mockImplementation((query: Query) => write(query, false));
  mocks.updateMany.mockImplementation((query: Query) => write(query, true));
});

/** What a rejected publish of `target` throws, for comparing rejections. */
async function rejection(call: () => Promise<unknown>) {
  const error = await call().then(() => null, (e: unknown) => e);
  expect(error, 'publishPuzzle should reject').toBeInstanceOf(Error);
  return (error as Error).message.replace(/\btarget\b/, '<id>');
}

describe('14-S4-9 publishing needs every hint', () => {
  it.each(['private', 'public'] as const)('publishes a complete puzzle as %s', async (visibility) => {
    const result = await actions.publishPuzzle('target', visibility);
    expect(own().publishedAt).toBeInstanceOf(Date);
    expect(own().visibility).toBe(visibility);
    expect(result).toEqual({ publishedAt: own().publishedAt, visibility });
  });

  it.each([
    ['empty', (hints: Record<string, string>) => { hints[KEYS[0]] = ''; }],
    ['whitespace-only', (hints: Record<string, string>) => { hints[KEYS[KEYS.length - 1]] = ' \t\n '; }],
    ['missing', (hints: Record<string, string>) => { delete hints[KEYS[1]]; }],
    ['all missing', (hints: Record<string, string>) => { for (const key of KEYS) delete hints[key]; }],
  ])('rejects a puzzle with a %s required hint and changes nothing', async (_kind, blank) => {
    blank(own().hints as Record<string, string>);
    const before = structuredClone(rows);
    await expect(actions.publishPuzzle('target', 'public')).rejects.toThrow();
    expect(rows).toEqual(before);
  });

  it('rejects a blank hint the same way as an ineligible puzzle', async () => {
    own().phase = 'grid';
    const ineligible = await rejection(() => actions.publishPuzzle('target', 'public'));
    own().phase = 'hints';
    (own().hints as Record<string, string>)[KEYS[0]] = '  ';
    const blank = await rejection(() => actions.publishPuzzle('target', 'public'));
    expect(blank).toBe(ineligible);
  });

  it('extra hints for keys the grid doesn’t need don’t matter', async () => {
    (own().hints as Record<string, string>)['9-across'] = '';
    await actions.publishPuzzle('target', 'private');
    expect(own().publishedAt).toBeInstanceOf(Date);
  });

  it('does not publish over a hint blanked between the read and the write', async () => {
    afterRead = () => {
      own().hints = { ...COMPLETE, [KEYS[2]]: '' };
      own().updatedAt = new Date('2026-10-26T11:00:00Z');
    };
    await expect(actions.publishPuzzle('target', 'public')).rejects.toThrow();
    expect(own().publishedAt).toBeNull();
    expect(own().hints).toEqual({ ...COMPLETE, [KEYS[2]]: '' });
  });

  it('keeps the existing rules: owner, hints phase, unpublished, valid visibility', async () => {
    for (const change of ['owner', 'phase', 'published', 'visibility'] as const) {
      rows = rows.map((row) => ({ ...structuredClone(row), publishedAt: null, phase: 'hints', builderId: 'session-builder' }));
      if (change === 'owner') own().builderId = 'other-builder';
      if (change === 'phase') own().phase = 'grid';
      if (change === 'published') own().publishedAt = new Date('2026-10-01T00:00:00Z');
      const before = structuredClone(rows);
      const visibility = change === 'visibility' ? ('invalid' as actions.Visibility) : 'public';
      await expect(actions.publishPuzzle('target', visibility), change).rejects.toThrow();
      expect(rows, change).toEqual(before);
    }
    expect(writes.every((write) => write.data === undefined || !('hints' in write.data))).toBe(true);
  });
});
