import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story 14-S8 — Old-token cleanup, checked in the source.
//
// The pre-redesign tokens are deleted from globals.css: the 23 old colors,
// --font-display and --font-data, the old radii, and the old type and
// weight tokens. --font-body (the app's one typeface) and --grid-line-width
// (the grid's hairline) stay. No runtime source uses a deleted token, the
// unused google-font module is gone, the uncalled unpublishPuzzle action is
// gone, and the Masthead doesn't branch on its caller's test id. The
// rendered app is checked by e2e/old-tokens.spec.ts.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../', import.meta.url));

const OLD_COLORS = [
  'background',
  'foreground',
  'ink-2',
  'ink-3',
  'rule',
  'rule-strong',
  'hover-tint',
  'panel-tint',
  'accent',
  'accent-hover',
  'ok-tint',
  'grid-empty',
  'grid-line-build',
  'grid-line-play',
  'cell-fill',
  'selected',
  'slot',
  'slot-content',
  'required',
  'recommended',
  'locked-letter',
  'editable-letter',
  'incomplete',
];
const OLD_FONTS = ['display', 'data'];
const OLD_RADII = ['btn', 'sm', 'md', 'lg', 'grid'];
const OLD_TEXT = ['headline', 'body', 'help', 'title'];
const OLD_WEIGHTS = ['normal', 'bold'];

const OLD_TOKENS = [
  ...OLD_COLORS.map((n) => `--color-${n}`),
  ...OLD_FONTS.map((n) => `--font-${n}`),
  ...OLD_RADII.map((n) => `--radius-${n}`),
  ...OLD_TEXT.map((n) => `--text-${n}`),
  ...OLD_WEIGHTS.map((n) => `--weight-${n}`),
];

const KEPT_TOKENS = ['--font-body', '--grid-line-width', '--radius-pill', '--radius-modal'];

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

function declaredNames() {
  const css = withoutComments(readFileSync(join(SRC, 'app/globals.css'), 'utf8'));
  return new Set(Array.from(css.matchAll(/(--[\w-]+)\s*:/g), (m) => m[1]));
}

/** Every runtime .ts/.tsx/.css file under src, tests excluded. */
function runtimeFiles(dir = SRC): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return runtimeFiles(path);
    if (!/\.(ts|tsx|css)$/.test(entry.name) || /\.test\.ts$/.test(entry.name)) return [];
    return [path];
  });
}

const alternatives = (names: string[]) => names.map((n) => n.replace(/-/g, '\\-')).join('|');
const UTILITY = '(?:bg|text|border(?:-[trblxyse])?|ring|outline|fill|stroke|from|via|to|divide|decoration|accent|caret|placeholder|shadow)';

const OLD_USES: [string, RegExp][] = [
  ['an old token by name', new RegExp(`(?:${alternatives(OLD_TOKENS)})(?![\\w-])`)],
  ['an old color utility', new RegExp(`(?<![\\w-])${UTILITY}-(?:${alternatives(OLD_COLORS)})(?![\\w-])`)],
  ['an old font utility', new RegExp(`(?<![\\w-])font-(?:${alternatives(OLD_FONTS)})(?![\\w-])`)],
  ['an old radius utility', new RegExp(`(?<![\\w-])rounded(?:-[trblxyse]{1,2})?-(?:${alternatives(OLD_RADII)})(?![\\w-])`)],
  ['an old type utility', new RegExp(`(?<![\\w-])text-(?:${alternatives(OLD_TEXT)})(?![\\w-])`)],
];

describe('14-S8-1 globals.css', () => {
  it('declares none of the old tokens', () => {
    const declared = declaredNames();
    expect(OLD_TOKENS.filter((name) => declared.has(name))).toEqual([]);
  });

  it('keeps the body typeface, the grid line width and the two radii', () => {
    const declared = declaredNames();
    for (const name of KEPT_TOKENS) expect(declared.has(name), name).toBe(true);
  });
});

describe('14-S8-2 runtime source', () => {
  it('uses no old token', () => {
    const found: string[] = [];
    for (const path of runtimeFiles()) {
      const code = withoutComments(readFileSync(path, 'utf8'));
      for (const [label, pattern] of OLD_USES) {
        const match = code.match(pattern);
        if (match) found.push(`${relative(SRC, path)}: ${label} (${match[0]})`);
      }
    }
    expect(found).toEqual([]);
  });
});

describe('14-S8-3 removed code', () => {
  it('google-font.ts and its test are gone, and nothing imports them', () => {
    expect(existsSync(join(SRC, 'lib/google-font.ts'))).toBe(false);
    expect(existsSync(join(SRC, 'lib/google-font.test.ts'))).toBe(false);
    const importers = runtimeFiles().filter((path) => /google-font/.test(readFileSync(path, 'utf8')));
    expect(importers.map((path) => relative(SRC, path))).toEqual([]);
  });

  it('unpublishPuzzle is gone from the actions and has no reference', () => {
    const references = runtimeFiles().filter((path) =>
      /\bunpublishPuzzle\b/.test(withoutComments(readFileSync(path, 'utf8')))
    );
    expect(references.map((path) => relative(SRC, path))).toEqual([]);
  });

  it("the Masthead doesn't branch on its caller's test id", () => {
    const code = withoutComments(readFileSync(join(SRC, 'components/layout/Masthead.tsx'), 'utf8'));
    expect(code).not.toMatch(/['"]app-header['"]/);
    expect(code).not.toMatch(/['"]home-link['"]/);
  });
});
