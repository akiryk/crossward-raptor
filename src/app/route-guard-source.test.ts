import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

// Story 23-S3 — one guard, nothing that can forget it, checked in the source.
//
// Privileged code asks `requireSession()` (lib/require-session), which admits
// only an account with a username. `requireAnySession()`, which admits an
// account without one, is used only by the username save. The front door,
// which serves signed-out visitors too, decides between the sign-in form, the
// username step and /puzzles with the same module's `hasUsername()`; it and
// the masthead read the session through that module, the only reader of
// Better Auth's session.
// Server actions live only in the modules whose every action is checked by a
// unit test (puzzles/actions.username-gate.test.ts, account-actions.test.ts);
// the only route handlers are Better Auth's and (amended by 24-S1, as epic
// 24 requires) the keepalive commit route, which only calls the checked
// `commitOperation` action; and every page outside `/` sits
// under a layout that calls `requireSession()`, so a page added later is
// guarded before it renders. The database client is imported only by the
// checked action modules and Better Auth's configuration, so no page or
// component can read or write data past the guard.
// Do not edit this file to match an implementation.

const SRC = fileURLToPath(new URL('../', import.meta.url));
const APP = join(SRC, 'app');

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

function rel(path: string) {
  return relative(SRC, path).split(sep).join('/');
}

function withoutComments(code: string) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const sources = files(SRC).filter((path) => /\.(ts|tsx)$/.test(path) && !/\.test\.tsx?$/.test(path));
const code = new Map(sources.map((path) => [rel(path), withoutComments(readFileSync(path, 'utf8'))]));

describe('23-S3-U7 the guard is central', () => {
  it('server actions live only in the two checked modules', () => {
    const modules = [...code].filter(([, text]) => /^\s*['"]use server['"]/.test(text)).map(([path]) => path);
    const inline = [...code].filter(([, text]) => /\{\s*['"]use server['"]/.test(text)).map(([path]) => path);
    expect(modules.sort()).toEqual(['app/account-actions.ts', 'app/puzzles/actions.ts']);
    expect(inline).toEqual([]);
  });

  it('requireAnySession is used only by the username save', () => {
    const users = [...code].filter(([, text]) => /\brequireAnySession\b/.test(text)).map(([path]) => path);
    expect(users.sort()).toEqual(['app/account-actions.ts', 'lib/require-session.ts']);
  });

  it('the front door decides with the guard module’s hasUsername', () => {
    const page = code.get('app/page.tsx') ?? '';
    expect(page).toMatch(/import \{[^}]*\bhasUsername\b[^}]*\} from ['"]@\/lib\/require-session['"]/);
    expect(page).toMatch(/\bhasUsername\(/);
  });

  it('sessions are read only through the guard module', () => {
    const readers = [...code].filter(([, text]) => /\bauth\.api\.getSession\b/.test(text)).map(([path]) => path);
    expect(readers).toEqual(['lib/require-session.ts']);
  });

  it('the only route handlers are Better Auth’s and the commit route, which only calls the checked action', () => {
    const handlers = [...code.keys()].filter((path) => /^app\/.*\/route\.tsx?$/.test(path));
    // 24-S1 amendment: epic 24's keepalive commit route joins Better Auth's.
    expect(handlers.sort()).toEqual(['app/api/auth/[...all]/route.ts', 'app/api/puzzles/[id]/operations/route.ts']);
    const commitRoute = code.get('app/api/puzzles/[id]/operations/route.ts') ?? '';
    const imports = [...commitRoute.matchAll(/from ['"]([^'"]+)['"]/g)].map((match) => match[1]).sort();
    expect(imports).toEqual(['@/app/puzzles/actions', 'next/server']);
    expect(commitRoute).toMatch(/import \{ commitOperation \} from ['"]@\/app\/puzzles\/actions['"]/);
    expect(commitRoute).toMatch(/\bawait commitOperation\(/);
  });

  it('every page outside / sits under a layout that calls requireSession()', () => {
    const pages = [...code.keys()].filter((path) => /^app\/.+\/page\.tsx$/.test(path));
    expect(pages.length).toBeGreaterThan(0);
    for (const page of pages) {
      const segment = page.split('/')[1];
      const layout = `app/${segment}/layout.tsx`;
      expect(existsSync(join(APP, segment, 'layout.tsx')), `${page}: ${layout}`).toBe(true);
      const text = code.get(layout) ?? '';
      expect(text, layout).toMatch(/from ['"]@\/lib\/require-session['"]/);
      expect(text, layout).toMatch(/\bawait requireSession\(\)/);
    }
  });

  it('the database client is imported only by the action modules and auth', () => {
    const importers = [...code]
      .filter(([, text]) => /from ['"](@\/lib\/prisma|(\.\.?\/)+(lib\/)?prisma)['"]/.test(text))
      .map(([path]) => path);
    expect(importers.sort()).toEqual(['app/account-actions.ts', 'app/puzzles/actions.ts', 'lib/auth.ts']);
  });

  it('the puzzles and style guide segments are guarded', () => {
    for (const segment of ['puzzles', 'style-guide']) {
      expect(code.get(`app/${segment}/layout.tsx`) ?? '', segment).toMatch(/\bawait requireSession\(\)/);
    }
  });
});
