import { beforeEach, describe, expect, it, vi } from 'vitest';

// Story 23-S3 — saving a username. `saveUsername(value)` is the one server
// action an account without a username may call. It changes only the
// signed-in account's own `displayName`, to the trimmed value, under the
// username rules (lib/username: 1–80 characters once trimmed), then sends the
// browser on to /puzzles. A value that breaks the rules writes nothing and
// returns the rule's message. Without a valid session it writes nothing and
// sends the browser to /. A later save replaces an earlier one (the latest
// explicit save wins).
//
// The write may be `prisma.user.update` or `updateMany`; either way exactly
// one write, keyed by the session user's id alone, setting only displayName.
// Do not edit this file to match an implementation.

const mocks = vi.hoisted(() => ({
  getSession: vi.fn(),
  headers: vi.fn(),
  revalidatePath: vi.fn(),
  userUpdate: vi.fn(),
  userUpdateMany: vi.fn(),
  userFindUnique: vi.fn(),
  puzzle: vi.fn(),
}));

vi.mock('@/lib/auth', () => ({ auth: { api: { getSession: mocks.getSession } } }));
vi.mock('next/headers', () => ({ headers: mocks.headers }));
vi.mock('next/navigation', () => ({
  redirect: (path: string) => { throw new Error(`redirect:${path}`); },
}));
vi.mock('next/cache', () => ({ revalidatePath: mocks.revalidatePath }));
vi.mock('@/lib/prisma', () => {
  const unsupported = new Proxy({}, { get: () => mocks.puzzle });
  return {
    prisma: {
      user: { update: mocks.userUpdate, updateMany: mocks.userUpdateMany, findUnique: mocks.userFindUnique },
      puzzle: unsupported,
      playSession: unsupported,
      session: unsupported,
      account: unsupported,
      verification: unsupported,
      $transaction: mocks.puzzle,
    },
  };
});

import * as accountActions from './account-actions';

const { saveUsername } = accountActions;
const requestHeaders = new Headers({ cookie: 'better-auth.session_token=token' });
const BLANK = 'Oops! You need to add a username.';
const LONG = 'Oops! Use 80 characters or fewer.';

function signedIn(displayName: string | null, id = 'own-user') {
  mocks.getSession.mockResolvedValue({
    user: { id, email: `${id}@example.test`, name: '', displayName },
    session: { id: `session-${id}`, userId: id },
  });
}

/** Every user write, normalized to its where and data. */
function writes() {
  return [...mocks.userUpdate.mock.calls, ...mocks.userUpdateMany.mock.calls].map(([args]) => ({
    where: args.where,
    data: args.data,
  }));
}

function expectNoWrite() {
  expect(writes()).toEqual([]);
  expect(mocks.puzzle).not.toHaveBeenCalled();
}

beforeEach(() => {
  vi.resetAllMocks();
  mocks.headers.mockResolvedValue(requestHeaders);
  mocks.userUpdate.mockImplementation(async ({ data }) => ({ id: 'own-user', ...data }));
  mocks.userUpdateMany.mockResolvedValue({ count: 1 });
  mocks.userFindUnique.mockResolvedValue({ id: 'own-user', displayName: null });
});

// Amended by 23-S4: the module also exports S4's `changeUsername` (Account
// details), tested in account-actions.change-username.test.ts.
// Amended by 23-S5: and S5's `changeEmail`, tested in
// account-actions.change-email.test.ts.
describe('23-S3-U1 the module', () => {
  it('exports saveUsername, changeUsername and changeEmail and no other action', () => {
    const exported = Object.entries(accountActions).filter(([, value]) => typeof value === 'function');
    expect(exported.map(([name]) => name).sort()).toEqual(['changeEmail', 'changeUsername', 'saveUsername']);
  });
});

describe('23-S3-U2 saving a username', () => {
  it('sets only the signed-in account’s displayName to the value, then goes to /puzzles', async () => {
    signedIn(null);
    await expect(saveUsername('Lil Orange Fox')).rejects.toThrow(/^redirect:\/puzzles$/);
    expect(mocks.getSession).toHaveBeenCalledWith({ headers: requestHeaders });
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: 'Lil Orange Fox' } }]);
    expect(mocks.puzzle).not.toHaveBeenCalled();
  });

  it('stores the trimmed value', async () => {
    signedIn('   ');
    await expect(saveUsername('  Ada Lovelace \t')).rejects.toThrow(/^redirect:\/puzzles$/);
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: 'Ada Lovelace' } }]);
  });

  it('accepts 80 code points', async () => {
    signedIn(null);
    await expect(saveUsername('🦖'.repeat(80))).rejects.toThrow(/^redirect:\/puzzles$/);
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: '🦖'.repeat(80) } }]);
  });

  it('replaces an earlier username (the latest save wins)', async () => {
    signedIn('First');
    mocks.userFindUnique.mockResolvedValue({ id: 'own-user', displayName: 'First' });
    await expect(saveUsername('Second')).rejects.toThrow(/^redirect:\/puzzles$/);
    expect(writes()).toEqual([{ where: { id: 'own-user' }, data: { displayName: 'Second' } }]);
  });

  it('writes only the caller’s own account, whatever else is passed', async () => {
    signedIn(null, 'caller');
    const call = saveUsername as unknown as (...args: unknown[]) => Promise<unknown>;
    await expect(call('Ada', 'victim', { id: 'victim', email: 'x@example.test' })).rejects.toThrow(
      /^redirect:\/puzzles$/,
    );
    expect(writes()).toEqual([{ where: { id: 'caller' }, data: { displayName: 'Ada' } }]);
  });
});

describe('23-S3-U3 the username rules, on the server', () => {
  it.each([
    ['empty', '', BLANK],
    ['spaces', '   ', BLANK],
    ['tabs and newlines', '\t\n', BLANK],
    ['81 code points', '🦖'.repeat(81), LONG],
    ['81 letters after trimming', `  ${'a'.repeat(81)}  `, LONG],
  ])('refuses %s with its message and writes nothing', async (_label, value, message) => {
    signedIn(null);
    await expect(saveUsername(value)).resolves.toEqual({ error: message });
    expectNoWrite();
  });

  it.each([['undefined', undefined], ['null', null], ['a number', 42], ['an object', { toString: () => 'Ada' }], ['an array', ['Ada']]])(
    'refuses %s, which is not text, and writes nothing',
    async (_label, value) => {
      signedIn(null);
      const call = saveUsername as unknown as (value: unknown) => Promise<unknown>;
      await expect(call(value)).resolves.toEqual({ error: BLANK });
      expectNoWrite();
    },
  );
});

describe('23-S3-U4 without a session', () => {
  it('writes nothing and sends the browser to /', async () => {
    mocks.getSession.mockResolvedValue(null);
    await expect(saveUsername('Ada')).rejects.toThrow(/^redirect:\/$/);
    expect(mocks.getSession).toHaveBeenCalledWith({ headers: requestHeaders });
    expectNoWrite();
  });

  it('checks the session before the value', async () => {
    mocks.getSession.mockResolvedValue(null);
    await expect(saveUsername('')).rejects.toThrow(/^redirect:\/$/);
    expectNoWrite();
  });
});
