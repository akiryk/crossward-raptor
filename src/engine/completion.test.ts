import { describe, expect, it } from 'vitest';
import { clearLetters, createGrid, withLetter, type Coord, type Grid } from './grid';
import {
  READY_PERCENT,
  completionCount,
  completionPercent,
  isReadyForHints,
  type CompletionCount,
} from './completion';

// Story 22-S1 — the completion count. A grid's completion is its lettered
// cells over all its cells (cols × rows), whatever Preview would show
// black. A rebus cell counts once; a black cell (possible in a grid saved
// before the all-white model) counts in the total but never as lettered.
// The percentage is 100 × lettered ÷ total, rounded down, and the grid is
// ready for hints at 80% or more: 180 of 225, 353 of 441. Every function
// is pure: the grid is never changed and the same input gives the same
// result.
//
// Do not edit this file to match an implementation.

/** Every cell of the grid in reading order. */
function coordsOf(grid: Grid): Coord[] {
  const coords: Coord[] = [];
  for (let row = 0; row < grid.rows; row += 1) {
    for (let col = 0; col < grid.cols; col += 1) coords.push({ col, row });
  }
  return coords;
}

/** A size × size grid with its first `n` cells (reading order) lettered "A". */
function filled(size: number, n: number): Grid {
  let grid = createGrid({ cols: size, rows: size });
  for (const coord of coordsOf(grid).slice(0, n)) grid = withLetter(grid, coord, 'A');
  return grid;
}

/** Every lookup in the grid, for detecting mutation. */
const snapshot = (grid: Grid) =>
  coordsOf(grid).map(({ col, row }) => ({ ...grid.at(col, row) }));

/** The rounded-down percentage in integer arithmetic, as a reference. */
const floorPercent = (lettered: number, total: number) =>
  (100 * lettered - ((100 * lettered) % total)) / total;

describe('22-S1-1 the count: lettered cells over all cells', () => {
  it('an empty daily is 0 of 225; an empty Sunday 0 of 441', () => {
    expect(completionCount(createGrid({ cols: 15, rows: 15 }))).toEqual({ lettered: 0, total: 225 });
    expect(completionCount(createGrid({ cols: 21, rows: 21 }))).toEqual({ lettered: 0, total: 441 });
  });

  it('counts each lettered cell, wherever it is', () => {
    let grid = createGrid({ cols: 15, rows: 15 });
    grid = withLetter(grid, { col: 0, row: 0 }, 'C');
    grid = withLetter(grid, { col: 14, row: 14 }, 'A');
    grid = withLetter(grid, { col: 7, row: 3 }, 'T');
    expect(completionCount(grid)).toEqual({ lettered: 3, total: 225 });
    expect(completionCount(filled(15, 90))).toEqual({ lettered: 90, total: 225 });
    expect(completionCount(filled(21, 353))).toEqual({ lettered: 353, total: 441 });
  });

  it('a full grid is every cell', () => {
    expect(completionCount(filled(15, 225))).toEqual({ lettered: 225, total: 225 });
    expect(completionCount(filled(21, 441))).toEqual({ lettered: 441, total: 441 });
  });

  it('a rebus cell counts once', () => {
    let grid = createGrid({ cols: 15, rows: 15 });
    grid = withLetter(grid, { col: 2, row: 2 }, 'HEART');
    grid = withLetter(grid, { col: 3, row: 2 }, 'S');
    expect(completionCount(grid)).toEqual({ lettered: 2, total: 225 });
  });

  it('black cells count in the total, never as lettered', () => {
    let grid = createGrid({
      cols: 15,
      rows: 15,
      black: [
        { col: 0, row: 0 },
        { col: 14, row: 14 },
        { col: 7, row: 7 },
      ],
    });
    expect(completionCount(grid)).toEqual({ lettered: 0, total: 225 });
    grid = withLetter(grid, { col: 1, row: 0 }, 'A');
    expect(completionCount(grid)).toEqual({ lettered: 1, total: 225 });
  });

  it('the total is cols × rows for any size', () => {
    expect(completionCount(createGrid({ cols: 5, rows: 5 }))).toEqual({ lettered: 0, total: 25 });
    expect(completionCount(createGrid({ cols: 9, rows: 9 }))).toEqual({ lettered: 0, total: 81 });
    expect(completionCount(createGrid({ cols: 4, rows: 3 }))).toEqual({ lettered: 0, total: 12 });
  });
});

describe('22-S1-2 only letters move it', () => {
  it('typing into an empty cell raises it by one', () => {
    const before = filled(15, 10);
    const after = withLetter(before, { col: 0, row: 5 }, 'Q');
    expect(completionCount(after).lettered).toBe(completionCount(before).lettered + 1);
  });

  it('overtyping a letter leaves it', () => {
    const before = filled(15, 10);
    const after = withLetter(before, { col: 3, row: 0 }, 'Z');
    expect(completionCount(after)).toEqual(completionCount(before));
  });

  it('deleting a letter lowers it by one', () => {
    const before = filled(15, 10);
    const after = withLetter(before, { col: 3, row: 0 }, null);
    expect(completionCount(after).lettered).toBe(completionCount(before).lettered - 1);
  });

  it('clearing every letter takes it to zero', () => {
    expect(completionCount(clearLetters(filled(21, 400)))).toEqual({ lettered: 0, total: 441 });
  });
});

describe('22-S1-3 the percentage, rounded down', () => {
  it('matches the EPIC examples', () => {
    expect(completionPercent({ lettered: 90, total: 225 })).toBe(40);
    expect(completionPercent({ lettered: 179, total: 225 })).toBe(79);
    expect(completionPercent({ lettered: 180, total: 225 })).toBe(80);
    expect(completionPercent({ lettered: 352, total: 441 })).toBe(79);
    expect(completionPercent({ lettered: 353, total: 441 })).toBe(80);
  });

  it('runs from 0 to 100', () => {
    expect(completionPercent({ lettered: 0, total: 225 })).toBe(0);
    expect(completionPercent({ lettered: 1, total: 225 })).toBe(0);
    expect(completionPercent({ lettered: 2, total: 225 })).toBe(0);
    expect(completionPercent({ lettered: 3, total: 225 })).toBe(1);
    expect(completionPercent({ lettered: 224, total: 225 })).toBe(99);
    expect(completionPercent({ lettered: 225, total: 225 })).toBe(100);
    expect(completionPercent({ lettered: 440, total: 441 })).toBe(99);
    expect(completionPercent({ lettered: 441, total: 441 })).toBe(100);
  });

  it('is always a whole number rounded down, for every daily and Sunday count', () => {
    for (const total of [225, 441]) {
      for (let lettered = 0; lettered <= total; lettered += 1) {
        expect(completionPercent({ lettered, total })).toBe(floorPercent(lettered, total));
      }
    }
  });

  it('works from a real grid’s count', () => {
    expect(completionPercent(completionCount(filled(15, 179)))).toBe(79);
    expect(completionPercent(completionCount(filled(21, 353)))).toBe(80);
  });

  it('a grid with no cells is 0%', () => {
    expect(completionPercent({ lettered: 0, total: 0 })).toBe(0);
  });
});

describe('22-S1-4 ready at 80%', () => {
  it('the threshold is 80', () => {
    expect(READY_PERCENT).toBe(80);
  });

  it('a daily is ready at 180 of 225, not 179', () => {
    expect(isReadyForHints({ lettered: 179, total: 225 })).toBe(false);
    expect(isReadyForHints({ lettered: 180, total: 225 })).toBe(true);
    expect(isReadyForHints({ lettered: 225, total: 225 })).toBe(true);
  });

  it('a Sunday is ready at 353 of 441, not 352', () => {
    expect(isReadyForHints({ lettered: 352, total: 441 })).toBe(false);
    expect(isReadyForHints({ lettered: 353, total: 441 })).toBe(true);
    expect(isReadyForHints({ lettered: 441, total: 441 })).toBe(true);
  });

  it('an empty grid, or one with no cells, is not ready', () => {
    expect(isReadyForHints({ lettered: 0, total: 225 })).toBe(false);
    expect(isReadyForHints({ lettered: 0, total: 0 })).toBe(false);
  });

  it('agrees with the shown percentage for every daily and Sunday count', () => {
    for (const total of [225, 441]) {
      for (let lettered = 0; lettered <= total; lettered += 1) {
        const count: CompletionCount = { lettered, total };
        expect(isReadyForHints(count)).toBe(completionPercent(count) >= 80);
      }
    }
  });

  it('works from a real grid’s count', () => {
    expect(isReadyForHints(completionCount(filled(15, 179)))).toBe(false);
    expect(isReadyForHints(completionCount(filled(15, 180)))).toBe(true);
  });
});

describe('22-S1-5 pure', () => {
  it('never changes the grid, and gives the same count each time', () => {
    let grid = createGrid({ cols: 15, rows: 15, black: [{ col: 7, row: 7 }] });
    grid = withLetter(grid, { col: 0, row: 0 }, 'HEART');
    grid = withLetter(grid, { col: 1, row: 0 }, 'A');
    const before = snapshot(grid);

    const first = completionCount(grid);
    const second = completionCount(grid);

    expect(snapshot(grid)).toEqual(before);
    expect(first).toEqual({ lettered: 2, total: 225 });
    expect(second).toEqual(first);
  });

  it('never changes the count it is given', () => {
    const count: CompletionCount = { lettered: 180, total: 225 };
    completionPercent(count);
    isReadyForHints(count);
    expect(count).toEqual({ lettered: 180, total: 225 });
  });

  it('one grid’s count is unaffected by counting another first', () => {
    completionCount(filled(21, 441));
    expect(completionCount(createGrid({ cols: 15, rows: 15 }))).toEqual({ lettered: 0, total: 225 });
  });
});
